      const upazila = student.presentUpazila || student.upazila;
      const district = student.presentDistrict || student.district;

      if (village) parts.push(village);
      if (post && post !== village) parts.push(post);
      if (upazila) parts.push(upazila);
      if (district && district !== upazila) parts.push(district);

