import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState } from 'react';
import { StudentIdCardSettings } from '../../types';
import { Settings2, RefreshCcw, UserSquare, Edit3, Image as ImageIcon, Printer, Type, X, Palette, Upload, Trash2, CheckCircle2 } from 'lucide-react';
import { useAppStore, defaultStudentIdCardSettings } from '../../store/useAppStore';
import { toast } from '../../utils/toast';

interface StudentIdCardSettingsPanelProps {
  isBn: boolean;
  onClose?: () => void;
}

export const StudentIdCardSettingsPanel: React.FC<StudentIdCardSettingsPanelProps> = ({
  isBn,
  onClose,
}) => {
  const [activeTab, setActiveTab] = useState<'info' | 'signature' | 'photo' | 'typography' | 'graphic' | 'print'>('info');
  const rawSettings = useAppStore((state) => state.studentIdCardSettings);
  const settings = rawSettings || defaultStudentIdCardSettings;
  const updateSettings = useAppStore((state) => state.updateStudentIdCardSettings);
  const institution = useAppStore((state) => state.institution);
  const staff = useAppStore((state) => state.staff) || [];
  
  // Detect saved principal signature from staff or institution
  const principalStaff = staff.find(s => 
    s.designationId === 'des_head_teacher' || 
    s.designation === 'Head Teacher' || 
    s.designation === 'প্রধান শিক্ষক' || 
    s.designationBn === 'প্রধান শিক্ষক'
  );
  const detectedPrincipalSignature = (principalStaff && principalStaff.signaturePhoto) 
    ? principalStaff.signaturePhoto 
    : institution.headmasterSignature;
  
  const handleUpdate = (key: keyof StudentIdCardSettings, value: any) => {
    updateSettings({ ...settings, [key]: value });
  };
  
  const onReset = () => {
    updateSettings(defaultStudentIdCardSettings);
  };

  const handleCustomGraphicUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    if (file.size > 3 * 1024 * 1024) {
      toast.error(isBn ? BN_DICT['please_upload_an_image_smaller'] : EN_DICT['please_upload_an_image_smaller']);
      return;
    }
    const reader = new FileReader();
    reader.onload = () => {
      if (typeof reader.result === 'string') {
        handleUpdate('customGraphicUrl', reader.result);
        toast.success(isBn ? BN_DICT['custom_graphic_uploaded_succes'] : EN_DICT['custom_graphic_uploaded_succes']);
      }
    };
    reader.readAsDataURL(file);
  };

  const tabs = [
    { id: 'info', label: isBn ? BN_DICT['card_info'] : EN_DICT['card_info'], icon: <UserSquare className="w-4 h-4" /> },
    { id: 'signature', label: isBn ? BN_DICT['signature'] : EN_DICT['signature'], icon: <Edit3 className="w-4 h-4" /> },
    { id: 'photo', label: isBn ? BN_DICT['photo'] : EN_DICT['photo'], icon: <ImageIcon className="w-4 h-4" /> },
    { id: 'typography', label: isBn ? BN_DICT['typography'] : EN_DICT['typography'], icon: <Type className="w-4 h-4" /> },
    { id: 'graphic', label: isBn ? BN_DICT['graphics'] : EN_DICT['graphics'], icon: <Palette className="w-4 h-4" /> },
    { id: 'print', label: isBn ? BN_DICT['print'] : EN_DICT['print'], icon: <Printer className="w-4 h-4" /> },
  ] as const;

  return (
    <div className="w-full h-full flex flex-col bg-white border border-slate-200/90 shadow-2xs rounded-2xl overflow-hidden">
      {/* Header */}
      <div className="shrink-0 px-4 py-3.5 bg-gradient-to-r from-emerald-800 to-[#08544c] text-white flex justify-between items-center z-10 shadow-sm">
        <div className="flex items-center gap-2">
          <Settings2 className="w-5 h-5 opacity-90" />
          <h2 className="text-sm font-black tracking-wide drop-shadow-sm">
            {isBn ? BN_DICT['card_settings'] : EN_DICT['card_settings']}
          </h2>
        </div>
        <div className="flex items-center gap-1">
          <button
            onClick={() => {
              if (window.confirm(isBn ? BN_DICT['are_you_sure_you_want_to_reset'] : EN_DICT['are_you_sure_you_want_to_reset'])) {
                onReset();
                toast.success(isBn ? BN_DICT['card_settings_reset_to_default'] : EN_DICT['card_settings_reset_to_default']);
              }
            }}
            className="p-1.5 hover:bg-white/10 rounded-lg transition-colors flex items-center gap-1 text-[11px] font-bold text-emerald-100 hover:text-white group"
            title={isBn ? BN_DICT['reset_to_default'] : EN_DICT['reset_to_default']}
          >
            <RefreshCcw className="w-3.5 h-3.5 group-hover:-rotate-180 transition-transform duration-500" />
            <span>{isBn ? BN_DICT['reset'] : EN_DICT['reset']}</span>
          </button>
          {onClose && (
            <button
              onClick={onClose}
              className="p-1 hover:bg-white/10 rounded-lg transition-colors text-white"
            >
              <X className="w-5 h-5" />
            </button>
          )}
        </div>
      </div>

      {/* Tabs */}
      <div className="shrink-0 flex overflow-x-auto border-b border-slate-200 bg-slate-50/50 hide-scrollbar px-1 pt-1">
        {tabs.map((tab) => (
          <button
            key={tab.id}
            onClick={() => setActiveTab(tab.id as any)}
            className={`flex-1 min-w-[70px] flex flex-col items-center justify-center gap-1 px-2 py-2.5 text-[10px] font-bold transition-all border-b-2 ${
              activeTab === tab.id
                ? 'border-emerald-600 text-emerald-700 bg-white shadow-[0_-2px_10px_rgba(0,0,0,0.02)]'
                : 'border-transparent text-slate-500 hover:text-slate-700 hover:bg-slate-100/50'
            }`}
          >
            {tab.icon}
            <span className="whitespace-nowrap">{tab.label}</span>
          </button>
        ))}
      </div>

      {/* Scrollable Content */}
      <div className="flex-1 overflow-y-auto p-4 custom-scrollbar bg-slate-50/30">
        
        {/* ---------------------------------------------------- */}
        {/* TAB 1: CARD INFO                                     */}
        {/* ---------------------------------------------------- */}
        {activeTab === 'info' && (
          <div className="space-y-4 animate-fadeIn">
            {/* Front Information Mode */}
            <div className="space-y-2">
              <label className="font-bold text-slate-700 block">
                {isBn ? BN_DICT['front_information_mode'] : EN_DICT['front_information_mode']}
              </label>
              <div className="grid grid-cols-1 gap-2">
                <button
                  type="button"
                  onClick={() => handleUpdate('frontPrimaryInfoMode', 'parents')}
                  className={`p-3 rounded-xl border text-left transition-all flex items-center gap-2 ${
                    settings.frontPrimaryInfoMode !== 'academic'
                      ? 'bg-emerald-50 border-emerald-500 text-emerald-900 shadow-2xs'
                      : 'border-slate-200 bg-white text-slate-600 hover:border-slate-300'
                  }`}
                >
                  <div className={`w-4 h-4 rounded-full border-2 flex items-center justify-center ${settings.frontPrimaryInfoMode !== 'academic' ? 'border-emerald-600' : 'border-slate-300'}`}>
                    {settings.frontPrimaryInfoMode !== 'academic' && <div className="w-2 h-2 rounded-full bg-emerald-600" />}
                  </div>
                  <div>
                    <div className="font-bold text-xs">{isBn ? BN_DICT['parents_info_on_front'] : EN_DICT['parents_info_on_front']}</div>
                    <div className="text-[10px] opacity-75">{isBn ? BN_DICT['academic_info_on_back'] : EN_DICT['academic_info_on_back']}</div>
                  </div>
                </button>
                <button
                  type="button"
                  onClick={() => handleUpdate('frontPrimaryInfoMode', 'academic')}
                  className={`p-3 rounded-xl border text-left transition-all flex items-center gap-2 ${
                    settings.frontPrimaryInfoMode === 'academic'
                      ? 'bg-emerald-50 border-emerald-500 text-emerald-900 shadow-2xs'
                      : 'border-slate-200 bg-white text-slate-600 hover:border-slate-300'
                  }`}
                >
                  <div className={`w-4 h-4 rounded-full border-2 flex items-center justify-center ${settings.frontPrimaryInfoMode === 'academic' ? 'border-emerald-600' : 'border-slate-300'}`}>
                    {settings.frontPrimaryInfoMode === 'academic' && <div className="w-2 h-2 rounded-full bg-emerald-600" />}
                  </div>
                  <div>
                    <div className="font-bold text-xs">{isBn ? BN_DICT['academic_info_on_front'] : EN_DICT['academic_info_on_front']}</div>
                    <div className="text-[10px] opacity-75">{isBn ? BN_DICT['parents_info_on_back'] : EN_DICT['parents_info_on_back']}</div>
                  </div>
                </button>
              </div>
            </div>

            {/* Back Side Custom Text */}
            <div className="pt-3 border-t border-slate-100 space-y-2">
              <label className="flex items-center justify-between cursor-pointer">
                <span className="font-bold text-slate-700">{isBn ? BN_DICT['back_custom_text'] : EN_DICT['back_custom_text']}</span>
                <input
                  type="checkbox"
                  checked={settings.showBackCustomShape !== false}
                  onChange={(e) => handleUpdate('showBackCustomShape', e.target.checked)}
                  className="w-4 h-4 rounded text-emerald-600 focus:ring-emerald-500 border-slate-300 cursor-pointer"
                />
              </label>
              {settings.showBackCustomShape !== false && (
                <input
                  type="text"
                  value={settings.backCustomShapeTextBn || ''}
                  onChange={(e) => handleUpdate('backCustomShapeTextBn', e.target.value)}
                  className="w-full px-3 py-2 bg-white border border-slate-200 rounded-lg text-xs font-medium focus:ring-1 focus:ring-emerald-500"
                  placeholder={isBn ? BN_DICT['emergency_contact_1'] : EN_DICT['emergency_contact_1']}
                />
              )}
            </div>
          </div>
        )}

        {/* ---------------------------------------------------- */}
        {/* TAB 2: SIGNATURE                                     */}
        {/* ---------------------------------------------------- */}
        {activeTab === 'signature' && (
          <div className="space-y-4 animate-fadeIn">
            {/* Detected Principal Signature Status */}
            <div className="p-3 rounded-xl bg-slate-50 border border-slate-200">
              <div className="flex items-center gap-2 mb-1.5">
                <CheckCircle2 className={`w-4 h-4 ${detectedPrincipalSignature ? 'text-emerald-600' : 'text-slate-400'}`} />
                <span className="text-xs font-bold text-slate-700">
                  {isBn ? BN_DICT['principal_signature_status'] : EN_DICT['principal_signature_status']}
                </span>
              </div>
              {detectedPrincipalSignature ? (
                <div className="flex items-center gap-3 bg-white p-2 rounded-lg border border-emerald-200">
                  <div className="w-16 h-8 bg-slate-50 border border-slate-200 rounded flex items-center justify-center p-0.5">
                    <img src={detectedPrincipalSignature} alt="Signature Preview" className="max-w-full max-h-full object-contain" />
                  </div>
                  <div>
                    <p className="text-[11px] font-bold text-emerald-800">
                      {principalStaff ? (principalStaff.nameBn || principalStaff.name) : (isBn ? BN_DICT['head_of_institution'] : EN_DICT['head_of_institution'])}
                    </p>
                    <p className="text-[9.5px] text-slate-500">
                      {isBn ? BN_DICT['connected_from_hr_institution'] : EN_DICT['connected_from_hr_institution']}
                    </p>
                  </div>
                </div>
              ) : (
                <p className="text-[10.5px] text-slate-500 leading-snug">
                  {isBn ? BN_DICT['if_a_signature_photo_is_upload'] : EN_DICT['if_a_signature_photo_is_upload']}
                </p>
              )}
            </div>

            {/* Show Principal Signature */}
            <label className="flex items-center justify-between p-3 rounded-xl bg-white border border-slate-200 cursor-pointer hover:border-emerald-300 transition-colors shadow-2xs">
              <div>
                <span className="font-bold text-slate-700 block text-xs">{isBn ? BN_DICT['show_principal_signature'] : EN_DICT['show_principal_signature']}</span>
              </div>
              <input
                type="checkbox"
                checked={settings.showPrincipalSignature !== false}
                onChange={(e) => handleUpdate('showPrincipalSignature', e.target.checked)}
                className="w-4 h-4 rounded text-emerald-600 focus:ring-emerald-500 border-slate-300 cursor-pointer"
              />
            </label>

            {settings.showPrincipalSignature !== false && (
              <>
                <div className="space-y-2 bg-white p-3 rounded-xl border border-slate-200 shadow-2xs">
                  <label className="font-bold text-slate-700 block text-xs">
                    {isBn ? BN_DICT['signature_position'] : EN_DICT['signature_position']}
                  </label>
                  <div className="grid grid-cols-2 gap-2">
                    <button
                      type="button"
                      onClick={() => handleUpdate('signatureSide', 'front')}
                      className={`py-2 px-3 rounded-lg border text-center font-bold text-xs transition-all ${
                        settings.signatureSide !== 'back'
                          ? 'bg-emerald-50 border-emerald-500 text-emerald-900'
                          : 'border-slate-200 text-slate-600 hover:border-slate-300'
                      }`}
                    >
                      {isBn ? BN_DICT['front_side'] : EN_DICT['front_side']}
                    </button>
                    <button
                      type="button"
                      onClick={() => handleUpdate('signatureSide', 'back')}
                      className={`py-2 px-3 rounded-lg border text-center font-bold text-xs transition-all ${
                        settings.signatureSide === 'back'
                          ? 'bg-emerald-50 border-emerald-500 text-emerald-900'
                          : 'border-slate-200 text-slate-600 hover:border-slate-300'
                      }`}
                    >
                      {isBn ? BN_DICT['back_side'] : EN_DICT['back_side']}
                    </button>
                  </div>
                </div>

                <div className="space-y-1.5">
                  <label className="font-bold text-slate-700 block text-xs">
                    {isBn ? BN_DICT['principal_title'] : EN_DICT['principal_title']}
                  </label>
                  <input
                    type="text"
                    value={settings.principalTitleBn || ''}
                    onChange={(e) => handleUpdate('principalTitleBn', e.target.value)}
                    className="w-full px-3 py-2 bg-white border border-slate-200 rounded-lg text-xs font-semibold focus:ring-1 focus:ring-emerald-500"
                    placeholder="অধ্যক্ষ / প্রধান শিক্ষক"
                  />
                </div>
              </>
            )}
          </div>
        )}

        {/* ---------------------------------------------------- */}
        {/* TAB 3: PHOTO POSITION                                */}
        {/* ---------------------------------------------------- */}
        {activeTab === 'photo' && (
          <div className="space-y-4 animate-fadeIn">
            {/* Show Photo */}
            <label className="flex items-center justify-between p-3 rounded-xl bg-white border border-slate-200 cursor-pointer hover:border-emerald-300 transition-colors shadow-2xs">
              <span className="font-bold text-slate-700 text-xs">{isBn ? BN_DICT['show_student_photo'] : EN_DICT['show_student_photo']}</span>
              <input
                type="checkbox"
                checked={settings.showPhoto !== false}
                onChange={(e) => handleUpdate('showPhoto', e.target.checked)}
                className="w-4 h-4 rounded text-emerald-600 focus:ring-emerald-500 border-slate-300 cursor-pointer"
              />
            </label>

            {settings.showPhoto !== false && (
              <div className="space-y-4 bg-white p-3 rounded-xl border border-slate-200 shadow-2xs">
                {/* Photo Size */}
                <div className="space-y-1.5">
                  <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                    <span>{isBn ? BN_DICT['photo_size'] : EN_DICT['photo_size']}</span>
                    <span className="font-mono text-emerald-700">{settings.photoSize || 21.5} mm</span>
                  </div>
                  <input
                    type="range"
                    min={15}
                    max={30}
                    step={0.5}
                    value={settings.photoSize || 21.5}
                    onChange={(e) => handleUpdate('photoSize', parseFloat(e.target.value))}
                    className="w-full accent-emerald-600 cursor-pointer"
                  />
                </div>

                {/* Photo X Offset */}
                <div className="space-y-1.5 pt-2 border-t border-slate-100">
                  <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                    <span>{isBn ? BN_DICT['horizontal_position'] : EN_DICT['horizontal_position']}</span>
                    <span className="font-mono text-emerald-700">{settings.photoOffsetX || 0} px</span>
                  </div>
                  <input
                    type="range"
                    min={-20}
                    max={20}
                    step={1}
                    value={settings.photoOffsetX || 0}
                    onChange={(e) => handleUpdate('photoOffsetX', parseInt(e.target.value, 10))}
                    className="w-full accent-emerald-600 cursor-pointer"
                  />
                </div>
                
                {/* Photo Y Offset */}
                <div className="space-y-1.5">
                  <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                    <span>{isBn ? BN_DICT['vertical_position'] : EN_DICT['vertical_position']}</span>
                    <span className="font-mono text-emerald-700">{settings.photoOffsetY || 0} px</span>
                  </div>
                  <input
                    type="range"
                    min={-20}
                    max={20}
                    step={1}
                    value={settings.photoOffsetY || 0}
                    onChange={(e) => handleUpdate('photoOffsetY', parseInt(e.target.value, 10))}
                    className="w-full accent-emerald-600 cursor-pointer"
                  />
                </div>
              </div>
            )}
          </div>
        )}

        {/* ---------------------------------------------------- */}
        {/* TAB 4: TYPOGRAPHY                                    */}
        {/* ---------------------------------------------------- */}
        {activeTab === 'typography' && (
          <div className="space-y-4 animate-fadeIn">
            {/* Institute Names */}
            <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-2xs space-y-4">
              <label className="font-bold text-slate-700 block text-xs border-b border-slate-100 pb-2 mb-2">
                {isBn ? BN_DICT['institute_info'] : EN_DICT['institute_info']}
              </label>
              <div className="space-y-1.5">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['institute_name'] : EN_DICT['institute_name']}</span>
                  <span className="font-mono text-emerald-700">{settings.instNameSize || 11} px</span>
                </div>
                <input
                  type="range"
                  min={8} max={16} step={0.5}
                  value={settings.instNameSize || 11}
                  onChange={(e) => handleUpdate('instNameSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>
              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['institute_address'] : EN_DICT['institute_address']}</span>
                  <span className="font-mono text-emerald-700">{settings.instAddressSize || 7.5} px</span>
                </div>
                <input
                  type="range"
                  min={5} max={12} step={0.5}
                  value={settings.instAddressSize || 7.5}
                  onChange={(e) => handleUpdate('instAddressSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>
            </div>

            {/* Labels */}
            <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-2xs space-y-4">
              <label className="font-bold text-slate-700 block text-xs border-b border-slate-100 pb-2 mb-2">
                {isBn ? BN_DICT['labels_titles'] : EN_DICT['labels_titles']}
              </label>
              
              <div className="space-y-1.5">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['id_card_label_font_size'] : EN_DICT['id_card_label_font_size']}</span>
                  <span className="font-mono text-emerald-700">{settings.idCardLabelSize || 7.5} px</span>
                </div>
                <input
                  type="range"
                  min={5} max={12} step={0.5}
                  value={settings.idCardLabelSize || 7.5}
                  onChange={(e) => handleUpdate('idCardLabelSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['id_label_text_centering_paddin'] : EN_DICT['id_label_text_centering_paddin']}</span>
                  <span className="font-mono text-emerald-700">{settings.idCardLabelPaddingTop || 2} px</span>
                </div>
                <input
                  type="range"
                  min={0} max={8} step={0.5}
                  value={settings.idCardLabelPaddingTop || 2}
                  onChange={(e) => handleUpdate('idCardLabelPaddingTop', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['id_label_box_top_margin'] : EN_DICT['id_label_box_top_margin']}</span>
                  <span className="font-mono text-emerald-700">{settings.idCardLabelMarginTop || 1} px</span>
                </div>
                <input
                  type="range"
                  min={0} max={8} step={0.5}
                  value={settings.idCardLabelMarginTop || 1}
                  onChange={(e) => handleUpdate('idCardLabelMarginTop', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>
            </div>

            {/* Line & Spacing Controls */}
            <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-2xs space-y-4">
              <label className="font-bold text-slate-700 block text-xs border-b border-slate-100 pb-2 mb-2">
                {isBn ? BN_DICT['spacing_line_heights'] : EN_DICT['spacing_line_heights']}
              </label>

              <div className="space-y-1.5">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['line_height'] : EN_DICT['line_height']}</span>
                  <span className="font-mono text-emerald-700">{settings.lineHeightMultiplier || 1.25}x</span>
                </div>
                <input
                  type="range"
                  min={1.0} max={1.7} step={0.05}
                  value={settings.lineHeightMultiplier || 1.25}
                  onChange={(e) => handleUpdate('lineHeightMultiplier', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['item_row_spacing'] : EN_DICT['item_row_spacing']}</span>
                  <span className="font-mono text-emerald-700">{settings.itemSpacingValue !== undefined ? settings.itemSpacingValue : 1.5} px</span>
                </div>
                <input
                  type="range"
                  min={0} max={6} step={0.5}
                  value={settings.itemSpacingValue !== undefined ? settings.itemSpacingValue : 1.5}
                  onChange={(e) => handleUpdate('itemSpacingValue', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['section_paragraph_spacing'] : EN_DICT['section_paragraph_spacing']}</span>
                  <span className="font-mono text-emerald-700">{settings.paragraphSpacing !== undefined ? settings.paragraphSpacing : 2} px</span>
                </div>
                <input
                  type="range"
                  min={0} max={8} step={0.5}
                  value={settings.paragraphSpacing !== undefined ? settings.paragraphSpacing : 2}
                  onChange={(e) => handleUpdate('paragraphSpacing', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['content_top_margin'] : EN_DICT['content_top_margin']}</span>
                  <span className="font-mono text-emerald-700">{settings.contentTopMargin !== undefined ? settings.contentTopMargin : 0} px</span>
                </div>
                <input
                  type="range"
                  min={-4} max={8} step={0.5}
                  value={settings.contentTopMargin !== undefined ? settings.contentTopMargin : 0}
                  onChange={(e) => handleUpdate('contentTopMargin', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>
            </div>

            {/* Student Core Info */}
            <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-2xs space-y-4">
              <label className="font-bold text-slate-700 block text-xs border-b border-slate-100 pb-2 mb-2">
                {isBn ? BN_DICT['student_core_info'] : EN_DICT['student_core_info']}
              </label>
              <div className="space-y-1.5">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['student_name_size'] : EN_DICT['student_name_size']}</span>
                  <span className="font-mono text-emerald-700">{settings.studentNameSize || 13} px</span>
                </div>
                <input
                  type="range"
                  min={10} max={18} step={0.5}
                  value={settings.studentNameSize || 13}
                  onChange={(e) => handleUpdate('studentNameSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['student_id_size'] : EN_DICT['student_id_size']}</span>
                  <span className="font-mono text-emerald-700">{settings.studentIdSize || 9.5} px</span>
                </div>
                <input
                  type="range"
                  min={7} max={14} step={0.5}
                  value={settings.studentIdSize || 9.5}
                  onChange={(e) => handleUpdate('studentIdSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['blood_group_size'] : EN_DICT['blood_group_size']}</span>
                  <span className="font-mono text-emerald-700">{settings.bloodGroupSize || 8} px</span>
                </div>
                <input
                  type="range"
                  min={5} max={12} step={0.5}
                  value={settings.bloodGroupSize || 8}
                  onChange={(e) => handleUpdate('bloodGroupSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>
            </div>

            {/* Other Info */}
            <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-2xs space-y-4">
              <label className="font-bold text-slate-700 block text-xs border-b border-slate-100 pb-2 mb-2">
                {isBn ? BN_DICT['other_info'] : EN_DICT['other_info']}
              </label>
              
              <div className="space-y-1.5">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['parents_name_size'] : EN_DICT['parents_name_size']}</span>
                  <span className="font-mono text-emerald-700">{settings.parentsNameSize || 8.5} px</span>
                </div>
                <input
                  type="range"
                  min={5} max={12} step={0.5}
                  value={settings.parentsNameSize || 8.5}
                  onChange={(e) => handleUpdate('parentsNameSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['address_size'] : EN_DICT['address_size']}</span>
                  <span className="font-mono text-emerald-700">{settings.addressTextSize || 7} px</span>
                </div>
                <input
                  type="range"
                  min={5} max={11} step={0.5}
                  value={settings.addressTextSize || 7}
                  onChange={(e) => handleUpdate('addressTextSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>

              <div className="space-y-1.5 pt-2 border-t border-slate-100">
                <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                  <span>{isBn ? BN_DICT['academic_info_size'] : EN_DICT['academic_info_size']}</span>
                  <span className="font-mono text-emerald-700">{settings.academicInfoSize || 7.5} px</span>
                </div>
                <input
                  type="range"
                  min={5} max={11} step={0.5}
                  value={settings.academicInfoSize || 7.5}
                  onChange={(e) => handleUpdate('academicInfoSize', parseFloat(e.target.value))}
                  className="w-full accent-emerald-600 cursor-pointer"
                />
              </div>
            </div>
          </div>
        )}

        {/* ---------------------------------------------------- */}
        {/* TAB 5: GRAPHICS                                      */}
        {/* ---------------------------------------------------- */}
        {activeTab === 'graphic' && (
          <div className="space-y-4 animate-fadeIn">
            {/* Graphic Themes */}
            <div className="space-y-2">
              <label className="font-bold text-slate-700 block text-xs">
                {isBn ? BN_DICT['card_design_graphic_theme'] : EN_DICT['card_design_graphic_theme']}
              </label>
              <div className="grid grid-cols-2 gap-2">
                {[
                  {
                    id: 'classic_waves',
                    nameBn: 'ক্লাসিক ওয়েভস',
                    nameEn: 'Classic Waves',
                    descBn: 'ডবল স্মুথ ওয়েভ ও ফ্রেম',
                    badge: 'ডিফল্ট',
                  },
                  {
                    id: 'modern_geometric',
                    nameBn: 'মডার্ন জিওমেট্রিক',
                    nameEn: 'Modern Geometric',
                    descBn: 'কৌণিক পলিগন ও হাই-টেক লাইন',
                  },
                  {
                    id: 'elegant_curves',
                    nameBn: 'এলিগ্যান্ট কার্ভস',
                    nameEn: 'Elegant Curves',
                    descBn: 'মসৃণ কার্ভ ও সোনালী রিবন',
                  },
                  {
                    id: 'minimal_clean',
                    nameBn: 'মিনিমাল ও ক্লিন',
                    nameEn: 'Minimal & Clean',
                    descBn: 'খোলামেলা ও ফ্রেশ মার্জিন',
                  },
                  {
                    id: 'tech_stripes',
                    nameBn: 'টেক স্ট্রাইপস',
                    nameEn: 'Tech Stripes',
                    descBn: 'ডায়নামিক স্পিড স্ট্রাইপ',
                  },
                  {
                    id: 'islamic_ornament',
                    nameBn: 'ঐতিহ্যবাহী ইসলামিক',
                    nameEn: 'Islamic Ornament',
                    descBn: 'আর্চ গম্বুজ কার্ভ ও নকশা',
                  },
                ].map((theme) => {
                  const isSelected = (settings.cardGraphicTheme || 'classic_waves') === theme.id;
                  return (
                    <button
                      key={theme.id}
                      type="button"
                      onClick={() => handleUpdate('cardGraphicTheme', theme.id)}
                      className={`p-2.5 rounded-xl border text-left transition-all relative flex flex-col justify-between ${
                        isSelected
                          ? 'bg-emerald-50/70 border-emerald-500 text-emerald-950 shadow-2xs ring-1 ring-emerald-500/20'
                          : 'bg-white border-slate-200 text-slate-700 hover:border-slate-300'
                      }`}
                    >
                      <div className="flex items-center justify-between mb-1">
                        <span className="font-black text-[11px] text-[#08544c]">
                          {isBn ? theme.nameBn : theme.nameEn}
                        </span>
                        {theme.badge && (
                          <span className="text-[8.5px] px-1 py-0.2 bg-emerald-100 text-emerald-800 rounded font-bold">
                            {theme.badge}
                          </span>
                        )}
                      </div>
                      <p className="text-[9px] text-slate-500 line-clamp-2 leading-tight">
                        {isBn ? theme.descBn : theme.id}
                      </p>
                    </button>
                  );
                })}
              </div>
            </div>

            {/* Custom Graphic Upload */}
            <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-2xs space-y-3">
              <div className="flex items-center justify-between border-b border-slate-100 pb-2">
                <div>
                  <h4 className="font-bold text-slate-700 text-xs">
                    {isBn ? BN_DICT['custom_background_graphic'] : EN_DICT['custom_background_graphic']}
                  </h4>
                  <p className="text-[10px] text-slate-400">
                    {isBn ? BN_DICT['upload_your_custom_banner_or_t'] : EN_DICT['upload_your_custom_banner_or_t']}
                  </p>
                </div>
                <label className="cursor-pointer inline-flex items-center gap-1.5 px-2.5 py-1.5 bg-emerald-700 hover:bg-emerald-800 text-white rounded-lg text-xs font-bold transition-colors">
                  <Upload className="w-3.5 h-3.5" />
                  <span>{isBn ? BN_DICT['upload'] : EN_DICT['upload']}</span>
                  <input
                    type="file"
                    accept="image/png, image/jpeg, image/svg+xml, image/webp"
                    className="hidden"
                    onChange={handleCustomGraphicUpload}
                  />
                </label>
              </div>

              {settings.customGraphicUrl ? (
                <div className="space-y-3">
                  <div className="flex items-center gap-3 p-2 bg-slate-50 rounded-lg border border-slate-200">
                    <div className="w-16 h-12 bg-white border border-slate-200 rounded overflow-hidden flex items-center justify-center">
                      <img
                        src={settings.customGraphicUrl}
                        alt="Custom Graphic Preview"
                        className="w-full h-full object-cover"
                      />
                    </div>
                    <div className="flex-1 min-w-0">
                      <p className="text-[11px] font-bold text-slate-800 truncate">
                        {isBn ? BN_DICT['custom_graphic_connected'] : EN_DICT['custom_graphic_connected']}
                      </p>
                      <button
                        type="button"
                        onClick={() => handleUpdate('customGraphicUrl', '')}
                        className="inline-flex items-center gap-1 text-[10px] text-red-600 hover:text-red-700 font-bold mt-1"
                      >
                        <Trash2 className="w-3 h-3" />
                        <span>{isBn ? BN_DICT['remove'] : EN_DICT['remove']}</span>
                      </button>
                    </div>
                  </div>

                  {/* Opacity Slider */}
                  <div className="space-y-1.5 pt-1">
                    <div className="flex justify-between text-slate-600 text-[11px] font-bold">
                      <span>{isBn ? BN_DICT['graphic_opacity'] : EN_DICT['graphic_opacity']}</span>
                      <span className="font-mono text-emerald-700">{settings.graphicOpacity || 100}%</span>
                    </div>
                    <input
                      type="range"
                      min={10} max={100} step={5}
                      value={settings.graphicOpacity || 100}
                      onChange={(e) => handleUpdate('graphicOpacity', parseInt(e.target.value, 10))}
                      className="w-full accent-emerald-600 cursor-pointer"
                    />
                  </div>
                </div>
              ) : (
                <p className="text-[10px] text-slate-400 italic">
                  {isBn ? BN_DICT['no_custom_graphic_uploaded_def'] : EN_DICT['no_custom_graphic_uploaded_def']}
                </p>
              )}
            </div>

            {/* Graphic Display Toggles */}
            <div className="bg-white p-3 rounded-xl border border-slate-200 shadow-2xs space-y-3">
              <label className="flex items-center justify-between cursor-pointer">
                <div>
                  <span className="font-bold text-slate-700 block text-xs">
                    {isBn ? BN_DICT['show_background_graphics'] : EN_DICT['show_background_graphics']}
                  </span>
                  <span className="text-[9.5px] text-slate-400">
                    {isBn ? BN_DICT['show_bottom_curves_and_border'] : EN_DICT['show_bottom_curves_and_border']}
                  </span>
                </div>
                <input
                  type="checkbox"
                  checked={settings.showBackgroundGraphics !== false}
                  onChange={(e) => handleUpdate('showBackgroundGraphics', e.target.checked)}
                  className="w-4 h-4 rounded text-emerald-600 focus:ring-emerald-500 border-slate-300 cursor-pointer"
                />
              </label>

              <div className="pt-2 border-t border-slate-100">
                <label className="flex items-center justify-between cursor-pointer">
                  <div>
                    <span className="font-bold text-slate-700 block text-xs">
                      {isBn ? BN_DICT['show_watermark_logo'] : EN_DICT['show_watermark_logo']}
                    </span>
                    <span className="text-[9.5px] text-slate-400">
                      {isBn ? BN_DICT['light_watermark_logo_in_center'] : EN_DICT['light_watermark_logo_in_center']}
                    </span>
                  </div>
                  <input
                    type="checkbox"
                    checked={settings.showWatermarkLogo !== false}
                    onChange={(e) => handleUpdate('showWatermarkLogo', e.target.checked)}
                    className="w-4 h-4 rounded text-emerald-600 focus:ring-emerald-500 border-slate-300 cursor-pointer"
                  />
                </label>
              </div>
            </div>
          </div>
        )}

        {/* ---------------------------------------------------- */}
        {/* TAB 6: PRINT                                         */}
        {/* ---------------------------------------------------- */}
        {activeTab === 'print' && (
          <div className="space-y-4 animate-fadeIn">
            {/* Paper Size */}
            <div className="space-y-2">
              <label className="font-bold text-slate-700 block text-xs">
                {isBn ? BN_DICT['print_paper_size'] : EN_DICT['print_paper_size']}
              </label>
              <div className="grid grid-cols-2 gap-2">
                <button
                  type="button"
                  onClick={() => handleUpdate('paperSize', 'a4')}
                  className={`py-2.5 px-3 rounded-xl border text-center font-bold text-xs transition-all ${
                    settings.paperSize === 'a4'
                      ? 'bg-emerald-50 border-emerald-500 text-emerald-900 shadow-2xs'
                      : 'border-slate-200 bg-white text-slate-600 hover:border-slate-300'
                  }`}
                >
                  A4
                </button>
                <button
                  type="button"
                  onClick={() => handleUpdate('paperSize', 'legal')}
                  className={`py-2.5 px-3 rounded-xl border text-center font-bold text-xs transition-all ${
                    settings.paperSize === 'legal'
                      ? 'bg-emerald-50 border-emerald-500 text-emerald-900 shadow-2xs'
                      : 'border-slate-200 bg-white text-slate-600 hover:border-slate-300'
                  }`}
                >
                  Legal
                </button>
              </div>
            </div>

            {/* Card Side */}
            <div className="space-y-2">
              <label className="font-bold text-slate-700 block text-xs">
                {isBn ? BN_DICT['card_sides'] : EN_DICT['card_sides']}
              </label>
              <div className="grid grid-cols-3 gap-1.5">
                {[
                  { key: 'both', label: isBn ? BN_DICT['both'] : EN_DICT['both'] },
                  { key: 'front', label: isBn ? BN_DICT['front'] : EN_DICT['front'] },
                  { key: 'back', label: isBn ? BN_DICT['back'] : EN_DICT['back'] },
                ].map((item) => (
                  <button
                    key={item.key}
                    type="button"
                    onClick={() => handleUpdate('cardSide', item.key as any)}
                    className={`py-2 px-2 rounded-lg border text-center text-xs transition-all ${
                      settings.cardSide === item.key
                        ? 'bg-emerald-50 border-emerald-500 text-emerald-900 font-bold shadow-2xs'
                        : 'border-slate-200 bg-white text-slate-600 font-semibold hover:border-slate-300'
                    }`}
                  >
                    {item.label}
                  </button>
                ))}
              </div>
            </div>

            {/* Cut Marks Toggle */}
            <label className="flex items-center justify-between p-3 rounded-xl bg-white border border-slate-200 cursor-pointer hover:border-emerald-300 transition-colors shadow-2xs">
              <span className="font-bold text-slate-700 text-xs">{isBn ? BN_DICT['show_cut_marks'] : EN_DICT['show_cut_marks']}</span>
              <input
                type="checkbox"
                checked={settings.showCutMarks !== false}
                onChange={(e) => handleUpdate('showCutMarks', e.target.checked)}
                className="w-4 h-4 rounded text-emerald-600 focus:ring-emerald-500 border-slate-300 cursor-pointer"
              />
            </label>
          </div>
        )}
      </div>
    </div>
  );
};
