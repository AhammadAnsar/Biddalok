import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React from 'react';
import { WifiOff, RefreshCw, ExternalLink, ShieldCheck } from 'lucide-react';
import { useNetworkStatus, openInExternalBrowser } from '../../utils/networkStatus';
import { useAppStore } from '../../store/useAppStore';

interface OnlineFeatureBoundaryProps {
  featureNameEn: string;
  featureNameBn: string;
  externalUrl?: string;
  explanationEn?: string;
  explanationBn?: string;
  children: React.ReactNode;
  fallbackUi?: React.ReactNode;
}

export const OnlineFeatureBoundary: React.FC<OnlineFeatureBoundaryProps> = ({
  featureNameEn,
  featureNameBn,
  externalUrl,
  explanationEn,
  explanationBn,
  children,
  fallbackUi,
}) => {
  const { language } = useAppStore();
  const isBn = language === 'bn';
  const { isOnline, isProbing, probeConnectivity } = useNetworkStatus();

  if (isOnline) {
    return <>{children}</>;
  }

  return (
    <div className="rounded-2xl border border-amber-200 bg-amber-50/70 p-6 text-center space-y-4 shadow-sm animate-fade-in">
      <div className="w-12 h-12 rounded-2xl bg-amber-100 text-amber-700 mx-auto flex items-center justify-center border border-amber-300">
        <WifiOff className="w-6 h-6" />
      </div>

      <div className="space-y-1.5 max-w-md mx-auto">
        <div className="inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full bg-amber-100 text-amber-800 text-xs font-bold">
          <span>{isBn ? BN_DICT['online_only_feature'] : EN_DICT['online_only_feature']}</span>
        </div>
        <h3 className="text-base font-bold text-slate-900">
          {isBn ? `${featureNameBn} ব্যবহারের জন্য ইন্টারনেট প্রয়োজন` : `${featureNameEn} Requires Internet Connection`}
        </h3>
        <p className="text-xs text-slate-600 leading-relaxed">
          {isBn 
            ? (explanationBn || 'সফটওয়্যারটির মূল খতিয়ান, শিক্ষার্থী তথ্য, সনদ ও পরীক্ষা ব্যবস্থাপনা শতভাগ অফলাইনে সুরক্ষিত ও সক্রিয় আছে। কেবল এই বহিঃসংযোগ ফিচারের জন্য সক্রিয় ইন্টারনেট সংযোগ প্রয়োজন।')
            : (explanationEn || 'Core school records, student profiles, testimonials and exam management remain 100% functional offline. Only this external service requires an internet connection.')}
        </p>
      </div>

      <div className="flex flex-wrap items-center justify-center gap-3 pt-2">
        <button
          type="button"
          onClick={() => probeConnectivity()}
          disabled={isProbing}
          className="px-4 py-2 text-xs font-bold text-slate-800 bg-white hover:bg-slate-50 border border-slate-300 rounded-xl transition-all shadow-xs inline-flex items-center gap-2 disabled:opacity-50"
        >
          <RefreshCw className={`w-3.5 h-3.5 text-slate-600 ${isProbing ? 'animate-spin' : ''}`} />
          <span>{isBn ? BN_DICT['retry_connection'] : EN_DICT['retry_connection']}</span>
        </button>

        {externalUrl && (
          <button
            type="button"
            onClick={() => openInExternalBrowser(externalUrl)}
            className="px-4 py-2 text-xs font-bold text-white bg-indigo-600 hover:bg-indigo-700 rounded-xl transition-all shadow-xs inline-flex items-center gap-2"
          >
            <ExternalLink className="w-3.5 h-3.5" />
            <span>{isBn ? BN_DICT['open_in_external_browser'] : EN_DICT['open_in_external_browser']}</span>
          </button>
        )}
      </div>

      {fallbackUi && (
        <div className="mt-4 pt-4 border-t border-amber-200/80 text-left">
          {fallbackUi}
        </div>
      )}

      <div className="pt-2 flex items-center justify-center gap-1.5 text-[11px] text-emerald-700 font-medium">
        <ShieldCheck className="w-3.5 h-3.5" />
        <span>{isBn ? BN_DICT['local_offline_database_active'] : EN_DICT['local_offline_database_active']}</span>
      </div>
    </div>
  );
};
