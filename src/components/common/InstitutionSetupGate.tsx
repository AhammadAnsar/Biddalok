import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React from 'react';
import { Building2, AlertTriangle, ArrowRight } from 'lucide-react';
import { useNavigate } from 'react-router-dom';
import { useAppStore } from '../../store/useAppStore';

interface InstitutionSetupGateProps {
  children?: React.ReactNode;
  mode?: 'gate' | 'banner';
  featureName?: string;
}

export const InstitutionSetupGate: React.FC<InstitutionSetupGateProps> = ({
  children,
  mode = 'gate',
  featureName
}) => {
  const navigate = useNavigate();
  const { institution, language } = useAppStore();
  const isBn = language === 'bn';

  const hasName = Boolean(institution?.name?.trim() || institution?.nameBn?.trim());
  const hasEiin = Boolean(institution?.eiin?.trim());
  const isConfigured = hasName && hasEiin;

  if (isConfigured) {
    return <>{children}</>;
  }

  if (mode === 'banner') {
    return (
      <div className="mb-4 p-4 bg-amber-50 border border-amber-200 rounded-2xl flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3 shadow-xs">
        <div className="flex items-start gap-3">
          <div className="w-8 h-8 rounded-xl bg-amber-100 text-amber-800 flex items-center justify-center shrink-0 mt-0.5">
            <AlertTriangle className="w-4 h-4" />
          </div>
          <div>
            <h4 className="text-xs font-bold text-amber-900">
              {isBn ? BN_DICT['institution_setup_incomplete_n'] : EN_DICT['institution_setup_incomplete_n']}
            </h4>
            <p className="text-[11px] text-slate-600 mt-0.5">
              {isBn ? BN_DICT['please_configure_official_inst'] : EN_DICT['please_configure_official_inst']}
            </p>
          </div>
        </div>
        <button
          type="button"
          onClick={() => navigate('/institution')}
          className="px-3 py-1.5 bg-amber-600 hover:bg-amber-700 text-white rounded-xl text-xs font-semibold inline-flex items-center gap-1.5 shrink-0"
        >
          <span>{isBn ? BN_DICT['go_to_settings'] : EN_DICT['go_to_settings']}</span>
          <ArrowRight className="w-3.5 h-3.5" />
        </button>
      </div>
    );
  }

  // Gate mode
  return (
    <div className="p-8 sm:p-12 max-w-lg mx-auto bg-white rounded-3xl border border-amber-200 shadow-md text-center space-y-5 my-8">
      <div className="w-14 h-14 rounded-2xl bg-amber-100 text-amber-700 mx-auto flex items-center justify-center border border-amber-200 shadow-inner">
        <Building2 className="w-7 h-7" />
      </div>

      <div className="space-y-2">
        <div className="inline-flex items-center gap-1.5 px-3 py-1 rounded-full bg-amber-100 text-amber-800 text-xs font-bold">
          <AlertTriangle className="w-3.5 h-3.5" />
          <span>{isBn ? BN_DICT['setup_required'] : EN_DICT['setup_required']}</span>
        </div>
        <h3 className="text-lg font-bold text-slate-900">
          {isBn ? BN_DICT['institution_profile_incomplete'] : EN_DICT['institution_profile_incomplete']}
        </h3>
        <p className="text-xs text-slate-600 leading-relaxed">
          {isBn 
            ? `${featureName ? featureName + ' তৈরি বা প্রিন্ট' : 'অফিশিয়াল ডকুমেন্ট ইস্যু'} করার পূর্বে প্রতিষ্ঠানের নাম, EIIN ও প্রধান শিক্ষকের তথ্য সংরক্ষণ করতে হবে। বিদ্যালোক কোনো ডামি বা অননুমোদিত ফলব্যাক ব্যবহার করে না।`
            : `Before issuing official documents${featureName ? ' for ' + featureName : ''}, please configure official institution name, EIIN, and headmaster details. Biddalok never outputs hardcoded dummy fallbacks.`}
        </p>
      </div>

      <div className="pt-2">
        <button
          type="button"
          onClick={() => navigate('/institution')}
          className="px-5 py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white text-xs font-bold rounded-xl shadow-md inline-flex items-center gap-2 transition-all"
        >
          <Building2 className="w-4 h-4" />
          <span>{isBn ? BN_DICT['complete_institution_settings'] : EN_DICT['complete_institution_settings']}</span>
          <ArrowRight className="w-4 h-4" />
        </button>
      </div>
    </div>
  );
};
