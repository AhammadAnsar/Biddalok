import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { AttestationSettings } from '../types';
import { Sliders, RotateCcw, Check, X, Save, Type, MoveVertical, FileSpreadsheet, Frame, QrCode, PenTool } from 'lucide-react';

interface AttestationLayoutSettingsModalProps {
 isOpen: boolean;
 onClose: () => void;
 currentSettings: AttestationSettings;
 onApplySettings: (settings: Partial<AttestationSettings>) => void;
 onSaveAsDefault: (settings: Partial<AttestationSettings>) => void;
 isBn: boolean;
}

const defaultOptimalSettings: Partial<AttestationSettings> = {
 instNameFontSize: 25,
 titleFontSize: 28,
 bodyFontSize: 16,
 bodyLineHeight: 2.25,
 titleTopSpace: 24,
 titleBottomSpace: 20,
 paragraphSpacing: 14,
 closingTopSpace: 20,
 closingFontSize: 18,
 pageMargin: 0.45,
 frameStyle: 'none',
 showQrCode: true,
 showSignature: true,
};

export const AttestationLayoutSettingsModal: React.FC<AttestationLayoutSettingsModalProps> = ({
 isOpen,
 onClose,
 currentSettings,
 onApplySettings,
 onSaveAsDefault,
 isBn,
}) => {
 const [formData, setFormData] = useState<Partial<AttestationSettings>>({
 ...defaultOptimalSettings,
 ...currentSettings,
 });

 const [savedNotification, setSavedNotification] = useState(false);

 useEffect(() => {
 setFormData(prev => ({
 ...prev,
 ...currentSettings,
 }));
 }, [currentSettings]);

 if (!isOpen) return null;

 const handleChange = (key: keyof AttestationSettings, val: any) => {
 const updated = { ...formData, [key]: val };
 setFormData(updated);
 // Instant Live Update to Certificate Preview
 onApplySettings(updated);
 };

 const handleReset = () => {
 setFormData(defaultOptimalSettings);
 onApplySettings(defaultOptimalSettings);
 };

 const handleSaveDefault = () => {
 onSaveAsDefault(formData);
 setSavedNotification(true);
 setTimeout(() => {
 setSavedNotification(false);
 }, 2500);
 };

 const frameOptions: { key: AttestationSettings['frameStyle']; labelBn: string; labelEn: string; descBn: string }[] = [
 { key: 'none', labelBn: 'বর্ডার নেই', labelEn: 'None', descBn: 'ক্লিন বর্ডারলেস ফরম্যাট' },
 { key: 'simple', labelBn: 'সিম্পল বর্ডার', labelEn: 'Simple', descBn: 'একক সূক্ষ্ম লাইন' },
 { key: 'double', labelBn: 'ডাবল বর্ডার', labelEn: 'Double', descBn: 'দ্বৈত মার্জিন বর্ডার' },
 { key: 'corner', labelBn: 'কোর্নার ফ্রেম', labelEn: 'Corner', descBn: 'চার কোণায় ক্লাসিক কর্নার' },
 { key: 'royal', labelBn: 'রয়্যাল ফ্রেম', labelEn: 'Royal', descBn: 'রাজকীয় সনদ অলঙ্করণ' },
 { key: 'academic', labelBn: 'একাডেমিক ফ্রেম', labelEn: 'Academic', descBn: 'ঐতিহ্যবাহী প্রাতিষ্ঠানিক ফ্রেম' },
 ];

 return (
 <div className="fixed inset-0 z-50 overflow-hidden">
 {/* Light Backdrop that allows seeing certificate preview in real-time */}
 <div 
 className="fixed inset-0 bg-slate-900/30 backdrop-blur-[1px] transition-opacity"
 onClick={onClose}
 />

 {/* Slide-over Drawer docked to Right */}
 <div className="fixed inset-y-0 right-0 max-w-full flex pl-10">
 <div 
 className="w-screen max-w-md bg-white shadow-2xl flex flex-col border-l border-slate-200 slide-in-from-right "
 onClick={(e) => e.stopPropagation()}
 >
 {/* Header */}
 <div className="flex items-center justify-between px-5 py-4 border-b border-slate-200 bg-slate-50/80">
 <div className="flex items-center gap-2.5">
 <div className="p-2 bg-indigo-50 text-indigo-600 rounded-xl border border-indigo-100">
 <Sliders className="w-5 h-5" />
 </div>
 <div>
 <h2 className="text-base font-bold text-slate-900">
 {isBn ? BN_DICT['live_layout_frame_settings'] : EN_DICT['live_layout_frame_settings']}
 </h2>
 <p className="text-[11px] text-slate-500">
 {isBn ? BN_DICT['changes_update_certificate_pre'] : EN_DICT['changes_update_certificate_pre']}
 </p>
 </div>
 </div>
 <button
 onClick={onClose}
 className="p-2 text-slate-400 hover:text-slate-700 hover:bg-slate-100 rounded-xl transition-colors"
 >
 <X className="w-5 h-5" />
 </button>
 </div>

 {/* Form Body */}
 <div className="p-5 space-y-6 overflow-y-auto flex-1">
 {savedNotification && (
 <div className="p-3 bg-emerald-50 border border-emerald-200 rounded-xl flex items-center gap-2 text-emerald-800 text-xs font-semibold ">
 <Check className="w-4 h-4 text-emerald-600" />
 <span>{isBn ? BN_DICT['layout_successfully_saved_as_d'] : EN_DICT['layout_successfully_saved_as_d']}</span>
 </div>
 )}

 {/* Section 1: Border Frames */}
 <div className="space-y-3">
 <div className="flex items-center gap-2 text-slate-800 font-bold text-xs border-b border-slate-100 pb-1.5">
 <Frame className="w-4 h-4 text-indigo-600" />
 <span>{isBn ? BN_DICT['certificate_border_frame'] : EN_DICT['certificate_border_frame']}</span>
 </div>

 <div className="grid grid-cols-2 gap-2">
 {frameOptions.map(opt => {
 const isSelected = (formData.frameStyle || 'none') === opt.key;
 return (
 <button
 key={opt.key}
 type="button"
 onClick={() => handleChange('frameStyle', opt.key)}
 className={`p-2.5 rounded-xl border text-left transition-all ${
 isSelected
 ? 'border-indigo-600 bg-indigo-50/70 shadow-xs'
 : 'border-slate-200 hover:border-slate-300 hover:bg-slate-50'
 }`}
 >
 <div className="flex items-center justify-between">
 <span className={`text-xs font-bold ${isSelected ? 'text-indigo-700' : 'text-slate-800'}`}>
 {isBn ? opt.labelBn : opt.labelEn}
 </span>
 {isSelected && <Check className="w-3.5 h-3.5 text-indigo-600" />}
 </div>
 <p className="text-[10px] text-slate-500 mt-0.5 leading-tight">
 {opt.descBn}
 </p>
 </button>
 );
 })}
 </div>
 </div>

 {/* Section 2: Element Toggles */}
 <div className="space-y-3">
 <div className="flex items-center gap-2 text-slate-800 font-bold text-xs border-b border-slate-100 pb-1.5">
 <QrCode className="w-4 h-4 text-indigo-600" />
 <span>{isBn ? BN_DICT['components_visibility'] : EN_DICT['components_visibility']}</span>
 </div>

 <div className="grid grid-cols-2 gap-2.5">
 {/* QR Code toggle */}
 <button
 type="button"
 onClick={() => handleChange('showQrCode', !formData.showQrCode)}
 className={`p-2.5 rounded-xl border flex items-center justify-between transition-all ${
 formData.showQrCode !== false
 ? 'border-indigo-200 bg-indigo-50/60 text-indigo-700'
 : 'border-slate-200 text-slate-600 bg-slate-50/50'
 }`}
 >
 <div className="flex items-center gap-2">
 <QrCode className="w-4 h-4" />
 <span className="text-xs font-semibold">{isBn ? BN_DICT['verify_qr'] : EN_DICT['verify_qr']}</span>
 </div>
 <div className={`w-4 h-4 rounded-full flex items-center justify-center border ${formData.showQrCode !== false ? 'bg-indigo-600 border-indigo-600 text-white' : 'border-slate-300'}`}>
 {formData.showQrCode !== false && <Check className="w-2.5 h-2.5" />}
 </div>
 </button>

 {/* Signature toggle */}
 <button
 type="button"
 onClick={() => handleChange('showSignature', !formData.showSignature)}
 className={`p-2.5 rounded-xl border flex items-center justify-between transition-all ${
 formData.showSignature !== false
 ? 'border-indigo-200 bg-indigo-50/60 text-indigo-700'
 : 'border-slate-200 text-slate-600 bg-slate-50/50'
 }`}
 >
 <div className="flex items-center gap-2">
 <PenTool className="w-4 h-4" />
 <span className="text-xs font-semibold">{isBn ? BN_DICT['signature_block'] : EN_DICT['signature_block']}</span>
 </div>
 <div className={`w-4 h-4 rounded-full flex items-center justify-center border ${formData.showSignature !== false ? 'bg-indigo-600 border-indigo-600 text-white' : 'border-slate-300'}`}>
 {formData.showSignature !== false && <Check className="w-2.5 h-2.5" />}
 </div>
 </button>
 </div>
 </div>

 {/* Section 3: Font Sizes */}
 <div className="space-y-3">
 <div className="flex items-center gap-2 text-slate-800 font-bold text-xs border-b border-slate-100 pb-1.5">
 <Type className="w-4 h-4 text-indigo-600" />
 <span>{isBn ? BN_DICT['typography_font_sizes'] : EN_DICT['typography_font_sizes']}</span>
 </div>

 <div className="space-y-3">
 {/* Institution Name */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['institution_name'] : EN_DICT['institution_name']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.instNameFontSize || 25}px
 </span>
 </div>
 <input
 type="range"
 min={18}
 max={34}
 value={formData.instNameFontSize || 25}
 onChange={(e) => handleChange('instNameFontSize', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>

 {/* Certificate Title */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['certificate_title'] : EN_DICT['certificate_title']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.titleFontSize || 28}px
 </span>
 </div>
 <input
 type="range"
 min={20}
 max={38}
 value={formData.titleFontSize || 28}
 onChange={(e) => handleChange('titleFontSize', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>

 {/* Body Font Size */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['body_text'] : EN_DICT['body_text']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.bodyFontSize || 16}px
 </span>
 </div>
 <input
 type="range"
 min={13}
 max={20}
 value={formData.bodyFontSize || 16}
 onChange={(e) => handleChange('bodyFontSize', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>

 {/* Closing Sentence */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['closing_blessing'] : EN_DICT['closing_blessing']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.closingFontSize || 18}px
 </span>
 </div>
 <input
 type="range"
 min={14}
 max={24}
 value={formData.closingFontSize || 18}
 onChange={(e) => handleChange('closingFontSize', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>
 </div>
 </div>

 {/* Section 4: Spacing & Line Height */}
 <div className="space-y-3">
 <div className="flex items-center gap-2 text-slate-800 font-bold text-xs border-b border-slate-100 pb-1.5">
 <MoveVertical className="w-4 h-4 text-indigo-600" />
 <span>{isBn ? BN_DICT['spacing_line_heights'] : EN_DICT['spacing_line_heights']}</span>
 </div>

 <div className="space-y-3">
 {/* Body Line Height */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['line_height'] : EN_DICT['line_height']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.bodyLineHeight || 2.25}x
 </span>
 </div>
 <input
 type="range"
 min={1.8}
 max={2.8}
 step={0.05}
 value={formData.bodyLineHeight || 2.25}
 onChange={(e) => handleChange('bodyLineHeight', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>

 {/* Paragraph Spacing */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['paragraph_spacing'] : EN_DICT['paragraph_spacing']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.paragraphSpacing || 14}px
 </span>
 </div>
 <input
 type="range"
 min={8}
 max={28}
 value={formData.paragraphSpacing || 14}
 onChange={(e) => handleChange('paragraphSpacing', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>

 {/* Title Top Space */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['title_top_space'] : EN_DICT['title_top_space']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.titleTopSpace || 24}px
 </span>
 </div>
 <input
 type="range"
 min={10}
 max={45}
 value={formData.titleTopSpace || 24}
 onChange={(e) => handleChange('titleTopSpace', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>

 {/* Closing Top Space */}
 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['closing_blessing_space'] : EN_DICT['closing_blessing_space']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.closingTopSpace || 20}px
 </span>
 </div>
 <input
 type="range"
 min={8}
 max={40}
 value={formData.closingTopSpace || 20}
 onChange={(e) => handleChange('closingTopSpace', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>
 </div>
 </div>

 {/* Section 5: Page Margins */}
 <div className="space-y-3">
 <div className="flex items-center gap-2 text-slate-800 font-bold text-xs border-b border-slate-100 pb-1.5">
 <FileSpreadsheet className="w-4 h-4 text-indigo-600" />
 <span>{isBn ? BN_DICT['page_margin'] : EN_DICT['page_margin']}</span>
 </div>

 <div className="bg-slate-50/80 p-3 rounded-xl border border-slate-200/80">
 <div className="flex justify-between items-center mb-1.5">
 <label className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['outer_margin_inches'] : EN_DICT['outer_margin_inches']}
 </label>
 <span className="text-[11px] font-bold text-indigo-700 bg-indigo-50 px-2 py-0.5 rounded">
 {formData.pageMargin || 0.45} in
 </span>
 </div>
 <input
 type="range"
 min={0.3}
 max={0.7}
 step={0.05}
 value={formData.pageMargin || 0.45}
 onChange={(e) => handleChange('pageMargin', Number(e.target.value))}
 className="w-full h-1.5 bg-slate-200 rounded-lg appearance-none cursor-pointer accent-indigo-600"
 />
 </div>
 </div>
 </div>

 {/* Footer Actions */}
 <div className="p-4 border-t border-slate-200 bg-slate-50 flex items-center justify-between gap-2">
 <button
 type="button"
 onClick={handleReset}
 className="flex items-center gap-1.5 text-xs font-semibold text-slate-600 hover:text-slate-900 bg-white hover:bg-slate-100 border border-slate-200 px-3 py-2 rounded-xl transition-colors shadow-2xs"
 >
 <RotateCcw className="w-3.5 h-3.5" />
 <span>{isBn ? BN_DICT['reset'] : EN_DICT['reset']}</span>
 </button>

 <div className="flex items-center gap-2">
 <button
 type="button"
 onClick={handleSaveDefault}
 className="flex items-center gap-1.5 text-xs font-semibold text-indigo-700 bg-indigo-50 hover:bg-indigo-100 border border-indigo-200 px-3 py-2 rounded-xl transition-colors shadow-2xs"
 >
 <Save className="w-3.5 h-3.5" />
 <span>{isBn ? BN_DICT['save_default'] : EN_DICT['save_default']}</span>
 </button>

 <button
 type="button"
 onClick={onClose}
 className="flex items-center gap-1.5 text-xs font-semibold text-white bg-slate-900 hover:bg-slate-800 px-4 py-2 rounded-xl transition-colors shadow-xs"
 >
 <Check className="w-3.5 h-3.5" />
 <span>{isBn ? BN_DICT['done'] : EN_DICT['done']}</span>
 </button>
 </div>
 </div>
 </div>
 </div>
 </div>
 );
};
