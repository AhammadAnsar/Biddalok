import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { Shield, ShieldAlert, Check, Users, UserCog, UserCheck, Key, Lock, Settings } from 'lucide-react';
import { useAppStore } from '../store/useAppStore';
import { useAuthStore } from '../store/useAuthStore';

const MODULES = [
 { id: 'dashboard', labelBn: 'ড্যাশবোর্ড', labelEn: 'Dashboard' },
 { id: 'students', labelBn: 'শিক্ষার্থী ব্যবস্থাপনা', labelEn: 'Students' },
 { id: 'academic', labelBn: 'একাডেমিক কাঠামো', labelEn: 'Academic' },
 { id: 'examination', labelBn: 'পরীক্ষা ও ফলাফল', labelEn: 'Examination' },
 { id: 'testimonial', labelBn: 'প্রশংসাপত্র', labelEn: 'Testimonial' },
 { id: 'hr', labelBn: 'শিক্ষক ও কর্মচারী (HR)', labelEn: 'Human Resources' },
 { id: 'committee', labelBn: 'কমিটি (SMC)', labelEn: 'Committee' },
 { id: 'institution', labelBn: 'প্রতিষ্ঠান সেটিংস', labelEn: 'Institution' },
 { id: 'system', labelBn: 'সিস্টেম অ্যাডমিন', labelEn: 'System Admin' }
];

export const AccessControlManager: React.FC = () => {
 const { language, staffDesignations, designationPermissions, updateDesignationPermission } = useAppStore();
 const { users, removeUser, updateUserRole, resetAuth } = useAuthStore();
 const isBn = language === 'bn';

 const [activeTab, setActiveTab] = useState<'rbac' | 'users'>('rbac');
 
 // Track selected designation for RBAC editing
 const [selectedDesignation, setSelectedDesignation] = useState<string | null>(null);
 
 // Get active permissions for selected designation
 const activePerms = designationPermissions?.find(p => p.designationId === selectedDesignation)?.allowedModules || [];

 const handleToggleModule = (moduleId: string) => {
 if (!selectedDesignation) return;
 
 let newModules = [...activePerms];
 if (newModules.includes(moduleId)) {
 newModules = newModules.filter(id => id !== moduleId);
 } else {
 newModules.push(moduleId);
 }
 
 updateDesignationPermission(selectedDesignation, newModules);
 };

 const handleSelectAll = () => {
 if (!selectedDesignation) return;
 updateDesignationPermission(selectedDesignation, MODULES.map(m => m.id));
 };

 const handleDeselectAll = () => {
 if (!selectedDesignation) return;
 updateDesignationPermission(selectedDesignation, []);
 };

 return (
 <div className="space-y-6">
 {/* Local Tabs */}
 <div className="flex bg-slate-100 dark:bg-slate-800 p-1 rounded-xl">
 <button
 onClick={() => setActiveTab('rbac')}
 className={`flex-1 flex items-center justify-center gap-2 py-2.5 rounded-lg text-sm font-bold transition-all ${
 activeTab === 'rbac' 
 ? 'bg-white dark:bg-slate-900 text-indigo-700 dark:text-indigo-400 shadow-sm' 
 : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-slate-200'
 }`}
 >
 <Shield className="w-4 h-4" />
 {isBn ? BN_DICT['role_based_access_control'] : EN_DICT['role_based_access_control']}
 </button>
 <button
 onClick={() => setActiveTab('users')}
 className={`flex-1 flex items-center justify-center gap-2 py-2.5 rounded-lg text-sm font-bold transition-all ${
 activeTab === 'users' 
 ? 'bg-white dark:bg-slate-900 text-indigo-700 dark:text-indigo-400 shadow-sm' 
 : 'text-slate-600 dark:text-slate-400 hover:text-slate-900 dark:hover:text-slate-200'
 }`}
 >
 <Users className="w-4 h-4" />
 {isBn ? BN_DICT['system_user_accounts'] : EN_DICT['system_user_accounts']}
 </button>
 </div>

 {activeTab === 'rbac' && (
 <div className="bg-white dark:bg-slate-900 rounded-2xl border border-slate-200 dark:border-slate-800 p-6 shadow-sm space-y-6">
 <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
 <div>
 <h3 className="text-lg font-bold text-slate-900 dark:text-slate-100 flex items-center gap-2">
 <Settings className="w-5 h-5 text-indigo-500" />
 {isBn ? BN_DICT['module_access_control'] : EN_DICT['module_access_control']}
 </h3>
 <p className="text-sm text-slate-500 mt-1">
 {isBn ? BN_DICT['define_which_system_modules_ca'] : EN_DICT['define_which_system_modules_ca']}
 </p>
 </div>
 </div>

 <div className="grid grid-cols-1 md:grid-cols-3 gap-6">
 {/* Designations List */}
 <div className="md:col-span-1 border border-slate-200 dark:border-slate-800 rounded-xl overflow-hidden flex flex-col h-[400px]">
 <div className="bg-slate-50 dark:bg-slate-800/50 p-3 border-b border-slate-200 dark:border-slate-800">
 <h4 className="font-bold text-sm text-slate-700 dark:text-slate-300">
 {isBn ? BN_DICT['select_designation'] : EN_DICT['select_designation']}
 </h4>
 </div>
 <div className="overflow-y-auto flex-1 p-2 space-y-1">
 {staffDesignations?.map(desig => {
 const isSelected = selectedDesignation === desig.id;
 const permsCount = designationPermissions?.find(p => p.designationId === desig.id)?.allowedModules?.length || 0;
 
 return (
 <button
 key={desig.id}
 onClick={() => setSelectedDesignation(desig.id)}
 className={`w-full flex items-center justify-between p-3 rounded-lg text-left transition-all ${
 isSelected 
 ? 'bg-indigo-50 dark:bg-indigo-900/30 border border-indigo-200 dark:border-indigo-800' 
 : 'hover:bg-slate-50 dark:hover:bg-slate-800 border border-transparent'
 }`}
 >
 <div>
 <span className={`block text-sm font-bold ${isSelected ? 'text-indigo-700 dark:text-indigo-400' : 'text-slate-700 dark:text-slate-300'}`}>
 {isBn ? desig.nameBn : desig.name}
 </span>
 <span className="text-xs text-slate-500 font-mono mt-0.5 block capitalize">{desig.staffType}</span>
 </div>
 <span className={`text-[10px] font-bold px-2 py-1 rounded-full ${
 permsCount > 0 
 ? 'bg-emerald-100 text-emerald-700 dark:bg-emerald-900/50 dark:text-emerald-400' 
 : 'bg-slate-100 text-slate-500 dark:bg-slate-800 dark:text-slate-400'
 }`}>
 {permsCount} modules
 </span>
 </button>
 );
 })}
 </div>
 </div>

 {/* Permissions Checkboxes */}
 <div className="md:col-span-2 border border-slate-200 dark:border-slate-800 rounded-xl overflow-hidden flex flex-col h-[400px]">
 <div className="bg-slate-50 dark:bg-slate-800/50 p-3 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
 <h4 className="font-bold text-sm text-slate-700 dark:text-slate-300">
 {isBn ? BN_DICT['allowed_modules'] : EN_DICT['allowed_modules']}
 </h4>
 {selectedDesignation && (
 <div className="flex gap-2">
 <button onClick={handleSelectAll} className="text-xs text-indigo-600 font-bold hover:underline">
 {isBn ? BN_DICT['select_all'] : EN_DICT['select_all']}
 </button>
 <span className="text-slate-300">|</span>
 <button onClick={handleDeselectAll} className="text-xs text-rose-600 font-bold hover:underline">
 {isBn ? BN_DICT['deselect_all'] : EN_DICT['deselect_all']}
 </button>
 </div>
 )}
 </div>
 
 <div className="p-4 flex-1 overflow-y-auto bg-slate-50/30 dark:bg-slate-900/50">
 {!selectedDesignation ? (
 <div className="h-full flex flex-col items-center justify-center text-slate-400 space-y-3">
 <UserCog className="w-12 h-12 text-slate-300 dark:text-slate-700" />
 <p className="text-sm font-medium">{isBn ? BN_DICT['select_a_designation_from_the'] : EN_DICT['select_a_designation_from_the']}</p>
 </div>
 ) : (
 <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
 {MODULES.map(mod => {
 const hasAccess = activePerms.includes(mod.id);
 return (
 <label 
 key={mod.id} 
 className={`flex items-start gap-3 p-3 rounded-xl border cursor-pointer transition-all ${
 hasAccess 
 ? 'bg-emerald-50/50 dark:bg-emerald-900/20 border-emerald-200 dark:border-emerald-800' 
 : 'bg-white dark:bg-slate-800 border-slate-200 dark:border-slate-700 hover:border-slate-300'
 }`}
 >
 <div className={`mt-0.5 w-5 h-5 rounded flex items-center justify-center shrink-0 border ${
 hasAccess 
 ? 'bg-emerald-500 border-emerald-600 text-white' 
 : 'bg-white dark:bg-slate-900 border-slate-300 dark:border-slate-600'
 }`}>
 {hasAccess && <Check className="w-3.5 h-3.5" />}
 </div>
 <input 
 type="checkbox" 
 className="sr-only" 
 checked={hasAccess}
 onChange={() => handleToggleModule(mod.id)}
 />
 <div>
 <span className={`block text-sm font-bold ${hasAccess ? 'text-emerald-900 dark:text-emerald-100' : 'text-slate-700 dark:text-slate-300'}`}>
 {isBn ? mod.labelBn : mod.labelEn}
 </span>
 <span className="text-xs text-slate-500 font-mono mt-0.5 block">{mod.id}</span>
 </div>
 </label>
 );
 })}
 </div>
 )}
 </div>
 </div>
 </div>
 </div>
 )}

 {activeTab === 'users' && (
 <div className="bg-white dark:bg-slate-900 rounded-2xl border border-slate-200 dark:border-slate-800 overflow-hidden shadow-sm">
 <div className="p-6 border-b border-slate-200 dark:border-slate-800 flex items-center justify-between">
 <div>
 <h3 className="text-lg font-bold text-slate-900 dark:text-slate-100 flex items-center gap-2">
 <Users className="w-5 h-5 text-indigo-500" />
 {isBn ? BN_DICT['admins_users_list'] : EN_DICT['admins_users_list']}
 </h3>
 </div>
 </div>
 <div className="overflow-x-auto">
 <table className="w-full text-left border-collapse">
 <thead>
 <tr className="bg-slate-50 dark:bg-slate-800/50 border-b border-slate-200 dark:border-slate-800">
 <th className="py-3 px-4 text-xs font-bold text-slate-500 uppercase tracking-wider">{isBn ? BN_DICT['name'] : EN_DICT['name']}</th>
 <th className="py-3 px-4 text-xs font-bold text-slate-500 uppercase tracking-wider">{isBn ? BN_DICT['username'] : EN_DICT['username']}</th>
 <th className="py-3 px-4 text-xs font-bold text-slate-500 uppercase tracking-wider">{isBn ? BN_DICT['role'] : EN_DICT['role']}</th>
 <th className="py-3 px-4 text-xs font-bold text-slate-500 uppercase tracking-wider text-right">{isBn ? BN_DICT['action'] : EN_DICT['action']}</th>
 </tr>
 </thead>
 <tbody className="divide-y divide-slate-200 dark:divide-slate-800">
 {users.map(u => (
 <tr key={u.id} className="hover:bg-slate-50 dark:hover:bg-slate-800/30 transition-colors">
 <td className="py-3 px-4">
 <div className="font-bold text-sm text-slate-900 dark:text-slate-100">{u.name}</div>
 </td>
 <td className="py-3 px-4">
 <div className="font-mono text-sm text-indigo-600 dark:text-indigo-400 bg-indigo-50 dark:bg-indigo-900/30 inline-block px-2 py-0.5 rounded">
 {u.username}
 </div>
 </td>
 <td className="py-3 px-4">
 <select 
 value={u.role}
 onChange={(e) => updateUserRole(u.id, e.target.value as any)}
 disabled={u.username === 'admin'}
 className="text-xs font-bold bg-white dark:bg-slate-900 border border-slate-300 dark:border-slate-700 rounded px-2 py-1 outline-none focus:ring-1 focus:ring-indigo-500 disabled:opacity-50"
 >
 <option value="admin">Admin</option>
 <option value="teacher">Teacher</option>
 <option value="accountant">Accountant</option>
 <option value="staff">Staff</option>
 </select>
 </td>
 <td className="py-3 px-4 text-right">
 {u.username !== 'admin' && (
 <button
 onClick={() => {
 if(window.confirm(isBn ? BN_DICT['are_you_sure'] : EN_DICT['are_you_sure'])) {
 removeUser(u.id);
 }
 }}
 className="text-xs font-bold text-rose-600 bg-rose-50 hover:bg-rose-100 px-3 py-1.5 rounded-lg transition-colors"
 >
 {isBn ? BN_DICT['remove'] : EN_DICT['remove']}
 </button>
 )}
 </td>
 </tr>
 ))}
 </tbody>
 </table>
 </div>
 </div>
 )}
 </div>
 );
};
