import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useEffect, useMemo } from 'react';
import { 
 X, 
 ArrowRightLeft, 
 ArrowRight, 
 Users, 
 CheckCircle2, 
 Layers, 
 GitFork, 
 BookmarkCheck, 
 Calendar, 
 Sparkles, 
 Search, 
 CheckSquare, 
 Square, 
 AlertCircle,
 Hash,
 Filter
} from 'lucide-react';
import toast from 'react-hot-toast';
import { useAppStore } from '../store/useAppStore';
import { Student, AcademicClass, AcademicGroup, AcademicSection } from '../types';
import { 
 isClassMatch, 
 isSectionMatch, 
 isGroupMatch, 
 isSessionMatch, 
 findClass, 
 findGroup, 
 findSection, 
 findSession, 
 linkStudentIds 
} from '../utils/academicRelations';

interface StudentTransferModalProps {
 isOpen: boolean;
 onClose: () => void;
 initialStudent?: Student | null;
 initialSelectedStudentIds?: string[];
}

export const StudentTransferModal: React.FC<StudentTransferModalProps> = ({
 isOpen,
 onClose,
 initialStudent,
 initialSelectedStudentIds
}) => {
 const language = useAppStore(state => state.language);
 const students = useAppStore(state => state.students);
 const academicSessions = useAppStore(state => state.academicSessions);
 const academicClasses = useAppStore(state => state.academicClasses);
 const academicGroups = useAppStore(state => state.academicGroups);
 const academicSections = useAppStore(state => state.academicSections);
 const bulkUpdateStudents = useAppStore(state => state.bulkUpdateStudents);

 const isBn = language === 'bn';

 const classesList: AcademicClass[] = useMemo(() => Array.isArray(academicClasses) ? academicClasses : [], [academicClasses]);
 const groupsList: AcademicGroup[] = useMemo(() => Array.isArray(academicGroups) ? academicGroups : [], [academicGroups]);
 const sectionsList: AcademicSection[] = useMemo(() => Array.isArray(academicSections) ? academicSections : [], [academicSections]);
 const studentList: Student[] = useMemo(() => Array.isArray(students) ? students : [], [students]);

 // Active Mode: 'batch' (Filter & migrate) or 'single' (Individual student)
 const [transferMode, setTransferMode] = useState<'batch' | 'single'>('batch');

 // Available sessions & years in DB
 const availableSessions = useMemo(() => {
 const sSet = new Set<string>();
 const currentYr = new Date().getFullYear();
 sSet.add(currentYr.toString());
 sSet.add((currentYr + 1).toString());
 sSet.add((currentYr - 1).toString());
 (academicSessions || []).forEach(as => {
 if (as.name) sSet.add(as.name);
 if (as.nameBn) sSet.add(as.nameBn);
 });
 studentList.forEach(s => {
 if (s.session) sSet.add(s.session);
 });
 return Array.from(sSet);
 }, [studentList, academicSessions]);

 const availableYears = useMemo(() => {
 const ySet = new Set<string>();
 const currentYr = new Date().getFullYear();
 for (let y = currentYr - 5; y <= currentYr + 2; y++) {
 ySet.add(y.toString());
 }
 studentList.forEach(s => {
 if (s.year) ySet.add(s.year);
 if (s.admissionYear) ySet.add(s.admissionYear);
 });
 return Array.from(ySet).sort((a, b) => b.localeCompare(a));
 }, [studentList]);

 // Source Filters for Batch Mode (5 controls: Year, Session, Class, Group, Section)
 const [sourceYear, setSourceYear] = useState<string>('all');
 const [sourceSession, setSourceSession] = useState<string>('all');
 const [sourceClass, setSourceClass] = useState<string>('all');
 const [sourceGroup, setSourceGroup] = useState<string>('all');
 const [sourceSection, setSourceSection] = useState<string>('all');

 // Destination Targets (5 controls: Year, Session, Class, Group, Section)
 const [targetYear, setTargetYear] = useState<string>('');
 const [targetSession, setTargetSession] = useState<string>('');
 const [targetClass, setTargetClass] = useState<string>('');
 const [targetGroup, setTargetGroup] = useState<string>('');
 const [targetSection, setTargetSection] = useState<string>('');

 // Roll Reassignment Options: 'keep' | 'auto_1' | 'custom_start'
 const [rollOption, setRollOption] = useState<'keep' | 'auto_1' | 'custom_start'>('keep');
 const [customStartRoll, setCustomStartRoll] = useState<number>(1);

 // Selected Student IDs for Transfer
 const [selectedIds, setSelectedIds] = useState<Set<string>>(new Set());
 const [searchTerm, setSearchTerm] = useState('');
 const [isProcessing, setIsProcessing] = useState(false);
 const [successMessage, setSuccessMessage] = useState<string | null>(null);

 // Single Student Mode State
 const [singleStudent, setSingleStudent] = useState<Student | null>(null);
 const [singleYear, setSingleYear] = useState<string>('');
 const [singleRoll, setSingleRoll] = useState<string>('');

 useEffect(() => {
 if (isOpen) {
 setSuccessMessage(null);
 setIsProcessing(false);
 setSearchTerm('');

 const defaultClass = classesList.find(c => c.isDefault)?.name || classesList[0]?.name || 'Class 6';
 const defaultGroup = groupsList.find(g => g.isDefault)?.name || groupsList[0]?.name || 'General';
 const defaultSection = sectionsList.find(s => s.isDefault)?.name || sectionsList[0]?.name || 'Section A';
 const defaultSessionObj = (academicSessions || []).find(s => s.isDefault) || academicSessions?.[0];
 const defaultSessionName = defaultSessionObj?.name || new Date().getFullYear().toString();
 const currentYrStr = new Date().getFullYear().toString();

 if (initialStudent) {
 setTransferMode('single');
 setSingleStudent(initialStudent);
 setSingleRoll(initialStudent.roll || '1');
 setSingleYear(initialStudent.year || initialStudent.admissionYear || currentYrStr);
 setTargetYear(initialStudent.year || initialStudent.admissionYear || currentYrStr);
 setTargetSession(initialStudent.session || defaultSessionName);
 setTargetClass(initialStudent.class || defaultClass);
 setTargetGroup(initialStudent.group || defaultGroup);
 setTargetSection(initialStudent.section || defaultSection);
 } else {
 setTransferMode('batch');
 setSingleStudent(null);
 setSourceYear('all');
 setSourceSession('all');
 setSourceClass('all');
 setSourceGroup('all');
 setSourceSection('all');

 setTargetYear(currentYrStr);
 setTargetSession(defaultSessionName);
 setTargetClass(defaultClass);
 setTargetGroup(defaultGroup);
 setTargetSection(defaultSection);

 if (initialSelectedStudentIds && initialSelectedStudentIds.length > 0) {
 setSelectedIds(new Set(initialSelectedStudentIds));
 } else {
 setSelectedIds(new Set());
 }
 }
 }
 }, [isOpen, initialStudent, initialSelectedStudentIds, classesList, groupsList, sectionsList, academicSessions]);

 // Filtered Source Students
 const eligibleSourceStudents = useMemo(() => {
 return studentList.filter(s => {
 if (sourceYear !== 'all') {
 const studYr = s.year || s.admissionYear;
 if (studYr && studYr !== sourceYear) return false;
 }
 if (sourceSession !== 'all' && !isSessionMatch(s, sourceSession, academicSessions || [])) return false;
 if (sourceClass !== 'all' && !isClassMatch(s, sourceClass, classesList)) return false;
 if (sourceGroup !== 'all' && !isGroupMatch(s, sourceGroup, groupsList)) return false;
 if (sourceSection !== 'all' && !isSectionMatch(s, sourceSection, sectionsList)) return false;

 if (!searchTerm.trim()) return true;
 const term = searchTerm.toLowerCase();
 return (
 (s.name && s.name.toLowerCase().includes(term)) ||
 (s.nameBn && s.nameBn.includes(term)) ||
 (s.roll && s.roll.includes(term)) ||
 (s.studentId && s.studentId.toLowerCase().includes(term))
 );
 });
 }, [studentList, sourceYear, sourceSession, sourceClass, sourceGroup, sourceSection, searchTerm, classesList, groupsList, sectionsList, academicSessions]);

 // When source filter changes and no pre-selection, auto-select all eligible students
 useEffect(() => {
 if (transferMode === 'batch' && !initialSelectedStudentIds?.length) {
 setSelectedIds(new Set(eligibleSourceStudents.map(s => s.id)));
 }
 }, [sourceYear, sourceSession, sourceClass, sourceGroup, sourceSection, eligibleSourceStudents.length, transferMode]);

 const handleToggleSelectAll = () => {
 if (selectedIds.size === eligibleSourceStudents.length) {
 setSelectedIds(new Set());
 } else {
 setSelectedIds(new Set(eligibleSourceStudents.map(s => s.id)));
 }
 };

 const handleToggleStudent = (id: string) => {
 setSelectedIds(prev => {
 const next = new Set(prev);
 if (next.has(id)) next.delete(id);
 else next.add(id);
 return next;
 });
 };

 // Execution: Batch Transfer
 const handleExecuteBatchTransfer = () => {
 if (selectedIds.size === 0) return;
 if (!targetClass) {
 toast.error(isBn ? BN_DICT['please_select_target_class'] : EN_DICT['please_select_target_class']);
 return;
 }

 setIsProcessing(true);

 const studentsToUpdate: Student[] = [];
 const selectedArray = studentList.filter(s => selectedIds.has(s.id));

 // Sort by roll ascending if auto renumbering
 if (rollOption === 'auto_1' || rollOption === 'custom_start') {
 selectedArray.sort((a, b) => (parseInt(a.roll) || 0) - (parseInt(b.roll) || 0));
 }

 const currentRollSeq = rollOption === 'custom_start' ? customStartRoll : 1;

 const matchedClass = findClass(targetClass, classesList);
 const matchedGroup = findGroup(targetGroup, groupsList);
 const matchedSection = findSection(targetSection, sectionsList);
 const matchedSession = findSession(targetSession, academicSessions || []);

 selectedArray.forEach((student, index) => {
 let newRoll = student.roll;
 if (rollOption === 'auto_1') {
 newRoll = (index + 1).toString();
 } else if (rollOption === 'custom_start') {
 newRoll = (currentRollSeq + index).toString();
 }

 const raw = {
 ...student,
 year: targetYear || student.year || student.admissionYear,
 admissionYear: targetYear || student.admissionYear || student.year,
 session: targetSession || student.session,
 sessionId: matchedSession?.id || student.sessionId,
 class: targetClass,
 classId: matchedClass?.id || student.classId,
 group: targetGroup || student.group,
 groupId: matchedGroup?.id || student.groupId,
 section: targetSection || student.section,
 sectionId: matchedSection?.id || student.sectionId,
 roll: newRoll
 };

 studentsToUpdate.push(linkStudentIds(raw, {
 classes: classesList,
 groups: groupsList,
 sections: sectionsList,
 sessions: academicSessions || []
 }));
 });

 bulkUpdateStudents(studentsToUpdate);
 setIsProcessing(false);
 const msg = isBn 
 ? `${studentsToUpdate.length} জন শিক্ষার্থীর সাল, সেশন, শ্রেণি, বিভাগ ও শাখা সফলভাবে স্থানান্তরিত ও মাইগ্রেট হয়েছে!`
 : `Successfully transferred ${studentsToUpdate.length} students!`;
 setSuccessMessage(msg);
 toast.success(msg);

 setTimeout(() => {
 onClose();
 }, 1400);
 };

 // Execution: Single Student Transfer
 const handleExecuteSingleTransfer = () => {
 if (!singleStudent || !targetClass) return;

 setIsProcessing(true);

 const matchedClass = findClass(targetClass, classesList);
 const matchedGroup = findGroup(targetGroup, groupsList);
 const matchedSection = findSection(targetSection, sectionsList);
 const matchedSession = findSession(targetSession, academicSessions || []);

 const updated: Student = linkStudentIds({
 ...singleStudent,
 year: targetYear || singleYear || singleStudent.year || singleStudent.admissionYear,
 admissionYear: targetYear || singleYear || singleStudent.admissionYear || singleStudent.year,
 session: targetSession || singleStudent.session,
 sessionId: matchedSession?.id || singleStudent.sessionId,
 class: targetClass,
 classId: matchedClass?.id || singleStudent.classId,
 group: targetGroup || singleStudent.group,
 groupId: matchedGroup?.id || singleStudent.groupId,
 section: targetSection || singleStudent.section,
 sectionId: matchedSection?.id || singleStudent.sectionId,
 roll: singleRoll || singleStudent.roll
 }, {
 classes: classesList,
 groups: groupsList,
 sections: sectionsList,
 sessions: academicSessions || []
 });

 bulkUpdateStudents([updated]);
 setIsProcessing(false);
 const singleMsg = isBn 
 ? `শিক্ষার্থী ${singleStudent.name}-এর স্থানান্তর সফলভাবে সম্পন্ন হয়েছে!`
 : `Student ${singleStudent.name} transferred successfully!`;
 setSuccessMessage(singleMsg);
 toast.success(singleMsg);

 setTimeout(() => {
 onClose();
 }, 1200);
 };

 if (!isOpen) return null;

 return (
 <div className="fixed inset-0 z-50 flex items-center justify-center p-2 sm:p-4 bg-slate-900/60 overflow-y-auto">
 <div className="bg-white rounded-2xl shadow-2xl w-full max-w-5xl max-h-[92vh] flex flex-col border border-slate-200 overflow-hidden my-auto">
 {/* Modal Header */}
 <div className="flex items-center justify-between px-6 py-4 border-b border-slate-200 bg-white shrink-0">
 <div className="flex items-center gap-3">
 <div className="w-10 h-10 rounded-xl bg-indigo-50 flex items-center justify-center text-indigo-600 border border-indigo-100 shadow-xs">
 <ArrowRightLeft className="w-5 h-5" />
 </div>
 <div>
 <div className="flex items-center gap-2">
 <h2 className="text-xl font-bold text-slate-800">
 {isBn ? BN_DICT['student_transfer_academic_migr'] : EN_DICT['student_transfer_academic_migr']}
 </h2>
 <span className="px-2.5 py-0.5 text-xs font-semibold rounded-full bg-indigo-50 text-indigo-700 border border-indigo-200">
 {isBn ? BN_DICT['migration_promotion'] : EN_DICT['migration_promotion']}
 </span>
 </div>
 <p className="text-xs text-slate-500">
 {isBn ? BN_DICT['transfer_and_migrate_students'] : EN_DICT['transfer_and_migrate_students']}
 </p>
 </div>
 </div>

 <div className="flex items-center gap-2">
 <button 
 onClick={onClose}
 className="p-2 hover:bg-slate-100 rounded-lg transition-colors text-slate-500 hover:text-slate-700"
 >
 <X className="w-5 h-5" />
 </button>
 </div>
 </div>

 {/* Mode Selector Tabs */}
 {!initialStudent && (
 <div className="flex border-b border-slate-200 bg-slate-50 px-6 py-2 gap-3 shrink-0">
 <button
 onClick={() => setTransferMode('batch')}
 className={`px-4 py-2 rounded-xl text-xs font-bold transition-all flex items-center gap-2 ${
 transferMode === 'batch'
 ? 'bg-indigo-600 text-white shadow-xs'
 : 'bg-white text-slate-600 hover:bg-slate-200/70 border border-slate-200'
 }`}
 >
 <Users className="w-4 h-4" />
 <span>{isBn ? BN_DICT['batch_class_migration'] : EN_DICT['batch_class_migration']}</span>
 </button>
 <button
 onClick={() => setTransferMode('single')}
 className={`px-4 py-2 rounded-xl text-xs font-bold transition-all flex items-center gap-2 ${
 transferMode === 'single'
 ? 'bg-indigo-600 text-white shadow-xs'
 : 'bg-white text-slate-600 hover:bg-slate-200/70 border border-slate-200'
 }`}
 >
 <ArrowRightLeft className="w-4 h-4" />
 <span>{isBn ? BN_DICT['individual_student_transfer'] : EN_DICT['individual_student_transfer']}</span>
 </button>
 </div>
 )}

 {/* Success Alert */}
 {successMessage && (
 <div className="mx-6 mt-4 p-3 bg-emerald-50 border border-emerald-200 text-emerald-800 text-sm font-semibold rounded-xl flex items-center gap-2 shrink-0">
 <CheckCircle2 className="w-5 h-5 text-emerald-600" />
 <span>{successMessage}</span>
 </div>
 )}

 {/* Modal Scrollable Body */}
 <div className="flex-1 overflow-y-auto p-6 space-y-6">
 {/* ===================== MODE 1: BATCH MIGRATION ===================== */}
 {transferMode === 'batch' && (
 <div className="space-y-6">
 {/* Dual Panel: Source vs Destination */}
 <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
 {/* SOURCE PANEL (5 fields: Year, Session, Class, Group, Section) */}
 <div className="bg-slate-50 p-5 rounded-2xl border border-slate-200 space-y-4">
 <div className="flex items-center justify-between text-indigo-700 font-bold text-sm border-b border-slate-200 pb-2">
 <div className="flex items-center gap-2">
 <Filter className="w-4 h-4 text-indigo-600" />
 <span>{isBn ? BN_DICT['k_1_select_source_current_positi'] : EN_DICT['k_1_select_source_current_positi']}</span>
 </div>
 <span className="text-[11px] font-normal text-slate-500 bg-white px-2 py-0.5 rounded border">
 {isBn ? BN_DICT['k_5_filters'] : EN_DICT['k_5_filters']}
 </span>
 </div>

 <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
 {/* Source Year */}
 <div>
 <label className="block text-xs font-semibold text-slate-600 mb-1">
 {isBn ? BN_DICT['source_year'] : EN_DICT['source_year']}
 </label>
 <select
 value={sourceYear}
 onChange={(e) => setSourceYear(e.target.value)}
 className="w-full bg-white border border-slate-300 rounded-xl px-3 py-2 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 <option value="all">{isBn ? BN_DICT['all_years'] : EN_DICT['all_years']}</option>
 {availableYears.map(y => <option key={y} value={y}>{y}</option>)}
 </select>
 </div>

 {/* Source Session */}
 <div>
 <label className="block text-xs font-semibold text-slate-600 mb-1">
 {isBn ? BN_DICT['source_session'] : EN_DICT['source_session']}
 </label>
 <select
 value={sourceSession}
 onChange={(e) => setSourceSession(e.target.value)}
 className="w-full bg-white border border-slate-300 rounded-xl px-3 py-2 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 <option value="all">{isBn ? BN_DICT['all_sessions'] : EN_DICT['all_sessions']}</option>
 {(academicSessions || []).map(s => (
 <option key={s.id} value={s.name}>
 {s.name} {s.nameBn ? `(${s.nameBn})` : ''}
 </option>
 ))}
 {availableSessions.filter(as => !(academicSessions || []).some(s => s.name === as)).map(s => (
 <option key={s} value={s}>{s}</option>
 ))}
 </select>
 </div>

 {/* Source Class */}
 <div>
 <label className="block text-xs font-semibold text-slate-600 mb-1">
 {isBn ? BN_DICT['source_class'] : EN_DICT['source_class']}
 </label>
 <select
 value={sourceClass}
 onChange={(e) => setSourceClass(e.target.value)}
 className="w-full bg-white border border-slate-300 rounded-xl px-3 py-2 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 <option value="all">{isBn ? BN_DICT['all_classes'] : EN_DICT['all_classes']}</option>
 {classesList.map(c => (
 <option key={c.id} value={c.name}>
 {isBn ? (c.nameBn || c.name) : c.name}
 </option>
 ))}
 </select>
 </div>

 {/* Source Group */}
 <div>
 <label className="block text-xs font-semibold text-slate-600 mb-1">
 {isBn ? BN_DICT['source_group'] : EN_DICT['source_group']}
 </label>
 <select
 value={sourceGroup}
 onChange={(e) => setSourceGroup(e.target.value)}
 className="w-full bg-white border border-slate-300 rounded-xl px-3 py-2 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 <option value="all">{isBn ? BN_DICT['all_groups'] : EN_DICT['all_groups']}</option>
 {groupsList.map(g => (
 <option key={g.id} value={g.name}>
 {isBn ? (g.nameBn || g.name) : g.name}
 </option>
 ))}
 </select>
 </div>

 {/* Source Section */}
 <div className="sm:col-span-2">
 <label className="block text-xs font-semibold text-slate-600 mb-1">
 {isBn ? BN_DICT['source_section'] : EN_DICT['source_section']}
 </label>
 <select
 value={sourceSection}
 onChange={(e) => setSourceSection(e.target.value)}
 className="w-full bg-white border border-slate-300 rounded-xl px-3 py-2 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 <option value="all">{isBn ? BN_DICT['all_sections'] : EN_DICT['all_sections']}</option>
 {sectionsList.map(s => (
 <option key={s.id} value={s.name}>
 {isBn ? (s.nameBn || s.name) : s.name}
 </option>
 ))}
 </select>
 </div>
 </div>

 <div className="pt-2 text-xs text-slate-500 flex items-center justify-between border-t border-slate-200">
 <span>{isBn ? BN_DICT['matching_students_found'] : EN_DICT['matching_students_found']}</span>
 <span className="font-bold text-slate-800 bg-white px-2 py-0.5 rounded-md border border-slate-200">
 {eligibleSourceStudents.length} {isBn ? BN_DICT['k_'] : EN_DICT['k_']}
 </span>
 </div>
 </div>

 {/* DESTINATION PANEL (5 fields: Year, Session, Class, Group, Section) */}
 <div className="bg-indigo-50/50 p-5 rounded-2xl border border-indigo-200 space-y-4">
 <div className="flex items-center justify-between text-indigo-900 font-bold text-sm border-b border-indigo-200/80 pb-2">
 <div className="flex items-center gap-2">
 <ArrowRight className="w-4 h-4 text-indigo-600" />
 <span>{isBn ? BN_DICT['k_2_target_destination_new_detai'] : EN_DICT['k_2_target_destination_new_detai']}</span>
 </div>
 <span className="text-[11px] font-normal text-indigo-700 bg-white px-2 py-0.5 rounded border border-indigo-200">
 {isBn ? BN_DICT['k_5_parameters'] : EN_DICT['k_5_parameters']}
 </span>
 </div>

 <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
 {/* Target Year */}
 <div>
 <label className="block text-xs font-semibold text-indigo-950 mb-1">
 {isBn ? BN_DICT['target_year'] : EN_DICT['target_year']} <span className="text-red-500">*</span>
 </label>
 <input
 type="text"
 value={targetYear}
 onChange={(e) => setTargetYear(e.target.value)}
 placeholder="e.g. 2026"
 className="w-full bg-white border border-indigo-300 rounded-xl px-3 py-2 text-xs font-bold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 />
 </div>

 {/* Target Session */}
 <div>
 <label className="block text-xs font-semibold text-indigo-950 mb-1">
 {isBn ? BN_DICT['target_session'] : EN_DICT['target_session']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetSession}
 onChange={(e) => setTargetSession(e.target.value)}
 className="w-full bg-white border border-indigo-300 rounded-xl px-3 py-2 text-xs font-bold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 <option value="">{isBn ? BN_DICT['select_session'] : EN_DICT['select_session']}</option>
 {(academicSessions || []).map(s => (
 <option key={s.id} value={s.name}>
 {s.name} {s.nameBn ? `(${s.nameBn})` : ''}
 </option>
 ))}
 </select>
 </div>

 {/* Target Class */}
 <div>
 <label className="block text-xs font-semibold text-indigo-950 mb-1">
 {isBn ? BN_DICT['target_class'] : EN_DICT['target_class']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetClass}
 onChange={(e) => setTargetClass(e.target.value)}
 className="w-full bg-white border border-indigo-300 rounded-xl px-3 py-2 text-xs font-bold text-indigo-900 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 {classesList.map(c => (
 <option key={c.id} value={c.name}>
 {isBn ? (c.nameBn || c.name) : c.name}
 </option>
 ))}
 </select>
 </div>

 {/* Target Group */}
 <div>
 <label className="block text-xs font-semibold text-indigo-950 mb-1">
 {isBn ? BN_DICT['target_group'] : EN_DICT['target_group']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetGroup}
 onChange={(e) => setTargetGroup(e.target.value)}
 className="w-full bg-white border border-indigo-300 rounded-xl px-3 py-2 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 {groupsList.map(g => (
 <option key={g.id} value={g.name}>
 {isBn ? (g.nameBn || g.name) : g.name}
 </option>
 ))}
 </select>
 </div>

 {/* Target Section */}
 <div className="sm:col-span-2">
 <label className="block text-xs font-semibold text-indigo-950 mb-1">
 {isBn ? BN_DICT['target_section'] : EN_DICT['target_section']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetSection}
 onChange={(e) => setTargetSection(e.target.value)}
 className="w-full bg-white border border-indigo-300 rounded-xl px-3 py-2 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 {sectionsList.map(s => (
 <option key={s.id} value={s.name}>
 {isBn ? (s.nameBn || s.name) : s.name}
 </option>
 ))}
 </select>
 </div>
 </div>

 {/* Roll Reassignment Method */}
 <div className="pt-2 border-t border-indigo-200/80">
 <label className="block text-xs font-semibold text-indigo-950 mb-1.5 flex items-center gap-1">
 <Hash className="w-3.5 h-3.5 text-indigo-600" />
 {isBn ? BN_DICT['roll_numbering_option'] : EN_DICT['roll_numbering_option']}
 </label>
 <div className="grid grid-cols-1 sm:grid-cols-3 gap-2">
 <label className={`flex items-center gap-2 p-2 rounded-lg border text-xs cursor-pointer ${rollOption === 'keep' ? 'bg-indigo-600 text-white border-indigo-600 font-bold' : 'bg-white text-slate-700 border-slate-300'}`}>
 <input type="radio" name="rollOpt" checked={rollOption === 'keep'} onChange={() => setRollOption('keep')} className="hidden" />
 <span>{isBn ? BN_DICT['keep_current_roll'] : EN_DICT['keep_current_roll']}</span>
 </label>
 <label className={`flex items-center gap-2 p-2 rounded-lg border text-xs cursor-pointer ${rollOption === 'auto_1' ? 'bg-indigo-600 text-white border-indigo-600 font-bold' : 'bg-white text-slate-700 border-slate-300'}`}>
 <input type="radio" name="rollOpt" checked={rollOption === 'auto_1'} onChange={() => setRollOption('auto_1')} className="hidden" />
 <span>{isBn ? BN_DICT['auto_1_2_3'] : EN_DICT['auto_1_2_3']}</span>
 </label>
 <label className={`flex items-center gap-2 p-2 rounded-lg border text-xs cursor-pointer ${rollOption === 'custom_start' ? 'bg-indigo-600 text-white border-indigo-600 font-bold' : 'bg-white text-slate-700 border-slate-300'}`}>
 <input type="radio" name="rollOpt" checked={rollOption === 'custom_start'} onChange={() => setRollOption('custom_start')} className="hidden" />
 <span>{isBn ? BN_DICT['custom_start_roll'] : EN_DICT['custom_start_roll']}</span>
 </label>
 </div>

 {rollOption === 'custom_start' && (
 <div className="mt-2 flex items-center gap-2 bg-white p-2 rounded-lg border border-indigo-200">
 <span className="text-xs text-slate-600">{isBn ? BN_DICT['starting_roll'] : EN_DICT['starting_roll']}</span>
 <input
 type="number"
 min="1"
 value={customStartRoll}
 onChange={(e) => setCustomStartRoll(Math.max(1, parseInt(e.target.value) || 1))}
 className="w-20 px-2 py-1 border border-slate-300 rounded text-xs font-bold text-center outline-none"
 />
 </div>
 )}
 </div>
 </div>
 </div>

 {/* Student Checklist Table */}
 <div className="bg-white rounded-2xl border border-slate-200 overflow-hidden shadow-xs">
 <div className="p-4 bg-slate-50 border-b border-slate-200 flex flex-col sm:flex-row justify-between items-start sm:items-center gap-3">
 <div className="flex items-center gap-3">
 <button
 type="button"
 onClick={handleToggleSelectAll}
 className="flex items-center gap-2 px-3 py-1.5 bg-white border border-slate-300 rounded-lg text-xs font-bold text-slate-700 hover:bg-slate-100 shadow-2xs"
 >
 {selectedIds.size === eligibleSourceStudents.length && eligibleSourceStudents.length > 0 ? (
 <CheckSquare className="w-4 h-4 text-indigo-600" />
 ) : (
 <Square className="w-4 h-4 text-slate-400" />
 )}
 <span>
 {selectedIds.size === eligibleSourceStudents.length && eligibleSourceStudents.length > 0
 ? (isBn ? BN_DICT['deselect_all'] : EN_DICT['deselect_all'])
 : (isBn ? BN_DICT['select_all'] : EN_DICT['select_all'])}
 </span>
 </button>

 <span className="text-xs font-bold text-indigo-700 bg-indigo-50 px-2.5 py-1 rounded-lg border border-indigo-100">
 {isBn 
 ? `${selectedIds.size} / ${eligibleSourceStudents.length} জন নির্বাচিত` 
 : `${selectedIds.size} of ${eligibleSourceStudents.length} selected`}
 </span>
 </div>

 <div className="relative w-full sm:w-60">
 <Search className="w-3.5 h-3.5 absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
 <input
 type="text"
 value={searchTerm}
 onChange={(e) => setSearchTerm(e.target.value)}
 placeholder={isBn ? BN_DICT['search_student'] : EN_DICT['search_student']}
 className="w-full pl-8 pr-3 py-1.5 border border-slate-300 rounded-lg text-xs outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
 />
 </div>
 </div>

 <div className="max-h-60 overflow-y-auto divide-y divide-slate-100">
 {eligibleSourceStudents.length === 0 ? (
 <div className="p-8 text-center text-slate-400 text-xs">
 {isBn ? BN_DICT['no_students_found_matching_cur'] : EN_DICT['no_students_found_matching_cur']}
 </div>
 ) : (
 eligibleSourceStudents.map(student => {
 const isSelected = selectedIds.has(student.id);
 return (
 <div
 key={student.id}
 onClick={() => handleToggleStudent(student.id)}
 className={`p-3 px-4 flex items-center justify-between cursor-pointer transition-colors ${
 isSelected ? 'bg-indigo-50/40 hover:bg-indigo-50/70' : 'hover:bg-slate-50'
 }`}
 >
 <div className="flex items-center gap-3">
 <input
 type="checkbox"
 checked={isSelected}
 onChange={() => {}} // handled by parent onClick
 className="w-4 h-4 rounded text-indigo-600 focus:ring-indigo-500 border-slate-300"
 />
 <div>
 <div className="flex items-center gap-2">
 <span className="font-bold text-slate-800 text-xs">{student.name}</span>
 {student.nameBn && (
 <span className="text-[11px] text-slate-500">({student.nameBn})</span>
 )}
 </div>
 <div className="flex items-center gap-2 text-[11px] text-slate-500 mt-0.5">
 <span>{isBn ? BN_DICT['id'] : EN_DICT['id']} {student.studentId}</span>
 <span>•</span>
 <span>{isBn ? BN_DICT['class_1'] : EN_DICT['class_1']} {student.class}</span>
 <span>•</span>
 <span>{isBn ? BN_DICT['group_1'] : EN_DICT['group_1']} {student.group || '-'}</span>
 <span>•</span>
 <span>{isBn ? BN_DICT['section_1'] : EN_DICT['section_1']} {student.section || '-'}</span>
 </div>
 </div>
 </div>

 <div className="text-right">
 <span className="inline-flex items-center px-2.5 py-0.5 rounded-full bg-slate-100 text-slate-700 font-bold text-xs border border-slate-200">
 {isBn ? BN_DICT['roll_1'] : EN_DICT['roll_1']} {student.roll || '-'}
 </span>
 </div>
 </div>
 );
 })
 )}
 </div>
 </div>
 </div>
 )}

 {/* ===================== MODE 2: SINGLE STUDENT TRANSFER ===================== */}
 {transferMode === 'single' && (
 <div className="space-y-6 max-w-2xl mx-auto">
 {!initialStudent && (
 <div className="bg-slate-50 p-4 rounded-2xl border border-slate-200">
 <label className="block text-xs font-semibold text-slate-700 mb-1.5">
 {isBn ? BN_DICT['select_student_to_transfer'] : EN_DICT['select_student_to_transfer']}
 </label>
 <select
 value={singleStudent?.id || ''}
 onChange={(e) => {
 const found = studentList.find(s => s.id === e.target.value);
 if (found) {
 setSingleStudent(found);
 setSingleRoll(found.roll || '1');
 setTargetClass(found.class || classesList[0]?.name || 'Class 6');
 setTargetGroup(found.group || groupsList[0]?.name || 'General');
 setTargetSection(found.section || sectionsList[0]?.name || 'Section A');
 setTargetSession(found.session || new Date().getFullYear().toString());
 }
 }}
 className="w-full bg-white border border-slate-300 rounded-xl px-3 py-2.5 text-xs font-semibold text-slate-800 outline-none focus:ring-2 focus:ring-indigo-500"
 >
 <option value="">{isBn ? BN_DICT['choose_a_student'] : EN_DICT['choose_a_student']}</option>
 {studentList.map(s => (
 <option key={s.id} value={s.id}>
 {s.name} ({s.studentId}) - {s.class} • {s.group ? `${s.group} / ` : ''}{s.section || ''} (Roll: {s.roll || '-'})
 </option>
 ))}
 </select>
 </div>
 )}

 {singleStudent && (
 <div className="bg-white p-6 rounded-2xl border border-slate-200 shadow-sm space-y-6">
 {/* Current Summary Card */}
 <div className="bg-slate-50 p-4 rounded-xl border border-slate-200">
 <div className="flex items-center justify-between mb-2">
 <span className="text-xs font-bold uppercase text-slate-500">{isBn ? BN_DICT['current_position_info'] : EN_DICT['current_position_info']}</span>
 <span className="text-xs font-mono font-bold text-indigo-600 bg-white px-2 py-0.5 rounded border border-slate-200">ID: {singleStudent.studentId}</span>
 </div>
 <h3 className="font-bold text-base text-slate-800">{singleStudent.name} {singleStudent.nameBn ? `(${singleStudent.nameBn})` : ''}</h3>
 <div className="grid grid-cols-2 sm:grid-cols-3 gap-2.5 mt-3 text-xs text-slate-600">
 <div className="bg-white p-2 rounded-lg border border-slate-200">
 <span className="text-slate-400 block text-[10px]">{isBn ? BN_DICT['year_1'] : EN_DICT['year_1']}</span> 
 <span className="font-semibold text-slate-800">{singleStudent.year || singleStudent.admissionYear || '-'}</span>
 </div>
 <div className="bg-white p-2 rounded-lg border border-slate-200">
 <span className="text-slate-400 block text-[10px]">{isBn ? BN_DICT['session_1'] : EN_DICT['session_1']}</span> 
 <span className="font-semibold text-slate-800">{singleStudent.session || '-'}</span>
 </div>
 <div className="bg-white p-2 rounded-lg border border-slate-200">
 <span className="text-slate-400 block text-[10px]">{isBn ? BN_DICT['class_1'] : EN_DICT['class_1']}</span> 
 <span className="font-semibold text-slate-800">{singleStudent.class || '-'}</span>
 </div>
 <div className="bg-white p-2 rounded-lg border border-slate-200">
 <span className="text-slate-400 block text-[10px]">{isBn ? BN_DICT['group_1'] : EN_DICT['group_1']}</span> 
 <span className="font-semibold text-slate-800">{singleStudent.group || '-'}</span>
 </div>
 <div className="bg-white p-2 rounded-lg border border-slate-200">
 <span className="text-slate-400 block text-[10px]">{isBn ? BN_DICT['section_1'] : EN_DICT['section_1']}</span> 
 <span className="font-semibold text-slate-800">{singleStudent.section || '-'}</span>
 </div>
 <div className="bg-white p-2 rounded-lg border border-slate-200">
 <span className="text-slate-400 block text-[10px]">{isBn ? BN_DICT['roll_1'] : EN_DICT['roll_1']}</span> 
 <span className="font-semibold text-slate-800">{singleStudent.roll || '-'}</span>
 </div>
 </div>
 </div>

 {/* Transfer Destination Form */}
 <div className="space-y-4">
 <h4 className="text-sm font-bold text-indigo-900 border-b border-indigo-100 pb-2">
 {isBn ? BN_DICT['set_new_destination_details_ro'] : EN_DICT['set_new_destination_details_ro']}
 </h4>

 <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
 {/* Target Year */}
 <div>
 <label className="block text-xs font-semibold text-slate-700 mb-1">
 {isBn ? BN_DICT['new_year'] : EN_DICT['new_year']} <span className="text-red-500">*</span>
 </label>
 <input
 type="text"
 value={targetYear}
 onChange={(e) => setTargetYear(e.target.value)}
 className="w-full border border-slate-300 rounded-xl px-3 py-2 text-xs font-bold outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
 placeholder="e.g. 2026"
 />
 </div>

 {/* Target Session */}
 <div>
 <label className="block text-xs font-semibold text-slate-700 mb-1">
 {isBn ? BN_DICT['new_session'] : EN_DICT['new_session']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetSession}
 onChange={(e) => setTargetSession(e.target.value)}
 className="w-full border border-slate-300 rounded-xl px-3 py-2 text-xs font-bold outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
 >
 <option value="">{isBn ? BN_DICT['select_session'] : EN_DICT['select_session']}</option>
 {(academicSessions || []).map(s => (
 <option key={s.id} value={s.name}>
 {s.name} {s.nameBn ? `(${s.nameBn})` : ''}
 </option>
 ))}
 </select>
 </div>

 {/* Target Class */}
 <div>
 <label className="block text-xs font-semibold text-slate-700 mb-1">
 {isBn ? BN_DICT['new_class'] : EN_DICT['new_class']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetClass}
 onChange={(e) => setTargetClass(e.target.value)}
 className="w-full border border-slate-300 rounded-xl px-3 py-2 text-xs font-bold outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
 >
 {classesList.map(c => (
 <option key={c.id} value={c.name}>
 {isBn ? (c.nameBn || c.name) : c.name}
 </option>
 ))}
 </select>
 </div>

 {/* Target Group */}
 <div>
 <label className="block text-xs font-semibold text-slate-700 mb-1">
 {isBn ? BN_DICT['new_group'] : EN_DICT['new_group']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetGroup}
 onChange={(e) => setTargetGroup(e.target.value)}
 className="w-full border border-slate-300 rounded-xl px-3 py-2 text-xs font-semibold outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
 >
 {groupsList.map(g => (
 <option key={g.id} value={g.name}>
 {isBn ? (g.nameBn || g.name) : g.name}
 </option>
 ))}
 </select>
 </div>

 {/* Target Section */}
 <div>
 <label className="block text-xs font-semibold text-slate-700 mb-1">
 {isBn ? BN_DICT['new_section'] : EN_DICT['new_section']} <span className="text-red-500">*</span>
 </label>
 <select
 value={targetSection}
 onChange={(e) => setTargetSection(e.target.value)}
 className="w-full border border-slate-300 rounded-xl px-3 py-2 text-xs font-semibold outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
 >
 {sectionsList.map(s => (
 <option key={s.id} value={s.name}>
 {isBn ? (s.nameBn || s.name) : s.name}
 </option>
 ))}
 </select>
 </div>

 <div>
 <label className="block text-xs font-semibold text-slate-700 mb-1">
 {isBn ? BN_DICT['new_roll_number'] : EN_DICT['new_roll_number']} <span className="text-red-500">*</span>
 </label>
 <input
 type="text"
 value={singleRoll}
 onChange={(e) => setSingleRoll(e.target.value)}
 className="w-full border border-slate-300 rounded-xl px-3 py-2 text-xs font-bold outline-none focus:ring-2 focus:ring-indigo-500 bg-white"
 placeholder="e.g. 1"
 />
 </div>
 </div>
 </div>
 </div>
 )}
 </div>
 )}
 </div>

 {/* Modal Footer */}
 <div className="p-4 border-t border-slate-200 bg-slate-50 flex items-center justify-between gap-3 shrink-0">
 <div className="text-xs text-slate-500">
 {transferMode === 'batch' ? (
 <span>
 {isBn 
 ? `নির্বাচিত ${selectedIds.size} জন শিক্ষার্থীকে (${targetClass}${targetGroup ? ` • ${targetGroup}` : ''}${targetSection ? ` • ${targetSection}` : ''}) এ স্থানান্তর করা হবে`
 : `Migrating ${selectedIds.size} students to (${targetClass}${targetGroup ? ` • ${targetGroup}` : ''}${targetSection ? ` • ${targetSection}` : ''})`}
 </span>
 ) : (
 <span>{isBn ? BN_DICT['student_profile_will_be_update'] : EN_DICT['student_profile_will_be_update']}</span>
 )}
 </div>

 <div className="flex items-center gap-3">
 <button
 onClick={onClose}
 className="px-4 py-2 text-slate-600 font-medium hover:bg-slate-200 bg-slate-100 rounded-xl transition-colors text-sm"
 >
 {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
 </button>

 {transferMode === 'batch' ? (
 <button
 onClick={handleExecuteBatchTransfer}
 disabled={isProcessing || selectedIds.size === 0 || !targetClass}
 className="px-6 py-2 bg-indigo-600 hover:bg-indigo-700 text-white font-medium rounded-xl transition-colors flex items-center gap-2 disabled:opacity-50 text-sm shadow-sm"
 >
 <ArrowRightLeft className="w-4 h-4" />
 <span>
 {isProcessing 
 ? (isBn ? BN_DICT['migrating'] : EN_DICT['migrating']) 
 : (isBn ? `${selectedIds.size} জন শিক্ষার্থী স্থানান্তর করুন` : `Migrate ${selectedIds.size} Students`)}
 </span>
 </button>
 ) : (
 <button
 onClick={handleExecuteSingleTransfer}
 disabled={isProcessing || !singleStudent || !targetClass}
 className="px-6 py-2 bg-indigo-600 hover:bg-indigo-700 text-white font-medium rounded-xl transition-colors flex items-center gap-2 disabled:opacity-50 text-sm shadow-sm"
 >
 <ArrowRightLeft className="w-4 h-4" />
 <span>
 {isProcessing ? (isBn ? BN_DICT['transferring'] : EN_DICT['transferring']) : (isBn ? BN_DICT['confirm_transfer'] : EN_DICT['confirm_transfer'])}
 </span>
 </button>
 )}
 </div>
 </div>
 </div>
 </div>
 );
};
