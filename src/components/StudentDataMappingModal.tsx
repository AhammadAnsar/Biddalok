export function autoDetectColumnMappings(headers: string[]): Record<string, string> {
 const mappings: Record<string, string> = {};
 if (!headers || !headers.length) return mappings;

 const normalizedHeaders = headers.map(h => ({
 original: h,
 cleaned: String(h).toLowerCase().trim().replace(/[\s_\-()\/]/g, '')
 }));

 TARGET_FIELDS.forEach(field => {
 // 1. Exact or cleaned match
 for (const syn of field.synonyms) {
 const cleanedSyn = syn.toLowerCase().trim().replace(/[\s_\-()\/]/g, '');
 const match = normalizedHeaders.find(nh => nh.cleaned === cleanedSyn);
 if (match && !Object.values(mappings).includes(match.original)) {
 mappings[field.key] = match.original;
 return;
 }
 }

 // 2. Substring match (for longer strings)
 for (const syn of field.synonyms) {
 const cleanedSyn = syn.toLowerCase().trim().replace(/[\s_\-()\/]/g, '');
 if (cleanedSyn.length < 3) continue;
 const match = normalizedHeaders.find(nh => 
 (nh.cleaned.includes(cleanedSyn) || (cleanedSyn.includes(nh.cleaned) && nh.cleaned.length >= 4)) &&
 !Object.values(mappings).includes(nh.original)
 );
 if (match) {
 mappings[field.key] = match.original;
 return;
 }
 }
 });

 return mappings;
}

