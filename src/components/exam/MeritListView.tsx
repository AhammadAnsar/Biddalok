import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useMemo } from 'react';
import { Award, Printer, Download, Trophy, Medal, CheckCircle2, XCircle } from 'lucide-react';
import * as XLSX from 'xlsx';
import { 
  Student, 
  SubjectItem, 
  CurriculumSubjectMapping, 
  ExamResultEntry, 
  GradingRule, 
  ExamTerm, 
  Institution 
} from '../../types';
import { calculateStudentExamSummary, calculateClassMeritList, toBengaliRank } from '../../utils/examCalculations';

interface MeritListViewProps {
  institution?: Institution;
  exam: ExamTerm;
  className: string;
  sectionName?: string;
  groupName?: string;
  sessionName?: string;
  subjects: (SubjectItem | CurriculumSubjectMapping)[];
  students: Student[];
  gradingRules: GradingRule[];
  examResults: ExamResultEntry[];
  isBn: boolean;
}

export const MeritListView: React.FC<MeritListViewProps> = ({
  institution,
  exam,
  className,
  sectionName,
  groupName,
  sessionName,
  subjects,
  students,
  gradingRules,
  examResults,
  isBn
}) => {
  const rollsMap = useMemo(() => {
    const map: Record<string, number> = {};
    students.forEach(st => {
      map[st.id] = parseInt(st.roll || '999999') || 999999;
    });
    return map;
  }, [students]);

  const summaries = useMemo(() => {
    return students.map(st => 
      calculateStudentExamSummary(st.id, subjects, examResults, exam.id, gradingRules)
    );
  }, [students, subjects, examResults, exam.id, gradingRules]);

  const rankedStudents = useMemo(() => {
    return calculateClassMeritList(summaries, rollsMap);
  }, [summaries, rollsMap]);

  // Export to Excel
  const handleExportExcel = () => {
    const rows = rankedStudents.map(item => {
      const student = students.find(s => s.id === item.studentId);
      return {
        [isBn ? BN_DICT['rank'] : EN_DICT['rank']]: item.rank,
        [isBn ? BN_DICT['roll'] : EN_DICT['roll']]: student?.roll || '',
        [isBn ? BN_DICT['student_name'] : EN_DICT['student_name']]: isBn ? (student?.nameBn || student?.name) : student?.name,
        [isBn ? BN_DICT['student_id'] : EN_DICT['student_id']]: student?.studentId || '',
        [isBn ? BN_DICT['total_marks'] : EN_DICT['total_marks']]: item.totalObtained,
        [isBn ? BN_DICT['percentage'] : EN_DICT['percentage']]: `${item.percentage}%`,
        [isBn ? BN_DICT['gpa'] : EN_DICT['gpa']]: item.gpa.toFixed(2),
        [isBn ? BN_DICT['grade'] : EN_DICT['grade']]: item.grade,
        [isBn ? BN_DICT['status'] : EN_DICT['status']]: item.isPassed ? (isBn ? BN_DICT['passed'] : EN_DICT['passed']) : (isBn ? BN_DICT['failed'] : EN_DICT['failed'])
      };
    });

    const ws = XLSX.utils.json_to_sheet(rows);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, 'Merit_List');
    XLSX.writeFile(wb, `Merit_List_${className}_${exam.year || '2026'}.xlsx`);
  };

  return (
    <div className="space-y-6">
      {/* Action Bar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/90 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4 print:hidden">
        <div>
          <h2 className="text-base font-bold text-slate-800 flex items-center gap-2">
            <Trophy className="w-5 h-5 text-amber-500" />
            <span>{isBn ? BN_DICT['class_merit_list'] : EN_DICT['class_merit_list']}</span>
          </h2>
          <p className="text-xs text-slate-500 mt-0.5">
            {isBn ? BN_DICT['automated_ranking_based_on_pas'] : EN_DICT['automated_ranking_based_on_pas']}
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleExportExcel}
            className="px-3.5 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg text-xs font-semibold border border-slate-200 transition-colors flex items-center gap-1.5"
          >
            <Download className="w-4 h-4 text-slate-600" />
            <span>{isBn ? BN_DICT['export_excel'] : EN_DICT['export_excel']}</span>
          </button>
          <button
            onClick={() => window.print()}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
          >
            <Printer className="w-4 h-4" />
            <span>{isBn ? BN_DICT['print_merit_list'] : EN_DICT['print_merit_list']}</span>
          </button>
        </div>
      </div>

      {/* Top 3 Podium Cards (Print Hidden) */}
      <div className="grid grid-cols-1 sm:grid-cols-3 gap-4 print:hidden">
        {rankedStudents.slice(0, 3).map((item, idx) => {
          const student = students.find(s => s.id === item.studentId);
          if (!student) return null;

          const isFirst = idx === 0;
          const isSecond = idx === 1;
          const isThird = idx === 2;

          const bgStyle = isFirst
            ? 'bg-gradient-to-b from-amber-500/10 to-amber-500/5 border-amber-300'
            : isSecond
            ? 'bg-gradient-to-b from-slate-400/10 to-slate-400/5 border-slate-300'
            : 'bg-gradient-to-b from-amber-700/10 to-amber-700/5 border-amber-600/30';

          const badgeColor = isFirst
            ? 'bg-amber-500 text-white'
            : isSecond
            ? 'bg-slate-400 text-white'
            : 'bg-amber-700 text-white';

          return (
            <div key={student.id} className={`p-4 rounded-xl border ${bgStyle} shadow-xs flex items-center justify-between gap-3`}>
              <div className="flex items-center gap-3">
                <div className={`w-10 h-10 rounded-full flex items-center justify-center font-bold font-mono text-sm shadow-xs ${badgeColor}`}>
                  {idx + 1}
                </div>
                <div>
                  <div className="font-bold text-slate-900 text-sm">
                    {isBn ? (student.nameBn || student.name) : student.name}
                  </div>
                  <div className="text-xs text-slate-500 mt-0.5">
                    {isBn ? `রোল: ${student.roll || '—'}` : `Roll: ${student.roll || '—'}`} • {isBn ? `আইডি: ${student.studentId}` : `ID: ${student.studentId}`}
                  </div>
                </div>
              </div>

              <div className="text-right">
                <div className="text-base font-bold font-mono text-slate-900">
                  {item.gpa.toFixed(2)}
                </div>
                <div className="text-[11px] text-slate-500">
                  {item.totalObtained} {isBn ? BN_DICT['marks'] : EN_DICT['marks']}
                </div>
              </div>
            </div>
          );
        })}
      </div>

      {/* Main Printable Table Container */}
      <div className="bg-white p-6 sm:p-8 rounded-xl border border-slate-300 shadow-sm print:p-0 print:border-none print:shadow-none text-slate-900 font-sans">
        {/* Printable Institution Header */}
        <div className="text-center space-y-1 pb-4 border-b-2 border-slate-900">
          {institution?.logoUrl && (
            <img src={institution.logoUrl} alt="Logo" className="w-12 h-12 object-contain mx-auto mb-1" />
          )}
          <h1 className="text-xl sm:text-2xl font-bold uppercase tracking-wider text-slate-900">
            {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয়ের নাম') : (institution?.name || 'INSTITUTION NAME')}
          </h1>
          <p className="text-xs text-slate-600">
            {isBn ? (institution?.addressBn || institution?.address || '') : (institution?.address || '')}
            {institution?.eiin && ` | EIIN: ${institution.eiin}`}
          </p>
          <div className="inline-block mt-1 px-4 py-0.5 bg-slate-900 text-white rounded-full font-bold text-xs uppercase tracking-wider">
            {isBn ? BN_DICT['academic_merit_list'] : EN_DICT['academic_merit_list']}
          </div>
          <div className="text-xs font-bold text-slate-800 pt-1 flex items-center justify-center gap-4">
            <span>{isBn ? BN_DICT['exam'] : EN_DICT['exam']} {isBn ? (exam.nameBn || exam.name) : exam.name} ({exam.year})</span>
            <span>•</span>
            <span>{isBn ? BN_DICT['class_1'] : EN_DICT['class_1']} {className}</span>
            {sectionName && (
              <>
                <span>•</span>
                <span>{isBn ? BN_DICT['section_1'] : EN_DICT['section_1']} {sectionName}</span>
              </>
            )}
            {groupName && (
              <>
                <span>•</span>
                <span>{isBn ? BN_DICT['group_1'] : EN_DICT['group_1']} {groupName}</span>
              </>
            )}
          </div>
        </div>

        {/* Merit Table */}
        <div className="mt-4 overflow-x-auto">
          <table className="w-full border-collapse border border-slate-800 text-xs">
            <thead>
              <tr className="bg-slate-100 text-slate-900 font-bold border-b border-slate-800 text-center">
                <th className="border border-slate-800 p-2 w-16">{isBn ? BN_DICT['rank'] : EN_DICT['rank']}</th>
                <th className="border border-slate-800 p-2 w-16">{isBn ? BN_DICT['roll'] : EN_DICT['roll']}</th>
                <th className="border border-slate-800 p-2 text-left">{isBn ? BN_DICT['student_name'] : EN_DICT['student_name']}</th>
                <th className="border border-slate-800 p-2 w-24 font-mono">{isBn ? BN_DICT['student_id'] : EN_DICT['student_id']}</th>
                <th className="border border-slate-800 p-2 w-24 font-bold">{isBn ? BN_DICT['total_marks'] : EN_DICT['total_marks']}</th>
                <th className="border border-slate-800 p-2 w-20 font-bold">{isBn ? BN_DICT['gpa'] : EN_DICT['gpa']}</th>
                <th className="border border-slate-800 p-2 w-16">{isBn ? BN_DICT['grade'] : EN_DICT['grade']}</th>
                <th className="border border-slate-800 p-2 w-24">{isBn ? BN_DICT['status'] : EN_DICT['status']}</th>
              </tr>
            </thead>

            <tbody>
              {rankedStudents.map((item) => {
                const student = students.find(s => s.id === item.studentId);
                if (!student) return null;

                return (
                  <tr key={student.id} className="border-b border-slate-800 hover:bg-slate-50 text-center">
                    {/* Rank */}
                    <td className="border border-slate-800 p-2 font-mono font-bold text-sm bg-slate-50/50">
                      {item.isPassed ? (isBn ? toBengaliRank(item.rank) : item.rank) : '—'}
                    </td>

                    {/* Roll */}
                    <td className="border border-slate-800 p-2 font-mono font-bold text-slate-900">
                      {student.roll || '—'}
                    </td>

                    {/* Name */}
                    <td className="border border-slate-800 p-2 text-left font-semibold text-slate-900 px-3">
                      {isBn ? (student.nameBn || student.name) : student.name}
                    </td>

                    {/* ID */}
                    <td className="border border-slate-800 p-2 font-mono text-slate-500 text-xs">
                      {student.studentId || '—'}
                    </td>

                    {/* Total Marks */}
                    <td className="border border-slate-800 p-2 font-mono font-bold text-slate-950">
                      {item.totalObtained} / {item.totalMaxMarks}
                    </td>

                    {/* GPA */}
                    <td className="border border-slate-800 p-2 font-mono font-bold text-indigo-950 text-sm">
                      {item.gpa.toFixed(2)}
                    </td>

                    {/* Grade */}
                    <td className="border border-slate-800 p-2 font-mono font-bold">
                      <span className={item.grade === 'F' ? 'text-rose-700' : 'text-slate-900'}>
                        {item.grade}
                      </span>
                    </td>

                    {/* Status */}
                    <td className="border border-slate-800 p-2 font-bold">
                      {item.isPassed ? (
                        <span className="text-emerald-700 font-semibold">{isBn ? BN_DICT['passed'] : EN_DICT['passed']}</span>
                      ) : (
                        <span className="text-rose-700 font-semibold">{isBn ? BN_DICT['failed'] : EN_DICT['failed']}</span>
                      )}
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>

        {/* Triple Official Signature */}
        <div className="mt-16 pt-4 grid grid-cols-3 text-center text-xs font-bold text-slate-800">
          <div className="space-y-1">
            <div className="w-32 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? BN_DICT['class_teacher'] : EN_DICT['class_teacher']}</div>
          </div>
          <div className="space-y-1">
            <div className="w-32 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? BN_DICT['controller_of_exams'] : EN_DICT['controller_of_exams']}</div>
          </div>
          <div className="space-y-1 flex flex-col items-center justify-end">
            {institution?.headmasterSignature ? (
              <img 
                src={institution.headmasterSignature} 
                alt="Principal Signature" 
                className="h-9 max-w-[140px] object-contain mx-auto -mb-1"
              />
            ) : null}
            <div className="w-36 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? (institution?.headmasterTitleBn || 'প্রধান শিক্ষক') : (institution?.headmasterTitle || 'Principal')}</div>
          </div>
        </div>
      </div>
    </div>
  );
};
