import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useEffect, useRef, useCallback, useMemo } from 'react';
import { 
  CheckCircle2, RefreshCw, Copy, Download, Upload, 
  HelpCircle, AlertCircle, FileSpreadsheet, ArrowDown, Check,
  BookOpen, Sparkles
} from 'lucide-react';
import * as XLSX from 'xlsx';
import { Student, SubjectItem, CurriculumSubjectMapping, ExamResultEntry, GradingRule } from '../../types';
import { evaluateSubjectMarks, SubjectScoreBreakdown } from '../../utils/examCalculations';
import { toBengaliNumber } from '../../utils/bengaliUtils';

interface MarkEntryGridProps {
  examId: string;
  className: string;
  classId?: string;
  sessionId?: string;
  groupId?: string;
  subject: SubjectItem | CurriculumSubjectMapping;
  students: Student[];
  gradingRules: GradingRule[];
  existingResults: ExamResultEntry[];
  onAutoSave: (entries: ExamResultEntry[]) => void;
  isBn: boolean;
}

type ScoreField = 'cq' | 'mcq' | 'practical' | 'continuous';

export const MarkEntryGrid: React.FC<MarkEntryGridProps> = ({
  examId,
  className,
  classId,
  sessionId,
  groupId,
  subject,
  students,
  gradingRules,
  existingResults,
  onAutoSave,
  isBn
}) => {
  // Determine active score fields based on subject configuration
  const activeFields = useMemo<ScoreField[]>(() => {
    const fields: ScoreField[] = [];
    if (subject.cqMarks && subject.cqMarks > 0) fields.push('cq');
    if (subject.mcqMarks && subject.mcqMarks > 0) fields.push('mcq');
    if (subject.practicalMarks && subject.practicalMarks > 0) fields.push('practical');
    if ((subject as any).continuousMarks && (subject as any).continuousMarks > 0) fields.push('continuous');

    // Fallback: if no breakdown is defined (e.g. 100 marks single paper), default to cq
    if (fields.length === 0) fields.push('cq');
    return fields;
  }, [subject]);

  // Local state for all student scores: studentId -> scores
  const [scoresState, setScoresState] = useState<Record<string, SubjectScoreBreakdown>>({});
  const [saveStatus, setSaveStatus] = useState<'saved' | 'saving' | 'idle'>('saved');
  const [lastSavedTime, setLastSavedTime] = useState<string>('');
  const [toastMessage, setToastMessage] = useState<string | null>(null);

  // References for keyboard navigation: key = `${studentIndex}_${fieldIndex}`
  const inputRefs = useRef<Map<string, HTMLInputElement>>(new Map());
  const debounceTimerRef = useRef<NodeJS.Timeout | null>(null);

  // Populate scoresState when student or existing results change
  useEffect(() => {
    const initial: Record<string, SubjectScoreBreakdown> = {};
    students.forEach(st => {
      const match = existingResults.find(
        r => r.examId === examId && r.studentId === st.id && (r.subjectId === subject.id || (subject.code && r.subjectId === subject.code))
      );
      if (match) {
        initial[st.id] = {
          cq: match.cqMarksObtained ?? 0,
          mcq: match.mcqMarksObtained ?? 0,
          practical: match.practicalMarksObtained ?? 0,
          continuous: match.continuousMarksObtained ?? 0
        };
      } else {
        initial[st.id] = {
          cq: 0,
          mcq: 0,
          practical: 0,
          continuous: 0
        };
      }
    });
    setScoresState(initial);
    setSaveStatus('saved');
    setLastSavedTime(new Date().toLocaleTimeString(isBn ? BN_DICT['en_us'] : EN_DICT['en_us'], { hour12: true }));
  }, [examId, subject.id, students, existingResults, isBn]);

  // Max mark getter for a field
  const getMaxMark = useCallback((field: ScoreField): number => {
    if (field === 'cq') return subject.cqMarks || subject.fullMarks || 100;
    if (field === 'mcq') return subject.mcqMarks || 100;
    if (field === 'practical') return subject.practicalMarks || 100;
    if (field === 'continuous') return (subject as any).continuousMarks || 100;
    return subject.fullMarks || 100;
  }, [subject]);

  // Execute Auto Save
  const triggerAutoSave = useCallback((updatedState: Record<string, SubjectScoreBreakdown>) => {
    setSaveStatus('saving');
    
    const entries: ExamResultEntry[] = students.map(st => {
      const scores = updatedState[st.id] || { cq: null, mcq: null, practical: null, continuous: null };
      const evalRes = evaluateSubjectMarks(scores, subject, gradingRules);

      return {
        id: `res_${examId}_${st.id}_${subject.id}`,
        examId,
        studentId: st.id,
        studentDbId: st.id,
        subjectId: subject.id,
        classId,
        className,
        sessionId,
        groupId,
        cqMarksObtained: scores.cq !== null && scores.cq !== '' ? Number(scores.cq) : undefined,
        mcqMarksObtained: scores.mcq !== null && scores.mcq !== '' ? Number(scores.mcq) : undefined,
        practicalMarksObtained: scores.practical !== null && scores.practical !== '' ? Number(scores.practical) : undefined,
        continuousMarksObtained: scores.continuous !== null && scores.continuous !== undefined && scores.continuous !== '' ? Number(scores.continuous) : undefined,
        totalMarksObtained: evalRes.total,
        grade: evalRes.grade,
        gpa: evalRes.gpa.toString(),
        isPassed: evalRes.isPassed
      };
    });

    onAutoSave(entries);
    setSaveStatus('saved');
    setLastSavedTime(new Date().toLocaleTimeString(isBn ? BN_DICT['en_us'] : EN_DICT['en_us'], { hour12: true }));
  }, [students, examId, subject, classId, className, sessionId, groupId, gradingRules, onAutoSave, isBn]);

  // Handle single cell modification
  const handleScoreChange = (studentId: string, field: ScoreField, val: string | number) => {
    const maxMark = getMaxMark(field);
    let strVal = String(val).trim().toUpperCase();
    // Convert Bengali digits to English for validation/storage if typed
    const bnToEn: Record<string, string> = { '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4', '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9' };
    strVal = strVal.replace(/[০-৯]/g, char => bnToEn[char] || char);
    
    let parsedVal: number | string | null = null;
    
    if (strVal === 'A') {
      parsedVal = 'A';
    } else if (strVal === 'W') {
      parsedVal = 'W';
    } else if (strVal === '') {
      parsedVal = null;
    } else {
      const num = Number(strVal);
      if (isNaN(num) || num < 0 || !isFinite(num)) return; // Reject invalid numeric
      if (num > maxMark) {
        setToastMessage(isBn ? BN_DICT['marks_cannot_exceed_maximum_co'] : EN_DICT['marks_cannot_exceed_maximum_co']);
        setTimeout(() => setToastMessage(null), 3000);
        return; // Reject over-full marks
      }
      parsedVal = num;
    }

    setScoresState(prev => {
      const next = {
        ...prev,
        [studentId]: {
          ...(prev[studentId] || { cq: null, mcq: null, practical: null, continuous: null }),
          [field]: parsedVal
        }
      };

      // Debounce auto-save
      if (debounceTimerRef.current) clearTimeout(debounceTimerRef.current);
      setSaveStatus('saving');
      debounceTimerRef.current = setTimeout(() => {
        triggerAutoSave(next);
      }, 500); // 500ms debounce

      return next;
    });
  };

  // Keyboard navigation logic (Excel-like arrow keys, enter, tab)
  const handleKeyDown = (
    e: React.KeyboardEvent<HTMLInputElement>,
    rowIndex: number,
    fieldIndex: number
  ) => {
    const totalRows = students.length;
    const totalCols = activeFields.length;

    let targetRow = rowIndex;
    let targetCol = fieldIndex;

    if (e.key === 'ArrowDown' || e.key === 'Enter') {
      e.preventDefault();
      if (rowIndex + 1 < totalRows) {
        targetRow = rowIndex + 1;
      }
    } else if (e.key === 'ArrowUp') {
      e.preventDefault();
      if (rowIndex - 1 >= 0) {
        targetRow = rowIndex - 1;
      }
    } else if (e.key === 'ArrowRight' && e.currentTarget.selectionStart === e.currentTarget.value.length) {
      if (fieldIndex + 1 < totalCols) {
        e.preventDefault();
        targetCol = fieldIndex + 1;
      } else if (rowIndex + 1 < totalRows) {
        e.preventDefault();
        targetRow = rowIndex + 1;
        targetCol = 0;
      }
    } else if (e.key === 'ArrowLeft' && e.currentTarget.selectionStart === 0) {
      if (fieldIndex - 1 >= 0) {
        e.preventDefault();
        targetCol = fieldIndex - 1;
      } else if (rowIndex - 1 >= 0) {
        e.preventDefault();
        targetRow = rowIndex - 1;
        targetCol = totalCols - 1;
      }
    } else if (e.key === 'Tab') {
      // Let Tab work naturally or control focus seamlessly
      if (!e.shiftKey && fieldIndex + 1 >= totalCols && rowIndex + 1 < totalRows) {
        e.preventDefault();
        targetRow = rowIndex + 1;
        targetCol = 0;
      }
    }

    if (targetRow !== rowIndex || targetCol !== fieldIndex) {
      const targetKey = `${targetRow}_${targetCol}`;
      const targetInput = inputRefs.current.get(targetKey);
      if (targetInput) {
        targetInput.focus();
        targetInput.select();
      }
    }
  };

  // Excel Copy & Paste Handler
  const handlePaste = (
    e: React.ClipboardEvent<HTMLInputElement>,
    startRowIndex: number,
    startColIndex: number
  ) => {
    const pasteData = e.clipboardData.getData('text');
    if (!pasteData) return;

    // Check if multi-line or tab-separated data was pasted
    const rows = pasteData.trim().split(/\r\n|\n|\r/);
    if (rows.length > 1 || rows[0].includes('\t')) {
      e.preventDefault();

      setScoresState(prev => {
        const nextState = { ...prev };
        let modifiedCount = 0;

        rows.forEach((rowText, rOffset) => {
          const targetRow = startRowIndex + rOffset;
          if (targetRow >= students.length) return;

          const student = students[targetRow];
          const cellValues = rowText.split('\t');

          cellValues.forEach((valStr, cOffset) => {
            const targetCol = startColIndex + cOffset;
            if (targetCol >= activeFields.length) return;

            const field = activeFields[targetCol];
            const maxVal = getMaxMark(field);
            const parsedNum = Math.max(0, Math.min(maxVal, Number(valStr.trim()) || 0));

            nextState[student.id] = {
              ...(nextState[student.id] || { cq: null, mcq: null, practical: null, continuous: null }),
              [field]: parsedNum
            };
            modifiedCount++;
          });
        });

        triggerAutoSave(nextState);

        setToastMessage(
          isBn 
            ? `এক্সেল থেকে ${modifiedCount}টি ঘরের নম্বর সফলভাবে পেস্ট ও অটো-সেভ করা হয়েছে!`
            : `Successfully pasted and auto-saved ${modifiedCount} marks from spreadsheet!`
        );
        setTimeout(() => setToastMessage(null), 4000);

        return nextState;
      });
    }
  };

  // Copy current table data to clipboard in TSV format
  const handleCopyTable = () => {
    const headers = [
      isBn ? BN_DICT['roll'] : EN_DICT['roll'],
      isBn ? BN_DICT['name'] : EN_DICT['name'],
      isBn ? BN_DICT['student_id'] : EN_DICT['student_id'],
      ...activeFields.map(f => {
        if (f === 'cq') return `CQ (${subject.cqMarks || 100})`;
        if (f === 'mcq') return `MCQ (${subject.mcqMarks || 100})`;
        if (f === 'practical') return `Practical (${subject.practicalMarks || 100})`;
        return `Continuous (${(subject as any).continuousMarks || 100})`;
      }),
      isBn ? BN_DICT['total_1'] : EN_DICT['total_1'],
      isBn ? BN_DICT['grade'] : EN_DICT['grade'],
      isBn ? BN_DICT['gpa'] : EN_DICT['gpa'],
      isBn ? BN_DICT['status'] : EN_DICT['status']
    ];

    const lines = [headers.join('\t')];

    students.forEach(st => {
      const scores = scoresState[st.id] || { cq: null, mcq: null, practical: null, continuous: null };
      const evalRes = evaluateSubjectMarks(scores, subject, gradingRules);

      const rowValues = [
        st.roll || '',
        (isBn ? (st.nameBn || st.name) : st.name) || '',
        st.studentId || '',
        ...activeFields.map(f => scores[f] ?? 0),
        evalRes.total,
        evalRes.grade,
        evalRes.gpa.toFixed(2),
        evalRes.isPassed ? (isBn ? BN_DICT['pass'] : EN_DICT['pass']) : (isBn ? BN_DICT['fail'] : EN_DICT['fail'])
      ];
      lines.push(rowValues.join('\t'));
    });

    navigator.clipboard.writeText(lines.join('\n')).then(() => {
      setToastMessage(isBn ? BN_DICT['table_data_copied_to_clipboard'] : EN_DICT['table_data_copied_to_clipboard']);
      setTimeout(() => setToastMessage(null), 3500);
    });
  };

  // Export blank or populated Excel template
  const handleExportExcel = () => {
    const data = students.map(st => {
      const scores = scoresState[st.id] || { cq: null, mcq: null, practical: null, continuous: null };
      const row: Record<string, any> = {
        [isBn ? BN_DICT['roll'] : EN_DICT['roll']]: st.roll,
        [isBn ? BN_DICT['student_name'] : EN_DICT['student_name']]: isBn ? (st.nameBn || st.name) : st.name,
        [isBn ? BN_DICT['student_id'] : EN_DICT['student_id']]: st.studentId,
      };

      activeFields.forEach(f => {
        const label = f === 'cq' ? `CQ_${subject.cqMarks || 100}` 
          : f === 'mcq' ? `MCQ_${subject.mcqMarks || 100}` 
          : f === 'practical' ? `Prac_${subject.practicalMarks || 100}`
          : `Cont_${(subject as any).continuousMarks || 100}`;
        row[label] = scores[f];
      });

      return row;
    });

    const worksheet = XLSX.utils.json_to_sheet(data);
    const workbook = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(workbook, worksheet, 'Marks_Entry');
    const safeSubName = (subject.nameBn || subject.name || 'Subject').replace(/[^a-zA-Z0-9_\u0980-\u09FF]/g, '_');
    XLSX.writeFile(workbook, `Mark_Entry_${className}_${safeSubName}.xlsx`);
  };

  // Upload Excel file to populate marks
  const fileInputRef = useRef<HTMLInputElement>(null);
  const handleFileUpload = (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;

    const reader = new FileReader();
    reader.onload = (evt) => {
      try {
        const bstr = evt.target?.result;
        const wb = XLSX.read(bstr, { type: 'binary' });
        const wsName = wb.SheetNames[0];
        const ws = wb.Sheets[wsName];
        const rows: any[] = XLSX.utils.sheet_to_json(ws);

        if (rows && rows.length > 0) {
          setScoresState(prev => {
            const nextState = { ...prev };
            let count = 0;

            rows.forEach(row => {
              // Match student by Roll or Student ID
              const rowRoll = String(row['রোল'] ?? row['Roll'] ?? '').trim();
              const rowId = String(row['আইডি'] ?? row['Student ID'] ?? '').trim();

              const student = students.find(s => 
                (rowId && s.studentId === rowId) || 
                (rowRoll && String(s.roll).trim() === rowRoll)
              );

              if (student) {
                const currentScores = nextState[student.id] || { cq: null, mcq: null, practical: null, continuous: null };
                
                activeFields.forEach(f => {
                  // Look for column containing CQ, MCQ, etc.
                  const colKey = Object.keys(row).find(k => k.toLowerCase().includes(f.toLowerCase()));
                  if (colKey && row[colKey] !== undefined) {
                    const maxVal = getMaxMark(f);
                    const parsed = Math.max(0, Math.min(maxVal, Number(row[colKey]) || 0));
                    currentScores[f] = parsed;
                  }
                });

                nextState[student.id] = currentScores;
                count++;
              }
            });

            triggerAutoSave(nextState);
            setToastMessage(isBn ? `এক্সেল ফাইল থেকে ${count}জন শিক্ষার্থীর নম্বর যুক্ত হয়েছে!` : `Imported marks for ${count} students from Excel!`);
            setTimeout(() => setToastMessage(null), 4000);
            return nextState;
          });
        }
      } catch (err) {
        console.error('Failed to parse Excel file:', err);
        setToastMessage(isBn ? BN_DICT['failed_to_parse_excel_file'] : EN_DICT['failed_to_parse_excel_file']);
        setTimeout(() => setToastMessage(null), 4000);
      }
    };
    reader.readAsBinaryString(file);
    if (e.target) e.target.value = '';
  };

  return (
    <div className="space-y-4">
      {/* Toast Notification */}
      {toastMessage && (
        <div className="bg-emerald-50 border border-emerald-300 text-emerald-800 text-xs px-4 py-2.5 rounded-xl shadow-xs flex items-center justify-between animate-fade-in">
          <div className="flex items-center gap-2 font-medium">
            <Check className="w-4 h-4 text-emerald-600 shrink-0" />
            <span>{toastMessage}</span>
          </div>
          <button onClick={() => setToastMessage(null)} className="text-emerald-600 hover:text-emerald-900 font-bold ml-4">✕</button>
        </div>
      )}

      {/* Control Bar & Auto-Save Badge */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/90 shadow-xs flex flex-col md:flex-row md:items-center justify-between gap-4">
        {/* Subject Metadata Summary */}
        <div className="flex items-start sm:items-center gap-3.5">
          <div className="p-2.5 bg-indigo-50 text-indigo-700 rounded-xl shrink-0 border border-indigo-100">
            <BookOpen className="w-5 h-5" />
          </div>
          <div>
            <div className="flex flex-wrap items-center gap-2">
              <h3 className="font-bold text-slate-800 text-sm sm:text-base">
                {isBn ? (subject.nameBn || subject.name) : subject.name}
              </h3>
              <span className="px-2 py-0.5 bg-slate-100 text-slate-700 text-[11px] font-mono font-bold rounded border border-slate-200">
                {isBn ? `কোড: ${subject.code}` : `Code: ${subject.code}`}
              </span>
              {subject.isOptional && (
                <span className="px-2 py-0.5 bg-amber-50 text-amber-700 text-[10px] font-bold rounded border border-amber-200">
                  {isBn ? BN_DICT['k_4th_subject'] : EN_DICT['k_4th_subject']}
                </span>
              )}
            </div>

            <div className="flex flex-wrap items-center gap-2 text-xs text-slate-500 mt-1">
              <span>{isBn ? `পূর্ণমান: ${subject.fullMarks}` : `Full Marks: ${subject.fullMarks}`}</span>
              <span>•</span>
              {subject.cqMarks ? <span>CQ: {subject.cqMarks} {subject.passMarks ? `(পাস ${subject.passMarks})` : ''} •</span> : null}
              {subject.mcqMarks ? <span>MCQ: {subject.mcqMarks} {subject.passMarks ? `(পাস ${subject.passMarks})` : ''} •</span> : null}
              {subject.practicalMarks ? <span>Prac: {subject.practicalMarks} •</span> : null}
              <span className="text-emerald-700 font-medium">{isBn ? `পাস নম্বর: ${subject.passMarks}` : `Pass: ${subject.passMarks}`}</span>
            </div>
          </div>
        </div>

        {/* Action Buttons & Auto-Save Indicator */}
        <div className="flex flex-wrap items-center gap-2.5 self-end md:self-center">
          {/* Auto-Save Live Status Pill */}
          <div className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-lg border text-xs font-semibold bg-emerald-50/80 text-emerald-800 border-emerald-200/80 shadow-2xs">
            {saveStatus === 'saving' ? (
              <>
                <RefreshCw className="w-3.5 h-3.5 text-emerald-600 animate-spin" />
                <span>{isBn ? BN_DICT['saving'] : EN_DICT['saving']}</span>
              </>
            ) : (
              <>
                <CheckCircle2 className="w-3.5 h-3.5 text-emerald-600" />
                <span>{isBn ? BN_DICT['auto_saved'] : EN_DICT['auto_saved']}</span>
                {lastSavedTime && <span className="text-[10px] text-emerald-600 font-mono font-normal">({lastSavedTime})</span>}
              </>
            )}
          </div>

          {/* Copy Table to Clipboard */}
          <button
            onClick={handleCopyTable}
            className="px-3 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg text-xs font-semibold border border-slate-200 transition-colors flex items-center gap-1.5"
            title={isBn ? BN_DICT['copy_table_to_clipboard'] : EN_DICT['copy_table_to_clipboard']}
          >
            <Copy className="w-3.5 h-3.5 text-slate-600" />
            <span>{isBn ? BN_DICT['copy'] : EN_DICT['copy']}</span>
          </button>

          {/* Export Excel */}
          <button
            onClick={handleExportExcel}
            className="px-3 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg text-xs font-semibold border border-slate-200 transition-colors flex items-center gap-1.5"
            title={isBn ? BN_DICT['download_as_excel'] : EN_DICT['download_as_excel']}
          >
            <Download className="w-3.5 h-3.5 text-slate-600" />
            <span>{isBn ? BN_DICT['excel'] : EN_DICT['excel']}</span>
          </button>

          {/* Upload Excel */}
          <button
            onClick={() => fileInputRef.current?.click()}
            className="px-3 py-1.5 bg-indigo-50 hover:bg-indigo-100 text-indigo-700 rounded-lg text-xs font-semibold border border-indigo-200 transition-colors flex items-center gap-1.5"
            title={isBn ? BN_DICT['import_marks_from_excel'] : EN_DICT['import_marks_from_excel']}
          >
            <Upload className="w-3.5 h-3.5 text-indigo-600" />
            <span>{isBn ? BN_DICT['import'] : EN_DICT['import']}</span>
          </button>
          <input
            type="file"
            ref={fileInputRef}
            onChange={handleFileUpload}
            accept=".xlsx, .xls, .csv"
            className="hidden"
          />
        </div>
      </div>

      {/* Helpful Excel Keyboard Guidance Banner */}
      <div className="bg-blue-50/70 border border-blue-200 rounded-xl px-4 py-2.5 text-xs text-blue-800 flex items-center justify-between gap-3">
        <div className="flex items-center gap-2">
          <Sparkles className="w-4 h-4 text-blue-600 shrink-0" />
          <span>
            {isBn ? BN_DICT['tips_use_arrow_keys_or_enter_t'] : EN_DICT['tips_use_arrow_keys_or_enter_t']}
          </span>
        </div>
        <span className="hidden sm:inline-block text-[11px] font-bold text-blue-700 bg-blue-100/70 px-2 py-0.5 rounded">
          {isBn ? `${students.length} জন শিক্ষার্থী` : `${students.length} Students`}
        </span>
      </div>

      {/* Main Excel-like Data Table */}
      <div className="bg-white rounded-xl border border-slate-200/90 shadow-xs overflow-hidden">
        <div className="overflow-x-auto">
          <table className="w-full text-left text-xs text-slate-600 border-collapse">
            <thead className="bg-slate-50 text-slate-700 uppercase font-semibold text-[11px] border-b border-slate-200">
              <tr>
                <th className="px-3 py-3 text-center w-12 border-r border-slate-200/60 bg-slate-100/50">#</th>
                <th className="px-3 py-3 text-center w-16 border-r border-slate-200/60">{isBn ? BN_DICT['roll'] : EN_DICT['roll']}</th>
                <th className="px-4 py-3 border-r border-slate-200/60">{isBn ? BN_DICT['student_name'] : EN_DICT['student_name']}</th>
                <th className="px-3 py-3 text-slate-500 font-mono w-28 border-r border-slate-200/60">{isBn ? BN_DICT['student_id'] : EN_DICT['student_id']}</th>

                {/* Dynamic Mark Input Columns */}
                {activeFields.map((field) => {
                  const maxLimit = getMaxMark(field);
                  const passMark = field === 'cq' ? subject.passMarks : field === 'mcq' ? subject.passMarks : undefined;

                  return (
                    <th key={field} className="px-3 py-3 text-center w-28 border-r border-slate-200/60 bg-indigo-50/30">
                      <div className="font-bold text-indigo-950">
                        {field === 'cq' ? (isBn ? BN_DICT['cq'] : EN_DICT['cq'])
                          : field === 'mcq' ? (isBn ? BN_DICT['mcq'] : EN_DICT['mcq'])
                          : field === 'practical' ? (isBn ? BN_DICT['practical'] : EN_DICT['practical'])
                          : (isBn ? BN_DICT['continuous'] : EN_DICT['continuous'])}
                      </div>
                      <div className="text-[10px] text-indigo-600 font-normal mt-0.5">
                        {isBn ? `পূর্ণ: ${maxLimit}` : `Max: ${maxLimit}`}
                        {passMark ? ` | ${isBn ? BN_DICT['pass'] : EN_DICT['pass']}: ${passMark}` : ''}
                      </div>
                    </th>
                  );
                })}

                {/* Computed Columns */}
                <th className="px-3 py-3 text-center font-bold text-slate-900 w-24 border-r border-slate-200/60 bg-slate-50">
                  {isBn ? BN_DICT['total_1'] : EN_DICT['total_1']}
                </th>
                <th className="px-3 py-3 text-center w-20 border-r border-slate-200/60">{isBn ? BN_DICT['grade'] : EN_DICT['grade']}</th>
                <th className="px-3 py-3 text-center w-20 border-r border-slate-200/60">{isBn ? BN_DICT['gpa'] : EN_DICT['gpa']}</th>
                <th className="px-3 py-3 text-center w-24">{isBn ? BN_DICT['status'] : EN_DICT['status']}</th>
              </tr>
            </thead>

            <tbody className="divide-y divide-slate-100">
              {students.length === 0 ? (
                <tr>
                  <td colSpan={8 + activeFields.length} className="text-center py-12 text-slate-400">
                    <AlertCircle className="w-8 h-8 mx-auto mb-2 opacity-50" />
                    <p>{isBn ? BN_DICT['no_students_found_in_this_clas'] : EN_DICT['no_students_found_in_this_clas']}</p>
                  </td>
                </tr>
              ) : (
                students.map((st, rIndex) => {
                  const scores = scoresState[st.id] || { cq: null, mcq: null, practical: null, continuous: null };
                  const evalRes = evaluateSubjectMarks(scores, subject, gradingRules);

                  return (
                    <tr 
                      key={st.id} 
                      className="hover:bg-slate-50/80 transition-colors focus-within:bg-indigo-50/20"
                    >
                      {/* Row Index */}
                      <td className="px-3 py-2 text-center text-slate-400 font-mono text-[11px] border-r border-slate-100">
                        {rIndex + 1}
                      </td>

                      {/* Roll */}
                      <td className="px-3 py-2 text-center font-mono font-bold text-slate-800 border-r border-slate-100">
                        {st.roll || '—'}
                      </td>

                      {/* Student Name */}
                      <td className="px-4 py-2 font-semibold text-slate-900 border-r border-slate-100">
                        {isBn ? (st.nameBn || st.name) : st.name}
                      </td>

                      {/* ID */}
                      <td className="px-3 py-2 font-mono text-slate-500 text-[11px] border-r border-slate-100">
                        {st.studentId || '—'}
                      </td>

                      {/* Interactive Inputs for each Active Score Field */}
                      {activeFields.map((field, cIndex) => {
                        const cellKey = `${rIndex}_${cIndex}`;
                        const maxLimit = getMaxMark(field);
                        const val = scores[field] ?? 0;

                        return (
                          <td key={field} className="px-2 py-1.5 text-center border-r border-slate-100">
                            <input
                              ref={el => {
                                if (el) inputRefs.current.set(cellKey, el);
                                else inputRefs.current.delete(cellKey);
                              }}
                              type="number"
                              min="0"
                              max={maxLimit}
                              step="1"
                              value={val === null ? '' : val}
                              onFocus={(e) => e.target.select()}
                              onChange={(e) => handleScoreChange(st.id, field, e.target.value)}
                              onKeyDown={(e) => handleKeyDown(e, rIndex, cIndex)}
                              onPaste={(e) => handlePaste(e, rIndex, cIndex)}
                              className="w-20 p-1.5 bg-slate-50/90 border border-slate-200 rounded-md font-mono text-center font-bold text-slate-900 focus:bg-white focus:border-indigo-500 focus:ring-1 focus:ring-indigo-400 focus:outline-none text-xs transition-all"
                            />
                          </td>
                        );
                      })}

                      {/* Total Marks */}
                      <td className="px-3 py-2 text-center font-mono font-bold text-slate-900 border-r border-slate-100 bg-slate-50/40">
                        {evalRes.total}
                      </td>

                      {/* Letter Grade */}
                      <td className="px-3 py-2 text-center border-r border-slate-100">
                        <span className={`inline-block px-2 py-0.5 rounded font-bold font-mono text-xs ${
                          evalRes.grade === 'A+' ? 'bg-emerald-100 text-emerald-800' :
                          evalRes.grade === 'A' ? 'bg-emerald-50 text-emerald-700' :
                          evalRes.grade === 'A-' ? 'bg-teal-50 text-teal-700' :
                          evalRes.grade === 'B' ? 'bg-blue-50 text-blue-700' :
                          evalRes.grade === 'C' ? 'bg-amber-50 text-amber-700' :
                          evalRes.grade === 'D' ? 'bg-orange-50 text-orange-700' :
                          'bg-rose-100 text-rose-800'
                        }`}>
                          {evalRes.grade}
                        </span>
                      </td>

                      {/* Point / GPA */}
                      <td className="px-3 py-2 text-center font-mono font-semibold text-slate-700 border-r border-slate-100">
                        {evalRes.gpa.toFixed(2)}
                      </td>

                      {/* Result Status */}
                      <td className="px-3 py-2 text-center">
                        {evalRes.isPassed ? (
                          <span className="px-2 py-0.5 rounded-full bg-emerald-50 text-emerald-700 text-[10px] font-semibold border border-emerald-200 inline-flex items-center gap-1">
                            <span className="w-1.5 h-1.5 rounded-full bg-emerald-500"></span>
                            {isBn ? BN_DICT['pass'] : EN_DICT['pass']}
                          </span>
                        ) : (
                          <span className="px-2 py-0.5 rounded-full bg-rose-50 text-rose-700 text-[10px] font-semibold border border-rose-200 inline-flex items-center gap-1">
                            <span className="w-1.5 h-1.5 rounded-full bg-rose-500"></span>
                            {isBn ? BN_DICT['fail'] : EN_DICT['fail']}
                          </span>
                        )}
                      </td>
                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>
      </div>
    </div>
  );
};
