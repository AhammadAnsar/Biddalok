import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useMemo } from 'react';
import { Printer, Download, Users, CheckCircle2, XCircle, Award, TrendingUp, AlertTriangle, ShieldAlert, ShieldCheck } from 'lucide-react';
import * as XLSX from 'xlsx';
import { 
  Student, 
  SubjectItem, 
  CurriculumSubjectMapping, 
  ExamResultEntry, 
  GradingRule, 
  ExamTerm, 
  Institution 
} from '../../types';
import { calculateStudentExamSummary, calculateClassMeritList, toBengaliRank } from '../../utils/examCalculations';
import { toBengaliNumber } from '../../utils/bengaliUtils';

interface TabulationSheetViewProps {
  institution?: Institution;
  exam: ExamTerm;
  className: string;
  sectionName?: string;
  groupName?: string;
  sessionName?: string;
  subjects: (SubjectItem | CurriculumSubjectMapping)[];
  students: Student[];
  gradingRules: GradingRule[];
  examResults: ExamResultEntry[];
  isBn: boolean;
}

export const TabulationSheetView: React.FC<TabulationSheetViewProps> = ({
  institution,
  exam,
  className,
  sectionName,
  groupName,
  sessionName,
  subjects,
  students,
  gradingRules,
  examResults,
  isBn
}) => {
  // Map rolls for tie-breaking
  const rollsMap = useMemo(() => {
    const map: Record<string, number> = {};
    students.forEach(st => {
      map[st.id] = parseInt(st.roll || '999999') || 999999;
    });
    return map;
  }, [students]);

  // Calculate summaries for all students
  const summaries = useMemo(() => {
    return students.map(st => 
      calculateStudentExamSummary(st.id, subjects, examResults, exam.id, gradingRules)
    );
  }, [students, subjects, examResults, exam.id, gradingRules]);

  // Calculate ranks
  const rankedSummaries = useMemo(() => {
    return calculateClassMeritList(summaries, rollsMap);
  }, [summaries, rollsMap]);

  // Cohort statistics
  const totalStudents = students.length;
  const passedStudents = rankedSummaries.filter(s => s.isPassed).length;
  const failedStudents = totalStudents - passedStudents;
  const passRate = totalStudents > 0 ? ((passedStudents / totalStudents) * 100).toFixed(1) : '0';
  const gpa5Count = rankedSummaries.filter(s => s.gpa === 5.0).length;

  // Print handler
  const handlePrint = () => {
    window.print();
  };

  // Export to Excel
  const handleExportExcel = () => {
    const rows = students.map(st => {
      const sum = rankedSummaries.find(s => s.studentId === st.id);
      const row: Record<string, any> = {
        [isBn ? BN_DICT['rank'] : EN_DICT['rank']]: sum?.rank || '',
        [isBn ? BN_DICT['roll'] : EN_DICT['roll']]: st.roll,
        [isBn ? BN_DICT['student_name'] : EN_DICT['student_name']]: isBn ? (st.nameBn || st.name) : st.name,
        [isBn ? BN_DICT['student_id'] : EN_DICT['student_id']]: st.studentId,
      };

      subjects.forEach(sub => {
        const rep = sum?.subjectReports.find(r => r.subject.id === sub.id || (sub.code && r.subject.code === sub.code));
        const subName = sub.nameBn || sub.name;
        if (sub.cqMarks) row[`${subName}_CQ`] = rep?.scores.cq ?? 0;
        if (sub.mcqMarks) row[`${subName}_MCQ`] = rep?.scores.mcq ?? 0;
        if (sub.practicalMarks) row[`${subName}_Prac`] = rep?.scores.practical ?? 0;
        row[`${subName}_Total`] = rep?.evaluation.total ?? 0;
        row[`${subName}_GP`] = rep?.evaluation.gpa.toFixed(2) ?? '0.00';
      });

      row[isBn ? BN_DICT['grand_total_1'] : EN_DICT['grand_total_1']] = sum?.totalObtained ?? 0;
      row[isBn ? BN_DICT['gpa'] : EN_DICT['gpa']] = sum?.gpa.toFixed(2) ?? '0.00';
      row[isBn ? BN_DICT['grade'] : EN_DICT['grade']] = sum?.grade ?? '-';
      row[isBn ? BN_DICT['result'] : EN_DICT['result']] = sum?.isPassed ? (isBn ? BN_DICT['passed'] : EN_DICT['passed']) : (isBn ? BN_DICT['failed'] : EN_DICT['failed']);

      return row;
    });

    const ws = XLSX.utils.json_to_sheet(rows);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, 'Tabulation_Sheet');
    XLSX.writeFile(wb, `Tabulation_Sheet_${className}_${exam.year || '2026'}.xlsx`);
  };

  const isPolicyApproved = exam.isPolicyApproved === true;

  return (
    <div className="space-y-6">
      {/* Unapproved Policy Release Guard Banner */}
      {!isPolicyApproved && (
        <div className="bg-amber-50 border-2 border-amber-300 p-4 rounded-xl flex flex-col sm:flex-row sm:items-center justify-between gap-3 shadow-xs print:border-amber-400">
          <div className="flex items-start gap-3">
            <ShieldAlert className="w-5 h-5 text-amber-600 shrink-0 mt-0.5" />
            <div>
              <h4 className="text-xs font-bold text-amber-900 uppercase tracking-wide">
                {isBn ? BN_DICT['unverified_exam_policy_officia'] : EN_DICT['unverified_exam_policy_officia']}
              </h4>
              <p className="text-xs text-amber-700 mt-0.5">
                {isBn ? BN_DICT['this_examination_term_has_not'] : EN_DICT['this_examination_term_has_not']}
              </p>
            </div>
          </div>
          <span className="px-2.5 py-1 bg-amber-200 text-amber-900 rounded-md text-[11px] font-bold shrink-0 self-start sm:self-auto">
            {isBn ? BN_DICT['draft_ledger'] : EN_DICT['draft_ledger']}
          </span>
        </div>
      )}

      {/* Top Actions & Summary Banner (Hidden during Print) */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/90 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4 print:hidden">
        <div>
          <h2 className="text-base font-bold text-slate-800 flex items-center gap-2">
            <Award className="w-5 h-5 text-indigo-600" />
            <span>{isBn ? BN_DICT['tabulation_sheet_master_ledger'] : EN_DICT['tabulation_sheet_master_ledger']}</span>
          </h2>
          <p className="text-xs text-slate-500 mt-0.5">
            {isBn ? `${className} - ${sectionName ? `শাখা: ${sectionName} • ` : ''}${sessionName || exam.year}` : `${className} - ${sectionName || ''}`}
          </p>
        </div>

        <div className="flex items-center gap-2">
          <button
            onClick={handleExportExcel}
            className="px-3.5 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg text-xs font-semibold border border-slate-200 transition-colors flex items-center gap-1.5"
          >
            <Download className="w-4 h-4 text-slate-600" />
            <span>{isBn ? BN_DICT['excel_export'] : EN_DICT['excel_export']}</span>
          </button>
          <button
            onClick={handlePrint}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
          >
            <Printer className="w-4 h-4" />
            <span>{isBn ? BN_DICT['print_sheet'] : EN_DICT['print_sheet']}</span>
          </button>
        </div>
      </div>

      {/* Metric Counters (Hidden during Print) */}
      <div className="grid grid-cols-2 sm:grid-cols-5 gap-3 print:hidden">
        <div className="bg-white p-3.5 rounded-xl border border-slate-200/80 shadow-xs flex items-center gap-3">
          <div className="p-2.5 bg-slate-100 text-slate-700 rounded-lg">
            <Users className="w-4 h-4" />
          </div>
          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['students_1'] : EN_DICT['students_1']}</div>
            <div className="text-base font-bold text-slate-900">{totalStudents}</div>
          </div>
        </div>

        <div className="bg-white p-3.5 rounded-xl border border-slate-200/80 shadow-xs flex items-center gap-3">
          <div className="p-2.5 bg-emerald-50 text-emerald-600 rounded-lg">
            <CheckCircle2 className="w-4 h-4" />
          </div>
          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['passed'] : EN_DICT['passed']}</div>
            <div className="text-base font-bold text-emerald-700">{passedStudents}</div>
          </div>
        </div>

        <div className="bg-white p-3.5 rounded-xl border border-slate-200/80 shadow-xs flex items-center gap-3">
          <div className="p-2.5 bg-rose-50 text-rose-600 rounded-lg">
            <XCircle className="w-4 h-4" />
          </div>
          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['failed'] : EN_DICT['failed']}</div>
            <div className="text-base font-bold text-rose-700">{failedStudents}</div>
          </div>
        </div>

        <div className="bg-white p-3.5 rounded-xl border border-slate-200/80 shadow-xs flex items-center gap-3">
          <div className="p-2.5 bg-indigo-50 text-indigo-600 rounded-lg">
            <TrendingUp className="w-4 h-4" />
          </div>
          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['pass_rate'] : EN_DICT['pass_rate']}</div>
            <div className="text-base font-bold text-indigo-700">{passRate}%</div>
          </div>
        </div>

        <div className="bg-white p-3.5 rounded-xl border border-slate-200/80 shadow-xs flex items-center gap-3">
          <div className="p-2.5 bg-amber-50 text-amber-600 rounded-lg">
            <Award className="w-4 h-4" />
          </div>
          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['gpa_5_00'] : EN_DICT['gpa_5_00']}</div>
            <div className="text-base font-bold text-amber-700">{gpa5Count}</div>
          </div>
        </div>
      </div>

      {/* Printable Landscape Tabulation Container */}
      <div className="bg-white p-6 sm:p-8 rounded-xl border border-slate-300 shadow-sm print:p-0 print:border-none print:shadow-none text-slate-900 font-sans overflow-x-auto">
        {/* Official Header */}
        <div className="text-center space-y-1 pb-4 border-b-2 border-slate-900">
          {institution?.logoUrl && (
            <img src={institution.logoUrl} alt="Logo" className="w-12 h-12 object-contain mx-auto mb-1" />
          )}
          <h1 className="text-xl sm:text-2xl font-bold uppercase tracking-wider text-slate-900">
            {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয়ের নাম') : (institution?.name || 'INSTITUTION NAME')}
          </h1>
          <p className="text-xs text-slate-600">
            {isBn ? (institution?.addressBn || institution?.address || '') : (institution?.address || '')}
            {institution?.eiin && ` | EIIN: ${institution.eiin}`}
          </p>
          <div className="inline-block mt-1 px-4 py-0.5 bg-slate-900 text-white rounded-full font-bold text-xs uppercase tracking-wider">
            {isBn ? BN_DICT['official_tabulation_sheet'] : EN_DICT['official_tabulation_sheet']}
          </div>
          <div className="text-xs font-bold text-slate-800 pt-1 flex items-center justify-center gap-4">
            <span>{isBn ? BN_DICT['exam'] : EN_DICT['exam']} {isBn ? (exam.nameBn || exam.name) : exam.name} ({exam.year})</span>
            <span>•</span>
            <span>{isBn ? BN_DICT['class_1'] : EN_DICT['class_1']} {className}</span>
            {sectionName && (
              <>
                <span>•</span>
                <span>{isBn ? BN_DICT['section_1'] : EN_DICT['section_1']} {sectionName}</span>
              </>
            )}
            {groupName && (
              <>
                <span>•</span>
                <span>{isBn ? BN_DICT['group_1'] : EN_DICT['group_1']} {groupName}</span>
              </>
            )}
          </div>
        </div>

        {/* Master Tabulation Table */}
        <div className="mt-4 overflow-x-auto">
          <table className="w-full border-collapse border border-slate-800 text-[10px] sm:text-[11px]">
            <thead>
              {/* Row 1: Subject Super Headers */}
              <tr className="bg-slate-100 text-slate-900 font-bold border-b border-slate-800 text-center">
                <th rowSpan={2} className="border border-slate-800 p-1.5 w-10">{isBn ? BN_DICT['rank'] : EN_DICT['rank']}</th>
                <th rowSpan={2} className="border border-slate-800 p-1.5 w-12">{isBn ? BN_DICT['roll'] : EN_DICT['roll']}</th>
                <th rowSpan={2} className="border border-slate-800 p-1.5 text-left min-w-[140px]">{isBn ? BN_DICT['student_name'] : EN_DICT['student_name']}</th>
                <th rowSpan={2} className="border border-slate-800 p-1.5 w-16 font-mono">{isBn ? BN_DICT['id_1'] : EN_DICT['id_1']}</th>

                {subjects.map(sub => (
                  <th key={sub.id} colSpan={2 + (sub.cqMarks ? 1 : 0) + (sub.mcqMarks ? 1 : 0) + (sub.practicalMarks ? 1 : 0)} className="border border-slate-800 p-1 bg-slate-50">
                    <div className="truncate max-w-[160px] mx-auto">{isBn ? (sub.nameBn || sub.name) : sub.name}</div>
                    <div className="text-[9px] font-normal text-slate-500">({sub.code} • {sub.fullMarks})</div>
                  </th>
                ))}

                <th colSpan={4} className="border border-slate-800 p-1 bg-slate-200/80">{isBn ? BN_DICT['overall_result'] : EN_DICT['overall_result']}</th>
              </tr>

              {/* Row 2: Sub-columns for each subject (CQ, MCQ, Prac, Total, GP) */}
              <tr className="bg-slate-50 text-slate-800 font-semibold border-b border-slate-800 text-center text-[9px]">
                {subjects.map(sub => (
                  <React.Fragment key={sub.id}>
                    {sub.cqMarks ? <th className="border border-slate-800 p-1 w-8">CQ</th> : null}
                    {sub.mcqMarks ? <th className="border border-slate-800 p-1 w-8">MCQ</th> : null}
                    {sub.practicalMarks ? <th className="border border-slate-800 p-1 w-8">Prac</th> : null}
                    <th className="border border-slate-800 p-1 w-9 font-bold bg-slate-100">{isBn ? BN_DICT['tot'] : EN_DICT['tot']}</th>
                    <th className="border border-slate-800 p-1 w-8">{isBn ? BN_DICT['gp'] : EN_DICT['gp']}</th>
                  </React.Fragment>
                ))}

                <th className="border border-slate-800 p-1 w-12 font-bold">{isBn ? BN_DICT['total_1'] : EN_DICT['total_1']}</th>
                <th className="border border-slate-800 p-1 w-11 font-bold">{isBn ? BN_DICT['gpa'] : EN_DICT['gpa']}</th>
                <th className="border border-slate-800 p-1 w-10 font-bold">{isBn ? BN_DICT['grd'] : EN_DICT['grd']}</th>
                <th className="border border-slate-800 p-1 w-12 font-bold">{isBn ? BN_DICT['status'] : EN_DICT['status']}</th>
              </tr>
            </thead>

            <tbody>
              {students.map((st) => {
                const sum = rankedSummaries.find(s => s.studentId === st.id);

                return (
                  <tr key={st.id} className="border-b border-slate-800 hover:bg-slate-50/70 text-center">
                    {/* Rank */}
                    <td className="border border-slate-800 p-1 font-mono font-bold text-indigo-900 bg-slate-50/50">
                      {sum?.isPassed ? (isBn ? toBengaliRank(sum.rank) : sum.rank) : '—'}
                    </td>

                    {/* Roll */}
                    <td className="border border-slate-800 p-1 font-mono font-bold text-slate-900">
                      {st.roll || '—'}
                    </td>

                    {/* Name */}
                    <td className="border border-slate-800 p-1 text-left font-semibold text-slate-900 px-2 truncate max-w-[160px]">
                      {isBn ? (st.nameBn || st.name) : st.name}
                    </td>

                    {/* ID */}
                    <td className="border border-slate-800 p-1 font-mono text-slate-500 text-[10px]">
                      {st.studentId || '—'}
                    </td>

                    {/* Subject scores */}
                    {subjects.map(sub => {
                      const rep = sum?.subjectReports.find(r => r.subject.id === sub.id || (sub.code && r.subject.code === sub.code));
                      const scores = rep?.scores || { cq: 0, mcq: 0, practical: 0, continuous: 0 };
                      const evalRes = rep?.evaluation;
                      const hasMarks = rep?.hasMarks;

                      return (
                        <React.Fragment key={sub.id}>
                          {sub.cqMarks ? (
                            <td className="border border-slate-800 p-1 font-mono text-slate-700">
                              {hasMarks ? scores.cq : '—'}
                            </td>
                          ) : null}
                          {sub.mcqMarks ? (
                            <td className="border border-slate-800 p-1 font-mono text-slate-700">
                              {hasMarks ? scores.mcq : '—'}
                            </td>
                          ) : null}
                          {sub.practicalMarks ? (
                            <td className="border border-slate-800 p-1 font-mono text-slate-700">
                              {hasMarks ? (scores.practical || '—') : '—'}
                            </td>
                          ) : null}
                          {/* Subject Total */}
                          <td className="border border-slate-800 p-1 font-mono font-bold text-slate-900 bg-slate-50/40">
                            {hasMarks ? evalRes?.total : '—'}
                          </td>
                          {/* Subject GP */}
                          <td className={`border border-slate-800 p-1 font-mono font-bold ${
                            !hasMarks ? 'text-slate-400' :
                            evalRes?.isPassed ? 'text-slate-900' : 'text-rose-700 bg-rose-50/50'
                          }`}>
                            {hasMarks ? (evalRes?.gpa.toFixed(1) ?? '0.0') : '—'}
                          </td>
                        </React.Fragment>
                      );
                    })}

                    {/* Overall Grand Total */}
                    <td className="border border-slate-800 p-1 font-mono font-bold text-slate-950 bg-slate-100/60">
                      {sum?.totalObtained ?? 0}
                    </td>

                    {/* Final GPA */}
                    <td className="border border-slate-800 p-1 font-mono font-bold text-slate-900">
                      {sum?.gpa.toFixed(2) ?? '0.00'}
                    </td>

                    {/* Final Grade */}
                    <td className="border border-slate-800 p-1 font-mono font-bold">
                      <span className={sum?.grade === 'F' ? 'text-rose-700' : 'text-slate-900'}>
                        {sum?.grade ?? '-'}
                      </span>
                    </td>

                    {/* Final Pass/Fail Status */}
                    <td className="border border-slate-800 p-1 font-bold">
                      {sum?.isPassed ? (
                        <span className="text-emerald-700 font-semibold">{isBn ? BN_DICT['pass'] : EN_DICT['pass']}</span>
                      ) : (
                        <span className="text-rose-700 font-semibold">{isBn ? BN_DICT['fail'] : EN_DICT['fail']}</span>
                      )}
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>

        {/* Signature Section */}
        <div className="mt-14 pt-4 grid grid-cols-3 text-center text-xs font-bold text-slate-800">
          <div className="space-y-1">
            <div className="w-32 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? BN_DICT['prepared_by'] : EN_DICT['prepared_by']}</div>
          </div>
          <div className="space-y-1">
            <div className="w-32 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? BN_DICT['class_teacher'] : EN_DICT['class_teacher']}</div>
          </div>
          <div className="space-y-1 flex flex-col items-center justify-end">
            {institution?.headmasterSignature ? (
              <img 
                src={institution.headmasterSignature} 
                alt="Principal Signature" 
                className="h-9 max-w-[140px] object-contain mx-auto -mb-1"
              />
            ) : null}
            <div className="w-36 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? (institution?.headmasterTitleBn || 'প্রধান শিক্ষক') : (institution?.headmasterTitle || 'Headmaster / Principal')}</div>
          </div>
        </div>
      </div>
    </div>
  );
};
