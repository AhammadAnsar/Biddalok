import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState } from 'react';
import { Printer, ChevronLeft, ChevronRight, User, Award, CheckCircle2, XCircle } from 'lucide-react';
import { 
  Student, 
  SubjectItem, 
  CurriculumSubjectMapping, 
  ExamResultEntry, 
  GradingRule, 
  ExamTerm, 
  Institution 
} from '../../types';
import { calculateStudentExamSummary, calculateClassMeritList, toBengaliRank, defaultFallbackGradingRules } from '../../utils/examCalculations';

interface StudentMarksheetCardProps {
  institution?: Institution;
  exam: ExamTerm;
  className: string;
  sectionName?: string;
  groupName?: string;
  sessionName?: string;
  subjects: (SubjectItem | CurriculumSubjectMapping)[];
  students: Student[];
  gradingRules: GradingRule[];
  examResults: ExamResultEntry[];
  initialStudentId?: string;
  isBn: boolean;
}

export const StudentMarksheetCard: React.FC<StudentMarksheetCardProps> = ({
  institution,
  exam,
  className,
  sectionName,
  groupName,
  sessionName,
  subjects,
  students,
  gradingRules,
  examResults,
  initialStudentId,
  isBn
}) => {
  const [selectedStudentId, setSelectedStudentId] = useState<string>(
    initialStudentId || (students[0]?.id ?? '')
  );

  const currentIndex = students.findIndex(s => s.id === selectedStudentId);
  const currentStudent = students[currentIndex] || students[0];

  // Pre-calculate ranks for all students so we can display student's merit position
  const rollsMap = React.useMemo(() => {
    const map: Record<string, number> = {};
    students.forEach(st => {
      map[st.id] = parseInt(st.roll || '999999') || 999999;
    });
    return map;
  }, [students]);

  const summaries = React.useMemo(() => {
    return students.map(st => 
      calculateStudentExamSummary(st.id, subjects, examResults, exam.id, gradingRules)
    );
  }, [students, subjects, examResults, exam.id, gradingRules]);

  const rankedStudents = React.useMemo(() => {
    return calculateClassMeritList(summaries, rollsMap);
  }, [summaries, rollsMap]);

  // Current student summary
  const studentSummary = React.useMemo(() => {
    if (!currentStudent) return null;
    return rankedStudents.find(r => r.studentId === currentStudent.id);
  }, [currentStudent, rankedStudents]);

  // Highest mark across cohort for each subject
  const highestMarksMap = React.useMemo(() => {
    const map: Record<string, number> = {};
    subjects.forEach(sub => {
      let maxScore = 0;
      examResults.forEach(r => {
        if (r.examId === exam.id && (r.subjectId === sub.id || (sub.code && r.subjectId === sub.code))) {
          const tot = r.totalMarksObtained || ((r.cqMarksObtained || 0) + (r.mcqMarksObtained || 0) + (r.practicalMarksObtained || 0));
          if (tot > maxScore) maxScore = tot;
        }
      });
      map[sub.id] = maxScore;
    });
    return map;
  }, [subjects, examResults, exam.id]);

  if (!currentStudent || !studentSummary) {
    return (
      <div className="text-center py-12 bg-white rounded-xl border border-slate-200 text-slate-500">
        {isBn ? BN_DICT['no_student_found'] : EN_DICT['no_student_found']}
      </div>
    );
  }

  return (
    <div className="space-y-6">
      {/* Student Navigation Control Bar (Hidden on Print) */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/90 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4 print:hidden">
        {/* Selector dropdown */}
        <div className="flex items-center gap-3">
          <label className="text-xs font-bold text-slate-700 whitespace-nowrap">
            {isBn ? BN_DICT['select_student'] : EN_DICT['select_student']}
          </label>
          <select
            value={selectedStudentId}
            onChange={(e) => setSelectedStudentId(e.target.value)}
            className="p-2 border border-slate-300 rounded-lg text-xs font-semibold text-slate-800 bg-white focus:ring-1 focus:ring-indigo-500"
          >
            {students.map(st => (
              <option key={st.id} value={st.id}>
                {isBn ? `রোল ${st.roll || '-'}: ${st.nameBn || st.name}` : `Roll ${st.roll || '-'}: ${st.name}`} ({st.studentId})
              </option>
            ))}
          </select>
        </div>

        {/* Prev / Next / Print */}
        <div className="flex items-center gap-2">
          <button
            onClick={() => {
              if (currentIndex > 0) setSelectedStudentId(students[currentIndex - 1].id);
            }}
            disabled={currentIndex <= 0}
            className="p-2 border border-slate-200 rounded-lg hover:bg-slate-50 disabled:opacity-40 disabled:cursor-not-allowed text-xs font-semibold flex items-center gap-1"
          >
            <ChevronLeft className="w-4 h-4" />
            <span className="hidden sm:inline">{isBn ? BN_DICT['prev'] : EN_DICT['prev']}</span>
          </button>

          <button
            onClick={() => {
              if (currentIndex < students.length - 1) setSelectedStudentId(students[currentIndex + 1].id);
            }}
            disabled={currentIndex >= students.length - 1}
            className="p-2 border border-slate-200 rounded-lg hover:bg-slate-50 disabled:opacity-40 disabled:cursor-not-allowed text-xs font-semibold flex items-center gap-1"
          >
            <span className="hidden sm:inline">{isBn ? BN_DICT['next'] : EN_DICT['next']}</span>
            <ChevronRight className="w-4 h-4" />
          </button>

          <button
            onClick={() => window.print()}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
          >
            <Printer className="w-4 h-4" />
            <span>{isBn ? BN_DICT['print_marksheet'] : EN_DICT['print_marksheet']}</span>
          </button>
        </div>
      </div>

      {/* Printable Marksheet Container */}
      <div className="bg-white p-6 sm:p-10 rounded-2xl border border-slate-300 shadow-sm print:p-0 print:border-none print:shadow-none text-slate-900 font-sans max-w-4xl mx-auto">
        {/* Official Header */}
        <div className="text-center space-y-1 pb-4 border-b-2 border-slate-900">
          {institution?.logoUrl && (
            <img src={institution.logoUrl} alt="Logo" className="w-16 h-16 object-contain mx-auto mb-1" />
          )}
          <h1 className="text-xl sm:text-2xl font-bold uppercase tracking-wide text-slate-900">
            {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয়ের নাম') : (institution?.name || 'INSTITUTION NAME')}
          </h1>
          <p className="text-xs text-slate-600">
            {isBn ? (institution?.addressBn || institution?.address || '') : (institution?.address || '')}
            {institution?.eiin && ` | EIIN: ${institution.eiin}`}
          </p>
          <div className="inline-block mt-2 px-5 py-1 bg-slate-900 text-white rounded-full font-bold text-xs uppercase tracking-wider">
            {isBn ? BN_DICT['academic_progress_report_marks'] : EN_DICT['academic_progress_report_marks']}
          </div>
          <div className="text-sm font-bold text-slate-800 pt-1">
            {isBn ? (exam.nameBn || exam.name) : exam.name} - {exam.year || '2026'}
          </div>
        </div>

        {/* Student Biodata & Grading Scale Box */}
        <div className="mt-4 grid grid-cols-1 md:grid-cols-3 gap-4 pb-4 border-b border-slate-300">
          {/* Student Info */}
          <div className="md:col-span-2 space-y-1.5 text-xs">
            <div className="grid grid-cols-3">
              <span className="text-slate-500 font-medium">{isBn ? BN_DICT['student_name_1'] : EN_DICT['student_name_1']}</span>
              <span className="col-span-2 font-bold text-slate-900 text-sm">
                {isBn ? (currentStudent.nameBn || currentStudent.name) : currentStudent.name}
              </span>
            </div>
            <div className="grid grid-cols-3">
              <span className="text-slate-500 font-medium">{isBn ? BN_DICT['student_id_1'] : EN_DICT['student_id_1']}</span>
              <span className="col-span-2 font-mono font-semibold text-slate-800">{currentStudent.studentId}</span>
            </div>
            <div className="grid grid-cols-3">
              <span className="text-slate-500 font-medium">{isBn ? BN_DICT['class_section'] : EN_DICT['class_section']}</span>
              <span className="col-span-2 font-semibold text-slate-800">
                {className} {sectionName ? `(শাখা: ${sectionName})` : ''}
              </span>
            </div>
            <div className="grid grid-cols-3">
              <span className="text-slate-500 font-medium">{isBn ? BN_DICT['roll_group'] : EN_DICT['roll_group']}</span>
              <span className="col-span-2 font-semibold text-slate-800">
                {isBn ? BN_DICT['roll_1'] : EN_DICT['roll_1']} {currentStudent.roll || '—'} {groupName ? `| বিভাগ: ${groupName}` : ''}
              </span>
            </div>
            <div className="grid grid-cols-3">
              <span className="text-slate-500 font-medium">{isBn ? BN_DICT['academic_session_2'] : EN_DICT['academic_session_2']}</span>
              <span className="col-span-2 font-semibold text-slate-800">{sessionName || exam.year}</span>
            </div>
          </div>

          {/* Mini Grading Scale Box */}
          <div className="border border-slate-300 rounded-lg p-2 text-[10px] bg-slate-50/50">
            <div className="font-bold text-slate-800 text-center pb-1 border-b border-slate-200">
              {isBn ? BN_DICT['grading_system'] : EN_DICT['grading_system']}
            </div>
            <div className="grid grid-cols-3 gap-1 pt-1 text-center font-mono">
              <div className="text-slate-500 font-sans">80-100</div>
              <div className="font-bold">A+</div>
              <div>5.00</div>
              <div className="text-slate-500 font-sans">70-79</div>
              <div className="font-bold">A</div>
              <div>4.00</div>
              <div className="text-slate-500 font-sans">60-69</div>
              <div className="font-bold">A-</div>
              <div>3.50</div>
              <div className="text-slate-500 font-sans">50-59</div>
              <div className="font-bold">B</div>
              <div>3.00</div>
              <div className="text-slate-500 font-sans">40-49</div>
              <div className="font-bold">C</div>
              <div>2.00</div>
              <div className="text-slate-500 font-sans">33-39</div>
              <div className="font-bold">D</div>
              <div>1.00</div>
              <div className="text-slate-500 font-sans">00-32</div>
              <div className="font-bold text-rose-600">F</div>
              <div className="text-rose-600">0.00</div>
            </div>
          </div>
        </div>

        {/* Detailed Subject Marks Table */}
        <div className="mt-4">
          <table className="w-full border-collapse border border-slate-800 text-xs">
            <thead>
              <tr className="bg-slate-100 text-slate-900 font-bold border-b border-slate-800 text-center">
                <th className="border border-slate-800 p-2 w-10">#</th>
                <th className="border border-slate-800 p-2 text-left">{isBn ? BN_DICT['subject_name'] : EN_DICT['subject_name']}</th>
                <th className="border border-slate-800 p-2 w-14">{isBn ? BN_DICT['full'] : EN_DICT['full']}</th>
                <th className="border border-slate-800 p-2 w-12">CQ</th>
                <th className="border border-slate-800 p-2 w-12">MCQ</th>
                <th className="border border-slate-800 p-2 w-12">{isBn ? BN_DICT['prac'] : EN_DICT['prac']}</th>
                <th className="border border-slate-800 p-2 w-16 font-bold bg-slate-200/60">{isBn ? BN_DICT['total_1'] : EN_DICT['total_1']}</th>
                <th className="border border-slate-800 p-2 w-14">{isBn ? BN_DICT['highest'] : EN_DICT['highest']}</th>
                <th className="border border-slate-800 p-2 w-14">{isBn ? BN_DICT['grade'] : EN_DICT['grade']}</th>
                <th className="border border-slate-800 p-2 w-14">{isBn ? BN_DICT['gp'] : EN_DICT['gp']}</th>
              </tr>
            </thead>

            <tbody>
              {studentSummary.subjectReports.map((rep, idx) => {
                const sub = rep.subject;
                const scores = rep.scores;
                const evalRes = rep.evaluation;
                const highest = highestMarksMap[sub.id] || evalRes.total;

                return (
                  <tr key={sub.id} className="border-b border-slate-800 text-center">
                    <td className="border border-slate-800 p-1.5 font-mono text-slate-500">{idx + 1}</td>
                    <td className="border border-slate-800 p-1.5 text-left font-semibold text-slate-900 px-3">
                      {isBn ? (sub.nameBn || sub.name) : sub.name}
                      {sub.isOptional && (
                        <span className="ml-1 text-[10px] text-amber-700 font-normal">
                          ({isBn ? BN_DICT['k_4th_subject'] : EN_DICT['k_4th_subject']})
                        </span>
                      )}
                    </td>
                    <td className="border border-slate-800 p-1.5 font-mono">{sub.fullMarks || 100}</td>
                    <td className="border border-slate-800 p-1.5 font-mono">{sub.cqMarks ? (rep.hasMarks ? scores.cq : '—') : '—'}</td>
                    <td className="border border-slate-800 p-1.5 font-mono">{sub.mcqMarks ? (rep.hasMarks ? scores.mcq : '—') : '—'}</td>
                    <td className="border border-slate-800 p-1.5 font-mono">{sub.practicalMarks ? (rep.hasMarks ? scores.practical : '—') : '—'}</td>
                    <td className="border border-slate-800 p-1.5 font-mono font-bold text-slate-950 bg-slate-50">
                      {rep.hasMarks ? evalRes.total : '—'}
                    </td>
                    <td className="border border-slate-800 p-1.5 font-mono text-slate-600">{highest}</td>
                    <td className={`border border-slate-800 p-1.5 font-mono font-bold ${
                      evalRes.grade === 'F' ? 'text-rose-700' : 'text-slate-900'
                    }`}>
                      {rep.hasMarks ? evalRes.grade : '—'}
                    </td>
                    <td className="border border-slate-800 p-1.5 font-mono font-bold text-slate-900">
                      {rep.hasMarks ? evalRes.gpa.toFixed(2) : '—'}
                    </td>
                  </tr>
                );
              })}
            </tbody>
          </table>
        </div>

        {/* Final Result Summary Cards */}
        <div className="mt-4 grid grid-cols-2 sm:grid-cols-4 gap-3 bg-slate-50 p-4 rounded-xl border border-slate-300">
          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['total_obtained_marks'] : EN_DICT['total_obtained_marks']}</div>
            <div className="text-base font-bold font-mono text-slate-900">
              {studentSummary.totalObtained} / {studentSummary.totalMaxMarks}
            </div>
          </div>

          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['grade_point_average'] : EN_DICT['grade_point_average']}</div>
            <div className="text-base font-bold font-mono text-indigo-950">
              {studentSummary.gpa.toFixed(2)}
            </div>
          </div>

          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['letter_grade'] : EN_DICT['letter_grade']}</div>
            <div className={`text-base font-bold font-mono ${studentSummary.grade === 'F' ? 'text-rose-700' : 'text-slate-900'}`}>
              {studentSummary.grade}
            </div>
          </div>

          <div>
            <div className="text-[11px] text-slate-500 font-medium">{isBn ? BN_DICT['rank_status'] : EN_DICT['rank_status']}</div>
            <div className="text-base font-bold text-slate-900 flex items-center gap-1.5">
              {studentSummary.isPassed ? (
                <>
                  <span className="text-indigo-950 font-mono">{isBn ? toBengaliRank(studentSummary.rank) : `#${studentSummary.rank}`}</span>
                  <span className="text-emerald-700 text-xs font-semibold">({isBn ? BN_DICT['passed'] : EN_DICT['passed']})</span>
                </>
              ) : (
                <span className="text-rose-700 text-sm font-semibold">{isBn ? BN_DICT['failed'] : EN_DICT['failed']}</span>
              )}
            </div>
          </div>
        </div>

        {/* Triple Official Signatures */}
        <div className="mt-16 pt-4 grid grid-cols-3 text-center text-xs font-bold text-slate-800">
          <div className="space-y-1">
            <div className="w-32 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? BN_DICT['guardian_signature'] : EN_DICT['guardian_signature']}</div>
          </div>
          <div className="space-y-1">
            <div className="w-32 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? BN_DICT['class_teacher'] : EN_DICT['class_teacher']}</div>
          </div>
          <div className="space-y-1 flex flex-col items-center justify-end">
            {institution?.headmasterSignature ? (
              <img 
                src={institution.headmasterSignature} 
                alt="Principal Signature" 
                className="h-9 max-w-[140px] object-contain mx-auto -mb-1"
              />
            ) : null}
            <div className="w-36 border-b border-slate-800 mx-auto"></div>
            <div>{isBn ? (institution?.headmasterTitleBn || 'অধ্যক্ষ / প্রধান শিক্ষক') : (institution?.headmasterTitle || 'Head of Institution')}</div>
          </div>
        </div>
      </div>
    </div>
  );
};
