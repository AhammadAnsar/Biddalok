import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { useAppStore } from '../store/useAppStore';
import { Trash2, AlertTriangle, CheckCircle, Search, Loader2, HardDrive, Database } from 'lucide-react';
import { JunkScanReport } from '../store/useAppStore';

export const JunkDataCleanup: React.FC = () => {
 const { language, students, scanJunkData, cleanJunkData } = useAppStore();
 const isBn = language === 'bn';

 const [isScanning, setIsScanning] = useState(false);
 const [isCleaning, setIsCleaning] = useState(false);
 const [dbReport, setDbReport] = useState<JunkScanReport | null>(null);
 
 const [orphanedFolders, setOrphanedFolders] = useState<{ id: string, size: number, count: number }[]>([]);
 const [mediaTotalSize, setMediaTotalSize] = useState(0);
 
 const [feedback, setFeedback] = useState<{ type: 'success' | 'error' | 'idle'; msg: string }>({ type: 'idle', msg: '' });

 const formatBytes = (bytes: number, decimals = 2) => {
 if (!+bytes) return '0 Bytes';
 const k = 1024;
 const dm = decimals < 0 ? 0 : decimals;
 const sizes = ['Bytes', 'KB', 'MB', 'GB', 'TB'];
 const i = Math.floor(Math.log(bytes) / Math.log(k));
 return `${parseFloat((bytes / Math.pow(k, i)).toFixed(dm))} ${sizes[i]}`;
 };

 const handleScan = async () => {
 setIsScanning(true);
 setFeedback({ type: 'idle', msg: '' });
 try {
 // 1. Scan DB
 const report = scanJunkData();
 setDbReport(report);

 // 2. Scan Media
 const validStudentIds = (students || []).map(s => s.studentId).filter(Boolean);
 const res = await fetch('/api/scan-orphaned-files', {
 method: 'POST',
 headers: { 'Content-Type': 'application/json' },
 body: JSON.stringify({ validStudentIds })
 });
 
 if (res.ok) {
 const data = await res.json();
 if (data.success) {
 setOrphanedFolders(data.orphanedFolders || []);
 setMediaTotalSize(data.totalSize || 0);
 }
 }
 } catch (err) {
 console.error(err);
 setFeedback({ type: 'error', msg: isBn ? BN_DICT['an_error_occurred_during_scann'] : EN_DICT['an_error_occurred_during_scann'] });
 } finally {
 setIsScanning(false);
 }
 };

 const handleCleanup = async () => {
 if (!window.confirm(isBn ? BN_DICT['are_you_sure_you_want_to_delet'] : EN_DICT['are_you_sure_you_want_to_delet'])) {
 return;
 }

 setIsCleaning(true);
 setFeedback({ type: 'idle', msg: '' });
 try {
 // 1. Clean DB
 cleanJunkData();

 // 2. Clean Media
 if (orphanedFolders.length > 0) {
 const orphanedIds = orphanedFolders.map(f => f.id);
 const res = await fetch('/api/delete-orphaned-files', {
 method: 'POST',
 headers: { 'Content-Type': 'application/json' },
 body: JSON.stringify({ orphanedIds })
 });
 
 if (res.ok) {
 const data = await res.json();
 if (!data.success) {
 console.error('Media cleanup failed:', data.message);
 }
 }
 }

 setFeedback({ type: 'success', msg: isBn ? BN_DICT['cleanup_completed_successfully'] : EN_DICT['cleanup_completed_successfully'] });
 
 // Rescan to show empty
 await handleScan();
 
 } catch (err) {
 console.error(err);
 setFeedback({ type: 'error', msg: isBn ? BN_DICT['an_error_occurred_during_clean'] : EN_DICT['an_error_occurred_during_clean'] });
 } finally {
 setIsCleaning(false);
 }
 };

 // Initial Scan
 useEffect(() => {
 handleScan();
 }, []);

 const totalDbIssues = dbReport ? dbReport.totalIssuesCount : 0;
 const hasJunk = totalDbIssues > 0 || orphanedFolders.length > 0;

 return (
 <div className="space-y-6">
 <div className="bg-white dark:bg-slate-900 rounded-2xl border border-slate-200/80 dark:border-slate-800 p-6 shadow-sm">
 <div className="flex flex-col sm:flex-row justify-between sm:items-start gap-4 mb-6">
 <div>
 <h3 className="text-lg font-bold text-slate-900 dark:text-slate-100 flex items-center gap-2">
 <Trash2 className="w-5 h-5 text-rose-500" />
 {isBn ? BN_DICT['junk_data_storage_cleanup'] : EN_DICT['junk_data_storage_cleanup']}
 </h3>
 <p className="text-sm text-slate-500 dark:text-slate-400 mt-1">
 {isBn ? BN_DICT['speed_up_the_system_by_removin'] : EN_DICT['speed_up_the_system_by_removin']}
 </p>
 </div>
 
 <div className="flex items-center gap-3">
 <button
 onClick={handleScan}
 disabled={isScanning || isCleaning}
 className="px-4 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 dark:bg-slate-800 dark:hover:bg-slate-700 dark:text-slate-200 rounded-xl font-medium text-sm transition-colors flex items-center gap-2 disabled:opacity-50"
 >
 {isScanning ? <Loader2 className="w-4 h-4 animate-spin" /> : <Search className="w-4 h-4" />}
 {isBn ? BN_DICT['rescan'] : EN_DICT['rescan']}
 </button>
 
 {hasJunk && (
 <button
 onClick={handleCleanup}
 disabled={isScanning || isCleaning}
 className="px-4 py-2 bg-rose-600 hover:bg-rose-700 text-white rounded-xl font-medium text-sm transition-colors flex items-center gap-2 shadow-sm shadow-rose-600/20 disabled:opacity-50"
 >
 {isCleaning ? <Loader2 className="w-4 h-4 animate-spin" /> : <Trash2 className="w-4 h-4" />}
 {isBn ? BN_DICT['clean_all_junk'] : EN_DICT['clean_all_junk']}
 </button>
 )}
 </div>
 </div>

 {feedback.type !== 'idle' && (
 <div className={`p-4 rounded-xl mb-6 flex items-start gap-3 ${feedback.type === 'success' ? 'bg-emerald-50 text-emerald-700 border border-emerald-200' : 'bg-rose-50 text-rose-700 border border-rose-200'}`}>
 {feedback.type === 'success' ? <CheckCircle className="w-5 h-5 mt-0.5 flex-shrink-0" /> : <AlertTriangle className="w-5 h-5 mt-0.5 flex-shrink-0" />}
 <p className="text-sm font-medium">{feedback.msg}</p>
 </div>
 )}

 <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
 {/* DB Junk Section */}
 <div className="border border-slate-200 dark:border-slate-800 rounded-xl p-5 bg-slate-50/50 dark:bg-slate-800/30">
 <h4 className="text-base font-bold text-slate-800 dark:text-slate-200 flex items-center gap-2 mb-4">
 <Database className="w-4 h-4 text-indigo-500" />
 {isBn ? BN_DICT['database_junk'] : EN_DICT['database_junk']}
 </h4>
 
 {isScanning ? (
 <div className="flex flex-col items-center justify-center py-8 text-slate-400">
 <Loader2 className="w-6 h-6 animate-spin mb-2" />
 <span className="text-sm">{isBn ? BN_DICT['scanning'] : EN_DICT['scanning']}</span>
 </div>
 ) : totalDbIssues > 0 ? (
 <div className="space-y-3">
 <div className="p-3 bg-rose-50/50 dark:bg-rose-900/10 border border-rose-100 dark:border-rose-800 rounded-lg flex items-center justify-between">
 <span className="text-sm text-rose-800 dark:text-rose-300 font-medium">
 {isBn ? BN_DICT['total_junk_found'] : EN_DICT['total_junk_found']}
 </span>
 <span className="text-sm font-bold text-rose-600 dark:text-rose-400 bg-rose-100 dark:bg-rose-900/30 px-2 py-0.5 rounded-md">
 {totalDbIssues}
 </span>
 </div>
 <div className="space-y-2 max-h-[250px] overflow-y-auto pr-2 custom-scrollbar">
 {dbReport?.details.map((detail, idx) => (
 <div key={idx} className="flex justify-between items-center text-sm p-2 hover:bg-white dark:hover:bg-slate-800 rounded-md transition-colors border border-transparent hover:border-slate-200 dark:hover:border-slate-700">
 <span className="text-slate-600 dark:text-slate-400">{isBn ? detail.categoryBn : detail.category}</span>
 <span className="font-medium text-slate-900 dark:text-slate-200">{detail.count}</span>
 </div>
 ))}
 </div>
 </div>
 ) : (
 <div className="flex flex-col items-center justify-center py-8 text-emerald-500">
 <CheckCircle className="w-10 h-10 mb-2 opacity-50" />
 <span className="text-sm font-medium">{isBn ? BN_DICT['no_database_junk_found'] : EN_DICT['no_database_junk_found']}</span>
 </div>
 )}
 </div>

 {/* Media Junk Section */}
 <div className="border border-slate-200 dark:border-slate-800 rounded-xl p-5 bg-slate-50/50 dark:bg-slate-800/30">
 <h4 className="text-base font-bold text-slate-800 dark:text-slate-200 flex items-center gap-2 mb-4">
 <HardDrive className="w-4 h-4 text-emerald-500" />
 {isBn ? BN_DICT['orphaned_media'] : EN_DICT['orphaned_media']}
 </h4>
 
 {isScanning ? (
 <div className="flex flex-col items-center justify-center py-8 text-slate-400">
 <Loader2 className="w-6 h-6 animate-spin mb-2" />
 <span className="text-sm">{isBn ? BN_DICT['scanning'] : EN_DICT['scanning']}</span>
 </div>
 ) : orphanedFolders.length > 0 ? (
 <div className="space-y-3">
 <div className="p-3 bg-amber-50/50 dark:bg-amber-900/10 border border-amber-100 dark:border-amber-800 rounded-lg flex items-center justify-between">
 <span className="text-sm text-amber-800 dark:text-amber-300 font-medium">
 {isBn ? BN_DICT['wasted_storage_space'] : EN_DICT['wasted_storage_space']}
 </span>
 <span className="text-sm font-bold text-amber-600 dark:text-amber-400 bg-amber-100 dark:bg-amber-900/30 px-2 py-0.5 rounded-md">
 {formatBytes(mediaTotalSize)}
 </span>
 </div>
 
 <p className="text-xs text-slate-500 dark:text-slate-400 pb-1 border-b border-slate-200 dark:border-slate-700">
 {isBn 
 ? `${orphanedFolders.length} জন শিক্ষার্থীর ফোল্ডার পাওয়া গেছে যাদের ডাটাবেজে কোনো রেকর্ড নেই।` 
 : `Found ${orphanedFolders.length} student folders with no corresponding database records.`}
 </p>

 <div className="space-y-2 max-h-[200px] overflow-y-auto pr-2 custom-scrollbar">
 {orphanedFolders.map((folder, idx) => (
 <div key={idx} className="flex justify-between items-center text-sm p-2 hover:bg-white dark:hover:bg-slate-800 rounded-md transition-colors border border-transparent hover:border-slate-200 dark:hover:border-slate-700">
 <span className="text-slate-600 dark:text-slate-400 font-mono text-xs">ID: {folder.id} ({folder.count} files)</span>
 <span className="font-medium text-slate-900 dark:text-slate-200">{formatBytes(folder.size)}</span>
 </div>
 ))}
 </div>
 </div>
 ) : (
 <div className="flex flex-col items-center justify-center py-8 text-emerald-500">
 <CheckCircle className="w-10 h-10 mb-2 opacity-50" />
 <span className="text-sm font-medium">{isBn ? BN_DICT['storage_is_clean'] : EN_DICT['storage_is_clean']}</span>
 </div>
 )}
 </div>
 </div>
 </div>
 </div>
 );
};
