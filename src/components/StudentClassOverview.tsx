import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useMemo, useState } from 'react';
import { useAppStore } from '../store/useAppStore';
import { translations } from '../locales';
import { BarChart3, ChevronDown, ChevronUp, Users, LayoutGrid, Table as TableIcon } from 'lucide-react';
import { toBengaliNumber, getBengaliClassName, getBengaliGroup } from '../utils/bengaliUtils';
import { findClass, findGroup, findSection, isSessionMatch } from '../utils/academicRelations';

interface StudentClassOverviewProps {
  isDashboardMode?: boolean;
}

export const StudentClassOverview: React.FC<StudentClassOverviewProps> = ({ isDashboardMode = false }) => {
  const language = useAppStore(state => state.language);
  const students = useAppStore(state => state.students);
  const institution = useAppStore(state => state.institution);
  const academicClasses = useAppStore(state => state.academicClasses);
  const academicGroups = useAppStore(state => state.academicGroups);
  const academicSections = useAppStore(state => state.academicSections);
  const isBn = language === 'bn';
  const t = translations[language];

  // Default to expanded
  const [isExpanded, setIsExpanded] = useState(true);
  const [viewMode, setViewMode] = useState<'table' | 'cards'>('table');

  // Extract available years from students and configuration
  const availableYears = useMemo(() => {
    const years = new Set<string>();
    const currentYr = new Date().getFullYear().toString();
    years.add(currentYr);
    years.add((new Date().getFullYear() - 1).toString());
    years.add((new Date().getFullYear() + 1).toString());
    if (institution?.defaultYear) years.add(institution.defaultYear);
    (students || []).forEach(s => {
      if (s.year) years.add(s.year);
      else if (s.session && /^\d{4}/.test(s.session)) {
        years.add(s.session.slice(0, 4));
      }
    });
    const sorted = Array.from(years).sort((a, b) => b.localeCompare(a));
    return sorted;
  }, [students, institution?.defaultYear]);

  // Default to institution defaultYear or current year or latest available year
  const defaultYear = institution?.defaultYear || new Date().getFullYear().toString();
  const initialYear = availableYears.includes(defaultYear) 
    ? defaultYear 
    : (availableYears.length > 0 ? availableYears[0] : defaultYear);

  const [selectedYear, setSelectedYear] = useState<string>(initialYear);

  // Keep synced if institution defaultYear changes and not manually overridden
  React.useEffect(() => {
    if (institution?.defaultYear && !availableYears.includes(selectedYear)) {
      setSelectedYear(institution.defaultYear);
    }
  }, [institution?.defaultYear, availableYears, selectedYear]);

  // Localization Helpers
  const getLocClassName = (name: string) => {
    if (!name) return isBn ? BN_DICT['unassigned'] : EN_DICT['unassigned'];
    return isBn ? getBengaliClassName(name) : name;
  };

  const getLocGroupName = (name: string) => {
    if (!name || name === 'সাধারণ' || name === 'General') return isBn ? BN_DICT['general'] : EN_DICT['general'];
    return isBn ? getBengaliGroup(name) : name;
  };

  const getLocSectionName = (name: string) => {
    if (!name) return isBn ? BN_DICT['all'] : EN_DICT['all'];
    return name;
  };

  // Structured Aggregation Engine
  const { renderRows, grandTotal, classCards } = useMemo(() => {
    const initStats = () => ({
      studying: { m: 0, f: 0, t: 0 },
      stipend: { m: 0, f: 0, t: 0 },
      scholarship: { m: 0, f: 0, t: 0 },
      repeater: { m: 0, f: 0, t: 0 },
      transfer: { in: 0, out: 0 }
    });

    const mergeStats = (target: ReturnType<typeof initStats>, source: ReturnType<typeof initStats>) => {
      return {
        studying: {
          m: target.studying.m + source.studying.m,
          f: target.studying.f + source.studying.f,
          t: target.studying.t + source.studying.t,
        },
        stipend: {
          m: target.stipend.m + source.stipend.m,
          f: target.stipend.f + source.stipend.f,
          t: target.stipend.t + source.stipend.t,
        },
        scholarship: {
          m: target.scholarship.m + source.scholarship.m,
          f: target.scholarship.f + source.scholarship.f,
          t: target.scholarship.t + source.scholarship.t,
        },
        repeater: {
          m: target.repeater.m + source.repeater.m,
          f: target.repeater.f + source.repeater.f,
          t: target.repeater.t + source.repeater.t,
        },
        transfer: {
          in: target.transfer.in + source.transfer.in,
          out: target.transfer.out + source.transfer.out,
        }
      };
    };

    // Filter active students for selected academic year
    const yearStudents = (students || []).filter(s => {
      if (s.status === 'archived' || s.status === 'passed_out' || s.status === 'dropped_out') {
        return false;
      }
      return isSessionMatch(s, selectedYear);
    });

    // Determine Canonical Class List
    const configuredClasses = (academicClasses || [])
      .filter(c => c.status !== 'inactive')
      .sort((a, b) => (a.orderIndex || 0) - (b.orderIndex || 0));

    const allClassesSet = new Set<string>();
    configuredClasses.forEach(c => allClassesSet.add(c.name));
    yearStudents.forEach(s => {
      const cObj = findClass(s.classId || s.class, academicClasses);
      allClassesSet.add(cObj?.name || s.class || 'Unassigned');
    });

    const sortedClasses = Array.from(allClassesSet).sort((a, b) => {
      const cA = configuredClasses.find(c => c.name === a);
      const cB = configuredClasses.find(c => c.name === b);
      if (cA && cB) return (cA.orderIndex || 0) - (cB.orderIndex || 0);
      if (cA) return -1;
      if (cB) return 1;
      return a.localeCompare(b);
    });

    let gTotal = initStats();
    const rows: Array<{
      isFirstInClass: boolean;
      rowSpan: number;
      className: string;
      groupName: string;
      sectionName: string;
      stats: ReturnType<typeof initStats>;
      isSubtotal: boolean;
      isLastInBlock: boolean;
    }> = [];

    const cardsData: Array<{
      className: string;
      stats: ReturnType<typeof initStats>;
      groupsCount: number;
      sectionsCount: number;
    }> = [];

    sortedClasses.forEach((className) => {
      const cStudents = yearStudents.filter(s => {
        const cObj = findClass(s.classId || s.class, academicClasses);
        const resolvedName = cObj?.name || s.class || 'Unassigned';
        return resolvedName === className;
      });

      if (cStudents.length === 0 && !configuredClasses.some(c => c.name === className)) {
        return;
      }

      let classTotalStats = initStats();
      const groupsMap = new Map<string, Map<string, typeof cStudents>>();

      cStudents.forEach(s => {
        const gObj = findGroup(s.groupId || s.group, academicGroups);
        const gName = gObj?.name || s.group || 'General';
        const secObj = findSection(s.sectionId || s.section, academicSections);
        const sName = secObj?.name || s.section || '';

        if (!groupsMap.has(gName)) {
          groupsMap.set(gName, new Map());
        }
        const secMap = groupsMap.get(gName)!;
        if (!secMap.has(sName)) {
          secMap.set(sName, []);
        }
        secMap.get(sName)!.push(s);
      });

      if (groupsMap.size === 0) {
        groupsMap.set('General', new Map([['', []]]));
      }

      const classRowsData: Array<{
        groupName: string;
        sectionName: string;
        stats: ReturnType<typeof initStats>;
      }> = [];

      groupsMap.forEach((secMap, groupName) => {
        secMap.forEach((studs, sectionName) => {
          const stats = initStats();

          studs.forEach(s => {
            const gender = (s.gender || '').toLowerCase();
            const isM = gender === 'male' || gender === 'পুরুষ' || gender === 'm';
            const isF = gender === 'female' || gender === 'মহিলা' || gender === 'f';

            stats.studying.t++;
            if (isM) stats.studying.m++;
            else if (isF) stats.studying.f++;

            const isStipend = !!(s.stipendEligible || s.isStipend || s.stipend);
            const isScholarship = !!(s.hasScholarship || s.isScholarship || s.scholarship);

            if (isStipend) {
              if (isM) { stats.stipend.m++; stats.stipend.t++; }
              if (isF) { stats.stipend.f++; stats.stipend.t++; }
            }
            if (isScholarship) {
              if (isM) { stats.scholarship.m++; stats.scholarship.t++; }
              if (isF) { stats.scholarship.f++; stats.scholarship.t++; }
            }
            
            if (s.prevTcNo) {
              stats.transfer.in++;
            }
          });

          classTotalStats = mergeStats(classTotalStats, stats);
          gTotal = mergeStats(gTotal, stats);

          classRowsData.push({
            groupName: groupName || '',
            sectionName: sectionName || '',
            stats
          });
        });
      });

      const needsSubtotal = classRowsData.length > 1;
      const rowSpan = needsSubtotal ? classRowsData.length + 1 : classRowsData.length;

      classRowsData.forEach((rData, idx) => {
        rows.push({
          isFirstInClass: idx === 0,
          rowSpan: idx === 0 ? rowSpan : 0,
          className: getLocClassName(className),
          groupName: getLocGroupName(rData.groupName),
          sectionName: getLocSectionName(rData.sectionName),
          stats: rData.stats,
          isSubtotal: false,
          isLastInBlock: !needsSubtotal && idx === classRowsData.length - 1
        });
      });

      if (needsSubtotal) {
        rows.push({
          isFirstInClass: false,
          rowSpan: 0,
          className: getLocClassName(className),
          groupName: isBn ? BN_DICT['subtotal'] : EN_DICT['subtotal'],
          sectionName: '',
          stats: classTotalStats,
          isSubtotal: true,
          isLastInBlock: true
        });
      }

      cardsData.push({
        className: getLocClassName(className),
        stats: classTotalStats,
        groupsCount: groupsMap.size,
        sectionsCount: classRowsData.length
      });
    });

    return { renderRows: rows, grandTotal: gTotal, classCards: cardsData };
  }, [students, selectedYear, academicClasses, academicGroups, academicSections, isBn]);

  const numFormat = (num: number) => {
    if (num === 0) return isBn ? BN_DICT['k_0'] : EN_DICT['k_0'];
    return isBn ? toBengaliNumber(num) : num.toString();
  };

  const showContent = isDashboardMode ? true : isExpanded;

  return (
    <div className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden mb-6">
      {/* Header / Toggle bar */}
      <div 
        className={`px-4 sm:px-5 py-3.5 sm:py-4 flex flex-wrap items-center justify-between gap-3 ${!isDashboardMode ? 'border-b border-slate-200 bg-slate-50/80 hover:bg-slate-100 transition-colors' : 'border-b border-slate-100'}`}
      >
        <div 
          className="flex items-center gap-3 cursor-pointer flex-1 min-w-[220px]"
          onClick={() => {
            if (!isDashboardMode) setIsExpanded(!isExpanded);
          }}
        >
          <div className="w-9 h-9 rounded-xl bg-emerald-100 flex items-center justify-center text-emerald-700 shadow-xs flex-shrink-0">
            <BarChart3 className="w-5 h-5" />
          </div>
          <div>
            <h2 className="text-sm sm:text-base font-bold text-slate-900 leading-tight">
              {isBn ? BN_DICT['class_wise_student_statistics'] : EN_DICT['class_wise_student_statistics']}
            </h2>
            <p className="text-xs text-slate-500 font-medium mt-0.5">
              {isBn 
                ? `${toBengaliNumber(selectedYear)} শিক্ষাবর্ষের পরিসংখ্যান` 
                : `Class-wise statistics for ${selectedYear}`}
            </p>
          </div>
        </div>
        
        <div className="flex items-center gap-2">
          {/* View Toggle: Table vs Cards (Accessible alternative to horizontal scroll) */}
          <div className="inline-flex rounded-xl border border-slate-200 bg-white p-0.5 shadow-2xs">
            <button
              onClick={(e) => {
                e.stopPropagation();
                setViewMode('table');
              }}
              className={`p-1.5 sm:px-2.5 sm:py-1 rounded-lg text-xs font-semibold flex items-center gap-1.5 transition-all cursor-pointer min-h-[36px] ${
                viewMode === 'table'
                  ? 'bg-indigo-600 text-white shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
              title={isBn ? BN_DICT['table_view'] : EN_DICT['table_view']}
              aria-label={isBn ? BN_DICT['table_view'] : EN_DICT['table_view']}
            >
              <TableIcon className="w-4 h-4" />
              <span className="hidden sm:inline">{isBn ? BN_DICT['table'] : EN_DICT['table']}</span>
            </button>
            <button
              onClick={(e) => {
                e.stopPropagation();
                setViewMode('cards');
              }}
              className={`p-1.5 sm:px-2.5 sm:py-1 rounded-lg text-xs font-semibold flex items-center gap-1.5 transition-all cursor-pointer min-h-[36px] ${
                viewMode === 'cards'
                  ? 'bg-indigo-600 text-white shadow-xs'
                  : 'text-slate-600 hover:text-slate-900'
              }`}
              title={isBn ? BN_DICT['card_view'] : EN_DICT['card_view']}
              aria-label={isBn ? BN_DICT['card_view'] : EN_DICT['card_view']}
            >
              <LayoutGrid className="w-4 h-4" />
              <span className="hidden sm:inline">{isBn ? BN_DICT['cards'] : EN_DICT['cards']}</span>
            </button>
          </div>

          {!isDashboardMode && (
            <button 
              onClick={() => setIsExpanded(!isExpanded)}
              className="w-9 h-9 flex items-center justify-center rounded-xl hover:bg-slate-200 text-slate-500 transition-colors cursor-pointer"
              aria-label={isExpanded ? (isBn ? BN_DICT['collapse'] : EN_DICT['collapse']) : (isBn ? BN_DICT['expand'] : EN_DICT['expand'])}
            >
              {isExpanded ? <ChevronUp className="w-5 h-5" /> : <ChevronDown className="w-5 h-5" />}
            </button>
          )}
        </div>
      </div>

      {/* Expanded Content */}
      {showContent && (
        <div className="p-4 sm:p-5">
          {/* Filters - Hidden in Dashboard Mode */}
          {!isDashboardMode && (
            <div className="flex items-center gap-3 mb-4">
              <label className="text-xs sm:text-sm font-bold text-slate-700 bg-slate-100 px-3 py-1.5 rounded-lg border border-slate-200">
                {isBn ? BN_DICT['academic_year_2'] : EN_DICT['academic_year_2']}
              </label>
              <div className="relative">
                <select 
                  value={selectedYear}
                  onChange={(e) => setSelectedYear(e.target.value)}
                  className="appearance-none pl-3 pr-8 py-1.5 border border-slate-300 rounded-lg text-xs sm:text-sm font-semibold bg-white text-indigo-700 focus:ring-2 focus:ring-indigo-500 outline-none shadow-2xs cursor-pointer hover:border-indigo-400 transition-colors min-h-[38px]"
                >
                  {availableYears.length > 0 ? availableYears.map(year => (
                    <option key={year} value={year}>{isBn ? toBengaliNumber(year) : year}</option>
                  )) : (
                    <option value={selectedYear}>{isBn ? toBengaliNumber(selectedYear) : selectedYear}</option>
                  )}
                </select>
                <ChevronDown className="w-4 h-4 text-slate-400 absolute right-2.5 top-1/2 -translate-y-1/2 pointer-events-none" />
              </div>
            </div>
          )}

          {/* View Mode: Cards (Perfect for mobile 360px - 768px screens without horizontal scroll) */}
          {viewMode === 'cards' ? (
            <div className="space-y-4">
              <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 xl:grid-cols-4 gap-3.5">
                {classCards.map((card, idx) => (
                  <div 
                    key={idx}
                    className="p-4 rounded-xl border border-slate-200 bg-white shadow-2xs hover:shadow-xs transition-shadow"
                  >
                    <div className="flex items-center justify-between pb-2.5 mb-2.5 border-b border-slate-100">
                      <span className="font-bold text-slate-900 text-sm">{card.className}</span>
                      <span className="text-xs font-bold px-2 py-0.5 rounded-full bg-indigo-50 text-indigo-700">
                        {numFormat(card.stats.studying.t)} {isBn ? BN_DICT['students'] : EN_DICT['students']}
                      </span>
                    </div>
                    <div className="grid grid-cols-2 gap-2 text-xs">
                      <div className="p-2 rounded-lg bg-slate-50 border border-slate-100">
                        <div className="text-slate-500 text-[11px]">{isBn ? BN_DICT['boys_girls'] : EN_DICT['boys_girls']}</div>
                        <div className="font-semibold text-slate-800 mt-0.5">
                          {numFormat(card.stats.studying.m)} / {numFormat(card.stats.studying.f)}
                        </div>
                      </div>
                      <div className="p-2 rounded-lg bg-emerald-50/50 border border-emerald-100">
                        <div className="text-emerald-700 text-[11px]">{isBn ? BN_DICT['stipend'] : EN_DICT['stipend']}</div>
                        <div className="font-semibold text-emerald-800 mt-0.5">
                          {numFormat(card.stats.stipend.t)}
                        </div>
                      </div>
                      <div className="p-2 rounded-lg bg-amber-50/50 border border-amber-100">
                        <div className="text-amber-700 text-[11px]">{isBn ? BN_DICT['scholarship'] : EN_DICT['scholarship']}</div>
                        <div className="font-semibold text-amber-800 mt-0.5">
                          {numFormat(card.stats.scholarship.t)}
                        </div>
                      </div>
                      <div className="p-2 rounded-lg bg-rose-50/50 border border-rose-100">
                        <div className="text-rose-700 text-[11px]">{isBn ? BN_DICT['repeater'] : EN_DICT['repeater']}</div>
                        <div className="font-semibold text-rose-800 mt-0.5">
                          {numFormat(card.stats.repeater.t)}
                        </div>
                      </div>
                    </div>
                  </div>
                ))}
              </div>

              {/* Mobile Grand Total Summary Card */}
              <div className="p-4 rounded-xl bg-slate-900 text-white shadow-sm">
                <div className="flex items-center justify-between pb-2 mb-3 border-b border-slate-800">
                  <span className="font-bold text-sm">{isBn ? BN_DICT['grand_total_summary'] : EN_DICT['grand_total_summary']}</span>
                  <span className="text-sm font-bold text-indigo-300">
                    {numFormat(grandTotal.studying.t)} {isBn ? BN_DICT['students'] : EN_DICT['students']}
                  </span>
                </div>
                <div className="grid grid-cols-2 sm:grid-cols-4 gap-2 text-xs">
                  <div>
                    <span className="text-slate-400 text-[11px] block">{isBn ? BN_DICT['boys_girls_1'] : EN_DICT['boys_girls_1']}</span>
                    <span className="font-bold text-white mt-0.5 block">{numFormat(grandTotal.studying.m)} / {numFormat(grandTotal.studying.f)}</span>
                  </div>
                  <div>
                    <span className="text-emerald-400 text-[11px] block">{isBn ? BN_DICT['stipend_1'] : EN_DICT['stipend_1']}</span>
                    <span className="font-bold text-emerald-300 mt-0.5 block">{numFormat(grandTotal.stipend.t)}</span>
                  </div>
                  <div>
                    <span className="text-amber-400 text-[11px] block">{isBn ? BN_DICT['scholarship_1'] : EN_DICT['scholarship_1']}</span>
                    <span className="font-bold text-amber-300 mt-0.5 block">{numFormat(grandTotal.scholarship.t)}</span>
                  </div>
                  <div>
                    <span className="text-rose-400 text-[11px] block">{isBn ? BN_DICT['repeater_1'] : EN_DICT['repeater_1']}</span>
                    <span className="font-bold text-rose-300 mt-0.5 block">{numFormat(grandTotal.repeater.t)}</span>
                  </div>
                </div>
              </div>
            </div>
          ) : (
            /* Complex Table with safe responsive horizontal scrolling */
            <div className="overflow-x-auto rounded-xl border border-slate-300 shadow-2xs">
              <table className="w-full text-center text-xs text-slate-700 border-collapse min-w-[700px]">
                <thead className="bg-slate-100 text-slate-800 font-bold border-b-2 border-slate-300">
                  <tr>
                    <th rowSpan={2} className="px-3 py-2 border-r border-b border-slate-300 align-middle bg-slate-50 w-20">{isBn ? BN_DICT['class_2'] : EN_DICT['class_2']}</th>
                    <th rowSpan={2} className="px-3 py-2 border-r border-b border-slate-300 align-middle bg-slate-50 w-24">{isBn ? BN_DICT['group_2'] : EN_DICT['group_2']}</th>
                    <th rowSpan={2} className="px-3 py-2 border-r border-b border-slate-300 align-middle bg-slate-50 w-20">{isBn ? BN_DICT['section_2'] : EN_DICT['section_2']}</th>
                    
                    <th colSpan={3} className="px-2 py-2 border-r border-b border-slate-300 bg-indigo-50/50 text-indigo-900 border-b-indigo-200">{isBn ? BN_DICT['studying'] : EN_DICT['studying']}</th>
                    <th colSpan={3} className="px-2 py-2 border-r border-b border-slate-300 bg-emerald-50/50 text-emerald-900 border-b-emerald-200">{isBn ? BN_DICT['stipend'] : EN_DICT['stipend']}</th>
                    <th colSpan={3} className="px-2 py-2 border-r border-b border-slate-300 bg-amber-50/50 text-amber-900 border-b-amber-200">{isBn ? BN_DICT['scholarship'] : EN_DICT['scholarship']}</th>
                    <th colSpan={3} className="px-2 py-2 border-r border-b border-slate-300 bg-rose-50/50 text-rose-900 border-b-rose-200">{isBn ? BN_DICT['repeater'] : EN_DICT['repeater']}</th>
                    <th colSpan={2} className="px-2 py-2 border-b border-slate-300 bg-sky-50/50 text-sky-900 border-b-sky-200">{isBn ? BN_DICT['transfer'] : EN_DICT['transfer']}</th>
                  </tr>
                  <tr className="bg-white">
                    {/* Studying */}
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-indigo-50/30 text-indigo-700">{isBn ? BN_DICT['m'] : EN_DICT['m']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-indigo-50/30 text-indigo-700">{isBn ? BN_DICT['f'] : EN_DICT['f']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-bold bg-indigo-100/50 text-indigo-800">{isBn ? BN_DICT['t'] : EN_DICT['t']}</th>
                    
                    {/* Stipend */}
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-emerald-50/30 text-emerald-700">{isBn ? BN_DICT['m'] : EN_DICT['m']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-emerald-50/30 text-emerald-700">{isBn ? BN_DICT['f'] : EN_DICT['f']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-bold bg-emerald-100/50 text-emerald-800">{isBn ? BN_DICT['t'] : EN_DICT['t']}</th>

                    {/* Scholarship */}
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-amber-50/30 text-amber-700">{isBn ? BN_DICT['m'] : EN_DICT['m']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-amber-50/30 text-amber-700">{isBn ? BN_DICT['f'] : EN_DICT['f']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-bold bg-amber-100/50 text-amber-800">{isBn ? BN_DICT['t'] : EN_DICT['t']}</th>

                    {/* Repeater */}
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-rose-50/30 text-rose-700">{isBn ? BN_DICT['m'] : EN_DICT['m']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-rose-50/30 text-rose-700">{isBn ? BN_DICT['f'] : EN_DICT['f']}</th>
                    <th className="px-2 py-1.5 border-r border-slate-300 font-bold bg-rose-100/50 text-rose-800">{isBn ? BN_DICT['t'] : EN_DICT['t']}</th>

                    {/* Transfer */}
                    <th className="px-2 py-1.5 border-r border-slate-300 font-semibold bg-sky-50/30 text-sky-700">{isBn ? BN_DICT['in'] : EN_DICT['in']}</th>
                    <th className="px-2 py-1.5 font-semibold bg-sky-50/30 text-sky-700">{isBn ? BN_DICT['out'] : EN_DICT['out']}</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-200 bg-white font-medium">
                  {renderRows.length > 0 ? renderRows.map((row, idx) => {
                    const isSub = row.isSubtotal;
                    const rowBg = isSub 
                      ? 'bg-indigo-50/40 font-bold text-slate-800' 
                      : (idx % 2 === 0 ? 'bg-white hover:bg-slate-50/70' : 'bg-slate-50/40 hover:bg-slate-100/60');
                    const bBottom = row.isLastInBlock ? 'border-b-2 border-slate-300' : 'border-b border-slate-200';

                    return (
                      <tr key={idx} className={`${rowBg} transition-colors`}>
                        {row.isFirstInClass && (
                          <td 
                            rowSpan={row.rowSpan} 
                            className="px-3 py-2.5 font-bold border-r border-slate-300 align-middle bg-white text-slate-900 border-b-2"
                          >
                            {row.className}
                          </td>
                        )}

                        {isSub ? (
                          <td colSpan={2} className={`px-3 py-2 border-r border-slate-300 ${bBottom} text-right pr-4 text-indigo-900`}>
                            {row.groupName}
                          </td>
                        ) : (
                          <>
                            <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-600`}>{row.groupName}</td>
                            <td className={`px-2 py-2 border-r border-slate-300 ${bBottom} text-slate-600`}>{row.sectionName}</td>
                          </>
                        )}

                        {/* Studying Stats */}
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-600`}>{numFormat(row.stats.studying.m)}</td>
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-600`}>{numFormat(row.stats.studying.f)}</td>
                        <td className={`px-2 py-2 border-r border-slate-300 ${bBottom} ${isSub ? 'text-indigo-700 bg-indigo-100/30' : 'font-bold text-slate-900 bg-slate-50/50'}`}>
                          {numFormat(row.stats.studying.t)}
                        </td>

                        {/* Stipend Stats */}
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-500`}>{numFormat(row.stats.stipend.m)}</td>
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-500`}>{numFormat(row.stats.stipend.f)}</td>
                        <td className={`px-2 py-2 border-r border-slate-300 ${bBottom} ${isSub ? 'text-emerald-700' : 'font-bold text-slate-700 bg-slate-50/50'}`}>
                          {numFormat(row.stats.stipend.t)}
                        </td>

                        {/* Scholarship Stats */}
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-500`}>{numFormat(row.stats.scholarship.m)}</td>
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-500`}>{numFormat(row.stats.scholarship.f)}</td>
                        <td className={`px-2 py-2 border-r border-slate-300 ${bBottom} ${isSub ? 'text-amber-700' : 'font-bold text-slate-700 bg-slate-50/50'}`}>
                          {numFormat(row.stats.scholarship.t)}
                        </td>

                        {/* Repeater Stats */}
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-500`}>{numFormat(row.stats.repeater.m)}</td>
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-500`}>{numFormat(row.stats.repeater.f)}</td>
                        <td className={`px-2 py-2 border-r border-slate-300 ${bBottom} ${isSub ? 'text-rose-700' : 'font-bold text-slate-700 bg-slate-50/50'}`}>
                          {numFormat(row.stats.repeater.t)}
                        </td>

                        {/* Transfer Stats */}
                        <td className={`px-2 py-2 border-r border-slate-200 ${bBottom} text-slate-500`}>{numFormat(row.stats.transfer.in)}</td>
                        <td className={`px-2 py-2 ${bBottom} text-slate-500`}>{numFormat(row.stats.transfer.out)}</td>
                      </tr>
                    );
                  }) : (
                    <tr>
                      <td colSpan={17} className="px-3 py-12 text-center">
                        <div className="flex flex-col items-center justify-center text-slate-400">
                          <Users className="w-10 h-10 mb-2 text-slate-300" />
                          <span className="font-medium">
                            {isBn 
                              ? `${toBengaliNumber(selectedYear)} সালের জন্য কোন শিক্ষার্থীর তথ্য পাওয়া যায়নি।` 
                              : `No student records found for year ${selectedYear}.`}
                          </span>
                        </div>
                      </td>
                    </tr>
                  )}

                  {/* Grand Total Row */}
                  {renderRows.length > 0 && (
                    <tr className="bg-slate-800 text-white font-bold text-xs sm:text-sm">
                      <td colSpan={3} className="px-4 py-3 text-right border-r border-slate-600">
                        {isBn ? BN_DICT['grand_total'] : EN_DICT['grand_total']}
                      </td>
                      
                      {/* Studying Total */}
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.studying.m)}</td>
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.studying.f)}</td>
                      <td className="px-2 py-3 border-r border-slate-600 text-indigo-300">{numFormat(grandTotal.studying.t)}</td>

                      {/* Stipend Total */}
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.stipend.m)}</td>
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.stipend.f)}</td>
                      <td className="px-2 py-3 border-r border-slate-600 text-emerald-300">{numFormat(grandTotal.stipend.t)}</td>

                      {/* Scholarship Total */}
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.scholarship.m)}</td>
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.scholarship.f)}</td>
                      <td className="px-2 py-3 border-r border-slate-600 text-amber-300">{numFormat(grandTotal.scholarship.t)}</td>

                      {/* Repeater Total */}
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.repeater.m)}</td>
                      <td className="px-2 py-3 border-r border-slate-700/50">{numFormat(grandTotal.repeater.f)}</td>
                      <td className="px-2 py-3 border-r border-slate-600 text-rose-300">{numFormat(grandTotal.repeater.t)}</td>

                      {/* Transfer Total */}
                      <td className="px-2 py-3 border-r border-slate-700/50 text-sky-300">{numFormat(grandTotal.transfer.in)}</td>
                      <td className="px-2 py-3 text-sky-300">{numFormat(grandTotal.transfer.out)}</td>
                    </tr>
                  )}
                </tbody>
              </table>
            </div>
          )}
        </div>
      )}
    </div>
  );
};
