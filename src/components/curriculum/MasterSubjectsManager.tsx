import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState } from 'react';
import { useAppStore } from '../../store/useAppStore';
import { MasterSubject, SubjectCategoryType } from '../../types';
import { 
 Plus, Search, Edit2, Trash2, RotateCcw, Tag
} from 'lucide-react';
import { toast } from '../../utils/toast';

export const MasterSubjectsManager: React.FC = () => {
 const { 
 language, 
 masterSubjects, 
 addMasterSubject, 
 updateMasterSubject, 
 deleteMasterSubject, 
 resetMasterSubjects 
 } = useAppStore();
 const isBn = language === 'bn';

 const [searchQuery, setSearchQuery] = useState('');
 const [selectedCategory, setSelectedCategory] = useState<string>('all');
 const [isModalOpen, setIsModalOpen] = useState(false);
 const [editingId, setEditingId] = useState<string | null>(null);

 const [formData, setFormData] = useState<Partial<MasterSubject>>({
 id: '',
 code: '',
 nameBn: '',
 nameEn: '',
 category: 'general',
 description: '',
 isActive: true,
 isContinuousAssessmentOnly: false
 });

 const categories = [
 { id: 'all', labelBn: 'সকল বিষয়', labelEn: 'All' },
 { id: 'language', labelBn: 'ভাষা ও সাহিত্য', labelEn: 'Language' },
 { id: 'general', labelBn: 'সাধারণ আবশ্যিক', labelEn: 'General' },
 { id: 'science', labelBn: 'বিজ্ঞান বিভাগ', labelEn: 'Science' },
 { id: 'humanities', labelBn: 'মানবিক বিভাগ', labelEn: 'Humanities' },
 { id: 'business', labelBn: 'ব্যবসায় শিক্ষা', labelEn: 'Business' },
 { id: 'religion', labelBn: 'ধর্ম শিক্ষা', labelEn: 'Religion' },
 { id: 'continuous', labelBn: 'ধারাবাহিক মূল্যায়ন', labelEn: 'Continuous' },
 ];

 const filteredSubjects = (masterSubjects || []).filter(sub => {
 if (selectedCategory !== 'all') {
 if (selectedCategory === 'continuous' && !sub.isContinuousAssessmentOnly) return false;
 if (selectedCategory !== 'continuous' && sub.category !== selectedCategory) return false;
 }
 if (searchQuery) {
 const q = searchQuery.toLowerCase().trim();
 const matchCode = sub.code.toLowerCase().includes(q) || sub.id.toLowerCase().includes(q);
 const matchBn = sub.nameBn && sub.nameBn.includes(searchQuery.trim());
 const matchEn = sub.nameEn && sub.nameEn.toLowerCase().includes(q);
 if (!matchCode && !matchBn && !matchEn) return false;
 }
 return true;
 });

 const handleOpenAdd = () => {
 setEditingId(null);
 setFormData({
 id: '',
 code: '',
 nameBn: '',
 nameEn: '',
 category: 'general',
 description: '',
 isActive: true,
 isContinuousAssessmentOnly: false
 });
 setIsModalOpen(true);
 };

 const handleOpenEdit = (subject: MasterSubject) => {
 setEditingId(subject.id);
 setFormData({ ...subject });
 setIsModalOpen(true);
 };

 const handleSave = (e: React.FormEvent) => {
 e.preventDefault();
 const code = (formData.code || '').trim();
 if (!code) {
 toast.error(isBn ? BN_DICT['please_provide_subject_code'] : EN_DICT['please_provide_subject_code']);
 return;
 }
 if (!formData.nameBn || !formData.nameEn) {
 toast.error(isBn ? BN_DICT['please_provide_subject_name_in'] : EN_DICT['please_provide_subject_name_in']);
 return;
 }

 if (editingId) {
 updateMasterSubject(editingId, {
 nameBn: formData.nameBn,
 nameEn: formData.nameEn,
 category: formData.category,
 description: formData.description,
 isContinuousAssessmentOnly: formData.isContinuousAssessmentOnly ?? false,
 isActive: formData.isActive ?? true
 });
 toast.success(isBn ? BN_DICT['subject_updated_successfully'] : EN_DICT['subject_updated_successfully']);
 } else {
 const exists = (masterSubjects || []).some(s => s.id === code || s.code === code);
 if (exists) {
 toast.error(isBn ? `বিষয় কোড '${code}' ইতোমধ্যে সংরক্ষিত আছে।` : `Subject code '${code}' already exists.`);
 return;
 }

 const newSubj: MasterSubject = {
 id: code,
 code: code,
 name: formData.nameEn || formData.nameBn || '',
 nameBn: formData.nameBn || '',
 nameEn: formData.nameEn || '',
 category: (formData.category as SubjectCategoryType) || 'general',
 description: formData.description,
 isContinuousAssessmentOnly: formData.isContinuousAssessmentOnly ?? false,
 isActive: formData.isActive ?? true
 };
 addMasterSubject(newSubj);
 toast.success(isBn ? BN_DICT['subject_added_successfully'] : EN_DICT['subject_added_successfully']);
 }
 setIsModalOpen(false);
 };

 const handleDelete = (id: string, name: string) => {
 if (confirm(isBn ? `আপনি কি "${name}" (কোড: ${id}) বিষয়টি মুছে ফেলতে চান?` : `Delete subject "${name}" (Code: ${id})?`)) {
 deleteMasterSubject(id);
 toast.success(isBn ? `"${name}" বিষয়টি মুছে ফেলা হয়েছে` : `Subject "${name}" deleted`);
 }
 };

 const handleResetDefaults = () => {
 if (confirm(isBn ? BN_DICT['reset_to_national_curriculum_d'] : EN_DICT['reset_to_national_curriculum_d'])) {
 resetMasterSubjects();
 toast.success(isBn ? BN_DICT['default_subjects_restored_succ'] : EN_DICT['default_subjects_restored_succ']);
 }
 };

 const getCategoryLabel = (cat: string) => {
 if (isBn) {
 switch (cat) {
 case 'language': return 'ভাষা ও সাহিত্য';
 case 'science': return 'বিজ্ঞান বিভাগ';
 case 'humanities': return 'মানবিক বিভাগ';
 case 'business': return 'ব্যবসায় শিক্ষা';
 case 'religion': return 'ধর্ম শিক্ষা';
 default: return 'সাধারণ বিষয়';
 }
 } else {
 switch (cat) {
 case 'language': return 'Language';
 case 'science': return 'Science';
 case 'humanities': return 'Humanities';
 case 'business': return 'Business Studies';
 case 'religion': return 'Religion';
 default: return 'General Compulsory';
 }
 }
 };

 return (
 <div className="space-y-4">
 {/* Table Card */}
 <div className="bg-white rounded-2xl border border-slate-200 overflow-hidden">
 {/* Header & Controls Bar */}
 <div className="p-4 border-b border-slate-100 flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-slate-50/50">
 <div className="flex items-center gap-2">
 <Tag className="w-4 h-4 text-teal-600" />
 <h3 className="text-sm font-bold text-slate-900">
 {isBn ? BN_DICT['master_subjects_directory'] : EN_DICT['master_subjects_directory']}
 </h3>
 <span className="text-xs text-slate-400 font-mono">
 ({masterSubjects?.length || 0} {isBn ? BN_DICT['subjects'] : EN_DICT['subjects']})
 </span>
 </div>

 <div className="flex items-center gap-2">
 <button
 onClick={handleResetDefaults}
 title={isBn ? BN_DICT['reset_to_defaults'] : EN_DICT['reset_to_defaults']}
 className="inline-flex items-center gap-1.5 px-3 py-1.5 border border-slate-200 hover:bg-slate-50 text-slate-600 font-semibold text-xs rounded-xl transition-colors"
 >
 <RotateCcw className="w-3.5 h-3.5" />
 <span>{isBn ? BN_DICT['reset_defaults'] : EN_DICT['reset_defaults']}</span>
 </button>

 <button
 id="btn-add-master-subject"
 onClick={handleOpenAdd}
 className="inline-flex items-center gap-1.5 px-3.5 py-1.5 bg-teal-600 hover:bg-teal-700 text-white font-semibold text-xs rounded-xl transition-colors shrink-0"
 >
 <Plus className="w-3.5 h-3.5" />
 <span>{isBn ? BN_DICT['add_subject'] : EN_DICT['add_subject']}</span>
 </button>
 </div>
 </div>

 {/* Search & Filter Bar */}
 <div className="p-3 border-b border-slate-100 flex flex-col md:flex-row md:items-center justify-between gap-3 bg-white">
 <div className="relative w-full md:w-64">
 <Search className="w-3.5 h-3.5 absolute left-2.5 top-2.5 text-slate-400" />
 <input
 type="text"
 value={searchQuery}
 onChange={(e) => setSearchQuery(e.target.value)}
 placeholder={isBn ? BN_DICT['search_code_or_name'] : EN_DICT['search_code_or_name']}
 className="w-full pl-8 pr-3 py-1.5 text-xs bg-slate-50 border border-slate-200 rounded-xl focus:bg-white focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>

 <div className="flex flex-wrap items-center gap-1.5">
 {categories.map(cat => (
 <button
 key={cat.id}
 onClick={() => setSelectedCategory(cat.id)}
 className={`px-2.5 py-1 rounded-lg text-xs font-semibold transition-colors ${
 selectedCategory === cat.id
 ? 'bg-teal-700 text-white'
 : 'bg-slate-100 text-slate-600 hover:bg-slate-200/70'
 }`}
 >
 {isBn ? cat.labelBn : cat.labelEn}
 </button>
 ))}
 </div>
 </div>

 {/* Clean Subjects Table */}
 <div className="w-full">
 <table className="w-full text-left border-collapse">
 <thead>
 <tr className="bg-slate-50/80 border-b border-slate-200 text-slate-500 text-[11px] font-bold uppercase tracking-wider">
 <th className="py-2.5 px-3 text-center w-20">{isBn ? BN_DICT['code'] : EN_DICT['code']}</th>
 <th className="py-2.5 px-3">{isBn ? BN_DICT['subject_name'] : EN_DICT['subject_name']}</th>
 <th className="py-2.5 px-3 w-40">{isBn ? BN_DICT['category'] : EN_DICT['category']}</th>
 <th className="py-2.5 px-3 w-44">{isBn ? BN_DICT['assessment'] : EN_DICT['assessment']}</th>
 <th className="py-2.5 px-3 text-right w-24">{isBn ? BN_DICT['action'] : EN_DICT['action']}</th>
 </tr>
 </thead>
 <tbody className="divide-y divide-slate-100 text-xs">
 {filteredSubjects.length > 0 ? (
 filteredSubjects.map((sub) => {
 const subjectName = isBn ? sub.nameBn : sub.nameEn;
 return (
 <tr key={sub.id} className="hover:bg-slate-50/60 transition-colors">
 <td className="py-2.5 px-3 text-center">
 <span className="font-mono font-bold px-2 py-0.5 bg-slate-100 text-slate-800 rounded text-xs border border-slate-200">
 {sub.code}
 </span>
 </td>

 <td className="py-2.5 px-3 font-bold text-slate-900 text-sm">
 {subjectName}
 </td>

 <td className="py-2.5 px-3 text-slate-600">
 <span className="px-2 py-0.5 rounded-md bg-slate-100 text-slate-700 font-medium text-xs">
 {getCategoryLabel(sub.category)}
 </span>
 </td>

 <td className="py-2.5 px-3">
 {sub.isContinuousAssessmentOnly ? (
 <span className="px-2 py-0.5 rounded-md bg-amber-50 text-amber-800 font-semibold text-xs border border-amber-200/60">
 {isBn ? BN_DICT['continuous_assessment'] : EN_DICT['continuous_assessment']}
 </span>
 ) : (
 <span className="px-2 py-0.5 rounded-md bg-emerald-50 text-emerald-800 font-semibold text-xs border border-emerald-200/60">
 {isBn ? BN_DICT['written_examination'] : EN_DICT['written_examination']}
 </span>
 )}
 </td>

 <td className="py-2.5 px-3 text-right">
 <div className="flex items-center justify-end gap-1">
 <button
 title={isBn ? BN_DICT['edit'] : EN_DICT['edit']}
 onClick={() => handleOpenEdit(sub)}
 className="p-1.5 text-slate-400 hover:text-teal-600 hover:bg-slate-100 rounded-lg transition-colors"
 >
 <Edit2 className="w-3.5 h-3.5" />
 </button>
 <button
 title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
 onClick={() => handleDelete(sub.id, subjectName)}
 className="p-1.5 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-lg transition-colors"
 >
 <Trash2 className="w-3.5 h-3.5" />
 </button>
 </div>
 </td>
 </tr>
 );
 })
 ) : (
 <tr>
 <td colSpan={5} className="py-10 text-center text-slate-400 font-medium text-xs">
 {isBn ? BN_DICT['no_subjects_found'] : EN_DICT['no_subjects_found']}
 </td>
 </tr>
 )}
 </tbody>
 </table>
 </div>
 </div>

 {/* Add / Edit Master Subject Modal */}
 {isModalOpen && (
 <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
 <div className="bg-white rounded-2xl max-w-lg w-full p-5 shadow-2xl border border-slate-200">
 <div className="flex items-center justify-between pb-3 border-b border-slate-100 mb-4">
 <h3 className="text-base font-bold text-slate-900">
 {editingId 
 ? (isBn ? BN_DICT['edit_subject'] : EN_DICT['edit_subject']) 
 : (isBn ? BN_DICT['add_new_subject'] : EN_DICT['add_new_subject'])}
 </h3>
 <button
 onClick={() => setIsModalOpen(false)}
 className="text-slate-400 hover:text-slate-600 text-lg font-bold p-1"
 >
 ✕
 </button>
 </div>

 <form onSubmit={handleSave} className="space-y-3">
 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['subject_code'] : EN_DICT['subject_code']}
 </label>
 <input
 type="text"
 required
 disabled={!!editingId}
 value={formData.code || ''}
 onChange={(e) => setFormData({ ...formData, code: e.target.value.trim(), id: e.target.value.trim() })}
 placeholder={isBn ? BN_DICT['e_g_101'] : EN_DICT['e_g_101']}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs font-mono font-bold focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>

 <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['subject_name_bengali'] : EN_DICT['subject_name_bengali']}
 </label>
 <input
 type="text"
 required
 value={formData.nameBn || ''}
 onChange={(e) => setFormData({ ...formData, nameBn: e.target.value })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>

 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['subject_name_english'] : EN_DICT['subject_name_english']}
 </label>
 <input
 type="text"
 required
 value={formData.nameEn || ''}
 onChange={(e) => setFormData({ ...formData, nameEn: e.target.value })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>
 </div>

 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['category_1'] : EN_DICT['category_1']}
 </label>
 <select
 value={formData.category || 'general'}
 onChange={(e) => setFormData({ ...formData, category: e.target.value as any })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 >
 <option value="language">{isBn ? BN_DICT['language_literature'] : EN_DICT['language_literature']}</option>
 <option value="general">{isBn ? BN_DICT['general_compulsory'] : EN_DICT['general_compulsory']}</option>
 <option value="science">{isBn ? BN_DICT['science'] : EN_DICT['science']}</option>
 <option value="humanities">{isBn ? BN_DICT['humanities'] : EN_DICT['humanities']}</option>
 <option value="business">{isBn ? BN_DICT['business_studies'] : EN_DICT['business_studies']}</option>
 <option value="religion">{isBn ? BN_DICT['religion'] : EN_DICT['religion']}</option>
 </select>
 </div>

 <div className="pt-2 border-t border-slate-100">
 <label className="flex items-center gap-2 cursor-pointer">
 <input
 type="checkbox"
 checked={formData.isContinuousAssessmentOnly || false}
 onChange={(e) => setFormData({ ...formData, isContinuousAssessmentOnly: e.target.checked })}
 className="rounded text-teal-600"
 />
 <span className="text-xs font-semibold text-slate-700">
 {isBn ? BN_DICT['continuous_assessment_only_50'] : EN_DICT['continuous_assessment_only_50']}
 </span>
 </label>
 </div>

 <div className="flex justify-end gap-2 pt-3 border-t border-slate-100">
 <button
 type="button"
 onClick={() => setIsModalOpen(false)}
 className="px-3.5 py-1.5 border border-slate-200 text-slate-600 text-xs font-semibold rounded-xl"
 >
 {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
 </button>
 <button
 type="submit"
 className="px-4 py-1.5 bg-teal-600 hover:bg-teal-700 text-white text-xs font-semibold rounded-xl"
 >
 {editingId ? (isBn ? BN_DICT['save'] : EN_DICT['save']) : (isBn ? BN_DICT['add_subject'] : EN_DICT['add_subject'])}
 </button>
 </div>
 </form>
 </div>
 </div>
 )}
 </div>
 );
};
