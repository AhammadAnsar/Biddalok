import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState } from 'react';
import { useAppStore } from '../../store/useAppStore';
import { CurriculumDefinition } from '../../types';
import { Settings2, Plus, Edit2, Trash2, CheckCircle, ArrowRight } from 'lucide-react';
import { toast } from '../../utils/toast';

interface Props {
 onSelectCurriculumForMapping?: (id: string) => void;
}

export const CurriculumFrameworks: React.FC<Props> = ({ onSelectCurriculumForMapping }) => {
 const { language, curriculums, addCurriculum, updateCurriculum, deleteCurriculum, setDefaultCurriculum, curriculumMappings } = useAppStore();
 const isBn = language === 'bn';

 const [isModalOpen, setIsModalOpen] = useState(false);
 const [editingId, setEditingId] = useState<string | null>(null);

 const [formData, setFormData] = useState<Partial<CurriculumDefinition>>({
 nameBn: '',
 nameEn: '',
 code: '',
 effectiveYear: '2025',
 classesCovered: ['Class 6', 'Class 7', 'Class 8', 'Class 9', 'Class 10'],
 descriptionBn: '',
 descriptionEn: '',
 isActive: true,
 isDefault: false
 });

 const availableClasses = ['Class 6', 'Class 7', 'Class 8', 'Class 9', 'Class 10'];

 const handleOpenAdd = () => {
 setEditingId(null);
 setFormData({
 nameBn: '',
 nameEn: '',
 code: `CURR-${Date.now().toString().slice(-4)}`,
 effectiveYear: '2025',
 classesCovered: ['Class 6', 'Class 7', 'Class 8', 'Class 9', 'Class 10'],
 descriptionBn: '',
 descriptionEn: '',
 isActive: true,
 isDefault: false
 });
 setIsModalOpen(true);
 };

 const handleOpenEdit = (curr: CurriculumDefinition) => {
 setEditingId(curr.id);
 setFormData({ ...curr });
 setIsModalOpen(true);
 };

 const handleSave = (e: React.FormEvent) => {
 e.preventDefault();
 if (!formData.nameBn || !formData.nameEn) {
 toast.error(isBn ? BN_DICT['please_enter_curriculum_name_i'] : EN_DICT['please_enter_curriculum_name_i']);
 return;
 }

 if (editingId) {
 updateCurriculum(editingId, formData);
 toast.success(isBn ? BN_DICT['curriculum_updated_successfull'] : EN_DICT['curriculum_updated_successfull']);
 } else {
 const newCurr: CurriculumDefinition = {
 id: `curr_${Date.now()}`,
 name: formData.nameEn || formData.nameBn || '',
 nameBn: formData.nameBn || '',
 nameEn: formData.nameEn || '',
 code: formData.code || `CURR-${Date.now().toString().slice(-4)}`,
 status: 'active',
 effectiveYear: formData.effectiveYear || '2025',
 classesCovered: formData.classesCovered || availableClasses,
 descriptionBn: formData.descriptionBn,
 descriptionEn: formData.descriptionEn,
 isActive: formData.isActive ?? true,
 isDefault: formData.isDefault ?? false,
 createdAt: new Date().toISOString(),
 updatedAt: new Date().toISOString()
 };
 addCurriculum(newCurr);
 if (newCurr.isDefault) {
 setDefaultCurriculum(newCurr.id);
 }
 toast.success(isBn ? BN_DICT['new_curriculum_created_success'] : EN_DICT['new_curriculum_created_success']);
 }
 setIsModalOpen(false);
 };

 const handleDelete = (id: string, name: string) => {
 if (confirm(isBn ? `আপনি কি "${name}" কারিকুলামটি মুছে ফেলতে চান?` : `Are you sure you want to delete "${name}"?`)) {
 deleteCurriculum(id);
 toast.success(isBn ? `"${name}" কারিকুলাম মুছে ফেলা হয়েছে` : `Curriculum "${name}" deleted`);
 }
 };

 return (
 <div className="space-y-4">
 {/* Top Header Card */}
 <div className="bg-white p-4 rounded-2xl border border-slate-200 flex flex-col sm:flex-row sm:items-center justify-between gap-3">
 <div className="flex items-center gap-2">
 <Settings2 className="w-5 h-5 text-teal-600" />
 <div>
 <h3 className="text-sm font-bold text-slate-900">
 {isBn ? BN_DICT['curriculum_frameworks'] : EN_DICT['curriculum_frameworks']}
 </h3>
 <p className="text-xs text-slate-500">
 {isBn ? BN_DICT['manage_national_curriculum_fra'] : EN_DICT['manage_national_curriculum_fra']}
 </p>
 </div>
 </div>

 <button
 id="btn-add-curriculum"
 onClick={handleOpenAdd}
 className="inline-flex items-center gap-1.5 px-3.5 py-1.5 bg-teal-600 hover:bg-teal-700 text-white font-semibold text-xs rounded-xl transition-colors shrink-0"
 >
 <Plus className="w-3.5 h-3.5" />
 <span>{isBn ? BN_DICT['create_framework'] : EN_DICT['create_framework']}</span>
 </button>
 </div>

 {/* Curriculum Frameworks Grid */}
 <div className="grid grid-cols-1 md:grid-cols-2 gap-4">
 {(curriculums || []).map((curr) => {
 const mappingCount = (curriculumMappings || []).filter(m => m.curriculumId === curr.id).length;
 const currTitle = isBn ? curr.nameBn : curr.nameEn;
 const currDesc = isBn ? curr.descriptionBn : curr.descriptionEn;

 return (
 <div
 key={curr.id}
 className={`bg-white rounded-2xl p-5 border flex flex-col justify-between transition-all ${
 curr.isDefault 
 ? 'border-teal-500/70 ring-2 ring-teal-500/15' 
 : 'border-slate-200 hover:border-slate-300'
 }`}
 >
 <div>
 <div className="flex items-start justify-between gap-3 mb-2">
 <div>
 <div className="flex items-center gap-2 mb-1">
 <span className="font-mono text-xs font-bold px-2 py-0.5 bg-slate-100 text-slate-700 rounded-md">
 {curr.code}
 </span>
 {curr.isDefault && (
 <span className="inline-flex items-center gap-1 text-[11px] font-bold px-2 py-0.5 bg-teal-50 text-teal-700 border border-teal-200 rounded-full">
 <CheckCircle className="w-3 h-3 text-teal-600" />
 <span>{isBn ? BN_DICT['default'] : EN_DICT['default']}</span>
 </span>
 )}
 <span className="text-xs text-slate-500">
 {isBn ? `কার্যকর: ${curr.effectiveYear}` : `Year: ${curr.effectiveYear}`}
 </span>
 </div>

 <h4 className="text-base font-bold text-slate-900">
 {currTitle}
 </h4>
 </div>

 <div className="flex items-center gap-1">
 <button
 title={isBn ? BN_DICT['edit'] : EN_DICT['edit']}
 onClick={() => handleOpenEdit(curr)}
 className="p-1.5 text-slate-400 hover:text-teal-600 hover:bg-slate-100 rounded-lg transition-colors"
 >
 <Edit2 className="w-3.5 h-3.5" />
 </button>
 {!curr.isDefault && (
 <button
 title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
 onClick={() => handleDelete(curr.id, currTitle)}
 className="p-1.5 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-lg transition-colors"
 >
 <Trash2 className="w-3.5 h-3.5" />
 </button>
 )}
 </div>
 </div>

 {currDesc && (
 <p className="text-xs text-slate-600 leading-relaxed mb-3">
 {currDesc}
 </p>
 )}

 {/* Covered Classes Tags */}
 <div className="flex flex-wrap items-center gap-1.5 mb-4">
 <span className="text-xs text-slate-400 font-semibold mr-1">
 {isBn ? BN_DICT['classes_1'] : EN_DICT['classes_1']}
 </span>
 {(curr.classesCovered || []).map((c, i) => (
 <span key={i} className="px-2 py-0.5 bg-slate-100 text-slate-700 font-medium text-xs rounded-md">
 {c}
 </span>
 ))}
 </div>
 </div>

 {/* Card Footer */}
 <div className="pt-3 border-t border-slate-100 flex items-center justify-between">
 <span className="text-xs font-semibold text-slate-600">
 {mappingCount} {isBn ? BN_DICT['subjects_mapped'] : EN_DICT['subjects_mapped']}
 </span>

 <div className="flex items-center gap-2">
 {!curr.isDefault && (
 <button
 onClick={() => setDefaultCurriculum(curr.id)}
 className="text-xs font-semibold text-slate-600 hover:text-teal-700 px-2.5 py-1 rounded-lg border border-slate-200 hover:border-teal-300 transition-colors"
 >
 {isBn ? BN_DICT['set_as_default'] : EN_DICT['set_as_default']}
 </button>
 )}
 {onSelectCurriculumForMapping && (
 <button
 onClick={() => onSelectCurriculumForMapping(curr.id)}
 className="inline-flex items-center gap-1 text-xs font-semibold bg-teal-50 hover:bg-teal-100 text-teal-700 px-3 py-1 rounded-lg transition-colors"
 >
 <span>{isBn ? BN_DICT['view_subjects'] : EN_DICT['view_subjects']}</span>
 <ArrowRight className="w-3 h-3" />
 </button>
 )}
 </div>
 </div>
 </div>
 );
 })}
 </div>

 {/* Add/Edit Modal */}
 {isModalOpen && (
 <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/60 backdrop-blur-xs">
 <div className="bg-white rounded-2xl max-w-lg w-full p-5 shadow-2xl border border-slate-200">
 <div className="flex items-center justify-between pb-3 border-b border-slate-100 mb-4">
 <h3 className="text-base font-bold text-slate-900">
 {editingId 
 ? (isBn ? BN_DICT['edit_curriculum'] : EN_DICT['edit_curriculum']) 
 : (isBn ? BN_DICT['create_framework'] : EN_DICT['create_framework'])}
 </h3>
 <button
 onClick={() => setIsModalOpen(false)}
 className="text-slate-400 hover:text-slate-600 text-lg font-bold p-1"
 >
 ✕
 </button>
 </div>

 <form onSubmit={handleSave} className="space-y-3">
 <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['name_bengali_1'] : EN_DICT['name_bengali_1']}
 </label>
 <input
 type="text"
 required
 value={formData.nameBn || ''}
 onChange={(e) => setFormData({ ...formData, nameBn: e.target.value })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>

 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['name_english_1'] : EN_DICT['name_english_1']}
 </label>
 <input
 type="text"
 required
 value={formData.nameEn || ''}
 onChange={(e) => setFormData({ ...formData, nameEn: e.target.value })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>
 </div>

 <div className="grid grid-cols-1 sm:grid-cols-2 gap-3">
 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['code_1'] : EN_DICT['code_1']}
 </label>
 <input
 type="text"
 required
 value={formData.code || ''}
 onChange={(e) => setFormData({ ...formData, code: e.target.value })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs font-mono focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>

 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['effective_year'] : EN_DICT['effective_year']}
 </label>
 <input
 type="text"
 required
 value={formData.effectiveYear || '2025'}
 onChange={(e) => setFormData({ ...formData, effectiveYear: e.target.value })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs font-mono focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>
 </div>

 <div>
 <label className="block text-xs font-bold text-slate-700 mb-1">
 {isBn ? BN_DICT['description_bengali'] : EN_DICT['description_bengali']}
 </label>
 <textarea
 rows={2}
 value={formData.descriptionBn || ''}
 onChange={(e) => setFormData({ ...formData, descriptionBn: e.target.value })}
 className="w-full px-3 py-1.5 border border-slate-200 rounded-xl text-xs focus:ring-2 focus:ring-teal-500/20 focus:border-teal-500"
 />
 </div>

 <div className="flex justify-end gap-2 pt-3 border-t border-slate-100">
 <button
 type="button"
 onClick={() => setIsModalOpen(false)}
 className="px-3.5 py-1.5 border border-slate-200 text-slate-600 text-xs font-semibold rounded-xl"
 >
 {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
 </button>
 <button
 type="submit"
 className="px-4 py-1.5 bg-teal-600 hover:bg-teal-700 text-white text-xs font-semibold rounded-xl"
 >
 {editingId ? (isBn ? BN_DICT['save'] : EN_DICT['save']) : (isBn ? BN_DICT['create'] : EN_DICT['create'])}
 </button>
 </div>
 </form>
 </div>
 </div>
 )}
 </div>
 );
};
