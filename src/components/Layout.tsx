import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { Link, useLocation } from 'react-router-dom';
import packageJson from '../../package.json';
import { 
 LayoutDashboard, Users, BookOpen, UserCircle, 
 Building2, Wallet, School, Trophy, Globe, 
 BarChart3, Settings, Menu, X, Award, FileCheck,
 Headphones, Phone, MessageSquare, Facebook, ExternalLink,
 Sparkles, Download, BellRing, ShieldAlert, LogOut,
 ShieldCheck
} from 'lucide-react';
import { useAppStore } from '../store/useAppStore';
import { useAuthStore } from '../store/useAuthStore';
import { useUpdateStore } from '../store/useUpdateStore';
import { translations, TranslationKey } from '../locales';
import { getSidebarNavigation, AppRole } from '../data/capabilityRegistry';
import { SupportModal } from './SupportModal';
import { FloatingSupportWidget } from './FloatingSupportWidget';
import { UniversalUpdateModal } from './UniversalUpdateModal';
import { SyncIndicator } from './common/SyncIndicator';

const Layout: React.FC<{ children: React.ReactNode }> = ({ children }) => {
 const [sidebarOpen, setSidebarOpen] = useState(true);
 const [isMobile, setIsMobile] = useState(false);
 const [supportModalOpen, setSupportModalOpen] = useState(false);
 const [supportTopic, setSupportTopic] = useState('general');
 const { language, setLanguage, institution, whiteLabel } = useAppStore();
 const { activeRole, currentUser, isAuthenticated, logout } = useAuthStore();
 const { 
 hasUpdate, latestRelease, isUpdateModalOpen, 
 bannerDismissed, checkUpdates, openUpdateModal, 
 closeUpdateModal, dismissBanner 
 } = useUpdateStore();
 const location = useLocation();

 const appName = whiteLabel?.enabled && whiteLabel.appName ? whiteLabel.appName : (institution?.name || 'Biddalok');
 const appIcon = whiteLabel?.enabled && whiteLabel.appIcon ? whiteLabel.appIcon : (institution?.logoUrl || './icon.svg');
 const appVersion = packageJson.version;
 const isBn = language === 'bn';

 const t = (key: TranslationKey) => translations[language][key];

 const handleOpenSupport = (topic: string = 'general') => {
 setSupportTopic(topic);
 setSupportModalOpen(true);
 };

 // Check for GitHub updates silently once when layout mounts
 useEffect(() => {
 const timer = setTimeout(() => {
 checkUpdates(true);
 }, 2500);
 return () => clearTimeout(timer);
 }, []);

 useEffect(() => {
 const handleResize = () => {
 const mobile = window.innerWidth < 1024;
 setIsMobile(mobile);
 if (mobile) {
 setSidebarOpen(false);
 } else {
 setSidebarOpen(true);
 }
 };
 
 // Initial check
 handleResize();
 
 window.addEventListener('resize', handleResize);
 return () => window.removeEventListener('resize', handleResize);
 }, []);

 // Close sidebar on route change on mobile
 useEffect(() => {
 if (isMobile) {
 setSidebarOpen(false);
 }
 }, [location.pathname, isMobile]);

 const menuItems = [
 { id: 'dashboard', icon: LayoutDashboard, path: '/dashboard', label: 'dashboard', titleBn: 'ড্যাশবোর্ড', titleEn: 'Dashboard', roles: ['super_admin', 'admin', 'teacher', 'accountant', 'staff'] },
 { id: 'students', icon: Users, path: '/students', label: 'students', titleBn: 'শিক্ষার্থী', titleEn: 'Students', roles: ['super_admin', 'admin', 'teacher', 'accountant', 'staff'] },
 { id: 'academic', icon: BookOpen, path: '/academic', label: 'academic', titleBn: 'একাডেমিক', titleEn: 'Academic', roles: ['super_admin', 'admin', 'teacher'] },
 { id: 'hr', icon: UserCircle, path: '/hr', label: 'hr', titleBn: 'মানবসম্পদ', titleEn: 'Human Resources', roles: ['super_admin', 'admin', 'teacher', 'accountant', 'staff'] },
 { id: 'committee', icon: ShieldCheck, path: '/committee', label: 'committee', titleBn: 'কমিটি', titleEn: 'Managing Committee', roles: ['super_admin', 'admin', 'teacher', 'staff'] },
 { id: 'examination', icon: FileCheck, path: '/exam', label: 'examination', titleBn: 'পরীক্ষা', titleEn: 'Examination', roles: ['super_admin', 'admin', 'teacher'] },
 { id: 'testimonial', icon: Award, path: '/testimonial', label: 'testimonial', titleBn: 'প্রত্যয়ন', titleEn: 'Testimonial', roles: ['super_admin', 'admin', 'teacher'] },
 { id: 'communication', icon: MessageSquare, path: '/communication', label: 'communication', titleBn: 'যোগাযোগ', titleEn: 'Communication', roles: ['super_admin', 'admin', 'teacher'] },
 { id: 'institution', icon: School, path: '/institution', label: 'institution', titleBn: 'প্রতিষ্ঠান', titleEn: 'Institution', roles: ['super_admin', 'admin'] },
 { id: 'system', icon: Settings, path: '/system', label: 'system', titleBn: 'সিস্টেম অ্যাডমিন', titleEn: 'System Admin', roles: ['super_admin'] },
 { id: 'support', icon: Headphones, path: '/support', label: 'support', titleBn: 'হেল্প ও সাপোর্ট', titleEn: 'Help & Support', roles: ['super_admin', 'admin', 'teacher', 'accountant', 'staff'] },
 ];

 const { designationPermissions } = useAppStore();
 const allowedMenuItems = menuItems.filter(item => {
 if (!activeRole || !isAuthenticated) return false;
 if (activeRole === 'super_admin') return item.roles.includes('super_admin');
 if (!item.roles.includes(activeRole)) return false;
 
 let activeModules: string[] | undefined = currentUser?.allowedModules;
 
 if (!activeModules && currentUser?.designationId) {
 const dp = designationPermissions?.find(p => p.designationId === currentUser.designationId);
 if (dp) activeModules = dp.allowedModules;
 }
 
 if (activeModules && item.id !== 'support') {
 return activeModules.includes(item.id);
 }
 
 return true;
 });

 return (
 <div className="flex h-screen bg-slate-50 font-sans text-slate-800 overflow-hidden relative">
 
 {/* Mobile Overlay */}
 {isMobile && sidebarOpen && (
 <div 
 className="fixed inset-0 bg-slate-900/50 z-40 lg:hidden transition-opacity"
 onClick={() => setSidebarOpen(false)}
 />
 )}

 {/* Sidebar */}
 <aside 
 className={`
 fixed lg:static inset-y-0 left-0 z-50
 bg-[#0f172a] text-slate-100 flex flex-col border-r border-slate-800/80 transition-all ease-in-out print:hidden
 ${sidebarOpen ? 'translate-x-0 w-72 lg:w-64' : '-translate-x-full lg:translate-x-0 lg:w-20'}
 `}
 >
 <div className="h-16 flex items-center justify-between border-b border-slate-800/80 px-4 shrink-0">
 <div className="flex items-center gap-3 overflow-hidden">
 <img 
 src={appIcon} 
 alt="Logo" 
 className="w-8 h-8 rounded-lg flex-shrink-0 object-cover bg-white/10 p-0.5 border border-white/10" 
 />
 {(sidebarOpen || isMobile) && (
 <div className="flex flex-col">
 <h1 className="text-sm font-bold tracking-tight text-white leading-tight truncate" title={appName}>
 {appName.length > 20 ? `${appName.substring(0, 20)}...` : appName}
 </h1>
 <p className="text-[10px] text-slate-400 font-medium tracking-wide">{isBn ? BN_DICT['by_softdows'] : EN_DICT['by_softdows']}</p>
 </div>
 )}
 </div>
 {isMobile && (
 <button 
 onClick={() => setSidebarOpen(false)}
 className="p-1.5 rounded-lg text-slate-400 hover:text-white hover:bg-slate-800 transition-colors"
 >
 <X className="w-5 h-5" />
 </button>
 )}
 </div>

 <nav className="flex-1 overflow-y-auto no-scrollbar py-3 px-3">
 <ul className="space-y-1">
 {allowedMenuItems.map((item) => {
 const Icon = item.icon;
 const isActive = item.path === '/' 
 ? location.pathname === '/' 
 : location.pathname === item.path || location.pathname.startsWith(`${item.path}/`);
 return (
 <li key={item.id}>
 <Link
 to={item.path}
 className={`flex items-center px-3 py-2 rounded-xl text-xs sm:text-sm font-medium transition-colors ${
 isActive 
 ? 'bg-slate-800 text-white font-semibold border border-slate-700/80 shadow-xs' 
 : 'text-slate-400 hover:text-white hover:bg-slate-800/50'
 }`}
 title={isBn ? (item.titleBn || item.label) : (item.titleEn || item.label)}
 >
 <Icon className={`w-4.5 h-4.5 flex-shrink-0 ${isActive ? 'text-teal-400' : 'text-slate-400'}`} />
 {(sidebarOpen || isMobile) && (
 <span className="ml-3 tracking-wide">{isBn ? (item.titleBn || item.label) : (item.titleEn || item.label)}</span>
 )}
 </Link>
 </li>
 );
 })}
 </ul>
 </nav>

 {/* Sidebar Footer */}
 {(sidebarOpen || isMobile) ? (
 <div className="p-3.5 border-t border-slate-800/80 bg-slate-950/40 shrink-0">
 <p className="font-medium text-slate-300 text-xs truncate">{appName} v{appVersion}</p>
 <p className="text-slate-500 text-[10px] truncate mt-0.5">{isBn ? BN_DICT['by_softdows'] : EN_DICT['by_softdows']}</p>
 </div>
 ) : (
 <div className="p-3 border-t border-slate-800/80 text-center text-[10px] text-slate-500 font-medium shrink-0">
 v{appVersion}
 </div>
 )}
 </aside>

 {/* Main Content */}
 <div className="flex-1 flex flex-col min-w-0 h-full overflow-hidden">
 {/* Header */}
 <header className="h-16 bg-white border-b border-slate-200/80 flex items-center justify-between px-4 sm:px-6 z-10 shrink-0 print:hidden">
 <div className="flex items-center gap-3">
 <button 
 onClick={() => setSidebarOpen(!sidebarOpen)}
 className="p-2 rounded-xl hover:bg-slate-100 text-slate-600 transition-colors focus:outline-none focus:ring-2 focus:ring-slate-300/50"
 aria-label="Toggle menu"
 >
 <Menu className="w-5 h-5" />
 </button>
 <div className="flex flex-col">
 <h2 className="font-bold text-slate-900 leading-tight text-sm sm:text-base truncate max-w-[180px] xs:max-w-[240px] sm:max-w-none">
 {language === 'bn' && institution.nameBn ? institution.nameBn : institution.name}
 </h2>
 {institution.eiin && (
 <p className="text-[11px] text-slate-500 font-medium hidden sm:block">EIIN: {institution.eiin}</p>
 )}
 </div>
 </div>
 
 <div className="flex items-center gap-2.5">
 <SyncIndicator />
        {/* Update Alert Notification Pill if new version found */}
 {hasUpdate && latestRelease && (
 <button
 onClick={openUpdateModal}
 className="bg-amber-500 hover:bg-amber-600 text-white text-xs font-semibold py-1.5 px-3 rounded-xl shadow-xs flex items-center gap-1.5 transition-colors"
 title={isBn ? `নতুন আপডেট v${latestRelease.version} পাওয়া গেছে` : `New update v${latestRelease.version} available`}
 >
 <Sparkles className="w-3.5 h-3.5" />
 <span className="hidden sm:inline">{isBn ? `আপডেট v${latestRelease.version}` : `Update v${latestRelease.version}`}</span>
 <span className="sm:hidden">{isBn ? BN_DICT['update'] : EN_DICT['update']}</span>
 </button>
 )}

 
        {/* Logout Button */}
        <button
          onClick={async () => {
            try {
              await logout();
            } catch (e: any) {
              alert(e.message);
            }
          }}
          className="flex items-center justify-center w-8 h-8 rounded-xl bg-slate-100 hover:bg-red-50 text-slate-500 hover:text-red-600 transition-colors border border-slate-200/80"
          title={isBn ? 'লগআউট' : 'Logout'}
        >
          <LogOut className="w-4 h-4" />
        </button>
        {/* Language Toggle */}

 <div className="flex items-center bg-slate-100 p-0.5 rounded-xl border border-slate-200/80">
 <button
 onClick={() => setLanguage('bn')}
 className={`px-2.5 py-1 text-xs rounded-lg font-medium transition-all ${
 isBn ? BN_DICT['text_slate_500_hover_text_slat'] : EN_DICT['text_slate_500_hover_text_slat']
 }`}
 >
 বাংলা
 </button>
 <button
 onClick={() => setLanguage('en')}
 className={`px-2.5 py-1 text-xs rounded-lg font-medium transition-all ${
 language === 'en' 
 ? 'bg-white shadow-2xs text-slate-900 font-bold' 
 : 'text-slate-500 hover:text-slate-800'
 }`}
 >
 English
 </button>
 </div>
 </div>
 </header>

 {/* Smart Non-Intrusive GitHub Update Notification Banner */}
 {hasUpdate && latestRelease && !bannerDismissed && (
 <div className="bg-slate-900 text-white px-4 py-2 flex items-center justify-between gap-3 text-xs shrink-0 border-b border-slate-800 print:hidden">
 <div className="flex items-center gap-2 overflow-hidden">
 <span className="w-1.5 h-1.5 rounded-full bg-emerald-400 shrink-0" />
 <BellRing className="w-3.5 h-3.5 text-amber-400 shrink-0" />
 <p className="truncate text-slate-200">
 <strong className="text-white font-medium">{isBn ? BN_DICT['new_release'] : EN_DICT['new_release']}</strong> {latestRelease.name} (v{latestRelease.version}) — {isBn ? BN_DICT['zero_data_loss_in_app_update_r'] : EN_DICT['zero_data_loss_in_app_update_r']}
 </p>
 </div>

 <div className="flex items-center gap-2 shrink-0">
 <button
 onClick={openUpdateModal}
 className="bg-slate-800 hover:bg-slate-700 text-white text-[11px] font-semibold px-2.5 py-1 rounded-lg transition-colors flex items-center gap-1 border border-slate-700"
 >
 <Download className="w-3 h-3 text-teal-400" />
 <span>{isBn ? BN_DICT['update'] : EN_DICT['update']}</span>
 </button>
 <button
 onClick={dismissBanner}
 className="text-slate-400 hover:text-white p-1 transition-colors"
 title={isBn ? BN_DICT['dismiss'] : EN_DICT['dismiss']}
 >
 <X className="w-3.5 h-3.5" />
 </button>
 </div>
 </div>
 )}

 {/* Page Content */}
 <main className="flex-1 overflow-x-hidden overflow-y-auto no-scrollbar scroll-smooth px-4 py-5 sm:px-6 sm:py-6 lg:px-8 lg:py-6 pb-24 lg:pb-8">
 <div className="max-w-7xl mx-auto w-full">
 {children}
 </div>
 </main>

 {/* Universal In-App Update Modal */}
 <UniversalUpdateModal
 isOpen={isUpdateModalOpen}
 onClose={closeUpdateModal}
 />

 {/* Support Modal & Floating Support Widget */}
 <SupportModal
 isOpen={supportModalOpen}
 onClose={() => setSupportModalOpen(false)}
 initialTopic={supportTopic}
 />
 
 <FloatingSupportWidget
 onOpenSupportModal={handleOpenSupport}
 />

 {/* Mobile Bottom Navigation */}
 {isMobile && (
 <nav className="fixed bottom-0 left-0 right-0 bg-white/95 border-t border-slate-200/80 flex justify-around items-center h-16 pb-safe z-40 lg:hidden print:hidden">
 <Link to="/dashboard" className={`flex flex-col items-center justify-center w-full h-full space-y-0.5 ${location.pathname === '/dashboard' ? 'text-teal-600' : 'text-slate-500 hover:text-slate-800'}`}>
 <LayoutDashboard className={`w-5 h-5 ${location.pathname === '/dashboard' ? 'fill-teal-50 text-teal-600' : ''}`} />
 <span className="text-[10px] font-medium">{t('dashboard')}</span>
 </Link>
 <Link to="/students" className={`flex flex-col items-center justify-center w-full h-full space-y-0.5 ${location.pathname.startsWith('/students') ? 'text-teal-600' : 'text-slate-500 hover:text-slate-800'}`}>
 <Users className={`w-5 h-5 ${location.pathname.startsWith('/students') ? 'fill-teal-50 text-teal-600' : ''}`} />
 <span className="text-[10px] font-medium">{t('students')}</span>
 </Link>
 <Link to="/academic" className={`flex flex-col items-center justify-center w-full h-full space-y-0.5 ${location.pathname === '/academic' ? 'text-teal-600' : 'text-slate-500 hover:text-slate-800'}`}>
 <BookOpen className={`w-5 h-5 ${location.pathname === '/academic' ? 'fill-teal-50 text-teal-600' : ''}`} />
 <span className="text-[10px] font-medium">{t('academic')}</span>
 </Link>
 <Link to="/institution" className={`flex flex-col items-center justify-center w-full h-full space-y-0.5 ${location.pathname.startsWith('/institution') ? 'text-teal-600' : 'text-slate-500 hover:text-slate-800'}`}>
 <School className={`w-5 h-5 ${location.pathname.startsWith('/institution') ? 'fill-teal-50 text-teal-600' : ''}`} />
 <span className="text-[10px] font-medium">{t('institution')}</span>
 </Link>
 <button onClick={() => setSidebarOpen(true)} className="flex flex-col items-center justify-center w-full h-full space-y-0.5 text-slate-500 hover:text-slate-800">
 <Menu className="w-5 h-5" />
 <span className="text-[10px] font-medium">{isBn ? BN_DICT['menu'] : EN_DICT['menu']}</span>
 </button>
 </nav>
 )}
 </div>
 </div>
 );
};

export default Layout;
