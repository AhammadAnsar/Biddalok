 const handleFileChange = async (e: React.ChangeEvent<HTMLInputElement>, fieldName: keyof Student) => {
 const file = e.target.files?.[0];
 if (file) {
 // Attempt to upload to local Express API
 try {
 const result = await uploadDocumentSecurely({
 file,
 type: 'student',
 id: formData.studentId || formData.id || 'Unknown',
 docType: fieldName,
 });

 if (result.success && result.filepath) {
 setFormData(prev => ({ ...prev, [fieldName]: result.filepath }));
 return;
 }
 } catch (err) {
 console.warn('Backend API upload failed, falling back to Base64', err);
 }

 // Fallback to Base64 compression
 try {
 const compressed = await compressImageBase64(file, 400, 400, 0.85);
 setFormData(prev => ({ ...prev, [fieldName]: compressed }));
 } catch {
 const reader = new FileReader();
 reader.onloadend = () => {
 setFormData(prev => ({ ...prev, [fieldName]: reader.result as string }));
 };
 reader.readAsDataURL(file);
 }
 }
 };

