import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React from 'react';
import { Link } from 'react-router-dom';
import { 
  Users, BookOpen, Award, Wallet, School, UserPlus, 
  FileText, ShieldCheck, ArrowRight, Sparkles, Building2,
  Calendar, CheckCircle, Clock
} from 'lucide-react';
import { useAppStore } from '../store/useAppStore';
import { getSidebarNavigation, AppRole } from '../data/capabilityRegistry';
import { useAuthStore } from '../store/useAuthStore';
import { translations, TranslationKey } from '../locales';
import { StudentClassOverview } from '../components/StudentClassOverview';

const Dashboard = () => {
  const { language, students, examResults, academicClasses, staff, institution, designationPermissions } = useAppStore();
  const { activeRole, currentUser, isAuthenticated } = useAuthStore();
  const isBn = language === 'bn';
  const t = (key: TranslationKey) => translations[language][key];

  const hasAccess = (path: string): boolean => {
    if (!isAuthenticated || !activeRole) return false;
    if (activeRole === 'super_admin') return true;

    let activeModules: string[] | undefined = currentUser?.allowedModules;
    if (!activeModules && currentUser?.designationId) {
      const dp = designationPermissions?.find(p => p.designationId === currentUser.designationId);
      if (dp) activeModules = dp.allowedModules;
    }

    if (!activeModules) return true;

    let requiredModuleId = '';
    if (path.startsWith('/students')) requiredModuleId = 'students';
    else if (path.startsWith('/academic')) requiredModuleId = 'academic';
    else if (path.startsWith('/exam')) requiredModuleId = 'examination';
    else if (path.startsWith('/testimonial')) requiredModuleId = 'testimonial';
    else if (path.startsWith('/hr')) requiredModuleId = 'hr';
    else if (path.startsWith('/committee')) requiredModuleId = 'committee';
    else if (path.startsWith('/institution')) requiredModuleId = 'institution';
    else if (path.startsWith('/system')) requiredModuleId = 'system';
    else if (path === '/') requiredModuleId = 'dashboard';

    if (!requiredModuleId) return true;
    if (requiredModuleId === 'committee' && activeModules.includes('hr')) return true;
    return activeModules.includes(requiredModuleId);
  };

  const currentDate = new Date().toLocaleDateString(isBn ? BN_DICT['en_us'] : EN_DICT['en_us'], {
    weekday: 'long',
    year: 'numeric',
    month: 'long',
    day: 'numeric'
  });

  const stats = [
    { 
      label: isBn ? BN_DICT['total_students_1'] : EN_DICT['total_students_1'], 
      value: (students || []).length, 
      icon: Users, 
      color: 'bg-blue-600', 
      border: 'border-blue-200',
      link: '/students/list'
    },
    { 
      label: isBn ? BN_DICT['testimonials_results'] : EN_DICT['testimonials_results'], 
      value: (examResults || []).length, 
      icon: Award, 
      color: 'bg-purple-600', 
      border: 'border-purple-200',
      link: '/testimonial'
    },
    { 
      label: isBn ? BN_DICT['classes_sections'] : EN_DICT['classes_sections'], 
      value: (academicClasses || []).length, 
      icon: BookOpen, 
      color: 'bg-emerald-600', 
      border: 'border-emerald-200',
      link: '/academic/class-section'
    },
    { 
      label: isBn ? BN_DICT['teachers_staff'] : EN_DICT['teachers_staff'], 
      value: (staff || []).length, 
      icon: Building2, 
      color: 'bg-amber-600', 
      border: 'border-amber-200',
      link: '/hr'
    },
  ];

  const quickActions = [
    {
      title: isBn ? BN_DICT['attestation'] : EN_DICT['attestation'],
      desc: isBn ? BN_DICT['generate_print_pdfs'] : EN_DICT['generate_print_pdfs'],
      icon: Award,
      color: 'bg-purple-100 text-purple-700 group-hover:bg-purple-600 group-hover:text-white',
      link: '/testimonial',
      badge: isBn ? BN_DICT['popular'] : EN_DICT['popular']
    },
    {
      title: isBn ? BN_DICT['new_admission'] : EN_DICT['new_admission'],
      desc: isBn ? BN_DICT['enroll_new_students'] : EN_DICT['enroll_new_students'],
      icon: UserPlus,
      color: 'bg-blue-100 text-blue-700 group-hover:bg-blue-600 group-hover:text-white',
      link: '/students/admission'
    },
    {
      title: isBn ? BN_DICT['student_directory'] : EN_DICT['student_directory'],
      desc: isBn ? BN_DICT['student_records_profiles'] : EN_DICT['student_records_profiles'],
      icon: Users,
      color: 'bg-sky-100 text-sky-700 group-hover:bg-sky-600 group-hover:text-white',
      link: '/students/list'
    },
    {
      title: isBn ? BN_DICT['classes_sections'] : EN_DICT['classes_sections'],
      desc: isBn ? BN_DICT['manage_academic_classes'] : EN_DICT['manage_academic_classes'],
      icon: BookOpen,
      color: 'bg-emerald-100 text-emerald-700 group-hover:bg-emerald-600 group-hover:text-white',
      link: '/academic/class-section'
    },
    {
      title: isBn ? BN_DICT['institute_settings'] : EN_DICT['institute_settings'],
      desc: isBn ? BN_DICT['manage_institute_info'] : EN_DICT['manage_institute_info'],
      icon: School,
      color: 'bg-amber-100 text-amber-700 group-hover:bg-amber-600 group-hover:text-white',
      link: '/institution/settings'
    },
    {
      title: isBn ? BN_DICT['system_backup'] : EN_DICT['system_backup'],
      desc: isBn ? BN_DICT['database_backup_restore'] : EN_DICT['database_backup_restore'],
      icon: ShieldCheck,
      color: 'bg-slate-100 text-slate-700 group-hover:bg-slate-700 group-hover:text-white',
      link: '/system'
    }
  ];

  return (
    <div className="space-y-6 sm:space-y-8">
      
      {/* Institution Hero Header Banner */}
      <div className="bg-gradient-to-r from-indigo-900 via-indigo-800 to-indigo-950 text-white rounded-2xl sm:rounded-3xl p-6 sm:p-8 shadow-xl border border-indigo-700/50 relative overflow-hidden">
        <div className="absolute top-0 right-0 w-80 h-80 bg-emerald-500/10 rounded-full blur-3xl pointer-events-none" />
        <div className="relative z-10 flex flex-col md:flex-row md:items-center justify-between gap-6">
          <div className="space-y-2 max-w-2xl">
            <div className="inline-flex items-center gap-2 px-3 py-1 rounded-full bg-white/10 text-emerald-300 text-xs font-semibold backdrop-blur-sm border border-white/15">
              <Sparkles className="w-3.5 h-3.5" />
              <span>{isBn ? BN_DICT['biddalok_education_erp_dashboa'] : EN_DICT['biddalok_education_erp_dashboa']}</span>
            </div>
            <h1 className="text-2xl sm:text-3xl font-black tracking-tight text-white">
              {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয়') : (institution?.name || institution?.nameBn || 'Institution')}
            </h1>
            <div className="flex flex-wrap items-center gap-x-4 gap-y-1 text-xs text-indigo-200">
              {institution?.eiin ? (
                <>
                  <span>EIIN: <strong className="text-white font-mono">{institution.eiin}</strong></span>
                  <span>&bull;</span>
                </>
              ) : null}
              <span className="flex items-center gap-1">
                <Calendar className="w-3.5 h-3.5 text-emerald-300" />
                {currentDate}
              </span>
            </div>
          </div>

          <div className="flex flex-wrap gap-3">
            <Link
              to="/students/admission"
              className="bg-indigo-600 hover:bg-indigo-500 text-white text-xs sm:text-sm font-bold py-2.5 px-4 rounded-xl shadow-md transition-all flex items-center gap-2"
            >
              <UserPlus className="w-4 h-4" />
              <span>{isBn ? BN_DICT['new_admission'] : EN_DICT['new_admission']}</span>
            </Link>
            <Link
              to="/testimonial"
              className="bg-emerald-600 hover:bg-emerald-700 text-white text-xs sm:text-sm font-bold py-2.5 px-4 rounded-xl shadow-lg transition-all flex items-center gap-2"
            >
              <Award className="w-4 h-4" />
              <span>{isBn ? BN_DICT['attestation'] : EN_DICT['attestation']}</span>
            </Link>
          </div>
        </div>
      </div>


      {/* Main Stats Grid */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4 sm:gap-6">
        {stats.filter(stat => hasAccess(stat.link)).map((stat, i) => {
          const Icon = stat.icon;
          return (
            <Link 
              key={i} 
              to={stat.link}
              className={`bg-white rounded-2xl shadow-sm hover:shadow-md border ${stat.border} p-5 flex items-center gap-4 transition-all hover:-translate-y-0.5 group`}
            >
              <div className={`${stat.color} p-3.5 rounded-xl text-white shadow-md group-hover:scale-105 transition-transform`}>
                <Icon className="w-6 h-6" />
              </div>
              <div className="overflow-hidden">
                <p className="text-xs text-slate-500 font-semibold truncate">{stat.label}</p>
                <p className="text-xl sm:text-2xl font-black text-slate-900 mt-0.5">{stat.value}</p>
              </div>
            </Link>
          );
        })}
      </div>

      {/* Student Class Overview Widget */}
      <StudentClassOverview isDashboardMode={true} />

      {/* Quick Access Operations Grid */}
      <div className="bg-white rounded-2xl sm:rounded-3xl shadow-sm border border-slate-200 p-6 sm:p-8 space-y-5">
        <div className="flex items-center justify-between border-b border-slate-100 pb-4">
          <div>
            <h2 className="text-lg font-bold text-slate-900 flex items-center gap-2">
              <Sparkles className="w-4 h-4 text-indigo-600" />
              {isBn ? BN_DICT['daily_academic_operations'] : EN_DICT['daily_academic_operations']}
            </h2>
            <p className="text-xs text-slate-500 mt-0.5">
              {isBn ? BN_DICT['select_a_module_below_to_quick'] : EN_DICT['select_a_module_below_to_quick']}
            </p>
          </div>
        </div>
        
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-3 gap-4">
          {quickActions.filter(action => hasAccess(action.link)).map((action, idx) => {
            const Icon = action.icon;
            return (
              <Link
                key={idx}
                to={action.link}
                className="p-4 rounded-2xl bg-slate-50/80 hover:bg-indigo-50/50 border border-slate-200/80 hover:border-indigo-300 transition-all flex items-center justify-between group shadow-sm hover:shadow"
              >
                <div className="flex items-center gap-3.5">
                  <div className={`w-11 h-11 rounded-xl flex items-center justify-center transition-colors ${action.color}`}>
                    <Icon className="w-5 h-5" />
                  </div>
                  <div>
                    <div className="flex items-center gap-2">
                      <h4 className="text-sm font-bold text-slate-900 group-hover:text-indigo-900">
                        {action.title}
                      </h4>
                      {action.badge && (
                        <span className="text-[10px] font-bold bg-purple-100 text-purple-700 px-1.5 py-0.5 rounded">
                          {action.badge}
                        </span>
                      )}
                    </div>
                    <p className="text-[11px] text-slate-500 mt-0.5 line-clamp-1">
                      {action.desc}
                    </p>
                  </div>
                </div>
                <ArrowRight className="w-4 h-4 text-slate-400 group-hover:text-indigo-600 group-hover:translate-x-1 transition-all shrink-0 ml-2" />
              </Link>
            );
          })}
        </div>
      </div>


      {/* Recent Admissions & Institution Overview */}
      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        
        {/* Recent Students Enrolled */}
        <div className="lg:col-span-2 bg-white rounded-2xl shadow-sm border border-slate-200 p-6 space-y-4">
          <div className="flex items-center justify-between border-b border-slate-100 pb-3">
            <div className="flex items-center gap-2">
              <Users className="w-4 h-4 text-indigo-600" />
              <h3 className="text-sm font-bold text-slate-900">
                {isBn ? BN_DICT['recent_students'] : EN_DICT['recent_students']}
              </h3>
            </div>
            <Link 
              to="/students/list" 
              className="text-xs font-bold text-indigo-600 hover:text-indigo-800 flex items-center gap-1"
            >
              <span>{isBn ? BN_DICT['view_all'] : EN_DICT['view_all']}</span>
              <ArrowRight className="w-3.5 h-3.5" />
            </Link>
          </div>

          {students && students.length > 0 ? (
            <div className="divide-y divide-slate-100">
              {students.slice(0, 5).map((student) => (
                <div key={student.id} className="py-2.5 flex items-center justify-between text-xs">
                  <div className="flex items-center gap-3">
                    <div className="w-7 h-7 rounded-lg bg-indigo-100 text-indigo-700 font-bold flex items-center justify-center">
                      {student.roll || '#'}
                    </div>
                    <div>
                      <p className="font-bold text-slate-800">{isBn && student.nameBn ? student.nameBn : student.name}</p>
                      <p className="text-[11px] text-slate-500 font-mono">ID: {student.studentId} &bull; Class {student.class}</p>
                    </div>
                  </div>
                  <span className="text-[10px] font-bold text-emerald-700 bg-emerald-50 px-2 py-0.5 rounded">
                    {student.session || '2026'}
                  </span>
                </div>
              ))}
            </div>
          ) : (
            <div className="py-8 text-center text-slate-400 text-xs">
              {isBn ? BN_DICT['no_student_records_yet'] : EN_DICT['no_student_records_yet']}
            </div>
          )}
        </div>

        {/* System & Institution Info Card */}
        <div className="bg-white rounded-2xl shadow-sm border border-slate-200 p-6 space-y-4 flex flex-col justify-between">
          <div>
            <div className="flex items-center gap-2 border-b border-slate-100 pb-3">
              <School className="w-4 h-4 text-emerald-600" />
              <h3 className="text-sm font-bold text-slate-900">
                {isBn ? BN_DICT['institute_details'] : EN_DICT['institute_details']}
              </h3>
            </div>

            <div className="mt-3 space-y-2 text-xs">
              <div className="flex justify-between py-1 border-b border-slate-100">
                <span className="text-slate-500">{isBn ? BN_DICT['name'] : EN_DICT['name']}</span>
                <span className="font-bold text-slate-800 text-right truncate max-w-[150px]">
                  {isBn ? (institution?.nameBn || institution?.name || 'প্রতিষ্ঠান') : (institution?.name || institution?.nameBn || 'Institution')}
                </span>
              </div>
              <div className="flex justify-between py-1 border-b border-slate-100">
                <span className="text-slate-500">EIIN</span>
                <span className="font-mono font-bold text-slate-800">{institution?.eiin || (isBn ? BN_DICT['n_a'] : EN_DICT['n_a'])}</span>
              </div>
              <div className="flex justify-between py-1 border-b border-slate-100">
                <span className="text-slate-500">{isBn ? BN_DICT['address'] : EN_DICT['address']}</span>
                <span className="font-medium text-slate-700 text-right truncate max-w-[160px]">
                  {isBn ? (institution?.addressBn || institution?.address || 'ঠিকানা সেট করা হয়নি') : (institution?.address || institution?.addressBn || 'Not set')}
                </span>
              </div>
              <div className="flex justify-between py-1">
                <span className="text-slate-500">{isBn ? BN_DICT['data_mode'] : EN_DICT['data_mode']}</span>
                <span className="font-bold text-emerald-600">{isBn ? BN_DICT['offline_safe'] : EN_DICT['offline_safe']}</span>
              </div>
            </div>
          </div>

          <Link
            to="/institution/settings"
            className="w-full bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-bold py-2 rounded-xl text-center transition-all"
          >
            {isBn ? BN_DICT['edit_institute_settings'] : EN_DICT['edit_institute_settings']}
          </Link>
        </div>

      </div>

    </div>
  );
};

export default Dashboard;
