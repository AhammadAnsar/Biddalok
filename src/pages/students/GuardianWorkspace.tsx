import React, { useState, useEffect } from 'react';
import { useGuardianStore, Guardian, StudentGuardian } from '../../store/useGuardianStore';
import { useAppStore } from '../../store/useAppStore';
import { generateId } from '../../utils/generateId';
import { Users, Save, Plus, Search, Edit, Trash2 } from 'lucide-react';
import { BN_DICT, EN_DICT } from '../../locales/autoGenerated';

export default function GuardianWorkspace() {
  const language = useAppStore(state => state.language);
  const isBengali = language === 'bn';
  const dict = isBengali ? BN_DICT : EN_DICT;

  const { guardians, studentGuardians, loadGuardians, saveGuardian, loading } = useGuardianStore();
  const students = useAppStore(state => state.students) || [];

  useEffect(() => {
    loadGuardians();
  }, []);

  const [isModalOpen, setIsModalOpen] = useState(false);
  const [editingGuardian, setEditingGuardian] = useState<Guardian | null>(null);
  const [linkedStudents, setLinkedStudents] = useState<StudentGuardian[]>([]);
  const [searchTerm, setSearchTerm] = useState('');
  
  const [formData, setFormData] = useState({
    name: '',
    primaryContact: '',
    relation: '',
    occupation: '',
    address: ''
  });

  const [studentSearch, setStudentSearch] = useState('');
  const [selectedStudentToAdd, setSelectedStudentToAdd] = useState<string>('');
  const [linkRelation, setLinkRelation] = useState('Father');

  const handleOpenModal = (guardian?: Guardian) => {
    if (guardian) {
      setEditingGuardian(guardian);
      setFormData({
        name: guardian.name,
        primaryContact: guardian.primaryContact,
        relation: guardian.relation,
        occupation: guardian.occupation || '',
        address: guardian.address || ''
      });
      setLinkedStudents(studentGuardians.filter(sg => sg.guardianId === guardian.id));
    } else {
      setEditingGuardian(null);
      setFormData({ name: '', primaryContact: '', relation: '', occupation: '', address: '' });
      setLinkedStudents([]);
    }
    setIsModalOpen(true);
  };

  const handleSave = async () => {
    if (!formData.name || !formData.primaryContact) {
      alert(isBengali ? 'নাম এবং মোবাইল নম্বর আবশ্যক' : 'Name and Contact are required');
      return;
    }
    
    const guardian: Guardian = {
      id: editingGuardian?.id || generateId('grd_'),
      name: formData.name,
      primaryContact: formData.primaryContact,
      relation: formData.relation,
      occupation: formData.occupation,
      address: formData.address,
      createdAt: editingGuardian?.createdAt || new Date().toISOString(),
      updatedAt: new Date().toISOString()
    };

    const finalLinks = linkedStudents.map(ls => ({
      ...ls,
      guardianId: guardian.id
    }));

    await saveGuardian(guardian, finalLinks);
    setIsModalOpen(false);
  };

  const handleLinkStudent = () => {
    if (!selectedStudentToAdd) return;
    if (linkedStudents.find(ls => ls.studentId === selectedStudentToAdd)) return; // already linked
    
    setLinkedStudents([
      ...linkedStudents,
      {
        id: generateId('sg_'),
        studentId: selectedStudentToAdd,
        guardianId: editingGuardian?.id || '',
        relation: linkRelation,
        isEmergencyContact: true,
        isPrimary: true
      }
    ]);
    setSelectedStudentToAdd('');
  };

  const filteredGuardians = guardians.filter(g => 
    g.name.toLowerCase().includes(searchTerm.toLowerCase()) || 
    g.primaryContact.includes(searchTerm)
  );

  const filteredStudents = students.filter(s => 
    (s.nameBn || s.name).toLowerCase().includes(studentSearch.toLowerCase()) || 
    s.roll?.includes(studentSearch)
  ).slice(0, 10);

  return (
    <div className="p-6">
      <div className="flex justify-between items-center mb-6">
        <div>
          <h1 className="text-2xl font-bold text-gray-900">{isBengali ? 'অভিভাবক ডিরেক্টরি' : 'Guardian Directory'}</h1>
          <p className="text-gray-500">{isBengali ? 'শিক্ষার্থীদের অভিভাবক এবং ইমার্জেন্সি কন্টাক্ট' : 'Student guardians and emergency contacts'}</p>
        </div>
        <button
          onClick={() => handleOpenModal()}
          className="flex items-center space-x-2 bg-indigo-600 hover:bg-indigo-700 text-white px-4 py-2 rounded-lg"
        >
          <Plus className="w-5 h-5" />
          <span>{isBengali ? 'নতুন অভিভাবক যুক্ত করুন' : 'Add New Guardian'}</span>
        </button>
      </div>

      <div className="bg-white rounded-xl shadow-sm border border-gray-200 overflow-hidden">
        <div className="p-4 border-b border-gray-200">
          <div className="relative w-full max-w-md">
            <Search className="absolute left-3 top-2.5 h-5 w-5 text-gray-400" />
            <input
              type="text"
              placeholder={isBengali ? 'নাম বা মোবাইল নম্বর দিয়ে খুঁজুন...' : 'Search by name or mobile...'}
              value={searchTerm}
              onChange={(e) => setSearchTerm(e.target.value)}
              className="pl-10 w-full rounded-lg border-gray-300 border px-3 py-2"
            />
          </div>
        </div>
        
        <table className="min-w-full divide-y divide-gray-200">
          <thead className="bg-gray-50">
            <tr>
              <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase">{isBengali ? 'নাম' : 'Name'}</th>
              <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase">{isBengali ? 'মোবাইল' : 'Mobile'}</th>
              <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase">{isBengali ? 'সম্পর্ক' : 'Relation'}</th>
              <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase">{isBengali ? 'শিক্ষার্থী' : 'Linked Students'}</th>
              <th className="px-6 py-3 text-right text-xs font-medium text-gray-500 uppercase">{isBengali ? 'অ্যাকশন' : 'Action'}</th>
            </tr>
          </thead>
          <tbody className="bg-white divide-y divide-gray-200">
            {filteredGuardians.map(g => {
              const links = studentGuardians.filter(sg => sg.guardianId === g.id);
              return (
                <tr key={g.id} className="hover:bg-gray-50">
                  <td className="px-6 py-4 whitespace-nowrap text-sm font-medium text-gray-900">{g.name}</td>
                  <td className="px-6 py-4 whitespace-nowrap text-sm text-gray-500">{g.primaryContact}</td>
                  <td className="px-6 py-4 whitespace-nowrap text-sm text-gray-500">{g.relation}</td>
                  <td className="px-6 py-4 text-sm text-gray-500">
                    <div className="flex flex-wrap gap-1">
                      {links.map(l => {
                        const s = students.find(st => st.id === l.studentId);
                        return s ? (
                          <span key={l.id} className="inline-flex items-center px-2 py-0.5 rounded text-xs font-medium bg-blue-100 text-blue-800">
                            {isBengali ? s.nameBn || s.name : s.name} ({s.roll})
                          </span>
                        ) : null;
                      })}
                    </div>
                  </td>
                  <td className="px-6 py-4 whitespace-nowrap text-right text-sm font-medium">
                    <button onClick={() => handleOpenModal(g)} className="text-indigo-600 hover:text-indigo-900">
                      <Edit className="w-4 h-4" />
                    </button>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>
      </div>

      {isModalOpen && (
        <div className="fixed inset-0 bg-gray-500 bg-opacity-75 flex items-center justify-center p-4 z-50">
          <div className="bg-white rounded-xl shadow-xl max-w-2xl w-full max-h-[90vh] overflow-y-auto">
            <div className="p-6 border-b border-gray-200">
              <h3 className="text-lg font-medium text-gray-900">
                {editingGuardian ? (isBengali ? 'অভিভাবক এডিট করুন' : 'Edit Guardian') : (isBengali ? 'নতুন অভিভাবক' : 'New Guardian')}
              </h3>
            </div>
            
            <div className="p-6 space-y-4">
              <div className="grid grid-cols-2 gap-4">
                <div>
                  <label className="block text-sm font-medium text-gray-700">{isBengali ? 'নাম' : 'Name'} *</label>
                  <input
                    type="text"
                    value={formData.name}
                    onChange={(e) => setFormData({...formData, name: e.target.value})}
                    className="mt-1 w-full rounded-md border-gray-300 border px-3 py-2"
                  />
                </div>
                <div>
                  <label className="block text-sm font-medium text-gray-700">{isBengali ? 'মোবাইল নম্বর' : 'Mobile Number'} *</label>
                  <input
                    type="text"
                    value={formData.primaryContact}
                    onChange={(e) => setFormData({...formData, primaryContact: e.target.value})}
                    className="mt-1 w-full rounded-md border-gray-300 border px-3 py-2"
                  />
                </div>
                <div>
                  <label className="block text-sm font-medium text-gray-700">{isBengali ? 'সাধারণ সম্পর্ক' : 'Default Relation'}</label>
                  <input
                    type="text"
                    value={formData.relation}
                    onChange={(e) => setFormData({...formData, relation: e.target.value})}
                    className="mt-1 w-full rounded-md border-gray-300 border px-3 py-2"
                    placeholder="Father, Mother, Uncle..."
                  />
                </div>
                <div>
                  <label className="block text-sm font-medium text-gray-700">{isBengali ? 'পেশা' : 'Occupation'}</label>
                  <input
                    type="text"
                    value={formData.occupation}
                    onChange={(e) => setFormData({...formData, occupation: e.target.value})}
                    className="mt-1 w-full rounded-md border-gray-300 border px-3 py-2"
                  />
                </div>
              </div>
              <div>
                <label className="block text-sm font-medium text-gray-700">{isBengali ? 'ঠিকানা' : 'Address'}</label>
                <textarea
                  value={formData.address}
                  onChange={(e) => setFormData({...formData, address: e.target.value})}
                  className="mt-1 w-full rounded-md border-gray-300 border px-3 py-2"
                  rows={2}
                />
              </div>

              <div className="mt-8 border-t border-gray-200 pt-4">
                <h4 className="font-medium text-gray-900 mb-2">{isBengali ? 'যুক্ত শিক্ষার্থীরা' : 'Linked Students'}</h4>
                
                <div className="flex gap-2 items-end mb-4">
                  <div className="flex-1">
                    <label className="block text-xs font-medium text-gray-700">{isBengali ? 'শিক্ষার্থী খুঁজুন' : 'Search Student'}</label>
                    <input
                      type="text"
                      value={studentSearch}
                      onChange={(e) => setStudentSearch(e.target.value)}
                      placeholder="Name or roll..."
                      className="mt-1 w-full rounded-md border-gray-300 border px-3 py-1"
                    />
                  </div>
                  <div className="flex-1">
                    <label className="block text-xs font-medium text-gray-700">{isBengali ? 'নির্বাচন করুন' : 'Select'}</label>
                    <select
                      value={selectedStudentToAdd}
                      onChange={(e) => setSelectedStudentToAdd(e.target.value)}
                      className="mt-1 w-full rounded-md border-gray-300 border px-3 py-1"
                    >
                      <option value="">--</option>
                      {filteredStudents.map(s => (
                        <option key={s.id} value={s.id}>{isBengali ? s.nameBn || s.name : s.name} ({s.roll})</option>
                      ))}
                    </select>
                  </div>
                  <div className="flex-1">
                    <label className="block text-xs font-medium text-gray-700">{isBengali ? 'সম্পর্ক' : 'Relation'}</label>
                    <input
                      type="text"
                      value={linkRelation}
                      onChange={(e) => setLinkRelation(e.target.value)}
                      className="mt-1 w-full rounded-md border-gray-300 border px-3 py-1"
                    />
                  </div>
                  <button
                    onClick={handleLinkStudent}
                    disabled={!selectedStudentToAdd}
                    className="bg-indigo-100 hover:bg-indigo-200 text-indigo-700 px-3 py-1 rounded-md border border-indigo-200 disabled:opacity-50 h-8"
                  >
                    {isBengali ? 'যুক্ত করুন' : 'Link'}
                  </button>
                </div>

                {linkedStudents.length > 0 && (
                  <ul className="divide-y divide-gray-200 border border-gray-200 rounded-md">
                    {linkedStudents.map(ls => {
                      const s = students.find(st => st.id === ls.studentId);
                      return (
                        <li key={ls.id} className="px-4 py-2 flex justify-between items-center text-sm">
                          <div>
                            <span className="font-medium text-gray-900">{s ? (isBengali ? s.nameBn || s.name : s.name) : 'Unknown'}</span>
                            <span className="ml-2 text-gray-500 text-xs">({ls.relation})</span>
                          </div>
                          <button
                            onClick={() => setLinkedStudents(linkedStudents.filter(l => l.id !== ls.id))}
                            className="text-red-500 hover:text-red-700"
                          >
                            <Trash2 className="w-4 h-4" />
                          </button>
                        </li>
                      );
                    })}
                  </ul>
                )}
              </div>
            </div>

            <div className="p-4 border-t border-gray-200 flex justify-end space-x-3 bg-gray-50">
              <button
                onClick={() => setIsModalOpen(false)}
                className="px-4 py-2 border border-gray-300 text-gray-700 rounded-md hover:bg-gray-100"
              >
                {isBengali ? 'বাতিল' : 'Cancel'}
              </button>
              <button
                onClick={handleSave}
                disabled={loading}
                className="px-4 py-2 bg-indigo-600 text-white rounded-md hover:bg-indigo-700"
              >
                {isBengali ? 'সেভ করুন' : 'Save'}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
}
