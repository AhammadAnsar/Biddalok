import React, { useState, useEffect } from 'react';
import { useAppStore } from '../../store/useAppStore';
import { useStudentAttendanceStore } from '../../store/useStudentAttendanceStore';
import { StudentAttendance } from '../../types';
import { Calendar, Save, CheckCircle, XCircle, Clock, AlertTriangle, FileText } from 'lucide-react';
import { generateId } from '../../utils/generateId';
import { BN_DICT, EN_DICT } from '../../locales/autoGenerated';

export default function StudentAttendanceWorkspace() {
  const language = useAppStore(state => state.language);
  const isBengali = language === 'bn';
  const dict = isBengali ? BN_DICT : EN_DICT;

  const academicClasses = useAppStore(state => state.academicClasses) || [];
  const academicSections = useAppStore(state => state.academicSections) || [];
  const students = useAppStore(state => state.students) || [];
  
  const { loadAttendance, saveAttendance, attendanceRecords, loading, error } = useStudentAttendanceStore();

  const [selectedClass, setSelectedClass] = useState<string>('');
  const [selectedSection, setSelectedSection] = useState<string>('');
  const [selectedDate, setSelectedDate] = useState<string>(new Date().toISOString().split('T')[0]);
  
  const [localRecords, setLocalRecords] = useState<Record<string, StudentAttendance>>({});
  const [unsavedChanges, setUnsavedChanges] = useState(false);

  // Filter sections by class
  const availableSections = academicSections.filter(s => s.classId === selectedClass);
  
  // Filter students by class and section
  const targetStudents = students.filter(s => 
    s.classId === selectedClass && 
    (selectedSection ? s.sectionId === selectedSection : true)
  );

  useEffect(() => {
    if (selectedClass && selectedSection && selectedDate) {
      loadAttendance(selectedClass, selectedSection, selectedDate);
    }
  }, [selectedClass, selectedSection, selectedDate]);

  useEffect(() => {
    // Populate local records from store
    const map: Record<string, StudentAttendance> = {};
    attendanceRecords.forEach(r => {
      map[r.studentId] = r;
    });
    setLocalRecords(map);
    setUnsavedChanges(false);
  }, [attendanceRecords]);

  const handleStatusChange = (studentId: string, status: StudentAttendance['status']) => {
    setLocalRecords(prev => {
      const existing = prev[studentId];
      return {
        ...prev,
        [studentId]: {
          id: existing?.id || generateId('att_'),
          studentId,
          classId: selectedClass,
          sectionId: selectedSection,
          date: selectedDate,
          status,
          createdAt: existing?.createdAt || new Date().toISOString(),
          updatedAt: new Date().toISOString(),
          recordedBy: 'currentUser'
        }
      };
    });
    setUnsavedChanges(true);
  };

  const handleNoteChange = (studentId: string, note: string) => {
    setLocalRecords(prev => {
      const existing = prev[studentId];
      if (!existing) return prev;
      return {
        ...prev,
        [studentId]: {
          ...existing,
          note,
          updatedAt: new Date().toISOString()
        }
      };
    });
    setUnsavedChanges(true);
  };

  const markAll = (status: StudentAttendance['status']) => {
    const map: Record<string, StudentAttendance> = { ...localRecords };
    targetStudents.forEach(student => {
      const existing = map[student.id];
      map[student.id] = {
        id: existing?.id || generateId('att_'),
        studentId: student.id,
        classId: selectedClass,
        sectionId: selectedSection,
        date: selectedDate,
        status,
        createdAt: existing?.createdAt || new Date().toISOString(),
        updatedAt: new Date().toISOString(),
        recordedBy: 'currentUser',
        note: existing?.note
      };
    });
    setLocalRecords(map);
    setUnsavedChanges(true);
  };

  const handleSave = async () => {
    await saveAttendance(Object.values(localRecords));
    setUnsavedChanges(false);
    alert(isBengali ? 'হাজিরা সেভ হয়েছে' : 'Attendance Saved');
  };

  return (
    <div className="p-6">
      <div className="flex justify-between items-center mb-6">
        <div>
          <h1 className="text-2xl font-bold text-gray-900">{isBengali ? 'শিক্ষার্থী হাজিরা' : 'Student Attendance'}</h1>
          <p className="text-gray-500">{isBengali ? 'দৈনিক হাজিরা খাতা' : 'Daily attendance register'}</p>
        </div>
        <button
          onClick={handleSave}
          disabled={!unsavedChanges || loading}
          className="flex items-center space-x-2 bg-indigo-600 hover:bg-indigo-700 text-white px-4 py-2 rounded-lg disabled:opacity-50"
        >
          <Save className="w-5 h-5" />
          <span>{isBengali ? 'সংরক্ষণ করুন' : 'Save Attendance'}</span>
        </button>
      </div>

      <div className="bg-white rounded-xl shadow-sm border border-gray-200 p-4 mb-6">
        <div className="grid grid-cols-1 md:grid-cols-3 gap-4">
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">{isBengali ? 'শ্রেণি' : 'Class'}</label>
            <select
              value={selectedClass}
              onChange={(e) => {
                setSelectedClass(e.target.value);
                setSelectedSection('');
              }}
              className="w-full rounded-lg border-gray-300 border px-3 py-2"
            >
              <option value="">{isBengali ? '-- নির্বাচন করুন --' : '-- Select --'}</option>
              {academicClasses.map(c => (
                <option key={c.id} value={c.id}>{isBengali ? c.nameBn || c.name : c.name}</option>
              ))}
            </select>
          </div>
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">{isBengali ? 'শাখা' : 'Section'}</label>
            <select
              value={selectedSection}
              onChange={(e) => setSelectedSection(e.target.value)}
              disabled={!selectedClass}
              className="w-full rounded-lg border-gray-300 border px-3 py-2 disabled:bg-gray-100"
            >
              <option value="">{isBengali ? '-- নির্বাচন করুন --' : '-- Select --'}</option>
              {availableSections.map(s => (
                <option key={s.id} value={s.id}>{isBengali ? s.nameBn || s.name : s.name}</option>
              ))}
            </select>
          </div>
          <div>
            <label className="block text-sm font-medium text-gray-700 mb-1">{isBengali ? 'তারিখ' : 'Date'}</label>
            <input
              type="date"
              value={selectedDate}
              onChange={(e) => setSelectedDate(e.target.value)}
              className="w-full rounded-lg border-gray-300 border px-3 py-2"
            />
          </div>
        </div>
      </div>

      {selectedClass && selectedSection && (
        <div className="bg-white rounded-xl shadow-sm border border-gray-200 overflow-hidden">
          <div className="p-4 border-b border-gray-200 flex justify-between items-center bg-gray-50">
            <h2 className="font-semibold text-gray-700">
              {targetStudents.length} {isBengali ? 'জন শিক্ষার্থী পাওয়া গেছে' : 'Students found'}
            </h2>
            <div className="flex space-x-2">
              <button onClick={() => markAll('present')} className="text-sm px-3 py-1 bg-green-100 text-green-700 rounded hover:bg-green-200">
                {isBengali ? 'সবাইকে উপস্থিত দিন' : 'Mark All Present'}
              </button>
              <button onClick={() => markAll('absent')} className="text-sm px-3 py-1 bg-red-100 text-red-700 rounded hover:bg-red-200">
                {isBengali ? 'সবাইকে অনুপস্থিত দিন' : 'Mark All Absent'}
              </button>
            </div>
          </div>
          
          <div className="overflow-x-auto">
            <table className="min-w-full divide-y divide-gray-200">
              <thead className="bg-gray-50">
                <tr>
                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase">{isBengali ? 'রোল' : 'Roll'}</th>
                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase">{isBengali ? 'নাম' : 'Name'}</th>
                  <th className="px-6 py-3 text-center text-xs font-medium text-gray-500 uppercase">{isBengali ? 'হাজিরা' : 'Status'}</th>
                  <th className="px-6 py-3 text-left text-xs font-medium text-gray-500 uppercase">{isBengali ? 'মন্তব্য' : 'Note'}</th>
                </tr>
              </thead>
              <tbody className="bg-white divide-y divide-gray-200">
                {targetStudents.length === 0 ? (
                  <tr>
                    <td colSpan={4} className="px-6 py-8 text-center text-gray-500">
                      {isBengali ? 'কোনো শিক্ষার্থী পাওয়া যায়নি' : 'No students found'}
                    </td>
                  </tr>
                ) : (
                  targetStudents.map(student => {
                    const record = localRecords[student.id];
                    return (
                      <tr key={student.id} className="hover:bg-gray-50">
                        <td className="px-6 py-4 whitespace-nowrap text-sm text-gray-900">{student.roll}</td>
                        <td className="px-6 py-4 whitespace-nowrap text-sm text-gray-900">{isBengali ? student.nameBn || student.name : student.name}</td>
                        <td className="px-6 py-4 whitespace-nowrap text-center">
                          <div className="inline-flex rounded-md shadow-sm" role="group">
                            <button
                              onClick={() => handleStatusChange(student.id, 'present')}
                              className={`px-3 py-1 text-sm font-medium border rounded-l-lg ${record?.status === 'present' ? 'bg-green-600 text-white border-green-600' : 'bg-white text-gray-700 border-gray-300 hover:bg-gray-50'}`}
                            >
                              {isBengali ? 'উপস্থিত' : 'Present'}
                            </button>
                            <button
                              onClick={() => handleStatusChange(student.id, 'absent')}
                              className={`px-3 py-1 text-sm font-medium border-t border-b border-r ${record?.status === 'absent' ? 'bg-red-600 text-white border-red-600' : 'bg-white text-gray-700 border-gray-300 hover:bg-gray-50'}`}
                            >
                              {isBengali ? 'অনুপস্থিত' : 'Absent'}
                            </button>
                            <button
                              onClick={() => handleStatusChange(student.id, 'late')}
                              className={`px-3 py-1 text-sm font-medium border-t border-b border-r ${record?.status === 'late' ? 'bg-yellow-500 text-white border-yellow-500' : 'bg-white text-gray-700 border-gray-300 hover:bg-gray-50'}`}
                            >
                              {isBengali ? 'বিলম্বে' : 'Late'}
                            </button>
                            <button
                              onClick={() => handleStatusChange(student.id, 'leave')}
                              className={`px-3 py-1 text-sm font-medium border-t border-b border-r rounded-r-lg ${record?.status === 'leave' ? 'bg-blue-600 text-white border-blue-600' : 'bg-white text-gray-700 border-gray-300 hover:bg-gray-50'}`}
                            >
                              {isBengali ? 'ছুটি' : 'Leave'}
                            </button>
                          </div>
                        </td>
                        <td className="px-6 py-4 whitespace-nowrap">
                          <input
                            type="text"
                            value={record?.note || ''}
                            onChange={(e) => handleNoteChange(student.id, e.target.value)}
                            placeholder={isBengali ? 'মন্তব্য (ঐচ্ছিক)' : 'Note (optional)'}
                            className="w-full text-sm border-gray-300 rounded-md px-2 py-1 border focus:ring-indigo-500 focus:border-indigo-500"
                          />
                        </td>
                      </tr>
                    );
                  })
                )}
              </tbody>
            </table>
          </div>
        </div>
      )}
    </div>
  );
}
