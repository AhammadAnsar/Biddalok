import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useEffect, useState } from 'react';
import { useAppStore } from '../../../../store/useAppStore';
import { db } from '../../../../db/database';
import { SyncQueueRecord, MessageQueueRecord } from '../../../../types';
import { RefreshCw, CheckCircle2, AlertCircle, Clock, Smartphone, CloudOff } from 'lucide-react';

export const SyncQueueTab: React.FC = () => {
  const { language } = useAppStore();
  const isBn = language === 'bn';
  const [syncQueue, setSyncQueue] = useState<SyncQueueRecord[]>([]);
  const [messageQueue, setMessageQueue] = useState<MessageQueueRecord[]>([]);

  const loadQueues = async () => {
    try {
      const syncs = await (db as any).syncQueue.toArray();
      const msgs = await (db as any).messageQueue.toArray();
      setSyncQueue(syncs.reverse());
      setMessageQueue(msgs.reverse());
    } catch (err) {
      console.error(err);
    }
  };

  useEffect(() => {
    loadQueues();
    const interval = setInterval(loadQueues, 5000);
    return () => clearInterval(interval);
  }, []);

  return (
    <div className="space-y-6">
      <div className="bg-white rounded-2xl shadow-sm border border-slate-200 p-6">
        <div className="flex items-center justify-between mb-4">
          <h2 className="text-lg font-black text-slate-800 flex items-center gap-2">
            <CloudOff className="w-5 h-5 text-indigo-600" />
            {isBn ? BN_DICT['offline_sync_outbox_phase_14'] : EN_DICT['offline_sync_outbox_phase_14']}
          </h2>
          <button onClick={loadQueues} className="p-2 hover:bg-slate-100 rounded-lg text-slate-500">
            <RefreshCw className="w-4 h-4" />
          </button>
        </div>
        
        <div className="space-y-3">
          {syncQueue.length === 0 ? (
            <p className="text-slate-500 text-sm">{isBn ? BN_DICT['no_pending_sync_items'] : EN_DICT['no_pending_sync_items']}</p>
          ) : (
            syncQueue.map(item => (
              <div key={item.id} className="flex items-center justify-between p-3 bg-slate-50 border border-slate-100 rounded-xl">
                <div>
                  <p className="text-sm font-semibold text-slate-800">
                    {item.entityType} ({item.operation})
                  </p>
                  <p className="text-xs text-slate-500">{new Date(item.createdAt).toLocaleString()}</p>
                </div>
                <div className="flex items-center gap-2">
                  <span className={`px-2.5 py-1 rounded-full text-xs font-bold ${
                    item.status === 'pending' ? 'bg-amber-100 text-amber-700' :
                    item.status === 'failed' ? 'bg-rose-100 text-rose-700' :
                    'bg-emerald-100 text-emerald-700'
                  }`}>
                    {item.status}
                  </span>
                </div>
              </div>
            ))
          )}
        </div>
      </div>

      <div className="bg-white rounded-2xl shadow-sm border border-slate-200 p-6">
        <div className="flex items-center justify-between mb-4">
          <h2 className="text-lg font-black text-slate-800 flex items-center gap-2">
            <Smartphone className="w-5 h-5 text-teal-600" />
            {isBn ? BN_DICT['message_queue'] : EN_DICT['message_queue']}
          </h2>
        </div>
        
        <div className="space-y-3">
          {messageQueue.length === 0 ? (
            <p className="text-slate-500 text-sm">{isBn ? BN_DICT['no_queued_messages'] : EN_DICT['no_queued_messages']}</p>
          ) : (
            messageQueue.map(item => (
              <div key={item.id} className="flex items-center justify-between p-3 bg-slate-50 border border-slate-100 rounded-xl">
                <div>
                  <p className="text-sm font-semibold text-slate-800">
                    {item.contactNumber}
                  </p>
                  <p className="text-xs text-slate-500 truncate max-w-md">{item.messageText}</p>
                  {item.providerResponse && (
                    <p className="text-xs text-indigo-600 font-mono mt-1">{item.providerResponse}</p>
                  )}
                </div>
                <div className="flex items-center gap-2">
                  <span className={`px-2.5 py-1 rounded-full text-xs font-bold ${
                    item.status === 'queued' ? 'bg-amber-100 text-amber-700' :
                    item.status === 'failed' ? 'bg-rose-100 text-rose-700' :
                    'bg-emerald-100 text-emerald-700'
                  }`}>
                    {item.status}
                  </span>
                </div>
              </div>
            ))
          )}
        </div>
      </div>
    </div>
  );
};
