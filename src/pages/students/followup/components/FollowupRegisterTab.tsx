import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState, useMemo } from 'react';
import { useAppStore } from '../../../../store/useAppStore';
import {
  WifiOff,
  ClipboardList,
  Search,
  FileDown,
  Eye,
  CheckCircle2,
  AlertTriangle,
  RefreshCcw,
  MapPin,
  Smartphone,
  X,
  Send,
  Printer,
  Calendar,
  Users,
  Check,
  Building,
  Filter,
} from 'lucide-react';
import { FollowupVisit, FollowupAssignment, Student, FollowupCampaign, FollowupTeam } from '../../../../types';
import { VisitDetailsModal, MappedVisit } from '../modals/VisitDetailsModal';
import { exportFollowupRegisterPdf } from '../utils/followupPdfExport';
import { FollowupRegisterPrintModal } from '../modals/FollowupRegisterPrintModal';
import { toBengaliNumber } from '../../../../utils/bengaliUtils';
import { toast } from '../../../../utils/toast';
import { enqueueMessage, processMessageQueue } from '../../../../services/messagingAdapter';

export const FollowupRegisterTab: React.FC = () => {
  const {
    language,
    followupVisits,
    followupAssignments,
    students,
    followupCampaigns,
    followupTeams,
    academicClasses,
    institution,
    staff,
  } = useAppStore();
  const isBn = language === 'bn';

  // Campaign selection (default to first campaign)
  const [selectedCampaignId, setSelectedCampaignId] = useState<string>(() => {
    return followupCampaigns[0]?.id || '';
  });
  const [selectedTeamId, setSelectedTeamId] = useState<string>('all');
  const [search, setSearch] = useState('');
  const [selectedClass, setSelectedClass] = useState('');
  const [selectedOutcome, setSelectedOutcome] = useState('');
  const [selectedVisit, setSelectedVisit] = useState<MappedVisit | null>(null);
  const [isDetailsModalOpen, setIsDetailsModalOpen] = useState(false);
  const [isPrintModalOpen, setIsPrintModalOpen] = useState(false);
  const [isDownloadingPdf, setIsDownloadingPdf] = useState(false);
  const [isSmsModalOpen, setIsSmsModalOpen] = useState(false);
  const [smsRecipient, setSmsRecipient] = useState<any>(null);

  // Active campaign object
  const activeCampaign = useMemo(() => {
    if (selectedCampaignId && selectedCampaignId !== 'all') {
      return followupCampaigns.find(c => c.id === selectedCampaignId) || followupCampaigns[0] || null;
    }
    return followupCampaigns[0] || null;
  }, [selectedCampaignId, followupCampaigns]);

  // Teams associated with the active campaign
  const campaignTeams = useMemo(() => {
    if (!activeCampaign) return [];
    return followupTeams.filter(t => t.campaignId === activeCampaign.id);
  }, [activeCampaign, followupTeams]);

  // Active team object
  const activeTeam = useMemo(() => {
    if (selectedTeamId && selectedTeamId !== 'all') {
      return campaignTeams.find(t => t.id === selectedTeamId) || null;
    }
    return null;
  }, [selectedTeamId, campaignTeams]);

  // Resolved team leader for the active campaign / team
  const resolvedLeaderText = useMemo(() => {
    if (activeTeam) {
      const leader = staff.find(s => s.id === activeTeam.leaderId);
      if (leader) {
        return (isBn && leader.nameBn ? leader.nameBn : leader.name) + 
          (leader.designationBn || leader.designation ? ` (${leader.designationBn || leader.designation})` : '');
      }
    } else if (campaignTeams.length > 0) {
      const leaders = campaignTeams
        .map(t => staff.find(s => s.id === t.leaderId))
        .filter(Boolean)
        .map(l => (isBn && l!.nameBn ? l!.nameBn : l!.name));
      if (leaders.length > 0) return leaders.join(', ');
    }
    return isBn ? BN_DICT['designated_teacher'] : EN_DICT['designated_teacher'];
  }, [activeTeam, campaignTeams, staff, isBn]);

  // Map all data with relational references
  const visitRecords = useMemo(() => {
    return followupVisits
      .map(visit => {
        const assignment = followupAssignments.find(a => a.id === visit.assignmentId);
        const student = students.find(s => s.id === visit.studentId);
        const campaign = followupCampaigns.find(c => c.id === visit.campaignId);
        const team = followupTeams.find(t => t.id === visit.teamId);

        return {
          ...visit,
          student,
          assignment,
          campaign,
          team,
        };
      })
      .filter(record => Boolean(record.student));
  }, [followupVisits, followupAssignments, students, followupCampaigns, followupTeams]);

  // Filter records by campaign, team, class, outcome, search
  const filteredRecords = useMemo(() => {
    return visitRecords.filter(record => {
      const { student } = record;
      if (!student) return false;

      // Filter by campaign
      if (selectedCampaignId && selectedCampaignId !== 'all') {
        if (record.campaignId !== selectedCampaignId) return false;
      }

      // Filter by team
      if (selectedTeamId && selectedTeamId !== 'all') {
        if (record.teamId !== selectedTeamId) return false;
      }

      // Filter by class
      if (selectedClass && student.class !== selectedClass) return false;

      // Filter by outcome
      if (selectedOutcome && record.outcome !== selectedOutcome) return false;

      // Search query
      if (search) {
        const q = search.toLowerCase();
        const matchesName = student.name?.toLowerCase().includes(q);
        const matchesNameBn = student.nameBn?.includes(search);
        const matchesId = student.studentId?.toLowerCase().includes(q);
        const matchesFather = student.fatherName?.toLowerCase().includes(q) || student.fatherNameBn?.includes(search);
        const matchesPhone = student.fatherMobile?.includes(search) || student.motherMobile?.includes(search);
        if (!matchesName && !matchesNameBn && !matchesId && !matchesFather && !matchesPhone) {
          return false;
        }
      }

      return true;
    });
  }, [visitRecords, selectedCampaignId, selectedTeamId, selectedClass, selectedOutcome, search]);

  // Direct PDF export
  const handleExportPdf = async () => {
    if (!activeCampaign) {
      alert(isBn ? BN_DICT['please_select_a_campaign'] : EN_DICT['please_select_a_campaign']);
      return;
    }
    try {
      setIsDownloadingPdf(true);
      await exportFollowupRegisterPdf(filteredRecords, isBn, {
        campaign: activeCampaign,
        team: activeTeam,
        institution,
        staff,
      });
    } catch (err) {
      console.error('PDF export failed:', err);
      alert(isBn ? BN_DICT['error_generating_pdf'] : EN_DICT['error_generating_pdf']);
    } finally {
      setIsDownloadingPdf(false);
    }
  };

  // CSV Export for tabular records
  const handleExportCsv = () => {
    const headers = [
      'Sl', 'Date', 'Student ID', 'Student Name', 'Class', 'Roll', 'Father Name', 'Mobile', 'Address', 'Status', 'Environment', 'Guardian Feedback', 'Outcome', 'Teacher Observations'
    ];

    const csvContent = [
      headers.join(','),
      ...filteredRecords.map((r, i) => {
        const date = new Date(r.visitDate).toLocaleDateString('en-US');
        const s = r.student;
        const sName = (s?.nameBn || s?.name || '').replace(/,/g, ' ');
        const sClass = s?.class || '';
        const sRoll = s?.roll || '';
        const fName = (s?.fatherNameBn || s?.fatherName || '').replace(/,/g, ' ');
        const phone = s?.fatherMobile || s?.motherMobile || '';
        const addr = (s?.presentAddress || s?.village || '').replace(/,/g, ' ');
        const status = r.studentFound ? 'Present' : 'Absent';
        const env = r.studyEnvironment || '';
        const feedback = ((r as any).guardianFeedback || '').replace(/,/g, ';');
        const outcome = r.outcome || '';
        const obs = (r.teacherObservation || '').replace(/,/g, ';');
        return `"${i + 1}","${date}","${s?.studentId || ''}","${sName}","${sClass}","${sRoll}","${fName}","${phone}","${addr}","${status}","${env}","${feedback}","${outcome}","${obs}"`;
      })
    ].join('\n');

    const blob = new Blob([csvContent], { type: 'text/csv;charset=utf-8;' });
    const url = URL.createObjectURL(blob);
    const link = document.createElement('a');
    link.href = url;
    link.setAttribute('download', `Followup_Register_${activeCampaign?.title || 'All'}.csv`);
    document.body.appendChild(link);
    link.click();
    document.body.removeChild(link);
  };

  const handleOpenSms = (record: any) => {
    setSmsRecipient(record);
    setIsSmsModalOpen(true);
  };

    const handleSendSms = async (e: React.FormEvent) => {
    e.preventDefault();
    if (!smsRecipient || !smsRecipient.student) return;

    const contactNumber = smsRecipient.student.fatherMobile || smsRecipient.student.motherMobile || '';
    if (!contactNumber) {
      toast.error(isBn ? BN_DICT['no_mobile_number_found'] : EN_DICT['no_mobile_number_found']);
      return;
    }

    const messageText = (document.getElementById('smsContent') as HTMLTextAreaElement)?.value || '';

    try {
      await enqueueMessage(smsRecipient.student.id, contactNumber, messageText, 'followup_sms');
      toast.success(isBn ? BN_DICT['sms_queued_successfully'] : EN_DICT['sms_queued_successfully']);
      setIsSmsModalOpen(false);
      // Trigger background process
      processMessageQueue().catch(console.error);
    } catch (err) {
      toast.error(isBn ? BN_DICT['failed_to_queue_sms'] : EN_DICT['failed_to_queue_sms']);
    }
  };

  const handleViewDetails = (record: any) => {
    setSelectedVisit(record);
    setIsDetailsModalOpen(true);
  };

  const getOutcomeBadge = (outcome?: string) => {
    switch (outcome) {
      case 'satisfactory':
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-emerald-100 text-emerald-800">
            <CheckCircle2 className="w-3 h-3" />
            {isBn ? BN_DICT['satisfactory'] : EN_DICT['satisfactory']}
          </span>
        );
      case 'monitoring':
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-amber-100 text-amber-800">
            <AlertTriangle className="w-3 h-3" />
            {isBn ? BN_DICT['monitoring'] : EN_DICT['monitoring']}
          </span>
        );
      case 're_followup':
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-rose-100 text-rose-800">
            <RefreshCcw className="w-3 h-3" />
            {isBn ? BN_DICT['re_followup'] : EN_DICT['re_followup']}
          </span>
        );
      case 'school_intervention':
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-purple-100 text-purple-800">
            <Building className="w-3 h-3" />
            {isBn ? BN_DICT['intervention'] : EN_DICT['intervention']}
          </span>
        );
      default:
        return (
          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[11px] font-semibold bg-slate-100 text-slate-700">
            {isBn ? BN_DICT['unspecified'] : EN_DICT['unspecified']}
          </span>
        );
    }
  };

  const getPersonMetText = (personMet?: string) => {
    switch (personMet) {
      case 'father': return isBn ? BN_DICT['father_1'] : EN_DICT['father_1'];
      case 'mother': return isBn ? BN_DICT['mother_1'] : EN_DICT['mother_1'];
      case 'student': return isBn ? BN_DICT['student'] : EN_DICT['student'];
      case 'other_guardian': return isBn ? BN_DICT['other_guardian'] : EN_DICT['other_guardian'];
      default: return isBn ? BN_DICT['unknown'] : EN_DICT['unknown'];
    }
  };

  return (
    <div className="space-y-6">
      {/* Page Header with Actions */}
      <div className="flex flex-col lg:flex-row justify-between items-start lg:items-center gap-4 bg-white p-5 rounded-2xl border border-slate-200 shadow-sm">
        <div>
          <div className="flex items-center gap-2.5">
            <div className="p-2.5 bg-indigo-50 text-indigo-700 rounded-xl">
              <ClipboardList className="w-6 h-6" />
            </div>
            <div>
              <h2 className="text-xl font-bold text-slate-800">
                {isBn ? BN_DICT['digital_follow_up_visit_regist'] : EN_DICT['digital_follow_up_visit_regist']}
              </h2>
              <p className="text-xs text-slate-500">
                {isBn ? BN_DICT['campaign_based_official_regist'] : EN_DICT['campaign_based_official_regist']}
              </p>
            </div>
          </div>
        </div>

        {/* Action Buttons: Print / Official PDF / CSV */}
        <div className="flex items-center flex-wrap gap-2.5 w-full lg:w-auto">
          <button
            onClick={() => setIsPrintModalOpen(true)}
            disabled={!activeCampaign || filteredRecords.length === 0}
            className="flex items-center gap-2 px-4 py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-xs font-bold shadow-md shadow-indigo-600/20 transition-all disabled:opacity-50"
            title={isBn ? BN_DICT['preview_and_print_in_official'] : EN_DICT['preview_and_print_in_official']}
          >
            <Printer className="w-4 h-4" />
            <span>{isBn ? BN_DICT['official_register_print_pdf'] : EN_DICT['official_register_print_pdf']}</span>
          </button>

          <button
            onClick={handleExportPdf}
            disabled={isDownloadingPdf || !activeCampaign || filteredRecords.length === 0}
            className="flex items-center gap-2 px-3.5 py-2.5 bg-emerald-600 hover:bg-emerald-700 text-white rounded-xl text-xs font-bold shadow-md shadow-emerald-600/20 transition-all disabled:opacity-50"
            title={isBn ? BN_DICT['directly_download_pdf_file'] : EN_DICT['directly_download_pdf_file']}
          >
            {isDownloadingPdf ? (
              <div className="w-4 h-4 border-2 border-white/30 border-t-white rounded-full animate-spin" />
            ) : (
              <FileDown className="w-4 h-4" />
            )}
            <span>{isBn ? BN_DICT['download_pdf'] : EN_DICT['download_pdf']}</span>
          </button>

          <button
            onClick={handleExportCsv}
            disabled={filteredRecords.length === 0}
            className="flex items-center gap-1.5 px-3 py-2.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl text-xs font-semibold transition-colors disabled:opacity-50"
            title={isBn ? BN_DICT['export_csv_data'] : EN_DICT['export_csv_data']}
          >
            <FileDown className="w-3.5 h-3.5" />
            <span>{isBn ? BN_DICT['csv_export'] : EN_DICT['csv_export']}</span>
          </button>
        </div>
      </div>

      {/* Campaign Selector Bar - Mandatory for separate campaign registers */}
      <div className="bg-white p-4 rounded-2xl border border-slate-200 shadow-sm space-y-4">
        <div className="flex flex-col md:flex-row items-start md:items-center justify-between gap-3 pb-3 border-b border-slate-100">
          <div className="flex items-center gap-2">
            <span className="text-xs font-bold text-slate-700 uppercase tracking-wider flex items-center gap-1">
              <Calendar className="w-3.5 h-3.5 text-indigo-600" />
              {isBn ? BN_DICT['select_campaign'] : EN_DICT['select_campaign']}
            </span>
            <select
              value={selectedCampaignId}
              onChange={e => {
                setSelectedCampaignId(e.target.value);
                setSelectedTeamId('all');
              }}
              className="px-3 py-2 bg-slate-50 border border-slate-300 rounded-xl text-xs font-bold text-slate-800 focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 min-w-[240px]"
            >
              {followupCampaigns.map(c => (
                <option key={c.id} value={c.id}>
                  {c.title} ({toBengaliNumber(c.academicYear)})
                </option>
              ))}
              <option value="all">{isBn ? BN_DICT['all_campaigns'] : EN_DICT['all_campaigns']}</option>
            </select>
          </div>

          {/* Campaign Metadata Badge */}
          {activeCampaign && (
            <div className="flex items-center gap-3 text-xs text-slate-600 flex-wrap">
              <div className="bg-slate-100 px-2.5 py-1 rounded-lg">
                <span className="text-slate-500">{isBn ? BN_DICT['year_3'] : EN_DICT['year_3']}</span>
                <strong className="text-slate-800">{toBengaliNumber(activeCampaign.academicYear)}</strong>
              </div>
              <div className="bg-slate-100 px-2.5 py-1 rounded-lg">
                <span className="text-slate-500">{isBn ? BN_DICT['teams'] : EN_DICT['teams']}</span>
                <strong className="text-slate-800">{toBengaliNumber(campaignTeams.length)}</strong>
              </div>
              <div className="bg-slate-100 px-2.5 py-1 rounded-lg">
                <span className="text-slate-500">{isBn ? BN_DICT['visits'] : EN_DICT['visits']}</span>
                <strong className="text-indigo-700">{toBengaliNumber(filteredRecords.length)}</strong>
              </div>
              <span className={`px-2.5 py-1 rounded-lg font-semibold text-[11px] ${
                activeCampaign.status === 'active' ? 'bg-emerald-100 text-emerald-800' :
                activeCampaign.status === 'completed' ? 'bg-blue-100 text-blue-800' : 'bg-slate-100 text-slate-700'
              }`}>
                {activeCampaign.status === 'active' ? (isBn ? BN_DICT['active'] : EN_DICT['active']) :
                 activeCampaign.status === 'completed' ? (isBn ? BN_DICT['completed'] : EN_DICT['completed']) : activeCampaign.status}
              </span>
            </div>
          )}
        </div>

        {/* Secondary Filter Controls: Team, Class, Outcome, Search */}
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3">
          {/* Team filter */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">
              {isBn ? BN_DICT['filter_by_team'] : EN_DICT['filter_by_team']}
            </label>
            <select
              value={selectedTeamId}
              onChange={e => setSelectedTeamId(e.target.value)}
              className="w-full px-3 py-2 bg-white border border-slate-200 rounded-xl text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
            >
              <option value="all">{isBn ? BN_DICT['all_teams'] : EN_DICT['all_teams']}</option>
              {campaignTeams.map(t => (
                <option key={t.id} value={t.id}>
                  {t.name}
                </option>
              ))}
            </select>
          </div>

          {/* Class filter */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">
              {isBn ? BN_DICT['class_2'] : EN_DICT['class_2']}
            </label>
            <select
              value={selectedClass}
              onChange={e => setSelectedClass(e.target.value)}
              className="w-full px-3 py-2 bg-white border border-slate-200 rounded-xl text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
            >
              <option value="">{isBn ? BN_DICT['all_classes'] : EN_DICT['all_classes']}</option>
              {academicClasses.map(c => (
                <option key={c.id} value={c.name}>
                  {isBn && c.nameBn ? c.nameBn : c.name}
                </option>
              ))}
            </select>
          </div>

          {/* Outcome filter */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">
              {isBn ? BN_DICT['outcome'] : EN_DICT['outcome']}
            </label>
            <select
              value={selectedOutcome}
              onChange={e => setSelectedOutcome(e.target.value)}
              className="w-full px-3 py-2 bg-white border border-slate-200 rounded-xl text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
            >
              <option value="">{isBn ? BN_DICT['all_outcomes'] : EN_DICT['all_outcomes']}</option>
              <option value="satisfactory">{isBn ? BN_DICT['satisfactory'] : EN_DICT['satisfactory']}</option>
              <option value="monitoring">{isBn ? BN_DICT['monitoring'] : EN_DICT['monitoring']}</option>
              <option value="re_followup">{isBn ? BN_DICT['re_followup'] : EN_DICT['re_followup']}</option>
              <option value="school_intervention">{isBn ? BN_DICT['counseling'] : EN_DICT['counseling']}</option>
            </select>
          </div>

          {/* Search bar */}
          <div>
            <label className="block text-[11px] font-semibold text-slate-600 mb-1">
              {isBn ? BN_DICT['search_student_parent'] : EN_DICT['search_student_parent']}
            </label>
            <div className="relative">
              <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-3.5 h-3.5 text-slate-400" />
              <input
                type="text"
                placeholder={isBn ? BN_DICT['name_id_phone'] : EN_DICT['name_id_phone']}
                value={search}
                onChange={e => setSearch(e.target.value)}
                className="w-full pl-8 pr-3 py-2 bg-white border border-slate-200 rounded-xl text-xs focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 transition-all"
              />
            </div>
          </div>
        </div>
      </div>

      {/* Official 11-Column Register Table */}
      <div className="bg-white rounded-2xl border border-slate-200 overflow-hidden shadow-sm">
        <div className="overflow-x-auto custom-scrollbar">
          <table className="w-full text-left border-collapse" style={{ minWidth: '1080px' }}>
            <thead>
              <tr className="bg-slate-50 border-b border-slate-200 text-[11px] font-bold text-slate-700 uppercase tracking-wider">
                <th className="px-3 py-3.5 text-center w-12">{isBn ? BN_DICT['sl_1'] : EN_DICT['sl_1']}</th>
                <th className="px-3 py-3.5 w-28">{isBn ? BN_DICT['date_time'] : EN_DICT['date_time']}</th>
                <th className="px-3 py-3.5 w-44">{isBn ? BN_DICT['student_name_id'] : EN_DICT['student_name_id']}</th>
                <th className="px-3 py-3.5 w-40">{isBn ? BN_DICT['parents_name'] : EN_DICT['parents_name']}</th>
                <th className="px-3 py-3.5 w-36">{isBn ? BN_DICT['address'] : EN_DICT['address']}</th>
                <th className="px-3 py-3.5 w-44">{isBn ? BN_DICT['observed_status'] : EN_DICT['observed_status']}</th>
                <th className="px-3 py-3.5 w-32">{isBn ? BN_DICT['study_env'] : EN_DICT['study_env']}</th>
                <th className="px-3 py-3.5 w-40">{isBn ? BN_DICT['guardian_feedback'] : EN_DICT['guardian_feedback']}</th>
                <th className="px-3 py-3.5 w-28 text-center">{isBn ? BN_DICT['decision'] : EN_DICT['decision']}</th>
                <th className="px-3 py-3.5 w-24 text-center">{isBn ? BN_DICT['signature'] : EN_DICT['signature']}</th>
                <th className="px-3 py-3.5 w-20 text-right">{isBn ? BN_DICT['action'] : EN_DICT['action']}</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 text-xs">
              {filteredRecords.length === 0 ? (
                <tr>
                  <td colSpan={11} className="px-6 py-14 text-center text-slate-500">
                    <div className="flex flex-col items-center justify-center">
                      <ClipboardList className="w-12 h-12 text-slate-300 mb-3" />
                      <p className="text-base font-bold text-slate-700">
                        {isBn ? BN_DICT['no_visit_records_found'] : EN_DICT['no_visit_records_found']}
                      </p>
                      <p className="text-xs text-slate-400 mt-1">
                        {isBn ? BN_DICT['change_campaign_or_perform_vis'] : EN_DICT['change_campaign_or_perform_vis']}
                      </p>
                    </div>
                  </td>
                </tr>
              ) : (
                filteredRecords.map((record, idx) => {
                  const student = record.student;
                  const visitDateObj = new Date(record.visitDate);
                  let visitDateStr = record.visitDate || '-';
                  if (!isNaN(visitDateObj.getTime())) {
                    const vd = String(visitDateObj.getDate()).padStart(2, '0');
                    const vm = String(visitDateObj.getMonth() + 1).padStart(2, '0');
                    const vy = String(visitDateObj.getFullYear());
                    visitDateStr = `${toBengaliNumber(vd)}-${toBengaliNumber(vm)}-${toBengaliNumber(vy)}`;
                  }
                  const addressText = student?.presentAddress || 
                    [student?.village ? `গ্রাম: ${student.village}` : '', student?.postOffice ? `ডাক: ${student.postOffice}` : '', student?.upazila || ''].filter(Boolean).join(', ') ||
                    (isBn ? BN_DICT['n_a'] : EN_DICT['n_a']);

                  let formattedNextDate = record.nextFollowupDate;
                  if (record.nextFollowupDate) {
                    const nd = new Date(record.nextFollowupDate);
                    if (!isNaN(nd.getTime())) {
                      const day = String(nd.getDate()).padStart(2, '0');
                      const mon = String(nd.getMonth() + 1).padStart(2, '0');
                      const yr = String(nd.getFullYear());
                      formattedNextDate = `${toBengaliNumber(day)}-${toBengaliNumber(mon)}-${toBengaliNumber(yr)}`;
                    }
                  }

                  return (
                    <tr key={record.id} className="hover:bg-slate-50/70 transition-colors align-top">
                      {/* 1. ক্রম */}
                      <td className="px-3 py-3 text-center font-bold text-slate-600 font-mono">
                        {toBengaliNumber(idx + 1)}
                      </td>

                      {/* 2. তারিখ ও সময় */}
                      <td className="px-3 py-3">
                        <span className="font-semibold text-slate-800 block">{visitDateStr}</span>
                        {record.latitude && (
                          <div className="flex items-center gap-1 mt-1 text-[10px] font-medium text-emerald-700 bg-emerald-50 w-fit px-1.5 py-0.5 rounded">
                            <MapPin className="w-3 h-3" />
                            GPS
                          </div>
                        )}
                        {record.syncStatus === 'pending' && (
                          <div className="flex items-center gap-1 mt-1 text-[10px] font-medium text-amber-700 bg-amber-50 w-fit px-1.5 py-0.5 rounded">
                            <WifiOff className="w-3 h-3" />
                            {isBn ? BN_DICT['pending'] : EN_DICT['pending']}
                          </div>
                        )}
                      </td>

                      {/* 3. শিক্ষার্থীর নাম ও আইডি নম্বর */}
                      <td className="px-3 py-3">
                        <div className="flex items-start gap-2.5">
                          {student?.photo ? (
                            <img
                              src={student.photo}
                              alt={student.name}
                              className="w-8 h-8 rounded-full object-cover border border-slate-200 shrink-0 mt-0.5"
                            />
                          ) : (
                            <div className="w-8 h-8 rounded-full bg-slate-100 flex items-center justify-center text-slate-500 font-bold border border-slate-200 shrink-0 mt-0.5 text-xs">
                              {student?.name?.charAt(0) || 'S'}
                            </div>
                          )}
                          <div>
                            <p className="font-bold text-slate-800 text-[12.5px] leading-snug">
                              {isBn && student?.nameBn ? student.nameBn : (student?.name || 'শিক্ষার্থী')}
                            </p>
                            <p className="text-[11px] text-slate-500 mt-0.5">
                              ID: <span className="font-mono font-semibold">{student?.studentId}</span>
                            </p>
                            <p className="text-[10.5px] text-slate-600">
                              {student?.class} {student?.section && `(${student.section})`} {student?.roll && `• রোল: ${toBengaliNumber(student.roll)}`}
                            </p>
                          </div>
                        </div>
                      </td>

                      {/* 4. পিতা ও মাতার নাম */}
                      <td className="px-3 py-3 text-[11px]">
                        <div>
                          <span className="text-slate-500">{isBn ? BN_DICT['f_1'] : EN_DICT['f_1']}</span>
                          <span className="font-semibold text-slate-800">
                            {student?.fatherNameBn || student?.fatherName || '-'}
                          </span>
                        </div>
                        <div className="mt-0.5">
                          <span className="text-slate-500">{isBn ? BN_DICT['m_1'] : EN_DICT['m_1']}</span>
                          <span className="font-semibold text-slate-800">
                            {student?.motherNameBn || student?.motherName || '-'}
                          </span>
                        </div>
                        {(student?.fatherMobile || student?.motherMobile) && (
                          <div className="text-[10px] text-slate-500 mt-0.5 font-mono">
                            {toBengaliNumber(student?.fatherMobile || student?.motherMobile)}
                          </div>
                        )}
                      </td>

                      {/* 5. ঠিকানা */}
                      <td className="px-3 py-3 text-[11px] text-slate-600 leading-relaxed">
                        {addressText}
                      </td>

                      {/* 6. ফলোআপে প্রাপ্ত অবস্থা */}
                      <td className="px-3 py-3">
                        <span className={`inline-block px-1.5 py-0.5 rounded text-[10px] font-bold ${
                          record.studentFound ? 'bg-emerald-100 text-emerald-800' : 'bg-rose-100 text-rose-800'
                        }`}>
                          {record.studentFound ? (isBn ? BN_DICT['present'] : EN_DICT['present']) : (isBn ? BN_DICT['absent'] : EN_DICT['absent'])}
                        </span>
                        <p className="text-[11px] text-slate-800 mt-1 whitespace-normal break-words leading-relaxed font-medium">
                          {record.teacherObservation || (isBn ? BN_DICT['no_observation'] : EN_DICT['no_observation'])}
                        </p>
                      </td>

                      {/* 7. লেখাপড়ার পরিবেশ */}
                      <td className="px-3 py-3 text-[11px]">
                        <span className="font-semibold text-slate-800 block capitalize">
                          {record.studyEnvironment?.replace('_', ' ') || 'N/A'}
                        </span>
                        <span className="text-[10px] text-slate-500 block mt-0.5">
                          {isBn ? BN_DICT['met'] : EN_DICT['met']} {getPersonMetText(record.personMet)}
                        </span>
                      </td>

                      {/* 8. অভিভাবকের বক্তব্য */}
                      <td className="px-3 py-3 text-[11px] text-slate-800 leading-snug">
                        <p className="whitespace-normal break-words leading-relaxed">
                          {(record as any).guardianFeedback || (record.guardianConcerns?.join(', ') || (isBn ? BN_DICT['satisfactory'] : EN_DICT['satisfactory']))}
                        </p>
                      </td>

                      {/* 9. সিদ্ধান্ত */}
                      <td className="px-3 py-3 text-center">
                        <div>{getOutcomeBadge(record.outcome)}</div>
                        {formattedNextDate && (
                          <div className="text-[10px] text-indigo-700 font-semibold mt-1">
                            {formattedNextDate}
                          </div>
                        )}
                      </td>

                      {/* 10. অভিভাবকের স্বাক্ষর */}
                      <td className="px-3 py-3 text-center align-middle">
                        {record.guardianSignaturePath ? (
                          <div className="flex flex-col items-center">
                            <img
                              src={record.guardianSignaturePath}
                              alt="Sign"
                              className="max-h-6 max-w-10 object-contain mx-auto"
                            />
                            <span className="text-[9px] text-emerald-700 font-semibold mt-0.5">
                              {isBn ? BN_DICT['verified'] : EN_DICT['verified']}
                            </span>
                          </div>
                        ) : (
                          <span className="text-[10px] text-slate-400 italic">
                            {isBn ? BN_DICT['pending'] : EN_DICT['pending']}
                          </span>
                        )}
                      </td>

                      {/* 11. অ্যাকশন */}
                      <td className="px-3 py-3 text-right">
                        <div className="flex items-center justify-end gap-1">
                          <button
                            onClick={() => handleOpenSms(record)}
                            className="p-1.5 text-slate-400 hover:text-blue-600 hover:bg-blue-50 rounded-lg transition-colors"
                            title={isBn ? BN_DICT['send_sms'] : EN_DICT['send_sms']}
                          >
                            <Smartphone className="w-4 h-4" />
                          </button>
                          <button
                            onClick={() => handleViewDetails(record)}
                            className="p-1.5 text-slate-400 hover:text-indigo-600 hover:bg-indigo-50 rounded-lg transition-colors"
                            title={isBn ? BN_DICT['view_details'] : EN_DICT['view_details']}
                          >
                            <Eye className="w-4 h-4" />
                          </button>
                        </div>
                      </td>
                    </tr>
                  );
                })
              )}
            </tbody>
          </table>
        </div>

        {/* Footer Summary */}
        <div className="p-4 border-t border-slate-200 bg-slate-50 flex flex-col sm:flex-row items-center justify-between gap-3 text-xs text-slate-600">
          <p>
            {isBn
              ? `ক্যাম্পেইন: "${activeCampaign?.title || 'সকল'}" • মোট ${filteredRecords.length} টি ভিজিট রেজিস্টার রেকর্ড`
              : `Campaign: "${activeCampaign?.title || 'All'}" • Total ${filteredRecords.length} records`}
          </p>
          <div className="flex items-center gap-3">
            <button
              onClick={() => setIsPrintModalOpen(true)}
              disabled={!activeCampaign || filteredRecords.length === 0}
              className="flex items-center gap-1.5 text-indigo-700 font-bold hover:underline disabled:opacity-40"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>{isBn ? BN_DICT['print_preview_print'] : EN_DICT['print_preview_print']}</span>
            </button>
          </div>
        </div>
      </div>

      {/* Official Print & PDF Preview Modal */}
      {isPrintModalOpen && activeCampaign && (
        <FollowupRegisterPrintModal
          isOpen={isPrintModalOpen}
          onClose={() => setIsPrintModalOpen(false)}
          campaign={activeCampaign}
          team={activeTeam}
          records={filteredRecords}
          institution={institution}
          staff={staff}
          isBn={isBn}
        />
      )}

      {/* Single Visit Details Modal */}
      {selectedVisit && (
        <VisitDetailsModal
          isOpen={isDetailsModalOpen}
          onClose={() => setIsDetailsModalOpen(false)}
          visit={selectedVisit}
        />
      )}

      {/* SMS Modal */}
      {isSmsModalOpen && smsRecipient && (
        <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm">
          <div className="bg-white rounded-2xl shadow-xl w-full max-w-lg flex flex-col overflow-hidden">
            <div className="flex items-center justify-between p-5 border-b border-slate-100 bg-slate-50">
              <h3 className="text-base font-bold text-slate-800 flex items-center gap-2">
                <Smartphone className="w-4 h-4 text-blue-600" />
                {isBn ? BN_DICT['send_sms_to_guardian'] : EN_DICT['send_sms_to_guardian']}
              </h3>
              <button
                onClick={() => setIsSmsModalOpen(false)}
                className="p-1.5 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-lg transition-colors"
              >
                <X className="w-4 h-4" />
              </button>
            </div>
            <form onSubmit={handleSendSms} className="p-6">
              <div className="mb-4">
                <p className="text-xs font-medium text-slate-500 mb-1">{isBn ? BN_DICT['recipient'] : EN_DICT['recipient']}</p>
                <div className="bg-slate-50 p-3 rounded-xl border border-slate-200">
                  <p className="font-bold text-slate-800 text-sm">
                    {isBn && smsRecipient.student?.nameBn ? smsRecipient.student.nameBn : smsRecipient.student?.name}
                  </p>
                  <p className="text-xs text-slate-500">
                    {isBn ? BN_DICT['mobile_2'] : EN_DICT['mobile_2']} 
                    {smsRecipient.student?.fatherMobile || smsRecipient.student?.motherMobile || (isBn ? BN_DICT['n_a'] : EN_DICT['n_a'])}
                  </p>
                </div>
              </div>

              <div className="mb-6">
                <label className="block text-xs font-semibold text-slate-700 mb-1">
                  {isBn ? BN_DICT['message_template'] : EN_DICT['message_template']}
                </label>
                <select className="w-full px-3 py-2 bg-white border border-slate-200 rounded-xl text-xs focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 mb-2">
                  <option value="thank_you">{isBn ? BN_DICT['thank_you_for_your_time'] : EN_DICT['thank_you_for_your_time']}</option>
                  <option value="urgent">{isBn ? BN_DICT['urgent_meeting_requested'] : EN_DICT['urgent_meeting_requested']}</option>
                  <option value="custom">{isBn ? BN_DICT['custom_message'] : EN_DICT['custom_message']}</option>
                </select>

                <textarea
                  rows={4}
                  className="w-full px-3 py-2.5 bg-white border border-slate-200 rounded-xl text-xs focus:outline-none focus:ring-2 focus:ring-blue-500/20 focus:border-blue-500 resize-none"
                  defaultValue={
                    isBn
                      ? `সম্মানিত অভিভাবক, ${smsRecipient.student?.nameBn || smsRecipient.student?.name}-এর ফলোআপ ভিজিটে আপনার আন্তরিক মতামতের জন্য ধন্যবাদ। - ${smsRecipient.campaign?.title}`
                      : `Dear Guardian, thank you for your feedback regarding ${smsRecipient.student?.name}. - ${smsRecipient.campaign?.title}`
                  }
                />
              </div>

              <div className="flex justify-end gap-2.5">
                <button
                  type="button"
                  onClick={() => setIsSmsModalOpen(false)}
                  className="px-4 py-2 text-xs font-semibold text-slate-600 bg-slate-100 hover:bg-slate-200 rounded-xl transition-colors"
                >
                  {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
                </button>
                <button
                  type="submit"
                  className="flex items-center gap-1.5 px-5 py-2 text-xs font-bold text-white bg-blue-600 hover:bg-blue-700 rounded-xl shadow-sm transition-colors"
                >
                  <Send className="w-3.5 h-3.5" />
                  {isBn ? BN_DICT['send_sms'] : EN_DICT['send_sms']}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
