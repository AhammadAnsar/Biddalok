import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useEffect, useState } from 'react';
import { useAppStore } from '../../../../store/useAppStore';
import { WifiOff, RefreshCw, CheckCircle2, AlertTriangle } from 'lucide-react';

export const FollowupSyncManager: React.FC = () => {
  const { language, followupVisits, updateFollowupVisit } = useAppStore();
  const isBn = language === 'bn';
  const [isOnline, setIsOnline] = useState(navigator.onLine);
  const [isSyncing, setIsSyncing] = useState(false);

  const pendingVisits = (followupVisits || []).filter(v => v.syncStatus === 'pending');

  useEffect(() => {
    const handleOnline = () => setIsOnline(true);
    const handleOffline = () => setIsOnline(false);

    window.addEventListener('online', handleOnline);
    window.addEventListener('offline', handleOffline);

    return () => {
      window.removeEventListener('online', handleOnline);
      window.removeEventListener('offline', handleOffline);
    };
  }, []);

  useEffect(() => {
    if (isOnline && pendingVisits.length > 0 && !isSyncing) {
      syncPendingVisits();
    }
  }, [isOnline, pendingVisits.length]);

  const syncPendingVisits = async () => {
    setIsSyncing(true);
    
    // Simulate network delay for sync
    for (const visit of pendingVisits) {
      await new Promise(resolve => setTimeout(resolve, 800));
      updateFollowupVisit(visit.id, { syncStatus: 'synced' });
    }
    
    setIsSyncing(false);
  };

  if (pendingVisits.length === 0 && isOnline) return null;

  return (
    <div className="fixed bottom-4 right-4 z-50 flex flex-col gap-2 pointer-events-none">
      {!isOnline && (
        <div className="bg-amber-100 border border-amber-200 text-amber-800 px-4 py-2 rounded-xl shadow-lg flex items-center gap-2 pointer-events-auto">
          <WifiOff className="w-5 h-5" />
          <div className="text-sm font-semibold">
            {isBn ? BN_DICT['offline_mode'] : EN_DICT['offline_mode']}
            {pendingVisits.length > 0 && (
              <span className="block text-xs font-normal opacity-80">
                {isBn ? `${pendingVisits.length} টি ভিজিট পিসি/মোবাইলে সেভ হয়েছে` : `${pendingVisits.length} visits saved locally`}
              </span>
            )}
          </div>
        </div>
      )}

      {isOnline && pendingVisits.length > 0 && (
        <div className="bg-sky-100 border border-sky-200 text-sky-800 px-4 py-2 rounded-xl shadow-lg flex items-center gap-2 pointer-events-auto">
          <RefreshCw className={`w-5 h-5 ${isSyncing ? 'animate-spin' : ''}`} />
          <div className="text-sm font-semibold">
            {isBn ? BN_DICT['syncing_to_server'] : EN_DICT['syncing_to_server']}
            <span className="block text-xs font-normal opacity-80">
              {isBn ? `${pendingVisits.length} টি ভিজিট সিঙ্ক বাকি` : `${pendingVisits.length} visits pending`}
            </span>
          </div>
        </div>
      )}
    </div>
  );
};
