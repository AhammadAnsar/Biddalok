import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState } from 'react';
import { useAppStore } from '../../../../store/useAppStore';
import { CalendarClock, Plus, Edit3, Trash2, Users, Search, Calendar, ChevronRight } from 'lucide-react';
import { FollowupCampaign, FollowupTeam } from '../../../../types';
import { CampaignModal } from '../modals/CampaignModal';
import { TeamModal } from '../modals/TeamModal';
import { AssignmentModal } from '../modals/AssignmentModal';

export const CampaignsTab: React.FC = () => {
  const { language, followupCampaigns, deleteFollowupCampaign, followupTeams } = useAppStore();
  const isBn = language === 'bn';
  
  const [search, setSearch] = useState('');
  const [isCampaignModalOpen, setIsCampaignModalOpen] = useState(false);
  const [selectedCampaign, setSelectedCampaign] = useState<FollowupCampaign | undefined>();
  
  const [isTeamModalOpen, setIsTeamModalOpen] = useState(false);
  const [selectedTeamCampaignId, setSelectedTeamCampaignId] = useState<string>('');
  const [selectedTeam, setSelectedTeam] = useState<FollowupTeam | undefined>();

  const [isAssignmentModalOpen, setIsAssignmentModalOpen] = useState(false);
  const [selectedAssignmentTeam, setSelectedAssignmentTeam] = useState<FollowupTeam | undefined>();
  const [selectedAssignmentCampaignId, setSelectedAssignmentCampaignId] = useState<string>('');

  const filteredCampaigns = followupCampaigns?.filter(c => 
    c.title.toLowerCase().includes(search.toLowerCase())
  ) || [];

  const handleOpenCampaignModal = (campaign?: FollowupCampaign) => {
    setSelectedCampaign(campaign);
    setIsCampaignModalOpen(true);
  };

  const handleOpenTeamModal = (campaignId: string, team?: FollowupTeam) => {
    setSelectedTeamCampaignId(campaignId);
    setSelectedTeam(team);
    setIsTeamModalOpen(true);
  };

  const handleOpenAssignmentModal = (campaignId: string, team: FollowupTeam) => {
    setSelectedAssignmentCampaignId(campaignId);
    setSelectedAssignmentTeam(team);
    setIsAssignmentModalOpen(true);
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
        <div>
          <h2 className="text-lg font-bold text-slate-800">
            {isBn ? BN_DICT['follow_up_campaigns_teams'] : EN_DICT['follow_up_campaigns_teams']}
          </h2>
          <p className="text-sm text-slate-500">
            {isBn ? BN_DICT['create_new_campaigns_and_form'] : EN_DICT['create_new_campaigns_and_form']}
          </p>
        </div>
        
        <div className="flex items-center gap-3 w-full sm:w-auto">
          <div className="relative flex-1 sm:w-64">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-slate-400" />
            <input
              type="text"
              placeholder={isBn ? BN_DICT['search_campaigns'] : EN_DICT['search_campaigns']}
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full pl-9 pr-4 py-2 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500 transition-all"
            />
          </div>
          <button 
            onClick={() => handleOpenCampaignModal()}
            className="px-4 py-2 bg-rose-600 hover:bg-rose-700 text-white text-sm font-semibold rounded-xl flex items-center gap-2 transition-colors shrink-0"
          >
            <Plus className="w-4 h-4" />
            <span className="hidden sm:inline">{isBn ? BN_DICT['new_campaign'] : EN_DICT['new_campaign']}</span>
          </button>
        </div>
      </div>

      {filteredCampaigns.length === 0 ? (
        <div className="bg-white rounded-2xl border border-slate-200 p-12 text-center shadow-sm">
          <CalendarClock className="w-12 h-12 text-slate-300 mx-auto mb-4" />
          <h3 className="text-lg font-semibold text-slate-700 mb-1">
            {isBn ? BN_DICT['no_campaigns_found'] : EN_DICT['no_campaigns_found']}
          </h3>
          <p className="text-sm text-slate-500 max-w-sm mx-auto">
            {isBn ? BN_DICT['create_a_new_campaign_for_stud'] : EN_DICT['create_a_new_campaign_for_stud']}
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-4">
          {filteredCampaigns.map(campaign => {
            const campaignTeams = followupTeams?.filter(t => t.campaignId === campaign.id) || [];
            return (
            <div key={campaign.id} className="bg-white border border-slate-200 rounded-2xl p-5 shadow-sm hover:shadow-md transition-shadow flex flex-col">
              <div className="flex justify-between items-start mb-4">
                <div>
                  <div className="flex items-center gap-2 mb-1">
                    <span className={`px-2.5 py-0.5 rounded-full text-xs font-medium ${
                      campaign.status === 'active' ? 'bg-emerald-100 text-emerald-700' :
                      campaign.status === 'planned' ? 'bg-amber-100 text-amber-700' :
                      campaign.status === 'completed' ? 'bg-slate-100 text-slate-700' :
                      'bg-slate-100 text-slate-600'
                    }`}>
                      {isBn ? (
                        campaign.status === 'active' ? 'চলমান' :
                        campaign.status === 'planned' ? 'পরিকল্পিত' :
                        campaign.status === 'completed' ? 'সম্পন্ন' :
                        campaign.status === 'archived' ? 'আর্কাইভড' : 'খসড়া'
                      ) : campaign.status}
                    </span>
                    <span className="text-xs text-slate-500 font-medium bg-slate-100 px-2 py-0.5 rounded-full">
                      {campaign.academicYear}
                    </span>
                  </div>
                  <h3 className="text-lg font-bold text-slate-800 line-clamp-1" title={campaign.title}>{campaign.title}</h3>
                </div>
                <div className="flex items-center gap-1 shrink-0">
                  <button 
                    onClick={() => handleOpenCampaignModal(campaign)}
                    className="p-1.5 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-lg transition-colors"
                  >
                    <Edit3 className="w-4 h-4" />
                  </button>
                  <button 
                    onClick={() => {
                      if (window.confirm(isBn ? BN_DICT['are_you_sure_you_want_to_delet_5'] : EN_DICT['are_you_sure_you_want_to_delet_5'])) {
                        deleteFollowupCampaign(campaign.id);
                      }
                    }}
                    className="p-1.5 text-slate-400 hover:text-red-600 hover:bg-red-50 rounded-lg transition-colors"
                  >
                    <Trash2 className="w-4 h-4" />
                  </button>
                </div>
              </div>
              
              {campaign.purpose && (
                <p className="text-sm text-slate-600 mb-4 line-clamp-2">{campaign.purpose}</p>
              )}

              <div className="flex flex-wrap items-center gap-4 text-sm text-slate-500 mb-5 flex-1">
                <div className="flex items-center gap-1.5">
                  <Calendar className="w-4 h-4 text-slate-400" />
                  <span>{new Date(campaign.startDate).toLocaleDateString()} - {new Date(campaign.endDate).toLocaleDateString()}</span>
                </div>
              </div>

              <div className="pt-4 border-t border-slate-100 flex items-center justify-between">
                <div className="flex items-center gap-2">
                  <div className="flex items-center justify-center w-8 h-8 rounded-full bg-indigo-100 text-indigo-700 font-bold text-sm">
                    {campaignTeams.length}
                  </div>
                  <span className="text-xs text-slate-500 font-medium">{isBn ? BN_DICT['teams_created'] : EN_DICT['teams_created']}</span>
                </div>
                <button 
                  onClick={() => handleOpenTeamModal(campaign.id)}
                  className="text-sm font-semibold text-rose-600 hover:text-rose-700 flex items-center gap-1"
                >
                  <Plus className="w-4 h-4" />
                  {isBn ? BN_DICT['new_team'] : EN_DICT['new_team']}
                </button>
              </div>

              {campaignTeams.length > 0 && (
                <div className="mt-4 pt-4 border-t border-slate-100 space-y-2">
                  {campaignTeams.map(team => (
                    <div key={team.id} className="flex items-center justify-between bg-slate-50 p-2 rounded-lg border border-slate-100">
                      <div className="flex items-center gap-2">
                        <Users className="w-4 h-4 text-slate-400" />
                        <span className="text-sm font-medium text-slate-700">{team.name}</span>
                        <span className="text-xs text-slate-500">
                          ({1 + (team.memberIds?.length || 0)} {isBn ? BN_DICT['members'] : EN_DICT['members']})
                        </span>
                      </div>
                      <div className="flex items-center gap-1">
                        <button 
                          onClick={() => handleOpenAssignmentModal(campaign.id, team)}
                          className="px-2 py-1 text-xs font-semibold text-rose-600 hover:bg-rose-100 bg-rose-50 rounded transition-colors"
                        >
                          {isBn ? BN_DICT['students_2'] : EN_DICT['students_2']}
                        </button>
                        <button 
                          onClick={() => handleOpenTeamModal(campaign.id, team)}
                          className="p-1 text-slate-400 hover:text-rose-600 transition-colors"
                        >
                          <Edit3 className="w-3.5 h-3.5" />
                        </button>
                      </div>
                    </div>
                  ))}
                </div>
              )}
            </div>
            );
          })}
        </div>
      )}

      <CampaignModal 
        isOpen={isCampaignModalOpen}
        onClose={() => setIsCampaignModalOpen(false)}
        campaign={selectedCampaign}
      />

      <TeamModal
        isOpen={isTeamModalOpen}
        onClose={() => setIsTeamModalOpen(false)}
        campaignId={selectedTeamCampaignId}
        team={selectedTeam}
      />

      {selectedAssignmentTeam && (
        <AssignmentModal
          isOpen={isAssignmentModalOpen}
          onClose={() => setIsAssignmentModalOpen(false)}
          campaignId={selectedAssignmentCampaignId}
          team={selectedAssignmentTeam}
        />
      )}
    </div>
  );
};
