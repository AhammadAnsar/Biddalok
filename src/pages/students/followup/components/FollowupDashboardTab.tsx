import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useMemo } from 'react';
import { useAppStore } from '../../../../store/useAppStore';
import { Target, Users, BookOpenCheck, CalendarClock, TrendingUp, CheckCircle2, AlertTriangle, RefreshCcw, AlertOctagon } from 'lucide-react';

export const FollowupDashboardTab: React.FC = () => {
  const { language, followupVisits = [], followupAssignments = [], followupCampaigns = [], followupTeams = [] } = useAppStore();
  const isBn = language === 'bn';

  // Performance Optimization: Memoize aggregates
  const aggregates = useMemo(() => {
    const totalCampaigns = followupCampaigns.length;
    const activeCampaigns = followupCampaigns.filter(c => c.status === 'active').length;
    const totalTeams = followupTeams.length;
    const totalAssignments = followupAssignments.length;
    const completedVisits = followupVisits.length;
    
    const pendingAssignments = totalAssignments - completedVisits;
    const completionRate = totalAssignments > 0 ? Math.round((completedVisits / totalAssignments) * 100) : 0;

    // Outcome breakdown
    let satisfactory = 0;
    let monitoring = 0;
    let refollowup = 0;
    let intervention = 0;

    followupVisits.forEach(v => {
      if (v.outcome === 'satisfactory') satisfactory++;
      else if (v.outcome === 'monitoring') monitoring++;
      else if (v.outcome === 're_followup') refollowup++;
      else if (v.outcome === 'school_intervention') intervention++;
    });

    // Campaign progress
    const campaignProgress = followupCampaigns.slice(0, 4).map(campaign => {
      const campAssignments = followupAssignments.filter(a => a.campaignId === campaign.id).length;
      const campVisits = followupVisits.filter(v => v.campaignId === campaign.id).length;
      const progress = campAssignments > 0 ? Math.round((campVisits / campAssignments) * 100) : 0;
      return { ...campaign, campAssignments, campVisits, progress };
    });

    return {
      totalCampaigns, activeCampaigns, totalTeams, totalAssignments, completedVisits,
      pendingAssignments, completionRate,
      satisfactory, monitoring, refollowup, intervention,
      campaignProgress
    };
  }, [followupVisits, followupAssignments, followupCampaigns, followupTeams]);

  const {
    totalCampaigns, activeCampaigns, totalTeams, totalAssignments, completedVisits,
    pendingAssignments, completionRate,
    satisfactory, monitoring, refollowup, intervention,
    campaignProgress
  } = aggregates;

  return (
    <div className="space-y-6" role="region" aria-label={isBn ? BN_DICT['follow_up_dashboard'] : EN_DICT['follow_up_dashboard']}>
      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-4 gap-4">
        {/* Metric 1 */}
        <div className="bg-white p-5 rounded-2xl border border-slate-200 shadow-sm flex items-center gap-4 focus-within:ring-2 focus-within:ring-indigo-500" tabIndex={0} aria-label={isBn ? `মোট ক্যাম্পেইন ${totalCampaigns}` : `Total Campaigns ${totalCampaigns}`}>
          <div className="bg-indigo-100 p-3 rounded-xl shrink-0" aria-hidden="true">
            <CalendarClock className="w-6 h-6 text-indigo-600" />
          </div>
          <div>
            <p className="text-sm font-medium text-slate-500 mb-0.5">{isBn ? BN_DICT['total_campaigns'] : EN_DICT['total_campaigns']}</p>
            <div className="flex items-end gap-2">
              <h3 className="text-2xl font-bold text-slate-800">{totalCampaigns}</h3>
              <span className="text-xs font-medium text-indigo-600 mb-1">({activeCampaigns} {isBn ? BN_DICT['active'] : EN_DICT['active']})</span>
            </div>
          </div>
        </div>

        {/* Metric 2 */}
        <div className="bg-white p-5 rounded-2xl border border-slate-200 shadow-sm flex items-center gap-4 focus-within:ring-2 focus-within:ring-blue-500" tabIndex={0}>
          <div className="bg-blue-100 p-3 rounded-xl shrink-0" aria-hidden="true">
            <Users className="w-6 h-6 text-blue-600" />
          </div>
          <div>
            <p className="text-sm font-medium text-slate-500 mb-0.5">{isBn ? BN_DICT['follow_up_teams'] : EN_DICT['follow_up_teams']}</p>
            <h3 className="text-2xl font-bold text-slate-800">{totalTeams}</h3>
          </div>
        </div>

        {/* Metric 3 */}
        <div className="bg-white p-5 rounded-2xl border border-slate-200 shadow-sm flex items-center gap-4 focus-within:ring-2 focus-within:ring-amber-500" tabIndex={0}>
          <div className="bg-amber-100 p-3 rounded-xl shrink-0" aria-hidden="true">
            <Target className="w-6 h-6 text-amber-600" />
          </div>
          <div>
            <p className="text-sm font-medium text-slate-500 mb-0.5">{isBn ? BN_DICT['assigned_students'] : EN_DICT['assigned_students']}</p>
            <div className="flex items-end gap-2">
              <h3 className="text-2xl font-bold text-slate-800">{totalAssignments}</h3>
              <span className="text-xs font-medium text-amber-600 mb-1">({pendingAssignments} {isBn ? BN_DICT['pending'] : EN_DICT['pending']})</span>
            </div>
          </div>
        </div>

        {/* Metric 4 */}
        <div className="bg-white p-5 rounded-2xl border border-slate-200 shadow-sm flex items-center gap-4 focus-within:ring-2 focus-within:ring-emerald-500" tabIndex={0}>
          <div className="bg-emerald-100 p-3 rounded-xl shrink-0" aria-hidden="true">
            <BookOpenCheck className="w-6 h-6 text-emerald-600" />
          </div>
          <div>
            <p className="text-sm font-medium text-slate-500 mb-0.5">{isBn ? BN_DICT['completed_visits'] : EN_DICT['completed_visits']}</p>
            <div className="flex items-end gap-2">
              <h3 className="text-2xl font-bold text-slate-800">{completedVisits}</h3>
              <span className="text-xs font-medium text-emerald-600 mb-1">({completionRate}%)</span>
            </div>
          </div>
        </div>
      </div>

      <div className="grid grid-cols-1 lg:grid-cols-3 gap-6">
        {/* Progress Overview */}
        <div className="lg:col-span-2 bg-white rounded-2xl border border-slate-200 shadow-sm p-6 flex flex-col">
          <h3 className="text-base font-bold text-slate-800 mb-6 flex items-center gap-2">
            <TrendingUp className="w-5 h-5 text-indigo-500" aria-hidden="true" />
            {isBn ? BN_DICT['campaign_progress'] : EN_DICT['campaign_progress']}
          </h3>
          
          <div className="flex-1 flex flex-col justify-center">
            {campaignProgress.length === 0 ? (
              <div className="text-center text-slate-400 py-12" role="status">
                {isBn ? BN_DICT['no_campaign_data_available'] : EN_DICT['no_campaign_data_available']}
              </div>
            ) : (
              <div className="space-y-6">
                {campaignProgress.map(campaign => (
                  <div key={campaign.id}>
                    <div className="flex justify-between items-end mb-2">
                      <div>
                        <p className="text-sm font-bold text-slate-800 line-clamp-1">{campaign.title}</p>
                        <p className="text-xs text-slate-500 mt-0.5">{campaign.campVisits} / {campaign.campAssignments} {isBn ? BN_DICT['visits_completed'] : EN_DICT['visits_completed']}</p>
                      </div>
                      <span className="text-sm font-bold text-indigo-600">{campaign.progress}%</span>
                    </div>
                    <div className="w-full bg-slate-100 rounded-full h-2.5 overflow-hidden" role="progressbar" aria-valuenow={campaign.progress} aria-valuemin={0} aria-valuemax={100} aria-label={campaign.title}>
                      <div 
                        className="bg-indigo-500 h-2.5 rounded-full transition-all duration-1000 ease-out" 
                        style={{ width: `${campaign.progress}%` }}
                      ></div>
                    </div>
                  </div>
                ))}
              </div>
            )}
          </div>
        </div>

        {/* Outcome Breakdown */}
        <div className="bg-white rounded-2xl border border-slate-200 shadow-sm p-6 flex flex-col">
          <h3 className="text-base font-bold text-slate-800 mb-6">
            {isBn ? BN_DICT['outcome_analysis'] : EN_DICT['outcome_analysis']}
          </h3>
          
          <div className="flex-1 flex flex-col justify-center">
            {completedVisits === 0 ? (
              <div className="text-center text-slate-400 py-12" role="status">
                {isBn ? BN_DICT['no_visits_completed_yet'] : EN_DICT['no_visits_completed_yet']}
              </div>
            ) : (
              <div className="space-y-4">
                <div className="bg-emerald-50 p-4 rounded-xl border border-emerald-100 flex items-center justify-between" tabIndex={0} aria-label={isBn ? `সন্তোষজনক ${satisfactory}` : `Satisfactory ${satisfactory}`}>
                  <div className="flex items-center gap-3">
                    <div className="p-2 bg-emerald-100 rounded-lg" aria-hidden="true">
                      <CheckCircle2 className="w-5 h-5 text-emerald-600" />
                    </div>
                    <div>
                      <p className="text-sm font-semibold text-emerald-800">{isBn ? BN_DICT['satisfactory'] : EN_DICT['satisfactory']}</p>
                      <p className="text-xs text-emerald-600/80">{Math.round((satisfactory/completedVisits)*100)}% {isBn ? BN_DICT['of_visits'] : EN_DICT['of_visits']}</p>
                    </div>
                  </div>
                  <h3 className="text-xl font-bold text-emerald-700">{satisfactory}</h3>
                </div>

                <div className="bg-amber-50 p-4 rounded-xl border border-amber-100 flex items-center justify-between" tabIndex={0} aria-label={isBn ? `পর্যবেক্ষণে ${monitoring}` : `Monitoring ${monitoring}`}>
                  <div className="flex items-center gap-3">
                    <div className="p-2 bg-amber-100 rounded-lg" aria-hidden="true">
                      <AlertTriangle className="w-5 h-5 text-amber-600" />
                    </div>
                    <div>
                      <p className="text-sm font-semibold text-amber-800">{isBn ? BN_DICT['monitoring'] : EN_DICT['monitoring']}</p>
                      <p className="text-xs text-amber-600/80">{Math.round((monitoring/completedVisits)*100)}% {isBn ? BN_DICT['of_visits'] : EN_DICT['of_visits']}</p>
                    </div>
                  </div>
                  <h3 className="text-xl font-bold text-amber-700">{monitoring}</h3>
                </div>

                <div className="bg-rose-50 p-4 rounded-xl border border-rose-100 flex items-center justify-between" tabIndex={0} aria-label={isBn ? `পুনরায় ভিজিট ${refollowup}` : `Re-followup ${refollowup}`}>
                  <div className="flex items-center gap-3">
                    <div className="p-2 bg-rose-100 rounded-lg" aria-hidden="true">
                      <RefreshCcw className="w-5 h-5 text-rose-600" />
                    </div>
                    <div>
                      <p className="text-sm font-semibold text-rose-800">{isBn ? BN_DICT['re_followup'] : EN_DICT['re_followup']}</p>
                      <p className="text-xs text-rose-600/80">{Math.round((refollowup/completedVisits)*100)}% {isBn ? BN_DICT['of_visits'] : EN_DICT['of_visits']}</p>
                    </div>
                  </div>
                  <h3 className="text-xl font-bold text-rose-700">{refollowup}</h3>
                </div>

                {intervention > 0 && (
                  <div className="bg-red-50 p-4 rounded-xl border border-red-100 flex items-center justify-between" tabIndex={0} aria-label={isBn ? `হস্তক্ষেপ প্রয়োজন ${intervention}` : `Intervention ${intervention}`}>
                    <div className="flex items-center gap-3">
                      <div className="p-2 bg-red-100 rounded-lg" aria-hidden="true">
                        <AlertOctagon className="w-5 h-5 text-red-600" />
                      </div>
                      <div>
                        <p className="text-sm font-semibold text-red-800">{isBn ? BN_DICT['intervention'] : EN_DICT['intervention']}</p>
                        <p className="text-xs text-red-600/80">{Math.round((intervention/completedVisits)*100)}% {isBn ? BN_DICT['of_visits'] : EN_DICT['of_visits']}</p>
                      </div>
                    </div>
                    <h3 className="text-xl font-bold text-red-700">{intervention}</h3>
                  </div>
                )}
              </div>
            )}
          </div>
        </div>
      </div>
    </div>
  );
};
