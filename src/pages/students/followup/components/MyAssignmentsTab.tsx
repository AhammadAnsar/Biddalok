import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState } from 'react';
import { useAppStore } from '../../../../store/useAppStore';
import { useAuthStore } from '../../../../store/useAuthStore';
import { WifiOff, FileText, BookOpenCheck, CheckCircle2, Clock, MapPin, Search, Calendar, LayoutList, ChevronLeft, ChevronRight } from 'lucide-react';
import { VisitFormModal } from '../modals/VisitFormModal';
import { FollowupAssignment } from '../../../../types';

export const MyAssignmentsTab: React.FC = () => {
  const { language, followupAssignments, followupVisits, students } = useAppStore();
  const isBn = language === 'bn';
  const [search, setSearch] = useState('');
  const [viewMode, setViewMode] = useState<'list' | 'calendar'>('list');
  const [isVisitModalOpen, setIsVisitModalOpen] = useState(false);
  const [selectedAssignment, setSelectedAssignment] = useState<FollowupAssignment | undefined>();
  
  const { currentUser } = useAuthStore();
  const myAssignments = (followupAssignments || []).filter(a => a.assignedToStaffId === currentUser?.staffId);

  const pending = myAssignments.filter(a => a.status === 'pending');
  const visited = myAssignments.filter(a => a.status === 'visited');

  const getStudent = (id: string) => students.find(s => s.id === id);

  
  const [currentDate, setCurrentDate] = useState(new Date());

  const getDaysInMonth = (year: number, month: number) => {
    return new Date(year, month + 1, 0).getDate();
  };

  const getFirstDayOfMonth = (year: number, month: number) => {
    return new Date(year, month, 1).getDay();
  };

  const nextMonth = () => {
    setCurrentDate(new Date(currentDate.getFullYear(), currentDate.getMonth() + 1, 1));
  };

  const prevMonth = () => {
    setCurrentDate(new Date(currentDate.getFullYear(), currentDate.getMonth() - 1, 1));
  };

  const renderCalendar = () => {
    const year = currentDate.getFullYear();
    const month = currentDate.getMonth();
    const daysInMonth = getDaysInMonth(year, month);
    const firstDay = getFirstDayOfMonth(year, month);
    
    const monthNamesEn = ['January', 'February', 'March', 'April', 'May', 'June', 'July', 'August', 'September', 'October', 'November', 'December'];
    const monthNamesBn = ['জানুয়ারি', 'ফেব্রুয়ারি', 'মার্চ', 'এপ্রিল', 'মে', 'জুন', 'জুলাই', 'আগস্ট', 'সেপ্টেম্বর', 'অক্টোবর', 'নভেম্বর', 'ডিসেম্বর'];
    
    const days = [];
    // Empty slots for first row
    for (let i = 0; i < firstDay; i++) {
      days.push(<div key={`empty-${i}`} className="bg-slate-50/50 border border-slate-100 rounded-xl min-h-[100px]"></div>);
    }
    
    // Fill days
    for (let day = 1; day <= daysInMonth; day++) {
      const dateStr = `${year}-${String(month + 1).padStart(2, '0')}-${String(day).padStart(2, '0')}`;
      const dayAssignments = filteredAssignments.filter(a => a.scheduledDate === dateStr);
      
      const isToday = new Date().toDateString() === new Date(year, month, day).toDateString();
      
      days.push(
        <div key={day} className={`p-2 border rounded-xl min-h-[120px] transition-all ${isToday ? 'border-indigo-500 bg-indigo-50/30 shadow-sm' : 'border-slate-200 bg-white hover:border-indigo-300'}`}>
          <div className="flex items-center justify-between mb-2">
            <span className={`text-sm font-bold w-7 h-7 flex items-center justify-center rounded-full ${isToday ? 'bg-indigo-600 text-white' : 'text-slate-700'}`}>
              {day}
            </span>
            {dayAssignments.length > 0 && (
              <span className="text-[10px] font-bold bg-rose-100 text-rose-700 px-1.5 py-0.5 rounded-md">
                {dayAssignments.length}
              </span>
            )}
          </div>
          
          <div className="space-y-1.5 mt-2">
            {dayAssignments.slice(0, 3).map(a => {
              const st = students.find(s => s.id === a.studentId);
              const isCompleted = a.status === 'visited';
              return (
                <div 
                  key={a.id} 
                  onClick={() => !isCompleted && setSelectedAssignment(a)}
                  className={`text-[11px] p-1.5 rounded-md border truncate cursor-pointer transition-colors ${isCompleted ? 'bg-emerald-50 border-emerald-100 text-emerald-700 line-through opacity-70' : 'bg-white border-slate-200 text-slate-700 hover:border-indigo-300 hover:bg-indigo-50'}`}
                  title={st?.name}
                >
                  {st?.name}
                </div>
              );
            })}
            {dayAssignments.length > 3 && (
              <div className="text-[10px] text-center text-slate-500 font-medium">
                +{dayAssignments.length - 3} more
              </div>
            )}
          </div>
        </div>
      );
    }
    
    return (
      <div className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden p-4 sm:p-6">
        <div className="flex items-center justify-between mb-6">
          <h3 className="text-lg font-bold text-slate-800">
            {isBn ? monthNamesBn[month] : monthNamesEn[month]} {year}
          </h3>
          <div className="flex items-center gap-2">
            <button onClick={prevMonth} className="p-2 hover:bg-slate-100 rounded-lg text-slate-600">
              <ChevronLeft className="w-5 h-5" />
            </button>
            <button onClick={() => setCurrentDate(new Date())} className="px-3 py-1.5 bg-slate-100 hover:bg-slate-200 rounded-lg text-sm font-medium text-slate-700">
              {isBn ? BN_DICT['today'] : EN_DICT['today']}
            </button>
            <button onClick={nextMonth} className="p-2 hover:bg-slate-100 rounded-lg text-slate-600">
              <ChevronRight className="w-5 h-5" />
            </button>
          </div>
        </div>
        
        <div className="grid grid-cols-7 gap-2 sm:gap-4 mb-2">
          {['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'].map((d, i) => (
            <div key={d} className="text-center text-xs font-bold text-slate-500 uppercase tracking-wider py-2">
              {isBn ? ['রবি', 'সোম', 'মঙ্গল', 'বুধ', 'বৃহঃ', 'শুক্র', 'শনি'][i] : d}
            </div>
          ))}
        </div>
        <div className="grid grid-cols-7 gap-2 sm:gap-4">
          {days}
        </div>
      </div>
    );
  };


  const filteredAssignments = myAssignments.filter(a => {
    const student = getStudent(a.studentId);
    if (!student) return false;
    if (search && !(
      student.name.toLowerCase().includes(search.toLowerCase()) || 
      (student.studentId && student.studentId.toLowerCase().includes(search.toLowerCase())) ||
      (student.nameBn && student.nameBn.includes(search))
    )) return false;
    return true;
  });

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4">
        <div>
          <h2 className="text-lg font-bold text-slate-800">
            {isBn ? BN_DICT['my_assignments_student_visits'] : EN_DICT['my_assignments_student_visits']}
          </h2>
          <p className="text-sm text-slate-500">
            {isBn ? BN_DICT['list_of_students_assigned_to_y'] : EN_DICT['list_of_students_assigned_to_y']}
          </p>
        </div>
        
        <div className="flex items-center gap-3 w-full sm:w-auto">
          <div className="relative flex-1 sm:w-64">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-slate-400" />
            <input
              type="text"
              placeholder={isBn ? BN_DICT['search_student'] : EN_DICT['search_student']}
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full pl-9 pr-4 py-2 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500 transition-all"
            />
          </div>
        </div>
      </div>

      <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
        <div className="bg-slate-50 p-4 rounded-2xl border border-slate-200 flex flex-col justify-center items-center text-center">
          <h3 className="text-3xl font-bold text-slate-800 mb-1">{myAssignments.length}</h3>
          <p className="text-sm font-medium text-slate-500">{isBn ? BN_DICT['total_assigned'] : EN_DICT['total_assigned']}</p>
        </div>
        <div className="bg-amber-50 p-4 rounded-2xl border border-amber-200 flex flex-col justify-center items-center text-center">
          <h3 className="text-3xl font-bold text-amber-600 mb-1">{pending.length}</h3>
          <p className="text-sm font-medium text-amber-600/80">{isBn ? BN_DICT['pending'] : EN_DICT['pending']}</p>
        </div>
        <div className="bg-emerald-50 p-4 rounded-2xl border border-emerald-200 flex flex-col justify-center items-center text-center">
          <h3 className="text-3xl font-bold text-emerald-600 mb-1">{visited.length}</h3>
          <p className="text-sm font-medium text-emerald-600/80">{isBn ? BN_DICT['visited'] : EN_DICT['visited']}</p>
        </div>
      </div>

      {filteredAssignments.length === 0 ? (
        <div className="bg-white rounded-2xl border border-slate-200 p-12 text-center shadow-sm">
          <BookOpenCheck className="w-12 h-12 text-slate-300 mx-auto mb-4" />
          <h3 className="text-lg font-semibold text-slate-700 mb-1">
            {isBn ? BN_DICT['no_assignments_found'] : EN_DICT['no_assignments_found']}
          </h3>
          <p className="text-sm text-slate-500 max-w-sm mx-auto">
            {isBn ? BN_DICT['no_students_have_been_assigned'] : EN_DICT['no_students_have_been_assigned']}
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 md:grid-cols-2 xl:grid-cols-3 gap-4">
          {filteredAssignments.map(assignment => {
            const student = getStudent(assignment.studentId);
            if (!student) return null;
            const isVisited = assignment.status === 'visited';
            const visit = followupVisits?.find(v => v.assignmentId === assignment.id);
            const isPendingSync = isVisited && visit?.syncStatus === 'pending';

            return (
              <div key={assignment.id} className={`bg-white border ${isVisited ? 'border-emerald-200' : 'border-slate-200'} rounded-2xl p-5 shadow-sm hover:shadow-md transition-shadow flex flex-col`}>
                <div className="flex justify-between items-start mb-3">
                  <div>
                    <div className="flex items-center gap-2 mb-2">
                      <span className={`inline-flex items-center gap-1.5 px-2.5 py-0.5 rounded-full text-xs font-medium ${
                        isVisited ? 'bg-emerald-100 text-emerald-700' : 'bg-amber-100 text-amber-700'
                      }`}>
                        {isVisited ? <CheckCircle2 className="w-3.5 h-3.5" /> : <BookOpenCheck className="w-3.5 h-3.5" />}
                        {isBn ? (isVisited ? 'সম্পন্ন' : 'অপেক্ষমাণ') : (isVisited ? 'Visited' : 'Pending')}
                      </span>
                      {isPendingSync && (
                        <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded-full text-[10px] font-medium bg-slate-100 text-slate-600 border border-slate-200" title={isBn ? BN_DICT['saved_locally_offline'] : EN_DICT['saved_locally_offline']}>
                          <WifiOff className="w-3 h-3" />
                          {isBn ? BN_DICT['pending_sync'] : EN_DICT['pending_sync']}
                        </span>
                      )}
                    </div>
                    <h3 className="text-lg font-bold text-slate-800 line-clamp-1" title={isBn && student.nameBn ? student.nameBn : student.name}>
                      {isBn && student.nameBn ? student.nameBn : student.name}
                    </h3>
                  </div>
                  {student.photo ? (
                    <img src={student.photo} alt={student.name} className="w-10 h-10 rounded-full object-cover border border-slate-200" />
                  ) : (
                    <div className="w-10 h-10 rounded-full bg-slate-100 flex items-center justify-center text-slate-400 font-bold border border-slate-200">
                      {student.name.charAt(0)}
                    </div>
                  )}
                </div>

                <div className="space-y-1 text-sm text-slate-600 mb-5 flex-1">
                  <p><span className="font-medium text-slate-400">{isBn ? BN_DICT['id_1'] : EN_DICT['id_1']}:</span> {student.studentId || 'N/A'}</p>
                  <p><span className="font-medium text-slate-400">{isBn ? BN_DICT['class_2'] : EN_DICT['class_2']}:</span> {student.class} {student.section && `(${student.section})`}</p>
                  {student.fatherMobile && <p><span className="font-medium text-slate-400">{isBn ? BN_DICT['mobile'] : EN_DICT['mobile']}:</span> {student.fatherMobile}</p>}
                </div>

                <button 
                  disabled={isVisited}
                  onClick={() => { setSelectedAssignment(assignment); setIsVisitModalOpen(true); }}
                  className={`w-full py-2.5 px-4 rounded-xl text-sm font-semibold flex justify-center items-center gap-2 transition-colors ${
                    isVisited 
                      ? 'bg-slate-50 text-slate-400 cursor-not-allowed'
                      : 'bg-indigo-50 hover:bg-indigo-100 text-indigo-700'
                  }`}
                >
                  <FileText className="w-4 h-4" />
                  {isBn ? (isVisited ? 'রিপোর্ট জমাকৃত' : 'ভিজিট ফর্ম পূরণ করুন') : (isVisited ? 'Report Submitted' : 'Fill Visit Form')}
                </button>
              </div>
            );
          })}
        </div>
      )}

      {selectedAssignment && getStudent(selectedAssignment.studentId) && (
        <VisitFormModal
          isOpen={isVisitModalOpen}
          onClose={() => setIsVisitModalOpen(false)}
          assignment={selectedAssignment}
          student={getStudent(selectedAssignment.studentId)!}
        />
      )}
    </div>
  );
};
