import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React from 'react';
import { createRoot } from 'react-dom/client';
import { downloadMultiPageDocumentPDF } from '../../../../utils/pdfGenerator';
import { FollowupVisit, Student, FollowupCampaign, FollowupTeam, Institution, StaffMember } from '../../../../types';
import { OfficialFollowupRegisterDoc } from '../components/OfficialFollowupRegisterDoc';

export interface MappedVisit extends FollowupVisit {
  student?: Student;
  campaign?: FollowupCampaign;
  team?: FollowupTeam;
}

const renderToElement = (element: React.ReactElement): HTMLElement => {
  const container = document.createElement('div');
  container.style.position = 'absolute';
  container.style.left = '-9999px';
  container.style.top = '-9999px';
  document.body.appendChild(container);
  
  const root = createRoot(container);
  root.render(element);
  
  return container;
};

const cleanupElement = (element: HTMLElement) => {
  setTimeout(() => {
    if (element.parentNode) {
      element.parentNode.removeChild(element);
    }
  }, 1000);
};

export const exportFollowupRegisterPdf = async (
  records: MappedVisit[],
  isBn: boolean = true,
  options?: {
    campaign?: FollowupCampaign;
    team?: FollowupTeam | null;
    institution?: Institution;
    staff?: StaffMember[];
    memoNo?: string;
  }
) => {
  const campaign = options?.campaign || records[0]?.campaign || {
    id: 'campaign-default',
    title: isBn ? BN_DICT['student_follow_up_home_visit_c'] : EN_DICT['student_follow_up_home_visit_c'],
    academicYear: new Date().getFullYear().toString(),
    startDate: new Date().toISOString(),
    endDate: new Date().toISOString(),
    status: 'active',
    createdAt: new Date().toISOString(),
    updatedAt: new Date().toISOString(),
  };

  const institution = options?.institution || {
    name: 'School Name',
    nameBn: 'বিদ্যালয়ের নাম',
    eiin: options?.institution?.eiin || '',
    address: 'Address',
    established: options?.institution?.establishedYear || options?.institution?.established || '',
    headmasterName: 'Headmaster',
  };

  const staff = options?.staff || [];
  const team = options?.team || records[0]?.team || null;

  const container = renderToElement(
    <OfficialFollowupRegisterDoc
      campaign={campaign}
      team={team}
      records={records}
      institution={institution}
      staff={staff}
      isBn={isBn}
      memoNo={options?.memoNo}
      printMode={true}
    />
  );
  
  // Give React time to render DOM
  await new Promise(resolve => setTimeout(resolve, 600));
  
  try {
    const pageNodes = container.querySelectorAll('.register-page-sheet');
    const elementsToPrint = pageNodes.length > 0 
      ? (Array.from(pageNodes) as HTMLElement[]) 
      : [container];

    const fileName = `Followup_Register_${campaign.title.replace(/\s+/g, '_')}_${new Date().toISOString().slice(0, 10)}.pdf`;

    await downloadMultiPageDocumentPDF(elementsToPrint, fileName, { 
      orientation: 'landscape', 
      format: 'a4' 
    });
  } finally {
    cleanupElement(container);
  }
};

