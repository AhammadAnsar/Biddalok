import { EN_DICT, BN_DICT } from "../../../locales/autoGenerated";
import React, { useState } from 'react';
import { useAppStore } from '../../../store/useAppStore';
import { UserCheck, LayoutDashboard, CalendarClock, BookOpenCheck, ClipboardList, CloudOff } from 'lucide-react';
import { CampaignsTab } from './components/CampaignsTab';
import { MyAssignmentsTab } from './components/MyAssignmentsTab';
import { FollowupDashboardTab } from './components/FollowupDashboardTab';
import { FollowupRegisterTab } from './components/FollowupRegisterTab';
import { FollowupSyncManager } from './components/FollowupSyncManager';

const StudentFollowup: React.FC = () => {
  const [activeTab, setActiveTab] = useState<'dashboard' | 'campaigns' | 'my_assignments' | 'register'>('dashboard');
  const { language } = useAppStore();
  const isBn = language === 'bn';

  const tabs = [
    { id: 'dashboard', labelEn: 'Dashboard', labelBn: 'ড্যাশবোর্ড', icon: LayoutDashboard },
    { id: 'campaigns', labelEn: 'Campaigns & Teams', labelBn: 'ক্যাম্পেইন ও টিম', icon: CalendarClock },
    { id: 'my_assignments', labelEn: 'My Assignments', labelBn: 'আমার দায়িত্ব (ভিজিট)', icon: BookOpenCheck },
        { id: 'register', labelEn: 'Follow-up Register', labelBn: 'ফলোআপ রেজিস্টার', icon: ClipboardList },
    { id: 'queue', labelEn: 'Sync Queue', labelBn: 'সিঙ্ক কিউ', icon: CloudOff }
  ] as const;

  return (
    <div className="space-y-6">
      <FollowupSyncManager />
      <div className="flex items-center gap-3">
        <div className="bg-rose-100 p-2 sm:p-3 rounded-xl sm:rounded-2xl shrink-0">
          <UserCheck className="w-6 h-6 sm:w-8 sm:h-8 text-rose-600" />
        </div>
        <div>
          <h1 className="text-xl sm:text-2xl font-bold text-slate-800">
            {isBn ? BN_DICT['student_follow_up_visit'] : EN_DICT['student_follow_up_visit']}
          </h1>
          <p className="text-sm text-slate-500 mt-1">
            {isBn ? BN_DICT['home_visits_guardian_feedback'] : EN_DICT['home_visits_guardian_feedback']}
          </p>
        </div>
      </div>

      <div className="bg-white rounded-xl sm:rounded-2xl shadow-sm border border-slate-200 overflow-hidden">
        <div className="flex overflow-x-auto border-b border-slate-200 custom-scrollbar">
          {tabs.map(tab => (
            <button
              key={tab.id}
              onClick={() => setActiveTab(tab.id as any)}
              className={`flex items-center gap-2 px-4 sm:px-6 py-4 text-sm font-semibold whitespace-nowrap transition-colors border-b-2 ${
                activeTab === tab.id
                  ? 'border-rose-600 text-rose-600 bg-rose-50/50'
                  : 'border-transparent text-slate-600 hover:text-slate-900 hover:bg-slate-50'
              }`}
            >
              <tab.icon className={`w-4 h-4 ${activeTab === tab.id ? 'text-rose-600' : 'text-slate-400'}`} />
              {isBn ? tab.labelBn : tab.labelEn}
            </button>
          ))}
        </div>

        <div className="p-4 sm:p-6 min-h-[60vh]">
          {activeTab === 'dashboard' && (
            <FollowupDashboardTab />
          )}
          
          {activeTab === 'campaigns' && (
            <CampaignsTab />
          )}

          {activeTab === 'my_assignments' && (
            <MyAssignmentsTab />
          )}

          {activeTab === 'register' && (
            <FollowupRegisterTab />
          )}
        </div>
      </div>
    </div>
  );
};

export default StudentFollowup;
