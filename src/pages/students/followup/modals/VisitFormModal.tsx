import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { X, Save, MapPin, Camera, Signature, CheckSquare } from 'lucide-react';
import { useAppStore } from '../../../../store/useAppStore';
import { FollowupAssignment, FollowupVisit, Student } from '../../../../types';
import toast from 'react-hot-toast';

interface VisitFormModalProps {
  isOpen: boolean;
  onClose: () => void;
  assignment: FollowupAssignment;
  student: Student;
}

export const VisitFormModal: React.FC<VisitFormModalProps> = ({ isOpen, onClose, assignment, student }) => {
  const { language, addFollowupVisit, updateFollowupAssignment } = useAppStore();
  const isBn = language === 'bn';

  const [formData, setFormData] = useState<Partial<FollowupVisit>>({
    visitDate: new Date().toISOString().split('T')[0],
    studentFound: true,
    status: 'submitted',
  });

  const [isLocating, setIsLocating] = useState(false);

  useEffect(() => {
    if (isOpen) {
      setFormData({
        visitDate: new Date().toISOString().split('T')[0],
        studentFound: true,
        status: 'submitted',
      });
    }
  }, [isOpen]);

  if (!isOpen) return null;

  const getLocation = () => {
    setIsLocating(true);
    if ('geolocation' in navigator) {
      navigator.geolocation.getCurrentPosition(
        (position) => {
          setFormData(prev => ({
            ...prev,
            latitude: position.coords.latitude,
            longitude: position.coords.longitude,
            locationAccuracy: position.coords.accuracy
          }));
          setIsLocating(false);
          toast.success(isBn ? BN_DICT['location_captured_successfully'] : EN_DICT['location_captured_successfully']);
        },
        (error) => {
          setIsLocating(false);
          toast.error(isBn ? BN_DICT['failed_to_get_location'] : EN_DICT['failed_to_get_location']);
        }
      );
    } else {
      setIsLocating(false);
      toast.error(isBn ? BN_DICT['geolocation_not_supported'] : EN_DICT['geolocation_not_supported']);
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    
    if (!formData.visitDate) {
      toast.error(isBn ? BN_DICT['visit_date_is_required'] : EN_DICT['visit_date_is_required']);
      return;
    }

    const newVisit: FollowupVisit = {
      ...formData as any,
      id: `fvs_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
      campaignId: assignment.campaignId,
      assignmentId: assignment.id,
      studentId: assignment.studentId,
      teamId: assignment.teamId,
      
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString(),
    };

    // PHASE 14: Save a visit and its assignment transition atomically
    useAppStore.getState().completeFollowupVisitAtomic(newVisit, assignment.id);
    updateFollowupAssignment(assignment.id, { status: 'visited' });
    toast.success(isBn ? BN_DICT['visit_report_submitted_success'] : EN_DICT['visit_report_submitted_success']);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm">
      <div className="bg-white rounded-2xl w-full max-w-2xl shadow-xl overflow-hidden flex flex-col max-h-[90vh]">
        <div className="flex items-center justify-between p-5 border-b border-slate-100 shrink-0 bg-slate-50/50">
          <div>
            <h2 className="text-xl font-bold text-slate-800 flex items-center gap-2">
              <CheckSquare className="w-5 h-5 text-indigo-500" />
              {isBn ? BN_DICT['student_follow_up_form'] : EN_DICT['student_follow_up_form']}
            </h2>
            <p className="text-sm text-slate-500 mt-1">
              {isBn && student.nameBn ? student.nameBn : student.name} (ID: {student.studentId})
            </p>
          </div>
          <button onClick={onClose} className="p-2 hover:bg-slate-200 rounded-full transition-colors">
            <X className="w-5 h-5 text-slate-500" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="p-6 overflow-y-auto custom-scrollbar flex-1 space-y-6">
          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['visit_date'] : EN_DICT['visit_date']} <span className="text-rose-500">*</span>
              </label>
              <input
                type="date"
                required
                value={formData.visitDate || ''}
                onChange={e => setFormData({ ...formData, visitDate: e.target.value })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
              />
            </div>
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['person_met'] : EN_DICT['person_met']}
              </label>
              <select
                value={formData.personMet || ''}
                onChange={e => setFormData({ ...formData, personMet: e.target.value })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
              >
                <option value="">{isBn ? BN_DICT['select_1'] : EN_DICT['select_1']}</option>
                <option value="father">{isBn ? BN_DICT['father_1'] : EN_DICT['father_1']}</option>
                <option value="mother">{isBn ? BN_DICT['mother_1'] : EN_DICT['mother_1']}</option>
                <option value="student">{isBn ? BN_DICT['student'] : EN_DICT['student']}</option>
                <option value="other_guardian">{isBn ? BN_DICT['other_guardian'] : EN_DICT['other_guardian']}</option>
              </select>
            </div>
          </div>

          <div className="flex items-center gap-3 p-4 bg-slate-50 border border-slate-200 rounded-xl">
            <input
              type="checkbox"
              id="studentFound"
              checked={formData.studentFound}
              onChange={e => setFormData({ ...formData, studentFound: e.target.checked })}
              className="w-5 h-5 text-indigo-600 rounded border-slate-300 focus:ring-indigo-500"
            />
            <label htmlFor="studentFound" className="text-sm font-semibold text-slate-700 cursor-pointer">
              {isBn ? BN_DICT['student_found_at_home'] : EN_DICT['student_found_at_home']}
            </label>
          </div>

          <div className="space-y-4">
            <h3 className="text-sm font-bold text-slate-800 border-b border-slate-100 pb-2">
              {isBn ? BN_DICT['observations_feedback'] : EN_DICT['observations_feedback']}
            </h3>
            
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['study_environment'] : EN_DICT['study_environment']}
              </label>
              <select
                value={formData.studyEnvironment || ''}
                onChange={e => setFormData({ ...formData, studyEnvironment: e.target.value })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
              >
                <option value="">{isBn ? BN_DICT['select_1'] : EN_DICT['select_1']}</option>
                <option value="excellent">{isBn ? BN_DICT['excellent'] : EN_DICT['excellent']}</option>
                <option value="good">{isBn ? BN_DICT['good'] : EN_DICT['good']}</option>
                <option value="needs_improvement">{isBn ? BN_DICT['needs_improvement'] : EN_DICT['needs_improvement']}</option>
                <option value="poor">{isBn ? BN_DICT['poor'] : EN_DICT['poor']}</option>
              </select>
            </div>

            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['teacher_observation_advice'] : EN_DICT['teacher_observation_advice']}
              </label>
              <textarea
                rows={3}
                value={formData.teacherObservation || ''}
                onChange={e => setFormData({ ...formData, teacherObservation: e.target.value })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500 resize-none"
                placeholder={isBn ? BN_DICT['write_your_observations'] : EN_DICT['write_your_observations']}
              />
            </div>
            
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['outcome'] : EN_DICT['outcome']}
              </label>
              <select
                value={formData.outcome || ''}
                onChange={e => setFormData({ ...formData, outcome: e.target.value as any })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-indigo-500/20 focus:border-indigo-500"
              >
                <option value="">{isBn ? BN_DICT['select_1'] : EN_DICT['select_1']}</option>
                <option value="satisfactory">{isBn ? BN_DICT['satisfactory'] : EN_DICT['satisfactory']}</option>
                <option value="monitoring">{isBn ? BN_DICT['needs_monitoring'] : EN_DICT['needs_monitoring']}</option>
                <option value="re_followup">{isBn ? BN_DICT['re_followup_needed'] : EN_DICT['re_followup_needed']}</option>
              </select>
            </div>
          </div>

          <div className="space-y-4">
            <h3 className="text-sm font-bold text-slate-800 border-b border-slate-100 pb-2">
              {isBn ? BN_DICT['proofs_attachments'] : EN_DICT['proofs_attachments']}
            </h3>
            
            <div className="flex gap-4">
              <button 
                type="button"
                onClick={getLocation}
                className={`flex-1 p-4 border-2 border-dashed rounded-xl flex flex-col items-center justify-center gap-2 transition-colors ${
                  formData.latitude ? 'border-emerald-300 bg-emerald-50 text-emerald-700' : 'border-slate-200 hover:border-slate-300 hover:bg-slate-50 text-slate-500'
                }`}
              >
                <MapPin className={`w-6 h-6 ${formData.latitude ? 'text-emerald-500' : 'text-slate-400'}`} />
                <span className="text-sm font-semibold">
                  {isLocating ? (isBn ? BN_DICT['getting_location'] : EN_DICT['getting_location']) : 
                   formData.latitude ? (isBn ? BN_DICT['location_captured'] : EN_DICT['location_captured']) : 
                   (isBn ? BN_DICT['tag_gps_location'] : EN_DICT['tag_gps_location'])}
                </span>
                {formData.latitude && (
                  <span className="text-xs opacity-80">{formData.latitude.toFixed(4)}, {formData.longitude?.toFixed(4)}</span>
                )}
              </button>

              <button 
                type="button"
                className="flex-1 p-4 border-2 border-dashed border-slate-200 hover:border-slate-300 hover:bg-slate-50 rounded-xl flex flex-col items-center justify-center gap-2 text-slate-500 transition-colors"
              >
                <Camera className="w-6 h-6 text-slate-400" />
                <span className="text-sm font-semibold">{isBn ? BN_DICT['add_photo'] : EN_DICT['add_photo']}</span>
                <span className="text-xs text-slate-400">{isBn ? BN_DICT['optional_1'] : EN_DICT['optional_1']}</span>
              </button>
            </div>
          </div>
        </form>

        <div className="p-5 border-t border-slate-100 bg-slate-50 shrink-0 flex justify-end gap-3">
          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2.5 text-sm font-semibold text-slate-600 hover:bg-slate-200 rounded-xl transition-colors"
          >
            {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
          </button>
          <button
            onClick={handleSubmit}
            className="px-5 py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white text-sm font-semibold rounded-xl flex items-center gap-2 transition-colors shadow-sm"
          >
            <Save className="w-4 h-4" />
            {isBn ? BN_DICT['submit_report'] : EN_DICT['submit_report']}
          </button>
        </div>
      </div>
    </div>
  );
};
