import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React from 'react';
import { X, Calendar, MapPin, User, Home, FileText, CheckCircle2, AlertTriangle, RefreshCcw, Camera, PenTool, Download } from 'lucide-react';
import { FollowupVisit, Student, FollowupCampaign, FollowupTeam } from '../../../../types';
import { useAppStore } from '../../../../store/useAppStore';
import { exportIndividualVisitPdf } from '../utils/followupPdfExport';

export interface MappedVisit extends FollowupVisit {
  student?: Student;
  campaign?: FollowupCampaign;
  team?: FollowupTeam;
}

interface VisitDetailsModalProps {
  isOpen: boolean;
  onClose: () => void;
  visit: MappedVisit;
}

export const VisitDetailsModal: React.FC<VisitDetailsModalProps> = ({ isOpen, onClose, visit }) => {
  const { language } = useAppStore();
  const isBn = language === 'bn';

  if (!isOpen) return null;

  const getOutcomeBadge = (outcome?: string) => {
    switch (outcome) {
      case 'satisfactory':
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-sm font-semibold bg-emerald-100 text-emerald-700">
            <CheckCircle2 className="w-4 h-4" />
            {isBn ? BN_DICT['satisfactory'] : EN_DICT['satisfactory']}
          </span>
        );
      case 'monitoring':
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-sm font-semibold bg-amber-100 text-amber-700">
            <AlertTriangle className="w-4 h-4" />
            {isBn ? BN_DICT['monitoring'] : EN_DICT['monitoring']}
          </span>
        );
      case 're_followup':
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-sm font-semibold bg-rose-100 text-rose-700">
            <RefreshCcw className="w-4 h-4" />
            {isBn ? BN_DICT['re_followup'] : EN_DICT['re_followup']}
          </span>
        );
      default:
        return (
          <span className="inline-flex items-center gap-1.5 px-3 py-1.5 rounded-full text-sm font-semibold bg-slate-100 text-slate-700">
            {isBn ? BN_DICT['unspecified'] : EN_DICT['unspecified']}
          </span>
        );
    }
  };

  const getPersonMetText = (personMet?: string) => {
    switch (personMet) {
      case 'father': return isBn ? BN_DICT['father_1'] : EN_DICT['father_1'];
      case 'mother': return isBn ? BN_DICT['mother_1'] : EN_DICT['mother_1'];
      case 'student': return isBn ? BN_DICT['student'] : EN_DICT['student'];
      case 'other_guardian': return isBn ? BN_DICT['other_guardian'] : EN_DICT['other_guardian'];
      default: return isBn ? BN_DICT['unknown'] : EN_DICT['unknown'];
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 sm:p-6 bg-slate-900/50 backdrop-blur-sm">
      <div className="bg-white rounded-2xl shadow-xl w-full max-w-2xl max-h-[90vh] flex flex-col overflow-hidden">
        
        {/* Header */}
        <div className="flex items-center justify-between p-5 border-b border-slate-100 bg-slate-50/50">
          <div>
            <h2 className="text-xl font-bold text-slate-800">
              {isBn ? BN_DICT['visit_details_report'] : EN_DICT['visit_details_report']}
            </h2>
            <p className="text-sm text-slate-500 mt-1 flex items-center gap-1.5">
              <Calendar className="w-4 h-4" />
              {new Date(visit.visitDate).toLocaleDateString(isBn ? BN_DICT['en_us'] : EN_DICT['en_us'], { 
                weekday: 'long', year: 'numeric', month: 'long', day: 'numeric',
                hour: '2-digit', minute: '2-digit'
              })}
            </p>
          </div>
          <button 
            onClick={onClose}
            className="p-2 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-xl transition-colors"
          >
            <X className="w-5 h-5" />
          </button>
        </div>

        {/* Content */}
        <div className="flex-1 overflow-y-auto p-5 sm:p-6 custom-scrollbar space-y-6">
          
          {/* Student & Campaign Header */}
          <div className="flex items-start gap-4 p-4 rounded-xl bg-slate-50 border border-slate-100">
            {visit.student?.photo ? (
              <img src={visit.student.photo} alt={visit.student.name} className="w-16 h-16 rounded-full object-cover border-2 border-white shadow-sm shrink-0" />
            ) : (
              <div className="w-16 h-16 rounded-full bg-indigo-100 flex items-center justify-center text-indigo-600 font-bold text-xl border-2 border-white shadow-sm shrink-0">
                {visit.student?.name.charAt(0)}
              </div>
            )}
            <div className="flex-1 min-w-0">
              <h3 className="text-lg font-bold text-slate-800 truncate">
                {isBn && visit.student?.nameBn ? visit.student.nameBn : visit.student?.name}
              </h3>
              <p className="text-sm text-slate-500 mb-2">
                ID: {visit.student?.studentId} • {isBn ? BN_DICT['class_1'] : EN_DICT['class_1']} {visit.student?.class} {visit.student?.section && `(${visit.student.section})`}
              </p>
              
              <div className="inline-flex items-center gap-2 px-2.5 py-1 rounded-md bg-indigo-50 text-indigo-700 text-xs font-medium">
                <FileText className="w-3.5 h-3.5" />
                <span className="truncate max-w-[200px] sm:max-w-xs">{visit.campaign?.title || 'Unknown Campaign'}</span>
              </div>
            </div>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-2 gap-6">
            {/* Visit Info */}
            <div className="space-y-4">
              <h4 className="text-sm font-bold text-slate-800 uppercase tracking-wider">
                {isBn ? BN_DICT['met_environment'] : EN_DICT['met_environment']}
              </h4>
              
              <div className="space-y-3">
                <div className="flex items-start gap-3">
                  <User className="w-5 h-5 text-slate-400 shrink-0 mt-0.5" />
                  <div>
                    <p className="text-xs font-medium text-slate-500">{isBn ? BN_DICT['person_met'] : EN_DICT['person_met']}</p>
                    <p className="text-sm font-semibold text-slate-800">{getPersonMetText(visit.personMet)}</p>
                  </div>
                </div>
                
                <div className="flex items-start gap-3">
                  <Home className="w-5 h-5 text-slate-400 shrink-0 mt-0.5" />
                  <div>
                    <p className="text-xs font-medium text-slate-500">{isBn ? BN_DICT['study_environment'] : EN_DICT['study_environment']}</p>
                    <p className="text-sm font-semibold text-slate-800 capitalize">
                      {visit.studyEnvironment?.replace('_', ' ') || 'N/A'}
                    </p>
                  </div>
                </div>

                <div className="flex items-start gap-3">
                  <MapPin className="w-5 h-5 text-slate-400 shrink-0 mt-0.5" />
                  <div>
                    <p className="text-xs font-medium text-slate-500">{isBn ? BN_DICT['location_gps'] : EN_DICT['location_gps']}</p>
                    {visit.latitude && visit.longitude ? (
                      <a 
                        href={`https://www.google.com/maps?q=${visit.latitude},${visit.longitude}`}
                        target="_blank"
                        rel="noreferrer"
                        className="text-sm font-semibold text-indigo-600 hover:underline flex items-center gap-1"
                      >
                        {visit.latitude.toFixed(4)}, {visit.longitude.toFixed(4)}
                      </a>
                    ) : (
                      <p className="text-sm text-slate-500 italic">{isBn ? BN_DICT['not_recorded'] : EN_DICT['not_recorded']}</p>
                    )}
                  </div>
                </div>
              </div>
            </div>

            {/* Outcome & Comments */}
            <div className="space-y-4">
              <h4 className="text-sm font-bold text-slate-800 uppercase tracking-wider">
                {isBn ? BN_DICT['outcome_observations'] : EN_DICT['outcome_observations']}
              </h4>
              
              <div>
                <p className="text-xs font-medium text-slate-500 mb-2">{isBn ? BN_DICT['final_outcome'] : EN_DICT['final_outcome']}</p>
                {getOutcomeBadge(visit.outcome)}
              </div>

              <div>
                <p className="text-xs font-medium text-slate-500 mb-1">{isBn ? BN_DICT['teacher_observations'] : EN_DICT['teacher_observations']}</p>
                <div className="p-3 bg-slate-50 rounded-xl border border-slate-200 text-sm text-slate-700 min-h-[80px]">
                  {visit.teacherObservation || (
                    <span className="italic text-slate-400">
                      {isBn ? BN_DICT['no_observations_recorded'] : EN_DICT['no_observations_recorded']}
                    </span>
                  )}
                </div>
              </div>
            </div>
          </div>

          {/* Photo Attachment (If any) */}
          {(visit as any).attachedPhoto && (
            <div className="pt-4 border-t border-slate-100">
              <h4 className="text-sm font-bold text-slate-800 mb-3 flex items-center gap-2">
                <Camera className="w-4 h-4 text-slate-400" />
                {isBn ? BN_DICT['attached_photo'] : EN_DICT['attached_photo']}
              </h4>
              <img 
                src={(visit as any).attachedPhoto} 
                alt="Visit Attachment" 
                className="w-full max-w-sm rounded-xl border border-slate-200 shadow-sm"
              />
            </div>
          )}
          
        
          {/* Digital Signature */}
          {visit.guardianSignaturePath && (
            <div className="pt-4 border-t border-slate-100">
              <h4 className="text-sm font-bold text-slate-800 mb-3 flex items-center gap-2">
                <PenTool className="w-4 h-4 text-slate-400" />
                {isBn ? BN_DICT['digital_signature_of_guardian'] : EN_DICT['digital_signature_of_guardian']}
              </h4>
              <div className="bg-slate-50 border border-slate-200 rounded-xl p-4 inline-block">
                <img 
                  src={visit.guardianSignaturePath} 
                  alt="Guardian Signature" 
                  className="w-full max-w-sm"
                  style={{ maxHeight: '150px' }}
                />
              </div>
              <p className="text-xs text-slate-500 mt-2">
                {isBn ? BN_DICT['signed_by'] : EN_DICT['signed_by']} {getPersonMetText(visit.personMet)}
              </p>
            </div>
          )}

        </div>

        {/* Footer */}
        <div className="p-5 border-t border-slate-100 bg-slate-50/50 flex justify-between">

          <button
            onClick={() => exportIndividualVisitPdf(visit, isBn)}
            className="flex items-center gap-2 px-6 py-2.5 bg-indigo-600 border border-transparent text-white font-semibold rounded-xl hover:bg-indigo-700 transition-colors shadow-sm"
          >
            <Download className="w-4 h-4" />
            {isBn ? BN_DICT['download_pdf'] : EN_DICT['download_pdf']}
          </button>
          <button
            onClick={onClose}

            className="px-6 py-2.5 bg-white border border-slate-200 text-slate-700 font-semibold rounded-xl hover:bg-slate-50 transition-colors"
          >
            {isBn ? BN_DICT['close'] : EN_DICT['close']}
          </button>
        </div>

      </div>
    </div>
  );
};
