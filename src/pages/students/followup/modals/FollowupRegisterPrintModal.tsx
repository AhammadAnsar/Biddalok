import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState, useRef } from 'react';
import { X, Printer, Download, FileText, CheckCircle2, ChevronLeft, ChevronRight } from 'lucide-react';
import { FollowupCampaign, FollowupTeam, Institution, StaffMember } from '../../../../types';
import { MappedVisit } from '../utils/followupPdfExport';
import { OfficialFollowupRegisterDoc } from '../components/OfficialFollowupRegisterDoc';
import { downloadMultiPageDocumentPDF } from '../../../../utils/pdfGenerator';
import { toBengaliNumber, getBengaliInstitutionAcronym } from '../../../../utils/bengaliUtils';

interface FollowupRegisterPrintModalProps {
  isOpen: boolean;
  onClose: () => void;
  campaign: FollowupCampaign;
  team?: FollowupTeam | null;
  records: MappedVisit[];
  institution: Institution;
  staff: StaffMember[];
  isBn?: boolean;
}

export const FollowupRegisterPrintModal: React.FC<FollowupRegisterPrintModalProps> = ({
  isOpen,
  onClose,
  campaign,
  team,
  records,
  institution,
  staff,
  isBn = true,
}) => {
  const [isGeneratingPdf, setIsGeneratingPdf] = useState(false);
  const [downloadSuccess, setDownloadSuccess] = useState(false);
  const [customMemoNo, setCustomMemoNo] = useState(() => {
    const instName = institution?.nameBn || institution?.name || 'বিদ্যালয়';
    const acronym = getBengaliInstitutionAcronym(instName);
    const curYear = new Date().getFullYear().toString();
    const yearBn = toBengaliNumber(curYear);
    return `${acronym}/শিক্ষার্থী/ফলোআপ/রেজিস্টার/${yearBn}/০১`;
  });

  const printContainerRef = useRef<HTMLDivElement>(null);

  if (!isOpen) return null;

  const handleDownloadPdf = async () => {
    if (!printContainerRef.current) return;
    try {
      setIsGeneratingPdf(true);
      const pageElements = printContainerRef.current.querySelectorAll('.register-page-sheet');
      if (!pageElements || pageElements.length === 0) {
        throw new Error('No pages found to export');
      }

      const elementsArray = Array.from(pageElements) as HTMLElement[];
      const fileName = `Followup_Register_${campaign.title.replace(/\s+/g, '_')}_${new Date().toISOString().slice(0, 10)}.pdf`;

      await downloadMultiPageDocumentPDF(elementsArray, fileName, {
        orientation: 'landscape',
        format: 'a4',
      });

      setDownloadSuccess(true);
      setTimeout(() => setDownloadSuccess(false), 4000);
    } catch (err) {
      console.error('PDF export failed:', err);
      alert(isBn ? BN_DICT['failed_to_export_pdf_please_tr'] : EN_DICT['failed_to_export_pdf_please_tr']);
    } finally {
      setIsGeneratingPdf(false);
    }
  };

  const handleNativePrint = () => {
    window.print();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-2 sm:p-4 bg-slate-950/70 backdrop-blur-sm">
      <div className="bg-slate-100 rounded-2xl shadow-2xl w-full max-w-7xl h-[92vh] flex flex-col overflow-hidden border border-slate-300">
        {/* Header Bar */}
        <div className="flex items-center justify-between px-6 py-3.5 bg-white border-b border-slate-200 shrink-0">
          <div className="flex items-center gap-3">
            <div className="p-2 bg-indigo-50 text-indigo-700 rounded-xl">
              <FileText className="w-5 h-5" />
            </div>
            <div>
              <h3 className="text-base font-bold text-slate-800 flex items-center gap-2">
                {isBn ? BN_DICT['official_follow_up_register_pr'] : EN_DICT['official_follow_up_register_pr']}
                <span className="px-2 py-0.5 rounded-full text-xs font-semibold bg-emerald-100 text-emerald-800">
                  {isBn ? BN_DICT['a4_landscape'] : EN_DICT['a4_landscape']}
                </span>
              </h3>
              <p className="text-xs text-slate-500">
                {campaign.title} {team ? `• ${team.name}` : ''} • {isBn ? `মোট ${records.length} টি রেকর্ড` : `${records.length} total records`}
              </p>
            </div>
          </div>

          <div className="flex items-center gap-3">
            {/* Memo No quick edit */}
            <div className="hidden md:flex items-center gap-1.5 text-xs bg-slate-50 border border-slate-200 rounded-lg px-2.5 py-1">
              <span className="font-semibold text-slate-600">{isBn ? BN_DICT['memo'] : EN_DICT['memo']}</span>
              <input
                type="text"
                value={customMemoNo}
                onChange={e => setCustomMemoNo(e.target.value)}
                className="bg-transparent border-none text-xs font-mono text-slate-800 focus:outline-none w-64"
                title={isBn ? BN_DICT['edit_memo_number_if_needed'] : EN_DICT['edit_memo_number_if_needed']}
              />
            </div>

            {/* Print Button */}
            <button
              onClick={handleNativePrint}
              className="flex items-center gap-1.5 px-3.5 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl text-xs font-semibold transition-colors"
            >
              <Printer className="w-4 h-4" />
              <span>{isBn ? BN_DICT['print'] : EN_DICT['print']}</span>
            </button>

            {/* Download PDF Button */}
            <button
              onClick={handleDownloadPdf}
              disabled={isGeneratingPdf}
              className="flex items-center gap-2 px-5 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-xs font-bold shadow-md shadow-indigo-600/20 transition-all disabled:opacity-50"
            >
              {isGeneratingPdf ? (
                <>
                  <div className="w-3.5 h-3.5 border-2 border-white/30 border-t-white rounded-full animate-spin" />
                  <span>{isBn ? BN_DICT['generating_pdf'] : EN_DICT['generating_pdf']}</span>
                </>
              ) : downloadSuccess ? (
                <>
                  <CheckCircle2 className="w-4 h-4 text-emerald-300" />
                  <span>{isBn ? BN_DICT['downloaded'] : EN_DICT['downloaded']}</span>
                </>
              ) : (
                <>
                  <Download className="w-4 h-4" />
                  <span>{isBn ? BN_DICT['download_pdf'] : EN_DICT['download_pdf']}</span>
                </>
              )}
            </button>

            {/* Close */}
            <button
              onClick={onClose}
              className="p-2 text-slate-400 hover:text-rose-600 hover:bg-rose-50 rounded-xl transition-colors ml-1"
            >
              <X className="w-5 h-5" />
            </button>
          </div>
        </div>

        {/* Document Preview Viewport */}
        <div className="flex-1 overflow-auto p-4 sm:p-6 bg-slate-200/80 custom-scrollbar flex flex-col items-center">
          <div ref={printContainerRef} className="space-y-6">
            <OfficialFollowupRegisterDoc
              campaign={campaign}
              team={team}
              records={records}
              institution={institution}
              staff={staff}
              isBn={isBn}
              memoNo={customMemoNo}
            />
          </div>
        </div>
      </div>
    </div>
  );
};
