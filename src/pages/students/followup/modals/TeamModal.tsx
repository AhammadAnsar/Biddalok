import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { X, Users, Save } from 'lucide-react';
import { useAppStore } from '../../../../store/useAppStore';
import { FollowupTeam } from '../../../../types';
import toast from 'react-hot-toast';

interface TeamModalProps {
  isOpen: boolean;
  onClose: () => void;
  campaignId: string;
  team?: FollowupTeam;
}

export const TeamModal: React.FC<TeamModalProps> = ({ isOpen, onClose, campaignId, team }) => {
  const { language, addFollowupTeam, updateFollowupTeam, staff } = useAppStore();
  const isBn = language === 'bn';

  const [formData, setFormData] = useState<Partial<FollowupTeam>>({
    name: '',
    leaderId: '',
    memberIds: []
  });

  const teachers = staff.filter(s => s.staffType === 'teaching' || s.role === 'teacher' || (s.designation && s.designation.toLowerCase().includes('teacher')));

  useEffect(() => {
    if (team) {
      setFormData(team);
    } else {
      setFormData({ name: '', leaderId: '', memberIds: [] });
    }
  }, [team, isOpen]);

  if (!isOpen) return null;

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!formData.name || !formData.leaderId) {
      toast.error(isBn ? BN_DICT['please_fill_all_required_field'] : EN_DICT['please_fill_all_required_field']);
      return;
    }

    if (team) {
      updateFollowupTeam(team.id, formData);
      toast.success(isBn ? BN_DICT['team_updated_successfully'] : EN_DICT['team_updated_successfully']);
    } else {
      const newTeam: FollowupTeam = {
        ...formData as any,
        id: `ftm_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
        campaignId,
        createdAt: new Date().toISOString(),
      };
      addFollowupTeam(newTeam);
      toast.success(isBn ? BN_DICT['new_team_created_successfully'] : EN_DICT['new_team_created_successfully']);
    }
    onClose();
  };

  const handleMemberToggle = (id: string) => {
    const current = formData.memberIds || [];
    if (current.includes(id)) {
      setFormData({ ...formData, memberIds: current.filter(i => i !== id) });
    } else {
      setFormData({ ...formData, memberIds: [...current, id] });
    }
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm">
      <div className="bg-white rounded-2xl w-full max-w-lg shadow-xl overflow-hidden flex flex-col max-h-[90vh]">
        <div className="flex items-center justify-between p-5 border-b border-slate-100 shrink-0">
          <h2 className="text-xl font-bold text-slate-800 flex items-center gap-2">
            <Users className="w-5 h-5 text-rose-500" />
            {team ? (isBn ? BN_DICT['edit_team'] : EN_DICT['edit_team']) : (isBn ? BN_DICT['new_team'] : EN_DICT['new_team'])}
          </h2>
          <button onClick={onClose} className="p-2 hover:bg-slate-100 rounded-full transition-colors">
            <X className="w-5 h-5 text-slate-500" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="p-6 overflow-y-auto custom-scrollbar flex-1 space-y-4">
          <div>
            <label className="block text-sm font-semibold text-slate-700 mb-1">
              {isBn ? BN_DICT['team_name'] : EN_DICT['team_name']} <span className="text-rose-500">*</span>
            </label>
            <input
              type="text"
              required
              value={formData.name || ''}
              onChange={e => setFormData({ ...formData, name: e.target.value })}
              className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
              placeholder={isBn ? BN_DICT['e_g_team_alpha'] : EN_DICT['e_g_team_alpha']}
            />
          </div>

          <div>
            <label className="block text-sm font-semibold text-slate-700 mb-1">
              {isBn ? BN_DICT['team_leader_1'] : EN_DICT['team_leader_1']} <span className="text-rose-500">*</span>
            </label>
            <select
              required
              value={formData.leaderId || ''}
              onChange={e => {
                const val = e.target.value;
                setFormData({ 
                  ...formData, 
                  leaderId: val,
                  memberIds: formData.memberIds?.filter(id => id !== val) // Remove leader from members if they were there
                });
              }}
              className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
            >
              <option value="">{isBn ? BN_DICT['select_leader'] : EN_DICT['select_leader']}</option>
              {teachers.map(t => (
                <option key={t.id} value={t.id}>{isBn && t.nameBn ? t.nameBn : t.name}</option>
              ))}
            </select>
          </div>

          <div>
            <label className="block text-sm font-semibold text-slate-700 mb-2">
              {isBn ? BN_DICT['team_members_optional'] : EN_DICT['team_members_optional']}
            </label>
            <div className="border border-slate-200 rounded-xl p-3 max-h-48 overflow-y-auto bg-slate-50 space-y-2 custom-scrollbar">
              {teachers.filter(t => t.id !== formData.leaderId).map(t => (
                <label key={t.id} className="flex items-center gap-3 p-2 hover:bg-white rounded-lg cursor-pointer transition-colors border border-transparent hover:border-slate-200">
                  <input
                    type="checkbox"
                    checked={formData.memberIds?.includes(t.id) || false}
                    onChange={() => handleMemberToggle(t.id)}
                    className="w-4 h-4 text-rose-600 border-slate-300 rounded focus:ring-rose-500"
                  />
                  <span className="text-sm text-slate-700">{isBn && t.nameBn ? t.nameBn : t.name}</span>
                </label>
              ))}
              {teachers.length <= 1 && (
                <p className="text-sm text-slate-500 text-center py-2">
                  {isBn ? BN_DICT['no_other_teachers_available'] : EN_DICT['no_other_teachers_available']}
                </p>
              )}
            </div>
          </div>
        </form>

        <div className="p-5 border-t border-slate-100 bg-slate-50 shrink-0 flex justify-end gap-3">
          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2.5 text-sm font-semibold text-slate-600 hover:bg-slate-200 rounded-xl transition-colors"
          >
            {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
          </button>
          <button
            onClick={handleSubmit}
            className="px-5 py-2.5 bg-rose-600 hover:bg-rose-700 text-white text-sm font-semibold rounded-xl flex items-center gap-2 transition-colors shadow-sm"
          >
            <Save className="w-4 h-4" />
            {team ? (isBn ? BN_DICT['update'] : EN_DICT['update']) : (isBn ? BN_DICT['save_team'] : EN_DICT['save_team'])}
          </button>
        </div>
      </div>
    </div>
  );
};
