import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { X, Calendar as CalendarIcon, Save } from 'lucide-react';
import { useAppStore } from '../../../../store/useAppStore';
import { FollowupCampaign, FollowupCampaignStatus } from '../../../../types';
import { toBengaliNumber } from '../../../../utils/bengaliUtils';
import toast from 'react-hot-toast';

interface CampaignModalProps {
  isOpen: boolean;
  onClose: () => void;
  campaign?: FollowupCampaign;
}

export const CampaignModal: React.FC<CampaignModalProps> = ({ isOpen, onClose, campaign }) => {
  const { language, addFollowupCampaign, updateFollowupCampaign, institution } = useAppStore();
  const isBn = language === 'bn';

  const currentYear = new Date().getFullYear().toString();
  const [formData, setFormData] = useState<Partial<FollowupCampaign>>({
    academicYear: currentYear,
    status: 'draft',
  });

  useEffect(() => {
    if (campaign) {
      setFormData(campaign);
    } else {
      setFormData({ academicYear: currentYear, status: 'draft' });
    }
  }, [campaign, currentYear, isOpen]);

  if (!isOpen) return null;

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (!formData.title || !formData.startDate || !formData.endDate) {
      toast.error(isBn ? BN_DICT['please_fill_all_required_field'] : EN_DICT['please_fill_all_required_field']);
      return;
    }

    if (new Date(formData.endDate) < new Date(formData.startDate)) {
      toast.error(isBn ? BN_DICT['end_date_cannot_be_before_star'] : EN_DICT['end_date_cannot_be_before_star']);
      return;
    }

    if (campaign) {
      updateFollowupCampaign(campaign.id, formData);
      toast.success(isBn ? BN_DICT['campaign_updated_successfully'] : EN_DICT['campaign_updated_successfully']);
    } else {
      const newCampaign: FollowupCampaign = {
        ...formData as any,
        id: `fcmp_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
        institutionId: institution?.eiin || '',
        createdAt: new Date().toISOString(),
        updatedAt: new Date().toISOString(),
      };
      addFollowupCampaign(newCampaign);
      toast.success(isBn ? BN_DICT['new_campaign_created_successfu'] : EN_DICT['new_campaign_created_successfu']);
    }
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm">
      <div className="bg-white rounded-2xl w-full max-w-lg shadow-xl overflow-hidden flex flex-col max-h-[90vh]">
        <div className="flex items-center justify-between p-5 border-b border-slate-100 shrink-0">
          <h2 className="text-xl font-bold text-slate-800 flex items-center gap-2">
            <CalendarIcon className="w-5 h-5 text-rose-500" />
            {campaign ? (isBn ? BN_DICT['edit_campaign'] : EN_DICT['edit_campaign']) : (isBn ? BN_DICT['new_campaign'] : EN_DICT['new_campaign'])}
          </h2>
          <button onClick={onClose} className="p-2 hover:bg-slate-100 rounded-full transition-colors">
            <X className="w-5 h-5 text-slate-500" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="p-6 overflow-y-auto custom-scrollbar flex-1 space-y-4">
          <div>
            <label className="block text-sm font-semibold text-slate-700 mb-1">
              {isBn ? BN_DICT['campaign_title_1'] : EN_DICT['campaign_title_1']} <span className="text-rose-500">*</span>
            </label>
            <input
              type="text"
              required
              value={formData.title || ''}
              onChange={e => setFormData({ ...formData, title: e.target.value })}
              className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
              placeholder={isBn ? BN_DICT['e_g_post_eid_home_visit_2026'] : EN_DICT['e_g_post_eid_home_visit_2026']}
            />
          </div>

          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['academic_year_1'] : EN_DICT['academic_year_1']} <span className="text-rose-500">*</span>
              </label>
              <select
                required
                value={formData.academicYear || currentYear}
                onChange={e => setFormData({ ...formData, academicYear: e.target.value })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
              >
                {[currentYear, (parseInt(currentYear) - 1).toString(), (parseInt(currentYear) - 2).toString()].map(y => (
                  <option key={y} value={y}>{isBn ? toBengaliNumber(y) : y}</option>
                ))}
              </select>
            </div>
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['status'] : EN_DICT['status']} <span className="text-rose-500">*</span>
              </label>
              <select
                required
                value={formData.status || 'draft'}
                onChange={e => setFormData({ ...formData, status: e.target.value as FollowupCampaignStatus })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
              >
                <option value="draft">{isBn ? BN_DICT['draft'] : EN_DICT['draft']}</option>
                <option value="planned">{isBn ? BN_DICT['planned'] : EN_DICT['planned']}</option>
                <option value="active">{isBn ? BN_DICT['active'] : EN_DICT['active']}</option>
                <option value="completed">{isBn ? BN_DICT['completed'] : EN_DICT['completed']}</option>
              </select>
            </div>
          </div>

          <div className="grid grid-cols-2 gap-4">
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['start_date'] : EN_DICT['start_date']} <span className="text-rose-500">*</span>
              </label>
              <input
                type="date"
                required
                value={formData.startDate || ''}
                onChange={e => setFormData({ ...formData, startDate: e.target.value })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
              />
            </div>
            <div>
              <label className="block text-sm font-semibold text-slate-700 mb-1">
                {isBn ? BN_DICT['end_date'] : EN_DICT['end_date']} <span className="text-rose-500">*</span>
              </label>
              <input
                type="date"
                required
                value={formData.endDate || ''}
                onChange={e => setFormData({ ...formData, endDate: e.target.value })}
                className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
              />
            </div>
          </div>

          <div>
            <label className="block text-sm font-semibold text-slate-700 mb-1">
              {isBn ? BN_DICT['purpose_description'] : EN_DICT['purpose_description']}
            </label>
            <textarea
              rows={3}
              value={formData.purpose || ''}
              onChange={e => setFormData({ ...formData, purpose: e.target.value })}
              className="w-full px-4 py-2 bg-slate-50 border border-slate-200 rounded-xl focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500 resize-none"
              placeholder={isBn ? BN_DICT['campaign_purpose'] : EN_DICT['campaign_purpose']}
            />
          </div>
        </form>

        <div className="p-5 border-t border-slate-100 bg-slate-50 shrink-0 flex justify-end gap-3">
          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2.5 text-sm font-semibold text-slate-600 hover:bg-slate-200 rounded-xl transition-colors"
          >
            {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
          </button>
          <button
            onClick={handleSubmit}
            className="px-5 py-2.5 bg-rose-600 hover:bg-rose-700 text-white text-sm font-semibold rounded-xl flex items-center gap-2 transition-colors shadow-sm"
          >
            <Save className="w-4 h-4" />
            {campaign ? (isBn ? BN_DICT['update'] : EN_DICT['update']) : (isBn ? BN_DICT['save_campaign'] : EN_DICT['save_campaign'])}
          </button>
        </div>
      </div>
    </div>
  );
};
