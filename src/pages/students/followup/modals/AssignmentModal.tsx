import { EN_DICT, BN_DICT } from "../../../../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { X, Save, UserPlus, Search } from 'lucide-react';
import { useAppStore } from '../../../../store/useAppStore';
import { FollowupAssignment, FollowupTeam } from '../../../../types';
import toast from 'react-hot-toast';

interface AssignmentModalProps {
  isOpen: boolean;
  onClose: () => void;
  campaignId: string;
  team: FollowupTeam;
}

export const AssignmentModal: React.FC<AssignmentModalProps> = ({ isOpen, onClose, campaignId, team }) => {
  const { language, students, followupAssignments, bulkAddFollowupAssignments, academicClasses } = useAppStore();
  const isBn = language === 'bn';

  const [selectedClass, setSelectedClass] = useState('');
  const [search, setSearch] = useState('');
  const [selectedStudentIds, setSelectedStudentIds] = useState<string[]>([]);

  // Reset when opened
  useEffect(() => {
    if (isOpen) {
      setSelectedStudentIds([]);
      setSearch('');
      setSelectedClass('');
    }
  }, [isOpen]);

  if (!isOpen) return null;

  // Filter out students already assigned to this campaign
  const existingAssignedStudentIds = (followupAssignments || [])
    .filter(a => a.campaignId === campaignId)
    .map(a => a.studentId);

  const availableStudents = students.filter(s => {
    if (existingAssignedStudentIds.includes(s.id)) return false;
    if (selectedClass && s.class !== selectedClass) return false;
    if (search && !(
      s.name.toLowerCase().includes(search.toLowerCase()) || 
      (s.studentId && s.studentId.toLowerCase().includes(search.toLowerCase())) ||
      (s.nameBn && s.nameBn.includes(search))
    )) return false;
    return true;
  });

  const handleToggleStudent = (id: string) => {
    if (selectedStudentIds.includes(id)) {
      setSelectedStudentIds(selectedStudentIds.filter(sid => sid !== id));
    } else {
      setSelectedStudentIds([...selectedStudentIds, id]);
    }
  };

  const handleToggleAll = () => {
    if (selectedStudentIds.length === availableStudents.length && availableStudents.length > 0) {
      setSelectedStudentIds([]);
    } else {
      setSelectedStudentIds(availableStudents.map(s => s.id));
    }
  };

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    if (selectedStudentIds.length === 0) {
      toast.error(isBn ? BN_DICT['select_at_least_one_student'] : EN_DICT['select_at_least_one_student']);
      return;
    }

    // PHASE 14: Enforce active-assignment uniqueness
    const activeAssignments = useAppStore.getState().followupAssignments.filter(a => a.campaignId === campaignId && a.status === 'pending');
    
    const validStudentIds = selectedStudentIds.filter(sid => !activeAssignments.some(a => a.studentId === sid));
    const duplicateCount = selectedStudentIds.length - validStudentIds.length;

    if (validStudentIds.length === 0) {
      toast.error(isBn ? BN_DICT['all_selected_students_already'] : EN_DICT['all_selected_students_already']);
      return;
    }

    const assignments: FollowupAssignment[] = validStudentIds.map(studentId => ({
      id: `fas_${Date.now()}_${Math.random().toString(36).substring(2, 7)}`,
      campaignId,
      teamId: team.id,
      studentId,
      status: 'pending',
      // Scheduled date intentionally empty to allow "unscheduled" state explicitly
      scheduledDate: '',
      createdAt: new Date().toISOString(),
      updatedAt: new Date().toISOString()
    }));

    bulkAddFollowupAssignments(assignments);
    
    if (duplicateCount > 0) {
      toast.error(isBn ? `${duplicateCount} জনের সক্রিয় অ্যাসাইনমেন্ট থাকায় বাদ দেওয়া হয়েছে` : `Skipped ${duplicateCount} due to active assignments`);
    }
    toast.success(isBn ? `${assignments.length} জন শিক্ষার্থীকে সফলভাবে অ্যাসাইন করা হয়েছে` : `${assignments.length} students assigned successfully`);
    onClose();
  };

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm">
      <div className="bg-white rounded-2xl w-full max-w-4xl shadow-xl overflow-hidden flex flex-col max-h-[90vh]">
        <div className="flex items-center justify-between p-5 border-b border-slate-100 shrink-0">
          <div>
            <h2 className="text-xl font-bold text-slate-800 flex items-center gap-2">
              <UserPlus className="w-5 h-5 text-rose-500" />
              {isBn ? BN_DICT['assign_students'] : EN_DICT['assign_students']}
            </h2>
            <p className="text-sm text-slate-500 mt-1">
              {isBn ? BN_DICT['team'] : EN_DICT['team']} <span className="font-semibold text-slate-700">{team.name}</span>
            </p>
          </div>
          <button onClick={onClose} className="p-2 hover:bg-slate-100 rounded-full transition-colors">
            <X className="w-5 h-5 text-slate-500" />
          </button>
        </div>

        <div className="p-5 border-b border-slate-100 bg-slate-50/50 shrink-0 flex flex-col sm:flex-row gap-4">
          <div className="w-full sm:w-1/3">
            <select
              value={selectedClass}
              onChange={e => setSelectedClass(e.target.value)}
              className="w-full px-4 py-2.5 bg-white border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500"
            >
              <option value="">{isBn ? BN_DICT['all_classes'] : EN_DICT['all_classes']}</option>
              {academicClasses.map(c => (
                <option key={c.id} value={c.name}>{isBn && c.nameBn ? c.nameBn : c.name}</option>
              ))}
            </select>
          </div>
          <div className="relative flex-1">
            <Search className="absolute left-3 top-1/2 -translate-y-1/2 w-4 h-4 text-slate-400" />
            <input
              type="text"
              placeholder={isBn ? BN_DICT['search_by_name_or_id'] : EN_DICT['search_by_name_or_id']}
              value={search}
              onChange={(e) => setSearch(e.target.value)}
              className="w-full pl-9 pr-4 py-2.5 bg-white border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-rose-500/20 focus:border-rose-500 transition-all"
            />
          </div>
        </div>

        <div className="flex-1 overflow-auto custom-scrollbar p-5">
          <div className="mb-3 flex items-center justify-between">
            <label className="flex items-center gap-2 cursor-pointer group">
              <input 
                type="checkbox"
                checked={selectedStudentIds.length === availableStudents.length && availableStudents.length > 0}
                onChange={handleToggleAll}
                className="w-4 h-4 text-rose-600 rounded border-slate-300 focus:ring-rose-500"
              />
              <span className="text-sm font-semibold text-slate-700 group-hover:text-slate-900 transition-colors">
                {isBn ? BN_DICT['select_all'] : EN_DICT['select_all']}
              </span>
            </label>
            <span className="text-sm font-medium text-rose-600 bg-rose-50 px-3 py-1 rounded-full">
              {selectedStudentIds.length} {isBn ? BN_DICT['selected'] : EN_DICT['selected']}
            </span>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 gap-3">
            {availableStudents.map(student => (
              <label 
                key={student.id} 
                className={`flex flex-col p-3 rounded-xl border transition-all cursor-pointer ${
                  selectedStudentIds.includes(student.id)
                    ? 'border-rose-500 bg-rose-50/30'
                    : 'border-slate-200 hover:border-slate-300 bg-white'
                }`}
              >
                <div className="flex items-start gap-3">
                  <input
                    type="checkbox"
                    checked={selectedStudentIds.includes(student.id)}
                    onChange={() => handleToggleStudent(student.id)}
                    className="mt-1 w-4 h-4 text-rose-600 border-slate-300 rounded focus:ring-rose-500 shrink-0"
                  />
                  <div className="min-w-0 flex-1">
                    <p className="text-sm font-bold text-slate-800 truncate">
                      {isBn && student.nameBn ? student.nameBn : student.name}
                    </p>
                    <div className="flex flex-wrap gap-x-3 gap-y-1 mt-1 text-xs text-slate-500">
                      <span>ID: {student.studentId || 'N/A'}</span>
                      <span>{isBn ? BN_DICT['class_2'] : EN_DICT['class_2']}: {student.class}</span>
                      {student.roll && <span>{isBn ? BN_DICT['roll'] : EN_DICT['roll']}: {student.roll}</span>}
                    </div>
                  </div>
                </div>
              </label>
            ))}
            
            {availableStudents.length === 0 && (
              <div className="col-span-full py-12 text-center text-slate-500">
                <p>{isBn ? BN_DICT['no_students_found_or_all_alrea'] : EN_DICT['no_students_found_or_all_alrea']}</p>
              </div>
            )}
          </div>
        </div>

        <div className="p-5 border-t border-slate-100 bg-slate-50 shrink-0 flex justify-end gap-3">
          <button
            type="button"
            onClick={onClose}
            className="px-5 py-2.5 text-sm font-semibold text-slate-600 hover:bg-slate-200 rounded-xl transition-colors"
          >
            {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
          </button>
          <button
            onClick={handleSubmit}
            disabled={selectedStudentIds.length === 0}
            className="px-5 py-2.5 bg-rose-600 hover:bg-rose-700 disabled:opacity-50 disabled:hover:bg-rose-600 text-white text-sm font-semibold rounded-xl flex items-center gap-2 transition-colors shadow-sm"
          >
            <Save className="w-4 h-4" />
            {isBn ? BN_DICT['assign'] : EN_DICT['assign']}
          </button>
        </div>
      </div>
    </div>
  );
};
