import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState } from 'react';
import { useAppStore } from '../../store/useAppStore';
import { 
  BookOpen, Settings2, Tag, RefreshCw, CheckCircle2, ChevronRight, School 
} from 'lucide-react';
import { CurriculumFrameworks } from '../../components/curriculum/CurriculumFrameworks';
import { MasterSubjectsManager } from '../../components/curriculum/MasterSubjectsManager';
import { ClassSubjectsManager } from '../../components/curriculum/ClassSubjectsManager';

const Curriculum = () => {
  const { 
    language, 
    curriculums, 
    masterSubjects, 
    curriculumMappings,
    syncCurriculumToExamSubjects 
  } = useAppStore();
  const isBn = language === 'bn';

  type TabType = 'class-subjects' | 'master-subjects' | 'frameworks';
  const [activeTab, setActiveTab] = useState<TabType>('class-subjects');
  const [selectedCurriculumIdForMapping, setSelectedCurriculumIdForMapping] = useState<string | undefined>(undefined);
  const [globalSyncAlert, setGlobalSyncAlert] = useState<string | null>(null);

  const defaultCurr = (curriculums || []).find(c => c.isDefault) || curriculums[0];

  const handleSelectCurriculumForMapping = (id: string) => {
    setSelectedCurriculumIdForMapping(id);
    setActiveTab('class-subjects');
  };

  const handleGlobalSync = () => {
    syncCurriculumToExamSubjects(selectedCurriculumIdForMapping || defaultCurr?.id);
    setGlobalSyncAlert(isBn ? BN_DICT['all_curriculum_subjects_marks'] : EN_DICT['all_curriculum_subjects_marks']);
    setTimeout(() => setGlobalSyncAlert(null), 3500);
  };

  const totalMasterCount = (masterSubjects || []).length;
  const totalFrameworkCount = (curriculums || []).length;
  const activeMappingsCount = (curriculumMappings || []).filter(m => !defaultCurr || m.curriculumId === defaultCurr.id).length;

  return (
    <div className="space-y-5">
      {/* Clean Minimal Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 bg-white p-4 sm:p-5 rounded-2xl border border-slate-200">
        <div>
          <div className="flex items-center gap-1.5 text-xs font-semibold text-teal-700 mb-1">
            <School className="w-3.5 h-3.5" />
            <span>{isBn ? BN_DICT['academic'] : EN_DICT['academic']}</span>
            <ChevronRight className="w-3 h-3 text-slate-400" />
            <span className="text-slate-500">{isBn ? BN_DICT['curriculum_subjects'] : EN_DICT['curriculum_subjects']}</span>
          </div>
          <h1 className="text-xl sm:text-2xl font-bold text-slate-900">
            {isBn ? BN_DICT['curriculum_subject_management'] : EN_DICT['curriculum_subject_management']}
          </h1>
        </div>

        <button
          onClick={handleGlobalSync}
          title={isBn ? BN_DICT['sync_to_exam_module'] : EN_DICT['sync_to_exam_module']}
          className="inline-flex items-center justify-center gap-2 px-4 py-2 bg-teal-600 hover:bg-teal-700 text-white text-xs font-semibold rounded-xl transition-colors shrink-0"
        >
          <RefreshCw className="w-3.5 h-3.5" />
          <span>{isBn ? BN_DICT['sync_exam_subjects'] : EN_DICT['sync_exam_subjects']}</span>
        </button>
      </div>

      {/* Sync Success Alert */}
      {globalSyncAlert && (
        <div className="flex items-center gap-2.5 p-3.5 rounded-xl bg-emerald-50 border border-emerald-200 text-emerald-800 text-xs font-semibold animate-in fade-in">
          <CheckCircle2 className="w-4 h-4 text-emerald-600 shrink-0" />
          <span>{globalSyncAlert}</span>
        </div>
      )}

      {/* Minimal Navigation Tabs */}
      <div className="flex items-center gap-2 border-b border-slate-200 pb-2">
        <button
          id="tab-class-subjects"
          onClick={() => setActiveTab('class-subjects')}
          className={`flex items-center gap-2 px-4 py-2 text-xs sm:text-sm font-semibold rounded-xl transition-colors ${
            activeTab === 'class-subjects' 
              ? 'bg-teal-600 text-white' 
              : 'text-slate-600 hover:bg-slate-100 bg-white border border-slate-200'
          }`}
        >
          <BookOpen className="w-4 h-4" />
          <span>{isBn ? BN_DICT['class_wise_subjects_marks'] : EN_DICT['class_wise_subjects_marks']}</span>
          <span className={`text-[11px] px-1.5 py-0.2 rounded-full font-mono ${
            activeTab === 'class-subjects' ? 'bg-white/20 text-white' : 'bg-slate-100 text-slate-700'
          }`}>
            {activeMappingsCount}
          </span>
        </button>

        <button
          id="tab-master-subjects"
          onClick={() => setActiveTab('master-subjects')}
          className={`flex items-center gap-2 px-4 py-2 text-xs sm:text-sm font-semibold rounded-xl transition-colors ${
            activeTab === 'master-subjects' 
              ? 'bg-teal-600 text-white' 
              : 'text-slate-600 hover:bg-slate-100 bg-white border border-slate-200'
          }`}
        >
          <Tag className="w-4 h-4" />
          <span>{isBn ? BN_DICT['master_subjects_directory'] : EN_DICT['master_subjects_directory']}</span>
          <span className={`text-[11px] px-1.5 py-0.2 rounded-full font-mono ${
            activeTab === 'master-subjects' ? 'bg-white/20 text-white' : 'bg-slate-100 text-slate-700'
          }`}>
            {totalMasterCount}
          </span>
        </button>

        <button
          id="tab-frameworks"
          onClick={() => setActiveTab('frameworks')}
          className={`flex items-center gap-2 px-4 py-2 text-xs sm:text-sm font-semibold rounded-xl transition-colors ${
            activeTab === 'frameworks' 
              ? 'bg-teal-600 text-white' 
              : 'text-slate-600 hover:bg-slate-100 bg-white border border-slate-200'
          }`}
        >
          <Settings2 className="w-4 h-4" />
          <span>{isBn ? BN_DICT['curriculum_frameworks'] : EN_DICT['curriculum_frameworks']}</span>
          <span className={`text-[11px] px-1.5 py-0.2 rounded-full font-mono ${
            activeTab === 'frameworks' ? 'bg-white/20 text-white' : 'bg-slate-100 text-slate-700'
          }`}>
            {totalFrameworkCount}
          </span>
        </button>
      </div>

      {/* Tab Contents */}
      {activeTab === 'class-subjects' && (
        <ClassSubjectsManager selectedCurriculumId={selectedCurriculumIdForMapping} />
      )}

      {activeTab === 'master-subjects' && (
        <MasterSubjectsManager />
      )}

      {activeTab === 'frameworks' && (
        <CurriculumFrameworks onSelectCurriculumForMapping={handleSelectCurriculumForMapping} />
      )}
    </div>
  );
};

export default Curriculum;
