import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useMemo, useEffect } from 'react';
import { 
  Download, Printer, Sliders, Search, ChevronLeft, ChevronRight, 
  ZoomIn, ZoomOut, CheckSquare, Square, Users, CreditCard, 
  FileText, Image as ImageIcon, Filter, Loader2, Sparkles, Check
} from 'lucide-react';
import { useAppStore } from '../store/useAppStore';
import { Student } from '../types';
import { toBengaliNumber } from '../utils/bengaliUtils';
import { Format1StudentCard } from '../components/idcard/Format1StudentCard';
import { StudentIdCardSettingsPanel } from '../components/idcard/StudentIdCardSettingsPanel';
import { 
  downloadSingleIdCardPdf, 
  downloadSingleIdCardPng, 
  downloadBulkIdCardsPdf 
} from '../utils/idCardPdfExporter';
import { notifyIdCardGenerated, toast } from '../utils/toast';
import { generateReport } from '../services/exportService';

export const StudentIdCard: React.FC = () => {
  const {
    students,
    institution,
    studentIdCardSettings,
    updateStudentIdCardSettings,
    language,
    academicClasses,
    academicSections,
    academicSessions,
  } = useAppStore();

  const isBn = language === 'bn';
  const settings = studentIdCardSettings;

  // View Mode: 'preview' (Single Card Studio) | 'sheet' (Full Sheet Grid)
  const [activeTab, setActiveTab] = useState<'preview' | 'sheet'>('preview');

  // Left panel mode: Toggle settings panel
  const [isSettingsOpen, setIsSettingsOpen] = useState<boolean>(false);

  // Filters
  const [selectedClass, setSelectedClass] = useState<string>('all');
  const [selectedSection, setSelectedSection] = useState<string>('all');
  const [selectedSession, setSelectedSession] = useState<string>('all');
  const [searchQuery, setSearchQuery] = useState<string>('');

  // Selection & Focus
  const [selectedStudentIds, setSelectedStudentIds] = useState<string[]>([]);
  const [focusedStudentId, setFocusedStudentId] = useState<string>('');

  // UI States
  const [previewZoom, setPreviewZoom] = useState<number>(100);
  const [isGeneratingPdf, setIsGeneratingPdf] = useState<boolean>(false);
  const [pdfProgress, setPdfProgress] = useState<{ current: number; total: number }>({ current: 0, total: 0 });
  const [currentSheetPageIndex, setCurrentSheetPageIndex] = useState<number>(0);

  // Filtered Students
  const filteredStudents = useMemo(() => {
    return (students || []).filter((s) => {
      if (selectedClass !== 'all' && s.class !== selectedClass && s.classId !== selectedClass) {
        return false;
      }
      if (selectedSection !== 'all' && s.section !== selectedSection && s.sectionId !== selectedSection) {
        return false;
      }
      if (selectedSession !== 'all' && s.session !== selectedSession && s.sessionId !== selectedSession && s.year !== selectedSession) {
        return false;
      }
      if (searchQuery.trim()) {
        const q = searchQuery.toLowerCase();
        const matchName = s.name && s.name.toLowerCase().includes(q);
        const matchNameBn = s.nameBn && s.nameBn.includes(q);
        const matchId = s.studentId && s.studentId.toLowerCase().includes(q);
        const matchRoll = s.roll && s.roll.toString().includes(q);
        const matchMobile = (s.guardianMobile || s.fatherMobile || s.motherMobile || '').includes(q);
        return matchName || matchNameBn || matchId || matchRoll || matchMobile;
      }
      return true;
    });
  }, [students, selectedClass, selectedSection, selectedSession, searchQuery]);

  // Active Students (If any selected via checkboxes, use those; otherwise use all filtered)
  const activeStudents = useMemo(() => {
    if (selectedStudentIds.length === 0) {
      return filteredStudents;
    }
    return filteredStudents.filter((s) => selectedStudentIds.includes(s.id));
  }, [filteredStudents, selectedStudentIds]);

  // Keep focusedStudentId in sync
  useEffect(() => {
    if (activeStudents.length > 0) {
      const exists = activeStudents.some((s) => s.id === focusedStudentId);
      if (!exists) {
        setFocusedStudentId(activeStudents[0].id);
      }
    } else {
      setFocusedStudentId('');
    }
  }, [activeStudents, focusedStudentId]);

  const currentPreviewStudent = useMemo(() => {
    return activeStudents.find((s) => s.id === focusedStudentId) || activeStudents[0] || null;
  }, [activeStudents, focusedStudentId]);

  const currentPreviewIndex = useMemo(() => {
    if (!currentPreviewStudent) return 0;
    return activeStudents.findIndex((s) => s.id === currentPreviewStudent.id);
  }, [activeStudents, currentPreviewStudent]);

  // Student Navigation
  const handlePrevStudent = () => {
    if (activeStudents.length === 0) return;
    const newIdx = currentPreviewIndex <= 0 ? activeStudents.length - 1 : currentPreviewIndex - 1;
    setFocusedStudentId(activeStudents[newIdx].id);
  };

  const handleNextStudent = () => {
    if (activeStudents.length === 0) return;
    const newIdx = currentPreviewIndex >= activeStudents.length - 1 ? 0 : currentPreviewIndex + 1;
    setFocusedStudentId(activeStudents[newIdx].id);
  };

  // Selection Handlers
  const handleToggleSelect = (id: string) => {
    setSelectedStudentIds((prev) => {
      const isAlready = prev.includes(id);
      const next = isAlready ? prev.filter((item) => item !== id) : [...prev, id];
      if (!isAlready) {
        setFocusedStudentId(id);
      }
      return next;
    });
  };

  const handleSelectAll = () => {
    if (selectedStudentIds.length === filteredStudents.length && filteredStudents.length > 0) {
      setSelectedStudentIds([]);
    } else {
      setSelectedStudentIds(filteredStudents.map((s) => s.id));
    }
  };

  const handleResetFilters = () => {
    setSelectedClass('all');
    setSelectedSection('all');
    setSelectedSession('all');
    setSearchQuery('');
  };

  const hasActiveFilters = selectedClass !== 'all' || selectedSection !== 'all' || selectedSession !== 'all' || searchQuery.trim().length > 0;

  // Sheet pages calculation
  const isLegal = settings.paperSize === 'legal';
  const cardsPerPage = settings.cardSide === 'both' ? (isLegal ? 4 : 3) : (isLegal ? 12 : 9);

  const studentPages = useMemo(() => {
    const pages: Student[][] = [];
    for (let i = 0; i < activeStudents.length; i += cardsPerPage) {
      pages.push(activeStudents.slice(i, i + cardsPerPage));
    }
    return pages;
  }, [activeStudents, cardsPerPage]);

  // PDF Export Handlers
  const handleDownloadBulkPDF = async () => {
    if (activeStudents.length === 0) {
      toast.error(isBn ? BN_DICT['no_active_students_for_export'] : EN_DICT['no_active_students_for_export']);
      return;
    }

    setIsGeneratingPdf(true);
    try {
      await downloadBulkIdCardsPdf(activeStudents, institution, settings, (curr, tot) => {
        setPdfProgress({ current: curr, total: tot });
      });
      notifyIdCardGenerated(activeStudents.length);
    } catch (err) {
      console.error('Failed to export bulk PDF:', err);
      toast.error(isBn ? BN_DICT['failed_to_generate_pdf'] : EN_DICT['failed_to_generate_pdf']);
    } finally {
      setIsGeneratingPdf(false);
    }
  };

  const handleDownloadSinglePdf = async () => {
    if (!currentPreviewStudent) return;
    setIsGeneratingPdf(true);
    try {
      await downloadSingleIdCardPdf(currentPreviewStudent, institution, settings);
      notifyIdCardGenerated(currentPreviewStudent.nameBn || currentPreviewStudent.name);
    } catch (err) {
      console.error('Failed to export single PDF:', err);
      toast.error(isBn ? BN_DICT['failed_to_generate_single_card'] : EN_DICT['failed_to_generate_single_card']);
    } finally {
      setIsGeneratingPdf(false);
    }
  };

  const handleDownloadSinglePng = async (side: 'front' | 'back' = 'front') => {
    if (!currentPreviewStudent) return;
    try {
      await downloadSingleIdCardPng(currentPreviewStudent, institution, settings, side);
      notifyIdCardGenerated(`${currentPreviewStudent.nameBn || currentPreviewStudent.name} (${side === 'front' ? 'সামনের পাশ' : 'পেছনের পাশ'})`);
    } catch (err) {
      console.error('Failed to export PNG:', err);
      toast.error(isBn ? BN_DICT['failed_to_download_png'] : EN_DICT['failed_to_download_png']);
    }
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="flex flex-col h-full bg-slate-50 text-slate-800">
      {/* ======================================================== */}
      {/* 1. TOP HEADER TOOLBAR (NO-PRINT)                         */}
      {/* ======================================================== */}
      <header className="no-print bg-white border-b border-slate-200/90 px-4 py-3 shrink-0 shadow-2xs">
        <div className="max-w-7xl mx-auto flex flex-col sm:flex-row items-start sm:items-center justify-between gap-3">
          {/* Left Title & Status */}
          <div className="flex items-center gap-3">
            <div className="w-9 h-9 rounded-xl bg-emerald-700 text-white flex items-center justify-center shadow-2xs">
              <CreditCard className="w-5 h-5" />
            </div>
            <div>
              <div className="flex items-center gap-2">
                <h1 className="text-base font-bold text-slate-900 leading-none">
                  {isBn ? BN_DICT['student_identity_card'] : EN_DICT['student_identity_card']}
                </h1>
                <span className="px-2 py-0.5 rounded-full text-[11px] font-bold bg-emerald-50 text-emerald-800 border border-emerald-200">
                  {isBn 
                    ? `সক্রিয়: ${toBengaliNumber(activeStudents.length)} জন` 
                    : `Active: ${activeStudents.length}`}
                </span>
                {selectedStudentIds.length > 0 && (
                  <span className="px-2 py-0.5 rounded-full text-[11px] font-bold bg-blue-50 text-blue-800 border border-blue-200">
                    {isBn 
                      ? `সিলেক্টেড: ${toBengaliNumber(selectedStudentIds.length)} জন` 
                      : `Selected: ${selectedStudentIds.length}`}
                  </span>
                )}
              </div>
              <p className="text-xs text-slate-500 mt-0.5">
                {isBn ? BN_DICT['standard_cr80_size_with_instan'] : EN_DICT['standard_cr80_size_with_instan']}
              </p>
            </div>
          </div>

          {/* Right Action Controls */}
          <div className="flex items-center gap-2 flex-wrap">
            {/* View Mode Toggle */}
            <div className="inline-flex rounded-xl bg-slate-100 p-1 border border-slate-200/70 text-xs font-semibold">
              <button
                type="button"
                onClick={() => setActiveTab('preview')}
                className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg transition-all ${
                  activeTab === 'preview'
                    ? 'bg-white text-emerald-900 shadow-2xs font-bold'
                    : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                <CreditCard className="w-3.5 h-3.5" />
                <span>{isBn ? BN_DICT['card_preview'] : EN_DICT['card_preview']}</span>
              </button>

              <button
                type="button"
                onClick={() => setActiveTab('sheet')}
                className={`flex items-center gap-1.5 px-3 py-1.5 rounded-lg transition-all ${
                  activeTab === 'sheet'
                    ? 'bg-white text-emerald-900 shadow-2xs font-bold'
                    : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                <FileText className="w-3.5 h-3.5" />
                <span>{isBn ? BN_DICT['print_sheet'] : EN_DICT['print_sheet']}</span>
              </button>
            </div>

            {/* Settings Drawer/Panel Toggle */}
            <button
              type="button"
              onClick={() => setIsSettingsOpen(!isSettingsOpen)}
              className={`flex items-center gap-1.5 px-3 py-1.5 rounded-xl border text-xs font-bold transition-all shadow-2xs ${
                isSettingsOpen
                  ? 'bg-emerald-700 text-white border-emerald-700'
                  : 'bg-white text-slate-700 border-slate-200 hover:border-emerald-300 hover:text-emerald-800'
              }`}
            >
              <Sliders className="w-3.5 h-3.5" />
              <span>{isBn ? BN_DICT['card_settings'] : EN_DICT['card_settings']}</span>
            </button>

            {/* Bulk PDF Export */}
            <button
              type="button"
              onClick={handleDownloadBulkPDF}
              disabled={isGeneratingPdf || activeStudents.length === 0}
              className="flex items-center gap-1.5 px-3.5 py-1.5 rounded-xl bg-emerald-700 hover:bg-emerald-800 text-white text-xs font-bold shadow-2xs transition-colors disabled:opacity-50"
            >
              <Download className="w-3.5 h-3.5" />
              <span>{isBn ? BN_DICT['download_pdf'] : EN_DICT['download_pdf']}</span>
            </button>

            {/* Direct Print */}
            <button
              type="button"
              onClick={handlePrint}
              className="flex items-center gap-1.5 px-3 py-1.5 rounded-xl bg-slate-800 hover:bg-slate-900 text-white text-xs font-bold shadow-2xs transition-colors"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>{isBn ? BN_DICT['print'] : EN_DICT['print']}</span>
            </button>
          </div>
        </div>
      </header>

      {/* ======================================================== */}
      {/* 2. MAIN WORKSPACE                                        */}
      {/* ======================================================== */}
      <main className="flex-1 overflow-y-auto no-scrollbar flex flex-col">
        {/* VIEW 1: LIVE CARD PREVIEW & STUDIO */}
        {activeTab === 'preview' && (
          <div className="flex-1 max-w-7xl w-full mx-auto p-4 flex flex-col md:flex-row gap-4 items-stretch">
            
            {/* LEFT COLUMN: EITHER SETTINGS PANEL OR STUDENT DIRECTORY */}
            <div className="w-full md:w-96 shrink-0 flex flex-col min-h-[580px]">
              {isSettingsOpen ? (
                <StudentIdCardSettingsPanel 
                  isBn={isBn} 
                  onClose={() => setIsSettingsOpen(false)} 
                />
              ) : (
                <div className="bg-white rounded-2xl border border-slate-200/90 shadow-2xs flex flex-col h-full overflow-hidden">
                  {/* Directory Header */}
                  <div className="p-3 border-b border-slate-100 bg-slate-50/70 flex items-center justify-between">
                    <div className="flex items-center gap-2">
                      <Users className="w-4 h-4 text-emerald-700" />
                      <h3 className="text-xs font-bold text-slate-800">
                        {isBn ? BN_DICT['student_directory'] : EN_DICT['student_directory']}
                      </h3>
                    </div>
                    <button
                      type="button"
                      onClick={() => setIsSettingsOpen(true)}
                      className="text-[11px] font-bold text-emerald-700 hover:text-emerald-800 flex items-center gap-1"
                    >
                      <Sliders className="w-3 h-3" />
                      <span>{isBn ? BN_DICT['settings'] : EN_DICT['settings']}</span>
                    </button>
                  </div>

                  {/* Compact Search & Filters */}
                  <div className="p-3 border-b border-slate-100 space-y-2 bg-white">
                    {/* Search */}
                    <div className="relative">
                      <Search className="w-3.5 h-3.5 absolute left-2.5 top-1/2 -translate-y-1/2 text-slate-400" />
                      <input
                        type="text"
                        value={searchQuery}
                        onChange={(e) => setSearchQuery(e.target.value)}
                        placeholder={isBn ? BN_DICT['search_by_name_id_or_roll'] : EN_DICT['search_by_name_id_or_roll']}
                        className="w-full pl-8 pr-3 py-1.5 bg-slate-50 border border-slate-200 rounded-lg text-xs font-medium focus:ring-1 focus:ring-emerald-500 focus:bg-white"
                      />
                    </div>

                    {/* Inline Filter Selects */}
                    <div className="grid grid-cols-3 gap-1.5">
                      <select
                        value={selectedClass}
                        onChange={(e) => setSelectedClass(e.target.value)}
                        className="px-2 py-1 bg-slate-50 border border-slate-200 rounded-lg text-[11px] font-medium text-slate-700 focus:ring-1 focus:ring-emerald-500"
                      >
                        <option value="all">{isBn ? BN_DICT['all_classes'] : EN_DICT['all_classes']}</option>
                        {academicClasses.map((c) => (
                          <option key={c.id} value={c.name}>{c.name}</option>
                        ))}
                      </select>

                      <select
                        value={selectedSection}
                        onChange={(e) => setSelectedSection(e.target.value)}
                        className="px-2 py-1 bg-slate-50 border border-slate-200 rounded-lg text-[11px] font-medium text-slate-700 focus:ring-1 focus:ring-emerald-500"
                      >
                        <option value="all">{isBn ? BN_DICT['all_sections'] : EN_DICT['all_sections']}</option>
                        {academicSections.map((s) => (
                          <option key={s.id} value={s.name}>{s.name}</option>
                        ))}
                      </select>

                      <select
                        value={selectedSession}
                        onChange={(e) => setSelectedSession(e.target.value)}
                        className="px-2 py-1 bg-slate-50 border border-slate-200 rounded-lg text-[11px] font-medium text-slate-700 focus:ring-1 focus:ring-emerald-500"
                      >
                        <option value="all">{isBn ? BN_DICT['all_sessions'] : EN_DICT['all_sessions']}</option>
                        {academicSessions.map((y) => (
                          <option key={y.id} value={y.name}>{y.name}</option>
                        ))}
                      </select>
                    </div>

                    {/* Select All Row */}
                    <div className="flex items-center justify-between pt-1">
                      <button
                        type="button"
                        onClick={handleSelectAll}
                        className="text-[11px] font-semibold text-slate-600 hover:text-emerald-800 flex items-center gap-1.5"
                      >
                        {selectedStudentIds.length === filteredStudents.length && filteredStudents.length > 0 ? (
                          <CheckSquare className="w-3.5 h-3.5 text-emerald-700" />
                        ) : (
                          <Square className="w-3.5 h-3.5 text-slate-400" />
                        )}
                        <span>{isBn ? BN_DICT['select_all'] : EN_DICT['select_all']}</span>
                      </button>

                      {hasActiveFilters && (
                        <button
                          type="button"
                          onClick={handleResetFilters}
                          className="text-[10px] font-bold text-red-600 hover:text-red-800"
                        >
                          {isBn ? BN_DICT['clear_filters'] : EN_DICT['clear_filters']}
                        </button>
                      )}
                    </div>
                  </div>

                  {/* Scrollable Student Items List */}
                  <div className="flex-1 overflow-y-auto divide-y divide-slate-100 max-h-[460px]">
                    {filteredStudents.length === 0 ? (
                      <div className="p-8 text-center text-slate-400 text-xs">
                        {isBn ? BN_DICT['no_students_found'] : EN_DICT['no_students_found']}
                      </div>
                    ) : (
                      filteredStudents.map((s) => {
                        const isFocused = currentPreviewStudent?.id === s.id;
                        const isSelected = selectedStudentIds.includes(s.id);
                        return (
                          <div
                            key={s.id}
                            onClick={() => setFocusedStudentId(s.id)}
                            className={`p-2.5 flex items-center justify-between cursor-pointer transition-colors ${
                              isFocused
                                ? 'bg-emerald-50/80 border-l-4 border-emerald-700'
                                : 'hover:bg-slate-50'
                            }`}
                          >
                            <div className="flex items-center gap-2.5 min-w-0">
                              <button
                                type="button"
                                onClick={(e) => {
                                  e.stopPropagation();
                                  handleToggleSelect(s.id);
                                }}
                                className="text-slate-400 hover:text-emerald-700 p-0.5"
                              >
                                {isSelected ? (
                                  <CheckSquare className="w-3.5 h-3.5 text-emerald-700" />
                                ) : (
                                  <Square className="w-3.5 h-3.5" />
                                )}
                              </button>

                              {s.photo || s.photoUrl ? (
                                <img
                                  src={s.photo || s.photoUrl}
                                  alt=""
                                  className="w-7 h-7 rounded-full object-cover border border-slate-200"
                                />
                              ) : (
                                <div className="w-7 h-7 rounded-full bg-slate-200 flex items-center justify-center text-[10px] font-bold text-slate-600">
                                  {s.name ? s.name.charAt(0) : 'S'}
                                </div>
                              )}

                              <div className="min-w-0">
                                <h4 className="text-xs font-bold text-slate-900 truncate">
                                  {isBn ? (s.nameBn || s.name) : (s.name || s.nameBn)}
                                </h4>
                                <div className="flex items-center gap-1.5 text-[10px] text-slate-500 font-medium">
                                  <span>ID: {s.studentId || s.roll}</span>
                                  <span>•</span>
                                  <span>{isBn ? `রোল: ${toBengaliNumber(s.roll || '০১')}` : `Roll: ${s.roll || '01'}`}</span>
                                </div>
                              </div>
                            </div>

                            {isFocused && (
                              <span className="w-2 h-2 rounded-full bg-emerald-600 shrink-0"></span>
                            )}
                          </div>
                        );
                      })
                    )}
                  </div>
                </div>
              )}
            </div>

            {/* RIGHT COLUMN: LIVE CARD PREVIEW CANVAS */}
            <div className="flex-1 flex flex-col bg-white rounded-2xl border border-slate-200/90 shadow-2xs overflow-hidden">
              {/* Preview Stage Header Toolbar */}
              <div className="px-4 py-2.5 border-b border-slate-100 bg-slate-50/70 flex flex-wrap items-center justify-between gap-2">
                {/* Student Selector (Prev / Next) */}
                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={handlePrevStudent}
                    disabled={activeStudents.length <= 1}
                    className="p-1 rounded-lg hover:bg-white border border-slate-200 hover:border-slate-300 text-slate-600 disabled:opacity-40 transition-colors shadow-2xs"
                    title={isBn ? BN_DICT['previous'] : EN_DICT['previous']}
                  >
                    <ChevronLeft className="w-4 h-4" />
                  </button>

                  <div className="text-center px-1">
                    <span className="text-xs font-bold text-slate-900 block truncate max-w-[200px]">
                      {currentPreviewStudent
                        ? (isBn ? (currentPreviewStudent.nameBn || currentPreviewStudent.name) : currentPreviewStudent.name)
                        : (isBn ? BN_DICT['student'] : EN_DICT['student'])}
                    </span>
                    <span className="text-[10px] text-slate-500 block">
                      {isBn
                        ? `${toBengaliNumber(currentPreviewIndex + 1)} / ${toBengaliNumber(activeStudents.length)}`
                        : `${currentPreviewIndex + 1} of ${activeStudents.length}`}
                    </span>
                  </div>

                  <button
                    type="button"
                    onClick={handleNextStudent}
                    disabled={activeStudents.length <= 1}
                    className="p-1 rounded-lg hover:bg-white border border-slate-200 hover:border-slate-300 text-slate-600 disabled:opacity-40 transition-colors shadow-2xs"
                    title={isBn ? BN_DICT['next'] : EN_DICT['next']}
                  >
                    <ChevronRight className="w-4 h-4" />
                  </button>
                </div>

                {/* Card Side Selector */}
                <div className="inline-flex rounded-lg bg-slate-200/70 p-0.5 text-xs font-semibold">
                  {[
                    { key: 'both', label: isBn ? BN_DICT['both'] : EN_DICT['both'] },
                    { key: 'front', label: isBn ? BN_DICT['front'] : EN_DICT['front'] },
                    { key: 'back', label: isBn ? BN_DICT['back'] : EN_DICT['back'] },
                  ].map((side) => (
                    <button
                      key={side.key}
                      type="button"
                      onClick={() => updateStudentIdCardSettings({ cardSide: side.key as any })}
                      className={`px-2.5 py-1 rounded-md text-[11px] transition-all ${
                        settings.cardSide === side.key
                          ? 'bg-white text-emerald-900 shadow-2xs font-bold'
                          : 'text-slate-600 hover:text-slate-900'
                      }`}
                    >
                      {side.label}
                    </button>
                  ))}
                </div>

                {/* Single Card Export & Zoom Controls */}
                <div className="flex items-center gap-1.5">
                  {/* Zoom Controls */}
                  <div className="hidden sm:flex items-center bg-slate-100 rounded-lg p-0.5 border border-slate-200 text-xs">
                    <button
                      type="button"
                      onClick={() => setPreviewZoom((z) => Math.max(z - 10, 70))}
                      className="p-1 text-slate-600 hover:text-slate-900"
                      title="Zoom Out"
                    >
                      <ZoomOut className="w-3.5 h-3.5" />
                    </button>
                    <span className="text-[10px] font-mono px-1 font-bold text-slate-700">{previewZoom}%</span>
                    <button
                      type="button"
                      onClick={() => setPreviewZoom((z) => Math.min(z + 10, 140))}
                      className="p-1 text-slate-600 hover:text-slate-900"
                      title="Zoom In"
                    >
                      <ZoomIn className="w-3.5 h-3.5" />
                    </button>
                  </div>

                  {/* Single PDF */}
                  <button
                    type="button"
                    onClick={handleDownloadSinglePdf}
                    disabled={!currentPreviewStudent || isGeneratingPdf}
                    className="inline-flex items-center gap-1 px-2.5 py-1.5 bg-emerald-50 hover:bg-emerald-100 text-emerald-800 border border-emerald-200 rounded-lg text-xs font-bold transition-colors shadow-2xs disabled:opacity-50"
                    title={isBn ? BN_DICT['download_cr80_pdf'] : EN_DICT['download_cr80_pdf']}
                  >
                    <Download className="w-3 h-3 text-emerald-700" />
                    <span>{isBn ? BN_DICT['single_pdf'] : EN_DICT['single_pdf']}</span>
                  </button>

                  {/* Single PNG */}
                  <button
                    type="button"
                    onClick={() => handleDownloadSinglePng('front')}
                    disabled={!currentPreviewStudent}
                    className="inline-flex items-center gap-1 px-2 py-1.5 bg-white hover:bg-slate-50 text-slate-700 border border-slate-200 rounded-lg text-xs font-semibold transition-colors shadow-2xs disabled:opacity-50"
                    title={isBn ? BN_DICT['download_png'] : EN_DICT['download_png']}
                  >
                    <ImageIcon className="w-3 h-3 text-slate-500" />
                    <span>{isBn ? BN_DICT['png'] : EN_DICT['png']}</span>
                  </button>
                </div>
              </div>

              {/* Stage Canvas */}
              <div className="flex-1 bg-slate-100/60 p-6 flex items-center justify-center overflow-auto min-h-[520px]">
                {currentPreviewStudent ? (
                  <div 
                    className="transition-transform duration-150 flex flex-wrap items-center justify-center gap-6"
                    style={{ transform: `scale(${previewZoom / 100})`, transformOrigin: 'center center' }}
                  >
                    {/* Front Side */}
                    {(settings.cardSide === 'both' || settings.cardSide === 'front') && (
                      <div className="flex flex-col items-center">
                        <span className="text-[11px] font-bold text-slate-500 mb-1.5 uppercase tracking-wider">
                          {isBn ? BN_DICT['front_side'] : EN_DICT['front_side']}
                        </span>
                        <div className="shadow-lg rounded-[3.18mm] overflow-hidden bg-white ring-1 ring-black/5">
                          <Format1StudentCard
                            student={currentPreviewStudent}
                            institution={institution}
                            settings={settings}
                            side="front"
                          />
                        </div>
                      </div>
                    )}

                    {/* Back Side */}
                    {(settings.cardSide === 'both' || settings.cardSide === 'back') && (
                      <div className="flex flex-col items-center">
                        <span className="text-[11px] font-bold text-slate-500 mb-1.5 uppercase tracking-wider">
                          {isBn ? BN_DICT['back_side'] : EN_DICT['back_side']}
                        </span>
                        <div className="shadow-lg rounded-[3.18mm] overflow-hidden bg-white ring-1 ring-black/5">
                          <Format1StudentCard
                            student={currentPreviewStudent}
                            institution={institution}
                            settings={settings}
                            side="back"
                          />
                        </div>
                      </div>
                    )}
                  </div>
                ) : (
                  <div className="text-center text-slate-400 text-sm font-medium">
                    {isBn ? BN_DICT['no_student_selected'] : EN_DICT['no_student_selected']}
                  </div>
                )}
              </div>
            </div>

          </div>
        )}

        {/* VIEW 2: FULL PRINT SHEET PREVIEW */}
        {activeTab === 'sheet' && (
          <div className="flex-1 max-w-5xl w-full mx-auto p-4 flex flex-col items-center gap-4">
            {/* Sheet Page Navigation & Controls */}
            <div className="no-print w-full bg-white p-3 rounded-2xl border border-slate-200/90 shadow-2xs flex flex-wrap items-center justify-between gap-3">
              <div className="flex items-center gap-2">
                <span className="text-xs font-bold text-slate-700">
                  {isBn 
                    ? `কাগজের সাইজ: ${isLegal ? 'লিগ্যাল (Legal)' : 'এ-ফোর (A4)'}` 
                    : `Paper: ${isLegal ? 'Legal' : 'A4'}`}
                </span>
                <span className="text-slate-300">•</span>
                <span className="text-xs font-medium text-slate-500">
                  {isBn 
                    ? `মোট পৃষ্ঠা: ${toBengaliNumber(studentPages.length)}` 
                    : `Total Pages: ${studentPages.length}`}
                </span>
              </div>

              {/* Page Navigator */}
              {studentPages.length > 1 && (
                <div className="flex items-center gap-2">
                  <button
                    type="button"
                    onClick={() => setCurrentSheetPageIndex((p) => Math.max(0, p - 1))}
                    disabled={currentSheetPageIndex === 0}
                    className="p-1 rounded-lg border border-slate-200 hover:bg-slate-50 text-slate-700 disabled:opacity-40"
                  >
                    <ChevronLeft className="w-4 h-4" />
                  </button>
                  <span className="text-xs font-bold text-slate-800">
                    {isBn 
                      ? `পৃষ্ঠা: ${toBengaliNumber(currentSheetPageIndex + 1)} / ${toBengaliNumber(studentPages.length)}` 
                      : `Page ${currentSheetPageIndex + 1} of ${studentPages.length}`}
                  </span>
                  <button
                    type="button"
                    onClick={() => setCurrentSheetPageIndex((p) => Math.min(studentPages.length - 1, p + 1))}
                    disabled={currentSheetPageIndex >= studentPages.length - 1}
                    className="p-1 rounded-lg border border-slate-200 hover:bg-slate-50 text-slate-700 disabled:opacity-40"
                  >
                    <ChevronRight className="w-4 h-4" />
                  </button>
                </div>
              )}

              <div className="flex items-center gap-2">
                <button
                  type="button"
                  onClick={handleDownloadBulkPDF}
                  disabled={isGeneratingPdf}
                  className="flex items-center gap-1.5 px-3 py-1.5 bg-emerald-700 text-white rounded-xl text-xs font-bold shadow-2xs hover:bg-emerald-800 transition-colors"
                >
                  <Download className="w-3.5 h-3.5" />
                  <span>{isBn ? BN_DICT['download_all_pdf'] : EN_DICT['download_all_pdf']}</span>
                </button>
                <button
                  type="button"
                  onClick={handlePrint}
                  className="flex items-center gap-1.5 px-3 py-1.5 bg-slate-800 text-white rounded-xl text-xs font-bold shadow-2xs hover:bg-slate-900 transition-colors"
                >
                  <Printer className="w-3.5 h-3.5" />
                  <span>{isBn ? BN_DICT['print'] : EN_DICT['print']}</span>
                </button>
              </div>
            </div>

            {/* Current Physical Sheet Rendering */}
            {studentPages.length > 0 && studentPages[currentSheetPageIndex] ? (
              <div 
                className="bg-white shadow-xl border border-slate-300 rounded-sm p-6 overflow-hidden flex flex-col items-center"
                style={{
                  width: isLegal ? '215.9mm' : '210mm',
                  minHeight: isLegal ? '355.6mm' : '297mm',
                  boxSizing: 'border-box',
                }}
              >
                {settings.cardSide === 'both' ? (
                  <div className="flex flex-col items-center gap-[6mm] w-full">
                    {studentPages[currentSheetPageIndex].map((s) => (
                      <div key={s.id} className="flex items-center justify-center gap-[6mm]">
                        <Format1StudentCard
                          student={s}
                          institution={institution}
                          settings={settings}
                          side="front"
                        />
                        <Format1StudentCard
                          student={s}
                          institution={institution}
                          settings={settings}
                          side="back"
                        />
                      </div>
                    ))}
                  </div>
                ) : (
                  <div className="grid grid-cols-3 gap-[4mm] justify-center items-center">
                    {studentPages[currentSheetPageIndex].map((s) => (
                      <Format1StudentCard
                        key={s.id}
                        student={s}
                        institution={institution}
                        settings={settings}
                        side={settings.cardSide === 'back' ? 'back' : 'front'}
                      />
                    ))}
                  </div>
                )}
              </div>
            ) : (
              <div className="p-12 text-center text-slate-400 text-xs">
                {isBn ? BN_DICT['no_students_to_print'] : EN_DICT['no_students_to_print']}
              </div>
            )}
          </div>
        )}

        {/* ======================================================== */}
        {/* 3. HIDDEN PRINT CONTAINER (PRINT-ONLY)                   */}
        {/* ======================================================== */}
        <div className="hidden print:block print-only">
          {studentPages.map((pageStudents, pageIdx) => (
            <div
              key={pageIdx}
              className="print-sheet"
              style={{
                width: isLegal ? '215.9mm' : '210mm',
                height: isLegal ? '355.6mm' : '297mm',
                padding: '6mm',
                boxSizing: 'border-box',
                backgroundColor: '#ffffff',
                display: 'flex',
                flexDirection: 'column',
                alignItems: 'center',
                justifyContent: 'flex-start',
              }}
            >
              {settings.cardSide === 'both' ? (
                <div 
                  style={{ 
                    display: 'flex', 
                    flexDirection: 'column', 
                    alignItems: 'center', 
                    gap: '5.5mm',
                    width: '100%' 
                  }}
                >
                  {pageStudents.map((s) => (
                    <div 
                      key={s.id} 
                      style={{ 
                        display: 'flex', 
                        alignItems: 'center', 
                        justifyContent: 'center', 
                        gap: '6mm' 
                      }}
                    >
                      <Format1StudentCard
                        student={s}
                        institution={institution}
                        settings={settings}
                        side="front"
                      />
                      <Format1StudentCard
                        student={s}
                        institution={institution}
                        settings={settings}
                        side="back"
                      />
                    </div>
                  ))}
                </div>
              ) : (
                <div 
                  style={{ 
                    display: 'grid', 
                    gridTemplateColumns: 'repeat(3, 1fr)', 
                    gap: '4mm',
                    justifyItems: 'center',
                    width: '100%' 
                  }}
                >
                  {pageStudents.map((s) => (
                    <Format1StudentCard
                      key={s.id}
                      student={s}
                      institution={institution}
                      settings={settings}
                      side={settings.cardSide === 'back' ? 'back' : 'front'}
                    />
                  ))}
                </div>
              )}
            </div>
          ))}
        </div>
      </main>

      {/* ======================================================== */}
      {/* 4. PDF GENERATION PROGRESS MODAL                         */}
      {/* ======================================================== */}
      {isGeneratingPdf && (
        <div className="fixed inset-0 bg-slate-900/40 backdrop-blur-xs z-50 flex items-center justify-center p-4">
          <div className="bg-white rounded-2xl p-6 max-w-sm w-full shadow-2xl border border-slate-200 text-center space-y-3">
            <div className="w-12 h-12 rounded-2xl bg-emerald-100 text-emerald-700 flex items-center justify-center mx-auto animate-spin">
              <Loader2 className="w-6 h-6" />
            </div>
            <h3 className="text-sm font-bold text-slate-900">
              {isBn ? BN_DICT['generating_print_ready_pdf'] : EN_DICT['generating_print_ready_pdf']}
            </h3>
            {pdfProgress.total > 0 && (
              <p className="text-xs text-slate-500 font-medium">
                {isBn 
                  ? `পৃষ্ঠা ${toBengaliNumber(pdfProgress.current)} / ${toBengaliNumber(pdfProgress.total)} প্রক্রিয়াকরণ হচ্ছে` 
                  : `Processing page ${pdfProgress.current} of ${pdfProgress.total}`}
              </p>
            )}
            <div className="w-full bg-slate-100 rounded-full h-2 overflow-hidden">
              <div 
                className="bg-emerald-600 h-full transition-all duration-300"
                style={{ 
                  width: pdfProgress.total > 0 
                    ? `${(pdfProgress.current / pdfProgress.total) * 100}%` 
                    : '60%' 
                }}
              />
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
