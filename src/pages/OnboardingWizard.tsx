// Helper to guarantee pure language text (no mixed English/Bangla in parenthetical formats)
const cleanPureTitle = (title: string, isBangla: boolean): string => {
  if (!title) return '';
  if (isBangla) {
    return title.replace(/\s*\([a-zA-Z0-9\s/.,'-]+\)\s*/g, '').trim();
  } else {
    return title.replace(/\s*\([\u0980-\u09FF\s/.,'-]+\)\s*/g, '').trim();
  }
};

// Strict input sanitizers ensuring pure scripts and correct data formats
const sanitizeBanglaOnly = (val: string): string => {
  if (!val) return '';
  const noEnglish = val.replace(/[a-zA-Z]/g, '');
  if (!/[\u0980-\u09FF]/.test(noEnglish)) {
    return noEnglish.replace(/\s+/g, '');
  }
  return noEnglish;
};

const sanitizeEnglishOnly = (val: string): string => {
  if (!val) return '';
  const noBangla = val.replace(/[\u0980-\u09FF]/g, '');
  if (!/[a-zA-Z0-9]/.test(noBangla)) {
    return noBangla.replace(/\s+/g, '');
  }
  return noBangla;
};

const sanitizeNumericOnly = (val: string, maxLen?: number): string => {
  if (!val) return '';
  const converted = toEnglishNumber(val);
  const clean = converted.replace(/[^0-9]/g, '');
  return maxLen ? clean.slice(0, maxLen) : clean;
};

const sanitizePhone = (val: string): string => {
  if (!val) return '';
  const converted = toEnglishNumber(val);
  const clean = converted.replace(/[^0-9+\-]/g, '');
  return clean.slice(0, 16);
};

const sanitizeEmailOrUrl = (val: string): string => {
  if (!val) return '';
  return val.replace(/[\u0980-\u09FF\s]/g, '');
};

const sanitizeUsername = (val: string): string => {
  if (!val) return '';
  const converted = toEnglishNumber(val);
  return converted.replace(/[\u0980-\u09FF\s]/g, '').replace(/[^a-zA-Z0-9._\-]/g, '');
};

const sanitizePdsIndexId = (val: string): string => {
  if (!val) return '';
  const converted = toEnglishNumber(val);
  return converted.replace(/[\u0980-\u09FF\s]/g, '').replace(/[^a-zA-Z0-9\-_/]/g, '').toUpperCase();
};

