import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useRef } from 'react';
import { Upload, Trash2, Building2, Type, Server } from 'lucide-react';
import { useAppStore } from '../store/useAppStore';
import { translations, TranslationKey } from '../locales';
import { compressImageBase64 } from '../utils/imageUtils';
import { toast } from '../utils/toast';
import { SystemFontSettingsPanel } from '../components/common/SystemFontSettingsPanel';
import { uploadDocumentSecurely } from '../utils/apiClient';
import { LanSettingsModal } from '../components/system/LanSettingsModal';

const InstitutionSettings = () => {
  const { 
    language, 
    institution, 
    updateInstitution, 
    whiteLabel, 
    updateWhiteLabel,
    staff,
    updateStaffMember 
  } = useAppStore();
  const isBn = language === 'bn';
  const t = (key: TranslationKey) => translations[language][key] || key;

  const [formData, setFormData] = useState(institution);
  const [saved, setSaved] = useState(false);
  const [wlData, setWlData] = useState(whiteLabel || { appName: '', appIcon: '', enabled: false });
  const [isLanModalOpen, setIsLanModalOpen] = useState(false);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const handleSubmit = (e: React.FormEvent) => {
    e.preventDefault();
    updateInstitution(formData);
    updateWhiteLabel(wlData);

    if (staff && updateStaffMember) {
      const hmStaff = staff.find(s => s.id === institution?.headmasterStaffId || s.role === 'headmaster');
      if (hmStaff) {
        updateStaffMember(hmStaff.id, {
          signaturePhoto: formData.headmasterSignature,
          name: formData.headmasterName || hmStaff.name,
          nameBn: formData.headmasterNameBn || hmStaff.nameBn,
          designation: formData.headmasterTitle || hmStaff.designation,
          designationBn: formData.headmasterTitleBn || hmStaff.designationBn,
        });
      }
    }

    setSaved(true);
    toast.success(isBn ? BN_DICT['institution_settings_saved_suc'] : EN_DICT['institution_settings_saved_suc']);
    setTimeout(() => setSaved(false), 3000);
  };

  const handleChange = (e: React.ChangeEvent<HTMLInputElement | HTMLSelectElement>) => {
    const { name, value } = e.target;
    setFormData(prev => ({ ...prev, [name]: value }));
  };

  const handleWlPhotoUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) {
      try {
        const result = await uploadDocumentSecurely({
          file,
          type: 'institution',
          docType: 'AppIcon',
        });

        if (result.success && result.filepath) {
          setWlData({ ...wlData, appIcon: result.filepath });
          return;
        }
      } catch (err) {
        console.warn('Backend API upload failed, falling back to Base64', err);
      }

      try {
        const compressed = await compressImageBase64(file, 256, 256, 0.9);
        setWlData({ ...wlData, appIcon: compressed });
      } catch {
        const reader = new FileReader();
        reader.onloadend = () => {
          setWlData({ ...wlData, appIcon: reader.result as string });
        };
        reader.readAsDataURL(file);
      }
    }
  };

  const handleLogoUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) {
      try {
        const result = await uploadDocumentSecurely({
          file,
          type: 'institution',
          docType: 'InstitutionLogo',
        });

        if (result.success && result.filepath) {
          setFormData({ ...formData, logoUrl: result.filepath });
          return;
        }
      } catch (err) {
        console.warn('Backend API upload failed, falling back to Base64', err);
      }

      const isPngOrSvg = file.type.includes('png') || file.type.includes('svg') || file.name.toLowerCase().endsWith('.png') || file.name.toLowerCase().endsWith('.svg');
      if (isPngOrSvg && file.size < 3 * 1024 * 1024) {
        const reader = new FileReader();
        reader.onloadend = () => {
          setFormData({ ...formData, logoUrl: reader.result as string });
        };
        reader.readAsDataURL(file);
      } else {
        try {
          const compressed = await compressImageBase64(file, 400, 400, 0.9);
          setFormData({ ...formData, logoUrl: compressed });
        } catch {
          const reader = new FileReader();
          reader.onloadend = () => {
            setFormData({ ...formData, logoUrl: reader.result as string });
          };
          reader.readAsDataURL(file);
        }
      }
    }
  };

  const removeLogo = () => {
    setFormData({ ...formData, logoUrl: undefined });
    if (fileInputRef.current) {
      fileInputRef.current.value = '';
    }
  };

  const handleSignatureUpload = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (file) {
      try {
        const result = await uploadDocumentSecurely({
          file,
          type: 'institution',
          docType: 'HeadmasterSignature',
        });

        if (result.success && result.filepath) {
          setFormData({ ...formData, headmasterSignature: result.filepath });
          return;
        }
      } catch (err) {
        console.warn('Backend API upload failed, falling back to Base64', err);
      }

      try {
        const compressed = await compressImageBase64(file, 300, 80, 0.9);
        setFormData({ ...formData, headmasterSignature: compressed });
      } catch {
        const reader = new FileReader();
        reader.onloadend = () => {
          setFormData({ ...formData, headmasterSignature: reader.result as string });
        };
        reader.readAsDataURL(file);
      }
    }
  };

  return (
    <div className="space-y-6">
      <div className="flex flex-col sm:flex-row sm:items-center sm:justify-between gap-4">
        <div>
          <h1 className="text-2xl font-bold text-slate-800">{isBn ? BN_DICT['institution_settings'] : EN_DICT['institution_settings']}</h1>
          <p className="text-slate-500 mt-1">{isBn ? BN_DICT['configure_general_details_cont'] : EN_DICT['configure_general_details_cont']}</p>
        </div>
        <button
          type="button"
          onClick={() => setIsLanModalOpen(true)}
          className="inline-flex items-center gap-2 px-3.5 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 dark:bg-slate-800 dark:hover:bg-slate-700 dark:text-slate-200 rounded-xl text-xs font-semibold transition-colors border border-slate-300 dark:border-slate-700"
        >
          <Server className="w-4 h-4 text-blue-600 dark:text-blue-400" />
          <span>{isBn ? BN_DICT['network_lan_security'] : EN_DICT['network_lan_security']}</span>
        </button>
      </div>

      <LanSettingsModal isOpen={isLanModalOpen} onClose={() => setIsLanModalOpen(false)} />

      <div className="bg-white rounded-xl shadow-sm border border-slate-200 overflow-hidden">
        <div className="p-6">
          <form onSubmit={handleSubmit} className="space-y-8 max-w-4xl">
            
            {/* Logo Section */}
            <div>
              <h3 className="text-lg font-semibold text-slate-800 mb-4 border-b pb-2">
                {isBn ? BN_DICT['institution_logo'] : EN_DICT['institution_logo']}
              </h3>
              <div className="flex items-center gap-6">
                <div className="w-32 h-32 rounded-xl border border-slate-200 flex items-center justify-center bg-white overflow-hidden relative group shadow-xs">
                  {formData.logoUrl ? (
                    <>
                      <img src={formData.logoUrl} alt="Institution Logo" className="w-full h-full object-contain p-2 bg-transparent" />
                      <div className="absolute top-2 right-2 opacity-0 group-hover:opacity-100 transition-opacity">
                        <button
                          type="button"
                          onClick={removeLogo}
                          className="p-1.5 bg-red-600 text-white rounded-lg hover:bg-red-700 transition-colors shadow-sm cursor-pointer"
                          title={isBn ? BN_DICT['remove_logo'] : EN_DICT['remove_logo']}
                        >
                          <Trash2 className="w-4 h-4" />
                        </button>
                      </div>
                    </>
                  ) : (
                    <Building2 className="w-12 h-12 text-slate-300" />
                  )}
                </div>
                <div>
                  <input
                    type="file"
                    ref={fileInputRef}
                    onChange={handleLogoUpload}
                    accept="image/*"
                    className="hidden"
                    id="logo-upload"
                  />
                  <label
                    htmlFor="logo-upload"
                    className="inline-flex items-center gap-2 px-4 py-2 bg-white border border-slate-300 rounded-lg text-sm font-medium text-slate-700 hover:bg-slate-50 cursor-pointer transition-colors shadow-sm"
                  >
                    <Upload className="w-4 h-4" />
                    {isBn ? BN_DICT['upload_logo'] : EN_DICT['upload_logo']}
                  </label>
                  <p className="text-xs text-slate-500 mt-2">
                    {isBn ? BN_DICT['recommended_png_or_svg_transpa'] : EN_DICT['recommended_png_or_svg_transpa']}
                  </p>
                </div>
              </div>
            </div>

            {/* Basic Info */}
            <div>
              <h3 className="text-lg font-semibold text-slate-800 mb-4 border-b pb-2">
                {isBn ? BN_DICT['institution_details'] : EN_DICT['institution_details']}
              </h3>
              <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">{t('eiin')}</label>
                  <input
                    type="text"
                    name="eiin"
                    value={formData.eiin || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">{t('established')}</label>
                  <input
                    type="text"
                    name="established"
                    value={formData.established || ''}
                    onChange={handleChange}
                    placeholder={isBn ? BN_DICT['e_g_1990'] : EN_DICT['e_g_1990']}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>

                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['mpo_code_optional'] : EN_DICT['mpo_code_optional']}
                  </label>
                  <input
                    type="text"
                    name="mpoCode"
                    value={formData.mpoCode || ''}
                    onChange={handleChange}
                    placeholder={isBn ? BN_DICT['e_g_1012345678'] : EN_DICT['e_g_1012345678']}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['school_code_optional'] : EN_DICT['school_code_optional']}
                  </label>
                  <input
                    type="text"
                    name="schoolCode"
                    value={formData.schoolCode || ''}
                    onChange={handleChange}
                    placeholder={isBn ? BN_DICT['e_g_1234'] : EN_DICT['e_g_1234']}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>

                {/* Names */}
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['institution_name_english'] : EN_DICT['institution_name_english']}
                  </label>
                  <input
                    type="text"
                    name="name"
                    value={formData.name || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                    required
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['institution_name_bangla'] : EN_DICT['institution_name_bangla']}
                  </label>
                  <input
                    type="text"
                    name="nameBn"
                    value={formData.nameBn || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>

                {/* Headmaster Names */}
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['headmaster_principal_name_engl'] : EN_DICT['headmaster_principal_name_engl']}
                  </label>
                  <input
                    type="text"
                    name="headmasterName"
                    value={formData.headmasterName || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['headmaster_principal_name_bang'] : EN_DICT['headmaster_principal_name_bang']}
                  </label>
                  <input
                    type="text"
                    name="headmasterNameBn"
                    value={formData.headmasterNameBn || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>

                {/* Headmaster Designation / Title */}
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['designation_title_english'] : EN_DICT['designation_title_english']}
                  </label>
                  <input
                    type="text"
                    name="headmasterTitle"
                    value={formData.headmasterTitle || ''}
                    onChange={handleChange}
                    placeholder="e.g. Headmaster / Principal"
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['designation_title_bangla'] : EN_DICT['designation_title_bangla']}
                  </label>
                  <input
                    type="text"
                    name="headmasterTitleBn"
                    value={formData.headmasterTitleBn || ''}
                    onChange={handleChange}
                    placeholder={isBn ? BN_DICT['e_g_headmaster_principal'] : EN_DICT['e_g_headmaster_principal']}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>

                {/* Headmaster Signature */}
                <div className="col-span-1 md:col-span-2 mt-2 mb-2 p-4 bg-slate-50 border border-slate-200 rounded-xl space-y-4">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['headmaster_principal_signature'] : EN_DICT['headmaster_principal_signature']}
                  </label>
                  <div className="flex flex-col sm:flex-row sm:items-center gap-6">
                    {formData.headmasterSignature ? (
                      <div className="relative p-2 bg-white border border-slate-200 rounded-lg shadow-sm w-fit">
                        <img 
                          src={formData.headmasterSignature} 
                          alt="Signature" 
                          className="h-20 w-[300px] object-contain border border-dashed border-slate-300 rounded"
                        />
                        <button
                          type="button"
                          onClick={() => setFormData({ ...formData, headmasterSignature: '' })}
                          className="absolute -top-2 -right-2 bg-red-100 text-red-600 rounded-full p-1.5 hover:bg-red-200 shadow-sm transition-colors"
                          title={isBn ? BN_DICT['remove_signature'] : EN_DICT['remove_signature']}
                        >
                          <Trash2 className="w-4 h-4" />
                        </button>
                      </div>
                    ) : (
                      <div className="h-20 w-full sm:w-[300px] flex items-center justify-center bg-white border-2 border-dashed border-slate-300 rounded-lg text-slate-400">
                        {isBn ? BN_DICT['no_signature'] : EN_DICT['no_signature']}
                      </div>
                    )}
                    <div>
                      <input
                        type="file"
                        onChange={handleSignatureUpload}
                        accept="image/*"
                        className="hidden"
                        id="signature-upload"
                      />
                      <label
                        htmlFor="signature-upload"
                        className="inline-flex items-center gap-2 px-4 py-2 bg-white border border-slate-300 rounded-lg text-sm font-medium text-slate-700 hover:bg-slate-50 cursor-pointer transition-colors shadow-sm"
                      >
                        <Upload className="w-4 h-4" />
                        {isBn ? BN_DICT['upload_signature'] : EN_DICT['upload_signature']}
                      </label>
                      <p className="text-xs text-slate-500 mt-2 max-w-[200px] leading-relaxed">
                        {isBn ? BN_DICT['recommended_300x80_px_transpar'] : EN_DICT['recommended_300x80_px_transpar']}
                      </p>
                    </div>
                  </div>
                </div>

                {/* Addresses */}
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['address_english'] : EN_DICT['address_english']}
                  </label>
                  <input
                    type="text"
                    name="address"
                    value={formData.address || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['address_bangla'] : EN_DICT['address_bangla']}
                  </label>
                  <input
                    type="text"
                    name="addressBn"
                    value={formData.addressBn || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>

                {/* Contact Info */}
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['mobile_number'] : EN_DICT['mobile_number']}
                  </label>
                  <input
                    type="text"
                    name="mobile"
                    value={formData.mobile || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['email_address'] : EN_DICT['email_address']}
                  </label>
                  <input
                    type="email"
                    name="email"
                    value={formData.email || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['website'] : EN_DICT['website']}
                  </label>
                  <input
                    type="text"
                    name="website"
                    value={formData.website || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['exam_center_english'] : EN_DICT['exam_center_english']}
                  </label>
                  <input
                    type="text"
                    name="examCenter"
                    value={formData.examCenter || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                    placeholder="e.g. Nangalkot-9"
                  />
                </div>
                <div className="space-y-2">
                  <label className="text-sm font-medium text-slate-700">
                    {isBn ? BN_DICT['exam_center_bengali'] : EN_DICT['exam_center_bengali']}
                  </label>
                  <input
                    type="text"
                    name="examCenterBn"
                    value={formData.examCenterBn || ''}
                    onChange={handleChange}
                    className="w-full px-4 py-2 border border-slate-300 rounded-lg focus:ring-2 focus:ring-indigo-500 focus:border-indigo-500 outline-none transition-all"
                    placeholder="যেমন: নাঙ্গলকোট-৯"
                  />
                </div>
              </div>
            </div>

            {/* Address Management Link Banner */}
            <div className="bg-indigo-50/70 border border-indigo-100 rounded-xl p-5 flex flex-col sm:flex-row sm:items-center justify-between gap-4">
              <div>
                <h3 className="text-base font-bold text-indigo-950 flex items-center gap-2">
                  <Building2 className="w-5 h-5 text-indigo-600" />
                  {isBn ? BN_DICT['default_address_location_maste'] : EN_DICT['default_address_location_maste']}
                </h3>
                <p className="text-sm text-indigo-800/80 mt-1">
                  {isBn ? BN_DICT['configure_institute_wide_defau'] : EN_DICT['configure_institute_wide_defau']}
                </p>
              </div>
              <a
                href="#/institution/address"
                className="inline-flex items-center justify-center gap-2 px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white font-medium rounded-lg text-sm transition-colors shrink-0 shadow-sm"
              >
                {isBn ? BN_DICT['open_address_management'] : EN_DICT['open_address_management']}
              </a>
            </div>

            {/* White Label Settings */}
            <div className="bg-slate-50/50 p-6 rounded-xl border border-slate-100">
              <div className="flex items-center gap-3 mb-4">
                <Building2 className="w-5 h-5 text-indigo-600" />
                <h3 className="text-lg font-semibold text-slate-800">
                  {isBn ? BN_DICT['white_label_software_branding'] : EN_DICT['white_label_software_branding']}
                </h3>
              </div>
              <div className="flex items-center gap-3 mb-6">
                <input 
                  type="checkbox" 
                  id="wl-enabled" 
                  checked={wlData.enabled} 
                  onChange={e => setWlData({...wlData, enabled: e.target.checked})}
                  className="w-4 h-4 text-indigo-600 rounded border-slate-300 focus:ring-indigo-500"
                />
                <label htmlFor="wl-enabled" className="text-sm font-medium text-slate-700">
                  {isBn ? BN_DICT['enable_white_label_branding'] : EN_DICT['enable_white_label_branding']}
                </label>
              </div>

              {wlData.enabled && (
                <div className="grid grid-cols-1 md:grid-cols-2 gap-6">
                  <div className="space-y-2">
                    <label className="text-sm font-medium text-slate-700">
                      {isBn ? BN_DICT['institution_name_for_software'] : EN_DICT['institution_name_for_software']}
                    </label>
                    <input
                      type="text"
                      value={wlData.appName}
                      onChange={e => setWlData({...wlData, appName: e.target.value})}
                      className="w-full border border-slate-300 rounded-lg px-4 py-2 focus:ring-2 focus:ring-indigo-500 outline-none"
                      placeholder="e.g. Aziara High School"
                    />
                    <p className="text-xs text-slate-500">
                      {isBn ? BN_DICT['will_be_shown_as'] : EN_DICT['will_be_shown_as']} {wlData.appName ? `${wlData.appName.split(' ').map(w => w[0]).join('').toUpperCase()} ERP by SoftDows` : 'Biddalok by SoftDows'}
                    </p>
                  </div>
                  
                  <div className="space-y-2">
                    <label className="text-sm font-medium text-slate-700">
                      {isBn ? BN_DICT['software_icon_logo'] : EN_DICT['software_icon_logo']}
                    </label>
                    <div className="flex items-center gap-4">
                      {wlData.appIcon ? (
                        <div className="relative">
                          <img src={wlData.appIcon} alt="Icon" className="w-12 h-12 rounded-lg border border-slate-200 object-cover" />
                          <button 
                            type="button" 
                            onClick={() => setWlData({...wlData, appIcon: ''})} 
                            className="absolute -top-2 -right-2 bg-red-100 text-red-600 rounded-full p-1 hover:bg-red-200"
                            title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
                          >
                            <Trash2 className="w-3 h-3" />
                          </button>
                        </div>
                      ) : (
                        <div className="w-12 h-12 rounded-lg bg-slate-100 border border-slate-200 flex items-center justify-center">
                          <Building2 className="w-5 h-5 text-slate-400" />
                        </div>
                      )}
                      <div>
                        <input type="file" accept="image/*" id="wl-icon-upload" className="hidden" onChange={handleWlPhotoUpload} />
                        <label htmlFor="wl-icon-upload" className="cursor-pointer text-sm font-medium text-indigo-600 hover:text-indigo-800 bg-indigo-50 px-3 py-1.5 rounded-lg border border-indigo-100 transition-colors">
                          {isBn ? BN_DICT['upload_icon'] : EN_DICT['upload_icon']}
                        </label>
                      </div>
                    </div>
                  </div>
                </div>
              )}
            </div>

            <div className="pt-4 flex items-center gap-4 border-t border-slate-100">
              <button
                type="submit"
                className="bg-indigo-600 hover:bg-indigo-700 text-white px-6 py-2.5 rounded-lg font-medium transition-colors"
              >
                {t('save')}
              </button>
              {saved && (
                <span className="text-emerald-600 font-medium bg-emerald-50 px-3 py-1 rounded-full text-sm">
                  {isBn ? BN_DICT['saved_successfully'] : EN_DICT['saved_successfully']}
                </span>
              )}
            </div>
          </form>
        </div>

        {/* Standard Font Configuration Card */}
        <div className="bg-white rounded-2xl shadow-sm border border-slate-200 p-6 md:p-8">
          <SystemFontSettingsPanel />
        </div>
      </div>
    </div>
  );
};

export default InstitutionSettings;
