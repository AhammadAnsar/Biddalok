import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState, useMemo } from 'react';
import { 
  MapPin, Plus, Edit2, Trash2, Search, Check, Filter, 
  ArrowLeft, CheckCircle2, AlertCircle, Sparkles, FolderTree
} from 'lucide-react';
import { Link } from 'react-router-dom';
import { useAppStore } from '../store/useAppStore';
import { LocationSelect } from '../components/LocationSelect';
import { LocationItem } from '../constants/bdLocations';
import { slugifyLocationId, sanitizeLocationId } from '../utils/locationUtils';

type GeoCategory = 'districts' | 'upazilas' | 'unions' | 'postOffices' | 'villages';

export default function AddressManagement() {
  const {
    language,
    institution,
    updateInstitution,
    learnedLocations,
    learnLocation,
    updateLocation,
    cascadeUpdateLocationId,
    deleteLocation,
  } = useAppStore();

  const isBn = language === 'bn';

  // Top Default Address Configuration State
  const [defaultForm, setDefaultForm] = useState({
    defaultDivision: institution?.defaultDivision || '',
    defaultDistrict: institution?.defaultDistrict || '',
    defaultUpazila: institution?.defaultUpazila || '',
    defaultUnion: institution?.defaultUnion || '',
    defaultPostOffice: institution?.defaultPostOffice || '',
    defaultVillage: institution?.defaultVillage || '',
  });
  const [defaultSaved, setDefaultSaved] = useState(false);

  // Active Category
  const [activeGeoCategory, setActiveGeoCategory] = useState<GeoCategory>('upazilas');

  // Search & Filter
  const [searchTerm, setSearchTerm] = useState('');
  const [parentFilter, setParentFilter] = useState<string>('all');

  // Modal State for Adding / Editing Geo Location
  const [isGeoModalOpen, setIsGeoModalOpen] = useState(false);
  const [editingGeoItem, setEditingGeoItem] = useState<LocationItem | null>(null);
  const [geoNameEn, setGeoNameEn] = useState('');
  const [geoNameBn, setGeoNameBn] = useState('');
  const [geoCustomId, setGeoCustomId] = useState('');
  const [geoParentId, setGeoParentId] = useState('');

  // Notification toast
  const [toastMsg, setToastMsg] = useState<string | null>(null);

  const showToast = (msg: string) => {
    setToastMsg(msg);
    setTimeout(() => setToastMsg(null), 3000);
  };

  // Categorized Geo Locations
  const divisions = useMemo(() => learnedLocations?.filter(l => l.id.startsWith('div_')) || [], [learnedLocations]);
  const districts = useMemo(() => learnedLocations?.filter(l => l.id.startsWith('dist_')) || [], [learnedLocations]);
  const upazilas = useMemo(() => learnedLocations?.filter(l => l.id.startsWith('upz_')) || [], [learnedLocations]);
  const unions = useMemo(() => learnedLocations?.filter(l => l.id.startsWith('uni_')) || [], [learnedLocations]);
  const postOffices = useMemo(() => learnedLocations?.filter(l => l.id.startsWith('po_')) || [], [learnedLocations]);
  const villages = useMemo(() => learnedLocations?.filter(l => l.id.startsWith('vil_')) || [], [learnedLocations]);

  // Filtering for Default Form
  const defaultDistrictsList = useMemo(() => districts.filter(d => defaultForm.defaultDivision ? d.parentId === defaultForm.defaultDivision : true), [districts, defaultForm.defaultDivision]);
  const defaultUpazilasList = useMemo(() => upazilas.filter(u => defaultForm.defaultDistrict ? u.parentId === defaultForm.defaultDistrict : true), [upazilas, defaultForm.defaultDistrict]);
  const defaultUnionsList = useMemo(() => unions.filter(u => defaultForm.defaultUpazila ? u.parentId === defaultForm.defaultUpazila : true), [unions, defaultForm.defaultUpazila]);
  const defaultPostOfficesList = useMemo(() => postOffices.filter(po => defaultForm.defaultUpazila ? po.parentId === defaultForm.defaultUpazila : true), [postOffices, defaultForm.defaultUpazila]);
  const defaultVillagesList = useMemo(() => villages.filter(v => defaultForm.defaultUnion ? v.parentId === defaultForm.defaultUnion : true), [villages, defaultForm.defaultUnion]);

  // Handle Default Address Save
  const handleSaveDefaultAddress = (e: React.FormEvent) => {
    e.preventDefault();
    updateInstitution({
      defaultDivision: defaultForm.defaultDivision,
      defaultDistrict: defaultForm.defaultDistrict,
      defaultUpazila: defaultForm.defaultUpazila,
      defaultUnion: defaultForm.defaultUnion,
      defaultPostOffice: defaultForm.defaultPostOffice,
      defaultVillage: defaultForm.defaultVillage,
    });
    setDefaultSaved(true);
    showToast(isBn ? BN_DICT['default_address_saved_successf'] : EN_DICT['default_address_saved_successf']);
    setTimeout(() => setDefaultSaved(false), 3000);
  };

  const handleDefaultChange = (field: string, value: string) => {
    let updates: any = { [field]: value };
    if (field === 'defaultDivision') {
      updates = { ...updates, defaultDistrict: '', defaultUpazila: '', defaultUnion: '', defaultPostOffice: '', defaultVillage: '' };
    } else if (field === 'defaultDistrict') {
      updates = { ...updates, defaultUpazila: '', defaultUnion: '', defaultPostOffice: '', defaultVillage: '' };
    } else if (field === 'defaultUpazila') {
      updates = { ...updates, defaultUnion: '', defaultPostOffice: '', defaultVillage: '' };
    } else if (field === 'defaultUnion') {
      updates = { ...updates, defaultVillage: '' };
    }
    setDefaultForm(prev => ({ ...prev, ...updates }));
  };

  const handleAddDefaultLocationInline = (type: string, name: string, nameBn: string, parentId?: string) => {
    const prefix = type === 'defaultDivision' ? 'div_' : type === 'defaultDistrict' ? 'dist_' : type === 'defaultUpazila' ? 'upz_' : type === 'defaultUnion' ? 'uni_' : type === 'defaultPostOffice' ? 'po_' : 'vil_';
    const existingIds = (learnedLocations || []).map(l => l.id);
    const newId = slugifyLocationId(prefix, name || nameBn, existingIds);
    learnLocation({ id: newId, name, nameBn, parentId });
    setDefaultForm(prev => ({ ...prev, [type]: newId }));
    showToast(isBn ? `নতুন ${nameBn || name} যুক্ত করা হয়েছে` : `New ${name || nameBn} added`);
  };

  // Helper to find parent name
  const getParentName = (parentId?: string) => {
    if (!parentId) return '—';
    const parent = learnedLocations?.find(l => l.id === parentId);
    return parent ? (isBn ? parent.nameBn || parent.name : parent.name || parent.nameBn) : parentId;
  };

  // Active Category Prefix
  const currentPrefix = useMemo(() => {
    return activeGeoCategory === 'districts' ? 'dist_' 
      : activeGeoCategory === 'upazilas' ? 'upz_' 
      : activeGeoCategory === 'unions' ? 'uni_' 
      : activeGeoCategory === 'postOffices' ? 'po_' : 'vil_';
  }, [activeGeoCategory]);

  // Preview / Suggested Smart ID
  const previewSmartId = useMemo(() => {
    if (editingGeoItem) {
      if (geoCustomId.trim()) return sanitizeLocationId(geoCustomId, currentPrefix);
      return editingGeoItem.id;
    }
    if (geoCustomId.trim()) return sanitizeLocationId(geoCustomId, currentPrefix);
    return slugifyLocationId(currentPrefix, geoNameEn || geoNameBn, (learnedLocations || []).map(l => l.id));
  }, [editingGeoItem, geoCustomId, currentPrefix, geoNameEn, geoNameBn, learnedLocations]);

  // Geo List filtered by active category, search, and parent
  const activeGeoList = useMemo(() => {
    let list: LocationItem[] = [];
    if (activeGeoCategory === 'districts') list = districts;
    else if (activeGeoCategory === 'upazilas') list = upazilas;
    else if (activeGeoCategory === 'unions') list = unions;
    else if (activeGeoCategory === 'postOffices') list = postOffices;
    else if (activeGeoCategory === 'villages') list = villages;

    if (parentFilter !== 'all') {
      list = list.filter(item => item.parentId === parentFilter);
    }

    if (searchTerm.trim()) {
      const term = searchTerm.toLowerCase().trim();
      list = list.filter(item => 
        (item.name && item.name.toLowerCase().includes(term)) ||
        (item.nameBn && item.nameBn.includes(term)) ||
        (item.id && item.id.toLowerCase().includes(term))
      );
    }

    return list;
  }, [activeGeoCategory, districts, upazilas, unions, postOffices, villages, parentFilter, searchTerm]);

  // Open Geo Modal
  const handleOpenGeoModal = (item?: LocationItem) => {
    if (item) {
      setEditingGeoItem(item);
      setGeoNameEn(item.name || '');
      setGeoNameBn(item.nameBn || '');
      setGeoCustomId(item.id);
      setGeoParentId(item.parentId || '');
    } else {
      setEditingGeoItem(null);
      setGeoNameEn('');
      setGeoNameBn('');
      setGeoCustomId('');
      // set intelligent default parent
      if (activeGeoCategory === 'districts') setGeoParentId(divisions[0]?.id || 'div_chittagong');
      else if (activeGeoCategory === 'upazilas') setGeoParentId(districts[0]?.id || 'dist_comilla');
      else if (activeGeoCategory === 'unions' || activeGeoCategory === 'postOffices') setGeoParentId(upazilas[0]?.id || 'upz_nangalkot');
      else if (activeGeoCategory === 'villages') setGeoParentId(unions[0]?.id || 'uni_hesakhal');
    }
    setIsGeoModalOpen(true);
  };

  const handleSaveGeoItem = (e: React.FormEvent) => {
    e.preventDefault();
    const nameEn = geoNameEn.trim();
    const nameBn = geoNameBn.trim() || nameEn;
    if (!nameEn && !nameBn) return;

    const existingIds = (learnedLocations || []).map(l => l.id);

    if (editingGeoItem) {
      const finalId = geoCustomId.trim()
        ? sanitizeLocationId(geoCustomId, currentPrefix)
        : editingGeoItem.id;

      if (finalId !== editingGeoItem.id) {
        cascadeUpdateLocationId(editingGeoItem.id, finalId, {
          name: nameEn || nameBn,
          nameBn: nameBn || nameEn,
          parentId: geoParentId,
        });
        showToast(isBn ? `আইডি (${finalId}) ও সকল সাব-রেফারেন্স সফলভাবে ক্যাসকেড আপডেট হয়েছে` : `ID (${finalId}) and references updated successfully`);
      } else {
        updateLocation(editingGeoItem.id, {
          name: nameEn || nameBn,
          nameBn: nameBn || nameEn,
          parentId: geoParentId,
        });
        showToast(isBn ? BN_DICT['information_updated_successful'] : EN_DICT['information_updated_successful']);
      }
    } else {
      const finalId = geoCustomId.trim()
        ? sanitizeLocationId(geoCustomId, currentPrefix)
        : slugifyLocationId(currentPrefix, nameEn || nameBn, existingIds);

      learnLocation({
        id: finalId,
        name: nameEn || nameBn,
        nameBn: nameBn || nameEn,
        parentId: geoParentId,
      });
      showToast(isBn ? `নতুন অবস্থান সফলভাবে যুক্ত হয়েছে (আইডি: ${finalId})` : `New location added successfully (ID: ${finalId})`);
    }
    setIsGeoModalOpen(false);
  };

  const handleDeleteGeoItem = (id: string, name: string) => {
    if (window.confirm(isBn ? `আপনি কি নিশ্চিতভাবে "${name}" মুছে ফেলতে চান?` : `Are you sure you want to delete "${name}"?`)) {
      deleteLocation(id);
      showToast(isBn ? `"${name}" মুছে ফেলা হয়েছে` : `"${name}" deleted`);
    }
  };

  return (
    <div className="space-y-6">
      {/* Toast Notification */}
      {toastMsg && (
        <div className="fixed bottom-6 right-6 z-50 bg-slate-900 text-white px-5 py-3 rounded-xl shadow-xl flex items-center gap-3 border border-slate-700 animate-bounce">
          <CheckCircle2 className="w-5 h-5 text-emerald-400" />
          <span className="text-sm font-medium">{toastMsg}</span>
        </div>
      )}

      {/* Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 border-b border-slate-200 pb-5">
        <div className="flex items-center gap-3">
          <Link 
            to="/institution" 
            className="p-2 bg-slate-100 hover:bg-slate-200 text-slate-600 rounded-lg transition-colors"
            title={isBn ? BN_DICT['back_to_institution_settings'] : EN_DICT['back_to_institution_settings']}
          >
            <ArrowLeft className="w-5 h-5" />
          </Link>
          <div>
            <h1 className="text-2xl font-bold text-slate-900 flex items-center gap-2">
              <MapPin className="w-6 h-6 text-indigo-600" />
              {isBn ? BN_DICT['address_location_data'] : EN_DICT['address_location_data']}
            </h1>
            <p className="text-sm text-slate-500 mt-0.5">
              {isBn ? BN_DICT['centralized_database_for_defau'] : EN_DICT['centralized_database_for_defau']}
            </p>
          </div>
        </div>
      </div>

      {/* 1. TOP SECTION: Default Address Configuration */}
      <div className="bg-white rounded-2xl border border-slate-200/80 shadow-sm relative z-30">
        <div className="p-5 sm:p-6 bg-gradient-to-r from-indigo-50/70 via-blue-50/40 to-slate-50 border-b border-slate-100 rounded-t-2xl">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4">
            <div>
              <div className="inline-flex items-center gap-1.5 px-2.5 py-1 rounded-md bg-indigo-100/80 text-indigo-700 text-xs font-semibold uppercase tracking-wider mb-2">
                <Sparkles className="w-3.5 h-3.5" />
                {isBn ? BN_DICT['quick_auto_fill_config'] : EN_DICT['quick_auto_fill_config']}
              </div>
              <h2 className="text-lg font-bold text-slate-900">
                {isBn ? BN_DICT['default_address_configuration'] : EN_DICT['default_address_configuration']}
              </h2>
              <p className="text-sm text-slate-600 mt-1 max-w-3xl">
                {isBn ? BN_DICT['configure_default_address_loca'] : EN_DICT['configure_default_address_loca']}
              </p>
            </div>

            <button
              onClick={handleSaveDefaultAddress}
              className="inline-flex items-center justify-center gap-2 px-5 py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white font-medium rounded-xl text-sm transition-colors shadow-sm self-start sm:self-center shrink-0 cursor-pointer"
            >
              <Check className="w-4 h-4" />
              {isBn ? BN_DICT['save_default_address'] : EN_DICT['save_default_address']}
            </button>
          </div>
        </div>

        <form onSubmit={handleSaveDefaultAddress} className="p-5 sm:p-6">
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-5">
            {/* Division */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                {isBn ? BN_DICT['default_division'] : EN_DICT['default_division']}
              </label>
              <LocationSelect
                options={divisions}
                value={defaultForm.defaultDivision || ''}
                onChange={(val) => handleDefaultChange('defaultDivision', val)}
                onAdd={(name, nameBn) => handleAddDefaultLocationInline('defaultDivision', name, nameBn)}
                placeholder={isBn ? BN_DICT['select_division'] : EN_DICT['select_division']}
                language={language}
              />
            </div>

            {/* District */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                {isBn ? BN_DICT['default_district'] : EN_DICT['default_district']}
              </label>
              <LocationSelect
                options={defaultDistrictsList}
                value={defaultForm.defaultDistrict || ''}
                onChange={(val) => handleDefaultChange('defaultDistrict', val)}
                onAdd={(name, nameBn) => handleAddDefaultLocationInline('defaultDistrict', name, nameBn, defaultForm.defaultDivision)}
                placeholder={isBn ? BN_DICT['select_district'] : EN_DICT['select_district']}
                disabled={!defaultForm.defaultDivision}
                language={language}
              />
            </div>

            {/* Upazila */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                {isBn ? BN_DICT['default_upazila_thana'] : EN_DICT['default_upazila_thana']}
              </label>
              <LocationSelect
                options={defaultUpazilasList}
                value={defaultForm.defaultUpazila || ''}
                onChange={(val) => handleDefaultChange('defaultUpazila', val)}
                onAdd={(name, nameBn) => handleAddDefaultLocationInline('defaultUpazila', name, nameBn, defaultForm.defaultDistrict)}
                placeholder={isBn ? BN_DICT['select_upazila'] : EN_DICT['select_upazila']}
                disabled={!defaultForm.defaultDistrict}
                language={language}
              />
            </div>

            {/* Union */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                {isBn ? BN_DICT['default_union_ward'] : EN_DICT['default_union_ward']}
              </label>
              <LocationSelect
                options={defaultUnionsList}
                value={defaultForm.defaultUnion || ''}
                onChange={(val) => handleDefaultChange('defaultUnion', val)}
                onAdd={(name, nameBn) => handleAddDefaultLocationInline('defaultUnion', name, nameBn, defaultForm.defaultUpazila)}
                placeholder={isBn ? BN_DICT['select_union'] : EN_DICT['select_union']}
                disabled={!defaultForm.defaultUpazila}
                language={language}
              />
            </div>

            {/* Post Office */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                {isBn ? BN_DICT['default_post_office'] : EN_DICT['default_post_office']}
              </label>
              <LocationSelect
                options={defaultPostOfficesList}
                value={defaultForm.defaultPostOffice || ''}
                currentTextValue={defaultForm.defaultPostOffice}
                onChange={(val, text) => handleDefaultChange('defaultPostOffice', text || val)}
                onAdd={(name, nameBn) => handleAddDefaultLocationInline('defaultPostOffice', name, nameBn, defaultForm.defaultUpazila)}
                placeholder={isBn ? BN_DICT['select_or_type_post_office'] : EN_DICT['select_or_type_post_office']}
                language={language}
              />
            </div>

            {/* Village */}
            <div className="space-y-1.5">
              <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                {isBn ? BN_DICT['default_village_area'] : EN_DICT['default_village_area']}
              </label>
              <LocationSelect
                options={defaultVillagesList}
                value={defaultForm.defaultVillage || ''}
                currentTextValue={defaultForm.defaultVillage}
                onChange={(val, text) => handleDefaultChange('defaultVillage', text || val)}
                onAdd={(name, nameBn) => handleAddDefaultLocationInline('defaultVillage', name, nameBn, defaultForm.defaultUnion)}
                placeholder={isBn ? BN_DICT['select_or_type_village'] : EN_DICT['select_or_type_village']}
                language={language}
              />
            </div>
          </div>
        </form>
      </div>

      {/* 2. MAIN GEOGRAPHICAL MASTER SECTION */}
      <div className="space-y-6">
        <div className="bg-white rounded-2xl border border-slate-200 shadow-sm p-6 space-y-6">
          {/* Category Pills */}
          <div className="flex flex-wrap items-center justify-between gap-4">
            <div className="flex flex-wrap items-center gap-2 bg-slate-100/80 p-1.5 rounded-xl border border-slate-200/60">
              <button
                onClick={() => { setActiveGeoCategory('districts'); setParentFilter('all'); }}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
                  activeGeoCategory === 'districts' ? 'bg-white text-indigo-700 shadow-sm' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                {isBn ? `জেলা (${districts.length})` : `Districts (${districts.length})`}
              </button>
              <button
                onClick={() => { setActiveGeoCategory('upazilas'); setParentFilter('all'); }}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
                  activeGeoCategory === 'upazilas' ? 'bg-white text-indigo-700 shadow-sm' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                {isBn ? `উপজেলা (${upazilas.length})` : `Upazilas (${upazilas.length})`}
              </button>
              <button
                onClick={() => { setActiveGeoCategory('unions'); setParentFilter('all'); }}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
                  activeGeoCategory === 'unions' ? 'bg-white text-indigo-700 shadow-sm' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                {isBn ? `ইউনিয়ন (${unions.length})` : `Unions (${unions.length})`}
              </button>
              <button
                onClick={() => { setActiveGeoCategory('postOffices'); setParentFilter('all'); }}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
                  activeGeoCategory === 'postOffices' ? 'bg-white text-indigo-700 shadow-sm' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                {isBn ? `ডাকঘর (${postOffices.length})` : `Post Offices (${postOffices.length})`}
              </button>
              <button
                onClick={() => { setActiveGeoCategory('villages'); setParentFilter('all'); }}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all cursor-pointer ${
                  activeGeoCategory === 'villages' ? 'bg-white text-indigo-700 shadow-sm' : 'text-slate-600 hover:text-slate-900'
                }`}
              >
                {isBn ? `গ্রাম (${villages.length})` : `Villages (${villages.length})`}
              </button>
            </div>

            {/* Add New Geo Button */}
            <button
              onClick={() => handleOpenGeoModal()}
              className="inline-flex items-center gap-2 px-3.5 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-xs font-semibold transition-colors shadow-sm cursor-pointer"
            >
              <Plus className="w-4 h-4" />
              {isBn ? (
                <>
                  {activeGeoCategory === 'districts' && 'নতুন জেলা'}
                  {activeGeoCategory === 'upazilas' && 'নতুন উপজেলা'}
                  {activeGeoCategory === 'unions' && 'নতুন ইউনিয়ন'}
                  {activeGeoCategory === 'postOffices' && 'নতুন ডাকঘর'}
                  {activeGeoCategory === 'villages' && 'নতুন গ্রাম'}
                </>
              ) : (
                <>
                  {activeGeoCategory === 'districts' && 'Add District'}
                  {activeGeoCategory === 'upazilas' && 'Add Upazila'}
                  {activeGeoCategory === 'unions' && 'Add Union'}
                  {activeGeoCategory === 'postOffices' && 'Add Post Office'}
                  {activeGeoCategory === 'villages' && 'Add Village'}
                </>
              )}
            </button>
          </div>

          {/* Filter Bar */}
          <div className="flex flex-col sm:flex-row items-center gap-4 bg-slate-50/70 p-4 rounded-xl border border-slate-100">
            <div className="relative flex-1 w-full">
              <Search className="w-4 h-4 absolute left-3.5 top-1/2 -translate-y-1/2 text-slate-400" />
              <input
                type="text"
                placeholder={isBn ? BN_DICT['search_by_name_or_id'] : EN_DICT['search_by_name_or_id']}
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                className="w-full pl-9 pr-4 py-2 bg-white border border-slate-200 rounded-lg text-sm focus:ring-2 focus:ring-indigo-500 outline-none"
              />
            </div>

            {/* Parent Filter */}
            {activeGeoCategory === 'districts' && (
              <div className="flex items-center gap-2 w-full sm:w-auto">
                <Filter className="w-4 h-4 text-slate-500" />
                <select
                  value={parentFilter}
                  onChange={(e) => setParentFilter(e.target.value)}
                  className="bg-white border border-slate-200 rounded-lg px-3 py-2 text-sm text-slate-700 outline-none focus:ring-2 focus:ring-indigo-500"
                >
                  <option value="all">{isBn ? BN_DICT['all_divisions'] : EN_DICT['all_divisions']}</option>
                  {divisions.map(d => (
                    <option key={d.id} value={d.id}>{isBn ? d.nameBn || d.name : d.name || d.nameBn}</option>
                  ))}
                </select>
              </div>
            )}

            {activeGeoCategory === 'upazilas' && (
              <div className="flex items-center gap-2 w-full sm:w-auto">
                <Filter className="w-4 h-4 text-slate-500" />
                <select
                  value={parentFilter}
                  onChange={(e) => setParentFilter(e.target.value)}
                  className="bg-white border border-slate-200 rounded-lg px-3 py-2 text-sm text-slate-700 outline-none focus:ring-2 focus:ring-indigo-500"
                >
                  <option value="all">{isBn ? BN_DICT['all_districts'] : EN_DICT['all_districts']}</option>
                  {districts.map(d => (
                    <option key={d.id} value={d.id}>{isBn ? d.nameBn || d.name : d.name || d.nameBn}</option>
                  ))}
                </select>
              </div>
            )}

            {(activeGeoCategory === 'unions' || activeGeoCategory === 'postOffices') && (
              <div className="flex items-center gap-2 w-full sm:w-auto">
                <Filter className="w-4 h-4 text-slate-500" />
                <select
                  value={parentFilter}
                  onChange={(e) => setParentFilter(e.target.value)}
                  className="bg-white border border-slate-200 rounded-lg px-3 py-2 text-sm text-slate-700 outline-none focus:ring-2 focus:ring-indigo-500"
                >
                  <option value="all">{isBn ? BN_DICT['all_upazilas'] : EN_DICT['all_upazilas']}</option>
                  {upazilas.map(u => (
                    <option key={u.id} value={u.id}>{isBn ? u.nameBn || u.name : u.name || u.nameBn}</option>
                  ))}
                </select>
              </div>
            )}

            {activeGeoCategory === 'villages' && (
              <div className="flex items-center gap-2 w-full sm:w-auto">
                <Filter className="w-4 h-4 text-slate-500" />
                <select
                  value={parentFilter}
                  onChange={(e) => setParentFilter(e.target.value)}
                  className="bg-white border border-slate-200 rounded-lg px-3 py-2 text-sm text-slate-700 outline-none focus:ring-2 focus:ring-indigo-500"
                >
                  <option value="all">{isBn ? BN_DICT['all_unions'] : EN_DICT['all_unions']}</option>
                  {unions.map(u => (
                    <option key={u.id} value={u.id}>{isBn ? u.nameBn || u.name : u.name || u.nameBn}</option>
                  ))}
                </select>
              </div>
            )}
          </div>

          {/* Table */}
          <div className="overflow-x-auto border border-slate-200 rounded-xl">
            <table className="w-full text-left text-sm border-collapse">
              <thead className="bg-slate-50 text-slate-600 font-semibold border-b border-slate-200">
                <tr>
                  <th className="py-3 px-4">{isBn ? BN_DICT['sl'] : EN_DICT['sl']}</th>
                  <th className="py-3 px-4">{isBn ? BN_DICT['bangla_name'] : EN_DICT['bangla_name']}</th>
                  <th className="py-3 px-4">{isBn ? BN_DICT['english_name'] : EN_DICT['english_name']}</th>
                  <th className="py-3 px-4">{isBn ? BN_DICT['parent_region'] : EN_DICT['parent_region']}</th>
                  <th className="py-3 px-4">{isBn ? BN_DICT['id_1'] : EN_DICT['id_1']}</th>
                  <th className="py-3 px-4 text-right">{isBn ? BN_DICT['action'] : EN_DICT['action']}</th>
                </tr>
              </thead>
              <tbody className="divide-y divide-slate-100">
                {activeGeoList.length === 0 ? (
                  <tr>
                    <td colSpan={6} className="py-8 text-center text-slate-400">
                      {isBn ? BN_DICT['no_data_found'] : EN_DICT['no_data_found']}
                    </td>
                  </tr>
                ) : (
                  activeGeoList.map((item, idx) => (
                    <tr key={item.id} className="hover:bg-slate-50/80 transition-colors">
                      <td className="py-3 px-4 text-slate-400 font-mono text-xs">{idx + 1}</td>
                      <td className="py-3 px-4 font-medium text-slate-900">{item.nameBn || item.name}</td>
                      <td className="py-3 px-4 text-slate-600">{item.name || '—'}</td>
                      <td className="py-3 px-4 text-slate-600">
                        <span className="inline-flex items-center px-2 py-0.5 rounded-md bg-slate-100 text-slate-700 text-xs font-medium">
                          {getParentName(item.parentId)}
                        </span>
                      </td>
                      <td className="py-3 px-4 text-slate-400 font-mono text-xs">{item.id}</td>
                      <td className="py-3 px-4 text-right">
                        <div className="flex items-center justify-end gap-2">
                          <button
                            onClick={() => handleOpenGeoModal(item)}
                            className="p-1.5 text-indigo-600 hover:bg-indigo-50 rounded-lg transition-colors cursor-pointer"
                            title={isBn ? BN_DICT['edit'] : EN_DICT['edit']}
                          >
                            <Edit2 className="w-4 h-4" />
                          </button>
                          <button
                            onClick={() => handleDeleteGeoItem(item.id, item.nameBn || item.name)}
                            className="p-1.5 text-red-500 hover:bg-red-50 rounded-lg transition-colors cursor-pointer"
                            title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
                          >
                            <Trash2 className="w-4 h-4" />
                          </button>
                        </div>
                      </td>
                    </tr>
                  ))
                )}
              </tbody>
            </table>
          </div>
        </div>
      </div>

      {/* ========================================================= */}
      {/* MODAL: ADD / EDIT GEOGRAPHICAL LOCATION                   */}
      {/* ========================================================= */}
      {isGeoModalOpen && (
        <div className="fixed inset-0 bg-slate-900/50 backdrop-blur-xs z-50 flex items-center justify-center p-4">
          <div className="bg-white rounded-2xl max-w-md w-full p-6 shadow-2xl border border-slate-200 animate-scaleUp">
            <h3 className="text-lg font-bold text-slate-900 mb-4">
              {editingGeoItem 
                ? (isBn ? BN_DICT['edit_geographical_location'] : EN_DICT['edit_geographical_location'])
                : (isBn ? BN_DICT['add_new_geographical_location'] : EN_DICT['add_new_geographical_location'])}
            </h3>

            <form onSubmit={handleSaveGeoItem} className="space-y-4">
              <div>
                <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                  {isBn ? BN_DICT['bangla_name_1'] : EN_DICT['bangla_name_1']}
                </label>
                <input
                  type="text"
                  required
                  value={geoNameBn}
                  onChange={(e) => setGeoNameBn(e.target.value)}
                  placeholder={isBn ? BN_DICT['e_g_2'] : EN_DICT['e_g_2']}
                  className="w-full mt-1 px-3.5 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:ring-2 focus:ring-indigo-500 outline-none"
                  autoFocus
                />
              </div>

              <div>
                <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                  {isBn ? BN_DICT['english_name'] : EN_DICT['english_name']}
                </label>
                <input
                  type="text"
                  value={geoNameEn}
                  onChange={(e) => setGeoNameEn(e.target.value)}
                  placeholder="e.g. Nangalkot"
                  className="w-full mt-1 px-3.5 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:ring-2 focus:ring-indigo-500 outline-none"
                />
              </div>

              {/* Custom / Smart ID Input */}
              <div className="bg-slate-50/80 p-3.5 rounded-xl border border-slate-200/80 space-y-2">
                <div className="flex items-center justify-between">
                  <label className="text-xs font-semibold text-slate-700 uppercase tracking-wide flex items-center gap-1.5">
                    <Sparkles className="w-3.5 h-3.5 text-indigo-600" />
                    {isBn ? BN_DICT['custom_smart_id'] : EN_DICT['custom_smart_id']}
                  </label>
                  <span className="text-[11px] text-indigo-600 font-mono font-medium">
                    {editingGeoItem 
                      ? (isBn ? BN_DICT['editable_id'] : EN_DICT['editable_id']) 
                      : (isBn ? BN_DICT['optional_auto_slug'] : EN_DICT['optional_auto_slug'])}
                  </span>
                </div>
                
                <div className="relative">
                  <input
                    type="text"
                    value={geoCustomId}
                    onChange={(e) => setGeoCustomId(e.target.value)}
                    placeholder={isBn ? `যেমন: ${currentPrefix}nangalkot (ফাঁকা রাখলে ইংরেজি নাম থেকে অটো তৈরি হবে)` : `e.g. ${currentPrefix}nangalkot (Leave blank for auto-slug)`}
                    className="w-full px-3 py-2 bg-white border border-slate-200 rounded-lg text-xs font-mono text-slate-800 focus:ring-2 focus:ring-indigo-500 outline-none"
                  />
                </div>

                <div className="flex items-center justify-between text-[11px] text-slate-500">
                  <span>{isBn ? BN_DICT['system_target_id'] : EN_DICT['system_target_id']}</span>
                  <code className="px-2 py-0.5 bg-indigo-50 text-indigo-700 rounded font-mono font-semibold border border-indigo-100/80">
                    {previewSmartId}
                  </code>
                </div>

                {editingGeoItem && geoCustomId.trim() && sanitizeLocationId(geoCustomId, currentPrefix) !== editingGeoItem.id && (
                  <div className="p-2.5 bg-amber-50 border border-amber-200 rounded-lg flex items-start gap-2 text-xs text-amber-800">
                    <AlertCircle className="w-4 h-4 text-amber-600 shrink-0 mt-0.5" />
                    <div>
                      <span className="font-semibold">{isBn ? BN_DICT['cascade_update_active'] : EN_DICT['cascade_update_active']}</span>
                      <p className="mt-0.5 text-[11px] text-amber-700 leading-relaxed">
                        {isBn ? BN_DICT['modifying_the_id_will_automati'] : EN_DICT['modifying_the_id_will_automati']}
                      </p>
                    </div>
                  </div>
                )}
              </div>

              {/* Parent Selector */}
              {activeGeoCategory === 'districts' && (
                <div>
                  <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                    {isBn ? BN_DICT['parent_division'] : EN_DICT['parent_division']}
                  </label>
                  <select
                    value={geoParentId}
                    onChange={(e) => setGeoParentId(e.target.value)}
                    className="w-full mt-1 px-3.5 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:ring-2 focus:ring-indigo-500 outline-none"
                  >
                    {divisions.map(d => (
                      <option key={d.id} value={d.id}>{isBn ? d.nameBn || d.name : d.name || d.nameBn}</option>
                    ))}
                  </select>
                </div>
              )}

              {activeGeoCategory === 'upazilas' && (
                <div>
                  <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                    {isBn ? BN_DICT['parent_district'] : EN_DICT['parent_district']}
                  </label>
                  <select
                    value={geoParentId}
                    onChange={(e) => setGeoParentId(e.target.value)}
                    className="w-full mt-1 px-3.5 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:ring-2 focus:ring-indigo-500 outline-none"
                  >
                    {districts.map(d => (
                      <option key={d.id} value={d.id}>{isBn ? d.nameBn || d.name : d.name || d.nameBn}</option>
                    ))}
                  </select>
                </div>
              )}

              {(activeGeoCategory === 'unions' || activeGeoCategory === 'postOffices') && (
                <div>
                  <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                    {isBn ? BN_DICT['parent_upazila'] : EN_DICT['parent_upazila']}
                  </label>
                  <select
                    value={geoParentId}
                    onChange={(e) => setGeoParentId(e.target.value)}
                    className="w-full mt-1 px-3.5 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:ring-2 focus:ring-indigo-500 outline-none"
                  >
                    {upazilas.map(u => (
                      <option key={u.id} value={u.id}>{isBn ? u.nameBn || u.name : u.name || u.nameBn}</option>
                    ))}
                  </select>
                </div>
              )}

              {activeGeoCategory === 'villages' && (
                <div>
                  <label className="text-xs font-semibold text-slate-600 uppercase tracking-wide">
                    {isBn ? BN_DICT['parent_union'] : EN_DICT['parent_union']}
                  </label>
                  <select
                    value={geoParentId}
                    onChange={(e) => setGeoParentId(e.target.value)}
                    className="w-full mt-1 px-3.5 py-2.5 bg-slate-50 border border-slate-200 rounded-xl text-sm focus:ring-2 focus:ring-indigo-500 outline-none"
                  >
                    {unions.map(u => (
                      <option key={u.id} value={u.id}>{isBn ? u.nameBn || u.name : u.name || u.nameBn}</option>
                    ))}
                  </select>
                </div>
              )}

              <div className="flex items-center justify-end gap-3 pt-4 border-t border-slate-100">
                <button
                  type="button"
                  onClick={() => setIsGeoModalOpen(false)}
                  className="px-4 py-2 text-slate-600 hover:bg-slate-100 rounded-xl text-sm font-medium transition-colors cursor-pointer"
                >
                  {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
                </button>
                <button
                  type="submit"
                  className="px-5 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-sm font-medium transition-colors shadow-sm cursor-pointer"
                >
                  {isBn ? BN_DICT['save'] : EN_DICT['save']}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
}

