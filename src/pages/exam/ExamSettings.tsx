import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { useSearchParams, Link, useNavigate } from 'react-router-dom';
import { 
  Settings2, Plus, Edit2, Trash2, CheckCircle2, ChevronRight, ArrowLeft, 
  Award, Calendar, BookOpen, ExternalLink, Sparkles, ShieldCheck, AlertTriangle
} from 'lucide-react';
import { OFFICIAL_SECONDARY_GOLDEN_CORPUS, verifyExamPolicyAgainstCorpus } from '../../data/goldenExamFixtures';
import { useAppStore } from '../../store/useAppStore';
import { ExamTerm, SubjectItem } from '../../types';

interface ExamSettingsProps {
  hideTopHeader?: boolean;
  initialTab?: 'terms' | 'grading';
}

export const ExamSettings: React.FC<ExamSettingsProps> = ({ 
  hideTopHeader = false,
  initialTab
}) => {
  const navigate = useNavigate();
  const [searchParams, setSearchParams] = useSearchParams();
  const activeTabParam = initialTab || (searchParams.get('tab') === 'grading' ? 'grading' : 'terms');
  const [activeTab, setActiveTab] = useState<'terms' | 'grading'>(
    activeTabParam === 'grading' ? 'grading' : 'terms'
  );
  const verificationResult = verifyExamPolicyAgainstCorpus(OFFICIAL_SECONDARY_GOLDEN_CORPUS);

  const { 
    language, 
    examTerms, addExamTerm, updateExamTerm, deleteExamTerm, setDefaultExamTerm,
    subjects,
    gradingRules, resetGradingRules,
    academicClasses, academicSessions, curriculums,
  } = useAppStore();

  const isBn = language === 'bn';

  // --- TAB 1: Exam Terms State ---
  const [isTermModalOpen, setIsTermModalOpen] = useState(false);
  const [editingTerm, setEditingTerm] = useState<ExamTerm | null>(null);
  const [termFormData, setTermFormData] = useState<Partial<ExamTerm>>({
    name: '',
    nameBn: '',
    year: '2026',
    termCode: '',
    startDate: '',
    endDate: '',
    status: 'upcoming',
    isDefault: false,
    description: '',
          curriculumId: curriculums?.find(c => c.isDefault)?.id || ''
        });

  const handleOpenTermModal = (term?: ExamTerm) => {
    if (term) {
      setEditingTerm(term);
      setTermFormData(term);
    } else {
      setEditingTerm(null);
      setTermFormData({
        name: '',
        nameBn: '',
        year: '2026',
        termCode: `EXAM-${(examTerms || []).length + 1}`,
        startDate: new Date().toISOString().split('T')[0],
        endDate: '',
        status: 'upcoming',
        isDefault: false,
        description: '',
          curriculumId: curriculums?.find(c => c.isDefault)?.id || ''
        });
    }
    setIsTermModalOpen(true);
  };

  const handleSaveTerm = (e: React.FormEvent) => {
    e.preventDefault();
    if (termFormData.status === 'published') {
      alert('Phase 01: Official result publication is blocked pending validation policies.');
      return;
    }
    if (!termFormData.name && !termFormData.nameBn) return;

    if (editingTerm) {
      updateExamTerm(editingTerm.id, termFormData);
    } else {
      const newTerm: ExamTerm = {
        id: `term_${Date.now()}`,
        name: termFormData.name || termFormData.nameBn || 'New Exam',
        nameBn: termFormData.nameBn || termFormData.name,
        year: termFormData.year || '2026',
        termCode: termFormData.termCode || 'EXAM',
        startDate: termFormData.startDate,
        endDate: termFormData.endDate,
        status: termFormData.status || 'upcoming',
        isDefault: termFormData.isDefault || false,
        description: termFormData.description,
          curriculumId: termFormData.curriculumId || curriculums?.find(c => c.isDefault)?.id || ''
        };
      addExamTerm(newTerm);
    }
    setIsTermModalOpen(false);
  };

  // Preview class for curriculum subjects
  const [previewClass, setPreviewClass] = useState<string>(
    academicClasses && academicClasses.length > 0 ? (academicClasses[0].nameBn || academicClasses[0].name) : '৯ম শ্রেণি'
  );

  const classSubjects = (subjects || []).filter(s => s.className === previewClass);

  return (
    <div className="space-y-6">
      {/* Top Header & Breadcrumb */}
      {!hideTopHeader ? (
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200">
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-xs text-slate-500">
              <Link to="/exam" className="hover:text-indigo-600 flex items-center gap-1 font-medium">
                <ArrowLeft className="w-3.5 h-3.5" />
                {isBn ? BN_DICT['exam_hub'] : EN_DICT['exam_hub']}
              </Link>
              <ChevronRight className="w-3.5 h-3.5 text-slate-300" />
              <span className="text-slate-700 font-semibold">{isBn ? BN_DICT['exam_settings'] : EN_DICT['exam_settings']}</span>
            </div>
            <h1 className="text-2xl font-bold text-slate-800 flex items-center gap-2.5">
              <Settings2 className="w-6 h-6 text-indigo-600" />
              <span>{isBn ? BN_DICT['exam_settings'] : EN_DICT['exam_settings']}</span>
            </h1>
            <p className="text-xs sm:text-sm text-slate-500">
              {isBn ? BN_DICT['configure_examination_terms_an'] : EN_DICT['configure_examination_terms_an']}
            </p>
          </div>

          {/* Tab switchers */}
          <div className="flex bg-slate-100 p-1 rounded-xl border border-slate-200/80 self-start sm:self-auto">
            <button
              onClick={() => { setActiveTab('terms'); setSearchParams({ tab: 'terms' }); }}
              className={`px-3.5 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                activeTab === 'terms' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {isBn ? BN_DICT['exam_terms'] : EN_DICT['exam_terms']}
            </button>
            <button
              onClick={() => { setActiveTab('grading'); setSearchParams({ tab: 'grading' }); }}
              className={`px-3.5 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                activeTab === 'grading' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {isBn ? BN_DICT['grading_policy'] : EN_DICT['grading_policy']}
            </button>
          </div>
        </div>
      ) : (
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-100">
          <span className="text-xs font-bold text-slate-600 uppercase tracking-wider">
            {isBn ? BN_DICT['exam_configuration_settings'] : EN_DICT['exam_configuration_settings']}
          </span>
          <div className="flex bg-slate-100 p-1 rounded-xl border border-slate-200/80 self-start sm:self-auto">
            <button
              onClick={() => setActiveTab('terms')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                activeTab === 'terms' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {isBn ? BN_DICT['exam_terms'] : EN_DICT['exam_terms']}
            </button>
            <button
              onClick={() => setActiveTab('grading')}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                activeTab === 'grading' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600 hover:text-slate-900'
              }`}
            >
              {isBn ? BN_DICT['grading_policy'] : EN_DICT['grading_policy']}
            </button>
          </div>
        </div>
      )}

      {/* ================= TAB 1: EXAM TERMS ================= */}
      {activeTab === 'terms' && (
        <div className="space-y-6">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 bg-white p-4 rounded-xl border border-slate-200/80 shadow-xs">
            <div>
              <h2 className="text-base font-bold text-slate-800">
                {isBn ? BN_DICT['examination_terms_sessions'] : EN_DICT['examination_terms_sessions']}
              </h2>
              <p className="text-xs text-slate-500">
                {isBn ? BN_DICT['manage_all_terminal_and_annual'] : EN_DICT['manage_all_terminal_and_annual']}
              </p>
            </div>
            <button
              onClick={() => handleOpenTermModal()}
              className="inline-flex items-center justify-center gap-2 px-4 py-2 bg-indigo-600 text-white rounded-lg text-xs font-semibold hover:bg-indigo-700 shadow-xs transition-colors"
            >
              <Plus className="w-4 h-4" />
              <span>{isBn ? BN_DICT['add_new_exam'] : EN_DICT['add_new_exam']}</span>
            </button>
          </div>

          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
            {(examTerms || []).map((term) => (
              <div 
                key={term.id}
                className={`bg-white rounded-xl p-5 border transition-all relative ${
                  term.isDefault ? 'border-indigo-400 ring-2 ring-indigo-50 shadow-xs' : 'border-slate-200/80 shadow-xs hover:border-slate-300'
                }`}
              >
                {term.isDefault && (
                  <div className="absolute top-3 right-3 flex items-center gap-1 bg-indigo-50 text-indigo-700 px-2 py-0.5 rounded-full text-[11px] font-semibold border border-indigo-200">
                    <CheckCircle2 className="w-3 h-3 text-indigo-600" />
                    <span>{isBn ? BN_DICT['active_default'] : EN_DICT['active_default']}</span>
                  </div>
                )}

                <div className="space-y-3">
                  <div>
                    <div className="text-xs text-slate-400 font-mono font-medium">{term.termCode || 'TERM'}</div>
                    <h3 className="text-lg font-bold text-slate-800 mt-0.5">
                      {isBn ? (term.nameBn || term.name) : term.name}
                    </h3>
                    {term.description && (
                      <p className="text-xs text-slate-500 mt-1 line-clamp-2">{term.description}</p>
                    )}
                  </div>

                  {/* Policy Verification & Release Approval */}
                  <div className={term.isPolicyApproved ? "p-2.5 rounded-lg border text-xs flex items-center justify-between bg-emerald-50/70 border-emerald-200 text-emerald-800" : "p-2.5 rounded-lg border text-xs flex items-center justify-between bg-amber-50/70 border-amber-200 text-amber-800"}>
                    <div className="flex items-center gap-1.5">
                      {term.isPolicyApproved ? (
                        <ShieldCheck className="w-4 h-4 text-emerald-600 shrink-0" />
                      ) : (
                        <AlertTriangle className="w-4 h-4 text-amber-600 shrink-0" />
                      )}
                      <div>
                        <div className="font-bold text-[11px]">
                          {term.isPolicyApproved 
                            ? (isBn ? BN_DICT['policy_approved_release_ready'] : EN_DICT['policy_approved_release_ready']) 
                            : (isBn ? BN_DICT['unverified_policy_release_bloc'] : EN_DICT['unverified_policy_release_bloc'])}
                        </div>
                        <div className="text-[10px] text-slate-500">
                          {term.isPolicyApproved ? (term.policyVersion || 'v2025.1') : (isBn ? BN_DICT['needs_board_inst_approval'] : EN_DICT['needs_board_inst_approval'])}
                        </div>
                      </div>
                    </div>
                    <button
                      type="button"
                      onClick={() => {
                        const newApproved = !term.isPolicyApproved;
                        updateExamTerm(term.id, {
                          isPolicyApproved: newApproved,
                          policyApprovedBy: newApproved ? 'Academic Authority' : undefined,
                          policyApprovedAt: newApproved ? new Date().toISOString() : undefined,
                          policyVersion: newApproved ? OFFICIAL_SECONDARY_GOLDEN_CORPUS.version : undefined
                        });
                      }}
                      className={"px-2 py-1 rounded text-[10px] font-semibold border transition-colors " + (term.isPolicyApproved ? 'bg-white text-emerald-700 border-emerald-300 hover:bg-emerald-100' : 'bg-amber-600 text-white border-amber-700 hover:bg-amber-700')}
                    >
                      {term.isPolicyApproved ? (isBn ? BN_DICT['revoke'] : EN_DICT['revoke']) : (isBn ? BN_DICT['approve'] : EN_DICT['approve'])}
                    </button>
                  </div>

                  <div className="pt-2 border-t border-slate-100 grid grid-cols-2 gap-2 text-xs">
                    <div>
                      <span className="text-slate-400 block">{isBn ? BN_DICT['year_1'] : EN_DICT['year_1']}</span>
                      <span className="font-semibold text-slate-700">{term.year}</span>
                    </div>
                    <div>
                      <span className="text-slate-400 block">{isBn ? BN_DICT['status_1'] : EN_DICT['status_1']}</span>
                      <span className={`inline-block px-1.5 py-0.5 rounded font-medium text-[10px] uppercase ${
                        term.status === 'ongoing' ? 'bg-emerald-50 text-emerald-700 border border-emerald-200' :
                        term.status === 'published' ? 'bg-blue-50 text-blue-700 border border-blue-200' :
                        term.status === 'archived' ? 'bg-slate-100 text-slate-600 border border-slate-200' :
                        'bg-amber-50 text-amber-700 border border-amber-200'
                      }`}>
                        {term.status}
                      </span>
                    </div>
                  </div>

                  {(term.startDate || term.endDate) && (
                    <div className="text-xs text-slate-500 flex items-center gap-1.5 pt-1">
                      <Calendar className="w-3.5 h-3.5 text-slate-400" />
                      <span>{term.startDate || '—'} {isBn ? BN_DICT['to'] : EN_DICT['to']} {term.endDate || '—'}</span>
                    </div>
                  )}

                  <div className="pt-3 border-t border-slate-100 flex items-center justify-between">
                    {!term.isDefault ? (
                      <button
                        onClick={() => setDefaultExamTerm(term.id)}
                        className="text-xs font-semibold text-slate-500 hover:text-indigo-600 transition-colors"
                      >
                        {isBn ? BN_DICT['set_as_default'] : EN_DICT['set_as_default']}
                      </button>
                    ) : <span />}

                    <div className="flex items-center gap-1">
                      <button
                        onClick={() => handleOpenTermModal(term)}
                        className="p-1.5 text-slate-400 hover:text-indigo-600 rounded-lg hover:bg-slate-50 transition-colors"
                        title={isBn ? BN_DICT['edit'] : EN_DICT['edit']}
                      >
                        <Edit2 className="w-4 h-4" />
                      </button>
                      <button
                        onClick={() => {
                          if (confirm(isBn ? BN_DICT['are_you_sure_you_want_to_delet_2'] : EN_DICT['are_you_sure_you_want_to_delet_2'])) {
                            deleteExamTerm(term.id);
                          }
                        }}
                        className="p-1.5 text-slate-400 hover:text-rose-600 rounded-lg hover:bg-slate-50 transition-colors"
                        title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </div>
                  </div>
                </div>
              </div>
            ))}
          </div>

          {/* Curriculum Subjects Preview Banner */}
          <div className="bg-slate-50 p-5 rounded-2xl border border-slate-200/90 shadow-xs space-y-4">
            <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-200">
              <div className="flex items-center gap-2.5">
                <div className="p-2 bg-indigo-50 text-indigo-600 rounded-xl">
                  <BookOpen className="w-5 h-5" />
                </div>
                <div>
                  <h3 className="text-sm font-bold text-slate-800 flex items-center gap-2">
                    <span>{isBn ? BN_DICT['class_wise_subjects_marks_prev'] : EN_DICT['class_wise_subjects_marks_prev']}</span>
                    <span className="text-[10px] bg-emerald-100 text-emerald-800 font-semibold px-2 py-0.5 rounded-full">
                      {isBn ? BN_DICT['auto_synced'] : EN_DICT['auto_synced']}
                    </span>
                  </h3>
                  <p className="text-xs text-slate-500">
                    {isBn ? BN_DICT['all_subject_mappings_and_mark'] : EN_DICT['all_subject_mappings_and_mark']}
                  </p>
                </div>
              </div>

              <button
                onClick={() => navigate('/academic/curriculum')}
                className="inline-flex items-center gap-1.5 px-3.5 py-1.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors self-start sm:self-auto"
              >
                <span>{isBn ? BN_DICT['manage_in_curriculum'] : EN_DICT['manage_in_curriculum']}</span>
                <ExternalLink className="w-3.5 h-3.5" />
              </button>
            </div>

            {/* Class Pill Selector */}
            <div className="flex items-center gap-1.5 overflow-x-auto pb-1">
              <span className="text-xs font-semibold text-slate-500 shrink-0 mr-1">
                {isBn ? BN_DICT['select_class_2'] : EN_DICT['select_class_2']}
              </span>
              {(academicClasses || []).map(c => {
                const name = c.nameBn || c.name;
                const isSelected = previewClass === name;
                return (
                  <button
                    key={c.id}
                    onClick={() => setPreviewClass(name)}
                    className={`px-3 py-1 rounded-lg text-xs font-semibold transition-all shrink-0 ${
                      isSelected 
                        ? 'bg-indigo-600 text-white shadow-xs' 
                        : 'bg-white text-slate-700 hover:bg-slate-100 border border-slate-200'
                    }`}
                  >
                    {name}
                  </button>
                );
              })}
            </div>

            {/* Subjects Table Preview */}
            <div className="bg-white rounded-xl border border-slate-200 overflow-hidden">
              <div className="overflow-x-auto">
                <table className="w-full text-left text-xs text-slate-600">
                  <thead className="bg-slate-50 text-slate-700 uppercase font-semibold text-[11px] border-b border-slate-200">
                    <tr>
                      <th className="px-4 py-2.5">{isBn ? BN_DICT['code'] : EN_DICT['code']}</th>
                      <th className="px-4 py-2.5">{isBn ? BN_DICT['subject_name'] : EN_DICT['subject_name']}</th>
                      <th className="px-4 py-2.5">{isBn ? BN_DICT['group_2'] : EN_DICT['group_2']}</th>
                      <th className="px-4 py-2.5 text-center">{isBn ? BN_DICT['full_marks'] : EN_DICT['full_marks']}</th>
                      <th className="px-4 py-2.5 text-center">{isBn ? BN_DICT['pass_marks'] : EN_DICT['pass_marks']}</th>
                      <th className="px-4 py-2.5 text-center">{isBn ? BN_DICT['breakdown_cq_mcq_prac'] : EN_DICT['breakdown_cq_mcq_prac']}</th>
                    </tr>
                  </thead>
                  <tbody className="divide-y divide-slate-100">
                    {classSubjects.length === 0 ? (
                      <tr>
                        <td colSpan={6} className="px-4 py-6 text-center text-slate-400">
                          {isBn ? BN_DICT['no_subjects_configured_for_thi'] : EN_DICT['no_subjects_configured_for_thi']}
                        </td>
                      </tr>
                    ) : (
                      classSubjects.map(sub => (
                        <tr key={sub.id} className="hover:bg-slate-50/70 transition-colors">
                          <td className="px-4 py-2.5 font-mono font-bold text-indigo-700">{sub.code}</td>
                          <td className="px-4 py-2.5 font-semibold text-slate-800">
                            {isBn ? (sub.nameBn || sub.name) : sub.name}
                            {sub.isOptional && (
                              <span className="ml-1.5 text-[10px] px-1.5 py-0.5 rounded bg-amber-50 text-amber-700 font-semibold border border-amber-200">
                                {isBn ? BN_DICT['optional'] : EN_DICT['optional']}
                              </span>
                            )}
                          </td>
                          <td className="px-4 py-2.5 text-slate-500">{sub.groupName || 'সাধারণ'}</td>
                          <td className="px-4 py-2.5 text-center font-bold font-mono text-slate-800">{sub.fullMarks}</td>
                          <td className="px-4 py-2.5 text-center font-mono font-semibold text-rose-600">{sub.passMarks}</td>
                          <td className="px-4 py-2.5 text-center font-mono text-slate-600">
                            {sub.cqMarks || 0} / {sub.mcqMarks || 0} / {sub.practicalMarks || 0}
                          </td>
                        </tr>
                      ))
                    )}
                  </tbody>
                </table>
              </div>
            </div>
          </div>
        </div>
      )}

      {/* ================= TAB 2: GRADING POLICY ================= */}
      {activeTab === 'grading' && (
        <div className="space-y-6">
          <div className="bg-white p-5 rounded-xl border border-slate-200/80 shadow-xs flex flex-col sm:flex-row sm:items-center justify-between gap-4">
            <div>
              <h2 className="text-base font-bold text-slate-800 flex items-center gap-2">
                <Award className="w-5 h-5 text-indigo-600" />
                <span>{isBn ? BN_DICT['standard_bangladesh_board_grad'] : EN_DICT['standard_bangladesh_board_grad']}</span>
              </h2>
              <p className="text-xs text-slate-500 mt-0.5">
                {isBn ? BN_DICT['nctb_board_standardized_5_0_gp'] : EN_DICT['nctb_board_standardized_5_0_gp']}
              </p>
            </div>

            <button
              onClick={() => {
                if (confirm(isBn ? BN_DICT['reset_grading_scale_to_officia'] : EN_DICT['reset_grading_scale_to_officia'])) {
                  resetGradingRules();
                }
              }}
              className="px-3.5 py-1.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg text-xs font-semibold transition-colors self-start sm:self-auto"
            >
              {isBn ? BN_DICT['reset_to_defaults_1'] : EN_DICT['reset_to_defaults_1']}
            </button>
          </div>

          <div className="bg-white rounded-xl border border-slate-200/80 shadow-xs overflow-hidden">
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs text-slate-600">
                <thead className="bg-slate-50 text-slate-700 uppercase font-semibold text-[11px] border-b border-slate-200">
                  <tr>
                    <th className="px-5 py-3.5">{isBn ? BN_DICT['letter_grade'] : EN_DICT['letter_grade']}</th>
                    <th className="px-5 py-3.5">{isBn ? BN_DICT['grade_point_gpa'] : EN_DICT['grade_point_gpa']}</th>
                    <th className="px-5 py-3.5">{isBn ? BN_DICT['marks_range'] : EN_DICT['marks_range']}</th>
                    <th className="px-5 py-3.5">{isBn ? BN_DICT['performance'] : EN_DICT['performance']}</th>
                    <th className="px-5 py-3.5 text-center">{isBn ? BN_DICT['status'] : EN_DICT['status']}</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {(gradingRules || []).map((rule) => {
                    const isPass = rule.grade !== 'F';
                    return (
                      <tr key={rule.id} className="hover:bg-slate-50/80 transition-colors">
                        <td className="px-5 py-3.5 font-bold text-base text-slate-800 font-mono">
                          <span className={`inline-block px-2.5 py-0.5 rounded-md ${
                            rule.grade === 'A+' ? 'bg-emerald-100 text-emerald-800' :
                            rule.grade === 'A' ? 'bg-emerald-50 text-emerald-700' :
                            rule.grade === 'A-' ? 'bg-blue-50 text-blue-700' :
                            rule.grade === 'B' ? 'bg-cyan-50 text-cyan-700' :
                            rule.grade === 'C' ? 'bg-amber-50 text-amber-700' :
                            rule.grade === 'D' ? 'bg-orange-50 text-orange-700' :
                            'bg-rose-100 text-rose-800'
                          }`}>
                            {rule.grade}
                          </span>
                        </td>
                        <td className="px-5 py-3.5 font-mono font-bold text-slate-700 text-sm">
                          {rule.gpa.toFixed(2)}
                        </td>
                        <td className="px-5 py-3.5 font-mono font-semibold text-slate-700">
                          {rule.minMarks}% — {rule.maxMarks}%
                        </td>
                        <td className="px-5 py-3.5">
                          <div className="font-semibold text-slate-800">{isBn ? (rule.remarksBn || rule.remarks) : rule.remarks}</div>
                          <div className="text-[11px] text-slate-400">{isBn ? rule.remarks : rule.remarksBn}</div>
                        </td>
                        <td className="px-5 py-3.5 text-center">
                          {isPass ? (
                            <span className="px-2.5 py-1 rounded-full bg-emerald-50 text-emerald-700 text-[11px] font-semibold border border-emerald-200">
                              {isBn ? BN_DICT['passed'] : EN_DICT['passed']}
                            </span>
                          ) : (
                            <span className="px-2.5 py-1 rounded-full bg-rose-50 text-rose-700 text-[11px] font-semibold border border-rose-200">
                              {isBn ? BN_DICT['failed'] : EN_DICT['failed']}
                            </span>
                          )}
                        </td>
                      </tr>
                    );
                  })}
                </tbody>
              </table>
            </div>
          </div>
        </div>
      )}

      {/* ================= MODAL: ADD / EDIT EXAM TERM ================= */}
      {isTermModalOpen && (
        <div className="fixed inset-0 z-50 bg-slate-900/50 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-2xl max-w-md w-full p-6 shadow-xl border border-slate-200 space-y-4">
            <div className="flex items-center justify-between pb-3 border-b border-slate-100">
              <h3 className="font-bold text-slate-800 text-base">
                {editingTerm 
                  ? (isBn ? BN_DICT['edit_exam_term'] : EN_DICT['edit_exam_term']) 
                  : (isBn ? BN_DICT['add_new_exam_term'] : EN_DICT['add_new_exam_term'])}
              </h3>
              <button 
                onClick={() => setIsTermModalOpen(false)}
                className="text-slate-400 hover:text-slate-600 text-sm font-bold"
              >
                ✕
              </button>
            </div>

            <form onSubmit={handleSaveTerm} className="space-y-3.5 text-xs">
              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  {isBn ? BN_DICT['exam_name_bangla'] : EN_DICT['exam_name_bangla']}
                </label>
                <input
                  type="text"
                  required
                  placeholder="যেমন: অর্ধ-বার্ষিক পরীক্ষা ২০২৬"
                  value={termFormData.nameBn || ''}
                  onChange={(e) => setTermFormData({ ...termFormData, nameBn: e.target.value })}
                  className="w-full p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500 text-xs"
                />
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  {isBn ? BN_DICT['exam_name_english'] : EN_DICT['exam_name_english']}
                </label>
                <input
                  type="text"
                  placeholder="e.g. Half-Yearly Examination 2026"
                  value={termFormData.name || ''}
                  onChange={(e) => setTermFormData({ ...termFormData, name: e.target.value })}
                  className="w-full p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500 text-xs"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['academic_session_1'] : EN_DICT['academic_session_1']}
                  </label>
                  <select
                    value={termFormData.year || '2026'}
                    onChange={(e) => setTermFormData({ ...termFormData, year: e.target.value })}
                    className="w-full p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500 text-xs"
                  >
                    <option value="" disabled>{isBn ? BN_DICT['select_session'] : EN_DICT['select_session']}</option>
                    <option value="2026">2026</option>
                    {(academicSessions || []).map(s => <option key={s.id} value={s.name}>{s.name}</option>)}
                  </select>
                </div>
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['term_code'] : EN_DICT['term_code']}
                  </label>
                  <input
                    type="text"
                    value={termFormData.termCode || ''}
                    onChange={(e) => setTermFormData({ ...termFormData, termCode: e.target.value })}
                    placeholder="e.g. HALF-26"
                    className="w-full p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500 text-xs"
                  />
                </div>
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['start_date'] : EN_DICT['start_date']}
                  </label>
                  <input
                    type="date"
                    value={termFormData.startDate || ''}
                    onChange={(e) => setTermFormData({ ...termFormData, startDate: e.target.value })}
                    className="w-full p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500 text-xs"
                  />
                </div>
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['end_date'] : EN_DICT['end_date']}
                  </label>
                  <input
                    type="date"
                    value={termFormData.endDate || ''}
                    onChange={(e) => setTermFormData({ ...termFormData, endDate: e.target.value })}
                    className="w-full p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500 text-xs"
                  />
                </div>
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  {isBn ? BN_DICT['status'] : EN_DICT['status']}
                </label>
                <select
                  value={termFormData.status || 'upcoming'}
                  onChange={(e) => setTermFormData({ ...termFormData, status: e.target.value as any })}
                  className="w-full p-2.5 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500 text-xs"
                >
                  <option value="upcoming">{isBn ? BN_DICT['upcoming'] : EN_DICT['upcoming']}</option>
                  <option value="ongoing">{isBn ? BN_DICT['ongoing'] : EN_DICT['ongoing']}</option>
                  <option value="published">{isBn ? BN_DICT['published'] : EN_DICT['published']}</option>
                  <option value="archived">{isBn ? BN_DICT['archived'] : EN_DICT['archived']}</option>
                </select>
              </div>

              <div className="flex items-center gap-2 pt-1">
                <input
                  type="checkbox"
                  id="isDefaultTerm"
                  checked={!!termFormData.isDefault}
                  onChange={(e) => setTermFormData({ ...termFormData, isDefault: e.target.checked })}
                  className="w-4 h-4 rounded text-indigo-600 focus:ring-indigo-500 border-slate-300"
                />
                <label htmlFor="isDefaultTerm" className="font-semibold text-slate-700 cursor-pointer">
                  {isBn ? BN_DICT['set_as_current_active_exam'] : EN_DICT['set_as_current_active_exam']}
                </label>
              </div>

              <div className="pt-3 border-t border-slate-100 flex justify-end gap-2">
                <button
                  type="button"
                  onClick={() => setIsTermModalOpen(false)}
                  className="px-4 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg font-semibold"
                >
                  {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
                </button>
                <button
                  type="submit"
                  className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg font-semibold shadow-xs"
                >
                  {isBn ? BN_DICT['save'] : EN_DICT['save']}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};
export default ExamSettings;
