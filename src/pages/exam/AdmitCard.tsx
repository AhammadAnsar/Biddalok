import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useMemo } from 'react';
import { Link } from 'react-router-dom';
import { 
  IdCard, Printer, ArrowLeft, ChevronRight, Filter, 
  Settings, Users, CheckSquare, Square, Search, School,
  Sparkles, SlidersHorizontal, Eye
} from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';
import { Student } from '../../types';

export interface AdmitCardProps {
  initialClass?: string;
  initialSection?: string;
  initialExamId?: string;
  hideTopHeader?: boolean;
}

export const AdmitCard: React.FC<AdmitCardProps> = ({
  initialClass,
  initialSection,
  initialExamId,
  hideTopHeader = false
}) => {
  const { 
    language, institution, examTerms, academicClasses, 
    academicSections, academicGroups, students, subjects,
    admitCardSettings, updateAdmitCardSettings
  } = useAppStore();

  const isBn = language === 'bn';

  const defaultExamId = initialExamId || (examTerms || []).find(t => t.isDefault)?.id || (examTerms && examTerms[0]?.id) || 'term_2';
  const [selectedExamId, setSelectedExamId] = useState<string>(defaultExamId);
  const [selectedClass, setSelectedClass] = useState<string>(initialClass || 'all');
  const [selectedSection, setSelectedSection] = useState<string>(initialSection || 'all');
  const [searchQuery, setSearchQuery] = useState<string>('');
  
  const [selectedStudentIds, setSelectedStudentIds] = useState<string[]>([]);
  const [isSettingsOpen, setIsSettingsOpen] = useState(false);

  // Sync with props
  React.useEffect(() => {
    if (initialClass !== undefined) setSelectedClass(initialClass);
  }, [initialClass]);
  React.useEffect(() => {
    if (initialSection !== undefined) setSelectedSection(initialSection);
  }, [initialSection]);
  React.useEffect(() => {
    if (initialExamId !== undefined) setSelectedExamId(initialExamId);
  }, [initialExamId]);

  const selectedExam = (examTerms || []).find(t => t.id === selectedExamId);

  // Filter students
  const filteredStudents = useMemo(() => {
    return (students || []).filter(student => {
      const matchesClass = selectedClass === 'all' || student.class === selectedClass;
      const matchesSection = selectedSection === 'all' || student.section === selectedSection;
      const matchesSearch = !searchQuery || 
        student.name.toLowerCase().includes(searchQuery.toLowerCase()) ||
        (student.nameBn && student.nameBn.includes(searchQuery)) ||
        student.roll?.includes(searchQuery) ||
        student.studentId?.includes(searchQuery);
      return matchesClass && matchesSection && matchesSearch;
    });
  }, [students, selectedClass, selectedSection, searchQuery]);

  // Select all or none
  const handleToggleSelectAll = () => {
    if (selectedStudentIds.length === filteredStudents.length && filteredStudents.length > 0) {
      setSelectedStudentIds([]);
    } else {
      setSelectedStudentIds(filteredStudents.map(s => s.id));
    }
  };

  const handleToggleStudent = (id: string) => {
    setSelectedStudentIds(prev => 
      prev.includes(id) ? prev.filter(item => item !== id) : [...prev, id]
    );
  };

  const studentsToPrint = useMemo(() => {
    if (selectedStudentIds.length > 0) {
      return (students || []).filter(s => selectedStudentIds.includes(s.id));
    }
    return filteredStudents;
  }, [students, selectedStudentIds, filteredStudents]);

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6">
      {/* Top Header & Breadcrumb */}
      {!hideTopHeader ? (
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200 print:hidden">
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-xs text-slate-500">
              <Link to="/exam" className="hover:text-indigo-600 flex items-center gap-1 font-medium">
                <ArrowLeft className="w-3.5 h-3.5" />
                {isBn ? BN_DICT['exam_hub'] : EN_DICT['exam_hub']}
              </Link>
              <ChevronRight className="w-3.5 h-3.5 text-slate-300" />
              <span className="text-slate-700 font-semibold">{isBn ? BN_DICT['admit_card'] : EN_DICT['admit_card']}</span>
            </div>
            <h1 className="text-2xl font-bold text-slate-800 flex items-center gap-2.5">
              <IdCard className="w-6 h-6 text-indigo-600" />
              <span>{isBn ? BN_DICT['exam_admit_card_generator'] : EN_DICT['exam_admit_card_generator']}</span>
            </h1>
            <p className="text-xs sm:text-sm text-slate-500">
              {isBn ? BN_DICT['generate_and_batch_print_offic'] : EN_DICT['generate_and_batch_print_offic']}
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => setIsSettingsOpen(!isSettingsOpen)}
              className="px-3.5 py-2 rounded-lg text-xs font-semibold bg-white border border-slate-200 text-slate-700 hover:bg-slate-50 flex items-center gap-1.5"
            >
              <SlidersHorizontal className="w-4 h-4 text-slate-500" />
              <span>{isBn ? BN_DICT['card_settings'] : EN_DICT['card_settings']}</span>
            </button>

            <button
              onClick={handlePrint}
              disabled={studentsToPrint.length === 0}
              className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 disabled:opacity-50 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
            >
              <Printer className="w-4 h-4" />
              <span>
                {isBn 
                  ? `প্রিন্ট করুন (${studentsToPrint.length} জন)` 
                  : `Print Cards (${studentsToPrint.length})`}
              </span>
            </button>
          </div>
        </div>
      ) : (
        <div className="flex items-center justify-between pb-3 border-b border-slate-100 print:hidden">
          <span className="text-xs font-bold text-slate-600 uppercase tracking-wider">
            {isBn ? `প্রবেশপত্র প্রিভিউ (${studentsToPrint.length} জন শিক্ষার্থী)` : `Admit Cards Preview (${studentsToPrint.length} Students)`}
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={() => setIsSettingsOpen(!isSettingsOpen)}
              className="px-3 py-1.5 rounded-lg text-xs font-semibold bg-white border border-slate-200 text-slate-700 hover:bg-slate-50 flex items-center gap-1.5"
            >
              <SlidersHorizontal className="w-3.5 h-3.5 text-slate-500" />
              <span>{isBn ? BN_DICT['card_settings'] : EN_DICT['card_settings']}</span>
            </button>

            <button
              onClick={handlePrint}
              disabled={studentsToPrint.length === 0}
              className="px-3.5 py-1.5 bg-indigo-600 hover:bg-indigo-700 disabled:opacity-50 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>
                {isBn 
                  ? `প্রিন্ট প্রবেশপত্র (${studentsToPrint.length})` 
                  : `Print (${studentsToPrint.length})`}
              </span>
            </button>
          </div>
        </div>
      )}

      {/* Settings Drawer/Box */}
      {isSettingsOpen && (
        <div className="bg-indigo-50/70 p-4 rounded-xl border border-indigo-200 text-xs space-y-3 print:hidden">
          <div className="flex items-center justify-between font-bold text-slate-800">
            <span className="flex items-center gap-1.5">
              <Settings className="w-4 h-4 text-indigo-600" />
              {isBn ? BN_DICT['admit_card_settings'] : EN_DICT['admit_card_settings']}
            </span>
            <button 
              onClick={() => setIsSettingsOpen(false)}
              className="text-slate-400 hover:text-slate-600"
            >
              ✕
            </button>
          </div>

          <div className="grid grid-cols-1 sm:grid-cols-3 gap-3">
            <label className="flex items-center gap-2 cursor-pointer bg-white p-2.5 rounded-lg border border-slate-200">
              <input
                type="checkbox"
                checked={admitCardSettings?.showPhoto !== false}
                onChange={(e) => updateAdmitCardSettings({ showPhoto: e.target.checked })}
                className="w-4 h-4 rounded text-indigo-600"
              />
              <span className="font-semibold text-slate-700">{isBn ? BN_DICT['show_student_photo'] : EN_DICT['show_student_photo']}</span>
            </label>

            <label className="flex items-center gap-2 cursor-pointer bg-white p-2.5 rounded-lg border border-slate-200">
              <input
                type="checkbox"
                checked={admitCardSettings?.showQrCode !== false}
                onChange={(e) => updateAdmitCardSettings({ showQrCode: e.target.checked })}
                className="w-4 h-4 rounded text-indigo-600"
              />
              <span className="font-semibold text-slate-700">{isBn ? BN_DICT['show_verification_qr'] : EN_DICT['show_verification_qr']}</span>
            </label>

            <label className="flex items-center gap-2 cursor-pointer bg-white p-2.5 rounded-lg border border-slate-200">
              <input
                type="checkbox"
                checked={admitCardSettings?.showLogo !== false}
                onChange={(e) => updateAdmitCardSettings({ showLogo: e.target.checked })}
                className="w-4 h-4 rounded text-indigo-600"
              />
              <span className="font-semibold text-slate-700">{isBn ? BN_DICT['show_institution_logo'] : EN_DICT['show_institution_logo']}</span>
            </label>
          </div>
        </div>
      )}

      {/* Filter and Selection Bar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/80 shadow-xs space-y-3 print:hidden">
        <div className="grid grid-cols-1 sm:grid-cols-4 gap-3 text-xs">
          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['exam'] : EN_DICT['exam']}
            </label>
            <select
              value={selectedExamId}
              onChange={(e) => setSelectedExamId(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            >
              {(examTerms || []).map(t => (
                <option key={t.id} value={t.id}>{isBn ? (t.nameBn || t.name) : t.name} ({t.year})</option>
              ))}
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['class_1'] : EN_DICT['class_1']}
            </label>
            <select
              value={selectedClass}
              onChange={(e) => setSelectedClass(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            >
              <option value="all">{isBn ? BN_DICT['all_classes'] : EN_DICT['all_classes']}</option>
              {(academicClasses || []).map(c => (
                <option key={c.id} value={c.nameBn || c.name}>{c.nameBn || c.name}</option>
              ))}
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['section_1'] : EN_DICT['section_1']}
            </label>
            <select
              value={selectedSection}
              onChange={(e) => setSelectedSection(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            >
              <option value="all">{isBn ? BN_DICT['all_sections'] : EN_DICT['all_sections']}</option>
              {(academicSections || []).map(s => (
                <option key={s.id} value={s.nameBn || s.name}>{s.nameBn || s.name}</option>
              ))}
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['search'] : EN_DICT['search']}
            </label>
            <div className="relative">
              <Search className="w-3.5 h-3.5 text-slate-400 absolute left-2.5 top-1/2 -translate-y-1/2" />
              <input
                type="text"
                placeholder={isBn ? BN_DICT['name_or_roll'] : EN_DICT['name_or_roll']}
                value={searchQuery}
                onChange={(e) => setSearchQuery(e.target.value)}
                className="w-full pl-8 pr-2.5 py-2 bg-slate-50 border border-slate-200 rounded-lg"
              />
            </div>
          </div>
        </div>

        <div className="pt-2 border-t border-slate-100 flex items-center justify-between text-xs">
          <div className="flex items-center gap-2">
            <button
              onClick={handleToggleSelectAll}
              className="flex items-center gap-1.5 font-semibold text-indigo-600 hover:text-indigo-800"
            >
              {selectedStudentIds.length === filteredStudents.length && filteredStudents.length > 0 ? (
                <CheckSquare className="w-4 h-4" />
              ) : (
                <Square className="w-4 h-4" />
              )}
              <span>{isBn ? BN_DICT['select_all'] : EN_DICT['select_all']}</span>
            </button>
            <span className="text-slate-400">|</span>
            <span className="text-slate-500">
              {isBn 
                ? `মোট ${filteredStudents.length} জনের মধ্যে ${selectedStudentIds.length || filteredStudents.length} জনের কার্ড তৈরি হচ্ছে` 
                : `Ready to print ${selectedStudentIds.length || filteredStudents.length} of ${filteredStudents.length} students`}
            </span>
          </div>
        </div>
      </div>

      {/* Cards List / Print Sheet Layout */}
      {studentsToPrint.length === 0 ? (
        <div className="bg-white p-12 rounded-xl border border-slate-200 text-center space-y-3">
          <Users className="w-10 h-10 text-slate-300 mx-auto" />
          <div className="font-semibold text-slate-700 text-sm">
            {isBn ? BN_DICT['no_students_found_matching_fil'] : EN_DICT['no_students_found_matching_fil']}
          </div>
          <p className="text-xs text-slate-500">
            {isBn ? BN_DICT['change_class_or_section_filter'] : EN_DICT['change_class_or_section_filter']}
          </p>
        </div>
      ) : (
        <div className="grid grid-cols-1 lg:grid-cols-2 gap-6 print:grid-cols-1 print:gap-4">
          {studentsToPrint.map((student) => (
            <div
              key={student.id}
              className="bg-white rounded-xl border-2 border-slate-800 p-5 shadow-sm print:shadow-none print:break-inside-avoid relative flex flex-col justify-between"
              style={{ minHeight: '340px' }}
            >
              {/* Header Box */}
              <div className="space-y-1 text-center border-b-2 border-slate-800 pb-3">
                <div className="flex items-center justify-between">
                  <div className="w-12 h-12 flex items-center justify-center">
                    {admitCardSettings?.showLogo !== false && institution?.logoUrl ? (
                      <img src={institution.logoUrl} alt="Logo" className="w-10 h-10 object-contain" />
                    ) : (
                      <School className="w-8 h-8 text-slate-700" />
                    )}
                  </div>

                  <div className="flex-1 px-2 text-center">
                    <h3 className="font-bold text-sm sm:text-base uppercase tracking-wide text-slate-900 leading-tight">
                      {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয়ের নাম') : (institution?.name || 'INSTITUTION NAME')}
                    </h3>
                    <p className="text-[10px] text-slate-600">
                      {isBn ? (institution?.addressBn || institution?.address || '') : (institution?.address || '')}
                      {institution?.eiin && ` | EIIN: ${institution.eiin}`}
                    </p>
                    <div className="inline-block mt-1 px-3 py-0.5 bg-slate-900 text-white rounded-full font-bold text-[10px] uppercase tracking-wider">
                      {isBn ? BN_DICT['admit_card_1'] : EN_DICT['admit_card_1']}
                    </div>
                  </div>

                  {/* QR or Placeholder Box */}
                  <div className="w-12 h-12 border border-slate-300 rounded flex items-center justify-center bg-slate-50 text-[8px] font-mono text-slate-500">
                    QR CODE
                  </div>
                </div>

                <div className="text-xs font-bold text-slate-800 pt-1">
                  {isBn ? (selectedExam?.nameBn || selectedExam?.name) : selectedExam?.name} - {selectedExam?.year || '2026'}
                </div>
              </div>

              {/* Student Details with Photo */}
              <div className="py-3 flex items-start gap-4">
                <div className="flex-1 grid grid-cols-2 gap-x-3 gap-y-1.5 text-xs text-slate-800">
                  <div>
                    <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['student_name_1'] : EN_DICT['student_name_1']}</span>
                    <span className="font-bold">{isBn ? (student.nameBn || student.name) : student.name}</span>
                  </div>

                  <div>
                    <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['student_id_1'] : EN_DICT['student_id_1']}</span>
                    <span className="font-mono font-semibold">{student.studentId || 'N/A'}</span>
                  </div>

                  <div>
                    <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['class_section'] : EN_DICT['class_section']}</span>
                    <span className="font-semibold">{student.class} ({student.section || 'N/A'})</span>
                  </div>

                  <div>
                    <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['roll_no'] : EN_DICT['roll_no']}</span>
                    <span className="font-mono font-bold text-sm text-indigo-950">{student.roll || '—'}</span>
                  </div>

                  <div>
                    <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['group_1'] : EN_DICT['group_1']}</span>
                    <span className="font-semibold">{student.group || 'সাধারণ'}</span>
                  </div>

                  <div>
                    <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['academic_year_2'] : EN_DICT['academic_year_2']}</span>
                    <span className="font-semibold">{student.session || '2026'}</span>
                  </div>
                </div>

                {/* Photo box */}
                {admitCardSettings?.showPhoto !== false && (
                  <div className="w-20 h-24 border-2 border-slate-400 rounded-md overflow-hidden bg-slate-50 flex items-center justify-center shrink-0">
                    {student.photo ? (
                      <img src={student.photo} alt={student.name} className="w-full h-full object-cover" />
                    ) : (
                      <div className="text-center p-1 text-[9px] text-slate-400 font-semibold uppercase">
                        {isBn ? BN_DICT['photo'] : EN_DICT['photo']}
                      </div>
                    )}
                  </div>
                )}
              </div>

              {/* Instructions */}
              <div className="bg-slate-50 p-2 rounded border border-slate-200 text-[10px] text-slate-600 space-y-0.5">
                <div className="font-bold text-slate-800 text-[10px]">{isBn ? BN_DICT['instructions'] : EN_DICT['instructions']}</div>
                <div>১. পরীক্ষা শুরুর ১৫ মিনিট আগে হলে উপস্থিত থাকতে হবে। ২. প্রবেশপত্র প্রদর্শন বাধ্যতামূলক।</div>
              </div>

              {/* Signatures */}
              <div className="pt-8 grid grid-cols-2 text-[11px] font-semibold">
                <div className="text-left">
                  <div className="w-28 border-b border-slate-700"></div>
                  <div className="mt-1 text-slate-700">{isBn ? BN_DICT['class_teacher'] : EN_DICT['class_teacher']}</div>
                </div>
                <div className="text-right flex flex-col items-end justify-end">
                  {institution?.headmasterSignature ? (
                    <img 
                      src={institution.headmasterSignature} 
                      alt="Principal Signature" 
                      className="h-8 max-w-[120px] object-contain ml-auto -mb-1"
                    />
                  ) : null}
                  <div className="w-28 border-b border-slate-700 ml-auto"></div>
                  <div className="mt-1 text-slate-700">
                    {isBn ? (institution?.headmasterTitleBn || 'প্রধান শিক্ষক') : (institution?.headmasterTitle || 'Headmaster')}
                  </div>
                </div>
              </div>
            </div>
          ))}
        </div>
      )}
    </div>
  );
};

export default AdmitCard;
