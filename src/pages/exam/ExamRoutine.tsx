import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState } from 'react';
import { Link } from 'react-router-dom';
import { 
  Calendar, Plus, Edit2, Trash2, Printer, 
  ArrowLeft, ChevronRight, Clock, MapPin, 
  FileText, CheckCircle, School, Share2
} from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';
import { ExamRoutineItem } from '../../types';

export interface ExamRoutineProps {
  initialClass?: string;
  initialExamId?: string;
  hideTopHeader?: boolean;
}

export const ExamRoutine: React.FC<ExamRoutineProps> = ({
  initialClass,
  initialExamId,
  hideTopHeader = false
}) => {
  const { 
    language, institution, examTerms, academicClasses, 
    examRoutines, addExamRoutine, updateExamRoutine, deleteExamRoutine,
    subjects, rooms, staff } = useAppStore();

  const isBn = language === 'bn';

  const defaultExamId = initialExamId || (examTerms || []).find(t => t.isDefault)?.id || (examTerms && examTerms[0]?.id) || 'term_2';
  const [selectedExamId, setSelectedExamId] = useState<string>(defaultExamId);
  const [selectedClass, setSelectedClass] = useState<string>(
    initialClass || (academicClasses && academicClasses.length > 0 ? (academicClasses[0].nameBn || academicClasses[0].name) : '১০ম শ্রেণি')
  );

  // Sync props
  React.useEffect(() => {
    if (initialClass !== undefined) setSelectedClass(initialClass);
  }, [initialClass]);
  React.useEffect(() => {
    if (initialExamId !== undefined) setSelectedExamId(initialExamId);
  }, [initialExamId]);

  const selectedExam = (examTerms || []).find(t => t.id === selectedExamId);

  const [isModalOpen, setIsModalOpen] = useState(false);
  const [editingRoutine, setEditingRoutine] = useState<ExamRoutineItem | null>(null);
  const [formData, setFormData] = useState<Partial<ExamRoutineItem>>({
    examId: selectedExamId,
    className: selectedClass,
    subjectName: '',
    subjectCode: '',
    examDate: '',
    dayName: '',
    startTime: '10:00 AM',
    endTime: '01:00 PM',
    roomId: '', invigilatorId: ''
  });

  const [printMode, setPrintMode] = useState(false);

  const classRoutines = (examRoutines || [])
    .filter(r => (r.examId === selectedExamId || !r.examId) && r.className === selectedClass)
    .sort((a, b) => new Date(a.examDate).getTime() - new Date(b.examDate).getTime());

  const availableSubjectsForClass = (subjects || []).filter(s => s.className === selectedClass);

  const getDayNameFromDate = (dateStr: string) => {
    if (!dateStr) return '';
    const date = new Date(dateStr);
    const daysEn = ['Sunday', 'Monday', 'Tuesday', 'Wednesday', 'Thursday', 'Friday', 'Saturday'];
    const daysBn = ['রবিবার', 'সোমবার', 'মঙ্গলবার', 'বুধবার', 'বৃহস্পতিবার', 'শুক্রবার', 'শনিবার'];
    const dayIdx = date.getDay();
    return isBn ? daysBn[dayIdx] : daysEn[dayIdx];
  };

  const handleOpenModal = (routine?: ExamRoutineItem) => {
    if (routine) {
      setEditingRoutine(routine);
      setFormData(routine);
    } else {
      setEditingRoutine(null);
      const today = new Date().toISOString().split('T')[0];
      setFormData({
        examId: selectedExamId,
        className: selectedClass,
        subjectName: availableSubjectsForClass[0] ? (availableSubjectsForClass[0].nameBn || availableSubjectsForClass[0].name) : '',
        subjectCode: availableSubjectsForClass[0] ? availableSubjectsForClass[0].code : '',
        examDate: today,
        dayName: getDayNameFromDate(today),
        startTime: '10:00 AM',
        endTime: '01:00 PM',
        roomId: '', invigilatorId: ''
      });
    }
    setIsModalOpen(true);
  };

  const handleSaveRoutine = (e: React.FormEvent) => {
    e.preventDefault();
    if (!formData.subjectName || !formData.examDate) return;

    if (editingRoutine) {
      updateExamRoutine(editingRoutine.id, formData);
    } else {
      const newRoutine: ExamRoutineItem = {
        id: `rt_${Date.now()}`,
        examId: selectedExamId,
        className: selectedClass,
        subjectName: formData.subjectName,
        subjectCode: formData.subjectCode,
        examDate: formData.examDate || '',
        dayName: formData.dayName || getDayNameFromDate(formData.examDate || ''),
        startTime: formData.startTime || '10:00 AM',
        endTime: formData.endTime || '01:00 PM',
        roomId: formData.roomId, roomName: rooms.find(r => r.id === formData.roomId)?.name || formData.roomId, invigilatorId: formData.invigilatorId, invigilatorName: staff.find(s => s.id === formData.invigilatorId)?.name || formData.invigilatorId, roomNo: formData.roomNo
      };
      addExamRoutine(newRoutine);
    }
    setIsModalOpen(false);
  };

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6">
      {/* Top Header & Breadcrumb */}
      {!hideTopHeader ? (
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200 print:hidden">
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-xs text-slate-500">
              <Link to="/exam" className="hover:text-indigo-600 flex items-center gap-1 font-medium">
                <ArrowLeft className="w-3.5 h-3.5" />
                {isBn ? BN_DICT['exam_hub'] : EN_DICT['exam_hub']}
              </Link>
              <ChevronRight className="w-3.5 h-3.5 text-slate-300" />
              <span className="text-slate-700 font-semibold">{isBn ? BN_DICT['exam_routine'] : EN_DICT['exam_routine']}</span>
            </div>
            <h1 className="text-2xl font-bold text-slate-800 flex items-center gap-2.5">
              <Calendar className="w-6 h-6 text-indigo-600" />
              <span>{isBn ? BN_DICT['examination_timetable_routine'] : EN_DICT['examination_timetable_routine']}</span>
            </h1>
            <p className="text-xs sm:text-sm text-slate-500">
              {isBn ? BN_DICT['create_exam_schedule_by_date_t'] : EN_DICT['create_exam_schedule_by_date_t']}
            </p>
          </div>

          <div className="flex items-center gap-2">
            <button
              onClick={() => setPrintMode(!printMode)}
              className={`px-3.5 py-2 rounded-lg text-xs font-semibold border transition-all flex items-center gap-1.5 ${
                printMode 
                  ? 'bg-indigo-50 border-indigo-300 text-indigo-700' 
                  : 'bg-white border-slate-200 text-slate-700 hover:bg-slate-50'
              }`}
            >
              <FileText className="w-4 h-4" />
              <span>{printMode ? (isBn ? BN_DICT['table_view'] : EN_DICT['table_view']) : (isBn ? BN_DICT['official_notice_sheet'] : EN_DICT['official_notice_sheet'])}</span>
            </button>

            <button
              onClick={handlePrint}
              className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
            >
              <Printer className="w-4 h-4" />
              <span>{isBn ? BN_DICT['print_routine'] : EN_DICT['print_routine']}</span>
            </button>
          </div>
        </div>
      ) : (
        <div className="flex items-center justify-between pb-3 border-b border-slate-100 print:hidden">
          <span className="text-xs font-bold text-slate-600 uppercase tracking-wider">
            {isBn ? `শ্রেণির পরীক্ষার রুটিন (${selectedClass})` : `Class Exam Routine (${selectedClass})`}
          </span>
          <div className="flex items-center gap-2">
            <button
              onClick={() => setPrintMode(!printMode)}
              className={`px-3 py-1.5 rounded-lg text-xs font-semibold border transition-all flex items-center gap-1.5 ${
                printMode 
                  ? 'bg-indigo-50 border-indigo-300 text-indigo-700' 
                  : 'bg-white border-slate-200 text-slate-700 hover:bg-slate-50'
              }`}
            >
              <FileText className="w-3.5 h-3.5" />
              <span>{printMode ? (isBn ? BN_DICT['table'] : EN_DICT['table']) : (isBn ? BN_DICT['notice_view'] : EN_DICT['notice_view'])}</span>
            </button>

            <button
              onClick={handlePrint}
              className="px-3.5 py-1.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>{isBn ? BN_DICT['print'] : EN_DICT['print']}</span>
            </button>
          </div>
        </div>
      )}

      {/* Selectors Bar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/80 shadow-xs space-y-4 print:hidden">
        <div className="grid grid-cols-1 sm:grid-cols-2 gap-4">
          <div>
            <label className="text-xs font-semibold text-slate-600 uppercase tracking-wider block mb-1.5">
              {isBn ? BN_DICT['select_examination'] : EN_DICT['select_examination']}
            </label>
            <select
              value={selectedExamId}
              onChange={(e) => setSelectedExamId(e.target.value)}
              className="w-full text-xs font-semibold bg-slate-50 border border-slate-200 rounded-lg p-2.5 text-slate-800 focus:outline-hidden focus:border-indigo-500"
            >
              {(examTerms || []).map(term => (
                <option key={term.id} value={term.id}>
                  {isBn ? (term.nameBn || term.name) : term.name} ({term.year})
                </option>
              ))}
            </select>
          </div>

          <div>
            <label className="text-xs font-semibold text-slate-600 uppercase tracking-wider block mb-1.5">
              {isBn ? BN_DICT['select_class_2'] : EN_DICT['select_class_2']}
            </label>
            <div className="flex flex-wrap gap-1.5">
              {(academicClasses || []).map((cls) => {
                const clsName = cls.nameBn || cls.name;
                const isSelected = selectedClass === clsName;
                return (
                  <button
                    key={cls.id}
                    onClick={() => setSelectedClass(clsName)}
                    className={`px-3 py-1.5 rounded-lg text-xs font-semibold transition-all ${
                      isSelected
                        ? 'bg-indigo-600 text-white shadow-xs'
                        : 'bg-slate-100 text-slate-600 hover:bg-slate-200'
                    }`}
                  >
                    {clsName}
                  </button>
                );
              })}
            </div>
          </div>
        </div>

        <div className="pt-3 border-t border-slate-100 flex items-center justify-between">
          <div className="text-xs text-slate-500">
            {isBn 
              ? `${selectedClass} - মোট ${classRoutines.length}টি পরীক্ষা তালিকাভুক্ত` 
              : `${selectedClass} - ${classRoutines.length} exam slots scheduled`}
          </div>
          <button
            onClick={() => handleOpenModal()}
            className="inline-flex items-center gap-1.5 px-3.5 py-1.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs"
          >
            <Plus className="w-3.5 h-3.5" />
            <span>{isBn ? BN_DICT['add_subject_slot'] : EN_DICT['add_subject_slot']}</span>
          </button>
        </div>
      </div>

      {/* Routine Content: Table View OR Official Notice View */}
      {!printMode ? (
        <div className="bg-white rounded-xl border border-slate-200/80 shadow-xs overflow-hidden print:border-none print:shadow-none">
          <div className="px-5 py-3.5 bg-slate-50/70 border-b border-slate-200/80 flex items-center justify-between">
            <span className="font-bold text-slate-800 text-sm">
              {isBn ? (selectedExam?.nameBn || selectedExam?.name) : selectedExam?.name} — {selectedClass}
            </span>
            <span className="text-xs text-slate-500 font-mono">
              {isBn ? `সেশন: ${selectedExam?.year || '2026'}` : `Session: ${selectedExam?.year || '2026'}`}
            </span>
          </div>

          {classRoutines.length === 0 ? (
            <div className="p-12 text-center space-y-3">
              <Calendar className="w-10 h-10 text-slate-300 mx-auto" />
              <div className="text-sm font-semibold text-slate-700">
                {isBn ? BN_DICT['no_routine_scheduled_for_this'] : EN_DICT['no_routine_scheduled_for_this']}
              </div>
              <p className="text-xs text-slate-500 max-w-sm mx-auto">
                {isBn ? BN_DICT['click_the_button_above_to_add'] : EN_DICT['click_the_button_above_to_add']}
              </p>
              <button
                onClick={() => handleOpenModal()}
                className="px-4 py-2 text-xs font-semibold bg-indigo-600 text-white rounded-lg hover:bg-indigo-700"
              >
                {isBn ? BN_DICT['add_first_schedule'] : EN_DICT['add_first_schedule']}
              </button>
            </div>
          ) : (
            <div className="overflow-x-auto">
              <table className="w-full text-left text-xs text-slate-600">
                <thead className="bg-slate-50 text-slate-700 uppercase font-semibold text-[11px] border-b border-slate-200">
                  <tr>
                    <th className="px-4 py-3">{isBn ? BN_DICT['sl'] : EN_DICT['sl']}</th>
                    <th className="px-4 py-3">{isBn ? BN_DICT['date_day'] : EN_DICT['date_day']}</th>
                    <th className="px-4 py-3">{isBn ? BN_DICT['time'] : EN_DICT['time']}</th>
                    <th className="px-4 py-3">{isBn ? BN_DICT['code'] : EN_DICT['code']}</th>
                    <th className="px-4 py-3">{isBn ? BN_DICT['subject'] : EN_DICT['subject']}</th>
                    <th className="px-4 py-3">{isBn ? BN_DICT['room_hall'] : EN_DICT['room_hall']}</th>
                    <th className="px-4 py-3 text-right print:hidden">{isBn ? BN_DICT['actions'] : EN_DICT['actions']}</th>
                  </tr>
                </thead>
                <tbody className="divide-y divide-slate-100">
                  {classRoutines.map((item, idx) => (
                    <tr key={item.id} className="hover:bg-slate-50/80 transition-colors">
                      <td className="px-4 py-3.5 font-mono text-slate-400">{idx + 1}</td>
                      <td className="px-4 py-3.5">
                        <div className="font-bold text-slate-800">{item.examDate}</div>
                        <div className="text-[11px] text-slate-400 font-medium">{item.dayName || getDayNameFromDate(item.examDate)}</div>
                      </td>
                      <td className="px-4 py-3.5">
                        <div className="inline-flex items-center gap-1 px-2 py-0.5 rounded bg-slate-100 text-slate-700 font-mono text-[11px] font-semibold">
                          <Clock className="w-3 h-3 text-slate-400" />
                          <span>{item.startTime} — {item.endTime}</span>
                        </div>
                      </td>
                      <td className="px-4 py-3.5 font-mono font-semibold text-slate-700">{item.subjectCode || '—'}</td>
                      <td className="px-4 py-3.5 font-semibold text-slate-900 text-sm">{item.subjectName}</td>
                      <td className="px-4 py-3.5">
                        <span className="text-xs text-slate-600 flex items-center gap-1">
                          <MapPin className="w-3 h-3 text-slate-400" />
                          {item.roomName || item.roomNo || 'Hall 1'}{item.invigilatorName ? ` - Inv: ${item.invigilatorName}` : ''}
                        </span>
                      </td>
                      <td className="px-4 py-3.5 text-right print:hidden">
                        <div className="flex items-center justify-end gap-1">
                          <button
                            onClick={() => handleOpenModal(item)}
                            className="p-1.5 text-slate-400 hover:text-indigo-600 rounded-lg hover:bg-slate-100"
                            title={isBn ? BN_DICT['edit'] : EN_DICT['edit']}
                          >
                            <Edit2 className="w-3.5 h-3.5" />
                          </button>
                          <button
                            onClick={() => {
                              if (confirm(isBn ? BN_DICT['delete_this_schedule_entry'] : EN_DICT['delete_this_schedule_entry'])) {
                                deleteExamRoutine(item.id);
                              }
                            }}
                            className="p-1.5 text-slate-400 hover:text-rose-600 rounded-lg hover:bg-slate-100"
                            title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
                          >
                            <Trash2 className="w-3.5 h-3.5" />
                          </button>
                        </div>
                      </td>
                    </tr>
                  ))}
                </tbody>
              </table>
            </div>
          )}
        </div>
      ) : (
        /* Official Printable Notice Sheet */
        <div className="bg-white p-8 sm:p-12 rounded-xl border border-slate-200 shadow-sm max-w-4xl mx-auto text-slate-900 font-sans print:p-0 print:border-none print:shadow-none">
          {/* Header */}
          <div className="text-center space-y-1 pb-6 border-b-2 border-slate-800">
            {institution?.logoUrl && (
              <img src={institution.logoUrl} alt="Logo" className="w-14 h-14 object-contain mx-auto mb-2" />
            )}
            <h2 className="text-2xl font-bold uppercase tracking-wide">
              {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয় / প্রতিষ্ঠানের নাম') : (institution?.name || 'INSTITUTION NAME')}
            </h2>
            <p className="text-xs text-slate-600">
              {isBn ? (institution?.addressBn || institution?.address || '') : (institution?.address || '')}
              {institution?.eiin && ` | EIIN: ${institution.eiin}`}
            </p>
            <div className="inline-block mt-3 px-4 py-1 bg-slate-900 text-white rounded-full font-bold text-xs uppercase tracking-wider">
              {isBn ? (selectedExam?.nameBn || selectedExam?.name) : selectedExam?.name} - {isBn ? BN_DICT['examination_timetable'] : EN_DICT['examination_timetable']}
            </div>
            <div className="text-xs font-semibold text-slate-700 pt-1">
              {isBn ? `শ্রেণি: ${selectedClass} | শিক্ষাবর্ষ: ${selectedExam?.year || '2026'}` : `Class: ${selectedClass} | Session: ${selectedExam?.year || '2026'}`}
            </div>
          </div>

          {/* Table */}
          <div className="mt-6">
            <table className="w-full border-collapse border border-slate-800 text-xs">
              <thead>
                <tr className="bg-slate-100 text-slate-900 font-bold border-b border-slate-800">
                  <th className="border border-slate-800 p-2 text-center w-12">{isBn ? BN_DICT['sl'] : EN_DICT['sl']}</th>
                  <th className="border border-slate-800 p-2 text-left">{isBn ? BN_DICT['date_day'] : EN_DICT['date_day']}</th>
                  <th className="border border-slate-800 p-2 text-left">{isBn ? BN_DICT['time'] : EN_DICT['time']}</th>
                  <th className="border border-slate-800 p-2 text-center w-16">{isBn ? BN_DICT['code'] : EN_DICT['code']}</th>
                  <th className="border border-slate-800 p-2 text-left">{isBn ? BN_DICT['subject'] : EN_DICT['subject']}</th>
                  <th className="border border-slate-800 p-2 text-left">{isBn ? BN_DICT['exam_room'] : EN_DICT['exam_room']}</th>
                </tr>
              </thead>
              <tbody>
                {classRoutines.map((item, idx) => (
                  <tr key={item.id} className="border-b border-slate-800">
                    <td className="border border-slate-800 p-2 text-center font-mono">{idx + 1}</td>
                    <td className="border border-slate-800 p-2 font-semibold">
                      {item.examDate} ({item.dayName || getDayNameFromDate(item.examDate)})
                    </td>
                    <td className="border border-slate-800 p-2 font-mono">{item.startTime} — {item.endTime}</td>
                    <td className="border border-slate-800 p-2 text-center font-mono">{item.subjectCode || '—'}</td>
                    <td className="border border-slate-800 p-2 font-bold">{item.subjectName}</td>
                    <td className="border border-slate-800 p-2">{item.roomName || item.roomNo || 'Hall 1'}{item.invigilatorName ? ` - Inv: ${item.invigilatorName}` : ''}</td>
                  </tr>
                ))}
              </tbody>
            </table>
          </div>

          {/* Special Instructions */}
          <div className="mt-6 p-4 bg-slate-50 border border-slate-200 rounded-lg text-xs space-y-1.5">
            <div className="font-bold text-slate-800">{isBn ? BN_DICT['important_instructions'] : EN_DICT['important_instructions']}</div>
            <ul className="list-disc list-inside space-y-1 text-slate-600 text-[11px]">
              <li>{isBn ? BN_DICT['students_must_enter_the_exam_h'] : EN_DICT['students_must_enter_the_exam_h']}</li>
              <li>{isBn ? BN_DICT['admit_card_is_strictly_mandato'] : EN_DICT['admit_card_is_strictly_mandato']}</li>
              <li>{isBn ? BN_DICT['mobile_phones_and_electronic_g'] : EN_DICT['mobile_phones_and_electronic_g']}</li>
            </ul>
          </div>

          {/* Signatures */}
          <div className="mt-16 pt-4 grid grid-cols-2 text-xs font-semibold">
            <div className="text-left space-y-1">
              <div className="w-36 border-b border-slate-800"></div>
              <div>{isBn ? BN_DICT['convener_exam_committee'] : EN_DICT['convener_exam_committee']}</div>
            </div>
            <div className="text-right space-y-1 flex flex-col items-end justify-end">
              {institution?.headmasterSignature ? (
                <img 
                  src={institution.headmasterSignature} 
                  alt="Principal Signature" 
                  className="h-9 max-w-[140px] object-contain ml-auto -mb-1"
                />
              ) : null}
              <div className="w-36 border-b border-slate-800 ml-auto"></div>
              <div>{isBn ? (institution?.headmasterTitleBn || 'প্রধান শিক্ষক / অধ্যক্ষ') : (institution?.headmasterTitle || 'Principal / Headmaster')}</div>
            </div>
          </div>
        </div>
      )}

      {/* ================= MODAL: ADD / EDIT ROUTINE SLOT ================= */}
      {isModalOpen && (
        <div className="fixed inset-0 z-50 bg-slate-900/50 backdrop-blur-xs flex items-center justify-center p-4">
          <div className="bg-white rounded-2xl max-w-md w-full p-6 shadow-xl border border-slate-200 space-y-4">
            <div className="flex items-center justify-between pb-3 border-b border-slate-100">
              <h3 className="font-bold text-slate-800 text-base">
                {editingRoutine 
                  ? (isBn ? BN_DICT['edit_schedule_slot'] : EN_DICT['edit_schedule_slot']) 
                  : (isBn ? `নতুন বিষয় সময়সূচি যোগ (${selectedClass})` : `Add Schedule Slot (${selectedClass})`)}
              </h3>
              <button 
                onClick={() => setIsModalOpen(false)}
                className="text-slate-400 hover:text-slate-600 text-sm font-bold"
              >
                ✕
              </button>
            </div>

            <form onSubmit={handleSaveRoutine} className="space-y-3.5 text-xs">
              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  {isBn ? BN_DICT['subject_selection'] : EN_DICT['subject_selection']}
                </label>
                <div className="space-y-1.5">
                  <select
                    onChange={(e) => {
                      const selected = availableSubjectsForClass.find(s => s.id === e.target.value);
                      if (selected) {
                        setFormData({
                          ...formData,
                          subjectName: isBn ? (selected.nameBn || selected.name) : selected.name,
                          subjectCode: selected.code
                        });
                      }
                    }}
                    className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500"
                  >
                    <option value="">-- {isBn ? BN_DICT['pick_from_configured_subjects'] : EN_DICT['pick_from_configured_subjects']} --</option>
                    {availableSubjectsForClass.map(s => (
                      <option key={s.id} value={s.id}>
                        {s.code} - {isBn ? (s.nameBn || s.name) : s.name}
                      </option>
                    ))}
                  </select>

                  <input
                    type="text"
                    required
                    placeholder={isBn ? BN_DICT['or_type_subject_name'] : EN_DICT['or_type_subject_name']}
                    value={formData.subjectName || ''}
                    onChange={(e) => setFormData({ ...formData, subjectName: e.target.value })}
                    className="w-full p-2 bg-white border border-slate-200 rounded-lg text-slate-800 focus:outline-hidden focus:border-indigo-500"
                  />
                </div>
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['subject_code_1'] : EN_DICT['subject_code_1']}
                  </label>
                  <input
                    type="text"
                    value={formData.subjectCode || ''}
                    onChange={(e) => setFormData({ ...formData, subjectCode: e.target.value })}
                    placeholder="e.g. 101"
                    className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg font-mono"
                  />
                </div>
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['room_hall'] : EN_DICT['room_hall']}
                  </label>
                  <input
                    type="text"
                    value={formData.roomNo || ''}
                    onChange={(e) => setFormData({ ...formData, roomNo: e.target.value })}
                    placeholder="e.g. Room 101, 102"
                    className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg"
                  />
                </div>
              </div>

              <div>
                <label className="block font-semibold text-slate-700 mb-1">
                  {isBn ? BN_DICT['exam_date'] : EN_DICT['exam_date']}
                </label>
                <input
                  type="date"
                  required
                  value={formData.examDate || ''}
                  onChange={(e) => {
                    const dateVal = e.target.value;
                    setFormData({
                      ...formData,
                      examDate: dateVal,
                      dayName: getDayNameFromDate(dateVal)
                    });
                  }}
                  className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg"
                />
              </div>

              <div className="grid grid-cols-2 gap-3">
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['start_time'] : EN_DICT['start_time']}
                  </label>
                  <input
                    type="text"
                    value={formData.startTime || '10:00 AM'}
                    onChange={(e) => setFormData({ ...formData, startTime: e.target.value })}
                    placeholder="10:00 AM"
                    className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg font-mono"
                  />
                </div>
                <div>
                  <label className="block font-semibold text-slate-700 mb-1">
                    {isBn ? BN_DICT['end_time'] : EN_DICT['end_time']}
                  </label>
                  <input
                    type="text"
                    value={formData.endTime || '01:00 PM'}
                    onChange={(e) => setFormData({ ...formData, endTime: e.target.value })}
                    placeholder="01:00 PM"
                    className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg font-mono"
                  />
                </div>
              </div>

              <div className="pt-3 border-t border-slate-100 flex justify-end gap-2">
                <button
                  type="button"
                  onClick={() => setIsModalOpen(false)}
                  className="px-4 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-lg font-semibold"
                >
                  {isBn ? BN_DICT['cancel'] : EN_DICT['cancel']}
                </button>
                <button
                  type="submit"
                  className="px-5 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg font-semibold shadow-xs"
                >
                  {isBn ? BN_DICT['save_slot'] : EN_DICT['save_slot']}
                </button>
              </div>
            </form>
          </div>
        </div>
      )}
    </div>
  );
};

export default ExamRoutine;
