import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useMemo } from 'react';
import { Link } from 'react-router-dom';
import { 
  LayoutGrid, Printer, ArrowLeft, ChevronRight, 
  MapPin, Users, Sparkles, RefreshCw, SlidersHorizontal,
  School, CheckCircle2, Bookmark
} from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';

interface SeatAllocation {
  benchNumber: number;
  seatPosition: 'Left' | 'Right' | 'Center';
  studentId: string;
  studentName: string;
  studentNameBn?: string;
  roll: string;
  className: string;
  section?: string;
  roomNo: string;
}

export interface SeatPlanningProps {
  initialClass?: string;
  initialExamId?: string;
  hideTopHeader?: boolean;
}

export const SeatPlanning: React.FC<SeatPlanningProps> = ({
  initialClass,
  initialExamId,
  hideTopHeader = false
}) => {
  const { 
    language, institution, examTerms, academicClasses, 
    academicSections, students 
  } = useAppStore();

  const isBn = language === 'bn';

  const defaultExamId = initialExamId || (examTerms || []).find(t => t.isDefault)?.id || (examTerms && examTerms[0]?.id) || 'term_2';
  const [selectedExamId, setSelectedExamId] = useState<string>(defaultExamId);
  const [selectedRoom, setSelectedRoom] = useState<string>('Room 101');
  const [selectedClass1, setSelectedClass1] = useState<string>(
    initialClass || (academicClasses && academicClasses[0] ? (academicClasses[0].nameBn || academicClasses[0].name) : '৯ম শ্রেণি')
  );
  const [selectedClass2, setSelectedClass2] = useState<string>(
    academicClasses && academicClasses[1] ? (academicClasses[1].nameBn || academicClasses[1].name) : '১০ম শ্রেণি'
  );
  const [allocationMode, setAllocationMode] = useState<'single' | 'alternate'>('alternate');
  const [benchesCount, setBenchesCount] = useState<number>(15);
  const [seatsPerBench, setSeatsPerBench] = useState<number>(2);

  const [viewMode, setViewMode] = useState<'grid' | 'stickers'>('grid');

  // Sync props
  React.useEffect(() => {
    if (initialClass !== undefined) setSelectedClass1(initialClass);
  }, [initialClass]);
  React.useEffect(() => {
    if (initialExamId !== undefined) setSelectedExamId(initialExamId);
  }, [initialExamId]);

  const selectedExam = (examTerms || []).find(t => t.id === selectedExamId);

  // Generate seat allocation
  const seatPlan: SeatAllocation[] = useMemo(() => {
    const class1Students = (students || []).filter(s => s.class === selectedClass1);
    const class2Students = (students || []).filter(s => s.class === selectedClass2);

    const allocations: SeatAllocation[] = [];
    let c1Index = 0;
    let c2Index = 0;

    for (let b = 1; b <= benchesCount; b++) {
      if (seatsPerBench === 2) {
        // Seat Left
        if (allocationMode === 'alternate') {
          if (c1Index < class1Students.length) {
            const st = class1Students[c1Index++];
            allocations.push({
              benchNumber: b,
              seatPosition: 'Left',
              studentId: st.id,
              studentName: st.name,
              studentNameBn: st.nameBn,
              roll: st.roll || `${c1Index}`,
              className: st.class,
              section: st.section,
              roomNo: selectedRoom
            });
          }
          // Seat Right
          if (c2Index < class2Students.length) {
            const st = class2Students[c2Index++];
            allocations.push({
              benchNumber: b,
              seatPosition: 'Right',
              studentId: st.id,
              studentName: st.name,
              studentNameBn: st.nameBn,
              roll: st.roll || `${c2Index}`,
              className: st.class,
              section: st.section,
              roomNo: selectedRoom
            });
          }
        } else {
          // Single Class
          if (c1Index < class1Students.length) {
            const st = class1Students[c1Index++];
            allocations.push({
              benchNumber: b,
              seatPosition: 'Left',
              studentId: st.id,
              studentName: st.name,
              studentNameBn: st.nameBn,
              roll: st.roll || `${c1Index}`,
              className: st.class,
              section: st.section,
              roomNo: selectedRoom
            });
          }
          if (c1Index < class1Students.length) {
            const st = class1Students[c1Index++];
            allocations.push({
              benchNumber: b,
              seatPosition: 'Right',
              studentId: st.id,
              studentName: st.name,
              studentNameBn: st.nameBn,
              roll: st.roll || `${c1Index}`,
              className: st.class,
              section: st.section,
              roomNo: selectedRoom
            });
          }
        }
      }
    }

    return allocations;
  }, [students, selectedClass1, selectedClass2, allocationMode, benchesCount, seatsPerBench, selectedRoom]);

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6">
      {/* Top Header & Breadcrumb */}
      {!hideTopHeader ? (
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200 print:hidden">
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-xs text-slate-500">
              <Link to="/exam" className="hover:text-indigo-600 flex items-center gap-1 font-medium">
                <ArrowLeft className="w-3.5 h-3.5" />
                {isBn ? BN_DICT['exam_hub'] : EN_DICT['exam_hub']}
              </Link>
              <ChevronRight className="w-3.5 h-3.5 text-slate-300" />
              <span className="text-slate-700 font-semibold">{isBn ? BN_DICT['seat_planning'] : EN_DICT['seat_planning']}</span>
            </div>
            <h1 className="text-2xl font-bold text-slate-800 flex items-center gap-2.5">
              <LayoutGrid className="w-6 h-6 text-indigo-600" />
              <span>{isBn ? BN_DICT['exam_hall_seating_layout'] : EN_DICT['exam_hall_seating_layout']}</span>
            </h1>
            <p className="text-xs sm:text-sm text-slate-500">
              {isBn ? BN_DICT['configure_room_wise_seat_alloc'] : EN_DICT['configure_room_wise_seat_alloc']}
            </p>
          </div>

          <div className="flex items-center gap-2">
            <div className="flex bg-slate-100 p-1 rounded-xl border border-slate-200">
              <button
                onClick={() => setViewMode('grid')}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold ${
                  viewMode === 'grid' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600'
                }`}
              >
                {isBn ? BN_DICT['hall_grid'] : EN_DICT['hall_grid']}
              </button>
              <button
                onClick={() => setViewMode('stickers')}
                className={`px-3 py-1.5 rounded-lg text-xs font-semibold ${
                  viewMode === 'stickers' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600'
                }`}
              >
                {isBn ? BN_DICT['desk_stickers'] : EN_DICT['desk_stickers']}
              </button>
            </div>

            <button
              onClick={handlePrint}
              className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
            >
              <Printer className="w-4 h-4" />
              <span>{viewMode === 'stickers' ? (isBn ? BN_DICT['print_stickers'] : EN_DICT['print_stickers']) : (isBn ? BN_DICT['print_plan'] : EN_DICT['print_plan'])}</span>
            </button>
          </div>
        </div>
      ) : (
        <div className="flex items-center justify-between pb-3 border-b border-slate-100 print:hidden">
          <span className="text-xs font-bold text-slate-600 uppercase tracking-wider">
            {isBn ? `সিট প্লানিং ও হল রুম (${selectedRoom})` : `Seat Plan & Hall Room (${selectedRoom})`}
          </span>
          <div className="flex items-center gap-2">
            <div className="flex bg-slate-100 p-1 rounded-xl border border-slate-200">
              <button
                onClick={() => setViewMode('grid')}
                className={`px-2.5 py-1 rounded-lg text-xs font-semibold ${
                  viewMode === 'grid' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600'
                }`}
              >
                {isBn ? BN_DICT['grid'] : EN_DICT['grid']}
              </button>
              <button
                onClick={() => setViewMode('stickers')}
                className={`px-2.5 py-1 rounded-lg text-xs font-semibold ${
                  viewMode === 'stickers' ? 'bg-white text-indigo-600 shadow-xs' : 'text-slate-600'
                }`}
              >
                {isBn ? BN_DICT['stickers'] : EN_DICT['stickers']}
              </button>
            </div>

            <button
              onClick={handlePrint}
              className="px-3.5 py-1.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
            >
              <Printer className="w-3.5 h-3.5" />
              <span>{viewMode === 'stickers' ? (isBn ? BN_DICT['print_stickers'] : EN_DICT['print_stickers']) : (isBn ? BN_DICT['print'] : EN_DICT['print'])}</span>
            </button>
          </div>
        </div>
      )}

      {/* Configuration Controls Bar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/80 shadow-xs space-y-4 print:hidden">
        <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-3 text-xs">
          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['exam'] : EN_DICT['exam']}
            </label>
            <select
              value={selectedExamId}
              onChange={(e) => setSelectedExamId(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            >
              {(examTerms || []).map(t => (
                <option key={t.id} value={t.id}>{isBn ? (t.nameBn || t.name) : t.name}</option>
              ))}
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['exam_room_hall'] : EN_DICT['exam_room_hall']}
            </label>
            <input
              type="text"
              value={selectedRoom}
              onChange={(e) => setSelectedRoom(e.target.value)}
              placeholder="e.g. Room 101"
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            />
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['allocation_mode'] : EN_DICT['allocation_mode']}
            </label>
            <select
              value={allocationMode}
              onChange={(e) => setAllocationMode(e.target.value as any)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium text-indigo-700 font-semibold"
            >
              <option value="alternate">{isBn ? BN_DICT['alternate_class_mixed'] : EN_DICT['alternate_class_mixed']}</option>
              <option value="single">{isBn ? BN_DICT['single_class'] : EN_DICT['single_class']}</option>
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['total_benches'] : EN_DICT['total_benches']}
            </label>
            <input
              type="number"
              min="1"
              max="50"
              value={benchesCount}
              onChange={(e) => setBenchesCount(Number(e.target.value))}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium font-mono"
            />
          </div>
        </div>

        <div className="grid grid-cols-1 sm:grid-cols-2 gap-3 pt-3 border-t border-slate-100 text-xs">
          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['class_1_left_seats'] : EN_DICT['class_1_left_seats']}
            </label>
            <select
              value={selectedClass1}
              onChange={(e) => setSelectedClass1(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            >
              {(academicClasses || []).map(c => (
                <option key={c.id} value={c.nameBn || c.name}>{c.nameBn || c.name}</option>
              ))}
            </select>
          </div>

          {allocationMode === 'alternate' && (
            <div>
              <label className="font-semibold text-slate-600 block mb-1">
                {isBn ? BN_DICT['class_2_right_seats'] : EN_DICT['class_2_right_seats']}
              </label>
              <select
                value={selectedClass2}
                onChange={(e) => setSelectedClass2(e.target.value)}
                className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
              >
                {(academicClasses || []).map(c => (
                  <option key={c.id} value={c.nameBn || c.name}>{c.nameBn || c.name}</option>
                ))}
              </select>
            </div>
          )}
        </div>
      </div>

      {/* Main Seat Layout Content */}
      {viewMode === 'grid' ? (
        /* Hall Visual Room Grid */
        <div className="bg-white p-6 rounded-xl border border-slate-200/80 shadow-xs space-y-6 print:border-none print:shadow-none">
          <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-2 border-b border-slate-200 pb-4">
            <div>
              <div className="flex items-center gap-2">
                <MapPin className="w-4 h-4 text-indigo-600" />
                <h3 className="font-bold text-slate-800 text-base">{selectedRoom} - {isBn ? BN_DICT['seating_plan'] : EN_DICT['seating_plan']}</h3>
              </div>
              <p className="text-xs text-slate-500 mt-0.5">
                {isBn ? (selectedExam?.nameBn || selectedExam?.name) : selectedExam?.name} | {isBn ? `মোট বরাদ্দকৃত আসন: ${seatPlan.length}` : `Total Allocated: ${seatPlan.length}`}
              </p>
            </div>

            <div className="flex items-center gap-3 text-xs">
              <span className="flex items-center gap-1.5">
                <span className="w-3 h-3 rounded bg-indigo-100 border border-indigo-300"></span>
                <span className="font-medium text-slate-700">{selectedClass1}</span>
              </span>
              {allocationMode === 'alternate' && (
                <span className="flex items-center gap-1.5">
                  <span className="w-3 h-3 rounded bg-emerald-100 border border-emerald-300"></span>
                  <span className="font-medium text-slate-700">{selectedClass2}</span>
                </span>
              )}
            </div>
          </div>

          {/* Teacher Desk / Black Board Indicator */}
          <div className="w-48 mx-auto py-1.5 bg-slate-800 text-white rounded text-center text-[11px] font-bold tracking-widest uppercase">
            {isBn ? BN_DICT['teacher_s_desk_front'] : EN_DICT['teacher_s_desk_front']}
          </div>

          {/* Bench Grid */}
          <div className="grid grid-cols-1 md:grid-cols-2 lg:grid-cols-3 gap-4">
            {Array.from({ length: benchesCount }).map((_, idx) => {
              const benchNo = idx + 1;
              const leftSeat = seatPlan.find(s => s.benchNumber === benchNo && s.seatPosition === 'Left');
              const rightSeat = seatPlan.find(s => s.benchNumber === benchNo && s.seatPosition === 'Right');

              return (
                <div 
                  key={benchNo}
                  className="bg-slate-50/80 rounded-xl border border-slate-200 p-3.5 space-y-2.5"
                >
                  <div className="flex items-center justify-between text-xs font-bold text-slate-500 pb-1.5 border-b border-slate-200/80">
                    <span>{isBn ? `বেঞ্চ নং: #${benchNo}` : `Bench #${benchNo}`}</span>
                    <span className="text-[10px] font-mono text-slate-400">{selectedRoom}</span>
                  </div>

                  <div className="grid grid-cols-2 gap-2">
                    {/* Left Seat */}
                    <div className={`p-2.5 rounded-lg border text-xs space-y-1 ${
                      leftSeat ? 'bg-indigo-50/70 border-indigo-200 text-indigo-950' : 'bg-white border-dashed border-slate-300 text-slate-400'
                    }`}>
                      <div className="text-[10px] font-bold uppercase text-indigo-600 flex justify-between">
                        <span>{isBn ? BN_DICT['seat_1'] : EN_DICT['seat_1']}</span>
                        {leftSeat && <span className="font-mono text-indigo-700">{leftSeat.className}</span>}
                      </div>
                      {leftSeat ? (
                        <div>
                          <div className="font-bold truncate">{isBn ? (leftSeat.studentNameBn || leftSeat.studentName) : leftSeat.studentName}</div>
                          <div className="text-[11px] font-mono font-semibold text-indigo-800">
                            {isBn ? `রোল: ${leftSeat.roll}` : `Roll: ${leftSeat.roll}`}
                          </div>
                        </div>
                      ) : (
                        <div className="text-center py-2 text-[10px] text-slate-400">{isBn ? BN_DICT['empty_1'] : EN_DICT['empty_1']}</div>
                      )}
                    </div>

                    {/* Right Seat */}
                    <div className={`p-2.5 rounded-lg border text-xs space-y-1 ${
                      rightSeat ? 'bg-emerald-50/70 border-emerald-200 text-emerald-950' : 'bg-white border-dashed border-slate-300 text-slate-400'
                    }`}>
                      <div className="text-[10px] font-bold uppercase text-emerald-600 flex justify-between">
                        <span>{isBn ? BN_DICT['seat_2'] : EN_DICT['seat_2']}</span>
                        {rightSeat && <span className="font-mono text-emerald-700">{rightSeat.className}</span>}
                      </div>
                      {rightSeat ? (
                        <div>
                          <div className="font-bold truncate">{isBn ? (rightSeat.studentNameBn || rightSeat.studentName) : rightSeat.studentName}</div>
                          <div className="text-[11px] font-mono font-semibold text-emerald-800">
                            {isBn ? `রোল: ${rightSeat.roll}` : `Roll: ${rightSeat.roll}`}
                          </div>
                        </div>
                      ) : (
                        <div className="text-center py-2 text-[10px] text-slate-400">{isBn ? BN_DICT['empty_1'] : EN_DICT['empty_1']}</div>
                      )}
                    </div>
                  </div>
                </div>
              );
            })}
          </div>
        </div>
      ) : (
        /* Printable Desk Stickers / Bench Slips Layout */
        <div className="space-y-4">
          <div className="bg-amber-50 p-3 rounded-xl border border-amber-200 text-amber-800 text-xs flex items-center gap-2 print:hidden">
            <Bookmark className="w-4 h-4 text-amber-600 shrink-0" />
            <span>
              {isBn ? BN_DICT['print_and_cut_these_stickers_t'] : EN_DICT['print_and_cut_these_stickers_t']}
            </span>
          </div>

          <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-4 gap-3 print:grid-cols-3 print:gap-2">
            {seatPlan.map((item, idx) => (
              <div 
                key={idx}
                className="bg-white border-2 border-slate-800 rounded-lg p-3 text-xs space-y-1.5 shadow-xs print:shadow-none print:break-inside-avoid text-slate-900"
              >
                <div className="text-center border-b border-slate-800 pb-1">
                  <div className="font-bold text-[11px] uppercase truncate">
                    {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয়ের নাম') : (institution?.name || 'INSTITUTION')}
                  </div>
                  <div className="text-[9px] text-slate-600">
                    {isBn ? (selectedExam?.nameBn || selectedExam?.name) : selectedExam?.name}
                  </div>
                </div>

                <div className="grid grid-cols-2 gap-1 text-[10px] pt-0.5">
                  <div>
                    <span className="text-slate-500 block text-[9px]">{isBn ? BN_DICT['room'] : EN_DICT['room']}</span>
                    <span className="font-bold">{item.roomNo}</span>
                  </div>
                  <div className="text-right">
                    <span className="text-slate-500 block text-[9px]">{isBn ? BN_DICT['bench'] : EN_DICT['bench']}</span>
                    <span className="font-bold">#{item.benchNumber} ({item.seatPosition})</span>
                  </div>
                </div>

                <div className="pt-1 border-t border-dashed border-slate-300">
                  <div className="font-bold text-xs truncate">
                    {isBn ? (item.studentNameBn || item.studentName) : item.studentName}
                  </div>
                  <div className="flex items-center justify-between text-[11px] mt-0.5">
                    <span className="font-semibold text-slate-700">{item.className}</span>
                    <span className="font-mono font-bold text-slate-900 bg-slate-100 px-1.5 py-0.2 rounded border border-slate-300">
                      {isBn ? `রোল: ${item.roll}` : `Roll: ${item.roll}`}
                    </span>
                  </div>
                </div>
              </div>
            ))}
          </div>
        </div>
      )}
    </div>
  );
};

export default SeatPlanning;
