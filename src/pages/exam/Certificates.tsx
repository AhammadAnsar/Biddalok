import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useMemo } from 'react';
import { Link } from 'react-router-dom';
import { 
  Award, Printer, ArrowLeft, ChevronRight, FileText, 
  Search, Users, GraduationCap, School, CheckCircle2,
  Calendar, ShieldCheck
} from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';
import { isClassMatch } from '../../utils/academicRelations';

export interface CertificatesProps {
  initialClass?: string;
  initialStudentId?: string;
  hideTopHeader?: boolean;
}

export const Certificates: React.FC<CertificatesProps> = ({
  initialClass,
  initialStudentId,
  hideTopHeader = false
}) => {
  const { 
    language, institution, examTerms, academicClasses, 
    students, subjects, gradingRules, examResults 
  } = useAppStore();

  const isBn = language === 'bn';

  const [docType, setDocType] = useState<'transcript' | 'testimonial' | 'completion'>('transcript');
  const [selectedClass, setSelectedClass] = useState<string>(
    initialClass || (academicClasses && academicClasses[0] ? (academicClasses[0].id || academicClasses[0].nameBn || academicClasses[0].name) : '১০ম শ্রেণি')
  );
  const [selectedStudentId, setSelectedStudentId] = useState<string>(initialStudentId || '');
  const [refNumber, setRefNumber] = useState<string>(`TRANS-2026-${Math.floor(1000 + Math.random() * 9000)}`);
  const [issueDate, setIssueDate] = useState<string>(new Date().toISOString().split('T')[0]);

  // Sync props
  React.useEffect(() => {
    if (initialClass !== undefined) setSelectedClass(initialClass);
  }, [initialClass]);
  React.useEffect(() => {
    if (initialStudentId !== undefined) setSelectedStudentId(initialStudentId);
  }, [initialStudentId]);

  const classStudents = useMemo(() => {
    return (students || []).filter(s => isClassMatch(s, selectedClass, academicClasses));
  }, [students, selectedClass, academicClasses]);

  React.useEffect(() => {
    if (classStudents.length > 0 && (!selectedStudentId || !classStudents.find(s => s.id === selectedStudentId))) {
      setSelectedStudentId(classStudents[0].id);
    }
  }, [classStudents, selectedStudentId]);

  const currentStudent = classStudents.find(s => s.id === selectedStudentId) || classStudents[0];
  const currentIndex = classStudents.findIndex(s => s.id === (currentStudent?.id || ''));
  const handlePrevStudent = () => {
    if (currentIndex > 0) setSelectedStudentId(classStudents[currentIndex - 1].id);
  };
  const handleNextStudent = () => {
    if (currentIndex < classStudents.length - 1) setSelectedStudentId(classStudents[currentIndex + 1].id);
  };

  const classSubjects = useMemo(() => {
    return (subjects || []).filter(s => s.className === selectedClass);
  }, [subjects, selectedClass]);

  // Scores for student
  const studentScores = useMemo(() => {
    if (!currentStudent) return [];
    return classSubjects.map(sub => {
      const existing = (examResults || []).find(r => r.studentId === currentStudent.id && r.subjectId === sub.id);
      const hasMarks = existing !== undefined;
      const total = hasMarks ? (existing.totalMarksObtained ?? ((existing.cqMarksObtained || 0) + (existing.mcqMarksObtained || 0) + (existing.practicalMarksObtained || 0))) : 0;
      const percent = (total / (sub.fullMarks || 100)) * 100;
      const rule = hasMarks ? (gradingRules || []).find(r => percent >= r.minMarks && percent <= r.maxMarks) : null;

      return {
        code: sub.code,
        name: isBn ? (sub.nameBn || sub.name) : sub.name,
        fullMarks: sub.fullMarks,
        total,
        grade: hasMarks ? (rule?.grade || 'F') : '-',
        gpa: hasMarks ? (rule?.gpa || 0.0) : 0.0,
        hasMarks
      };
    });
  }, [currentStudent, classSubjects, examResults, gradingRules, isBn]);

  const scoredItems = studentScores.filter(s => s.hasMarks);
  const totalObtained = scoredItems.reduce((a, b) => a + b.total, 0);
  const totalFull = scoredItems.reduce((a, b) => a + b.fullMarks, 0);
  const cumulativeGPA = scoredItems.length > 0 
    ? (scoredItems.reduce((a, b) => a + b.gpa, 0) / scoredItems.length).toFixed(2)
    : '0.00';

  const handlePrint = () => {
    window.print();
  };

  return (
    <div className="space-y-6">
      {/* Top Header & Breadcrumb */}
      {!hideTopHeader ? (
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 pb-4 border-b border-slate-200 print:hidden">
          <div className="space-y-1">
            <div className="flex items-center gap-2 text-xs text-slate-500">
              <Link to="/exam" className="hover:text-indigo-600 flex items-center gap-1 font-medium">
                <ArrowLeft className="w-3.5 h-3.5" />
                {isBn ? BN_DICT['exam_hub'] : EN_DICT['exam_hub']}
              </Link>
              <ChevronRight className="w-3.5 h-3.5 text-slate-300" />
              <span className="text-slate-700 font-semibold">{isBn ? BN_DICT['certificates_transcript'] : EN_DICT['certificates_transcript']}</span>
            </div>
            <h1 className="text-2xl font-bold text-slate-800 flex items-center gap-2.5">
              <Award className="w-6 h-6 text-indigo-600" />
              <span>{isBn ? BN_DICT['official_academic_transcript_c'] : EN_DICT['official_academic_transcript_c']}</span>
            </h1>
            <p className="text-xs sm:text-sm text-slate-500">
              {isBn ? BN_DICT['generate_and_print_official_ac'] : EN_DICT['generate_and_print_official_ac']}
            </p>
          </div>

          <button
            onClick={handlePrint}
            className="px-4 py-2 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5 self-start sm:self-auto"
          >
            <Printer className="w-4 h-4" />
            <span>{isBn ? BN_DICT['print_document'] : EN_DICT['print_document']}</span>
          </button>
        </div>
      ) : (
        <div className="flex items-center justify-between pb-3 border-b border-slate-100 print:hidden">
          <span className="text-xs font-bold text-slate-600 uppercase tracking-wider">
            {isBn ? `সার্টিফিকেট ও প্রশংসাপত্র প্রস্তুতকরণ` : `Certificates & Transcripts`}
          </span>
          <button
            onClick={handlePrint}
            className="px-3.5 py-1.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-lg text-xs font-semibold shadow-xs transition-colors flex items-center gap-1.5"
          >
            <Printer className="w-3.5 h-3.5" />
            <span>{isBn ? BN_DICT['print'] : EN_DICT['print']}</span>
          </button>
        </div>
      )}

      {/* Selectors Bar */}
      <div className="bg-white p-4 rounded-xl border border-slate-200/80 shadow-xs space-y-4 print:hidden">
        <div className="grid grid-cols-1 sm:grid-cols-4 gap-3 text-xs">
          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['document_type'] : EN_DICT['document_type']}
            </label>
            <select
              value={docType}
              onChange={(e) => setDocType(e.target.value as any)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-semibold text-indigo-700"
            >
              <option value="transcript">{isBn ? BN_DICT['official_transcript'] : EN_DICT['official_transcript']}</option>
              <option value="testimonial">{isBn ? BN_DICT['testimonial_certificate'] : EN_DICT['testimonial_certificate']}</option>
              <option value="completion">{isBn ? BN_DICT['completion_certificate'] : EN_DICT['completion_certificate']}</option>
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['class_1'] : EN_DICT['class_1']}
            </label>
            <select
              value={selectedClass}
              onChange={(e) => setSelectedClass(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            >
              {(academicClasses || []).map(c => (
                <option key={c.id} value={c.id}>{c.nameBn || c.name}</option>
              ))}
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1 flex items-center justify-between">
              <span>{isBn ? BN_DICT['select_student'] : EN_DICT['select_student']}</span>
              <div className="flex items-center gap-1">
                <button onClick={handlePrevStudent} disabled={currentIndex <= 0} className="text-slate-400 hover:text-indigo-600 disabled:opacity-50">«</button>
                <span className="text-[10px] text-slate-400">{currentIndex + 1}/{classStudents.length}</span>
                <button onClick={handleNextStudent} disabled={currentIndex >= classStudents.length - 1} className="text-slate-400 hover:text-indigo-600 disabled:opacity-50">»</button>
              </div>
            </label>
            <select
              value={selectedStudentId}
              onChange={(e) => setSelectedStudentId(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            >
              {classStudents.map(st => (
                <option key={st.id} value={st.id}>
                  রোল: {st.roll || '—'} - {isBn ? (st.nameBn || st.name) : st.name}
                </option>
              ))}
            </select>
          </div>

          <div>
            <label className="font-semibold text-slate-600 block mb-1">
              {isBn ? BN_DICT['issue_date_1'] : EN_DICT['issue_date_1']}
            </label>
            <input
              type="date"
              value={issueDate}
              onChange={(e) => setIssueDate(e.target.value)}
              className="w-full bg-slate-50 border border-slate-200 rounded-lg p-2 font-medium"
            />
          </div>
        </div>
      </div>

      {/* Document Sheet View */}
      {currentStudent && (
        <div className="bg-white p-8 sm:p-12 rounded-xl border-2 border-slate-800 shadow-sm max-w-4xl mx-auto text-slate-900 font-serif print:p-0 print:border-none print:shadow-none">
          {/* Top Crest / Header */}
          <div className="text-center space-y-1.5 pb-6 border-b-2 border-slate-800">
            {institution?.logoUrl && (
              <img src={institution.logoUrl} alt="Logo" className="w-16 h-16 object-contain mx-auto mb-2" />
            )}
            <h2 className="text-2xl sm:text-3xl font-bold uppercase tracking-wider text-slate-950 font-sans">
              {isBn ? (institution?.nameBn || institution?.name || 'বিদ্যালয়ের নাম') : (institution?.name || 'INSTITUTION NAME')}
            </h2>
            <p className="text-xs font-sans text-slate-600">
              {isBn ? (institution?.addressBn || institution?.address || '') : (institution?.address || '')}
              {institution?.eiin && ` | EIIN: ${institution.eiin}`}
            </p>
            
            <div className="pt-3">
              <span className="inline-block px-5 py-1.5 bg-slate-900 text-white font-sans font-bold text-xs uppercase tracking-widest rounded-full">
                {docType === 'transcript' && (isBn ? BN_DICT['official_academic_transcript'] : EN_DICT['official_academic_transcript'])}
                {docType === 'testimonial' && (isBn ? BN_DICT['testimonial_certificate_1'] : EN_DICT['testimonial_certificate_1'])}
                {docType === 'completion' && (isBn ? BN_DICT['certificate_of_completion'] : EN_DICT['certificate_of_completion'])}
              </span>
            </div>

            <div className="flex items-center justify-between text-xs font-sans text-slate-600 pt-3">
              <span>{isBn ? `স্মারক নং: ${refNumber}` : `Ref: ${refNumber}`}</span>
              <span>{isBn ? `তারিখ: ${issueDate}` : `Date: ${issueDate}`}</span>
            </div>
          </div>

          {/* TRANSCRIPT TYPE */}
          {docType === 'transcript' && (
            <div className="mt-6 space-y-6">
              <div className="grid grid-cols-2 sm:grid-cols-4 gap-4 p-4 bg-slate-50 border border-slate-300 rounded font-sans text-xs">
                <div>
                  <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['student_name_1'] : EN_DICT['student_name_1']}</span>
                  <span className="font-bold text-slate-900">{isBn ? (currentStudent.nameBn || currentStudent.name) : currentStudent.name}</span>
                </div>
                <div>
                  <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['class_group'] : EN_DICT['class_group']}</span>
                  <span className="font-semibold text-slate-900">{currentStudent.class} ({currentStudent.group || 'সাধারণ'})</span>
                </div>
                <div>
                  <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['roll_no'] : EN_DICT['roll_no']}</span>
                  <span className="font-mono font-bold text-slate-900">{currentStudent.roll || '—'}</span>
                </div>
                <div>
                  <span className="text-slate-500 block text-[10px]">{isBn ? BN_DICT['student_id_1'] : EN_DICT['student_id_1']}</span>
                  <span className="font-mono font-semibold text-slate-900">{currentStudent.studentId || 'N/A'}</span>
                </div>
              </div>

              <div className="overflow-x-auto">
                <table className="w-full border-collapse border border-slate-800 font-sans text-xs">
                  <thead>
                    <tr className="bg-slate-100 font-bold border-b border-slate-800 text-slate-900">
                      <th className="border border-slate-800 p-2.5 text-center w-16">{isBn ? BN_DICT['code'] : EN_DICT['code']}</th>
                      <th className="border border-slate-800 p-2.5 text-left">{isBn ? BN_DICT['subjects_1'] : EN_DICT['subjects_1']}</th>
                      <th className="border border-slate-800 p-2.5 text-center w-20">{isBn ? BN_DICT['full_marks'] : EN_DICT['full_marks']}</th>
                      <th className="border border-slate-800 p-2.5 text-center w-24 font-bold">{isBn ? BN_DICT['marks_1'] : EN_DICT['marks_1']}</th>
                      <th className="border border-slate-800 p-2.5 text-center w-20">{isBn ? BN_DICT['grade'] : EN_DICT['grade']}</th>
                      <th className="border border-slate-800 p-2.5 text-center w-20">{isBn ? BN_DICT['gp'] : EN_DICT['gp']}</th>
                    </tr>
                  </thead>
                  <tbody>
                    {studentScores.map((item, idx) => (
                      <tr key={idx} className="border-b border-slate-800">
                        <td className="border border-slate-800 p-2 text-center font-mono">{item.code}</td>
                        <td className="border border-slate-800 p-2 font-semibold">{item.name}</td>
                        <td className="border border-slate-800 p-2 text-center font-mono">{item.fullMarks}</td>
                        <td className="border border-slate-800 p-2 text-center font-mono font-bold">{item.total}</td>
                        <td className="border border-slate-800 p-2 text-center font-mono font-bold">{item.grade}</td>
                        <td className="border border-slate-800 p-2 text-center font-mono font-bold">{item.gpa.toFixed(2)}</td>
                      </tr>
                    ))}
                  </tbody>
                </table>
              </div>

              <div className="p-4 bg-slate-50 border border-slate-800 rounded font-sans flex items-center justify-between">
                <div>
                  <div className="text-xs text-slate-500 font-semibold">{isBn ? BN_DICT['total_marks_obtained'] : EN_DICT['total_marks_obtained']}</div>
                  <div className="text-lg font-bold font-mono text-slate-900">{totalObtained} / {totalFull}</div>
                </div>
                <div className="text-right">
                  <div className="text-xs text-slate-500 font-semibold">{isBn ? BN_DICT['cumulative_gpa'] : EN_DICT['cumulative_gpa']}</div>
                  <div className="text-2xl font-bold font-mono text-indigo-900">{cumulativeGPA} (5.00 স্কেলে)</div>
                </div>
              </div>
            </div>
          )}

          {/* TESTIMONIAL OR COMPLETION TYPE */}
          {(docType === 'testimonial' || docType === 'completion') && (
            <div className="mt-8 space-y-6 text-sm leading-relaxed px-4 sm:px-8">
              <p className="text-justify font-serif text-slate-800">
                {isBn ? (
                  <>
                    এই মর্মে প্রত্যয়ন করা যাচ্ছে যে, <strong className="font-bold text-slate-950 font-sans text-base">{currentStudent.nameBn || currentStudent.name}</strong>, 
                    পিতা: <strong className="font-bold font-sans">{currentStudent.fatherNameBn || currentStudent.fatherName || 'অভিভাবক'}</strong>, 
                    মাতা: <strong className="font-bold font-sans">{currentStudent.motherNameBn || currentStudent.motherName || 'অভিভাবক'}</strong>, 
                    এই বিদ্যালয়ের <strong className="font-bold font-sans">{currentStudent.class}</strong> শ্রেণির একজন নিয়মিত শিক্ষার্থী ছিল (রোল নং: {currentStudent.roll || '—'}, আইডি: {currentStudent.studentId || 'N/A'})।
                  </>
                ) : (
                  <>
                    This is to certify that <strong className="font-bold text-slate-950 font-sans text-base">{currentStudent.name}</strong>, 
                    Son/Daughter of <strong className="font-bold font-sans">{currentStudent.fatherName || "Guardian"}</strong> and <strong className="font-bold font-sans">{currentStudent.motherName || "Guardian"}</strong>, 
                    was a bona fide student of this institution in <strong className="font-bold font-sans">{currentStudent.class}</strong> (Roll: {currentStudent.roll || '—'}, ID: {currentStudent.studentId || 'N/A'}).
                  </>
                )}
              </p>

              <p className="text-justify font-serif text-slate-800">
                {isBn ? (
                  <>
                    সে অত্র বিদ্যালয়ের ২০২৬ শিক্ষাবর্ষের বার্ষিক মূল্যায়নে কৃতিত্বের সাথে উত্তীর্ণ হয়ে জিপিএ <strong className="font-bold font-mono text-base font-sans">{cumulativeGPA}</strong> অর্জন করেছে।
                    বিদ্যালয়ে অধ্যয়নকালীন সময়ে সে কোনো প্রকার শৃঙ্খলাবিরোধী কাজে লিপ্ত ছিল না। তাহার নৈতিক চরিত্র অত্যন্ত প্রশংসনীয় ও উত্তম।
                  </>
                ) : (
                  <>
                    He/She successfully completed the academic curriculum securing a Grade Point Average (GPA) of <strong className="font-bold font-mono text-base font-sans">{cumulativeGPA}</strong> on a 5.00 scale.
                    During his/her tenure at this institution, his/her conduct and moral character were found to be exemplary.
                  </>
                )}
              </p>

              <p className="font-serif italic text-slate-700">
                {isBn ? BN_DICT['i_wish_him_her_every_success_a'] : EN_DICT['i_wish_him_her_every_success_a']}
              </p>
            </div>
          )}

          {/* Signatures */}
          <div className="mt-20 pt-4 grid grid-cols-2 text-xs font-sans font-semibold">
            <div className="text-left space-y-1">
              <div className="w-36 border-b border-slate-800"></div>
              <div>{isBn ? BN_DICT['controller_of_examinations'] : EN_DICT['controller_of_examinations']}</div>
            </div>
            <div className="text-right space-y-1 flex flex-col items-end justify-end">
              {institution?.headmasterSignature ? (
                <img 
                  src={institution.headmasterSignature} 
                  alt="Principal Signature" 
                  className="h-9 max-w-[140px] object-contain ml-auto -mb-1"
                />
              ) : null}
              <div className="w-36 border-b border-slate-800 ml-auto"></div>
              <div>{isBn ? (institution?.headmasterTitleBn || 'প্রধান শিক্ষক / অধ্যক্ষ') : (institution?.headmasterTitle || 'Principal / Headmaster')}</div>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};

export default Certificates;
