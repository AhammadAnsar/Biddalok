import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useMemo, useEffect } from 'react';
import { Link } from 'react-router-dom';
import { 
  BarChart3, Printer, ArrowLeft, ChevronRight, Save, 
  Search, Award, CheckCircle2, AlertCircle, FileText,
  Users, BookOpen, GraduationCap, School, Trophy, LayoutGrid,
  Sparkles, Filter, Calendar, FolderCheck
} from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';
import { 
  ExamResultEntry, 
  Student, 
  SubjectItem, 
  CurriculumSubjectMapping, 
  AcademicClass, 
  AcademicSection, 
  AcademicGroup, 
  AcademicSession, 
  ExamTerm 
} from '../../types';
import { MarkEntryGrid } from '../../components/exam/MarkEntryGrid';
import { TabulationSheetView } from '../../components/exam/TabulationSheetView';
import { MeritListView } from '../../components/exam/MeritListView';
import { StudentMarksheetCard } from '../../components/exam/StudentMarksheetCard';
import { 
  isClassMatch, 
  isSectionMatch, 
  isGroupMatch, 
  isSessionMatch,
  findClass,
  findSection,
  findGroup,
  findSession
} from '../../utils/academicRelations';

export interface ExamResultsProps {
  initialSession?: string;
  initialClass?: string;
  initialSection?: string;
  initialExamId?: string;
  hideTopHeader?: boolean;
}

export const ExamResults: React.FC<ExamResultsProps> = ({
  initialSession,
  initialClass,
  initialSection,
  initialExamId,
  hideTopHeader = false
}) => {
  const { 
    language, 
    institution, 
    examTerms, 
    academicClasses, 
    academicSections,
    academicGroups,
    academicSessions,
    curriculumMappings,
    subjects, 
    students, 
    gradingRules, 
    examResults, 
    saveExamResults 
  } = useAppStore();

  const isBn = language === 'bn';

  // 1. Cascading Selector States
  // Session / Year
  const defaultSession = initialSession || academicSessions?.find(s => s.isDefault)?.name || academicSessions?.[0]?.name || '2026';
  const [selectedSession, setSelectedSession] = useState<string>(defaultSession);

  // Class
  const defaultClass = initialClass || academicClasses?.[0]?.nameBn || academicClasses?.[0]?.name || '৯ম শ্রেণি';
  const [selectedClass, setSelectedClass] = useState<string>(defaultClass);

  // Group
  const [selectedGroup, setSelectedGroup] = useState<string>('all');

  // Section
  const [selectedSection, setSelectedSection] = useState<string>(initialSection || 'all');

  // Exam Term
  const defaultExamId = initialExamId || examTerms?.find(t => t.isDefault)?.id || examTerms?.[0]?.id || 'term_1';
  const [selectedExamId, setSelectedExamId] = useState<string>(defaultExamId);

  // Sync with incoming props if changed
  useEffect(() => {
    if (initialSession) setSelectedSession(initialSession);
  }, [initialSession]);
  useEffect(() => {
    if (initialClass) setSelectedClass(initialClass);
  }, [initialClass]);
  useEffect(() => {
    if (initialSection) setSelectedSection(initialSection);
  }, [initialSection]);
  useEffect(() => {
    if (initialExamId) setSelectedExamId(initialExamId);
  }, [initialExamId]);

  // Subject
  const [selectedSubjectId, setSelectedSubjectId] = useState<string>('');

  // Active Tab: entry | tabulation | marksheet | merit
  const [activeTab, setActiveTab] = useState<'entry' | 'tabulation' | 'marksheet' | 'merit'>('entry');

  // Selected Exam Term Object
  const currentExam = useMemo<ExamTerm>(() => {
    return (examTerms || []).find(t => t.id === selectedExamId) || {
      id: selectedExamId || 'term_1',
      name: '1st Term Exam',
      nameBn: '১ম সাময়িক পরীক্ষা',
      year: selectedSession || '2026',
      totalMarks: 100,
      passingMarks: 33,
      status: 'ongoing'
    };
  }, [examTerms, selectedExamId, selectedSession]);

  // Selected Class Object
  const currentClassObj = useMemo(() => {
    return findClass(selectedClass, academicClasses);
  }, [selectedClass, academicClasses]);

  // Dynamically mapped subjects for this Class & Group from Curriculum Settings
  const availableSubjects = useMemo<(SubjectItem | CurriculumSubjectMapping)[]>(() => {
    // 1. Look in curriculumMappings for this class
    const activeExamTerm = examTerms.find(t => t.id === selectedExamId);
      const targetCurriculumId = activeExamTerm?.curriculumId || '';

      // 1. Look in curriculumMappings for this class (and curriculum if bound)
      const matchedCurriculum = (curriculumMappings || []).filter(cm => {
        if (targetCurriculumId && cm.curriculumId !== targetCurriculumId) return false;
      const matchCls = isClassMatch({ class: cm.className, classId: cm.classId }, selectedClass, academicClasses);
      const matchGrp = selectedGroup === 'all' || isGroupMatch({ group: cm.groupName }, selectedGroup, academicGroups);
      return matchCls && matchGrp;
    });

    if (matchedCurriculum.length > 0) {
      return matchedCurriculum.map(cm => ({
        id: cm.id,
        name: cm.name,
        nameBn: cm.nameBn,
        code: cm.subjectCode,
        className: cm.className,
        classId: cm.classId,
        groupName: cm.groupName,
        groupId: (cm as any).groupId,
        fullMarks: cm.fullMarks,
        passMarks: cm.passMarks,
        cqMarks: cm.cqMarks,
        cqPassMarks: cm.cqPassMarks,
        mcqMarks: cm.mcqMarks,
        mcqPassMarks: cm.mcqPassMarks,
        practicalMarks: cm.practicalMarks,
        practicalPassMarks: cm.practicalPassMarks,
        passLogic: cm.passLogic,
        cqMcqPassType: cm.cqMcqPassType,
        paperPassType: cm.paperPassType,
        combinedWithCode: cm.combinedWithSubjectCode || (cm as any).combinedWithCode,
        isOptional: cm.isOptional,
        isContinuous: (cm as any).isContinuous
      } as SubjectItem));
    }

    // 2. Fallback to standard subjects list
    return (subjects || []).filter(s => {
      const matchCls = isClassMatch({ class: s.className, classId: s.classId }, selectedClass, academicClasses);
      const matchGrp = selectedGroup === 'all' || isGroupMatch({ group: s.groupName, groupId: s.groupId }, selectedGroup, academicGroups);
      return matchCls && matchGrp;
    });
  }, [curriculumMappings, subjects, selectedClass, selectedGroup, academicClasses, academicGroups]);

  // Ensure an active subject is selected when availableSubjects changes
  useEffect(() => {
    if (availableSubjects.length > 0) {
      if (!selectedSubjectId || !availableSubjects.some(s => s.id === selectedSubjectId || ((s.code || (s as any).subjectCode) === selectedSubjectId))) {
        setSelectedSubjectId(availableSubjects[0].id);
      }
    } else {
      setSelectedSubjectId('');
    }
  }, [availableSubjects, selectedSubjectId]);

  const activeSubject = useMemo(() => {
    return availableSubjects.find(s => s.id === selectedSubjectId || ((s.code || (s as any).subjectCode) === selectedSubjectId)) || availableSubjects[0];
  }, [availableSubjects, selectedSubjectId]);

  // Dynamically filtered students for this Class, Group, Section, and Session
  const cohortStudents = useMemo<Student[]>(() => {
    return (students || [])
      .filter(st => {
        const matchCls = isClassMatch(st, selectedClass, academicClasses);
        const matchSec = isSectionMatch(st, selectedSection, academicSections);
        const matchGrp = selectedGroup === 'all' || isGroupMatch(st, selectedGroup, academicGroups);
        const matchSes = isSessionMatch(st, selectedSession, academicSessions);
        return matchCls && matchSec && matchGrp && matchSes;
      })
      .sort((a, b) => {
        const rollA = parseInt(a.roll || '999999') || 999999;
        const rollB = parseInt(b.roll || '999999') || 999999;
        return rollA - rollB;
      });
  }, [students, selectedClass, selectedSection, selectedGroup, selectedSession, academicClasses, academicSections, academicGroups, academicSessions]);

  // Auto-Save Handler
  const handleAutoSave = (entries: ExamResultEntry[]) => {
    saveExamResults(entries);
  };

  return (
    <div className="space-y-6">
      {/* Module Title & Breadcrumbs */}
      {!hideTopHeader && (
        <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-4 print:hidden">
          <div>
            <div className="flex items-center gap-2 text-xs text-slate-500 font-medium mb-1">
              <Link to="/exam" className="hover:text-indigo-600 transition-colors">
                {isBn ? BN_DICT['exam_module'] : EN_DICT['exam_module']}
              </Link>
              <ChevronRight className="w-3.5 h-3.5" />
              <span className="text-slate-800 font-semibold">{isBn ? BN_DICT['result_processing'] : EN_DICT['result_processing']}</span>
            </div>
            <h1 className="text-xl sm:text-2xl font-bold text-slate-900 tracking-tight flex items-center gap-2.5">
              <BarChart3 className="w-6 h-6 text-rose-600" />
              <span>{isBn ? BN_DICT['result_processing_grade_evalua'] : EN_DICT['result_processing_grade_evalua']}</span>
            </h1>
            <p className="text-xs sm:text-sm text-slate-500 mt-0.5">
              {isBn ? BN_DICT['excel_like_mark_entry_with_aut'] : EN_DICT['excel_like_mark_entry_with_aut']}
            </p>
          </div>

          {/* Global Action Links */}
          <div className="flex items-center gap-2">
            <Link
              to="/exam?tab=settings"
              className="px-3 py-2 bg-white hover:bg-slate-50 text-slate-700 rounded-xl text-xs font-semibold border border-slate-200 shadow-2xs transition-colors flex items-center gap-1.5"
            >
              <School className="w-4 h-4 text-indigo-600" />
              <span>{isBn ? BN_DICT['curriculum_settings'] : EN_DICT['curriculum_settings']}</span>
            </Link>
          </div>
        </div>
      )}

      {/* Dynamic Cascading Filter Bar (Academic Year -> Class -> Group -> Section -> Exam -> Subject) */}
      <div className="bg-white p-4 sm:p-5 rounded-2xl border border-slate-200 shadow-xs space-y-4 print:hidden">
        <div className="flex items-center gap-2 text-xs font-bold text-slate-800 border-b border-slate-100 pb-2">
          <Filter className="w-4 h-4 text-indigo-600" />
          <span>{isBn ? BN_DICT['selection_filters'] : EN_DICT['selection_filters']}</span>
        </div>

        <div className="grid grid-cols-2 sm:grid-cols-3 lg:grid-cols-6 gap-3">
          {/* 1. Academic Session / Year */}
          <div>
            <label className="block text-[11px] font-bold text-slate-600 uppercase tracking-wider mb-1">
              {isBn ? BN_DICT['session_2'] : EN_DICT['session_2']}
            </label>
            <select
              value={selectedSession}
              onChange={(e) => setSelectedSession(e.target.value)}
              className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg text-xs font-semibold text-slate-800 focus:bg-white focus:ring-1 focus:ring-indigo-500"
            >
              {(academicSessions || []).map(ses => (
                <option key={ses.id} value={ses.name}>
                  {isBn ? (ses.nameBn || ses.name) : ses.name}
                </option>
              ))}
            </select>
          </div>

          {/* 2. Class */}
          <div>
            <label className="block text-[11px] font-bold text-slate-600 uppercase tracking-wider mb-1">
              {isBn ? BN_DICT['class_2'] : EN_DICT['class_2']}
            </label>
            <select
              value={selectedClass}
              onChange={(e) => setSelectedClass(e.target.value)}
              className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg text-xs font-semibold text-slate-800 focus:bg-white focus:ring-1 focus:ring-indigo-500"
            >
              {(academicClasses || []).map(cls => (
                <option key={cls.id} value={cls.nameBn || cls.name}>
                  {isBn ? (cls.nameBn || cls.name) : cls.name}
                </option>
              ))}
            </select>
          </div>

          {/* 3. Group */}
          <div>
            <label className="block text-[11px] font-bold text-slate-600 uppercase tracking-wider mb-1">
              {isBn ? BN_DICT['group_2'] : EN_DICT['group_2']}
            </label>
            <select
              value={selectedGroup}
              onChange={(e) => setSelectedGroup(e.target.value)}
              className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg text-xs font-semibold text-slate-800 focus:bg-white focus:ring-1 focus:ring-indigo-500"
            >
              <option value="all">{isBn ? BN_DICT['all_groups'] : EN_DICT['all_groups']}</option>
              {(academicGroups || []).map(grp => (
                <option key={grp.id} value={grp.name}>
                  {isBn ? (grp.nameBn || grp.name) : grp.name}
                </option>
              ))}
            </select>
          </div>

          {/* 4. Section */}
          <div>
            <label className="block text-[11px] font-bold text-slate-600 uppercase tracking-wider mb-1">
              {isBn ? BN_DICT['section_2'] : EN_DICT['section_2']}
            </label>
            <select
              value={selectedSection}
              onChange={(e) => setSelectedSection(e.target.value)}
              className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg text-xs font-semibold text-slate-800 focus:bg-white focus:ring-1 focus:ring-indigo-500"
            >
              <option value="all">{isBn ? BN_DICT['all_sections'] : EN_DICT['all_sections']}</option>
              {(academicSections || []).map(sec => (
                <option key={sec.id} value={sec.name}>
                  {isBn ? (sec.nameBn || sec.name) : sec.name}
                </option>
              ))}
            </select>
          </div>

          {/* 5. Exam Term */}
          <div>
            <label className="block text-[11px] font-bold text-slate-600 uppercase tracking-wider mb-1">
              {isBn ? BN_DICT['exam_term'] : EN_DICT['exam_term']}
            </label>
            <select
              value={selectedExamId}
              onChange={(e) => setSelectedExamId(e.target.value)}
              className="w-full p-2 bg-slate-50 border border-slate-200 rounded-lg text-xs font-semibold text-slate-800 focus:bg-white focus:ring-1 focus:ring-indigo-500"
            >
              {(examTerms || []).map(term => (
                <option key={term.id} value={term.id}>
                  {isBn ? (term.nameBn || term.name) : term.name}
                </option>
              ))}
            </select>
          </div>

          {/* 6. Subject (Dynamic from Curriculum) */}
          <div>
            <label className="block text-[11px] font-bold text-slate-600 uppercase tracking-wider mb-1">
              {isBn ? BN_DICT['subject'] : EN_DICT['subject']}
            </label>
            <select
              value={selectedSubjectId}
              onChange={(e) => setSelectedSubjectId(e.target.value)}
              disabled={availableSubjects.length === 0}
              className="w-full p-2 bg-indigo-50/50 border border-indigo-200 rounded-lg text-xs font-bold text-indigo-900 focus:bg-white focus:ring-1 focus:ring-indigo-500 disabled:opacity-50"
            >
              {availableSubjects.length === 0 ? (
                <option value="">{isBn ? BN_DICT['no_subjects'] : EN_DICT['no_subjects']}</option>
              ) : (
                availableSubjects.map(sub => (
                  <option key={sub.id} value={sub.id}>
                    {isBn ? (sub.nameBn || sub.name) : sub.name} ({sub.code})
                  </option>
                ))
              )}
            </select>
          </div>
        </div>
      </div>

      {/* Navigation Tabs (১. নম্বর এন্ট্রি, ২. টেবুলেশন শীট, ৩. মার্কশীট, ৪. মেধা তালিকা) */}
      <div className="bg-slate-100 p-1.5 rounded-2xl flex flex-wrap gap-1.5 print:hidden border border-slate-200/80">
        <button
          onClick={() => setActiveTab('entry')}
          className={`flex-1 min-w-[140px] px-4 py-2.5 rounded-xl font-bold text-xs sm:text-sm transition-all flex items-center justify-center gap-2 ${
            activeTab === 'entry'
              ? 'bg-white text-indigo-700 shadow-sm'
              : 'text-slate-600 hover:text-slate-900 hover:bg-white/50'
          }`}
        >
          <FileText className="w-4 h-4" />
          <span>{isBn ? BN_DICT['k_1_mark_entry_excel_grid'] : EN_DICT['k_1_mark_entry_excel_grid']}</span>
        </button>

        <button
          onClick={() => setActiveTab('tabulation')}
          className={`flex-1 min-w-[140px] px-4 py-2.5 rounded-xl font-bold text-xs sm:text-sm transition-all flex items-center justify-center gap-2 ${
            activeTab === 'tabulation'
              ? 'bg-white text-indigo-700 shadow-sm'
              : 'text-slate-600 hover:text-slate-900 hover:bg-white/50'
          }`}
        >
          <LayoutGrid className="w-4 h-4" />
          <span>{isBn ? BN_DICT['k_2_tabulation_sheet'] : EN_DICT['k_2_tabulation_sheet']}</span>
        </button>

        <button
          onClick={() => setActiveTab('marksheet')}
          className={`flex-1 min-w-[140px] px-4 py-2.5 rounded-xl font-bold text-xs sm:text-sm transition-all flex items-center justify-center gap-2 ${
            activeTab === 'marksheet'
              ? 'bg-white text-indigo-700 shadow-sm'
              : 'text-slate-600 hover:text-slate-900 hover:bg-white/50'
          }`}
        >
          <GraduationCap className="w-4 h-4" />
          <span>{isBn ? BN_DICT['k_3_marksheet'] : EN_DICT['k_3_marksheet']}</span>
        </button>

        <button
          onClick={() => setActiveTab('merit')}
          className={`flex-1 min-w-[140px] px-4 py-2.5 rounded-xl font-bold text-xs sm:text-sm transition-all flex items-center justify-center gap-2 ${
            activeTab === 'merit'
              ? 'bg-white text-indigo-700 shadow-sm'
              : 'text-slate-600 hover:text-slate-900 hover:bg-white/50'
          }`}
        >
          <Trophy className="w-4 h-4" />
          <span>{isBn ? BN_DICT['k_4_merit_list'] : EN_DICT['k_4_merit_list']}</span>
        </button>
      </div>

      {/* Main Tab Views */}
      <div>
        {/* Tab 1: Mark Entry (Excel Grid with Auto-Save) */}
        {activeTab === 'entry' && (
          <div>
            {!activeSubject ? (
              <div className="text-center py-12 bg-white rounded-2xl border border-slate-200 text-slate-500">
                <AlertCircle className="w-8 h-8 mx-auto mb-2 text-amber-500" />
                <p className="font-semibold">{isBn ? BN_DICT['no_subjects_found_in_curriculu'] : EN_DICT['no_subjects_found_in_curriculu']}</p>
                <p className="text-xs text-slate-400 mt-1">
                  {isBn ? BN_DICT['please_configure_subjects_in_e'] : EN_DICT['please_configure_subjects_in_e']}
                </p>
              </div>
            ) : cohortStudents.length === 0 ? (
              <div className="text-center py-12 bg-white rounded-2xl border border-slate-200 text-slate-500">
                <Users className="w-8 h-8 mx-auto mb-2 text-slate-400" />
                <p className="font-semibold">{isBn ? BN_DICT['no_students_found_for_this_cla'] : EN_DICT['no_students_found_for_this_cla']}</p>
              </div>
            ) : (
              <MarkEntryGrid
                key={`${selectedExamId}_${activeSubject.id}_${selectedClass}_${selectedSection}_${selectedGroup}`}
                examId={selectedExamId}
                className={selectedClass}
                classId={currentClassObj?.id}
                sessionId={selectedSession}
                groupId={selectedGroup === 'all' ? undefined : selectedGroup}
                subject={activeSubject}
                students={cohortStudents}
                gradingRules={gradingRules}
                existingResults={examResults}
                onAutoSave={handleAutoSave}
                isBn={isBn}
              />
            )}
          </div>
        )}

        {/* Tab 2: Tabulation Sheet */}
        {activeTab === 'tabulation' && (
          <TabulationSheetView
            institution={institution}
            exam={currentExam}
            className={selectedClass}
            sectionName={selectedSection === 'all' ? undefined : selectedSection}
            groupName={selectedGroup === 'all' ? undefined : selectedGroup}
            sessionName={selectedSession}
            subjects={availableSubjects}
            students={cohortStudents}
            gradingRules={gradingRules}
            examResults={examResults}
            isBn={isBn}
          />
        )}

        {/* Tab 3: Marksheet Card */}
        {activeTab === 'marksheet' && (
          <StudentMarksheetCard
            institution={institution}
            exam={currentExam}
            className={selectedClass}
            sectionName={selectedSection === 'all' ? undefined : selectedSection}
            groupName={selectedGroup === 'all' ? undefined : selectedGroup}
            sessionName={selectedSession}
            subjects={availableSubjects}
            students={cohortStudents}
            gradingRules={gradingRules}
            examResults={examResults}
            isBn={isBn}
          />
        )}

        {/* Tab 4: Merit List */}
        {activeTab === 'merit' && (
          <MeritListView
            institution={institution}
            exam={currentExam}
            className={selectedClass}
            sectionName={selectedSection === 'all' ? undefined : selectedSection}
            groupName={selectedGroup === 'all' ? undefined : selectedGroup}
            sessionName={selectedSession}
            subjects={availableSubjects}
            students={cohortStudents}
            gradingRules={gradingRules}
            examResults={examResults}
            isBn={isBn}
          />
        )}
      </div>
    </div>
  );
};

export default ExamResults;

