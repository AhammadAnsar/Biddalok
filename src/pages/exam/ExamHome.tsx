import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useMemo, useEffect } from 'react';
import { useSearchParams } from 'react-router-dom';
import { 
  BarChart3, 
  Calendar, 
  IdCard, 
  LayoutGrid, 
  Award, 
  Settings2, 
  Filter,
  Users,
  CheckCircle2,
  Sparkles
} from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';
import { ExamResults } from './ExamResults';
import { ExamRoutine } from './ExamRoutine';
import { AdmitCard } from './AdmitCard';
import { SeatPlanning } from './SeatPlanning';
import { Certificates } from './Certificates';
import { ExamSettings } from './ExamSettings';
import { 
  findClass, 
  isSessionMatch, 
  isClassMatch, 
  isSectionMatch 
} from '../../utils/academicRelations';

type TabId = 'results' | 'routine' | 'admit-card' | 'seat-planning' | 'certificates' | 'settings';

interface TabItem {
  id: TabId;
  labelBn: string;
  labelEn: string;
  icon: React.ComponentType<{ className?: string }>;
}

const DASHBOARD_TABS: TabItem[] = [
  { id: 'results', labelBn: 'ফলাফল ও মার্কশীট', labelEn: 'Results & Marksheet', icon: BarChart3 },
  { id: 'routine', labelBn: 'পরীক্ষা রুটিন', labelEn: 'Exam Routine', icon: Calendar },
  { id: 'admit-card', labelBn: 'এডমিট কার্ড', labelEn: 'Admit Card', icon: IdCard },
  { id: 'seat-planning', labelBn: 'আসন বিন্যাস', labelEn: 'Seat Planning', icon: LayoutGrid },
  { id: 'certificates', labelBn: 'সনদ ও ট্রান্সক্রিপ্ট', labelEn: 'Certificates', icon: Award },
  { id: 'settings', labelBn: 'পরীক্ষা সেটিংস্', labelEn: 'Exam Settings', icon: Settings2 },
];

export const ExamHome: React.FC = () => {
  const [searchParams, setSearchParams] = useSearchParams();
  const rawTab = searchParams.get('tab') as TabId;
  const validTab: TabId = DASHBOARD_TABS.some(t => t.id === rawTab) ? rawTab : 'results';

  const [activeTab, setActiveTab] = useState<TabId>(validTab);

  // Sync tab with URL
  useEffect(() => {
    if (rawTab && DASHBOARD_TABS.some(t => t.id === rawTab) && rawTab !== activeTab) {
      setActiveTab(rawTab);
    }
  }, [rawTab]);

  const handleTabChange = (newTab: TabId) => {
    setActiveTab(newTab);
    setSearchParams({ tab: newTab });
  };

  const { 
    language, 
    examTerms, 
    academicClasses, 
    academicSections, 
    academicSessions,
    students 
  } = useAppStore();

  const isBn = language === 'bn';

  // Persistent Shared Filter States
  const defaultSession = academicSessions?.find(s => s.isDefault)?.name || academicSessions?.[0]?.name || '2026';
  const [selectedSession, setSelectedSession] = useState<string>(defaultSession);

  const defaultClass = academicClasses?.[0]?.nameBn || academicClasses?.[0]?.name || '৯ম শ্রেণি';
  const [selectedClass, setSelectedClass] = useState<string>(defaultClass);

  const [selectedSection, setSelectedSection] = useState<string>('all');

  const defaultExamId = examTerms?.find(t => t.isDefault)?.id || examTerms?.[0]?.id || 'term_1';
  const [selectedExamId, setSelectedExamId] = useState<string>(defaultExamId);

  // Class object
  const currentClassObj = useMemo(() => {
    return findClass(selectedClass, academicClasses);
  }, [selectedClass, academicClasses]);

  // Available sections
  const availableSections = useMemo(() => {
    return academicSections || [];
  }, [academicSections]);

  // When class changes, reset section if invalid
  const handleClassChange = (newClass: string) => {
    setSelectedClass(newClass);
    setSelectedSection('all');
  };

  // Exam terms filtered by selected session (if applicable)
  const filteredExamTerms = useMemo(() => {
    if (!examTerms || examTerms.length === 0) return [];
    const matched = examTerms.filter(t => !t.year || t.year === selectedSession);
    return matched.length > 0 ? matched : examTerms;
  }, [examTerms, selectedSession]);

  // Active exam object
  const currentExamObj = useMemo(() => {
    return (examTerms || []).find(t => t.id === selectedExamId) || filteredExamTerms[0];
  }, [examTerms, filteredExamTerms, selectedExamId]);

  // Matching student count for current filter
  const matchingStudentCount = useMemo(() => {
    return (students || []).filter(st => {
      const matchCls = isClassMatch(st, selectedClass, academicClasses);
      const matchSec = selectedSection === 'all' || isSectionMatch(st, selectedSection, academicSections);
      const matchSes = isSessionMatch(st, selectedSession, academicSessions);
      return matchCls && matchSec && matchSes;
    }).length;
  }, [students, selectedClass, selectedSection, selectedSession, academicClasses, academicSections, academicSessions]);

  return (
    <div className="space-y-5">
      {/* 1. Minimal Unified Dashboard Header */}
      <div className="flex flex-col sm:flex-row sm:items-center justify-between gap-3 pb-3 border-b border-slate-200">
        <div>
          <h1 className="text-xl sm:text-2xl font-bold text-slate-900 tracking-tight flex items-center gap-2">
            <span>{isBn ? BN_DICT['examination_dashboard'] : EN_DICT['examination_dashboard']}</span>
            <span className="hidden sm:inline-flex items-center gap-1 text-[11px] font-semibold px-2.5 py-0.5 rounded-full bg-indigo-50 text-indigo-700 border border-indigo-200">
              <Sparkles className="w-3 h-3" />
              {isBn ? BN_DICT['unified'] : EN_DICT['unified']}
            </span>
          </h1>
          <p className="text-xs text-slate-500 mt-0.5">
            {isBn ? BN_DICT['centralized_control_for_routin'] : EN_DICT['centralized_control_for_routin']}
          </p>
        </div>

        {/* Quick Context Pill */}
        {currentExamObj && (
          <div className="flex items-center gap-2 px-3 py-1.5 rounded-xl bg-white border border-slate-200 shadow-2xs text-xs self-start sm:self-auto">
            <span className="w-2 h-2 rounded-full bg-emerald-500 animate-pulse" />
            <span className="font-semibold text-slate-700">
              {isBn ? (currentExamObj.nameBn || currentExamObj.name) : currentExamObj.name}
            </span>
            <span className="text-slate-400">|</span>
            <span className="text-slate-500 font-medium">{selectedSession}</span>
          </div>
        )}
      </div>

      {/* 2. Global Persistent Filter Bar */}
      <div className="bg-white p-3.5 sm:p-4 rounded-2xl border border-slate-200 shadow-xs">
        <div className="flex flex-col lg:flex-row lg:items-center justify-between gap-3">
          {/* Controls Cluster */}
          <div className="grid grid-cols-2 sm:grid-cols-4 gap-2.5 flex-1">
            {/* Session / Academic Year */}
            <div>
              <label className="text-[11px] font-bold text-slate-500 uppercase tracking-wider block mb-1">
                {isBn ? BN_DICT['year_session_1'] : EN_DICT['year_session_1']}
              </label>
              <select
                value={selectedSession}
                onChange={(e) => setSelectedSession(e.target.value)}
                className="w-full text-xs font-semibold bg-slate-50 hover:bg-slate-100/80 border border-slate-200 rounded-xl px-2.5 py-2 text-slate-800 focus:outline-hidden focus:border-indigo-500 transition-colors"
              >
                {(academicSessions || []).map((ses) => (
                  <option key={ses.id} value={ses.name}>
                    {ses.name} {ses.isDefault ? (isBn ? BN_DICT['active_1'] : EN_DICT['active_1']) : ''}
                  </option>
                ))}
              </select>
            </div>

            {/* Exam Term */}
            <div>
              <label className="text-[11px] font-bold text-slate-500 uppercase tracking-wider block mb-1">
                {isBn ? BN_DICT['exam_term'] : EN_DICT['exam_term']}
              </label>
              <select
                value={selectedExamId}
                onChange={(e) => setSelectedExamId(e.target.value)}
                className="w-full text-xs font-semibold bg-slate-50 hover:bg-slate-100/80 border border-slate-200 rounded-xl px-2.5 py-2 text-slate-800 focus:outline-hidden focus:border-indigo-500 transition-colors"
              >
                {filteredExamTerms.map((term) => (
                  <option key={term.id} value={term.id}>
                    {isBn ? (term.nameBn || term.name) : term.name}
                  </option>
                ))}
              </select>
            </div>

            {/* Class */}
            <div>
              <label className="text-[11px] font-bold text-slate-500 uppercase tracking-wider block mb-1">
                {isBn ? BN_DICT['class_2'] : EN_DICT['class_2']}
              </label>
              <select
                value={selectedClass}
                onChange={(e) => handleClassChange(e.target.value)}
                className="w-full text-xs font-semibold bg-slate-50 hover:bg-slate-100/80 border border-slate-200 rounded-xl px-2.5 py-2 text-slate-800 focus:outline-hidden focus:border-indigo-500 transition-colors"
              >
                {(academicClasses || []).map((cls) => (
                  <option key={cls.id} value={cls.nameBn || cls.name}>
                    {isBn ? (cls.nameBn || cls.name) : cls.name}
                  </option>
                ))}
              </select>
            </div>

            {/* Section */}
            <div>
              <label className="text-[11px] font-bold text-slate-500 uppercase tracking-wider block mb-1">
                {isBn ? BN_DICT['section_2'] : EN_DICT['section_2']}
              </label>
              <select
                value={selectedSection}
                onChange={(e) => setSelectedSection(e.target.value)}
                className="w-full text-xs font-semibold bg-slate-50 hover:bg-slate-100/80 border border-slate-200 rounded-xl px-2.5 py-2 text-slate-800 focus:outline-hidden focus:border-indigo-500 transition-colors"
              >
                <option value="all">{isBn ? BN_DICT['all_sections'] : EN_DICT['all_sections']}</option>
                {availableSections.map((sec) => (
                  <option key={sec.id} value={sec.nameBn || sec.name}>
                    {sec.name} {sec.nameBn ? `(${sec.nameBn})` : ''}
                  </option>
                ))}
              </select>
            </div>
          </div>

          {/* Quick Counter Chip */}
          <div className="shrink-0 flex items-center lg:flex-col lg:items-end justify-between border-t lg:border-t-0 pt-2 lg:pt-0 border-slate-100">
            <span className="text-[11px] text-slate-400 font-medium">
              {isBn ? BN_DICT['enrolled_students'] : EN_DICT['enrolled_students']}
            </span>
            <div className="inline-flex items-center gap-1.5 text-xs font-bold text-slate-800 bg-slate-100/80 px-2.5 py-1 rounded-lg">
              <Users className="w-3.5 h-3.5 text-indigo-600" />
              <span>{matchingStudentCount} {isBn ? BN_DICT['students_1'] : EN_DICT['students_1']}</span>
            </div>
          </div>
        </div>
      </div>

      {/* 3. Clean Single-View Tab Navigation */}
      <div className="bg-slate-200/70 p-1 rounded-2xl flex items-center overflow-x-auto scrollbar-none gap-1 border border-slate-200">
        {DASHBOARD_TABS.map((tab) => {
          const Icon = tab.icon;
          const isActive = activeTab === tab.id;
          return (
            <button
              key={tab.id}
              onClick={() => handleTabChange(tab.id)}
              className={`flex-1 min-w-max flex items-center justify-center gap-2 px-3.5 py-2 rounded-xl text-xs font-bold transition-all ${
                isActive 
                  ? 'bg-white text-indigo-600 shadow-xs' 
                  : 'text-slate-600 hover:text-slate-900 hover:bg-white/50'
              }`}
            >
              <Icon className={`w-4 h-4 shrink-0 ${isActive ? 'text-indigo-600' : 'text-slate-500'}`} />
              <span>{isBn ? tab.labelBn : tab.labelEn}</span>
            </button>
          );
        })}
      </div>

      {/* 4. Tab Content: Render Selected Functionality with Shared Filters */}
      <div className="min-h-[480px]">
        {activeTab === 'results' && (
          <ExamResults
            initialSession={selectedSession}
            initialClass={selectedClass}
            initialSection={selectedSection}
            initialExamId={selectedExamId}
            hideTopHeader={true}
          />
        )}

        {activeTab === 'routine' && (
          <ExamRoutine
            initialClass={selectedClass}
            initialExamId={selectedExamId}
            hideTopHeader={true}
          />
        )}

        {activeTab === 'admit-card' && (
          <AdmitCard
            initialClass={selectedClass}
            initialSection={selectedSection}
            initialExamId={selectedExamId}
            hideTopHeader={true}
          />
        )}

        {activeTab === 'seat-planning' && (
          <SeatPlanning
            initialClass={selectedClass}
            initialExamId={selectedExamId}
            hideTopHeader={true}
          />
        )}

        {activeTab === 'certificates' && (
          <Certificates
            initialClass={selectedClass}
            hideTopHeader={true}
          />
        )}

        {activeTab === 'settings' && (
          <ExamSettings
            hideTopHeader={true}
          />
        )}
      </div>
    </div>
  );
};

export default ExamHome;
