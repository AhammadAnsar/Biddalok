import { EN_DICT, BN_DICT } from "../../../locales/autoGenerated";
import React, { useState, useMemo, useEffect } from 'react';
import { useAppStore } from '../../../store/useAppStore';
import { Search, Plus, Eye, Printer, Edit3, Trash2, Award, FileDown, Loader2, Sliders } from 'lucide-react';
import { toBengaliNumber } from '../../../utils/bengaliUtils';
import { ScholarshipRecord } from '../../../types';
import ScholarshipEntryModal from '../modals/ScholarshipEntryModal';
import ScholarshipPrintView from '../ScholarshipPrintView';
import { RevenueScholarshipRegisterModal } from './RevenueScholarshipRegisterModal';
import { downloadRevenueScholarshipFormPdf, downloadRevenueScholarshipRegisterPdf } from '../utils/revenueScholarshipPdfExporter';
import {
  ScholarshipFormSettings,
  getSavedScholarshipSettings,
} from '../types/scholarshipSettings';
import { ScholarshipLogoSettingsModal } from './ScholarshipLogoSettingsModal';
import { toast } from 'react-hot-toast';

export const RevenueScholarshipTab: React.FC = () => {
  const { scholarships, students, deleteScholarship, language, institution, staff } = useAppStore();
  const isBn = language === 'bn';
  const [searchQuery, setSearchQuery] = useState('');
  
  const [isEntryModalOpen, setIsEntryModalOpen] = useState(false);
  const [selectedRecordForEdit, setSelectedRecordForEdit] = useState<ScholarshipRecord | null>(null);
  
  const [selectedRecordForPrint, setSelectedRecordForPrint] = useState<ScholarshipRecord | null>(null);
  const [isRegisterModalOpen, setIsRegisterModalOpen] = useState(false);
  const [isLogoSettingsOpen, setIsLogoSettingsOpen] = useState(false);
  const [settings, setSettings] = useState<ScholarshipFormSettings>(getSavedScholarshipSettings());

  useEffect(() => {
    const handleSettingsUpdated = (e: any) => {
      if (e.detail) {
        setSettings(e.detail);
      }
    };
    window.addEventListener('biddalok-scholarship-settings-updated', handleSettingsUpdated);
    return () => {
      window.removeEventListener('biddalok-scholarship-settings-updated', handleSettingsUpdated);
    };
  }, []);

  const [isDownloadingRegister, setIsDownloadingRegister] = useState(false);
  const [downloadingFormRecordId, setDownloadingFormRecordId] = useState<string | null>(null);

  // Relational headmaster signature resolution per AGENTS.md rule
  const principalStaff = (staff || []).find(
    (s) =>
      s.designationId === 'des_head_teacher' ||
      s.designation === 'Head Teacher' ||
      s.designation === 'প্রধান শিক্ষক' ||
      s.designationBn === 'প্রধান শিক্ষক'
  );

  const headmasterSignatureUrl =
    principalStaff && principalStaff.signaturePhoto
      ? principalStaff.signaturePhoto
      : institution.headmasterSignature;

  const revenueScholarships = useMemo(() => {
    return (scholarships || []).filter(
      (s) => s.examType === 'PEC' || s.examType === 'JSC' || s.examType === 'SSC' || s.examType === 'HSC' ||
             s.examType === 'Ebtedaee' || s.examType === 'JDC' || s.examType === 'Dakhil' || s.examType === 'Alim' ||
             s.examType === 'Other'
    );
  }, [scholarships]);

  const filteredList = useMemo(() => {
    if (!searchQuery) return revenueScholarships;
    const q = searchQuery.toLowerCase();
    return revenueScholarships.filter((s) => {
      const student = students?.find((st) => st.id === s.studentId);
      const studentName = student?.nameBn || student?.name || '';
      return (
        studentName.toLowerCase().includes(q) ||
        s.financialYear?.toLowerCase().includes(q) ||
        s.enrollmentYear?.toLowerCase().includes(q) ||
        student?.studentId?.toLowerCase().includes(q)
      );
    });
  }, [revenueScholarships, searchQuery, students]);

  const handleDelete = (id: string) => {
    if (window.confirm(isBn ? BN_DICT['are_you_sure_you_want_to_delet_4'] : EN_DICT['are_you_sure_you_want_to_delet_4'])) {
      deleteScholarship(id);
      toast.success(isBn ? BN_DICT['record_deleted'] : EN_DICT['record_deleted']);
    }
  };

  // Direct download of individual student's filled scholarship form (A4 Portrait)
  const handleDownloadSingleForm = async (record: ScholarshipRecord) => {
    const student = students.find((s) => s.id === record.studentId);
    try {
      setDownloadingFormRecordId(record.id);
      toast.loading(isBn ? BN_DICT['generating_form_pdf'] : EN_DICT['generating_form_pdf'], { id: 'single-form-pdf' });
      await downloadRevenueScholarshipFormPdf(record, student, institution, headmasterSignatureUrl, settings);
      toast.success(isBn ? BN_DICT['form_pdf_downloaded_successful'] : EN_DICT['form_pdf_downloaded_successful'], { id: 'single-form-pdf' });
    } catch (err: any) {
      toast.error(err.message || (isBn ? BN_DICT['failed_to_generate_pdf_1'] : EN_DICT['failed_to_generate_pdf_1']), { id: 'single-form-pdf' });
    } finally {
      setDownloadingFormRecordId(null);
    }
  };

  // Direct download of full scholarship register (A4 Landscape)
  const handleDownloadRegister = async () => {
    if (filteredList.length === 0) {
      toast.error(isBn ? BN_DICT['no_scholarship_records_to_down'] : EN_DICT['no_scholarship_records_to_down']);
      return;
    }

    try {
      setIsDownloadingRegister(true);
      toast.loading(isBn ? BN_DICT['generating_register_pdf'] : EN_DICT['generating_register_pdf'], { id: 'reg-pdf-toast' });
      await downloadRevenueScholarshipRegisterPdf(filteredList, students, institution, {
        financialYear: filteredList[0]?.financialYear,
        headmasterSignatureUrl,
        customSettings: settings,
      });
      toast.success(isBn ? BN_DICT['register_pdf_downloaded_succes'] : EN_DICT['register_pdf_downloaded_succes'], { id: 'reg-pdf-toast' });
    } catch (err: any) {
      toast.error(err.message || (isBn ? BN_DICT['failed_to_download_register_pd'] : EN_DICT['failed_to_download_register_pd']), { id: 'reg-pdf-toast' });
    } finally {
      setIsDownloadingRegister(false);
    }
  };

  if (selectedRecordForPrint) {
    return (
      <ScholarshipPrintView 
        record={selectedRecordForPrint} 
        onClose={() => setSelectedRecordForPrint(null)} 
      />
    );
  }

  return (
    <div className="flex flex-col h-full">
      {/* Search & Actions Bar */}
      <div className="p-4 sm:p-6 border-b border-slate-100 flex flex-col sm:flex-row sm:items-center justify-between gap-4 print:hidden">
        <div className="relative flex-1 w-full max-w-md">
          <Search className="w-4 h-4 text-slate-400 absolute left-3 top-1/2 -translate-y-1/2" />
          <input
            type="text"
            placeholder={isBn ? BN_DICT['search_by_name_id_or_financial'] : EN_DICT['search_by_name_id_or_financial']}
            value={searchQuery}
            onChange={(e) => setSearchQuery(e.target.value)}
            className="w-full pl-9 pr-4 py-2 text-xs border border-slate-200 rounded-xl focus:ring-2 focus:ring-amber-600 focus:outline-none bg-slate-50/50 hover:bg-white transition-colors"
          />
        </div>

        <div className="flex flex-wrap items-center gap-2.5">
          {/* Register PDF Download (A4 Landscape) Button */}
          <button
            type="button"
            disabled={isDownloadingRegister || filteredList.length === 0}
            onClick={handleDownloadRegister}
            className="px-3.5 py-2 rounded-xl bg-amber-50 hover:bg-amber-100 border border-amber-300/80 text-amber-900 text-xs font-bold transition-all flex items-center gap-1.5 shadow-xs cursor-pointer disabled:opacity-50"
            title={isBn ? BN_DICT['download_register_a4_landscape'] : EN_DICT['download_register_a4_landscape']}
          >
            {isDownloadingRegister ? (
              <>
                <Loader2 className="w-4 h-4 animate-spin text-amber-700" />
                <span>{isBn ? BN_DICT['downloading'] : EN_DICT['downloading']}</span>
              </>
            ) : (
              <>
                <FileDown className="w-4 h-4 text-amber-700" />
                <span>{isBn ? BN_DICT['register_pdf'] : EN_DICT['register_pdf']}</span>
                <span className="text-[10px] bg-amber-200/80 text-amber-900 font-semibold px-1.5 py-0.2 rounded-md">
                  {isBn ? BN_DICT['landscape'] : EN_DICT['landscape']}
                </span>
              </>
            )}
          </button>

          {/* Register Print / Preview Button */}
          <button
            type="button"
            onClick={() => setIsRegisterModalOpen(true)}
            className="px-3.5 py-2 rounded-xl bg-white hover:bg-slate-50 border border-slate-200 text-slate-700 text-xs font-bold transition-all flex items-center gap-1.5 shadow-xs cursor-pointer"
            title={isBn ? BN_DICT['preview_print_register'] : EN_DICT['preview_print_register']}
          >
            <Printer className="w-4 h-4 text-slate-600" />
            <span className="hidden sm:inline">{isBn ? BN_DICT['print_preview_register'] : EN_DICT['print_preview_register']}</span>
          </button>

          {/* Logo & Header Settings Button */}
          <button
            type="button"
            onClick={() => setIsLogoSettingsOpen(true)}
            className="px-3.5 py-2 rounded-xl bg-slate-100 hover:bg-amber-50 hover:text-amber-700 hover:border-amber-300 border border-slate-200 text-slate-700 text-xs font-bold transition-all flex items-center gap-1.5 shadow-xs cursor-pointer"
            title={isBn ? BN_DICT['change_logo_header_settings'] : EN_DICT['change_logo_header_settings']}
          >
            <Sliders className="w-4 h-4 text-amber-600" />
            <span>{isBn ? BN_DICT['logo_settings'] : EN_DICT['logo_settings']}</span>
          </button>

          {/* Add New Student Button */}
          <button
            type="button"
            onClick={() => {
              setSelectedRecordForEdit(null);
              setIsEntryModalOpen(true);
            }}
            className="px-4 py-2 rounded-xl bg-amber-600 hover:bg-amber-700 text-white text-xs font-black shadow-md shadow-amber-900/20 transition-all cursor-pointer flex items-center gap-1.5"
          >
            <Plus className="w-4 h-4" />
            <span>{isBn ? BN_DICT['add_new_student'] : EN_DICT['add_new_student']}</span>
          </button>
        </div>
      </div>

      {/* Main Table */}
      <div className="flex-1 overflow-x-auto p-4 sm:p-6">
        <table className="w-full text-left text-xs border-collapse">
          <thead className="bg-slate-50 text-slate-600 font-bold border-b border-slate-200/80">
            <tr>
              <th className="px-4 py-3 text-center w-12">{isBn ? BN_DICT['sl'] : EN_DICT['sl']}</th>
              <th className="px-4 py-3">{isBn ? BN_DICT['student_name_id'] : EN_DICT['student_name_id']}</th>
              <th className="px-4 py-3">{isBn ? BN_DICT['class_section_1'] : EN_DICT['class_section_1']}</th>
              <th className="px-4 py-3">{isBn ? BN_DICT['financial_year'] : EN_DICT['financial_year']}</th>
              <th className="px-4 py-3">{isBn ? BN_DICT['exam_type'] : EN_DICT['exam_type']}</th>
              <th className="px-4 py-3 text-right pr-6 print:hidden">{isBn ? BN_DICT['action'] : EN_DICT['action']}</th>
            </tr>
          </thead>
          <tbody className="divide-y divide-slate-100 font-medium">
            {filteredList.map((record, index) => {
              const student = students?.find((st) => st.id === record.studentId);
              const isRecordDownloading = downloadingFormRecordId === record.id;

              return (
                <tr key={record.id} className="hover:bg-amber-50/30 transition-colors">
                  <td className="px-4 py-3 text-center text-slate-400 font-mono">
                    {isBn ? toBengaliNumber(index + 1) : index + 1}
                  </td>
                  <td className="px-4 py-3">
                    <strong className="text-slate-900 block">{student?.nameBn || student?.name || 'অজানা'}</strong>
                    <span className="text-[10px] text-slate-500 font-mono">আইডি: {student?.studentId || record.studentId}</span>
                  </td>
                  <td className="px-4 py-3">
                    <div className="text-slate-800">{student?.class || '-'}</div>
                    <div className="text-[10px] text-slate-500">{student?.section || '-'}</div>
                  </td>
                  <td className="px-4 py-3">
                    <strong className="text-slate-700">{isBn ? toBengaliNumber(record.financialYear) : record.financialYear}</strong>
                  </td>
                  <td className="px-4 py-3">
                    <div className="flex flex-wrap items-center gap-1.5">
                      <span className="px-2 py-0.5 bg-slate-100 text-slate-700 rounded-md text-[10px] font-bold">
                        {record.examType}
                      </span>
                      <span
                        className={`px-2 py-0.5 rounded-md text-[10px] font-bold ${
                          record.scholarshipCategory === 'Merit' ? 'bg-amber-100 text-amber-800' : 'bg-blue-100 text-blue-800'
                        }`}
                      >
                        {record.scholarshipCategory === 'Merit' ? (isBn ? BN_DICT['merit'] : EN_DICT['merit']) : (isBn ? BN_DICT['general'] : EN_DICT['general'])}
                      </span>
                      {record.isDraft || record.verificationStatus === 'Draft' ? (
                        <span className="px-1.5 py-0.5 bg-amber-50 text-amber-700 border border-amber-200 rounded-md text-[9px] font-extrabold">
                          খসড়া
                        </span>
                      ) : record.verificationStatus === 'Discrepancy' ? (
                        <span className="px-1.5 py-0.5 bg-rose-50 text-rose-700 border border-rose-200 rounded-md text-[9px] font-bold">
                          তথ্যে অমিল
                        </span>
                      ) : (
                        <span className="px-1.5 py-0.5 bg-emerald-50 text-emerald-700 border border-emerald-200 rounded-md text-[9px] font-bold">
                          যাচাইকৃত
                        </span>
                      )}
                    </div>
                  </td>
                  <td className="px-4 py-3 text-right pr-6 print:hidden">
                    <div className="flex items-center justify-end gap-1">
                      {/* Direct PDF Download Button for Filled Form (A4 Portrait) */}
                      <button
                        type="button"
                        disabled={isRecordDownloading}
                        onClick={() => handleDownloadSingleForm(record)}
                        className="p-1.5 text-amber-700 hover:text-amber-900 hover:bg-amber-100/80 rounded-lg transition-all cursor-pointer disabled:opacity-50"
                        title={isBn ? BN_DICT['download_filled_form_pdf_a4_po'] : EN_DICT['download_filled_form_pdf_a4_po']}
                      >
                        {isRecordDownloading ? (
                          <Loader2 className="w-4 h-4 animate-spin text-amber-700" />
                        ) : (
                          <FileDown className="w-4 h-4" />
                        )}
                      </button>

                      {/* View & Print Form Button */}
                      <button
                        type="button"
                        onClick={() => setSelectedRecordForPrint(record)}
                        className="p-1.5 text-slate-400 hover:text-slate-700 hover:bg-slate-100 rounded-lg transition-all cursor-pointer"
                        title={isBn ? BN_DICT['view_print_form'] : EN_DICT['view_print_form']}
                      >
                        <Eye className="w-4 h-4" />
                      </button>

                      {/* Edit Button */}
                      <button
                        type="button"
                        onClick={() => {
                          setSelectedRecordForEdit(record);
                          setIsEntryModalOpen(true);
                        }}
                        className="p-1.5 text-slate-400 hover:text-indigo-700 hover:bg-indigo-50 rounded-lg transition-all cursor-pointer"
                        title={isBn ? BN_DICT['edit'] : EN_DICT['edit']}
                      >
                        <Edit3 className="w-4 h-4" />
                      </button>

                      {/* Delete Button */}
                      <button
                        type="button"
                        onClick={() => handleDelete(record.id)}
                        className="p-1.5 text-slate-400 hover:text-rose-700 hover:bg-rose-50 rounded-lg transition-all cursor-pointer"
                        title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
                      >
                        <Trash2 className="w-4 h-4" />
                      </button>
                    </div>
                  </td>
                </tr>
              );
            })}
          </tbody>
        </table>

        {filteredList.length === 0 && (
          <div className="p-12 text-center flex flex-col items-center justify-center">
            <div className="w-16 h-16 bg-slate-50 rounded-full flex items-center justify-center mb-3">
              <Award className="w-8 h-8 text-slate-300" />
            </div>
            <p className="text-slate-500 text-sm">{isBn ? BN_DICT['no_scholarship_records_found'] : EN_DICT['no_scholarship_records_found']}</p>
          </div>
        )}
      </div>

      {/* Entry / Edit Modal */}
      {isEntryModalOpen && (
        <ScholarshipEntryModal
          isOpen={isEntryModalOpen}
          onClose={() => {
            setIsEntryModalOpen(false);
            setSelectedRecordForEdit(null);
          }}
          initialData={selectedRecordForEdit}
        />
      )}

      {/* Register Preview & Print Modal */}
      {isRegisterModalOpen && (
        <RevenueScholarshipRegisterModal
          isOpen={isRegisterModalOpen}
          onClose={() => setIsRegisterModalOpen(false)}
          records={filteredList}
          students={students}
          institution={institution}
          financialYear={filteredList[0]?.financialYear}
          headmasterSignatureUrl={headmasterSignatureUrl}
        />
      )}

      {/* Logo & Header Settings Modal */}
      <ScholarshipLogoSettingsModal
        isOpen={isLogoSettingsOpen}
        onClose={() => setIsLogoSettingsOpen(false)}
        currentSettings={settings}
        institution={institution}
        onSave={(updated) => setSettings(updated)}
      />
    </div>
  );
};
