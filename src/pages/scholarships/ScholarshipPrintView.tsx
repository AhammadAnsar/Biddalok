import { EN_DICT, BN_DICT } from "../../locales/autoGenerated";
import React, { useState, useEffect } from 'react';
import { ArrowLeft, Printer, FileDown, Loader2, Sliders } from 'lucide-react';
import { useAppStore } from '../../store/useAppStore';
import { ScholarshipRecord } from '../../types';
import { RevenueScholarshipFormDocument } from './components/RevenueScholarshipFormDocument';
import { downloadRevenueScholarshipFormPdf } from './utils/revenueScholarshipPdfExporter';
import {
  ScholarshipFormSettings,
  ScholarshipPageLayoutMode,
  getSavedScholarshipSettings,
  saveScholarshipSettings,
} from './types/scholarshipSettings';
import { ScholarshipLogoSettingsModal } from './components/ScholarshipLogoSettingsModal';
import { toast } from 'react-hot-toast';

interface ScholarshipPrintViewProps {
  record: ScholarshipRecord;
  onClose: () => void;
}

export default function ScholarshipPrintView({ record, onClose }: ScholarshipPrintViewProps) {
  const { students, language, institution, staff } = useAppStore();
  const isBn = language === 'bn';
  const [isDownloading, setIsDownloading] = useState(false);
  const [isSettingsOpen, setIsSettingsOpen] = useState(false);
  const [settings, setSettings] = useState<ScholarshipFormSettings>(getSavedScholarshipSettings());
  const [pageMode, setPageMode] = useState<ScholarshipPageLayoutMode>(
    settings.pageLayoutMode || 'two_page'
  );

  useEffect(() => {
    const handleSettingsUpdated = (e: any) => {
      if (e.detail) {
        setSettings(e.detail);
        if (e.detail.pageLayoutMode) {
          setPageMode(e.detail.pageLayoutMode);
        }
      }
    };
    window.addEventListener('biddalok-scholarship-settings-updated', handleSettingsUpdated);
    return () => {
      window.removeEventListener('biddalok-scholarship-settings-updated', handleSettingsUpdated);
    };
  }, []);

  const handleLayoutModeChange = (mode: ScholarshipPageLayoutMode) => {
    setPageMode(mode);
    const updated = { ...settings, pageLayoutMode: mode };
    setSettings(updated);
    saveScholarshipSettings(updated);
    toast.success(
      mode === 'single'
        ? (isBn ? 'এক পাতার কমপ্যাক্ট লেআউট সক্রিয় করা হয়েছে' : 'Single-page compact layout activated')
        : (isBn ? 'দুই পাতার সুষম লেআউট সক্রিয় করা হয়েছে' : 'Two-page spacious layout activated')
    );
  };

  const student = students.find((s) => s.id === record.studentId);

  // Relational headmaster signature resolution per AGENTS.md rule
  const principalStaff = (staff || []).find(
    (s) =>
      s.designationId === 'des_head_teacher' ||
      s.designation === 'Head Teacher' ||
      s.designation === 'প্রধান শিক্ষক' ||
      s.designationBn === 'প্রধান শিক্ষক'
  );

  const headmasterSignatureUrl =
    principalStaff && principalStaff.signaturePhoto
      ? principalStaff.signaturePhoto
      : institution.headmasterSignature;

  const handleDownloadPdf = async () => {
    try {
      setIsDownloading(true);
      toast.loading(isBn ? BN_DICT['generating_form_pdf'] : EN_DICT['generating_form_pdf'], { id: 'form-pdf' });
      await downloadRevenueScholarshipFormPdf(record, student, institution, headmasterSignatureUrl, {
        ...settings,
        pageLayoutMode: pageMode,
      });
      toast.success(isBn ? BN_DICT['form_pdf_downloaded_successful'] : EN_DICT['form_pdf_downloaded_successful'], { id: 'form-pdf' });
    } catch (err: any) {
      toast.error(err.message || (isBn ? BN_DICT['failed_to_download_pdf'] : EN_DICT['failed_to_download_pdf']), { id: 'form-pdf' });
    } finally {
      setIsDownloading(false);
    }
  };

  return (
    <div className="space-y-6 pb-12">
      {/* Top Action Bar (Hidden on print) */}
      <div className="bg-white p-4 rounded-2xl border border-slate-200/90 shadow-sm flex flex-wrap items-center justify-between gap-3 print:hidden">
        <button
          type="button"
          onClick={onClose}
          className="px-4 py-2 rounded-xl bg-slate-100 hover:bg-slate-200 text-slate-700 text-xs font-bold transition-all flex items-center gap-1.5 cursor-pointer"
        >
          <ArrowLeft className="w-4 h-4" />
          <span>{isBn ? BN_DICT['back'] : EN_DICT['back']}</span>
        </button>

        {/* Center: 1-Page vs 2-Page Segmented Toggle */}
        <div className="flex items-center bg-slate-100 p-1 rounded-xl border border-slate-200/90 shadow-2xs">
          <button
            type="button"
            onClick={() => handleLayoutModeChange('single')}
            className={`px-3.5 py-1.5 rounded-lg text-xs font-bold transition-all flex items-center gap-1.5 cursor-pointer ${
              pageMode === 'single'
                ? 'bg-white text-slate-950 shadow-xs border border-slate-300/80 font-black'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <span className="w-2 h-2 rounded-full bg-amber-500 inline-block" />
            <span>এক পাতা ফরম</span>
          </button>

          <button
            type="button"
            onClick={() => handleLayoutModeChange('two_page')}
            className={`px-3.5 py-1.5 rounded-lg text-xs font-bold transition-all flex items-center gap-1.5 cursor-pointer ${
              pageMode === 'two_page'
                ? 'bg-white text-slate-950 shadow-xs border border-slate-300/80 font-black'
                : 'text-slate-600 hover:text-slate-900'
            }`}
          >
            <span className="w-2 h-2 rounded-full bg-emerald-600 inline-block" />
            <span>দুই পাতা ফরম</span>
          </button>
        </div>

        <div className="flex items-center gap-2">
          {/* Font, Logo & Layout Customization Modal Trigger */}
          <button
            type="button"
            onClick={() => setIsSettingsOpen(true)}
            className="px-4 py-2 rounded-xl bg-slate-100 hover:bg-amber-50 hover:text-amber-700 hover:border-amber-300 border border-slate-200 text-slate-700 text-xs font-bold transition-all flex items-center gap-2 cursor-pointer shadow-xs"
            title="ফন্ট, টেবিল রো সাইজ, লোগো ও লেআউট পরিবর্তন করুন"
          >
            <Sliders className="w-4 h-4 text-amber-600" />
            <span>{isBn ? 'ফন্ট ও লেআউট সেটিংস' : 'Font Settings'}</span>
          </button>

          {/* Download PDF Button */}
          <button
            type="button"
            disabled={isDownloading}
            onClick={handleDownloadPdf}
            className="px-4 py-2 rounded-xl bg-amber-600 hover:bg-amber-700 text-white text-xs font-black shadow-md shadow-amber-900/20 transition-all flex items-center gap-2 cursor-pointer disabled:opacity-60"
          >
            {isDownloading ? (
              <>
                <Loader2 className="w-4 h-4 animate-spin" />
                <span>{isBn ? 'পিডিএফ তৈরি হচ্ছে...' : 'Generating...'}</span>
              </>
            ) : (
              <>
                <FileDown className="w-4 h-4" />
                <span>
                  {pageMode === 'single'
                    ? (isBn ? 'পিডিএফ ডাউনলোড (১ পাতা)' : 'Download PDF (1 Page)')
                    : (isBn ? 'পিডিএফ ডাউনলোড (২ পাতা)' : 'Download PDF (2 Pages)')}
                </span>
              </>
            )}
          </button>

          {/* Direct Print Button */}
          <button
            type="button"
            onClick={() => window.print()}
            className="px-4 py-2 rounded-xl bg-slate-800 hover:bg-slate-900 text-white text-xs font-bold shadow transition-all flex items-center gap-2 cursor-pointer"
          >
            <Printer className="w-4 h-4" />
            <span>{isBn ? 'প্রিন্ট করুন' : 'Print Form'}</span>
          </button>
        </div>
      </div>

      {/* Screen Preview and Print Container */}
      <div className="flex justify-center p-2 overflow-x-auto bg-slate-200/60 rounded-2xl border border-slate-300/80 py-8 print:p-0 print:m-0 print:bg-white print:border-none">
        <div className="print:shadow-none bg-transparent">
          <RevenueScholarshipFormDocument
            record={record}
            student={student}
            institution={institution}
            headmasterSignatureUrl={headmasterSignatureUrl}
            settings={settings}
            layoutMode={pageMode}
            onOpenLogoSettings={() => setIsSettingsOpen(true)}
          />
        </div>
      </div>

      {/* Logo & Header Settings Modal */}
      <ScholarshipLogoSettingsModal
        isOpen={isSettingsOpen}
        onClose={() => setIsSettingsOpen(false)}
        currentSettings={{ ...settings, pageLayoutMode: pageMode }}
        institution={institution}
        onSave={(updated) => {
          setSettings(updated);
          if (updated.pageLayoutMode) {
            setPageMode(updated.pageLayoutMode);
          }
        }}
      />

      <style>{`
        @media print {
          @page {
            size: A4 portrait;
            margin: 0;
          }
          body {
            background: white !important;
            margin: 0 !important;
            padding: 0 !important;
          }
          .revenue-scholarship-form-container {
            margin: 0 !important;
            padding: 0 !important;
            gap: 0 !important;
          }
          .revenue-scholarship-page {
            margin: 0 auto !important;
            box-shadow: none !important;
            page-break-after: always !important;
            break-after: page !important;
            height: 1123px !important;
            max-height: 1123px !important;
          }
          .revenue-scholarship-page:last-child {
            page-break-after: avoid !important;
            break-after: avoid !important;
          }
        }
      `}</style>
    </div>
  );
}
