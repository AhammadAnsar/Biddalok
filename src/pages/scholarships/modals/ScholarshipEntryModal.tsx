// Helper to convert Bengali digits to ASCII while preserving leading zeros
function normalizeDigits(str: string): string {
  if (!str) return '';
  const bnToEnMap: Record<string, string> = {
    '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
    '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9'
  };
  return str.replace(/[০-৯]/g, (d) => bnToEnMap[d] || d).trim();
}

// Award level resolver to enforce uniqueness
function getAwardLevelKey(examType?: string): string {
  if (!examType) return 'other';
  if (examType === 'PEC' || examType === 'Ebtedaee') return 'primary';
  if (examType === 'JSC' || examType === 'JDC') return 'junior';
  if (examType === 'SSC' || examType === 'Dakhil') return 'secondary';
  if (examType === 'HSC' || examType === 'Alim') return 'higher_secondary';
  return examType;
}

