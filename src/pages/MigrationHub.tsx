import { EN_DICT, BN_DICT } from "../locales/autoGenerated";
import React, { useState } from 'react';
import { Shield, Play, Save, CheckCircle, Database } from 'lucide-react';
import { useAuthStore } from '../store/useAuthStore';

function getDesktopApi() {
  return typeof window !== 'undefined' ? (window as any).desktopApi : null;
}

export const MigrationHub: React.FC = () => {
  const isBn = true; // Hardcoded for simplified Phase 5 UI
  const [dryRunData, setDryRunData] = useState<any>(null);
  const [isLoading, setIsLoading] = useState(false);
  const [isExecuting, setIsExecuting] = useState(false);
  const [executionResult, setExecutionResult] = useState<any>(null);

  const handleDryRun = async () => {
    setIsLoading(true);
    try {
      const api = getDesktopApi();
      if (!api) throw new Error('Desktop API required');
      const token = localStorage.getItem('sessionToken');
      const res = await api.db.migratePhase5DryRun(token);
      if (res.success) {
        setDryRunData(res.payload);
      } else {
        alert('Dry run failed: ' + res.error);
      }
    } catch (e: any) {
      alert(e.message);
    } finally {
      setIsLoading(false);
    }
  };

  const handleExecute = async () => {
    if (!confirm(isBn ? BN_DICT['are_you_sure_you_want_to_execu'] : EN_DICT['are_you_sure_you_want_to_execu'])) return;
    setIsExecuting(true);
    try {
      const api = getDesktopApi();
      const token = localStorage.getItem('sessionToken');
      const res = await api.db.migratePhase5Execute(token);
      if (res.success) {
        setExecutionResult(res);
      } else {
        alert('Execution failed: ' + res.error);
      }
    } catch (e: any) {
      alert(e.message);
    } finally {
      setIsExecuting(false);
    }
  };

  return (
    <div className="p-6 max-w-4xl mx-auto space-y-6">
      <div className="bg-white p-6 rounded-lg shadow-sm border border-gray-200">
        <h2 className="text-xl font-bold mb-4 flex items-center gap-2">
          <Database className="w-6 h-6 text-indigo-600" />
          {isBn ? BN_DICT['phase_05_database_migration'] : EN_DICT['phase_05_database_migration']}
        </h2>
        <p className="text-gray-600 mb-6">
          {isBn ? BN_DICT['converts_legacy_flat_json_stud'] : EN_DICT['converts_legacy_flat_json_stud']}
        </p>

        {!dryRunData && !executionResult && (
          <button 
            onClick={handleDryRun}
            disabled={isLoading}
            className="flex items-center gap-2 px-4 py-2 bg-indigo-600 text-white rounded hover:bg-indigo-700 disabled:opacity-50"
          >
            <Play className="w-4 h-4" />
            {isLoading ? (isBn ? BN_DICT['scanning'] : EN_DICT['scanning']) : (isBn ? BN_DICT['start_dry_run'] : EN_DICT['start_dry_run'])}
          </button>
        )}

        {dryRunData && !executionResult && (
          <div className="space-y-4">
            <div className="grid grid-cols-3 gap-4 mb-4">
              <div className="p-4 bg-blue-50 border border-blue-100 rounded">
                <p className="text-sm text-blue-600 font-semibold">{isBn ? BN_DICT['total_legacy_records'] : EN_DICT['total_legacy_records']}</p>
                <p className="text-2xl font-bold">{dryRunData.total}</p>
              </div>
              <div className="p-4 bg-yellow-50 border border-yellow-100 rounded">
                <p className="text-sm text-yellow-600 font-semibold">{isBn ? BN_DICT['duplicates'] : EN_DICT['duplicates']}</p>
                <p className="text-2xl font-bold">{dryRunData.duplicates}</p>
              </div>
              <div className="p-4 bg-red-50 border border-red-100 rounded">
                <p className="text-sm text-red-600 font-semibold">{isBn ? BN_DICT['orphan_records'] : EN_DICT['orphan_records']}</p>
                <p className="text-2xl font-bold">{dryRunData.orphans}</p>
              </div>
            </div>

            <div className="max-h-60 overflow-y-auto border border-gray-200 rounded p-4 bg-gray-50 text-sm font-mono">
              {dryRunData.mappings.slice(0, 50).map((m: any, idx: number) => (
                <div key={idx} className="flex justify-between py-1 border-b border-gray-200 last:border-0">
                  <span>{m.name || 'Unknown'}</span>
                  <span className="text-gray-500">{m.originalId} &rarr; {m.newStudentId}</span>
                </div>
              ))}
              {dryRunData.mappings.length > 50 && (
                <div className="text-center py-2 text-gray-500">...and {dryRunData.mappings.length - 50} more</div>
              )}
            </div>

            <button 
              onClick={handleExecute}
              disabled={isExecuting}
              className="flex items-center gap-2 px-4 py-2 bg-green-600 text-white rounded hover:bg-green-700 disabled:opacity-50"
            >
              <Save className="w-4 h-4" />
              {isExecuting ? (isBn ? BN_DICT['executing'] : EN_DICT['executing']) : (isBn ? BN_DICT['confirm_execute'] : EN_DICT['confirm_execute'])}
            </button>
          </div>
        )}

        {executionResult && (
          <div className="p-6 bg-green-50 border border-green-200 rounded flex flex-col items-center">
            <CheckCircle className="w-12 h-12 text-green-500 mb-4" />
            <h3 className="text-lg font-bold text-green-800">
              {isBn ? BN_DICT['migration_successful'] : EN_DICT['migration_successful']}
            </h3>
            <p className="text-green-700">
              {isBn 
                ? `মোট ${executionResult.count} টি রেকর্ড নতুন স্কিমায় স্থানান্তরিত হয়েছে।`
                : `${executionResult.count} records have been migrated to the new schema.`}
            </p>
          </div>
        )}
      </div>
    </div>
  );
};
