import { EN_DICT, BN_DICT } from "../../../locales/autoGenerated";
import React from 'react';
import { useAppStore } from '../../../store/useAppStore';
import { getBengaliFormattedDate, toBengaliNumber } from '../../../utils/bengaliUtils';
import { getLocationDisplayName } from '../../../utils/locationUtils';
import { useMasterData } from '../../../hooks/useMasterData';

export interface InvitationData {
  memoNo: string;
  issueDate: string;
  subject: string;
  greeting: string;
  bodyText: string;
  eventName: string;
  eventDate: string;
  eventTime: string;
  venue: string;
  chiefGuest: string;
  specialGuests: string;
  president: string;
  signatoryName: string;
  signatoryTitle: string;
  signatorySignature?: string;
  showHeader: boolean; // if false, use official pad
  themeColor: string;
  titleFontSize: number;
  bodyFontSize: number;
  bodyLineHeight: number;
  pageMargin: number;
  frameStyle: 'none' | 'simple' | 'double' | 'corner' | 'royal' | 'academic';
  layoutFormat: 'portrait' | 'landscape';
}

interface InvitationTemplateProps {
  data: InvitationData;
}


export const InvitationTemplate = React.forwardRef<HTMLDivElement, InvitationTemplateProps>(({ data }, ref) => {
  const { institution, language } = useAppStore();
  // const { learnedLocations } = useMasterData();
  const isBn = language === 'bn';

  // Institution Metadata
  const schoolName = isBn 
    ? (institution?.nameBn || institution?.name || '')
    : (institution?.name || institution?.nameBn || '');
  
  const rawInstPostOffice = institution?.postOffice || institution?.defaultPostOffice || '';
  const rawInstUpazila = institution?.upazila || institution?.defaultUpazila || '';
  const rawInstDistrict = institution?.district || institution?.defaultDistrict || '';
  
  const postOffice = getLocationDisplayName(rawInstPostOffice, [], 'bn') || rawInstPostOffice || '';
  const upazila = getLocationDisplayName(rawInstUpazila, [], 'bn') || rawInstUpazila || '';
  const district = getLocationDisplayName(rawInstDistrict, [], 'bn') || rawInstDistrict || '';

  const postOfficeEn = getLocationDisplayName(rawInstPostOffice, [], 'en') || rawInstPostOffice || '';
  const upazilaEn = getLocationDisplayName(rawInstUpazila, [], 'en') || rawInstUpazila || '';
  const districtEn = getLocationDisplayName(rawInstDistrict, [], 'en') || rawInstDistrict || '';
  
  const address = isBn 
    ? `ডাকঘর-${postOffice}, উপজেলা-${upazila}, জেলা-${district}`
    : `P.O-${postOfficeEn}, Upazila-${upazilaEn}, District-${districtEn}`;

  const estYear = isBn 
    ? toBengaliNumber(institution?.establishedYear || institution?.established || '')
    : (institution?.establishedYear || institution?.established || '');
  
  const eiin = isBn ? toBengaliNumber(institution?.eiin || '') : (institution?.eiin || '');
  const mpo = isBn ? toBengaliNumber(institution?.mpoCode || '') : (institution?.mpoCode || '');
  const schoolCode = isBn ? toBengaliNumber(institution?.schoolCode || '') : (institution?.schoolCode || '');
  const mobile = isBn ? toBengaliNumber(institution?.mobile || '') : (institution?.mobile || '');
  const email = institution?.email || '';
  const website = institution?.website || '';

  // Calculate dynamic styling based on settings
  const isLandscape = data.layoutFormat === 'landscape';
  const width = isLandscape ? '1123px' : '794px';
  const height = isLandscape ? '794px' : '1123px';
  
  const marginInches = data.pageMargin || 0.5;
  const paddingPx = Math.round(marginInches * 96);
  
  const memoText = data.memoNo || '..............................';
  const dateText = data.issueDate || getBengaliFormattedDate();

  return (
    <div 
      ref={ref}
      className="bg-white relative mx-auto overflow-hidden shadow-2xs print:shadow-none print:border-none"
      style={{ 
        width, 
        height, 
        padding: `${paddingPx}px`,
        boxSizing: 'border-box'
      }}
    >
      {/* Selected Frame */}
      {data.frameStyle !== 'none' && (
        <div 
          className="absolute pointer-events-none z-0"
          style={{
            top: `${Math.max(10, paddingPx - 20)}px`,
            left: `${Math.max(10, paddingPx - 20)}px`,
            right: `${Math.max(10, paddingPx - 20)}px`,
            bottom: `${Math.max(10, paddingPx - 20)}px`,
            border: data.frameStyle === 'simple' ? `2px solid ${data.themeColor}` 
                 : data.frameStyle === 'double' ? `4px double ${data.themeColor}`
                 : data.frameStyle === 'royal' ? `8px ridge ${data.themeColor}`
                 : data.frameStyle === 'academic' ? `3px solid ${data.themeColor}`
                 : `2px solid ${data.themeColor}`, // corner fallback
            borderRadius: data.frameStyle === 'academic' ? '12px' : '0px',
            opacity: 0.8
          }}
        />
      )}

      {/* Decorative Corner Frame */}
      {data.frameStyle === 'corner' && (
        <>
          <div className="absolute top-[20px] left-[20px] w-16 h-16 border-t-4 border-l-4 rounded-tl-xl pointer-events-none" style={{ borderColor: data.themeColor }} />
          <div className="absolute top-[20px] right-[20px] w-16 h-16 border-t-4 border-r-4 rounded-tr-xl pointer-events-none" style={{ borderColor: data.themeColor }} />
          <div className="absolute bottom-[20px] left-[20px] w-16 h-16 border-b-4 border-l-4 rounded-bl-xl pointer-events-none" style={{ borderColor: data.themeColor }} />
          <div className="absolute bottom-[20px] right-[20px] w-16 h-16 border-b-4 border-r-4 rounded-br-xl pointer-events-none" style={{ borderColor: data.themeColor }} />
        </>
      )}

      <div className="relative h-full flex flex-col z-10 w-full">
        
        {/* Header Section (Same as Attestation) */}
        {data.showHeader && (
          <div className="flex flex-col border-b-[2px] pb-4 mb-6" style={{ borderColor: '#000000' }}>
            <div className="flex justify-between items-start">
              {/* Left Logo */}
              <div className="w-[100px] flex items-center justify-center">
                {institution?.logoUrl ? (
                  <img src={institution.logoUrl} alt="Logo" className="w-[90px] h-[90px] object-contain" />
                ) : (
                  <div className="w-[85px] h-[85px] rounded-full border-2 border-dashed flex items-center justify-center" style={{ borderColor: `${data.themeColor}55` }}>
                    <span className="text-xs text-slate-400 font-medium">Logo</span>
                  </div>
                )}
              </div>

              {/* Center: Name & Address */}
              <div className="flex-1 text-center flex flex-col items-center justify-center px-4">
                <h1 
                  className="font-black text-slate-900 tracking-tight leading-none mb-1.5"
                  style={{ 
                    fontFamily: isBn ? BN_DICT['playfair_display_serif'] : EN_DICT['playfair_display_serif'],
                    fontSize: `${data.titleFontSize + 8}px`,
                    color: data.themeColor
                  }}
                >
                  {schoolName}
                </h1>
                <p className="text-[14px] font-bold text-slate-900 leading-snug">
                  {address}
                </p>
                {estYear && (
                  <p className="text-[14px] font-bold text-slate-900 leading-snug">
                    {isBn ? BN_DICT['est'] : EN_DICT['est']} {estYear}{isBn ? BN_DICT['k__4'] : EN_DICT['k__4']}
                  </p>
                )}
                <div className="flex flex-wrap justify-center gap-x-2 gap-y-0.5 mt-1 text-[13px] font-bold text-slate-900 font-sans">
                  {institution?.mobile && <span>mobile: {institution.mobile}{website || email ? ',' : ''}</span>}
                  {website && <span>web: {website}{email ? ',' : ''}</span>}
                  {email && <span>email: {email}</span>}
                </div>
              </div>

              {/* Right Spacer (for balance) */}
              <div className="w-[100px]"></div>
            </div>
          </div>
        )}

        {/* Top Info: Memo & Date */}
        <div className="flex justify-between items-center mb-8 text-[14px] font-bold text-slate-900">
          <div>
            <span>{isBn ? BN_DICT['memo'] : EN_DICT['memo']} </span>
            <span>{memoText}</span>
          </div>
          <div>
            <span>{isBn ? BN_DICT['date_2'] : EN_DICT['date_2']} </span>
            <span>{dateText}</span>
          </div>
        </div>

        {/* Subject */}
        {data.subject && (
          <div className="mb-10 mt-2 text-center">
            <h2 
              className="inline-block font-black"
              style={{ 
                fontSize: `${data.titleFontSize}px`, 
                color: data.themeColor === '#be185d' ? '#000000' : data.themeColor // Default to black for this template if pink is left as default
              }}
            >
              {isBn && !data.subject.startsWith('‘') && !data.subject.startsWith("'") ? `‘${data.subject}’` : data.subject}
            </h2>
          </div>
        )}

        {/* Greeting */}
        <div className="mb-4 font-bold text-slate-900" style={{ fontSize: `${data.bodyFontSize}px` }}>
          {data.greeting}
        </div>

        {/* Body Text */}
        <div 
          className="mb-10 text-slate-900 text-justify font-medium"
          style={{ 
            fontSize: `${data.bodyFontSize}px`,
            lineHeight: data.bodyLineHeight,
            whiteSpace: 'pre-wrap'
          }}
        >
          {data.bodyText}
        </div>

        {/* Guests Section (PDF Match) */}
        <div className="space-y-6 mb-10 text-[17px] font-medium text-slate-900 leading-relaxed">
          {data.chiefGuest && (
            <div>
              <div>{isBn ? BN_DICT['chief_guest'] : EN_DICT['chief_guest']}</div>
              <div className="pl-6 mt-1 space-y-1">
                {data.chiefGuest.split('\n').filter(Boolean).map((guest, i) => (
                   <div key={i} className="flex items-start gap-3">
                     <span className="text-[12px] mt-[7px]">■</span>
                     <span>{guest}</span>
                   </div>
                ))}
              </div>
            </div>
          )}
          
          {data.specialGuests && (
            <div className="pt-2">
              <div>{isBn ? BN_DICT['special_guests'] : EN_DICT['special_guests']}</div>
              <div className="pl-6 mt-1 space-y-1">
                {data.specialGuests.split('\n').filter(Boolean).map((guest, i) => (
                   <div key={i} className="flex items-start gap-3">
                     <span className="text-[12px] mt-[7px]">■</span>
                     <span>{guest}</span>
                   </div>
                ))}
              </div>
            </div>
          )}
          
          {data.president && (
            <div className="pt-2">
              <div>{isBn ? BN_DICT['chaired_by'] : EN_DICT['chaired_by']}</div>
              <div className="pl-6 mt-1 space-y-1">
                {data.president.split('\n').filter(Boolean).map((guest, i) => (
                   <div key={i} className="flex items-start gap-3">
                     <span className="text-[12px] mt-[7px]">■</span>
                     <span>{guest}</span>
                   </div>
                ))}
              </div>
            </div>
          )}
        </div>

        {/* Spacer to push schedule & signature to bottom */}
        <div className="flex-grow"></div>

        <div className="grid grid-cols-2 gap-8 items-end mt-8 pb-4">
           {/* Schedule */}
           <div>
              {(data.eventDate || data.eventTime || data.venue) && (
                <div className="border border-slate-900 p-5 rounded-lg bg-transparent shadow-none" style={{ borderWidth: '1px' }}>
                   <div className="font-bold mb-4 text-[17px] text-slate-900 border-b border-slate-800 pb-1.5 w-fit">
                     {isBn ? BN_DICT['event_schedule'] : EN_DICT['event_schedule']}
                   </div>
                   <div className="space-y-2 text-[16px] font-medium text-slate-900">
                     {data.eventDate && (
                       <div className="flex gap-4">
                         <div className="flex gap-2 w-[55px] shrink-0">
                           <span className="text-[10px] mt-[6px]">■</span>
                           <span>{isBn ? BN_DICT['date_3'] : EN_DICT['date_3']}</span>
                         </div>
                         <div className="flex-1">: {data.eventDate}</div>
                       </div>
                     )}
                     {data.eventTime && (
                       <div className="flex gap-4">
                         <div className="flex gap-2 w-[55px] shrink-0">
                           <span className="text-[10px] mt-[6px]">■</span>
                           <span>{isBn ? BN_DICT['time'] : EN_DICT['time']}</span>
                         </div>
                         <div className="flex-1">: {data.eventTime}</div>
                       </div>
                     )}
                     {data.venue && (
                       <div className="flex gap-4">
                         <div className="flex gap-2 w-[55px] shrink-0">
                           <span className="text-[10px] mt-[6px]">■</span>
                           <span>{isBn ? BN_DICT['venue'] : EN_DICT['venue']}</span>
                         </div>
                         <div className="flex-1">: {data.venue}</div>
                       </div>
                     )}
                   </div>
                </div>
              )}
           </div>

           {/* Signatory */}
           <div className="text-center text-[17px] font-medium text-slate-900 flex flex-col items-center">
              <div className="mb-6 self-start w-full text-center">{isBn ? BN_DICT['sincerely'] : EN_DICT['sincerely']}</div>
              {data.signatorySignature ? (
                <div className="h-14 flex items-end justify-center mb-1">
                  <img src={data.signatorySignature} alt="Signature" className="max-h-14 object-contain" />
                </div>
              ) : (
                <div className="h-14 mb-1 w-48"></div>
              )}
              {data.signatoryName && data.signatoryName !== (isBn ? BN_DICT['signatory'] : EN_DICT['signatory']) && (
                <div className="font-bold">
                  {data.signatoryName}
                </div>
              )}
              <div className="">
                {data.signatoryTitle || (isBn ? BN_DICT['headmaster'] : EN_DICT['headmaster'])}
              </div>
              <div className="">
                {schoolName}
              </div>
              {(upazila || district) && (
                <div className="">
                  {upazila}{upazila && district ? ', ' : ''}{district}
                </div>
              )}
           </div>
        </div>

      </div>
    </div>
  );
});
InvitationTemplate.displayName = 'InvitationTemplate';
