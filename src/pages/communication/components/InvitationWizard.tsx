import { EN_DICT, BN_DICT } from "../../../locales/autoGenerated";
import React, { useState, useRef } from 'react';
import { useAppStore } from '../../../store/useAppStore';
import { ArrowLeft, Download, Printer, Settings, CheckCircle2, ChevronRight, Wand2, ZoomIn, Scaling, Palette, Type, Square, LayoutTemplate, Save, FolderOpen, Trash2 } from 'lucide-react';
import { db } from '../../../db/database';
import { useLiveQuery } from 'dexie-react-hooks';
import { InvitationTemplate, InvitationData } from './InvitationTemplate';
import { getBengaliFormattedDate } from '../../../utils/bengaliUtils';
import { downloadCertificatePDF } from '../../../utils/pdfGenerator';
import { toast } from '../../../utils/toast';

interface InvitationWizardProps {
  onBack: () => void;
}

export const InvitationWizard: React.FC<InvitationWizardProps> = ({ onBack }) => {
  const { language, staff, institution } = useAppStore();
  const isBn = language === 'bn';

  const previewContainerRef = useRef<HTMLDivElement>(null);
  const printRef = useRef<HTMLDivElement>(null);
  const [isGenerating, setIsGenerating] = useState(false);
  const [zoomMode, setZoomMode] = useState<'fit' | 'fill'>('fit');
  const [showDrafts, setShowDrafts] = useState(false);

  const drafts = useLiveQuery(() => db.communicationDrafts.where('type').equals('invitation').reverse().sortBy('updatedAt'));

  const handleSaveDraft = async () => {
    try {
      const draftTitle = data.subject || (isBn ? BN_DICT['untitled_invitation'] : EN_DICT['untitled_invitation']);
      const newDraft = {
        id: data.memoNo || `draft_${Date.now()}`,
        type: 'invitation',
        title: draftTitle,
        updatedAt: new Date().toISOString(),
        data: data
      };
      await db.communicationDrafts.put(newDraft);
      toast.success(isBn ? BN_DICT['invitation_saved_as_draft_succ'] : EN_DICT['invitation_saved_as_draft_succ']);
    } catch (err) {
      console.error('Failed to save draft:', err);
      toast.error(isBn ? BN_DICT['failed_to_save_draft'] : EN_DICT['failed_to_save_draft']);
    }
  };

  const handleLoadDraft = (draftData: any) => {
    setData(draftData);
    setShowDrafts(false);
    toast.success(isBn ? BN_DICT['draft_loaded_successfully'] : EN_DICT['draft_loaded_successfully']);
  };

  const handleDeleteDraft = async (id: string) => {
    if (window.confirm(isBn ? BN_DICT['are_you_sure_you_want_to_delet_3'] : EN_DICT['are_you_sure_you_want_to_delet_3'])) {
      await db.communicationDrafts.delete(id);
      toast.success(isBn ? BN_DICT['draft_deleted_successfully'] : EN_DICT['draft_deleted_successfully']);
    }
  };
  const [activeStep, setActiveStep] = useState(1);
  const [previewScale, setPreviewScale] = useState(1);

  // Generate Auto Memo
  const instName = isBn ? (institution?.nameBn || institution?.name || '') : (institution?.name || '');
  const abbreviation = instName.split(' ').map(w => w[0]).join('');
  const autoMemo = `${abbreviation}/${isBn ? BN_DICT['inv'] : EN_DICT['inv']}/${isBn ? BN_DICT['k_2026'] : EN_DICT['k_2026']}/01`;

  const [data, setData] = useState<InvitationData>({
  
    memoNo: autoMemo,
    titleFontSize: 24,
    bodyFontSize: 17,
    bodyLineHeight: 2.2,
    pageMargin: 0.7,
    frameStyle: 'double',
    layoutFormat: 'portrait',
    issueDate: getBengaliFormattedDate(),
    subject: isBn ? BN_DICT['invitation_for_annual_sports'] : EN_DICT['invitation_for_annual_sports'],
    greeting: isBn ? BN_DICT['dear_sir_madam'] : EN_DICT['dear_sir_madam'],
    bodyText: isBn ? BN_DICT['we_are_delighted_to_inform_you'] : EN_DICT['we_are_delighted_to_inform_you'],
    eventName: isBn ? BN_DICT['annual_sports_competition_2026'] : EN_DICT['annual_sports_competition_2026'],
    eventDate: getBengaliFormattedDate(),
    eventTime: isBn ? BN_DICT['k_10_00_am'] : EN_DICT['k_10_00_am'],
    venue: isBn ? BN_DICT['school_premises'] : EN_DICT['school_premises'],
    chiefGuest: '',
    specialGuests: '',
    president: institution?.headmasterNameBn || institution?.headmasterName || '',
    signatoryName: institution?.headmasterNameBn || institution?.headmasterName || '',
    signatoryTitle: institution?.headmasterTitleBn || 'প্রধান শিক্ষক',
    signatorySignature: '',
    showHeader: true,
    themeColor: '#be185d', // Default Pink
  });

  React.useEffect(() => {
    const updateScale = () => {
      if (!previewContainerRef.current) return;
      const containerWidth = previewContainerRef.current.clientWidth - 48; // padding
      const containerHeight = previewContainerRef.current.clientHeight - 48;
      
      const targetWidth = data.layoutFormat === 'landscape' ? 1123 : 794;
      const targetHeight = data.layoutFormat === 'landscape' ? 794 : 1123;

      const scaleX = containerWidth / targetWidth;
      const scaleY = containerHeight / targetHeight;
      let scale = Math.min(scaleX, scaleY);
      
      if (scale > 1) scale = 1;
      
      setPreviewScale(zoomMode === 'fit' ? scale : 1);
    };
    
    updateScale();
    window.addEventListener('resize', updateScale);
    return () => window.removeEventListener('resize', updateScale);
  }, [zoomMode, data.layoutFormat]);

  const handleChange = (field: keyof InvitationData, value: any) => {
    setData(prev => ({ ...prev, [field]: value }));
  };

  const handlePrint = async () => {
    if (!printRef.current) return;
    setIsGenerating(true);
    try {
      await downloadCertificatePDF(
        printRef.current, 
        `${isBn ? BN_DICT['invitation'] : EN_DICT['invitation']}_${data.eventName.replace(/\s+/g, '_')}.pdf`, 
        { orientation: data.layoutFormat }
      );
      toast.success(isBn ? BN_DICT['invitation_pdf_downloaded_succ'] : EN_DICT['invitation_pdf_downloaded_succ']);
    } catch (error) {
      console.error('PDF Error:', error);
      toast.error(isBn ? BN_DICT['failed_to_generate_pdf_1'] : EN_DICT['failed_to_generate_pdf_1']);
    } finally {
      setIsGenerating(false);
    }
  };

  const steps = [
    { id: 1, label: isBn ? BN_DICT['basic_info'] : EN_DICT['basic_info'] },
    { id: 2, label: isBn ? BN_DICT['event_details'] : EN_DICT['event_details'] },
    { id: 3, label: isBn ? BN_DICT['guests'] : EN_DICT['guests'] },
    { id: 4, label: isBn ? BN_DICT['design_layout'] : EN_DICT['design_layout'] },
  ];

  return (
    <div className="min-h-screen bg-slate-50/50 pb-20">
      
      {/* Hidden container for print */}
      <div style={{ position: 'absolute', top: '-9999px', left: '-9999px', visibility: 'hidden', zIndex: -9999 }}>
        <div style={{ width: data.layoutFormat === 'landscape' ? '1123px' : '794px', height: data.layoutFormat === 'landscape' ? '794px' : '1123px' }}>
          <InvitationTemplate data={data} ref={printRef} />
        </div>
      </div>

      <div className="max-w-7xl mx-auto px-4 sm:px-6 lg:px-8 py-6 space-y-6 animate-in fade-in duration-300">
        
        {/* Header */}
        <div className="flex items-center justify-between">
          <div className="flex items-center gap-3">
            <button 
              onClick={onBack}
              className="w-10 h-10 rounded-full bg-white border border-slate-200 text-slate-500 hover:bg-slate-50 hover:text-slate-800 flex items-center justify-center transition-all shadow-sm"
            >
              <ArrowLeft className="w-5 h-5" />
            </button>
            <div className="p-2.5 bg-pink-100 text-pink-700 rounded-xl">
              <Wand2 className="w-6 h-6" />
            </div>
            <div>
              <h2 className="text-2xl font-black text-slate-900 tracking-tight">
                {isBn ? BN_DICT['invitation_wizard'] : EN_DICT['invitation_wizard']}
              </h2>
              <p className="text-sm font-medium text-slate-500">
                {isBn ? BN_DICT['create_an_invitation_using_the'] : EN_DICT['create_an_invitation_using_the']}
              </p>
            </div>
          </div>
          <div className="flex items-center gap-3">
            <button
              onClick={() => setShowDrafts(true)}
              className="flex items-center gap-2 px-4 py-2 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl font-bold transition-all text-sm hidden sm:flex"
            >
              <FolderOpen className="w-4 h-4" />
              <span>{isBn ? BN_DICT['open_draft'] : EN_DICT['open_draft']}</span>
            </button>
            <button
              onClick={handleSaveDraft}
              className="flex items-center gap-2 px-4 py-2 bg-pink-50 hover:bg-pink-100 text-pink-700 border border-pink-200 rounded-xl font-bold transition-all text-sm hidden sm:flex"
            >
              <Save className="w-4 h-4" />
              <span>{isBn ? BN_DICT['save_draft'] : EN_DICT['save_draft']}</span>
            </button>
            <button
              onClick={handlePrint}
              disabled={isGenerating}
              className={`flex items-center gap-2 px-5 py-2.5 rounded-xl font-bold transition-all shadow-sm ${
                isGenerating
                  ? 'bg-slate-100 text-slate-400 cursor-not-allowed'
                  : 'bg-indigo-600 hover:bg-indigo-700 text-white shadow-indigo-600/20 hover:shadow-lg'
              }`}
            >
              {isGenerating ? (
                <>
                  <Download className="w-4 h-4 animate-bounce" />
                  <span>{isBn ? BN_DICT['downloading'] : EN_DICT['downloading']}</span>
                </>
              ) : (
                <>
                  <Printer className="w-4 h-4" />
                  <span>{isBn ? BN_DICT['download_pdf_1'] : EN_DICT['download_pdf_1']}</span>
                </>
              )}
            </button>
          </div>
        </div>

        {/* Main Grid */}
        <div className="grid grid-cols-1 lg:grid-cols-12 gap-6 h-[calc(100vh-140px)] min-h-[600px]">
          
          {/* Left Column: Form Wizard */}
          <div className="lg:col-span-5 bg-white rounded-3xl shadow-sm border border-slate-200 flex flex-col overflow-hidden">
            
            {/* Steps Header */}
            <div className="px-6 py-4 border-b border-slate-100 bg-slate-50/50 flex justify-between items-center relative">
              <div className="absolute bottom-0 left-0 h-0.5 bg-pink-500 transition-all duration-300" style={{ width: `${(activeStep / steps.length) * 100}%` }}></div>
              {steps.map(step => (
                <div key={step.id} className={`flex flex-col items-center gap-1 ${activeStep === step.id ? 'opacity-100' : 'opacity-40'}`}>
                  <div className={`w-6 h-6 rounded-full flex items-center justify-center text-xs font-bold ${activeStep === step.id ? 'bg-pink-600 text-white shadow-md shadow-pink-600/20' : 'bg-slate-200 text-slate-500'}`}>
                    {activeStep > step.id ? <CheckCircle2 className="w-4 h-4" /> : step.id}
                  </div>
                </div>
              ))}
            </div>

            {/* Scrollable Form Area */}
            <div className="flex-1 overflow-y-auto p-6 space-y-6 custom-scrollbar">
              
              {/* Step 1: Basic Info */}
              {activeStep === 1 && (
                <div className="space-y-4 animate-in slide-in-from-right-4 duration-300">
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['subject'] : EN_DICT['subject']}</label>
                    <input
                      type="text"
                      value={data.subject}
                      onChange={(e) => handleChange('subject', e.target.value)}
                      className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                    />
                  </div>
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['greeting'] : EN_DICT['greeting']}</label>
                    <input
                      type="text"
                      value={data.greeting}
                      onChange={(e) => handleChange('greeting', e.target.value)}
                      className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                    />
                  </div>
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['body_message'] : EN_DICT['body_message']}</label>
                    <textarea
                      rows={6}
                      value={data.bodyText}
                      onChange={(e) => handleChange('bodyText', e.target.value)}
                      className="w-full px-4 py-3 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm resize-none"
                    ></textarea>
                  </div>
                </div>
              )}

              {/* Step 2: Event Details */}
              {activeStep === 2 && (
                <div className="space-y-4 animate-in slide-in-from-right-4 duration-300">
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['event_name'] : EN_DICT['event_name']}</label>
                    <input
                      type="text"
                      value={data.eventName}
                      onChange={(e) => handleChange('eventName', e.target.value)}
                      placeholder={isBn ? BN_DICT['e_g_annual_sports'] : EN_DICT['e_g_annual_sports']}
                      className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                    />
                  </div>
                  <div className="grid grid-cols-2 gap-4">
                    <div>
                      <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['date_3'] : EN_DICT['date_3']}</label>
                      <input
                        type="text"
                        value={data.eventDate}
                        onChange={(e) => handleChange('eventDate', e.target.value)}
                        className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                      />
                    </div>
                    <div>
                      <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['time'] : EN_DICT['time']}</label>
                      <input
                        type="text"
                        value={data.eventTime}
                        onChange={(e) => handleChange('eventTime', e.target.value)}
                        className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                      />
                    </div>
                  </div>
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['venue'] : EN_DICT['venue']}</label>
                    <input
                      type="text"
                      value={data.venue}
                      onChange={(e) => handleChange('venue', e.target.value)}
                      className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                    />
                  </div>
                </div>
              )}

              {/* Step 3: Guests */}
              {activeStep === 3 && (
                <div className="space-y-4 animate-in slide-in-from-right-4 duration-300">
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['chief_guest_optional'] : EN_DICT['chief_guest_optional']}</label>
                    <input
                      type="text"
                      value={data.chiefGuest}
                      onChange={(e) => handleChange('chiefGuest', e.target.value)}
                      placeholder={isBn ? BN_DICT['name_title'] : EN_DICT['name_title']}
                      className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                    />
                  </div>
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['special_guests_1'] : EN_DICT['special_guests_1']}</label>
                    <textarea
                      rows={3}
                      value={data.specialGuests}
                      onChange={(e) => handleChange('specialGuests', e.target.value)}
                      placeholder={isBn ? BN_DICT['multiple_guests_separated_by_c'] : EN_DICT['multiple_guests_separated_by_c']}
                      className="w-full px-4 py-3 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm resize-none"
                    ></textarea>
                  </div>
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['president_chair'] : EN_DICT['president_chair']}</label>
                    <input
                      type="text"
                      value={data.president}
                      onChange={(e) => handleChange('president', e.target.value)}
                      className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white transition-colors font-medium text-sm"
                    />
                  </div>
                </div>
              )}

              {/* Step 4: Final Touch */}
              {activeStep === 4 && (
                <div className="space-y-5 animate-in slide-in-from-right-4 duration-300 pb-10">
                  
                  {/* Layout & Print Size */}
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-2 flex items-center gap-1.5">
                      <LayoutTemplate className="w-4 h-4 text-pink-600" />
                      {isBn ? BN_DICT['layout_page_size'] : EN_DICT['layout_page_size']}
                    </label>
                    <div className="grid grid-cols-2 gap-3">
                      <button
                        onClick={() => handleChange('layoutFormat', 'portrait')}
                        className={`py-3 px-4 rounded-xl border flex flex-col items-center justify-center gap-1 transition-all ${data.layoutFormat === 'portrait' ? 'bg-pink-50 border-pink-500 text-pink-700' : 'bg-slate-50 border-slate-200 text-slate-600 hover:bg-slate-100'}`}
                      >
                        <div className="w-4 h-6 border-2 border-current rounded-sm"></div>
                        <span className="text-xs font-bold">{isBn ? BN_DICT['portrait'] : EN_DICT['portrait']}</span>
                      </button>
                      <button
                        onClick={() => handleChange('layoutFormat', 'landscape')}
                        className={`py-3 px-4 rounded-xl border flex flex-col items-center justify-center gap-1 transition-all ${data.layoutFormat === 'landscape' ? 'bg-pink-50 border-pink-500 text-pink-700' : 'bg-slate-50 border-slate-200 text-slate-600 hover:bg-slate-100'}`}
                      >
                        <div className="w-6 h-4 border-2 border-current rounded-sm"></div>
                        <span className="text-xs font-bold">{isBn ? BN_DICT['landscape'] : EN_DICT['landscape']}</span>
                      </button>
                    </div>
                  </div>

                  {/* Theme Colors */}
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-2 flex items-center gap-1.5">
                      <Palette className="w-4 h-4 text-pink-600" />
                      {isBn ? BN_DICT['choose_theme_color'] : EN_DICT['choose_theme_color']}
                    </label>
                    <div className="flex gap-3">
                      {[
                        { hex: '#be185d', name: 'Pink' },
                        { hex: '#4338ca', name: 'Indigo' },
                        { hex: '#0f766e', name: 'Teal' },
                        { hex: '#b45309', name: 'Amber' },
                        { hex: '#334155', name: 'Slate' }
                      ].map(color => (
                        <button
                          key={color.hex}
                          onClick={() => handleChange('themeColor', color.hex)}
                          className={`w-10 h-10 rounded-full transition-transform hover:scale-110 flex items-center justify-center ${data.themeColor === color.hex ? 'ring-2 ring-offset-2 ring-slate-800' : ''}`}
                          style={{ backgroundColor: color.hex }}
                        >
                          {data.themeColor === color.hex && <CheckCircle2 className="w-5 h-5 text-white" />}
                        </button>
                      ))}
                    </div>
                  </div>

                  {/* Header Visibility */}
                  <label className="flex items-center gap-3 p-4 bg-slate-50 border border-slate-200 rounded-xl cursor-pointer hover:bg-slate-100 transition-colors">
                    <input
                      type="checkbox"
                      checked={data.showHeader}
                      onChange={(e) => handleChange('showHeader', e.target.checked)}
                      className="w-5 h-5 rounded text-pink-600 focus:ring-pink-500"
                    />
                    <div>
                      <div className="font-bold text-sm text-slate-800">{isBn ? BN_DICT['show_institute_header'] : EN_DICT['show_institute_header']}</div>
                      <div className="text-xs text-slate-500 mt-0.5">{isBn ? BN_DICT['turn_off_if_using_official_pri'] : EN_DICT['turn_off_if_using_official_pri']}</div>
                    </div>
                  </label>

                  {/* Border Frame Style */}
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-2 flex items-center gap-1.5">
                      <Square className="w-4 h-4 text-pink-600" />
                      {isBn ? BN_DICT['border_frame'] : EN_DICT['border_frame']}
                    </label>
                    <div className="grid grid-cols-3 gap-2">
                      {[
                        { id: 'none', label: isBn ? BN_DICT['none'] : EN_DICT['none'] },
                        { id: 'simple', label: isBn ? BN_DICT['simple'] : EN_DICT['simple'] },
                        { id: 'double', label: isBn ? BN_DICT['double'] : EN_DICT['double'] },
                        { id: 'corner', label: isBn ? BN_DICT['corner'] : EN_DICT['corner'] },
                        { id: 'academic', label: isBn ? BN_DICT['academic'] : EN_DICT['academic'] },
                        { id: 'royal', label: isBn ? BN_DICT['royal'] : EN_DICT['royal'] }
                      ].map(frame => (
                        <button
                          key={frame.id}
                          onClick={() => handleChange('frameStyle', frame.id)}
                          className={`py-2 px-1 text-xs font-semibold rounded-lg border transition-all ${data.frameStyle === frame.id ? 'bg-pink-50 border-pink-500 text-pink-700' : 'bg-slate-50 border-slate-200 text-slate-600 hover:bg-slate-100'}`}
                        >
                          {frame.label}
                        </button>
                      ))}
                    </div>
                  </div>

                  {/* Typography Settings */}
                  <div>
                    <label className="block text-xs font-bold text-slate-800 mb-2 flex items-center gap-1.5">
                      <Type className="w-4 h-4 text-pink-600" />
                      {isBn ? BN_DICT['font_size_spacing'] : EN_DICT['font_size_spacing']}
                    </label>
                    <div className="space-y-4 bg-slate-50 p-4 rounded-xl border border-slate-200">
                      <div>
                        <div className="flex justify-between text-xs font-semibold text-slate-700 mb-1">
                          <span>{isBn ? BN_DICT['title_size'] : EN_DICT['title_size']} ({data.titleFontSize}px)</span>
                        </div>
                        <input type="range" min="18" max="40" value={data.titleFontSize} onChange={(e) => handleChange('titleFontSize', parseInt(e.target.value))} className="w-full accent-pink-600" />
                      </div>
                      <div>
                        <div className="flex justify-between text-xs font-semibold text-slate-700 mb-1">
                          <span>{isBn ? BN_DICT['body_size'] : EN_DICT['body_size']} ({data.bodyFontSize}px)</span>
                        </div>
                        <input type="range" min="14" max="24" value={data.bodyFontSize} onChange={(e) => handleChange('bodyFontSize', parseInt(e.target.value))} className="w-full accent-pink-600" />
                      </div>
                      <div>
                        <div className="flex justify-between text-xs font-semibold text-slate-700 mb-1">
                          <span>{isBn ? BN_DICT['line_space'] : EN_DICT['line_space']} ({data.bodyLineHeight}x)</span>
                        </div>
                        <input type="range" min="1.5" max="3" step="0.1" value={data.bodyLineHeight} onChange={(e) => handleChange('bodyLineHeight', parseFloat(e.target.value))} className="w-full accent-pink-600" />
                      </div>
                      <div>
                        <div className="flex justify-between text-xs font-semibold text-slate-700 mb-1">
                          <span>{isBn ? BN_DICT['page_margin'] : EN_DICT['page_margin']} ({data.pageMargin} in)</span>
                        </div>
                        <input type="range" min="0.3" max="1.5" step="0.1" value={data.pageMargin} onChange={(e) => handleChange('pageMargin', parseFloat(e.target.value))} className="w-full accent-pink-600" />
                      </div>
                    </div>
                  </div>

                  <hr className="border-slate-100" />

                  {/* Signatory Info */}
                  <div className="grid grid-cols-2 gap-4">
                    <div className="col-span-2">
                      <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['select_signatory'] : EN_DICT['select_signatory']}</label>
                      <select
                        className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white font-semibold text-sm"
                        onChange={(e) => {
                          const s = staff?.find(st => st.id === e.target.value);
                          if (s) {
                            setData(p => ({
                              ...p,
                              signatoryName: isBn ? (s.nameBn || s.name) : s.name,
                              signatoryTitle: isBn ? (s.designationBn || s.designation) : s.designation,
                              signatorySignature: s.signaturePhoto || p.signatorySignature
                            }));
                          }
                        }}
                      >
                        <option value="">{isBn ? BN_DICT['select_1'] : EN_DICT['select_1']}</option>
                        {staff?.map(s => (
                          <option key={s.id} value={s.id}>
                            {isBn ? (s.nameBn || s.name) : s.name}
                          </option>
                        ))}
                      </select>
                    </div>
                    <div>
                      <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['signatory_name'] : EN_DICT['signatory_name']}</label>
                      <input
                        type="text"
                        value={data.signatoryName}
                        onChange={(e) => handleChange('signatoryName', e.target.value)}
                        className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white text-sm"
                      />
                    </div>
                    <div>
                      <label className="block text-xs font-bold text-slate-800 mb-1.5">{isBn ? BN_DICT['title'] : EN_DICT['title']}</label>
                      <input
                        type="text"
                        value={data.signatoryTitle}
                        onChange={(e) => handleChange('signatoryTitle', e.target.value)}
                        className="w-full px-4 py-2.5 bg-slate-50 border border-slate-200 rounded-xl focus:ring-2 focus:ring-pink-500 focus:bg-white text-sm"
                      />
                    </div>
                  </div>

                </div>
              )}
            </div>

            {/* Bottom Actions */}
            <div className="p-4 border-t border-slate-100 bg-white flex justify-between items-center">
              <button
                onClick={() => setActiveStep(prev => Math.max(1, prev - 1))}
                disabled={activeStep === 1}
                className={`px-5 py-2.5 rounded-xl font-bold transition-all text-sm flex items-center gap-2 ${activeStep === 1 ? 'opacity-0 pointer-events-none' : 'bg-slate-100 hover:bg-slate-200 text-slate-700'}`}
              >
                <ArrowLeft className="w-4 h-4" />
                {isBn ? BN_DICT['back'] : EN_DICT['back']}
              </button>
              
              <div className="flex gap-2">
                <button
                  onClick={handleSaveDraft}
                  className="sm:hidden px-4 py-2.5 bg-pink-50 hover:bg-pink-100 text-pink-700 rounded-xl font-bold transition-all text-sm flex items-center"
                  title={isBn ? BN_DICT['save_draft'] : EN_DICT['save_draft']}
                >
                  <Save className="w-4 h-4" />
                </button>
                <button
                  onClick={() => setShowDrafts(true)}
                  className="sm:hidden px-4 py-2.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl font-bold transition-all text-sm flex items-center"
                  title={isBn ? BN_DICT['open_draft'] : EN_DICT['open_draft']}
                >
                  <FolderOpen className="w-4 h-4" />
                </button>
              {activeStep < 4 ? (
                <button
                  onClick={() => setActiveStep(prev => Math.min(4, prev + 1))}
                  className="px-6 py-2.5 rounded-xl font-bold transition-all text-sm bg-pink-600 hover:bg-pink-700 text-white shadow-md shadow-pink-600/20 flex items-center gap-2"
                >
                  {isBn ? BN_DICT['next_step'] : EN_DICT['next_step']}
                  <ChevronRight className="w-4 h-4" />
                </button>
              ) : (
                <button
                  onClick={handlePrint}
                  disabled={isGenerating}
                  className={`px-6 py-2.5 rounded-xl font-bold transition-all text-sm flex items-center gap-2 ${
                    isGenerating ? 'bg-slate-100 text-slate-400' : 'bg-indigo-600 hover:bg-indigo-700 text-white shadow-md shadow-indigo-600/20'
                  }`}
                >
                  <Printer className="w-4 h-4" />
                  {isBn ? BN_DICT['print_now'] : EN_DICT['print_now']}
                </button>
              )}
              </div>
            </div>

          </div>

          {/* Right Column: Live Preview */}
          <div className="lg:col-span-7 bg-white rounded-3xl shadow-sm border border-slate-200 flex flex-col overflow-hidden">
            <div className="px-5 py-3.5 border-b border-slate-100 flex items-center justify-between bg-slate-50/50">
              <div className="flex items-center gap-2">
                <ZoomIn className="w-4 h-4 text-slate-400" />
                <h3 className="font-bold text-slate-800 text-sm">
                  {isBn ? BN_DICT['live_preview'] : EN_DICT['live_preview']}
                </h3>
              </div>
              <div className="flex items-center gap-2 bg-slate-200/50 p-1 rounded-lg">
                <button
                  onClick={() => setZoomMode('fit')}
                  className={`px-3 py-1 text-xs font-semibold rounded-md transition-all ${
                    zoomMode === 'fit' ? 'bg-white text-slate-800 shadow-sm' : 'text-slate-500 hover:text-slate-700'
                  }`}
                >
                  Fit
                </button>
                <button
                  onClick={() => setZoomMode('fill')}
                  className={`px-3 py-1 text-xs font-semibold rounded-md transition-all ${
                    zoomMode === 'fill' ? 'bg-white text-slate-800 shadow-sm' : 'text-slate-500 hover:text-slate-700'
                  }`}
                >
                  100%
                </button>
              </div>
            </div>
            
            <div 
              ref={previewContainerRef}
              className="flex-1 overflow-hidden bg-slate-100 relative flex items-center justify-center p-6"
            >
              {/* Scale wrapper */}
              <div 
                className="transition-transform duration-300 flex-shrink-0"
                style={{
                  transform: `scale(${previewScale})`,
                  width: data.layoutFormat === 'landscape' ? '1123px' : '794px',
                  height: data.layoutFormat === 'landscape' ? '794px' : '1123px',
                  transformOrigin: 'center center'
                }}
              >
                <InvitationTemplate data={data} />
              </div>
            </div>
          </div>

        </div>
      </div>

      {showDrafts && (
        <div className="fixed inset-0 z-[100] flex items-center justify-center p-4 bg-slate-900/50 backdrop-blur-sm">
          <div className="bg-white rounded-2xl shadow-xl w-full max-w-lg overflow-hidden flex flex-col max-h-[85vh] animate-in zoom-in-95 duration-200">
            <div className="p-4 border-b flex justify-between items-center bg-slate-50">
              <h3 className="text-lg font-bold text-slate-800 flex items-center gap-2">
                <FolderOpen className="w-5 h-5 text-indigo-600" />
                {isBn ? BN_DICT['saved_drafts'] : EN_DICT['saved_drafts']}
              </h3>
              <button onClick={() => setShowDrafts(false)} className="text-slate-400 hover:text-slate-600 p-1">
                <svg className="w-5 h-5" fill="none" stroke="currentColor" viewBox="0 0 24 24"><path strokeLinecap="round" strokeLinejoin="round" strokeWidth={2} d="M6 18L18 6M6 6l12 12" /></svg>
              </button>
            </div>
            <div className="p-4 overflow-auto flex-1 bg-slate-50/50">
              {drafts && drafts.length > 0 ? (
                <div className="space-y-3">
                  {drafts.map(draft => (
                    <div key={draft.id} className="bg-white p-4 rounded-xl border border-slate-200 shadow-sm flex justify-between items-center hover:border-indigo-300 transition-all">
                      <div className="flex-1 min-w-0 pr-4">
                        <h4 className="font-bold text-slate-800 truncate">{draft.title}</h4>
                        <div className="text-xs font-semibold text-slate-500 mt-1 flex flex-wrap gap-x-3 gap-y-1">
                          <span>{isBn ? BN_DICT['memo'] : EN_DICT['memo']} {draft.data.memoNo}</span>
                          <span className="text-slate-400">&bull;</span>
                          <span>{new Date(draft.updatedAt).toLocaleDateString(isBn ? BN_DICT['en_us'] : EN_DICT['en_us'], { year: 'numeric', month: 'short', day: 'numeric', hour: '2-digit', minute: '2-digit' })}</span>
                        </div>
                      </div>
                      <div className="flex items-center gap-2">
                        <button onClick={() => handleLoadDraft(draft.data)} className="px-3 py-1.5 text-indigo-700 bg-indigo-50 hover:bg-indigo-100 rounded-lg font-bold text-sm transition-colors border border-indigo-100">
                          {isBn ? BN_DICT['load'] : EN_DICT['load']}
                        </button>
                        <button onClick={() => handleDeleteDraft(draft.id)} className="p-2 text-red-600 bg-red-50 hover:bg-red-100 rounded-lg transition-colors" title="Delete">
                          <Trash2 className="w-4 h-4" />
                        </button>
                      </div>
                    </div>
                  ))}
                </div>
              ) : (
                <div className="text-center py-10">
                  <div className="w-16 h-16 bg-slate-100 text-slate-300 rounded-full flex items-center justify-center mx-auto mb-3">
                    <FolderOpen className="w-8 h-8" />
                  </div>
                  <div className="text-slate-500 font-bold">
                    {isBn ? BN_DICT['no_drafts_found'] : EN_DICT['no_drafts_found']}
                  </div>
                  <p className="text-sm text-slate-400 mt-1">
                    {isBn ? BN_DICT['click_save_draft_to_store_your'] : EN_DICT['click_save_draft_to_store_your']}
                  </p>
                </div>
              )}
            </div>
            <div className="p-4 border-t text-right bg-white">
              <button onClick={() => setShowDrafts(false)} className="px-5 py-2 bg-slate-100 text-slate-700 rounded-xl font-bold hover:bg-slate-200 transition-colors">
                {isBn ? BN_DICT['close'] : EN_DICT['close']}
              </button>
            </div>
          </div>
        </div>
      )}
    </div>
  );
};
