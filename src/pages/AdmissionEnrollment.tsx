import { generateStudentId } from '../utils/generateId';
import { normalizeClassName, normalizeGroupName, normalizeSectionName, normalizeSession } from '../utils/classNormalizer';
import { extractDobFromRow, parseExcelDate } from '../utils/dateNormalizer';
import { processAsyncBatch } from '../utils/asyncBatch';
import { calculateStudentDataCompletion } from '../utils/studentCompletion';
import { toBengaliNumber } from '../utils/bengaliUtils';
import { notifyStudentAdded, notifyStudentUpdated, toast } from '../utils/toast';
import * as XLSX from 'xlsx';

const AdmissionEnrollment = () => {
  const language = useAppStore(state => state.language);
  const students = useAppStore(state => state.students);
  const academicClasses = useAppStore(state => state.academicClasses);
  const academicGroups = useAppStore(state => state.academicGroups);
  const academicSections = useAppStore(state => state.academicSections);
  const academicSessions = useAppStore(state => state.academicSessions);
  const addStudent = useAppStore(state => state.addStudent);
  const updateStudent = useAppStore(state => state.updateStudent);
  const deleteStudent = useAppStore(state => state.deleteStudent);
  const bulkAddStudents = useAppStore(state => state.bulkAddStudents);

  const isBn = language === 'bn';

  const [showEnrollModal, setShowEnrollModal] = useState(false);
  const [showHubModal, setShowHubModal] = useState(false);
  const [showSmartModal, setShowSmartModal] = useState(false);
  const [editingStudent, setEditingStudent] = useState<Student | null>(null);
  const [viewingStudent, setViewingStudent] = useState<Student | null>(null);
  const [smartData, setSmartData] = useState<Partial<Student> | null>(null);
  const [searchTerm, setSearchTerm] = useState('');
  const [filterClass, setFilterClass] = useState<string>('all');
  const [isImporting, setIsImporting] = useState(false);
  const [toastMessage, setToastMessage] = useState<string | null>(null);
  const fileInputRef = useRef<HTMLInputElement>(null);

  const showToast = useCallback((msg: string) => {
    setToastMessage(msg);
    setTimeout(() => setToastMessage(null), 3500);
  }, []);

  const studentList = useMemo(() => Array.isArray(students) ? students : [], [students]);
  const classesList = useMemo(() => Array.isArray(academicClasses) ? academicClasses : [], [academicClasses]);
  const groupsList = useMemo(() => Array.isArray(academicGroups) ? academicGroups : [], [academicGroups]);
  const sectionsList = useMemo(() => Array.isArray(academicSections) ? academicSections : [], [academicSections]);

  // Memoized Metrics
  const { totalStudents, maleStudents, femaleStudents, thisYearStudents } = useMemo(() => {
    const currentYear = new Date().getFullYear().toString();
    let male = 0;
    let female = 0;
    let thisYear = 0;

    studentList.forEach(s => {
      if (s.gender === 'Male') male++;
      else if (s.gender === 'Female') female++;

      if (s.session?.includes(currentYear) || s.applicationDate?.startsWith(currentYear)) {
        thisYear++;
      }
    });

    return {
      totalStudents: studentList.length,
      maleStudents: male,
      femaleStudents: female,
      thisYearStudents: thisYear
    };
  }, [studentList]);

  const handleSaveStudent = useCallback((data: Partial<Student>) => {
    if (editingStudent) {
      updateStudent(editingStudent.id, data);
      notifyStudentUpdated(data.nameBn || data.name);
    } else {
      const newStudent: Student = {
        ...data,
        id: Date.now().toString(),
      } as Student;
      addStudent(newStudent);
      notifyStudentAdded(newStudent.nameBn || newStudent.name);
    }
    setShowEnrollModal(false);
    setEditingStudent(null);
    setSmartData(null);
  }, [editingStudent, updateStudent, addStudent]);

  const handleSmartImportSubmit = (parsed: Partial<Student>) => {
    setSmartData(parsed);
    setEditingStudent(null);
    setShowSmartModal(false);
    setShowEnrollModal(true);
  };

  const handleBulkExcelImport = (newStudents: Student[]) => {
    bulkAddStudents(newStudents);
    const msg = isBn ? `${newStudents.length} জন শিক্ষার্থীর ডাটা সফলভাবে সেভ হয়েছে!` : `${newStudents.length} Students imported successfully!`;
    showToast(msg);
    toast.success(msg);
    setShowHubModal(false);
  };

  const downloadSampleExcel = () => {
    const defaultGroup = groupsList.find(g => g.isDefault)?.name || 'প্রযোজ্য নয়';
    const defaultSection = sectionsList.find(s => s.isDefault)?.name || 'প্রযোজ্য নয়';

    const wsData = [
      ['Student ID', 'Form No', 'Application Date', 'Session', 'Class', 'Group', 'Section', 'Roll', 'Name (English)', 'Name (Bangla)', 
       'Birth Registration No', 'Date of Birth', 'Gender', 'Religion', 'Nationality', 'Blood Group',
       'Permanent Village', 'Permanent Post Office', 'Permanent Upazila', 'Permanent District',
       'Present Village', 'Present Post Office', 'Present Upazila', 'Present District',
       'Father Name (English)', 'Father Name (Bangla)', 'Father NID', 'Father Mobile', 'Father Profession',
       'Mother Name (English)', 'Mother Name (Bangla)', 'Mother NID', 'Mother Mobile', 'Mother Profession',
       'Parents Status', 'Previous School', 'Previous Class', 'Admission Payment', 'Payment Method', 'Transaction No'],
      ['', '1001', '2026-01-01', '2026', '6', defaultGroup, defaultSection, '1', 'John Doe', 'জন ডো', 
       '12345678901234567', '2010-05-15', 'Male', 'Islam', 'বাংলাদেশি', 'A+',
       'নাঙ্গলকোট', 'নাঙ্গলকোট', 'নাঙ্গলকোট', 'কুমিল্লা',
       'নাঙ্গলকোট', 'নাঙ্গলকোট', 'নাঙ্গলকোট', 'কুমিল্লা',
       'Richard Doe', 'রিচার্ড ডো', '9876543210', '01700000000', 'Business',
       'Jane Doe', 'জেন ডো', '1234567890', '01800000000', 'Housewife',
       'দুজনেই জীবিত', 'Sample Primary School', '5', '1000', 'বিকাশ', 'TRX123456']
    ];
    const ws = XLSX.utils.aoa_to_sheet(wsData);
    const wb = XLSX.utils.book_new();
    XLSX.utils.book_append_sheet(wb, ws, 'Sample');
    XLSX.writeFile(wb, 'student_enrollment_import_format.xlsx');
  };

  const handleDirectExcelFile = async (e: React.ChangeEvent<HTMLInputElement>) => {
    const file = e.target.files?.[0];
    if (!file) return;
    setIsImporting(true);
    try {
      const buffer = await file.arrayBuffer();
      const wb = XLSX.read(buffer, { type: 'array' });
      const wsname = wb.SheetNames[0];
      const ws = wb.Sheets[wsname];
      const data = XLSX.utils.sheet_to_json(ws);

      const defaultClass = classesList.find(c => c.isDefault)?.name || classesList[0]?.name || 'Class 6';
      const defaultGroup = groupsList.find(g => g.isDefault)?.name || groupsList[0]?.name || 'প্রযোজ্য নয়';
      const defaultSection = sectionsList.find(s => s.isDefault)?.name || sectionsList[0]?.name || 'প্রযোজ্য নয়';
      const currentYearStr = new Date().getFullYear().toString();

      const getValue = (row: any, keys: string[]) => {
        const rowKeys = Object.keys(row);
        for (const key of keys) {
          const normalizedKey = key.toLowerCase().replace(/\s+/g, '');
          const match = rowKeys.find(rk => rk.toLowerCase().replace(/\s+/g, '') === normalizedKey);
          if (match && row[match] !== undefined && row[match] !== null) {
            return String(row[match]).trim();
          }
        }
        return '';
      };

      const newStudents = await processAsyncBatch<any, Student>(
        data,
        (row: any, index: number) => {
          const rawClass = getValue(row, ['Class', 'শ্রেণি', 'শ্রেণী']) || defaultClass;
          const normalizedClass = normalizeClassName(String(rawClass), classesList, defaultClass);
          const normalizedSess = normalizeSession(getValue(row, ['Session', 'শিক্ষাবর্ষ']) || currentYearStr, academicSessions || [], currentYearStr);

          const rawGroup = getValue(row, ['Group', 'বিভাগ', 'শাখা/বিভাগ']) || defaultGroup;
          const normalizedGroup = normalizeGroupName(String(rawGroup), groupsList, defaultGroup);

          const rawSection = getValue(row, ['Section', 'শাখা']) || defaultSection;
          const normalizedSection = normalizeSectionName(String(rawSection), sectionsList, defaultSection);

          const generatedId = generateStudentId(normalizedClass, studentList);
          const fallbackId = `${generatedId.slice(0,4)}${(parseInt(generatedId.slice(4)) + index).toString().padStart(3, '0')}`;
          
          const rawDob = getValue(row, ['Date of Birth', 'DOB', 'জন্ম তারিখ']);
          let parsedDob = extractDobFromRow(row); // fallback to old logic
          if (rawDob && !parsedDob) {
            parsedDob = rawDob;
          }

          const rawGender = getValue(row, ['Gender', 'Sex', 'লিঙ্গ']).toLowerCase();
          const gender = (rawGender === 'female' || rawGender === 'মেয়ে' || rawGender === 'ছাত্রী') ? 'Female' : (rawGender === 'other' || rawGender === 'অন্যান্য') ? 'Other' : 'Male';

          return {
            id: Date.now().toString() + index,
            studentId: getValue(row, ['Student ID', 'ID', 'আইডি']) || fallbackId,
            formNo: getValue(row, ['Form No', 'ফরম নং']),
            applicationDate: parseExcelDate(getValue(row, ['Application Date'])) || new Date().toISOString().split('T')[0],
            session: normalizedSess,
            class: normalizedClass,
            group: normalizedGroup,
            section: normalizedSection,
            roll: getValue(row, ['Roll', 'রোল']) || String(index + 1),
            name: getValue(row, ['Name (English)', 'Name', 'নাম', 'শিক্ষার্থীর নাম']),
            nameBn: getValue(row, ['Name (Bangla)', 'Bangla Name', 'বাংলা নাম']),
            birthRegistrationNo: getValue(row, ['Birth Registration No', 'জন্ম নিবন্ধন', 'জন্ম নিবন্ধন নম্বর']),
            dateOfBirth: parsedDob,
            gender: gender as any,
            religion: getValue(row, ['Religion', 'ধর্ম']) || 'Islam',
            nationality: getValue(row, ['Nationality', 'জাতীয়তা']) || 'বাংলাদেশি',
            bloodGroup: getValue(row, ['Blood Group', 'রক্তের গ্রুপ']) || 'পরীক্ষা করা হয় নাই',
            village: getValue(row, ['Permanent Village', 'Village', 'গ্রাম']),
            postOffice: getValue(row, ['Permanent Post Office', 'Post Office', 'ডাকঘর']),
            upazila: getValue(row, ['Permanent Upazila', 'Upazila', 'উপজেলা']),
            district: getValue(row, ['Permanent District', 'District', 'জেলা']),
            isAddressSame: false,
            presentVillage: getValue(row, ['Present Village', 'Village', 'গ্রাম']),
            presentPostOffice: getValue(row, ['Present Post Office', 'Post Office', 'ডাকঘর']),
            presentUpazila: getValue(row, ['Present Upazila', 'Upazila', 'উপজেলা']),
            presentDistrict: getValue(row, ['Present District', 'District', 'জেলা']),
            fatherName: getValue(row, ['Father Name (English)', "Father's Name (English)", "Father's Name", 'Father Name', 'পিতার নাম (ইংরেজি)', 'পিতার নাম']),
            fatherNameBn: getValue(row, ['Father Name (Bangla)', "Father's Name (Bangla)", 'পিতার নাম (বাংলা)']),
            fatherNid: getValue(row, ['Father NID', 'পিতার এনআইডি']),
            fatherMobile: getValue(row, ['Father Mobile', 'Mobile', 'মোবাইল']),
            fatherProfession: getValue(row, ['Father Profession', 'পিতার পেশা']),
            motherName: getValue(row, ['Mother Name (English)', "Mother's Name (English)", "Mother's Name", 'Mother Name', 'মাতার নাম (ইংরেজি)', 'মাতার নাম']),
            motherNameBn: getValue(row, ['Mother Name (Bangla)', "Mother's Name (Bangla)", 'মাতার নাম (বাংলা)']),
            motherNid: getValue(row, ['Mother NID', 'মাতার এনআইডি']),
            motherMobile: getValue(row, ['Mother Mobile', 'মাতার মোবাইল']),
            motherProfession: getValue(row, ['Mother Profession', 'মাতার পেশা']),
            parentsStatus: getValue(row, ['Parents Status', 'পিতামাতার অবস্থা']) || 'দুজনেই জীবিত',
            prevSchoolName: getValue(row, ['Previous School', 'Previous Institution', 'Previous Educational Institution', 'পূর্ববর্তী বিদ্যালয়', 'পূর্ববর্তী শিক্ষা প্রতিষ্ঠান', 'পূর্ববর্তী প্রতিষ্ঠান', 'পূর্বের স্কুল', 'পূর্ববর্তী প্রতিষ্ঠানের নাম']),
            prevClass: getValue(row, ['Previous Class', 'পূর্ববর্তী শ্রেণি']),
            admissionPayment: getValue(row, ['Admission Payment', 'ভর্তি ফি']),
            paymentMethod: getValue(row, ['Payment Method', 'পেমেন্ট মেথড']) || 'নগদ / ক্যাশ',
            transactionNo: getValue(row, ['Transaction No', 'ট্রানজেকশন নং']),
            passingYear: getValue(row, ['Passing Year', 'পাসের সন']),
            gpa: getValue(row, ['GPA', 'জিপিএ', 'Result']),
            registrationNo: getValue(row, ['Registration No', 'রেজিস্ট্রেশন নং']),
            board: getValue(row, ['Board', 'বোর্ড']),
            photo: ''
          } as Student;
        },
        { chunkSize: 40 }
      );

      if (newStudents.length > 0) {
        bulkAddStudents(newStudents);
        showToast(isBn ? `সফলভাবে ${newStudents.length} জন শিক্ষার্থীর তথ্য ইমপোর্ট হয়েছে!` : `Successfully imported ${newStudents.length} students!`);
      }
    } catch (err: any) {
      console.error(err);
      toast.error(isBn ? BN_DICT['error_reading_excel_file'] : EN_DICT['error_reading_excel_file']);
    } finally {
      setIsImporting(false);
      if (e.target) e.target.value = '';
    }
  };

  const filteredRecentStudents = useMemo(() => {
    return studentList.filter(s => {
      if (!s) return false;
      const matchClass = filterClass === 'all' || s.class === filterClass;
      const term = (searchTerm || '').toLowerCase().trim();
      if (!term) return matchClass;
      const name = (s.name || '').toLowerCase();
      const nameBn = (s.nameBn || '').toLowerCase();
      const sId = (s.studentId || '').toLowerCase();
      const roll = (s.roll || '').toLowerCase();
      return matchClass && (name.includes(term) || nameBn.includes(term) || sId.includes(term) || roll.includes(term));
    });
  }, [studentList, filterClass, searchTerm]);

  return (
    <div className="space-y-6">
      {/* Page Header */}
      <div className="flex flex-col md:flex-row justify-between items-start md:items-center gap-4 bg-white p-6 rounded-2xl border border-slate-200 shadow-sm">
        <div>
          <div className="flex items-center gap-2 text-xs font-semibold text-indigo-600 uppercase tracking-wider mb-1">
            <School className="w-4 h-4" />
            <span>{isBn ? BN_DICT['student_management'] : EN_DICT['student_management']}</span>
          </div>
          <h1 className="text-2xl lg:text-3xl font-bold text-slate-800 tracking-tight">
            {isBn ? BN_DICT['admission_enrollment'] : EN_DICT['admission_enrollment']}
          </h1>
          <p className="text-slate-500 text-sm mt-1">
            {isBn ? BN_DICT['new_student_admission_enrollme'] : EN_DICT['new_student_admission_enrollme']}
          </p>
        </div>

        <div className="flex flex-wrap items-center gap-3 w-full sm:w-auto">
          {/* Bulk Import Button */}
          <button
            onClick={() => setShowHubModal(true)}
            className="flex-1 sm:flex-none inline-flex items-center justify-center gap-2 px-4 py-2.5 bg-emerald-50 hover:bg-emerald-100 border border-emerald-200 text-emerald-800 rounded-xl text-sm font-semibold transition-colors shadow-xs"
          >
            <FileSpreadsheet className="w-4 h-4 text-emerald-600" />
            <span>{isBn ? BN_DICT['bulk_import'] : EN_DICT['bulk_import']}</span>
          </button>

          <button
            onClick={() => setShowSmartModal(true)}
            className="flex-1 sm:flex-none inline-flex items-center justify-center gap-2 px-4 py-2.5 bg-purple-50 hover:bg-purple-100 border border-purple-100 text-purple-700 rounded-xl text-sm font-medium transition-colors"
          >
            <Sparkles className="w-4 h-4" />
            <span className="hidden sm:inline">{isBn ? BN_DICT['smart_fill'] : EN_DICT['smart_fill']}</span>
          </button>

          <button
            onClick={() => {
              setEditingStudent(null);
              setSmartData(null);
              setShowEnrollModal(true);
            }}
            className="flex-1 sm:flex-none inline-flex items-center justify-center gap-2 px-4 py-2.5 bg-indigo-600 hover:bg-indigo-700 text-white rounded-xl text-sm font-medium transition-colors shadow-sm"
          >
            <UserPlus className="w-4 h-4" />
            <span>{isBn ? BN_DICT['new_admission'] : EN_DICT['new_admission']}</span>
          </button>

          <Link
            to="/students/list"
            title={isBn ? BN_DICT['student_profile_list'] : EN_DICT['student_profile_list']}
            className="inline-flex items-center justify-center p-2.5 bg-slate-100 hover:bg-slate-200 text-slate-700 rounded-xl transition-colors"
          >
            <Users className="w-4 h-4" />
          </Link>
        </div>
      </div>

      {/* Admission Statistics Overview */}
      <div className="grid grid-cols-1 sm:grid-cols-2 lg:grid-cols-4 gap-4">
        <div className="bg-white p-5 rounded-xl border border-slate-200 shadow-sm flex items-center gap-4">
          <div className="p-3 bg-indigo-50 text-indigo-600 rounded-xl">
            <Users className="w-6 h-6" />
          </div>
          <div>
            <p className="text-xs font-medium text-slate-500 uppercase tracking-wider">{isBn ? BN_DICT['total_students_1'] : EN_DICT['total_students_1']}</p>
            <h3 className="text-2xl font-bold text-slate-800">{totalStudents}</h3>
          </div>
        </div>

        <div className="bg-white p-5 rounded-xl border border-slate-200 shadow-sm flex items-center gap-4">
          <div className="p-3 bg-blue-50 text-blue-600 rounded-xl">
            <CheckCircle2 className="w-6 h-6" />
          </div>
          <div>
            <p className="text-xs font-medium text-slate-500 uppercase tracking-wider">{isBn ? BN_DICT['male_students'] : EN_DICT['male_students']}</p>
            <h3 className="text-2xl font-bold text-slate-800">{maleStudents}</h3>
          </div>
        </div>

        <div className="bg-white p-5 rounded-xl border border-slate-200 shadow-sm flex items-center gap-4">
          <div className="p-3 bg-rose-50 text-rose-600 rounded-xl">
            <CheckCircle2 className="w-6 h-6" />
          </div>
          <div>
            <p className="text-xs font-medium text-slate-500 uppercase tracking-wider">{isBn ? BN_DICT['female_students'] : EN_DICT['female_students']}</p>
            <h3 className="text-2xl font-bold text-slate-800">{femaleStudents}</h3>
          </div>
        </div>

        <div className="bg-white p-5 rounded-xl border border-slate-200 shadow-sm flex items-center gap-4">
          <div className="p-3 bg-emerald-50 text-emerald-600 rounded-xl">
            <Clock className="w-6 h-6" />
          </div>
          <div>
            <p className="text-xs font-medium text-slate-500 uppercase tracking-wider">{isBn ? BN_DICT['current_session'] : EN_DICT['current_session']}</p>
            <h3 className="text-2xl font-bold text-slate-800">{thisYearStudents || totalStudents}</h3>
          </div>
        </div>
      </div>

      {/* Hidden File Input for direct quick upload */}
      <input
        type="file"
        ref={fileInputRef}
        onChange={handleDirectExcelFile}
        accept=".xlsx, .xls"
        className="hidden"
      />

      {/* Recent Admissions & Enrollment Records */}
      <div className="bg-white rounded-2xl border border-slate-200 shadow-sm overflow-hidden">
        <div className="p-5 border-b border-slate-100 flex flex-col sm:flex-row justify-between items-start sm:items-center gap-4 bg-slate-50/50">
          <div>
            <h2 className="text-lg font-bold text-slate-800">
              {isBn ? BN_DICT['recent_enrolled_students_appli'] : EN_DICT['recent_enrolled_students_appli']}
            </h2>
            <p className="text-xs text-slate-500 mt-0.5">
              {isBn ? BN_DICT['list_of_newly_admitted_student'] : EN_DICT['list_of_newly_admitted_student']}
            </p>
          </div>

          <div className="flex flex-wrap items-center gap-3 w-full sm:w-auto">
            {/* Class Filter */}
            <div className="relative">
              <select
                value={filterClass}
                onChange={(e) => setFilterClass(e.target.value)}
                className="pl-3 pr-8 py-2 text-xs font-medium bg-white border border-slate-200 rounded-lg text-slate-700 outline-none focus:ring-2 focus:ring-indigo-500"
              >
                <option value="all">{isBn ? BN_DICT['all_classes'] : EN_DICT['all_classes']}</option>
                {classesList.map(c => (
                  <option key={c.id} value={c.name}>{c.name}</option>
                ))}
              </select>
            </div>

            {/* Search Input */}
            <div className="relative flex-1 sm:w-56">
              <Search className="w-4 h-4 absolute left-3 top-1/2 -translate-y-1/2 text-slate-400" />
              <input
                type="text"
                placeholder={isBn ? BN_DICT['search_name_id_or_roll'] : EN_DICT['search_name_id_or_roll']}
                value={searchTerm}
                onChange={(e) => setSearchTerm(e.target.value)}
                className="w-full pl-9 pr-3 py-2 text-xs border border-slate-200 rounded-lg bg-white outline-none focus:ring-2 focus:ring-indigo-500"
              />
            </div>
          </div>
        </div>

        <div className="overflow-x-auto">
          <table className="w-full text-left text-sm text-slate-600">
            <thead className="bg-slate-50 border-b border-slate-200 text-slate-700 text-xs uppercase font-semibold">
              <tr>
                <th className="px-6 py-3.5">{isBn ? BN_DICT['student_id'] : EN_DICT['student_id']}</th>
                <th className="px-6 py-3.5">{isBn ? BN_DICT['photo'] : EN_DICT['photo']}</th>
                <th className="px-6 py-3.5">{isBn ? BN_DICT['student_name'] : EN_DICT['student_name']}</th>
                <th className="px-6 py-3.5">{isBn ? BN_DICT['class_roll'] : EN_DICT['class_roll']}</th>
                <th className="px-6 py-3.5">{isBn ? BN_DICT['father_mobile_2'] : EN_DICT['father_mobile_2']}</th>
                <th className="px-6 py-3.5">{isBn ? BN_DICT['data_entry_1'] : EN_DICT['data_entry_1']}</th>
                <th className="px-6 py-3.5">{isBn ? BN_DICT['payment_method_1'] : EN_DICT['payment_method_1']}</th>
                <th className="px-6 py-3.5 text-right">{isBn ? BN_DICT['actions'] : EN_DICT['actions']}</th>
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100">
              {filteredRecentStudents.length > 0 ? (
                filteredRecentStudents.slice(0, 15).map((student) => {
                  const completion = calculateStudentDataCompletion(student);
                  return (
                    <tr key={student.id} className="hover:bg-slate-50/80 transition-colors">
                      <td className="px-6 py-3.5 font-medium text-slate-900">{student.studentId}</td>
                      <td className="px-6 py-3.5">
                        {student.photo ? (
                          <img src={student.photo} alt="Photo" className="w-8 h-8 rounded-full object-cover border border-slate-200 shadow-xs" />
                        ) : (
                          <div className="w-8 h-8 rounded-full bg-slate-100 flex items-center justify-center text-xs font-semibold text-slate-500 border border-slate-200">
                            {student.name ? student.name.charAt(0).toUpperCase() : 'S'}
                          </div>
                        )}
                      </td>
                      <td className="px-6 py-3.5">
                        <p className="font-semibold text-slate-800">{student.name}</p>
                        {student.nameBn && <p className="text-xs text-slate-500">{student.nameBn}</p>}
                      </td>
                      <td className="px-6 py-3.5">
                        <div className="flex flex-wrap items-center gap-1.5">
                          <span className="inline-flex items-center px-2 py-0.5 rounded text-xs font-semibold bg-indigo-50 text-indigo-700">
                            {student.class || 'N/A'}
                          </span>
                          {student.group && student.group !== 'প্রযোজ্য নয়' && (
                            <span className="inline-flex items-center px-1.5 py-0.5 rounded text-[10px] font-medium bg-amber-50 text-amber-700 border border-amber-200">
                              {student.group}
                            </span>
                          )}
                          {student.section && student.section !== 'প্রযোজ্য নয়' && (
                            <span className="inline-flex items-center px-1.5 py-0.5 rounded text-[10px] font-medium bg-emerald-50 text-emerald-700 border border-emerald-200">
                              {isBn ? BN_DICT['sec'] : EN_DICT['sec']} {student.section}
                            </span>
                          )}
                          <span className="text-xs text-slate-500 font-medium">{isBn ? BN_DICT['roll_1'] : EN_DICT['roll_1']} {student.roll || '-'}</span>
                        </div>
                      </td>
                      <td className="px-6 py-3.5">
                        <p className="text-xs font-medium text-slate-700">{student.fatherName || '-'}</p>
                        <p className="text-xs text-slate-400">{student.fatherMobile || '-'}</p>
                      </td>
                      <td className="px-6 py-3.5">
                        <div className="flex items-center gap-2">
                          <div className="w-12 bg-slate-200 h-1.5 rounded-full overflow-hidden shrink-0">
                            <div 
                              className={`h-full rounded-full transition-all ${
                                completion === 100 ? 'bg-emerald-500' : completion >= 60 ? 'bg-indigo-600' : 'bg-amber-500'
                              }`}
                              style={{ width: `${completion}%` }}
                            />
                          </div>
                          <span className={`text-xs font-bold ${
                            completion === 100 ? 'text-emerald-600' : completion >= 60 ? 'text-indigo-600' : 'text-amber-600'
                          }`}>
                            {isBn ? toBengaliNumber(completion) : completion}%
                          </span>
                        </div>
                      </td>
                      <td className="px-6 py-3.5">
                        {student.admissionPayment ? (
                          <span className="inline-flex items-center gap-1 px-2 py-0.5 rounded text-xs font-medium bg-emerald-50 text-emerald-700">
                            <CreditCard className="w-3 h-3" />
                            ৳{student.admissionPayment} ({student.paymentMethod || 'নগদ'})
                          </span>
                        ) : (
                          <span className="text-xs text-slate-400">-</span>
                        )}
                      </td>
                      <td className="px-6 py-3.5 text-right">
                        <div className="flex items-center justify-end gap-2">
                          <button
                            onClick={() => setViewingStudent(student)}
                            className="p-1.5 text-slate-500 hover:text-indigo-600 hover:bg-indigo-50 rounded-lg transition-colors cursor-pointer"
                            title={isBn ? BN_DICT['view_profile'] : EN_DICT['view_profile']}
                          >
                            <Eye className="w-4 h-4" />
                          </button>
                          <button
                            onClick={() => {
                              setEditingStudent(student);
                              setShowEnrollModal(true);
                            }}
                            className="p-1.5 text-slate-500 hover:text-emerald-600 hover:bg-emerald-50 rounded-lg transition-colors cursor-pointer"
                            title={isBn ? BN_DICT['edit'] : EN_DICT['edit']}
                          >
                            <Edit3 className="w-4 h-4" />
                          </button>
                          <button
                            onClick={() => {
                              if (window.confirm(isBn ? BN_DICT['are_you_sure_you_want_to_delet_1'] : EN_DICT['are_you_sure_you_want_to_delet_1'])) {
                                deleteStudent(student.id);
                                toast.success(isBn ? `শিক্ষার্থী "${student.nameBn || student.name}"-এর তথ্য মুছে ফেলা হয়েছে` : `Student "${student.name}" deleted`);
                              }
                            }}
                            className="p-1.5 text-slate-500 hover:text-red-600 hover:bg-red-50 rounded-lg transition-colors cursor-pointer"
                            title={isBn ? BN_DICT['delete'] : EN_DICT['delete']}
                          >
                            <Trash2 className="w-4 h-4" />
                          </button>
                        </div>
                      </td>
                    </tr>
                  );
                })
              ) : (
                <tr>
                  <td colSpan={8} className="px-6 py-12 text-center text-slate-500">
                    <Users className="w-8 h-8 mx-auto text-slate-300 mb-2" />
                    <p className="font-medium">{isBn ? BN_DICT['no_student_records_found'] : EN_DICT['no_student_records_found']}</p>
                    <p className="text-xs text-slate-400 mt-1">{isBn ? BN_DICT['use_the_buttons_above_to_enrol'] : EN_DICT['use_the_buttons_above_to_enrol']}</p>
                  </td>
                </tr>
              )}
            </tbody>
          </table>
        </div>

        {filteredRecentStudents.length > 15 && (
          <div className="p-4 border-t border-slate-100 text-center bg-slate-50">
            <Link
              to="/students/list"
              className="inline-flex items-center gap-1.5 text-sm font-semibold text-indigo-600 hover:text-indigo-800 transition-colors"
            >
              <span>{isBn ? `সকল ${studentList.length} জন শিক্ষার্থীর সম্পূর্ণ তালিকা দেখুন` : `View all ${studentList.length} students in Profile & List`}</span>
              <ArrowRight className="w-4 h-4" />
            </Link>
          </div>
        )}
      </div>

      {/* Modals */}
      <StudentEnrollmentModal
        isOpen={showEnrollModal}
        onClose={() => {
          setShowEnrollModal(false);
          setEditingStudent(null);
          setSmartData(null);
        }}
        student={editingStudent || (smartData as Student | null)}
        onSave={handleSaveStudent}
        generateId={(cls) => generateStudentId(cls, studentList)}
      />

      <AddStudentHubModal
        isOpen={showHubModal}
        onClose={() => setShowHubModal(false)}
        onExcelImportSubmit={handleBulkExcelImport}
      />

      <SmartImportModal
        isOpen={showSmartModal}
        onClose={() => setShowSmartModal(false)}
        onImportSuccess={handleSmartImportSubmit}
      />

      <StudentProfileModal
        student={viewingStudent}
        isOpen={!!viewingStudent}
        onClose={() => setViewingStudent(null)}
        onEdit={(st) => {
          setViewingStudent(null);
          setEditingStudent(st);
          setShowEnrollModal(true);
        }}
      />

      {/* Toast Notification */}
      {toastMessage && (
        <div className="fixed bottom-6 right-6 z-50 bg-slate-900 text-white px-5 py-3 rounded-xl shadow-xl flex items-center gap-3 animate-fade-in border border-slate-700">
          <div className="w-2.5 h-2.5 rounded-full bg-emerald-400 animate-pulse" />
          <span className="text-sm font-medium">{toastMessage}</span>
        </div>
      )}
    </div>
  );
};

export default AdmissionEnrollment;
