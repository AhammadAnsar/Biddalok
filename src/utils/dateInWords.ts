function numberToWordsEn(num: number): string {
  if (num < 100) {
    if (ONES_EN[num]) return ONES_EN[num];
    const tens = Math.floor(num / 10);
    const ones = num % 10;
    return `${TENS_EN[tens]} ${ONES_EN[ones] || ''}`.trim();
  }
  if (num >= 1000 && num < 10000) {
    const thousands = Math.floor(num / 1000);
    const remainder = num % 1000;
    let text = `${ONES_EN[thousands] || thousands} Thousand`;
    if (remainder > 0) {
      if (remainder < 100) {
        text += ` ${numberToWordsEn(remainder)}`;
      } else {
        const hundreds = Math.floor(remainder / 100);
        const remTens = remainder % 100;
        text += ` ${ONES_EN[hundreds]} Hundred`;
        if (remTens > 0) text += ` ${numberToWordsEn(remTens)}`;
      }
    }
    return text;
  }
  return num.toString();
}

function numberToWordsBn(num: number): string {
  if (num < 100) {
    return BN_NUMS_UNDER_100[num] || toBengaliNumber(num);
  }
  if (num >= 1000 && num < 10000) {
    const thousands = Math.floor(num / 1000);
    const remainder = num % 1000;
    let text = `${BN_NUMS_UNDER_100[thousands] || toBengaliNumber(thousands)} হাজার`;
    if (remainder > 0) {
      if (remainder < 100) {
        text += ` ${BN_NUMS_UNDER_100[remainder] || toBengaliNumber(remainder)}`;
      } else {
        const hundreds = Math.floor(remainder / 100);
        const remTens = remainder % 100;
        text += ` ${BN_NUMS_UNDER_100[hundreds] || toBengaliNumber(hundreds)} শত`;
        if (remTens > 0) text += ` ${BN_NUMS_UNDER_100[remTens] || toBengaliNumber(remTens)}`;
      }
    }
    return text;
  }
  return toBengaliNumber(num);
}

export interface ParsedDateInfo {
  day: number;
  month: number; // 1-12
  year: number;
  formattedNumeric: string; // e.g., 13/10/2010 or ১৩/১০/২০১০
  formattedInWords: string; // e.g., Thirteen October Two Thousand Ten
  fullWithWords: string; // e.g., 13/10/2010 (Thirteen October Two Thousand Ten)
}

export function parseAndFormatDob(dateStr?: string | null, isBn: boolean = false): ParsedDateInfo {
  if (!dateStr || !dateStr.trim()) {
    return {
      day: 0,
      month: 0,
      year: 0,
      formattedNumeric: isBn ? BN_DICT['k_'] : EN_DICT['k_'],
      formattedInWords: isBn ? BN_DICT['k__1'] : EN_DICT['k__1'],
      fullWithWords: isBn ? BN_DICT['k__2'] : EN_DICT['k__2'],
    };
  }

  const str = dateStr.trim();
  let d = 0;
  let m = 0;
  let y = 0;

  // Convert any Bengali digits to English for parsing
  const enStr = str.replace(/[০-৯]/g, (ch) => {
    const map: { [key: string]: string } = {
      '০': '0', '১': '1', '২': '2', '৩': '3', '৪': '4',
      '৫': '5', '৬': '6', '৭': '7', '৮': '8', '৯': '9'
    };
    return map[ch] || ch;
  });

  // Check YYYY-MM-DD
  const ymdMatch = enStr.match(/^(\d{4})[-/.](\d{1,2})[-/.](\d{1,2})/);
  if (ymdMatch) {
    y = parseInt(ymdMatch[1], 10);
    m = parseInt(ymdMatch[2], 10);
    d = parseInt(ymdMatch[3], 10);
  } else {
    // Check DD-MM-YYYY
    const dmyMatch = enStr.match(/^(\d{1,2})[-/.](\d{1,2})[-/.](\d{4})/);
    if (dmyMatch) {
      d = parseInt(dmyMatch[1], 10);
      m = parseInt(dmyMatch[2], 10);
      y = parseInt(dmyMatch[3], 10);
    } else {
      const dt = new Date(enStr);
      if (!isNaN(dt.getTime())) {
        d = dt.getDate();
        m = dt.getMonth() + 1;
        y = dt.getFullYear();
      }
    }
  }

  if (d > 0 && d <= 31 && m >= 1 && m <= 12 && y > 1900) {
    const dStr = String(d).padStart(2, '0');
    const mStr = String(m).padStart(2, '0');
    const yStr = String(y);

    if (isBn) {
      const numeric = `${toBengaliNumber(dStr)}/${toBengaliNumber(mStr)}/${toBengaliNumber(yStr)}`;
      const dayWord = DAYS_BN[d] || toBengaliNumber(d);
      const monthWord = MONTHS_BN[m - 1] || '';
      const yearWord = numberToWordsBn(y);
      const inWords = `${dayWord} ${monthWord} ${yearWord}`.trim();
      return {
        day: d,
        month: m,
        year: y,
        formattedNumeric: numeric,
        formattedInWords: inWords,
        fullWithWords: `${numeric} (${inWords})`,
      };
    } else {
      const numeric = `${dStr}/${mStr}/${yStr}`;
      const dayWord = ONES_EN[d] || String(d);
      const monthWord = MONTHS_EN[m - 1] || '';
      const yearWord = numberToWordsEn(y);
      const inWords = `${dayWord} ${monthWord} ${yearWord}`.trim();
      return {
        day: d,
        month: m,
        year: y,
        formattedNumeric: numeric,
        formattedInWords: inWords,
        fullWithWords: `${numeric} (${inWords})`,
      };
    }
  }

  // Fallback if parsing didn't match standard
  return {
    day: 0,
    month: 0,
    year: 0,
    formattedNumeric: isBn ? toBengaliNumber(str) : str,
    formattedInWords: str,
    fullWithWords: isBn ? toBengaliNumber(str) : str,
  };
}
